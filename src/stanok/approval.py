@dataclass(frozen=True, slots=True)
class Проба:
    """Часть документа, на которой смотрят шаблон. Всегда помечена пробой."""

    строк: int
    строк_всего: int
    страниц: int = 0
    страниц_всего: int = 0

    @property
    def доля_словами(self) -> str:
        if self.строк_всего:
            return f"{self.строк} операций из {self.строк_всего}"
        return f"{self.строк} операций"

    def словами(self) -> str:
        return f"проба · {self.доля_словами}"

    def as_json(self) -> dict:
        return {"строк": self.строк, "строк_всего": self.строк_всего,
                "страниц": self.страниц, "страниц_всего": self.страниц_всего,
                "это_проба": True}


ИТОГИ_СОШЛИСЬ = "итоги сходятся"
ИТОГИ_НЕ_СОШЛИСЬ = "итоги не сходятся"


def слова_об_итогах(сошлись: bool, проба: Проба | None = None) -> str:
    """Единственное место, где рождается утверждение об итогах.

    Пока проба приложена, голых слов «итоги сходятся» отсюда не выйдет: они
    говорят о документе, а проверено было десять строк. Оператор, прочитавший
    «итоги сходятся» на экране согласования, будет думать, что документ
    проверен, — и будет прав, если так написано, и обманут, если это была проба.
    """
    основа = ИТОГИ_СОШЛИСЬ if сошлись else ИТОГИ_НЕ_СОШЛИСЬ
    if проба is None:
        return основа
    if not проба.строк:
        # Итоги, сошедшиеся на пустой пробе, — та же пустая проверка, что
        # «учёт сошёлся» при пустом перечне ожиданий (шаг 76). Она выглядит
        # пройденной и не проверяет ничего.
        return ("об итогах сказать нечего: на пробе не собралось ни одной "
                "операции")
    return f"{основа} на пробе ({проба.доля_словами})"


def это_утверждение_о_документе(слова: str) -> bool:
    """Говорят ли эти слова о документе целиком, а не о пробе."""
    return слова.startswith(ИТОГИ_СОШЛИСЬ) and "на пробе" not in слова


