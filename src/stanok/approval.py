@dataclass(frozen=True, slots=True)
class Согласование:
    """Что согласовано, кем, когда и с какими колонками."""

    шаблон: str
    версия: str
    кем: str
    когда: str
    колонки: tuple[Колонка, ...] = ()
    проба: Проба | None = None
    основание: str = ""

    def as_json(self) -> dict:
        return {
            "schema_version": APPROVAL_VERSION,
            "род": СОБЫТИЕ_СОГЛАСОВАНИЯ,
            "шаблон": self.шаблон,
            "версия_шаблона": self.версия,
            "кем": self.кем,
            "когда": self.когда,
            "основание": self.основание,
            "колонки": [к.as_json() for к in self.колонки],
            "проба": self.проба.as_json() if self.проба else None,
            "листы_контрольной": list(ЛИСТЫ_КОНТРОЛЬНОЙ),
            "листы_согласованию_не_подлежат": True,
        }


class СогласованиеНевозможно(RuntimeError):
    """Ворота согласования закрыты: названо, чем именно."""


def согласовать(шаблон: str, версия: str, кем: str, когда: str,
                сопоставления, проба: Проба | None = None,
                основание: str = "") -> Согласование:
    """Фиксирует согласование. Нерешённое поле не пропускает."""
    можно, почему = можно_запускать(сопоставления)
    if not можно:
        raise СогласованиеНевозможно(почему)
    if not кем.strip():
        raise СогласованиеНевозможно(
            "согласование без имени невозможно: журнал хранит, кто согласовал")
    if not версия.strip():
        raise СогласованиеНевозможно(
            "согласование без версии шаблона невозможно: фиксировать нечего")
    return Согласование(шаблон=шаблон, версия=версия, кем=кем.strip(),
                        когда=когда or _сейчас(), проба=проба,
                        колонки=колонки_результата(сопоставления),
                        основание=основание.strip())


def записать(согласование: Согласование, журнал_путь) -> str:
    """Кладёт согласование в неизменяемый журнал (шаг 58). Возвращает вершину."""
    return journal.append_record(Path(журнал_путь), согласование.as_json(),
                                 схема=journal.нормализовать_событие,
                                 доверяя_хвосту=True)


def _сейчас() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# --------------------------------------------------------------- показ


def _т(значение) -> str:
    return обезвредить(значение)


_ТОЧКА = {СОВПАЛО: "t-zel", РЕШЕНО: "t-zel", НУЖНО_РЕШИТЬ: "t-zhel",
          ИСЧЕЗЛО: "t-zhel"}


def проба_html(проба: Проба | None) -> str:
    """Плашка пробы — жёлтая, как на макете. Без неё колонка не показывается."""
    if проба is None:
        return ('<div class="plashka">проба не бралась</div>')
    return f'<div class="plashka">{_т(проба.словами().upper())}</div>'


def источник_html(строки, проба: Проба | None, новых: int) -> str:
    """Первая колонка: исходный PDF как он есть."""
    куски = ['<div class="karta"><div class="mnk">1. Исходный PDF</div>'
             '<div class="list"><table class="dok">']
    for строка in строки:
        ячейки = getattr(строка, "ячейки", ()) or ()
        текст = " · ".join(str(getattr(я, "текст", "")) for я in ячейки[:6])
        куски.append(f"<tr><td>{_т(текст)}</td></tr>")
    куски.append("</table></div>")
    хвост = (f"страниц в пробе {проба.страниц} из {проба.страниц_всего}"
             if проба else "проба не бралась")
    если_новое = (f" · найдено новых полей: {новых}" if новых else
                  " · новых полей нет")
    куски.append(f'<div class="snoska">{_т(хвост)}{_т(если_новое)}</div>')
    куски.append("</div>")
    return "".join(куски)


def сопоставление_html(сопоставления, проба: Проба | None) -> str:
    """Вторая колонка: поле → колонка, с состоянием у каждого."""
    куски = ['<div class="karta"><div class="mnk">2. Сопоставление</div>',
             проба_html(проба)]
    for с in сопоставления:
        точка = _ТОЧКА.get(с.состояние, "t-ser")
        куда = с.колонка or "—"
        решение = (f'<div class="tih">{_т(с.решение)} — {_т(с.кем)}: '
                   f"{_т(с.основание)}</div>" if с.решено and с.решение
                   else "")
        куски.append(
            f'<div class="sopost"><div class="para"><b>{_т(с.поле)}</b>'
            f'<span class="str">→</span>{_т(куда)}</div>'
            f'<div class="sost"><span class="tochka {точка}"></span>'
            f"{_т(с.состояние)} · {_т(с.почему)}</div>{решение}</div>")
    можно, почему = можно_запускать(сопоставления)
    if не_пусто(сопоставления) and not можно:
        куски.append(f'<div class="plashka">{_т(почему.split(": ", 1)[-1])}'
                     "</div>")
    куски.append("</div>")
    return "".join(куски)


def не_пусто(что) -> bool:
    return bool(tuple(что))


def будущий_excel_html(сопоставления, строки, проба: Проба | None) -> str:
    """Третья колонка: будущий Excel клиента — и только его лист данных."""
    колонки = [с.колонка for с in сопоставления if с.колонка and с.решено]
    куски = ['<div class="karta"><div class="mnk">3. Будущий Excel</div>'
             "<b>Лист клиентского результата</b>",
             '<table class="excel"><tr>']
    for имя in колонки:
        куски.append(f"<th>{_т(имя)}</th>")
    for с in нерешённые(сопоставления):
        куски.append(f"<th>{_т(с.поле)}</th>")
    куски.append("</tr>")
    for строка in строки[:6]:
        ячейки = getattr(строка, "ячейки", ()) or ()
        куски.append("<tr>")
        for место, _ in enumerate(колонки):
            текст = (str(getattr(ячейки[место], "текст", ""))
                     if место < len(ячейки) else "")
            куски.append(f"<td>{_т(текст)}</td>")
        for _ in нерешённые(сопоставления):
            куски.append("<td>—</td>")
        куски.append("</tr>")
    куски.append("</table>")

    свои = нерешённые(сопоставления)
    if свои:
        куски.append(f'<div class="plashka">Выберите действие для '
                     f"«{_т(свои[0].поле)}»</div>")
        куски.append('<div class="knopki" style="margin-top:14px">'
                     f'<span class="pogashena">Сначала решите '
                     f"{len(свои)}</span></div>")
    else:
        куски.append('<div class="knopki" style="margin-top:14px">'
                     '<span class="sinyaya">Согласовать и запустить полный '
                     "прогон</span></div>")
    куски.append(f'<div class="tih">{_т(ПОЧЕМУ_ЛИСТЫ_НЕ_СОГЛАСУЮТСЯ)} '
                 f"Листы: {_т(', '.join(ЛИСТЫ_КОНТРОЛЬНОЙ))}.</div>")
    куски.append("</div>")
    return "".join(куски)


def итоги_html(сошлись: bool, проба: Проба | None) -> str:
    """Итоги на пробе — и прямо сказано, что это не итоги документа."""
    слова = слова_об_итогах(сошлись, проба)
    цвет = "sost-zel" if сошлись else "sost-kras"
    куски = [f'<div class="sopost"><div class="sost {цвет}">● {_т(слова)}'
             "</div></div>"]
    if проба is not None:
        куски.append('<div class="snoska">«Итоги сходятся на пробе» и «итоги '
                     "сходятся» — разные утверждения. Первое сказано о "
                     f"{_т(проба.доля_словами)}, второе о документе целиком, и "
                     "станок его здесь не делает.</div>")
    return "".join(куски)


