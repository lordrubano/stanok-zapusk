"""Согласование шаблона: режим 2 — самостоятельные производственные ворота.

Шаг 84 плана. Нормативная основа — ТЗ на интерфейс 1.0, часть III (режим 2) и
макет согласования из пакета интерфейса 1.2.

## Проба помечена пробой

**«Итоги сходятся на пробе» и «итоги сходятся» — разные утверждения.** Первое
говорит о десяти строках, второе о документе. Спутать их легко и дорого:
согласовавший шаблон по пробе будет думать, что проверил документ.

Поэтому проба не «помечается» надписью, которую можно забыть поставить.
Утверждение об итогах **собирается** :func:`слова_об_итогах`, и, пока проба
приложена, слов «итоги сходятся» без хвоста «на пробе» она не выдаёт вовсе. Тот
же приём, что у наружного вида дашборда: не «мы не станем говорить», а «сказать
не выйдет».

## Нерешённое поле блокирует запуск

Новое или исчезнувшее поле не проходит без решения. Пока хоть одно не решено,
ворота закрыты и кнопка полного прогона погашена — с названием того, что
осталось решить. Это те же ворота, что у выпуска (шаг 87): отказ называет
предмет, а не общее «нельзя».

## Согласовывается результат клиента, а не доказуемость

Согласовываются **колонки клиентского результата**: имена, порядок, типы,
обязательность. Состав пяти листов контрольной книги (DATA, REVIEW, REJECTED,
ERRORS, AUDIT) согласованию не подлежит — на разделении принятого, спорного,
отклонённого и следа держится доказуемость.

Это подаётся как **свойство**, а не как отказ: клиенту не запрещают влиять на
контрольную книгу — ему объясняют, что она не его рабочий файл, а доказательство
производства, и потому неизменна.

## Согласование фиксирует версию и попадает в неизменяемый журнал

С именем согласовавшего и основанием. Журнал — тот же, что у решений оператора
(шаг 58): одна цепь, свободная схема события.
"""

