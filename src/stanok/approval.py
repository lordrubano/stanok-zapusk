@dataclass(frozen=True, slots=True)
class Колонка:
    """Колонка клиентского результата: имя, порядок, тип, обязательность."""

    имя: str
    порядок: int
    тип: str = "не назван"
    обязательна: bool = False

    def as_json(self) -> dict:
        return {"имя": self.имя, "порядок": self.порядок, "тип": self.тип,
                "обязательна": self.обязательна}


@dataclass
class Сопоставление:
    """Поле источника и колонка клиентского результата — что с чем."""

    поле: str
    колонка: str | None
    состояние: str
    почему: str = ""
    решение: str = ""
    кем: str = ""
    основание: str = ""

    @property
    def решено(self) -> bool:
        return self.состояние in (СОВПАЛО, РЕШЕНО)

    def as_json(self) -> dict:
        return {"поле": self.поле, "колонка": self.колонка,
                "состояние": self.состояние, "почему": self.почему,
                "решение": self.решение, "кем": self.кем,
                "основание": self.основание}


class РешениеНегодно(ValueError):
    """Решение по полю не принято: названа причина."""


def решить(сопоставление: Сопоставление, решение: str, кем: str,
           основание: str, колонка: str | None = None) -> Сопоставление:
    """Решает судьбу поля. Без имени и основания решение не рождается.

    То же правило, что у действий оператора (шаг 57): решение без основания
    невозможно объяснить потом, а объяснять придётся именно потом.
    """
    if решение not in РЕШЕНИЯ:
        raise РешениеНегодно(
            f"такого решения не бывает: {решение!r}. Есть только "
            + " и ".join(РЕШЕНИЯ))
    if not кем.strip():
        raise РешениеНегодно("решение без имени не принимается: согласование "
                             "попадает в неизменяемый журнал")
    if len(основание.strip()) < 3:
        raise РешениеНегодно("решение без основания не принимается: оно нужно "
                             "тому, кто будет разбираться потом")
    сопоставление.состояние = РЕШЕНО
    сопоставление.решение = решение
    сопоставление.кем = кем.strip()
    сопоставление.основание = основание.strip()
    if решение == ВКЛЮЧИТЬ:
        сопоставление.колонка = колонка or сопоставление.поле
    else:
        сопоставление.колонка = None
    return сопоставление


def нерешённые(сопоставления) -> tuple[Сопоставление, ...]:
    return tuple(с for с in сопоставления if not с.решено)


def можно_запускать(сопоставления) -> tuple[bool, str]:
    """Ворота согласования. Нерешённое поле не пропускает полный прогон."""
    свои = нерешённые(сопоставления)
    if not свои:
        return True, "решены все поля: полный прогон можно запускать"
    имена = ", ".join(с.поле for с in свои)
    сколько = len(свои)
    слово = ("поле" if сколько % 10 == 1 and сколько % 100 != 11
             else "поля" if 2 <= сколько % 10 <= 4 and not 11 <= сколько % 100 <= 14
             else "полей")
    return False, (f"{СОГЛАСОВАНИЕ_ЗАКРЫТО}: {сколько} {слово} без решения — "
                   f"{имена}. Новое или исчезнувшее поле не проходит без "
                   "решения")


# --------------------------------------------------- сопоставление по пробе


def собрать_пробу(сегментация, оснастка, строк: int = СТРОК_В_ПРОБЕ):
    """Проба и сопоставление полей по ней. Ничего не выдумывает.

    Проба берётся **по операциям, а не по строкам листа**: первые строки
    документа — это шапка и реквизиты, и колонок операции в них нет. Первая
    редакция брала строки подряд и на своём же документе объявляла исчезнувшими
    шесть полей из семи. Границу операции находит тот же сборщик, что и в
    полном прогоне (шаг 36), — своего здесь не заводится.
    """
    from .columns import колонки, разложить_по_колонкам
    from .records import собрать as собрать_записи

    все_строки = list(getattr(сегментация, "строки", ()) or ())
    страницы = getattr(сегментация, "страницы", ()) or ()

    объявленные = []
    for колонка in колонки(оснастка) or ():
        имя = (колонка.get("поле") if isinstance(колонка, dict)
               else getattr(колонка, "поле", None))
        if имя and имя not in объявленные:
            объявленные.append(str(имя))

    сборка = собрать_записи(все_строки, оснастка)
    все_записи = list(getattr(сборка, "записи", ()) or ())
    свои = все_записи[:строк]
    проба = Проба(строк=len(свои), строк_всего=len(все_записи),
                  страниц=len({getattr(getattr(з, "первая", None), "страница", 0)
                               for з in свои}),
                  страниц_всего=len(страницы))

    if not свои:
        # Ни одной операции по этой оснастке. Для чужой формы это верный ответ,
        # и он честнее, чем перечень «исчезнувших» полей.
        сопоставления = [Сопоставление(
            поле="операции документа", колонка=None, состояние=НУЖНО_РЕШИТЬ,
            почему=(f"по этой оснастке на {len(все_строки)} строках не "
                    "собралось ни одной операции: форма другая либо граница "
                    "операции объявлена не так"))]
        return проба, сопоставления

    попались: set = set()
    лишних = 0
    for запись in свои:
        поля, лишние, _ = разложить_по_колонкам(запись.первая, оснастка)
        попались |= set(поля)
        лишних += len(лишние)

    сопоставления = []
    for имя in объявленные:
        if имя in попались:
            сопоставления.append(Сопоставление(
                поле=имя, колонка=имя, состояние=СОВПАЛО,
                почему="на пробе колонка получила ячейки"))
        else:
            сопоставления.append(Сопоставление(
                поле=имя, колонка=None, состояние=ИСЧЕЗЛО,
                почему="объявлено оснасткой, но на пробе ячеек не получило"))
    if лишних:
        сопоставления.append(Сопоставление(
            поле="ячейки вне объявленных колонок", колонка=None,
            состояние=НУЖНО_РЕШИТЬ,
            почему=f"на пробе {лишних} ячеек не попали ни в одну объявленную "
                   "колонку: это новое поле или сдвиг вёрстки"))
    return проба, сопоставления


def колонки_результата(сопоставления) -> tuple[Колонка, ...]:
    """Колонки клиентского результата в порядке согласования."""
    свои = []
    порядок = 0
    for с in сопоставления:
        if с.колонка and с.решено:
            порядок += 1
            свои.append(Колонка(имя=с.колонка, порядок=порядок))
    return tuple(свои)


