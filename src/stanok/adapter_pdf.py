"""Адаптер разбора PDF: текст с координатами областей.

Шаг 28 плана. Нормативная основа — чертёж v3.0, разделы 5.1 (компонент 3) и 5.3
(PDF с текстовым слоем — нативный разбор; сканированный — OCR, и это другой
шаг). Требования к адресу области — раздел 6.2: координатное пространство самой
страницы либо доли 0…1 с зафиксированной ориентацией, но не пиксели отображения.

**Зачем координаты.** Без страницы и области нельзя построить ни карту покрытия,
ни происхождение поля, ни независимую перепроверку изображением — то есть
половину Фазы 3. Поэтому координаты здесь не украшение, а главный выход.

Начало отсчёта — левый нижний угол страницы, как принято в самом PDF. Значения
нормированы по видимой рамке страницы и записаны **строками**: доли страницы
устойчивы к изменению размера отображения, а строка не теряет точность при
каноническом представлении.

**Ширина области известна не всегда.** Она считается по ширинам знаков шрифта.
Если шрифт их не объявил, ширина остаётся неизвестной, и область не выдумывается:
у объекта остаётся точка привязки, а полигон пуст. Придуманный полигон — ложный
адрес, а ложный адрес хуже отсутствующего.

**Битые текстовые слои не чинятся, а отмечаются.** Глифовая подмена и
повреждённый ToUnicode дают текст, который выглядит как текст и им не является.
Здесь такие страницы получают отметку, по которой их можно найти и не доверять
им. Лечение пришло с независимой перепроверкой (шаг 43), и оно не в починке
текста — чинить нечего, знаки подменены, — а в **замене пути**: страница с этой
отметкой требует второго прочтения изображением, и её значения берутся оттуда.
"""

