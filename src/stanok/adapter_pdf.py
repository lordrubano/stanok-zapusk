class РазборPDF:
    """Нативный разбор PDF с текстовым слоем: текст, страница, координаты."""

    имя = "разбор-pdf"
    версия = "1"
    форматы = frozenset({"pdf"})

    # Меньше этой доли толкуемых знаков слой считается битым: столько
    # неразобранного не бывает у настоящего текстового слоя.
    ПОРОГ_ТОЛКОВАНИЯ = Decimal("0.60")

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        document_id = getattr(конверт, "document_id", "") or ""
        # Чтение устройства и извлечение текста — два разных долгих места, и
        # потолки у них разные. Оба вложены в срок файла, а не приложены к нему.
        документ = прочитать(данные, срок)
        свой = срок_места("извлечение текста", срок)
        if документ.зашифрован:
            raise PDFНеЧитается(
                "файл зашифрован: разбор шифрованных — политика шага 23")
        if not документ.страницы:
            raise PDFНеЧитается("в файле не нашлось ни одной страницы")

        for номер, страница in enumerate(документ.страницы, start=1):
            свой.проверить()
            yield from self._страница(document_id, документ, страница, номер,
                                      свой)

    def _страница(self, document_id, документ, страница, номер, срок=None):
        рамка = документ.раскрыть(страница.get("/MediaBox")) or [0, 0, 612, 792]
        рамка = [float(документ.раскрыть(з) or 0) for з in рамка[:4]]
        x0, y0, x1, y1 = рамка
        ширина_рамки, высота_рамки = abs(x1 - x0), abs(y1 - y0)
        поворот = _поворот(документ, страница)
        # У повёрнутой страницы ширина и высота видимого листа меняются
        # местами: рамка описывает лист до поворота, а координаты обязаны быть
        # в той ориентации, в какой лист читают.
        if поворот in (90, 270):
            ширина_страницы, высота_страницы = высота_рамки, ширина_рамки
        else:
            ширина_страницы, высота_страницы = ширина_рамки, высота_рамки

        шрифты = _шрифты(документ, страница)
        содержимое = _содержимое(документ, страница)
        есть_картинки = _есть_изображения(документ, страница, содержимое)

        if содержимое is None:
            yield self._о_странице(
                document_id, номер, ширина_страницы, высота_страницы,
                "нечитаемая", 0, есть_картинки, {},
                "поток содержимого не разжат: способ сжатия не поддержан",
                поворот)
            return

        показы = _показы(содержимое, шрифты, срок)
        значимые = [показ for показ in показы if показ.глифов]
        порядок = 0
        для_счёта = []
        for показ in значимые:
            порядок += 1
            для_счёта.append(показ)
            yield self._о_тексте(document_id, номер, показ, порядок,
                                 x0, y0, ширина_рамки, высота_рамки, поворот)

        признаки = self._признаки(для_счёта, шрифты)
        слой = self._слой(для_счёта, есть_картинки, признаки)
        yield self._о_странице(
            document_id, номер, ширина_страницы, высота_страницы, слой,
            len(для_счёта), есть_картинки, признаки, "", поворот)

    # ------------------------------------------------------- определение

    def _признаки(self, показы, шрифты) -> dict:
        всего = sum(показ.глифов for показ in показы)
        текст = "".join(показ.текст for показ in показы)
        неведомых = sum(1 for знак in текст if знак == "�")
        частных = sum(1 for знак in текст
                      if _ЧАСТНЫЙ[0] <= ord(знак) <= _ЧАСТНЫЙ[1])
        без_толкования = sorted(
            имя for имя, шрифт in шрифты.items() if not шрифт.есть_toUnicode)
        толкуемых = всего - неведомых - частных
        доля = (Decimal(толкуемых) / Decimal(всего)) if всего else Decimal(0)
        return {
            "глифов": всего,
            "неведомых_знаков": неведомых,
            "знаков_частного_диапазона": частных,
            "шрифтов_без_toUnicode": len(без_толкования),
            "доля_толкуемых": f"{доля.quantize(Decimal('0.01')):f}" if всего else "0.00",
        }

    def _слой(self, показы, есть_картинки, признаки) -> str:
        """Чем является страница по содержимому, а не по расширению.

        Порядок вопросов важен. Сперва: показывались ли глифы вообще? Нет
        глифов и есть изображение — это скан, и никакое расширение файла этого
        не изменит. Есть глифы, но толкуются они плохо — слой битый: текст на
        вид есть, доверять ему нельзя.
        """
        if not показы:
            return "скан" if есть_картинки else "пустая"
        доля = Decimal(признаки["доля_толкуемых"])
        if доля < self.ПОРОГ_ТОЛКОВАНИЯ:
            return "битый текстовый слой"
        return "смешанная" if есть_картинки else "текстовый слой"

    # --------------------------------------------------------- объекты

    def _о_тексте(self, document_id, номер, показ, порядок,
                  x0, y0, ширина_рамки, высота_рамки, поворот=0):
        левый = показ.x - x0
        нижний = показ.y - y0
        углы = [(левый, нижний)]
        if показ.ширина is not None:
            правый = левый + показ.ширина
            верхний = нижний + (показ.высота or 0.0)
            углы = [(левый, нижний), (правый, нижний),
                    (правый, верхний), (левый, верхний)]
        доли = [_повернуть(гx, гy, ширина_рамки, высота_рамки, поворот)
                for гx, гy in углы]
        полигон = tuple(доли) if показ.ширина is not None else None
        # Привязка — повёрнутое **начало** строки, а не угол её коробки. Угол
        # зависит от длины текста, и склейка строк по нему разъезжается тем
        # сильнее, чем длиннее кусок: у повёрнутой страницы длина уходит в ту
        # же сторону, по которой строки и различаются.
        привязка_x, привязка_y = доли[0]
        свойства = [
            ("вид", "текст"),
            ("глифов", показ.глифов),
            ("привязка_x", привязка_x),
            ("привязка_y", привязка_y),
            ("кегль", f"{Decimal(repr(показ.высота or 0)).quantize(Decimal('0.01')):f}"),
            # Кегль в долях листа. Без него сегментатору пришлось бы переводить
            # пункты в доли по предположению о размере страницы, а размер у
            # каждого семейства свой: настоящая выписка пришла на листе
            # 1200×1700, а не на привычных 612×792.
            ("кегль_долей", _доля(показ.высота or 0,
                                  высота_рамки if поворот in (0, 180) else ширина_рамки)),
            ("порядок_вывода", порядок),
            ("поворот_страницы", поворот),
        ]
        if полигон is None:
            свойства.append(("ширина_неизвестна", True))
        return SourceObject(
            document_id=document_id, страница=номер,
            система_координат="доли страницы 0..1, начало снизу слева",
            структурный_путь=f"страница[{номер}]/текст[{порядок}]",
            сырой_текст=показ.текст, полигон=полигон,
            свойства=tuple(свойства))

    def _о_странице(self, document_id, номер, ширина, высота, слой,
                    сколько, есть_картинки, признаки, беда, поворот=0):
        свойства = [
            ("вид", "страница"),
            ("слой", слой),
            ("поворот", поворот),
            ("объектов_текста", сколько),
            ("есть_изображения", есть_картинки),
            ("ширина_пунктов", f"{Decimal(repr(ширина)).quantize(Decimal('0.01')):f}"),
            ("высота_пунктов", f"{Decimal(repr(высота)).quantize(Decimal('0.01')):f}"),
        ]
        свойства.extend(sorted(признаки.items()))
        if беда:
            свойства.append(("почему", беда))
        return SourceObject(
            document_id=document_id, страница=номер,
            система_координат="доли страницы 0..1, начало снизу слева",
            структурный_путь=f"страница[{номер}]",
            сырой_текст=None, полигон=None, свойства=tuple(свойства))


