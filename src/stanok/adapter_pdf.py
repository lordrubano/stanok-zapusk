def _показать(куски, tm, ctm, шрифт, размер, гориз):
    текст = []
    ширина_единиц = 0.0
    ширина_известна = True
    глифов = 0
    for кусок in куски:
        if isinstance(кусок, (int, float)):
            ширина_единиц -= float(кусок) / 1000.0
            continue
        if not isinstance(кусок, bytes):
            continue
        if шрифт is None:
            текст.append(кусок.decode("cp1252", errors="replace"))
            глифов += len(кусок)
            ширина_известна = False
            continue
        for код in шрифт.коды(кусок):
            глифов += 1
            текст.append(шрифт.знак(код))
            ширина = шрифт.ширина(код)
            if ширина is None:
                ширина_известна = False
            else:
                ширина_единиц += ширина / 1000.0

    собранный = "".join(текст)
    матрица = _умножить(tm, ctm)
    x, y = _точка(матрица, 0.0, 0.0)
    масштаб = (матрица[0] ** 2 + матрица[1] ** 2) ** 0.5 or 1.0
    ширина_точек = ширина_единиц * размер * гориз
    сдвиг = _умножить((1.0, 0.0, 0.0, 1.0, ширина_точек, 0.0), tm)

    if глифов == 0:
        return None, сдвиг
    показ = _Показ(
        собранный, x, y,
        ширина_точек * масштаб if ширина_известна else None,
        размер * масштаб, шрифт, глифов)
    return показ, сдвиг


