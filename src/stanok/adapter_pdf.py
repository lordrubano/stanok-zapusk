# Обозримая часть частного диапазона Unicode: туда попадает текст, у которого
# толкование знаков подменено, — на вид буквы, на деле неизвестно что.
_ЧАСТНЫЙ = (0xE000, 0xF8FF)

# Имена частей образца латинские: в двоичном образце кириллица недопустима —
# тот же урок, что и с командной строкой в шаге 24.
_ЛЕКСЕМА = re.compile(
    rb"(?P<lit>\((?:[^()\\]|\\.|\([^()]*\))*\))"
    rb"|(?P<hexs><[0-9A-Fa-f\s]*>)"
    rb"|(?P<name>/[^\s/\[\]()<>{}]*)"
    rb"|(?P<num>[-+]?\d*\.?\d+)"
    rb"|(?P<brack>[\[\]])"
    rb"|(?P<op>[A-Za-z'\"*][A-Za-z0-9'\"*]*)",
    re.DOTALL)


def _умножить(первая, вторая):
    a1, b1, c1, d1, e1, f1 = первая
    a2, b2, c2, d2, e2, f2 = вторая
    return (a1 * a2 + b1 * c2, a1 * b2 + b1 * d2,
            c1 * a2 + d1 * c2, c1 * b2 + d1 * d2,
            e1 * a2 + f1 * c2 + e2, e1 * b2 + f1 * d2 + f2)


def _точка(матрица, x, y):
    a, b, c, d, e, f = матрица
    return (a * x + c * y + e, b * x + d * y + f)


# Повороты, которые разрешает сам PDF. Иные значения приводятся к ближайшему
# кратному 90: страница, объявившая поворот 45 градусов, в природе не
# встречается, а молча принять её значило бы посчитать координаты неверно.
_ПОВОРОТЫ = (0, 90, 180, 270)


def _поворот(документ, страница) -> int:
    """Поворот страницы при показе. Наследуется от узла дерева страниц."""
    значение = документ.раскрыть(страница.get("/Rotate"))
    if значение is None:
        родитель = документ.раскрыть(страница.get("/Parent"))
        if isinstance(родитель, dict):
            значение = документ.раскрыть(родитель.get("/Rotate"))
    try:
        угол = int(значение) % 360
    except (TypeError, ValueError):
        return 0
    return угол if угол in _ПОВОРОТЫ else min(
        _ПОВОРОТЫ, key=lambda свой: abs(свой - угол))


def _повернуть(x, y, ширина, высота, поворот):
    """Точка страницы в долях **видимого** листа.

    Раздел 6.2 требует зафиксированной ориентации. Ориентация, зафиксированная
    как «как записано в файле», ею не является: у повёрнутой страницы низ листа
    в файле — это его бок на экране и на бумаге. Пока поворот не учитывался,
    сегментатор собирал в строку колонку — на настоящей выписке это дало
    строки с пятнадцатью датами.
    """
    if поворот == 90:
        # По часовой стрелке: левый край страницы становится верхним краем
        # листа. Направление проверено на настоящем документе — при обратном
        # знаке строка собирается справа налево, и первый столбец выписки
        # оказывается последним.
        новый_x, новый_y, ш, в = y, ширина - x, высота, ширина
    elif поворот == 180:
        новый_x, новый_y, ш, в = ширина - x, высота - y, ширина, высота
    elif поворот == 270:
        новый_x, новый_y, ш, в = высота - y, x, высота, ширина
    else:
        новый_x, новый_y, ш, в = x, y, ширина, высота
    return (_доля(новый_x, ш), _доля(новый_y, в))


def _доля(значение, размер) -> str:
    """Доля страницы строкой. Строка не теряет точности и не зависит от локали."""
    if not размер:
        return "0.000000"
    with localcontext() as правила:
        правила.prec = 12
        доля = Decimal(repr(значение)) / Decimal(repr(размер))
    return f"{доля.quantize(Decimal('0.000001')):f}"


