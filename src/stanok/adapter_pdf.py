class Шрифт:
    """Толкование кодов знаков и их ширины для одного шрифта страницы."""

    def __init__(self, документ, словарь):
        self.словарь = словарь or {}
        self.двухбайтовый = False
        self.толкование: dict[int, str] = {}
        self.ширины: dict[int, float] = {}
        self.есть_toUnicode = False
        self.подтип = self.словарь.get("/Subtype", "")
        self._разобрать(документ)

    def _разобрать(self, документ):
        потомки = документ.раскрыть(self.словарь.get("/DescendantFonts"))
        составной = self.подтип == "/Type0"
        кодировка = self.словарь.get("/Encoding")
        if составной:
            self.двухбайтовый = True

        поток = документ.поток(self.словарь.get("/ToUnicode"))
        if поток:
            self.есть_toUnicode = True
            self.толкование = _разобрать_cmap(поток)

        источник = self.словарь
        if составной and isinstance(потомки, list) and потомки:
            потомок = документ.раскрыть(потомки[0])
            if isinstance(потомок, dict):
                источник = потомок
                self.ширины = _ширины_составного(документ, потомок)
        if not составной:
            self.ширины = _ширины_простого(документ, источник)
        self.кодировка_имя = кодировка if isinstance(кодировка, str) else ""

    def коды(self, данные: bytes):
        if self.двухбайтовый:
            for место in range(0, len(данные) - 1, 2):
                yield (данные[место] << 8) | данные[место + 1]
        else:
            yield from данные

    def знак(self, код: int) -> str:
        if код in self.толкование:
            return self.толкование[код]
        if self.двухбайтовый:
            # Многобайтовый код без ToUnicode истолковать нечем. Подставлять
            # что-нибудь правдоподобное нельзя: получится текст, который
            # выглядит текстом и им не является.
            return "�"
        return bytes([код]).decode("cp1252", errors="replace")

    def ширина(self, код: int):
        return self.ширины.get(код)


def _ширины_простого(документ, словарь) -> dict[int, float]:
    первый = документ.раскрыть(словарь.get("/FirstChar"))
    ширины = документ.раскрыть(словарь.get("/Widths"))
    если_нет = {}
    if not isinstance(ширины, list) or not isinstance(первый, int):
        return если_нет
    собранные = {}
    for сдвиг, значение in enumerate(ширины):
        значение = документ.раскрыть(значение)
        if isinstance(значение, (int, float)):
            собранные[первый + сдвиг] = float(значение)
    return собранные


def _ширины_составного(документ, потомок) -> dict[int, float]:
    таблица = документ.раскрыть(потомок.get("/W"))
    собранные = {}
    if not isinstance(таблица, list):
        return собранные
    место = 0
    while место < len(таблица):
        первый = документ.раскрыть(таблица[место])
        следующее = документ.раскрыть(таблица[место + 1]) if место + 1 < len(таблица) else None
        if isinstance(следующее, list):
            for сдвиг, значение in enumerate(следующее):
                значение = документ.раскрыть(значение)
                if isinstance(значение, (int, float)) and isinstance(первый, int):
                    собранные[первый + сдвиг] = float(значение)
            место += 2
        elif место + 2 < len(таблица):
            последний = следующее
            ширина = документ.раскрыть(таблица[место + 2])
            if all(isinstance(з, int) for з in (первый, последний)) and \
                    isinstance(ширина, (int, float)):
                for код in range(первый, min(последний, первый + 65535) + 1):
                    собранные[код] = float(ширина)
            место += 3
        else:
            break
    return собранные


_BFCHAR = re.compile(rb"beginbfchar(.*?)endbfchar", re.DOTALL)
_BFRANGE = re.compile(rb"beginbfrange(.*?)endbfrange", re.DOTALL)
_ПАРА = re.compile(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>")
_ТРОЙКА = re.compile(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>")
_ДИАПАЗОН_СПИСКОМ = re.compile(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*\[(.*?)\]",
                               re.DOTALL)


def _знаки(шестнадцать: bytes) -> str:
    цифры = шестнадцать.decode("ascii")
    if len(цифры) % 4:
        цифры = цифры.zfill(((len(цифры) + 3) // 4) * 4)
    куски = [цифры[место : место + 4] for место in range(0, len(цифры), 4)]
    return "".join(chr(int(кусок, 16)) for кусок in куски if кусок)


def _разобрать_cmap(поток: bytes) -> dict[int, str]:
    """Разбирает таблицу толкования ToUnicode."""
    толкование: dict[int, str] = {}
    for кусок in _BFCHAR.findall(поток):
        for код, знак in _ПАРА.findall(кусок):
            толкование[int(код, 16)] = _знаки(знак)
    for кусок in _BFRANGE.findall(поток):
        for первый, последний, начало in _ТРОЙКА.findall(кусок):
            низ, верх = int(первый, 16), int(последний, 16)
            если = int(начало, 16)
            for сдвиг in range(0, min(верх - низ, 65535) + 1):
                толкование[низ + сдвиг] = chr(если + сдвиг)
        for первый, последний, список in _ДИАПАЗОН_СПИСКОМ.findall(кусок):
            низ = int(первый, 16)
            for сдвиг, знак in enumerate(re.findall(rb"<([0-9A-Fa-f]+)>", список)):
                толкование[низ + сдвиг] = _знаки(знак)
    return толкование


