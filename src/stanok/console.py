    def as_json(self) -> dict:
        return {
            "версия": self.версия,
            "record_id": self.record_id,
            "статус": self.статус,
            "страница": self.страница,
            "почему": self.почему,
            "сомнения": [с.as_json() for с in self.сомнения],
            "поля": [п.as_json() for п in self.поля],
            "фрагмент": self.фрагмент.as_json(),
        }


