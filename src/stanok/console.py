def _э(значение) -> str:
    return html.escape("" if значение is None else str(значение))


def _фрагмент_html(фрагмент: Фрагмент) -> str:
    куски = [f'<div class="место">{_э(фрагмент.место)}</div>']
    for текст in фрагмент.выше:
        куски.append(f'<div class="сосед">↑ {_э(текст)}</div>')
    if фрагмент.ячейки:
        строки = "".join(
            f'<td class="{"отмечена" if я.отмечена else ""}">{_э(я.текст)}'
            + (f'<div class="место">{_э(я.поле)}</div>' if я.поле else "")
            + "</td>"
            for я in фрагмент.ячейки)
        куски.append(f"<table><tr>{строки}</tr></table>")
    else:
        куски.append('<div class="тише">строка источника не найдена</div>')
    for текст in фрагмент.ниже:
        куски.append(f'<div class="сосед">↓ {_э(текст)}</div>')
    return "".join(куски)


def _поля_html(поля) -> str:
    строки = []
    for поле in поля:
        сомнения = "".join(
            f'<div class="место">{_э(с.словами)}</div>' for с in поле.сомнения)
        строки.append(
            f"<tr><td>{_э(поле.имя)}</td>"
            f"<td><b>{_э(поле.значение)}</b>{сомнения}</td>"
            f"<td>{_э(поле.сырьё)}</td>"
            f'<td class="тише">{_э(поле.правило)}<div class="место">'
            f"{_э(поле.место)}</div></td></tr>")
    return ("<table><tr><th>поле</th><th>значение</th><th>в документе</th>"
            "<th>правило и место</th></tr>" + "".join(строки) + "</table>")


def экран_html(экран: Экран) -> str:
    """Одна запись: сомнение сверху, фрагмент слева, поля справа."""
    статус = экран.статус or "решение не вынесено"
    return (
        f'<section class="запись"><div class="шапка">'
        f"<b>{_э(экран.record_id)}</b>"
        f'<span class="статус {"review" if статус == "review" else ""}">'
        f"{_э(статус)}</span>"
        f'<span class="место">{_э(экран.фрагмент.место)}</span></div>'
        f'<div class="почему">{_э(экран.почему)}</div>'
        f'<div class="рядом"><div class="фрагмент">'
        f"{_фрагмент_html(экран.фрагмент)}</div>"
        f'<div class="поля">{_поля_html(экран.поля)}</div></div></section>')


def страница_html(экраны, заголовок: str = "Экран разбора",
                  сколько: int | None = None) -> str:
    """Готовая страница для оператора. Показ, и только показ.

    ``сколько`` ограничивает число показанных записей: тысячи записей на одной
    странице читать невозможно, а урезание обязано быть видимым, а не тихим.
    """
    экраны = tuple(экраны)
    свои = экраны if сколько is None else экраны[:сколько]
    сводка = свод(экраны)
    связки_html = "".join(
        f'<span class="связка"><b>{с["сколько"]}</b> — {_э(с["род"])}'
        + (f' ({_э(", ".join(с["поля"]))})' if с["поля"] else "") + "</span>"
        for с in сводка["связки"])
    урезано = ("" if len(свои) == len(экраны) else
               f'<div class="тише">показано {len(свои)} записей из '
               f"{len(экраны)}: остальные не уместились бы на одной странице"
               "</div>")
    return (
        "<!doctype html><html lang=\"ru\"><meta charset=\"utf-8\">"
        f"<title>{_э(заголовок)}</title><style>{_СТИЛЬ}</style>"
        f"<header><b>{_э(заголовок)}</b> — записей {сводка['записей']}, "
        f"с сомнением {сводка['с_сомнением']}, без сомнения "
        f"{сводка['без_сомнения']}</header>"
        f'<div class="свод">{связки_html}{урезано}</div>'
        + "".join(экран_html(э) for э in свои)
        + "</html>")


