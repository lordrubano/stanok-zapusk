@dataclass(frozen=True, slots=True)
class Сомнение:
    """Одно сомнение, названное словами.

    ``род`` — для связок и порядка, ``словами`` — для человека, ``ключ`` — для
    машины. Ни одно из трёх не заменяет другого: по ключу связку не соберёшь, а
    словами машину не научишь.
    """

    род: str
    поле: str | None
    словами: str
    ключ: str = ""
    сырьё: str | None = None

    def as_json(self) -> dict:
        return {"род": self.род, "поле": self.поле, "словами": self.словами,
                "ключ": self.ключ, "сырьё": self.сырьё}


@dataclass(frozen=True, slots=True)
class ПолеЭкрана:
    """Поле записи так, как его видит оператор."""

    имя: str
    значение: str | None
    сырьё: str | None
    правило: str
    место: str
    страница: int | None
    адрес: str | None
    сомнения: tuple[Сомнение, ...] = ()

    def as_json(self) -> dict:
        return {"имя": self.имя, "значение": self.значение, "сырьё": self.сырьё,
                "правило": self.правило, "место": self.место,
                "страница": self.страница, "адрес": self.адрес,
                "сомнения": [с.as_json() for с in self.сомнения]}


@dataclass(frozen=True, slots=True)
class Ячейка:
    """Ячейка фрагмента источника."""

    текст: str
    столбец: str | None
    адрес: str
    поле: str | None = None
    отмечена: bool = False


@dataclass(frozen=True, slots=True)
class Фрагмент:
    """Кусок источника вокруг записи: её строка и соседние.

    Соседи нужны не для красоты: по ним видно, не съехала ли граница операции и
    не утащило ли продолжение чужую строку.
    """

    страница: int | None
    адрес: str | None
    ячейки: tuple[Ячейка, ...] = ()
    выше: tuple[str, ...] = ()
    ниже: tuple[str, ...] = ()
    место: str = ""

    def as_json(self) -> dict:
        return {"страница": self.страница, "адрес": self.адрес,
                "место": self.место,
                "ячейки": [{"текст": я.текст, "столбец": я.столбец,
                            "адрес": я.адрес, "поле": я.поле,
                            "отмечена": я.отмечена} for я in self.ячейки],
                "выше": list(self.выше), "ниже": list(self.ниже)}


@dataclass(frozen=True, slots=True)
class Экран:
    """Экран разбора одной записи."""

    версия: str
    record_id: str
    статус: str | None
    почему: str
    сомнения: tuple[Сомнение, ...]
    поля: tuple[ПолеЭкрана, ...]
