def _двоякая_дата_словами(сырьё: str, значение: str | None) -> str:
    """«05.03 — это и пятое марта, и третье мая»."""
    цифры = сырьё.replace("-", ".").replace("/", ".").split(".")
    первое, второе = цифры[0].strip(), цифры[1].strip()
    как_день = f"{_ЧИСЛА[int(первое)]} {_МЕСЯЦЫ[int(второе) - 1]}"
    как_месяц = f"{_ЧИСЛА[int(второе)]} {_МЕСЯЦЫ[int(первое) - 1]}"
    прочтено = f" Станок прочёл: {значение}." if значение else ""
    return (f"Дата читается двояко: {первое}.{второе} — это и {как_день}, "
            f"и {как_месяц}.{прочтено} Выбор сделан объявлением семейства, "
            "а не документом.")


def _разряды(цифры: str) -> str:
    """«12345» → «12 345». Разряды разделяются, как это делают в бумаге."""
    return f"{int(цифры):,}".replace(",", " ") if цифры.isdigit() else цифры


def _копейки_словами(сырьё: str, значение: str | None) -> str:
    """Числительные не склоняются нарочно: «1 234,56» вернее, чем «1234 рублей».

    Склонение по-русски зависит от числа, и подогнать его одной строкой на все
    случаи нельзя. Неверно склонённое число оператор читает дольше, чем просто
    записанное цифрами, — а быстрота чтения здесь и есть предмет работы.
    """
    без_пробелов = "".join(з for з in сырьё.strip().strip("()") if з.isdigit())
    целое = _разряды(без_пробелов)
    с_копейками = (f"{_разряды(без_пробелов[:-2])},{без_пробелов[-2:]}"
                   if len(без_пробелов) > 2
                   else f"0,{без_пробелов.rjust(2, chr(48))}")
    прочтено = f" Станок прочёл: {значение}." if значение else ""
    return (f"В сумме нет разделителя копеек: {сырьё.strip()} — это и {целое} "
            f"целыми, и {с_копейками} с копейками.{прочтено} Выбор сделан "
            "объявлением семейства.")


def _скобки_словами(сырьё: str, значение: str | None) -> str:
    прочтено = f" Станок прочёл: {значение}." if значение else ""
    return (f"Сумма записана в скобках: {сырьё.strip()}. У этого семейства "
            f"скобки объявлены минусом.{прочтено} В другом семействе те же "
            "скобки могут не значить ничего.")


def _написание_словами(поле: str, сырьё: str | None, значение: str | None) -> str:
    return (f"Написание изменено при чтении: в документе «{сырьё}», "
            f"в записи «{значение}». Знаки различаются, а не только вид.")


def сомнение_из_предупреждения(предупреждение, значение: str | None) -> Сомнение:
    """Предупреждение о значении, сказанное человеку.

    Род определяется по правилу, которым станок разрешил неоднозначность, а не
    по имени поля: одно и то же поле в разных семействах разрешается по-разному.
    """
    сырьё = str(предупреждение.сырьё or "")
    правило = предупреждение.правило or ""

    if предупреждение.род == РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ:
        if правило.startswith("порядок частей даты"):
            return Сомнение(ДВОЯКАЯ_ДАТА, предупреждение.поле,
                            _двоякая_дата_словами(сырьё, значение),
                            правило, сырьё)
        if правило.startswith("неявные копейки"):
            return Сомнение(НЕЯВНЫЕ_КОПЕЙКИ, предупреждение.поле,
                            _копейки_словами(сырьё, значение), правило, сырьё)
        if правило.startswith("знак в скобках"):
            return Сомнение(ЗНАК_В_СКОБКАХ, предупреждение.поле,
                            _скобки_словами(сырьё, значение), правило, сырьё)
    if предупреждение.род == ИЗМЕНЕНО_НАПИСАНИЕ:
        return Сомнение(ИНОЕ_НАПИСАНИЕ, предупреждение.поле,
                        _написание_словами(предупреждение.поле, сырьё, значение),
                        правило, сырьё)

    # Незнакомый род не подгоняется под похожую фразу: показывается как есть.
    return Сомнение(предупреждение.род, предупреждение.поле,
                    f"{предупреждение.род}: {предупреждение.пояснение or правило}",
                    правило, сырьё)


def сомнение_из_слагаемого(наблюдение) -> Сомнение:
    """Невыполненное слагаемое формулы допуска, сказанное человеку."""
    ключ = getattr(наблюдение, "слагаемое", "")
    подробность = getattr(наблюдение, "подробность", "") or ""
    состояние = getattr(наблюдение, "состояние", "")
    слова = СЛОВА_СЛАГАЕМЫХ.get(ключ, ключ)
    если_неизвестно = (" Это не нарушение, а неизвестность: наблюдателя у "
                       "слагаемого нет." if состояние == "неизвестно" else "")
    return Сомнение(
        НЕ_ХВАТАЕТ_СЛАГАЕМОГО, None,
        f"Запись ушла человеку, потому что {слова}."
        + (f" Подробность: {подробность}." if подробность else "")
        + если_неизвестно,
        ключ)


def _сомнение_неистолкованного(имя: str, поле: dict) -> Сомнение | None:
    """Поле, которое станок не смог прочитать вовсе."""
    отказ = поле.get("error") or поле.get("отказ")
    if not отказ:
        return None
    сырьё = поле.get("raw")
    return Сомнение(
        НЕИСТОЛКОВАННОЕ_ПОЛЕ, имя,
        f"Поле «{имя}» не прочитано: в документе стоит «{сырьё}», и правило "
        f"семейства к этому не подошло. Причина от станка: {отказ}.",
        str(отказ), сырьё)


def _вес(сомнение: Сомнение) -> int:
    try:
        return ПОРЯДОК_РОДОВ.index(сомнение.род)
    except ValueError:
        return len(ПОРЯДОК_РОДОВ)


