def _поля_записи(запись: dict) -> dict:
    return запись.get("fields") or {}


def _свидетельство(свидетельства, имя: str):
    for с in свидетельства:
        if с.поле == имя:
            return с
    return None


def _места_строк(строки) -> dict:
    """Указатель «адрес строки → её место в источнике». Строится один раз.

    Собирать его на каждую запись значило бы обойти все строки документа три
    тысячи раз: на настоящей выписке это секунды на ровном месте.
    """
    return {строка.адрес: место for место, строка in enumerate(строки)}


def _к_строке(адрес: str) -> str:
    """Адрес записи → адрес её первой строки.

    Запись адресуется якорем своей первой строки с припиской «/запись»: она
    отличает саму операцию от строки, из которой операция началась. Экрану
    нужна строка, и приписка снимается здесь, а не угадывается показом.
    """
    return адрес[:-len("/запись")] if адрес.endswith("/запись") else адрес


def _метка_ячейки(ячейка, поля_по_месту, поля_по_тексту) -> str | None:
    """Какое поле взято из этой ячейки, если такое есть.

    Сличается **место**, а не текст: у ячейки и у свидетельства поля один и тот
    же объект источника, а значит одна и та же область на странице. Совпадение
    по тексту оставлено запасным путём — для источников без координат, где
    области нет вовсе.
    """
    объект = getattr(ячейка, "объект", None)
    полигон = getattr(объект, "полигон", None)
    страница = getattr(объект, "страница", None)
    если_место = поля_по_месту.get((страница, полигон)) if полигон else None
    if если_место:
        return если_место
    return поля_по_тексту.get((ячейка.текст or "").strip())


def _фрагмент(строки, адреса_записи, поля_по_месту, поля_по_тексту,
              с_сомнением=(), места=None) -> Фрагмент:
    """Строка источника записи и её соседи сверху и снизу."""
    if not строки:
        return Фрагмент(None, None, (), (), (), "место неизвестно: строк нет")
    места = _места_строк(строки) if места is None else места
    свои = [места[_к_строке(адрес)] for адрес in адреса_записи
            if _к_строке(адрес) in места]
    if not свои:
        return Фрагмент(None, None, (), (), (),
                        "место неизвестно: строка записи не найдена")
    первая = строки[min(свои)]
    # Помечается не всякая узнанная ячейка, а та, из-за которой запись открыли:
    # подсветить всю строку — то же самое, что не подсветить ничего.
    ячейки = []
    for я in первая.ячейки:
        поле = _метка_ячейки(я, поля_по_месту, поля_по_тексту)
        ячейки.append(Ячейка(я.текст, я.столбец, я.адрес, поле,
                             поле in с_сомнением))
    ячейки = tuple(ячейки)
    выше = tuple(с.текст for с in строки[max(0, min(свои) - 1):min(свои)])
    ниже = tuple(с.текст for с in строки[max(свои) + 1:max(свои) + 2])
    return Фрагмент(первая.страница, первая.адрес, ячейки, выше, ниже,
                    f"страница {первая.страница}, строка {первая.адрес}")


def собрать_экран(запись: dict, свидетельства, предупреждения, решение,
                  строки, места=None) -> Экран:
    """Собирает экран одной записи из уже готового. Ничего не пересчитывает."""
    поля_записи = _поля_записи(запись)
    значения = {имя: (поле.get("value") if isinstance(поле, dict) else None)
                for имя, поле in поля_записи.items()}

    сомнения = [сомнение_из_предупреждения(п, значения.get(п.поле))
                for п in предупреждения]
    for имя, поле in sorted(поля_записи.items()):
        своё = _сомнение_неистолкованного(имя, поле) if isinstance(поле, dict) else None
        if своё is not None:
            сомнения.append(своё)
    if решение is not None:
        for наблюдение in getattr(решение, "невыполненные", ()):
            if getattr(наблюдение, "слагаемое", "") == "no_value_warning" \
                    and any(с.род in ПОРЯДОК_РОДОВ[:4] for с in сомнения):
                # Слагаемое «предупреждений нет» уже сказано теми самыми
                # предупреждениями. Повторять его общей фразой значило бы
                # отодвинуть настоящее объяснение вниз.
                continue
            сомнения.append(сомнение_из_слагаемого(наблюдение))
    сомнения.sort(key=_вес)

    по_полю: dict[str, list[Сомнение]] = {}
    for с in сомнения:
        if с.поле:
            по_полю.setdefault(с.поле, []).append(с)

    поля_экрана = []
    поля_по_месту, поля_по_тексту = {}, {}
    for имя, поле in sorted(поля_записи.items()):
        свидетельство = _свидетельство(свидетельства, имя)
        адрес = getattr(свидетельство, "source_anchor_id", None)
        полигон = getattr(свидетельство, "полигон", None)
        страница_поля = getattr(свидетельство, "страница", None)
        if полигон:
            поля_по_месту.setdefault(
                (страница_поля, tuple(tuple(т) for т in полигон)), имя)
        сырьё_поля = поле.get("raw") if isinstance(поле, dict) else None
        if сырьё_поля:
            поля_по_тексту.setdefault(str(сырьё_поля).strip(), имя)
        поля_экрана.append(ПолеЭкрана(
            имя=имя,
            значение=значения.get(имя),
            сырьё=(поле.get("raw") if isinstance(поле, dict) else None),
            правило=getattr(свидетельство, "правило", "") or "",
            место=(свидетельство.место() if свидетельство is not None
                   else "место неизвестно: происхождение не собрано"),
            страница=getattr(свидетельство, "страница", None),
            адрес=адрес,
            сомнения=tuple(по_полю.get(имя, ()))))

    фрагмент = _фрагмент(строки, запись.get("source_anchor_ids", ()),
                         поля_по_месту, поля_по_тексту,
                         frozenset(по_полю), места)
    статус = getattr(решение, "статус", None) if решение is not None else None
    почему = сомнения[0].словами if сомнения else "Сомнений нет."
    return Экран(CONSOLE_VERSION, запись.get("record_id", ""), статус, почему,
                 tuple(сомнения), tuple(поля_экрана), фрагмент,
                 фрагмент.страница)


def собрать_экраны(проводка) -> tuple[Экран, ...]:
    """Экраны разбора по всей проводке, в порядке записей документа."""
    строки = getattr(getattr(проводка, "сегментация", None), "строки", ())
    места = _места_строк(строки)
    решения = {р.record_id: р for р in getattr(проводка, "решения", ())}
    экраны = []
    for запись in getattr(проводка, "записи", ()):
        ключ = запись.get("record_id", "")
        экраны.append(собрать_экран(
            запись,
            проводка.происхождение.get(ключ, ()),
            проводка.предупреждения.get(ключ, ()),
            решения.get(ключ),
            строки, места))
    return tuple(экраны)


# ------------------------------------------------------------- связки


@dataclass(frozen=True, slots=True)
class Связка:
    """Записи с одинаковым сомнением: их оператор проходит подряд."""

    род: str
    сколько: int
    поля: tuple[str, ...]
    образец: str
    record_ids: tuple[str, ...] = field(default=())

    def as_json(self) -> dict:
        return {"род": self.род, "сколько": self.сколько,
                "поля": list(self.поля), "образец": self.образец,
                "record_ids": list(self.record_ids)}


def связки(экраны) -> tuple[Связка, ...]:
    """Собирает одинаковые сомнения вместе, от самого частого к редкому.

    Ради этого экран и делался быстрым: почти треть записей первого банка
    отличается друг от друга только числами в одной и той же двоякой дате, и
    показывать их как несвязанные значило бы заставить оператора разбираться
    заново три тысячи раз.
    """
    собранные: dict[str, dict] = {}
    for экран in экраны:
        for сомнение in экран.сомнения:
            свои = собранные.setdefault(
                сомнение.род, {"поля": set(), "record_ids": [],
                               "образец": сомнение.словами})
            if сомнение.поле:
                свои["поля"].add(сомнение.поле)
            # Запись входит в связку **один раз**, сколько бы сомнений одного
            # рода в ней ни было. Иначе связка называет число больше, чем в
            # ней записей, оператор вводит показанное — и получает отказ по
            # несошедшемуся числу. Так и было на настоящем документе: связка
            # объявляла 1935 записей при 645 настоящих, и решение по ней не
            # проходило вовсе. Куплено проходом браузерного пути.
            if экран.record_id not in свои["record_ids"]:
                свои["record_ids"].append(экран.record_id)
    готовые = [
        Связка(род, len(свои["record_ids"]), tuple(sorted(свои["поля"])),
               свои["образец"], tuple(свои["record_ids"]))
        for род, свои in собранные.items()]
    готовые.sort(key=lambda с: (-с.сколько, _вес(Сомнение(с.род, None, ""))))
    return tuple(готовые)


def свод(экраны) -> dict:
    """Числа для верхней части экрана: сколько записей и с чем."""
    экраны = tuple(экраны)
    с_сомнением = [э for э in экраны if э.сомнения]
    return {
        "версия": CONSOLE_VERSION,
        "записей": len(экраны),
        "с_сомнением": len(с_сомнением),
        "без_сомнения": len(экраны) - len(с_сомнением),
        "связки": [с.as_json() for с in связки(экраны)],
    }


