@dataclass(frozen=True, slots=True)
class Пункт:
    """Одна из девяти вещей: что сказано и чем подтверждено."""

    имя: str
    значение: str
    подтверждено: str

    def as_json(self) -> dict:
        return {"имя": self.имя, "значение": self.значение,
                "подтверждено": self.подтверждено}


@dataclass(frozen=True, slots=True)
class Девять:
    """Переход от числа к источнику: девять вещей об одном значении."""

    запись: str
    поле: str
    значение: str
    пункты: tuple[Пункт, ...]

    def as_json(self) -> dict:
        return {"версия": PROOF_VERSION, "запись": self.запись,
                "поле": self.поле, "значение": self.значение,
                "пункты": [п.as_json() for п in self.пункты]}


def _как_текст(значение) -> str:
    if значение is None:
        return ""
    if isinstance(значение, Decimal):
        return format(значение, "f")
    return str(значение)


def _проверки_словами(экран, поле) -> str:
    """Что проверки сказали об этом поле. Молчание тут — не «всё хорошо»."""
    свои = []
    статус = getattr(экран, "статус", None)
    if статус:
        свои.append(f"статус записи: {статус}")
    почему = getattr(экран, "почему", "")
    if почему:
        свои.append(почему)
    сомнения = tuple(getattr(поле, "сомнения", ()) or ())
    for сомнение in сомнения:
        свои.append(f"сомнение «{сомнение.род}»: {сомнение.словами}")
    if not сомнения:
        свои.append("по этому полю сомнений не поднято")
    return "; ".join(свои)


def _правка_словами(события, поле: str) -> tuple[str, bool]:
    """Была ли ручная правка этого поля и какая именно."""
    свои = [с for с in события if с.get("поле") == поле]
    if not свои:
        return ("правок не было: значение такое, каким его прочитал станок",
                False)
    последняя = свои[-1]
    было = _как_текст(последняя.get("было_значение"))
    стало = _как_текст(последняя.get("стало_значение"))
    return (f"{последняя.get('оператор', 'оператор')} "
            f"{последняя.get('время', '')}: было «{было}», стало «{стало}». "
            f"Основание: {последняя.get('основание', 'не названо')}", True)


def девять(экран, поле, *, документ: str, поле_записи=None,
           события_истории=()) -> Девять:
    """Девять вещей об одном значении. Ни одна не считается здесь заново."""
    распознанное = (_как_текст(поле_записи.get("value"))
                    if isinstance(поле_записи, dict)
                    else _как_текст(getattr(поле, "значение", None)))
    итоговое = распознанное
    совпало = " (совпадает с распознанным: между распознаванием и выдачей "
    совпало += "значение не меняется)"

    правка, была = _правка_словами(события_истории, поле.имя)
    страница = getattr(поле, "страница", None)
    пункты = (
        Пункт("исходный документ", документ or "документ не назван",
              "паспорт приёма (шаг 20): отпечаток байтов документа"),
        Пункт("страница",
              f"страница {страница}" if страница is not None
              else "страница не определена",
              "свидетельство поля (шаг 35)"),
        Пункт("область", getattr(поле, "место", "") or "область не построена",
              "свидетельство поля (шаг 35): якорь области источника"),
        Пункт("исходное написание", _как_текст(getattr(поле, "сырьё", None))
              or "написание не сохранено",
              "разбор страницы (шаг 28): текст ячейки как он есть"),
        Пункт("распознанное значение", распознанное or "не истолковано",
              "типизатор (шаг 29)"),
        Пункт("применённое преобразование",
              getattr(поле, "правило", "") or "правило не названо",
              "правило истолкования оснастки (шаг 37)"),
        Пункт("итоговое значение",
              (итоговое + совпало) if итоговое else "значения нет",
              "каноническая запись результата"),
        Пункт("результаты проверок", _проверки_словами(экран, поле),
              "движок политик (шаг 45): статус рождается в одном месте"),
        Пункт("ручная правка", правка,
              "неизменяемая история решений (шаг 58)"
              + ("" if была else ": событий по этому полю нет")),
    )
    return Девять(запись=getattr(экран, "запись", "") or "",
                  поле=поле.имя, значение=распознанное, пункты=пункты)


