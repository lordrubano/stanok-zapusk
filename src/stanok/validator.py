# -*- coding: utf-8 -*-
"""Проверки типов, обязательности и словарей — первый уровень валидатора.

Шаг 39 плана. Нормативная основа — чертёж v3.0, раздел 10 (политика допуска),
раздел 9 (уровень 4: обязательные поля, даты, валюты, Decimal, идентификаторы и
словари) и раздел 6.1 (состав ``RuleResult``).

**Проверка не чинит и не подгоняет.** Нашла несоответствие — назвала его. Ни
одно значение здесь не меняется, ни одно поле не дописывается, ни один пробел не
обрезается. Проверка, которая правит, перестаёт быть проверкой: она уравнивает
источник со своим представлением о нём, и расхождение исчезает вместе с
доказательством. Есть отдельная проверка на то, что запись после разбора
побайтово та же.

**Отсутствие значения и пустое значение — разные вещи.** Поля нет вовсе — это
одно; поле есть, а в нём пусто — совсем другое. Пустая строка вместо отсутствия
скрывает, что поле **не прочли**: на вид оно заполнено, на деле неизвестно.
Поэтому обязательность судится по **отсутствию**, а пустота — отдельным правилом
со своим именем и своей причиной.

Третий случай, который тоже нельзя смешивать с первыми двумя: поле есть, сырьё
прочитано, а истолковать его не удалось (типизатор отказался угадывать, шаг 29).
Это не отсутствие и не пустота, а нерешённое истолкование.

**Не проверенное не считается пройденным.** Если схемы для поля нет или оснастка
не приложена, правило даёт ``неизвестно``, а не ``прошло``: раздел 10.1 прямо
запрещает автоматический допуск, когда хотя бы одно обязательное условие
находится в состоянии ``unknown``.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from decimal import Decimal


VALIDATOR_VERSION = "rules-types/1"

KNOWN_LIMITATIONS = (
    "Здесь только четвёртый уровень раздела 9: типы, обязательность, словари и "
    "точность. Порядок и повторы — шаг 40, итоги и балансы — шаг 41, доменные "
    "правила — шаг 42.",
    "Критичность поля берётся из раздела «риск» оснастки. Поле, не названное "
    "критическим, даёт исправимое нарушение; решение о статусе записи "
    "принимает движок политик (шаг 45), а не эти правила.",
    "Точность проверяется по числу разрядов после запятой у истолкованного "
    "значения. Денежная единица с иным числом разрядов (например, три) "
    "объявляется оснасткой; проверка сама ничего не предполагает.",
)

# Состояния правила. «неизвестно» — полноценное состояние, а не отговорка:
# раздел 10.1 запрещает автодопуск при любом unknown.
ПРОШЛО = "прошло"
НАРУШЕНО = "нарушено"
НЕИЗВЕСТНО = "неизвестно"

КРИТИЧЕСКОЕ = "критическое"
ИСПРАВИМОЕ = "исправимое"

_ТИП_ЗНАЧЕНИЯ = {
    "деньги": (Decimal,),
    "дата": (date,),
    "текст": (str,),
    "словарь": (str,),
    "число": (int,),
}


@dataclass(frozen=True, slots=True)
class RuleResult:
    """Результат одного правила. Состав — раздел 6.1."""

    rule_id: str
    версия: str
    статус: str
    критичность: str
    входы: tuple[str, ...]
    вычисления: str
    причина: str

    @property
    def нарушено(self) -> bool:
        return self.статус == НАРУШЕНО

    def as_json(self) -> dict:
        return {
            "rule_id": self.rule_id,
            "версия": self.версия,
            "статус": self.статус,
            "критичность": self.критичность,
            "входы": list(self.входы),
            "вычисления": self.вычисления,
            "причина": self.причина,
        }


def _результат(rule_id, статус, критичность, входы, вычисления, причина):
    return RuleResult(rule_id, VALIDATOR_VERSION, статус, критичность,
                      tuple(входы), вычисления, причина)


def проверить_запись(запись, оснастка=None) -> tuple[RuleResult, ...]:
    """Проверяет запись ``record/1`` по схеме оснастки.

    Ничего не меняет: ни запись, ни оснастку. Возвращает перечень результатов —
    по правилу на каждую проверенную вещь.
    """
    поля = dict(запись.get("fields") or {})
    if оснастка is None:
        return (_результат(
            "схема/нет_оснастки", НЕИЗВЕСТНО, ИСПРАВИМОЕ, tuple(sorted(поля)),
            "оснастка не приложена",
            "проверять типы не по чему: без схемы семейства неизвестно даже, "
            "какие поля обязательны"),)

    описания = {поле["имя"]: поле for поле in оснастка.поля}
    критические = set(оснастка.критические_поля)
    словари = (оснастка.содержимое["нормализация"].get("словари") or {})

    итоги: list[RuleResult] = []
    for имя in sorted(описания):
        описание = описания[имя]
        важность = КРИТИЧЕСКОЕ if имя in критические else ИСПРАВИМОЕ
        итоги.extend(_проверить_поле(имя, описание, поля, важность, словари))

    лишние = sorted(set(поля) - set(описания))
    for имя in лишние:
        итоги.append(_результат(
            "схема/неизвестное_поле", НАРУШЕНО, ИСПРАВИМОЕ, (имя,),
            f"поле {имя!r} есть в записи, но не описано схемой",
            "поле, которого схема не знает, никем не проверено: считать его "
            "исправным не на чем"))
    return tuple(итоги)


def _проверить_поле(имя, описание, поля, важность, словари):
    обязательно = bool(описание.get("обязательно"))

    # 1. Поля нет вовсе.
    if имя not in поля:
        if обязательно:
            return (_результат(
                "обязательность/отсутствует", НАРУШЕНО, важность, (имя,),
                f"поле {имя!r} отсутствует в записи",
                "обязательное поле не найдено: это отсутствие, а не пустота, "
                "и подменять его пустой строкой нельзя"),)
        return (_результат(
            "обязательность/отсутствует", ПРОШЛО, важность, (имя,),
            f"поле {имя!r} отсутствует и необязательно", "поле необязательно"),)

    поле = поля[имя] or {}
    сырьё = поле.get("raw")
    значение = поле.get("value")

    # Поле есть. Правило отсутствия всё равно объявляется — прошедшим: иначе
    # по итогам нельзя отличить «поле на месте, но пустое» от «поля вовсе нет».
    # Различие обязано быть видно, а не выводиться из того, какого правила в
    # перечне не оказалось.
    итоги = [_результат(
        "обязательность/отсутствует", ПРОШЛО, важность, (имя,),
        f"поле {имя!r} присутствует в записи", "поле найдено")]

    # 2. Поле есть, а в нём пусто. Это не отсутствие: поле прочли и оно пустое.
    пусто = сырьё is None or (isinstance(сырьё, str) and сырьё.strip() == "")
    if пусто:
        итоги.append(_результат(
            "значение/пусто", НАРУШЕНО if обязательно else ПРОШЛО, важность,
            (имя,), f"поле {имя!r} присутствует, сырьё пустое",
            "пустое значение — не то же, что отсутствующее: поле прочли, и оно "
            "оказалось пустым. Подмена одного другим скрывает, что поле не "
            "прочли вовсе"))
        return tuple(итоги)

    # 3. Сырьё есть, а истолкования нет: типизатор отказался угадывать.
    if значение is None:
        итоги.append(_результат(
            "тип/не_истолковано", НАРУШЕНО, важность, (имя,),
            f"сырьё {сырьё!r} осталось без истолкования",
            "истолкование не состоялось — ни отсутствие, ни пустота, а "
            "нерешённое: правило истолкования не объявлено или запись ему не "
            "отвечает"))
        return tuple(итоги)

    # 4. Тип истолкованного значения.
    тип = описание.get("тип")
    ожидаемые = _ТИП_ЗНАЧЕНИЯ.get(тип)
    if ожидаемые is None:
        итоги.append(_результат(
            "тип/соответствие", НЕИЗВЕСТНО, важность, (имя,),
            f"тип {тип!r} схемой объявлен, но правилу неизвестен",
            "проверить нечем: неизвестный тип не считается пройденным"))
    elif isinstance(значение, bool) or not isinstance(значение, ожидаемые):
        итоги.append(_результат(
            "тип/соответствие", НАРУШЕНО, важность, (имя,),
            f"ожидался {тип}, получено {type(значение).__name__}",
            "истолкованное значение не того рода, что объявлен схемой"))
    else:
        итоги.append(_результат(
            "тип/соответствие", ПРОШЛО, важность, (имя,),
            f"{тип}: {значение!r}", "тип соответствует схеме"))

    # 5. Словарь.
    if тип == "словарь":
        итоги.append(_проверить_словарь(имя, описание, значение, важность, словари))

    # 6. Точность денежного значения.
    точность = описание.get("точность")
    if точность is not None and isinstance(значение, Decimal):
        итоги.append(_проверить_точность(имя, значение, точность, важность))
    return tuple(итоги)


def _проверить_словарь(имя, описание, значение, важность, словари):
    имя_словаря = описание.get("словарь")
    словарь = словари.get(имя_словаря) if имя_словаря else None
    if not словарь:
        return _результат(
            "словарь/значение", НЕИЗВЕСТНО, важность, (имя,),
            f"словарь {имя_словаря!r} оснасткой не объявлен",
            "сверять не с чем: несверенное не считается верным")
    if значение in словарь.values() or значение in словарь:
        return _результат(
            "словарь/значение", ПРОШЛО, важность, (имя,),
            f"{значение!r} есть в словаре {имя_словаря!r}", "значение известно")
    return _результат(
        "словарь/значение", НАРУШЕНО, важность, (имя,),
        f"{значение!r} отсутствует в словаре {имя_словаря!r}",
        "значение вне объявленного словаря; близкое по написанию слово — не то "
        "же самое слово")


def _проверить_точность(имя, значение: Decimal, точность, важность):
    показатель = -значение.as_tuple().exponent
    разрядов = показатель if показатель > 0 else 0
    if разрядов > int(точность):
        return _результат(
            "точность/разряды", НАРУШЕНО, важность, (имя,),
            f"разрядов после запятой {разрядов}, объявлено {точность}",
            "лишние разряды не отбрасываются: округление здесь было бы правкой "
            "источника, а не проверкой")
    return _результат(
        "точность/разряды", ПРОШЛО, важность, (имя,),
        f"разрядов {разрядов} при объявленных {точность}", "точность соблюдена")


# ------------------------------------------------------------- сводка


def нарушения(итоги) -> tuple[RuleResult, ...]:
    return tuple(итог for итог in итоги if итог.статус == НАРУШЕНО)


def неизвестные(итоги) -> tuple[RuleResult, ...]:
    return tuple(итог for итог in итоги if итог.статус == НЕИЗВЕСТНО)


def типы_проверены(итоги) -> bool:
    """Условие ``required_types_valid`` из формулы 10.1.

    Истинно только когда все правила прошли. Одно ``неизвестно`` делает условие
    ложным: раздел 10.1 прямо запрещает автодопуск при неопределённости.
    """
    итоги = tuple(итоги)
    return bool(итоги) and all(итог.статус == ПРОШЛО for итог in итоги)


def свод(итоги) -> dict:
    итоги = tuple(итоги)
    return {
        "версия": VALIDATOR_VERSION,
        "правил": len(итоги),
        "прошло": sum(1 for и in итоги if и.статус == ПРОШЛО),
        "нарушено": len(нарушения(итоги)),
        "неизвестно": len(неизвестные(итоги)),
        "критических_нарушений": sum(
            1 for и in нарушения(итоги) if и.критичность == КРИТИЧЕСКОЕ),
        "типы_проверены": типы_проверены(итоги),
        "результаты": [и.as_json() for и in итоги],
    }


