# -*- coding: utf-8 -*-
"""Счётчики объектов и сшивка продолжений таблиц между страницами.

Шаг 36 плана. Нормативная основа — чертёж v3.0, раздел 8 (счётчики объектов и
продолжений таблиц входят в обязательную совокупность механизмов покрытия) и
раздел 5.3 (продолжения таблиц и заголовков на новых страницах).

**Таблица, разорванная между страницами, — не две таблицы.** Считать её двумя
значит дважды посчитать шапку и ни разу не заметить, что строки одной таблицы
разошлись по разным счётам.

**Повторённая шапка — не строка данных.** Она выглядит как строка: те же
столбцы, то же место. Посчитать её данными — приписать выписке строку, которой
нет. Пропустить её при сшивке, не назвав, — потерять настоящую строку, если
догадка о шапке была неверна. Поэтому шапка не выбрасывается: она уходит в
исключения **с адресом и причиной**, и карта покрытия её видит.

**Сшивать по догадке нельзя.** Где кончается одна таблица и начинается другая, в
общем случае знает шаблон семейства (шаг 37). Здесь сшивается только то, что
доказуемо по устройству источника, а всё остальное объявляется требующим
шаблона — прямо, с описанием того, чего именно недостаёт.

Что доказуемо без шаблона:

* **совпадение набора столбцов** у последней таблицы страницы и первой таблицы
  следующей — это измеримый факт, а не предположение;
* **повторение шапки** — первая строка продолжения дословно совпадает с первой
  строкой начала. Тоже факт: сравниваются записанные значения.

Чего без шаблона утверждать нельзя, и потому не утверждается:

* что две таблицы с одинаковыми столбцами на соседних страницах — одна таблица,
  а не две разные выписки одной формы, напечатанные подряд;
* где таблица кончается по смыслу: строка итогов, разделитель разделов, начало
  нового счёта — всё это смысл, а не устройство;
* что несовпавшая первая строка продолжения — это вариант шапки.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, InvalidOperation


CONTINUATIONS_VERSION = "continuations/1"

KNOWN_LIMITATIONS = (
    "Сшивается только соседство страниц: последняя таблица одной и первая "
    "таблица следующей. Таблица, прерванная посреди страницы и продолженная "
    "ниже на той же странице, требует шаблона.",
    "Совпадение столбцов и повторение шапки — доказуемые признаки, но не "
    "доказательство тождества таблиц. Две разные выписки одной формы подряд "
    "неотличимы от одной разорванной без шаблона семейства.",
    "Итоговые строки, разделители разделов и начала новых счетов не "
    "распознаются: это смысл, а не устройство источника.",
)


@dataclass(frozen=True, slots=True)
class СшитаяТаблица:
    """Таблица, собранная из кусков на разных страницах."""

    адрес: str
    страницы: tuple[int, ...]
    куски: tuple[str, ...]
    строки: tuple[str, ...]
    строк_шапок: int = 0
    шапок_исключено: int = 0
    основание: str = ""

    @property
    def строк_данных(self) -> int:
        """Строки данных: всё, что осталось, кроме шапки начала.

        Повторённые шапки сюда не входят и вычитать их не нужно: они уже
        вынуты из ``строки`` и лежат в исключениях. Вычесть их второй раз
        значило бы недосчитать столько же настоящих строк.
        """
        return len(self.строки) - self.строк_шапок

    def as_json(self) -> dict:
        return {
            "адрес": self.адрес,
            "страницы": list(self.страницы),
            "кусков": len(self.куски),
            "строк_всего": len(self.строки),
            "строк_шапок": self.строк_шапок,
            "шапок_исключено": self.шапок_исключено,
            "строк_данных": self.строк_данных,
            "основание_сшивки": self.основание,
        }


@dataclass(frozen=True, slots=True)
class ТребуетШаблона:
    """Случай, который без шаблона семейства решить нельзя."""

    где: str
    что: str
    чего_недостаёт: str

    def as_json(self) -> dict:
        return {"где": self.где, "что": self.что,
                "чего_недостаёт": self.чего_недостаёт}


@dataclass(frozen=True, slots=True)
class Сшивка:
    """Итог сшивки: таблицы, счётчики, исключения и нерешённое."""

    schema_version: str = CONTINUATIONS_VERSION
    таблицы: tuple[СшитаяТаблица, ...] = ()
    исключения: tuple = ()
    требуют_шаблона: tuple[ТребуетШаблона, ...] = ()

    @property
    def счётчики(self) -> dict:
        return {
            "таблиц": len(self.таблицы),
            "продолжений": sum(len(т.куски) - 1 for т in self.таблицы),
            "страниц_с_таблицами": len(
                {страница for т in self.таблицы for страница in т.страницы}),
            "строк_всего": sum(len(т.строки) for т in self.таблицы),
            "строк_шапок": sum(т.строк_шапок for т in self.таблицы),
            "шапок_исключено": sum(т.шапок_исключено for т in self.таблицы),
            "строк_данных": sum(т.строк_данных for т in self.таблицы),
        }

    @property
    def всё_решено(self) -> bool:
        return not self.требуют_шаблона

    def as_json(self) -> dict:
        return {
            "schema_version": self.schema_version,
            "счётчики": self.счётчики,
            "таблицы": [т.as_json() for т in self.таблицы],
            "исключения": [и.as_json() for и in self.исключения],
            "требуют_шаблона": [т.as_json() for т in self.требуют_шаблона],
            "всё_решено": self.всё_решено,
        }


def _столбцы_совпадают(первые, вторые, допуск="0.02") -> bool:
    """Совпадает ли набор столбцов у двух кусков.

    Числовые столбцы сравниваются с допуском: у настоящих выписок столбец
    гуляет на доли процента ширины. Именованные — точным совпадением.
    """
    if not первые or not вторые or len(первые) != len(вторые):
        return False
    порог = Decimal(допуск)
    for первый, второй in zip(первые, вторые):
        try:
            if abs(Decimal(str(первый)) - Decimal(str(второй))) > порог:
                return False
        except (InvalidOperation, ValueError, ArithmeticError):
            if первый != второй:
                return False
    return True


def _текст_строки(строки_по_адресу, адрес: str) -> str:
    строка = строки_по_адресу.get(адрес)
    if строка is None:
        return ""
    return " ".join((ячейка.текст or "").strip()
                    for ячейка in строка.ячейки).strip()


def сшить(сегментация, допуск_столбца: str = "0.02", оснастка=None,
          срок=None) -> Сшивка:
    """Сшивает продолжения таблиц между соседними страницами.

    Сшивает только доказуемое. Всё, что требует смысла, объявляется требующим
    шаблона и **не** сшивается: неверная сшивка склеит две разные выписки в
    одну, и потеря будет невидимой.

    ``оснастка`` — пакет семейства (шаг 37). Он и разрешает то, что по одному
    устройству неразрешимо: объявляет, обязана ли шапка повторяться на
    продолжении. Решение приходит **объявлением**, а не догадкой: оснастку
    писал тот, кто видел форму банка, и он отвечает за сказанное.
    """
    from .coverage import Исключение
    from .deadline import место as срок_места

    (срок if срок is not None else срок_места("сборка страниц")).проверить()
    таблицы = list(getattr(сегментация, "таблицы", ()))
    строки_по_адресу = {строка.адрес: строка
                        for строка in getattr(сегментация, "строки", ())}
    if not таблицы:
        return Сшивка()

    по_страницам: dict[int, list] = {}
    for таблица in таблицы:
        по_страницам.setdefault(таблица.страница, []).append(таблица)

    # Кусок таблицы -> к какой сшитой таблице он присоединён.
    присоединён: dict[str, int] = {}
    собранные: list[dict] = []
    исключения: list = []
    нерешённое: list[ТребуетШаблона] = []

    страницы = sorted(по_страницам)
    for место, страница in enumerate(страницы[:-1]):
        следующая = страницы[место + 1]
        if следующая != страница + 1:
            # Между страницами пропуск: сшивать через дыру нельзя.
            continue
        конец = по_страницам[страница][-1]
        начало = по_страницам[следующая][0]

        if not _столбцы_совпадают(конец.столбцы, начало.столбцы, допуск_столбца):
            continue

        шапка_начала = _текст_строки(строки_по_адресу, конец.строки[0])
        первая_продолжения = _текст_строки(строки_по_адресу, начало.строки[0])
        шапка_повторена = bool(шапка_начала) and шапка_начала == первая_продолжения

        if not шапка_повторена:
            # Столбцы те же, а шапка не повторена. По одному устройству это и
            # продолжение без шапки, и вторая выписка той же формы.
            объявлено = getattr(оснастка, "шапка_повторяется", None)
            if объявлено is True:
                # Оснастка сказала: у этого семейства шапка повторяется всегда.
                # Значит, отсутствие повтора означает новую таблицу, а не
                # продолжение. Вопрос решён объявлением.
                continue
            if объявлено is False:
                # Оснастка сказала: шапка на продолжении не повторяется.
                # Тогда совпадения столбцов достаточно, и шапки исключать
                # нечего — её там нет.
                куда = присоединён.get(конец.адрес)
                if куда is None:
                    собранные.append({
                        "куски": [конец.адрес, начало.адрес],
                        "страницы": [конец.страница, начало.страница],
                        "строки": list(конец.строки),
                        "шапок_в_строках": 0,
                        "исключено": 0,
                    })
                    куда = len(собранные) - 1
                    присоединён[конец.адрес] = куда
                else:
                    собранные[куда]["куски"].append(начало.адрес)
                    собранные[куда]["страницы"].append(начало.страница)
                присоединён[начало.адрес] = куда
                собранные[куда]["строки"].extend(начало.строки)
                continue
            нерешённое.append(ТребуетШаблона(
                где=f"{конец.адрес} → {начало.адрес}",
                что="столбцы совпали, но шапка не повторена: продолжение это "
                    "или новая таблица той же формы — по устройству не видно",
                чего_недостаёт="правило шаблона семейства о границе таблицы "
                               "(шаг 37)"))
            continue

        # Доказуемая сшивка: и столбцы те же, и шапка повторена дословно.
        куда = присоединён.get(конец.адрес)
        if куда is None:
            собранные.append({
                "куски": [конец.адрес, начало.адрес],
                "страницы": [конец.страница, начало.страница],
                "строки": list(конец.строки),
                # Раз шапка повторилась, первая строка начала — тоже шапка.
                # Это стало известно только теперь: до повтора её нечем было
                # отличить от строки данных.
                "шапок_в_строках": 1,
                "исключено": 0,
            })
            куда = len(собранные) - 1
            присоединён[конец.адрес] = куда
        else:
            собранные[куда]["куски"].append(начало.адрес)
            собранные[куда]["страницы"].append(начало.страница)
        присоединён[начало.адрес] = куда

        # Повторённая шапка не считается строкой данных, но и не исчезает:
        # уходит в исключения с адресом и причиной, и карта покрытия её видит.
        собранные[куда]["строки"].extend(начало.строки[1:])
        собранные[куда]["исключено"] += 1
        исключения.append(Исключение(
            начало.строки[0], "запись",
            "повторённая шапка таблицы на следующей странице: не строка данных"))

    # Таблицы, ни к чему не присоединённые, остаются сами собой.
    сшитые = []
    for сборка in собранные:
        сшитые.append(СшитаяТаблица(
            адрес=f"{сборка['куски'][0]}~{сборка['куски'][-1]}",
            страницы=tuple(сборка["страницы"]),
            куски=tuple(сборка["куски"]),
            строки=tuple(сборка["строки"]),
            строк_шапок=сборка["шапок_в_строках"],
            шапок_исключено=сборка["исключено"],
            основание="совпадение столбцов и дословно повторённая шапка"))
    for таблица in таблицы:
        if таблица.адрес in присоединён:
            continue
        сшитые.append(СшитаяТаблица(
            адрес=таблица.адрес, страницы=(таблица.страница,),
            куски=(таблица.адрес,), строки=tuple(таблица.строки),
            строк_шапок=0, шапок_исключено=0,
            основание="одна страница, сшивать нечего"))

    сшитые.sort(key=lambda т: (т.страницы[0], т.адрес))
    return Сшивка(CONTINUATIONS_VERSION, tuple(сшитые), tuple(исключения),
                  tuple(нерешённое))


def исключения_для_карты(сшивка: Сшивка):
    """Повторённые шапки в виде исключений карты покрытия.

    Причина обязательна и уже написана: карта покрытия примет их наравне с
    прочими исключениями, и ни одна строка не исчезнет молча.
    """
    return tuple(сшивка.исключения)


def неуверенности(сшивка: Сшивка) -> tuple[str, ...]:
    """Словесные описания нерешённого — для статуса полноты."""
    return tuple(
        f"{т.где}: {т.что}; недостаёт: {т.чего_недостаёт}"
        for т in сшивка.требуют_шаблона)


