"""Обновление у клиента без потери прошлого.

Шаг 72 плана. Нормативная основа — чертёж v3.0, разделы 18 и 20.

Здесь закрывается то, что было названо нерешённым на шаге 38: **правила
перехода между версиями**. Ядро обновилось — и владелец пакета оснастки должен
знать, что делать, а не гадать.

## Четыре исхода и ни одного пятого

Исход называется словами и говорит, чьё это действие:

* :data:`ГОДЕН` — пакет работает как есть; делать нечего;
* :data:`ПРЕОБРАЗОВАТЬ` — переход механический, есть преобразователь;
  объявление переписывается станком, а не рукой;
* :data:`ПЕРЕПИСАТЬ` — переход смысловой: новая версия языка спрашивает то,
  чего в старом объявлении не было и вывести неоткуда. Преобразователя тут не
  может быть в принципе: он выдумывал бы за владельца;
* :data:`ОТКАТИТЬ` — новое ядро эту версию языка больше не знает, а
  преобразователя нет. Работать нечем: нужно вернуть прежнее ядро.

Умолчания нет. Не попавший ни в один из трёх первых случаев — откат, а не
«попробуем и посмотрим».

## Прошлое переживает обновление

Потеря прошлого считается дефектом — так записано в плане, и здесь это
проверяется счётом, а не обещанием. Прошлое — это три вещи, и все три
неизменяемы по устройству:

* журнал прогонов (шаг 18);
* история действий оператора (шаг 58);
* реестр запусков (шаг 62).

:func:`осмотреть_прошлое` снимает счёт до обновления, :func:`пережило_обновление`
сверяет после. Убыль — отказ :data:`ПРОШЛОЕ_ПОТЕРЯНО`. Отдельно ловится не
убыль, а **подмена**: цепь, которая не продолжает прежнюю вершину, а начинается
заново. Записей при этом может быть и больше — прошлого всё равно нет.

## Откат назад и почему он держится на чтении

Откат обязан быть возможен и не должен стирать сделанное новой версией. Стирать
здесь нечем: журналы дописываются и скреплены цепью, откат ядра их не трогает.
Опасность другая и она не очевидна — **старое ядро может отказаться читать то,
что дописало новое**, и прошлое станет недоступным, ни одной записи не потеряв.

Опыт показал ровно это. У журнала две схемы (шаг 58), и ведут они себя
по-разному:

* **свободная схема** (история оператора) неизвестное поле принимает: цепь
  проверяется, дописывать после чужой записи можно. Откат безопасен;
* **схема прогона закрыта** — неизвестное поле останавливает чтение всего
  журнала отказом ``E_UNKNOWN_FIELD``. Одно поле, добавленное новым ядром,
  делает откат невозможным.

Отсюда правило, и оно жёстче обычного пожелания: **закрытую схему прогона
расширять на месте нельзя никогда**. Новое ядро записывает новое либо свободной
схемой, либо новой версией схемы, которую старое ядро отличит и пропустит как
чужую, а не сочтёт порчей. Правило держит не обещание, а проверка:
:data:`ПОЛЯ_СХЕМЫ_ПРОГОНА_1` закреплён здесь, и сверка с настоящим перечнем
полей журнала стоит в наборе.

:func:`откат_безопасен` проверяет это делом на настоящих файлах клиента: читает
каждый журнал тем ядром, на которое откатываются. Нечитаемое **называется и
остаётся на месте** — станок не выбрасывает того, чего не понял.
"""

