@dataclass(frozen=True, slots=True)
class Решение:
    """Что делать владельцу пакета после обновления ядра."""

    исход: str
    словами: str
    чьё_действие: str
    переход: tuple[str, str] | None = None

    def as_json(self) -> dict:
        свод = {"версия": UPGRADE_VERSION, "исход": self.исход,
                "словами": self.словами, "чьё_действие": self.чьё_действие}
        if self.переход:
            свод["переход"] = list(self.переход)
        return свод


@dataclass
class Преобразователи:
    """Перечень механических переходов между версиями языка оснастки.

    Перечень закрытый: чего в нём нет, того станок сделать не берётся. Пустой
    перечень — честный ответ «преобразователя нет», а не повод попробовать.
    """

    свои: dict = field(default_factory=dict)
    руками: set = field(default_factory=set)

    def завести(self, откуда: str, куда: str, как) -> None:
        self.свои[(откуда, куда)] = как

    def объявить_смысловым(self, откуда: str, куда: str) -> None:
        """Переход есть, но механическим быть не может: решает человек."""
        self.руками.add((откуда, куда))

    def найти(self, откуда: str, куда: str):
        return self.свои.get((откуда, куда))

    def смысловой(self, откуда: str, куда: str) -> bool:
        return (откуда, куда) in self.руками


ПРЕОБРАЗОВАТЕЛИ = Преобразователи()


def что_делать_владельцу_пакета(опись, версия_ядра: str,
                                поддерживаемые=None,
                                преобразователи: Преобразователи | None = None,
                                прежнее_ядро: str | None = None) -> Решение:
    """Единственное место, где рождается ответ «что делать с пакетом».

    Порядок проверок повторяет порядок бед: сперва язык, потом требование к
    ядру. Пакет на незнакомом языке нельзя даже прочитать, и разбираться с его
    требованиями незачем.
    """
    from .package import _старше
    from .tooling import ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ

    знакомые = tuple(поддерживаемые or ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ)
    свои = преобразователи if преобразователи is not None else ПРЕОБРАЗОВАТЕЛИ

    if опись.язык in знакомые:
        if _старше(версия_ядра, опись.наименьшее_ядро):
            return Решение(
                ОТКАТИТЬ,
                f"пакет требует ядра не ниже {опись.наименьшее_ядро}, а это "
                f"ядро {версия_ядра}: язык знаком, а ядро младше нужного",
                "клиент ставит ядро новее либо берёт пакет для этого")
        return Решение(ГОДЕН,
                       f"язык пакета {опись.язык} это ядро знает, требованиям "
                       "к версии ядра пакет отвечает: делать нечего",
                       "никто")

    for новый in знакомые:
        if свои.найти(опись.язык, новый) is not None:
            return Решение(
                ПРЕОБРАЗОВАТЬ,
                f"переход {опись.язык} → {новый} механический: объявление "
                "переписывает станок, прежний пакет остаётся нетронутым",
                "владелец пакета запускает преобразование",
                (опись.язык, новый))

    for новый in знакомые:
        if свои.смысловой(опись.язык, новый):
            return Решение(
                ПЕРЕПИСАТЬ,
                f"переход {опись.язык} → {новый} смысловой: новая версия языка "
                "спрашивает то, чего в старом объявлении нет и вывести "
                "неоткуда. Выдумывать за владельца станок не станет",
                "владелец пакета правит объявление руками",
                (опись.язык, новый))

    прежнее = f" — вернуть ядро {прежнее_ядро}" if прежнее_ядро else ""
    return Решение(
        ОТКАТИТЬ,
        f"язык пакета {опись.язык} это ядро не знает "
        f"({', '.join(sorted(знакомые))}), преобразователя нет: работать "
        f"нечем{прежнее}",
        "клиент откатывает ядро назад",
        None)


def преобразовать_объявление(объявление: dict, откуда: str, куда: str,
                             преобразователи: Преобразователи | None = None
                             ) -> dict:
    """Механическое преобразование объявления. Исходное не трогается.

    Возвращается **новое** объявление. Правило то же, что у исправлений
    оператора (шаг 57): преобразованное хранится отдельно, первичное не
    переписывается никогда — иначе откат ядра оставит владельца без объявления,
    годного прежнему ядру.
    """
    свои = преобразователи if преобразователи is not None else ПРЕОБРАЗОВАТЕЛИ
    как = свои.найти(откуда, куда)
    if как is None:
        raise ValueError(
            f"преобразователя {откуда} → {куда} нет: этот переход механическим "
            "не объявлен, и делать его наугад нельзя")
    новое = как(_глубокая_копия(объявление))
    if новое is объявление:
        raise ValueError(
            "преобразователь вернул то же объявление: преобразование обязано "
            "давать новое, а не править прежнее на месте")
    новое["язык"] = куда
    return новое


def _глубокая_копия(значение):
    if isinstance(значение, dict):
        return {к: _глубокая_копия(з) for к, з in значение.items()}
    if isinstance(значение, list):
        return [_глубокая_копия(з) for з in значение]
    return значение


