@dataclass(frozen=True, slots=True)
class Прошлое:
    """Счёт прошлого на один миг: сколько записей и какова вершина цепи."""

    записей: int
    вершины: tuple[tuple[str, str], ...]
    где: str = ""

    def as_json(self) -> dict:
        return {"версия": UPGRADE_VERSION, "записей": self.записей,
                "вершины": {имя: вершина for имя, вершина in self.вершины}}


def _схема_для(путь: Path):
    """История оператора ведётся свободной схемой, прогоны — закрытой."""
    имя = путь.name.lower()
    if имя.startswith(("istoriya", "история", "istor")):
        return journal.нормализовать_событие
    return None


def осмотреть_прошлое(каталог) -> Прошлое:
    """Счёт прошлого: сколько записей лежит и какая у каждой цепи вершина.

    Считается по строкам, а не по разбору: осмотр должен работать и тогда,
    когда часть журналов этому ядру непонятна, — иначе перед откатом он сам бы
    и падал.
    """
    место = Path(каталог)
    всего = 0
    вершины: list[tuple[str, str]] = []
    for путь in sorted(место.rglob("*.jsonl")):
        строки = [с for с in путь.read_text(encoding="utf-8",
                                            errors="replace").splitlines() if с]
        всего += len(строки)
        try:
            вершина = journal.current_head(путь)
        except Exception:  # pragma: no cover — вершина читается по строке
            вершина = _вершина_по_строке(строки)
        вершины.append((путь.name, вершина))
    return Прошлое(всего, tuple(вершины), str(место))


def _вершина_по_строке(строки) -> str:
    import json as _json

    for строка in reversed(строки):
        try:
            return str(_json.loads(строка).get("hash", ""))
        except Exception:
            continue
    return ""


@dataclass(frozen=True, slots=True)
class Беда:
    код: str
    словами: str

    def as_json(self) -> dict:
        return {"код": self.код, "словами": self.словами}


def пережило_обновление(до: Прошлое, после: Прошлое) -> tuple[Беда, ...]:
    """Сверяет прошлое до и после обновления. Убыль — дефект, а не мелочь.

    Ловятся две разные беды. Убыль записей — прошлое стёрли. Пропавшая или
    начавшаяся заново цепь — прошлое подменили: записей может стать и больше,
    а прежнего в них нет.
    """
    беды: list[Беда] = []
    if после.записей < до.записей:
        беды.append(Беда(
            ПРОШЛОЕ_ПОТЕРЯНО,
            f"записей было {до.записей}, стало {после.записей}: обновление "
            f"съело {до.записей - после.записей}. Прошлое неизменяемо, и "
            "убыли в нём быть не может"))

    было = dict(до.вершины)
    стало = dict(после.вершины)
    for имя in было:
        if имя not in стало:
            беды.append(Беда(
                ПРОШЛОЕ_ПОТЕРЯНО,
                f"журнал {имя} после обновления исчез"))

    for имя, вершина in было.items():
        если_есть = стало.get(имя)
        if если_есть is not None and если_есть == вершина:
            continue
        if если_есть is None:
            continue
        if not _цепь_продолжена(имя, вершина, после):
            беды.append(Беда(
                ПРОШЛОЕ_ПОДМЕНЕНО,
                f"журнал {имя} после обновления не продолжает прежнюю "
                "вершину, а начинается заново: записи могли и прибавиться, "
                "прошлого в них нет"))
    return tuple(беды)


def _цепь_продолжена(имя: str, вершина: str, после: Прошлое) -> bool:
    """Цепь продолжена, если прежняя вершина всё ещё лежит в журнале.

    По счётчикам этого не узнать: журнал, начатый заново, бывает и длиннее
    прежнего. Судит здесь только сама цепь — прежняя вершина либо есть среди
    записей, либо прошлого нет.
    """
    if not вершина:
        return True
    if not после.где:
        return True
    путь = Path(после.где) / имя
    if not путь.is_file():
        return False
    with путь.open("r", encoding="utf-8", errors="replace") as файл:
        return any(вершина in строка for строка in файл)


