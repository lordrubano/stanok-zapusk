@dataclass(frozen=True, slots=True)
class Откат:
    можно: bool
    прочитано: int
    нечитаемое: tuple[tuple[str, str], ...]

    def as_json(self) -> dict:
        return {"версия": UPGRADE_VERSION, "можно_откатывать": self.можно,
                "журналов_прочитано": self.прочитано,
                "нечитаемое": [{"журнал": имя, "почему": почему}
                               for имя, почему in self.нечитаемое]}


def откат_безопасен(каталог) -> Откат:
    """Прочтёт ли это ядро всё, что лежит у клиента.

    Проверка делом: каждый журнал читается тем самым ядром, на которое
    откатываются. Нечитаемое называется и **остаётся на месте**: станок не
    выбрасывает того, чего не понял, — иначе откат сам стал бы потерей
    прошлого, которую он призван предотвратить.
    """
    место = Path(каталог)
    прочитано = 0
    нечитаемое: list[tuple[str, str]] = []
    for путь in sorted(место.rglob("*.jsonl")):
        try:
            journal.verify_journal(путь, схема=_схема_для(путь))
            прочитано += 1
        except Exception as беда:
            нечитаемое.append((путь.name, str(беда)))
    return Откат(not нечитаемое, прочитано, tuple(нечитаемое))


def свод(каталог, до: Прошлое | None = None) -> dict:
    """Один ответ на вопрос «можно ли обновляться и можно ли откатываться»."""
    сейчас = осмотреть_прошлое(каталог)
    откат = откат_безопасен(каталог)
    свод = {"версия": UPGRADE_VERSION, "прошлое": сейчас.as_json(),
            "откат": откат.as_json()}
    if до is not None:
        беды = пережило_обновление(до, сейчас)
        свод["прошлое_цело"] = not беды
        свод["беды"] = [б.as_json() for б in беды]
    return свод


