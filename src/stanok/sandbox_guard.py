# -*- coding: utf-8 -*-
"""Запреты, которые устанавливаются внутри обработчика до его работы.

Часть шага 24. Ставится в дочернем процессе **первым делом**, до того как будет
загружена хоть одна библиотека разбора: запрет, поставленный после, ничего не
стоит — библиотека успеет открыть соединение при загрузке.

Главный запрет — сеть. Чертёж v3.0, раздел 14.1: «отсутствие сетевого доступа в
локальном маршруте». Проверять это отсутствием надобности нельзя: надобность
появляется сама, без спроса. Разборщик XML тянет внешнюю сущность, шрифт
подтягивается по ссылке, библиотека проверяет обновления. Поэтому попытка выйти
в сеть обязана быть **отвергнута**, а не просто не случиться.

Граница честности: запрет ставится внутри процесса и держит код, который
пользуется обычными средствами языка. Код, который сознательно обходит их через
системные вызовы, он не удержит — это работа для песочницы уровня системы.
Здесь важно другое: угроза в станке — недоверенные **данные**, а не свой код, и
именно данные заставляют доверенную библиотеку полезть в сеть.
"""

from __future__ import annotations


class СетьЗапрещена(RuntimeError):
    """Обработчик попытался выйти в сеть на локальном маршруте."""

    код = "E_SANDBOX_NETWORK"


def запретить_сеть():
    """Отбирает у процесса все обычные способы открыть соединение.

    Затыкаются оба уровня: модуль ``socket`` и лежащий под ним ``_socket``.
    Одного верхнего мало — ``import _socket`` в обход даёт целый рабочий сокет.
    """

    import socket as _высокий
    import _socket as _низкий

    # Готовые обёртки загружаются ДО подмены. Порядок здесь важен: http.client
    # при загрузке трогает средства сокетов, и подмена, сделанная раньше,
    # роняет саму загрузку — запрет получался бы не запретом, а поломкой.
    try:
        import http.client as _http
    except ImportError:
        _http = None
    try:
        import urllib.request as _urllib
    except ImportError:
        _urllib = None

    def отказать(*_доводы, **_именованные):
        raise СетьЗапрещена(
            "выход в сеть запрещён: локальный маршрут работает без сети")

    for модуль in (_низкий, _высокий):
        for имя in (
            "socket",
            "socketpair",
            "create_connection",
            "create_server",
            "getaddrinfo",
            "gethostbyname",
            "gethostbyname_ex",
            "gethostbyaddr",
            "getnameinfo",
        ):
            if hasattr(модуль, имя):
                setattr(модуль, имя, отказать)

    # Обёртки держат ссылку на настоящий socket, взятую при загрузке, поэтому
    # подмены имени им мало — их закрываем отдельно.
    if _http is not None:
        _http.HTTPConnection.connect = отказать
        _http.HTTPSConnection.connect = отказать
    if _urllib is not None:
        _urllib.urlopen = отказать
        _urllib.OpenerDirector.open = отказать


def запретить_запуск_процессов():
    """Отбирает у обработчика право заводить новые процессы.

    Чертёж: обработка идёт «без лишних прав». Разбор документа не нуждается в
    запуске сторонних программ, а нужда в этом — верный признак того, что
    разбором дело не ограничилось.

    Со стороны родителя то же самое держит задание операционной системы: даже
    обойдя этот запрет, обработчик упрётся в предел числа процессов задания.
    """

    import os
    import subprocess

    def отказать(*_доводы, **_именованные):
        raise PermissionError(
            "запуск сторонних процессов запрещён: обработчик работает "
            "без лишних прав")

    subprocess.Popen = отказать
    subprocess.run = отказать
    for имя in ("system", "popen", "execv", "execve", "execvp", "spawnv", "spawnve"):
        if hasattr(os, имя):
            setattr(os, имя, отказать)


__all__ = ["СетьЗапрещена", "запретить_запуск_процессов", "запретить_сеть"]
