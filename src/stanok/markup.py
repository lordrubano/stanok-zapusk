# -*- coding: utf-8 -*-
"""Разметка эталона: что записал человек и как это читает станок.

Шаг 48 плана. Нормативная основа — чертёж v3.0, раздел 16.3 (критические поля
размечаются двумя независимыми людьми; расхождения разрешает третий; хранится
происхождение каждого эталонного значения; неразрешённое разногласие не
превращается в эталон).

**Слабая разметка обращает все метрики в фикцию.** Доля ошибок, измеренная по
неверному эталону, — это не доля ошибок, а доля расхождений с чужой ошибкой, и
отличить одно от другого потом уже нельзя. Поэтому здесь строго не там, где
удобно, а там, где человек может ошибиться незаметно.

**Размечающий записывает то, что видит, и не додумывает.** Главное следствие
для устройства: **сомнение — это значение**, а не пустое место. Пустая клетка
без пометки сомнения читается как беда разметки, а не как «ничего особенного»:
иначе пропуск и неуверенность стали бы неразличимы.

**Двусмысленная дата разрешается разметкой, а не станком.** У первого семейства
такие даты — почти треть записей. Поэтому день, месяц и год записываются
**раздельно**: человек, видящий весь документ, знает, что из двух чисел день, а
станок, видящий одну ячейку, не знает. И знать, откуда человек это взял, тоже
надо: если обе части не больше двенадцати, размечающий обязан назвать, **чем**
он разрешил двусмысленность. Не назвал — беда разметки, а не эталон.

**Формат — таблица с разделителем «точка с запятой» в UTF-8.** Человек
открывает её в том, что у него есть, и сохраняет как есть; станок читает без
ручного перевода. Метка порядка байтов допускается: её ставит Excel, и требовать
от человека её отсутствия значило бы требовать смены орудия.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass, field


MARKUP_VERSION = "markup/1"

# Колонки бланка разметки. Порядок задан: человек заполняет слева направо, и
# перестановка колонок — беда, а не мелочь.
КОЛОНКИ = (
    "документ", "страница", "операция",
    "день", "месяц", "год", "чем_разрешена_дата",
    "сумма_как_записано", "сторона",
    "сомнение", "нечитаемо", "примечание",
)

ОБЯЗАТЕЛЬНЫЕ = ("документ", "страница", "операция")
СТОРОНЫ = ("списание", "поступление")

# Критические поля этого бланка: их размечают двое независимо (раздел 16.3).
КРИТИЧЕСКИЕ = ("день", "месяц", "год", "сумма_как_записано", "сторона")

KNOWN_LIMITATIONS = (
    "Бланк рассчитан на выписку по счёту: дата, сумма, сторона. Семейству с "
    "иным составом критических полей нужен свой бланк, и это работа, а не "
    "настройка.",
    "Совпадение двух разметок считается по написанному дословно. Два человека, "
    "записавшие одну сумму по-разному — с пробелом и без, — дадут расхождение, "
    "и разрешать его будет третий. Это дороже, но честнее молчаливого "
    "приведения: приведение решает за человека.",
    "Квалификация меряется долей совпадений с эталонной разметкой. Какая доля "
    "достаточна — решение владельца, а не измерение: здесь оно только "
    "считается.",
    "Ни одной настоящей разметки не сделано: размечающего пока нет. Правила "
    "проверены на построенных образцах.",
)


class РазметкаНегодна(ValueError):
    """Бланк разметки не читается или заполнен так, что эталоном быть не может."""

    код = "E_MARKUP_INVALID"


@dataclass(frozen=True, slots=True)
class Строка:
    """Одна размеченная операция."""

    документ: str
    страница: str
    операция: str
    день: str = ""
    месяц: str = ""
    год: str = ""
    чем_разрешена_дата: str = ""
    сумма_как_записано: str = ""
    сторона: str = ""
    сомнение: str = ""
    нечитаемо: str = ""
    примечание: str = ""
    место: int = 0

    @property
    def ключ(self) -> str:
        """Чем одна размеченная операция опознаётся в другой разметке."""
        return f"{self.документ}|{self.страница}|{self.операция}"

    @property
    def под_сомнением(self) -> bool:
        return bool(self.сомнение.strip() or self.нечитаемо.strip())

    @property
    def дата_двусмысленна(self) -> bool:
        """Обе первые части не больше двенадцати — читается двумя способами."""
        return (_целое(self.день) is not None and _целое(self.месяц) is not None
                and _целое(self.день) <= 12 and _целое(self.месяц) <= 12)

    def значения(self) -> dict:
        return {имя: getattr(self, имя) for имя in КРИТИЧЕСКИЕ}

    def as_json(self) -> dict:
        свой = {имя: getattr(self, имя) for имя in КОЛОНКИ}
        свой["под_сомнением"] = self.под_сомнением
        return свой


def _целое(значение):
    текст = str(значение or "").strip()
    if not текст.isdigit():
        return None
    return int(текст)


def _беды_строки(строка: Строка) -> tuple:
    """Почему строка разметки не может стать эталоном."""
    беды = []
    где = f"строка {строка.место}"

    for имя in ОБЯЗАТЕЛЬНЫЕ:
        if not str(getattr(строка, имя) or "").strip():
            беды.append(f"{где}: не заполнено «{имя}» — без него операцию не "
                        "найти в документе")

    if строка.нечитаемо.strip():
        # Нечитаемое место — законный исход разметки, и требовать при нём
        # значений нельзя: человек честно сказал, что не видит.
        return tuple(беды)

    день, месяц, год = _целое(строка.день), _целое(строка.месяц), _целое(строка.год)
    if строка.под_сомнением:
        # Под сомнением значения могут быть неполными: сомнение и есть ответ.
        pass
    else:
        if день is None or not (1 <= день <= 31):
            беды.append(f"{где}: день не записан числом от 1 до 31. Если день "
                        "не виден — заполните «сомнение», а не оставляйте пусто")
        if месяц is None or not (1 <= месяц <= 12):
            беды.append(f"{где}: месяц не записан числом от 1 до 12")
        if год is None or not (1900 <= год <= 2200):
            беды.append(f"{где}: год не записан четырьмя цифрами")
        if not строка.сумма_как_записано.strip():
            беды.append(f"{где}: сумма не выписана. Выписывается дословно, как "
                        "напечатано в документе")
        if строка.сторона.strip() not in СТОРОНЫ:
            беды.append(f"{где}: сторона должна быть одной из: "
                        + ", ".join(СТОРОНЫ))

    # Главное правило бланка: двусмысленную дату разрешает человек и говорит,
    # чем именно. Не сказал — это догадка, а догадка эталоном не бывает.
    #
    # Помеченное сомнением сюда не попадает: сомнение и есть ответ. Требовать
    # объяснения там, где человек честно сказал «не вижу», значило бы толкать
    # его выдумать объяснение.
    if (строка.дата_двусмысленна and not строка.чем_разрешена_дата.strip()
            and not строка.под_сомнением):
        беды.append(
            f"{где}: обе части даты не больше двенадцати — запись читается и "
            "как день с месяцем, и как месяц с днём. Напишите в «чем разрешена "
            "дата», откуда видно, что это именно день: по порядку строк, по "
            "периоду выписки, по соседней операции. Если ниоткуда не видно — "
            "заполните «сомнение»")

    if строка.чем_разрешена_дата.strip() and not строка.дата_двусмысленна:
        беды.append(f"{где}: дата однозначна, а «чем разрешена дата» заполнено. "
                    "Это поле только для случая, когда обе части не больше "
                    "двенадцати")
    return tuple(беды)


def прочитать(данные, имя_бланка: str = "бланк") -> tuple:
    """Читает бланк разметки. Возвращает строки и беды.

    Строгость намеренная: бланк с лишней или переставленной колонкой не
    читается вовсе. Человек, переставивший колонки, почти наверняка заполнял их
    не туда, и прочитать такое «как получится» значило бы принять испорченный
    эталон за годный.
    """
    текст = данные.decode("utf-8-sig") if isinstance(данные, bytes) else данные
    текст = текст.lstrip("﻿")
    читатель = csv.reader(io.StringIO(текст, newline=""), delimiter=";")
    ряды = [ряд for ряд in читатель if ряд and any(з.strip() for з in ряд)]
    if not ряды:
        raise РазметкаНегодна(f"{имя_бланка}: пусто")

    заголовок = [з.strip().lstrip("﻿") for з in ряды[0]]
    if tuple(заголовок) != КОЛОНКИ:
        raise РазметкаНегодна(
            f"{имя_бланка}: заголовок не тот. Ожидается ровно и в этом порядке: "
            + "; ".join(КОЛОНКИ))

    строки, беды = [], []
    for место, ряд in enumerate(ряды[1:], start=2):
        if len(ряд) != len(КОЛОНКИ):
            беды.append(f"строка {место}: колонок {len(ряд)}, ожидается "
                        f"{len(КОЛОНКИ)}")
            continue
        своя = Строка(*[з.strip() for з in ряд], место=место)
        строки.append(своя)
        беды.extend(_беды_строки(своя))

    ключи = [с.ключ for с in строки]
    повторы = sorted({к for к in ключи if ключи.count(к) > 1})
    for ключ in повторы:
        беды.append(f"одна и та же операция размечена дважды: {ключ}")
    return tuple(строки), tuple(беды)


# --------------------------------------------- две независимые разметки


@dataclass(frozen=True, slots=True)
class Расхождение:
    """Где двое разметчиков сказали разное."""

    ключ: str
    поле: str
    первый: str
    второй: str

    def as_json(self) -> dict:
        return {"операция": self.ключ, "поле": self.поле,
                "первый": self.первый, "второй": self.второй}


def сверить(первая, вторая) -> tuple:
    """Сличает две независимые разметки по критическим полям.

    Возвращает расхождения и операции, размеченные только одним. И то и другое
    — работа для третьего проверяющего, а не повод выбрать любую из двух.
    """
    по_ключу_1 = {с.ключ: с for с in первая}
    по_ключу_2 = {с.ключ: с for с in вторая}
    расхождения = []
    for ключ in sorted(set(по_ключу_1) & set(по_ключу_2)):
        а, б = по_ключу_1[ключ], по_ключу_2[ключ]
        for поле in КРИТИЧЕСКИЕ:
            если_а, если_б = getattr(а, поле).strip(), getattr(б, поле).strip()
            if если_а != если_б:
                расхождения.append(Расхождение(ключ, поле, если_а, если_б))
        # Сомнение одного из двоих — тоже расхождение: один видел неясность,
        # другой нет, и решить это должен третий.
        if а.под_сомнением != б.под_сомнением:
            расхождения.append(Расхождение(
                ключ, "сомнение", а.сомнение or а.нечитаемо or "нет",
                б.сомнение or б.нечитаемо or "нет"))
    только_у_первого = tuple(sorted(set(по_ключу_1) - set(по_ключу_2)))
    только_у_второго = tuple(sorted(set(по_ключу_2) - set(по_ключу_1)))
    return tuple(расхождения), только_у_первого, только_у_второго


def эталон(первая, вторая, разрешения=None) -> tuple:
    """Эталон из двух разметок. Неразрешённое разногласие эталоном не станет.

    ``разрешения`` — решения третьего проверяющего вида
    ``{(ключ, поле): значение}``. Раздел 16.3 прямо запрещает превращать
    неразрешённое разногласие в эталон, и обойти это здесь нечем: операция с
    неразрешённым расхождением в эталон не попадает вовсе.
    """
    разрешения = разрешения or {}
    расхождения, только_первый, только_второй = сверить(первая, вторая)
    спорные: dict[str, list] = {}
    for р in расхождения:
        спорные.setdefault(р.ключ, []).append(р)

    по_ключу_1 = {с.ключ: с for с in первая}
    по_ключу_2 = {с.ключ: с for с in вторая}
    принятые, отвергнутые = [], []
    for ключ in sorted(set(по_ключу_1) & set(по_ключу_2)):
        свои_споры = спорные.get(ключ, [])
        неразрешённые = [р for р in свои_споры
                         if (ключ, р.поле) not in разрешения]
        if неразрешённые:
            отвергнутые.append({
                "операция": ключ,
                "почему": "неразрешённое разногласие: "
                          + ", ".join(sorted(р.поле for р in неразрешённые))})
            continue
        значения = dict(по_ключу_1[ключ].значения())
        for р in свои_споры:
            значения[р.поле] = разрешения[(ключ, р.поле)]
        принятые.append({
            "операция": ключ,
            "значения": значения,
            # Раздел 16.3: хранится происхождение каждого эталонного значения.
            "происхождение": ("согласие двух разметок" if not свои_споры
                              else "решение третьего проверяющего по полям: "
                                   + ", ".join(sorted(р.поле for р in свои_споры))),
        })
    for ключ in только_первый + только_второй:
        отвергнутые.append({"операция": ключ,
                            "почему": "размечена только одним из двоих"})
    return tuple(принятые), tuple(отвергнутые)


# ------------------------------------------- квалификация разметчика


def проверить_квалификацию(эталонная, ученическая) -> dict:
    """Считает, насколько разметка ученика совпала с эталонной.

    Порог достаточности здесь не назначается: какая доля довольна — решение
    владельца. Считается только то, что можно посчитать, и перечисляются
    несовпадения, чтобы человека было чему учить.
    """
    по_эталону = {с.ключ: с for с in эталонная}
    по_ученику = {с.ключ: с for с in ученическая}
    общие = sorted(set(по_эталону) & set(по_ученику))
    сверено = совпало = 0
    промахи = []
    for ключ in общие:
        для_эталона, для_ученика = по_эталону[ключ], по_ученику[ключ]
        for поле in КРИТИЧЕСКИЕ:
            сверено += 1
            если_э = getattr(для_эталона, поле).strip()
            если_у = getattr(для_ученика, поле).strip()
            if если_э == если_у:
                совпало += 1
            else:
                промахи.append({"операция": ключ, "поле": поле,
                                "эталон": если_э, "ученик": если_у})
    пропущено = sorted(set(по_эталону) - set(по_ученику))
    лишнее = sorted(set(по_ученику) - set(по_эталону))
    return {
        "версия": MARKUP_VERSION,
        "операций_в_эталоне": len(по_эталону),
        "сверено_значений": сверено,
        "совпало": совпало,
        "доля_совпадений": (f"{совпало / сверено:.4f}" if сверено else None),
        "пропущено_операций": пропущено,
        "лишних_операций": лишнее,
        "промахи": промахи,
    }


def бланк() -> str:
    """Пустой бланк разметки: то, что человек открывает и заполняет."""
    return ";".join(КОЛОНКИ) + "\n"


def свод(строки, беды) -> dict:
    строки = tuple(строки)
    return {
        "версия": MARKUP_VERSION,
        "строк": len(строки),
        "под_сомнением": sum(1 for с in строки if с.под_сомнением),
        "нечитаемых": sum(1 for с in строки if с.нечитаемо.strip()),
        "двусмысленных_дат": sum(1 for с in строки if с.дата_двусмысленна),
        "бед": len(беды),
        "беды": list(беды),
        "годна_как_эталон": not беды,
    }


