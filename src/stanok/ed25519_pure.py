# -*- coding: utf-8 -*-
"""Проверка подписи Ed25519 без единой сторонней библиотеки.

Шаг 74. Это **только проверка**, и это нарочно: тайный ключ живёт на сборочной
машине и туда, куда уезжает изделие, не попадает никогда. Подписывать станок у
клиента не должен и не может.

## Почему это здесь, а не взято готовым

Библиотека подписей двоичная, собрана под свою систему и потому в изделие не
укладывается (шаг 71). Оттого её у клиента может не быть. Но проверка авторства
— **товарное свойство**: клиент платит за возможность убедиться, что изделие
пришло от нас. Свойство, доступное не всем покупателям, товарным не является.

Проверка Ed25519 — счёт по описанным правилам (RFC 8032), без всякой снасти:
целые числа и SHA-512, оба есть в самом языке. Кода на страницу, и он весь
здесь.

## Чем это проверено

Своя криптография — дело опасное, и проверять её рассуждением нельзя. Она
сверена **с образцовой библиотекой на множестве настоящих подписей**: те же
ключи, те же сообщения, тот же ответ — и, что важнее, тот же **отказ** на
испорченной подписи, чужом ключе, изменённом сообщении. Сверка стоит в наборе
проверок и идёт при каждом прогоне на машине, где образцовая библиотека есть.

Здесь нет ни одного действия с тайным ключом, а значит нет и того, ради чего в
такой код обычно смотрят злым глазом: утечь отсюда нечему. Постоянство времени
работы тоже не требуется — проверяется общедоступная подпись общедоступным
ключом.
"""

from __future__ import annotations

import hashlib

# Кривая Ed25519 по RFC 8032. Числа не выдуманы: они заданы описанием.
P = 2 ** 255 - 19
L = 2 ** 252 + 27742317777372353535851937790883648493
D = -121665 * pow(121666, P - 2, P) % P
I = pow(2, (P - 1) // 4, P)  # noqa: E741 — имя из описания


class ПодписьНеСошлась(ValueError):
    """Подпись не сошлась. Отдельная порода: это не поломка, а ответ."""


def _обратное(значение: int) -> int:
    return pow(значение, P - 2, P)


def _восстановить_x(y: int, знак: int) -> int | None:
    """Восстанавливает x точки по y. Отсутствие корня — не точка кривой."""
    числитель = (y * y - 1) % P
    знаменатель = (D * y * y + 1) % P
    x = pow(числитель * _обратное(знаменатель) % P, (P + 3) // 8, P)
    if (x * x - числитель * _обратное(знаменатель)) % P != 0:
        x = x * I % P
    if (x * x - числитель * _обратное(знаменатель)) % P != 0:
        return None
    if x % 2 != знак:
        x = P - x
    return x


def _сложить(первая, вторая):
    """Сложение точек в расширенных координатах: без деления на каждом шаге."""
    x1, y1, z1, t1 = первая
    x2, y2, z2, t2 = вторая
    a = (y1 - x1) * (y2 - x2) % P
    b = (y1 + x1) * (y2 + x2) % P
    c = t1 * 2 * D * t2 % P
    d = z1 * 2 * z2 % P
    e, f, g, h = b - a, d - c, d + c, b + a
    return (e * f % P, g * h % P, f * g % P, e * h % P)


def _умножить(точка, множитель: int):
    итог = (0, 1, 1, 0)
    while множитель > 0:
        if множитель & 1:
            итог = _сложить(итог, точка)
        точка = _сложить(точка, точка)
        множитель >>= 1
    return итог


def _в_плоские(точка) -> tuple[int, int]:
    x, y, z, _ = точка
    обратное = _обратное(z)
    return x * обратное % P, y * обратное % P


_BY = 4 * _обратное(5) % P
_BX = _восстановить_x(_BY, 0)
ОСНОВАНИЕ = (_BX, _BY, 1, _BX * _BY % P)


def _точка_из_байтов(сжатая: bytes):
    """Разжимает точку из 32 байт. Негодные байты — не точка, а отказ."""
    if len(сжатая) != 32:
        return None
    число = int.from_bytes(сжатая, "little")
    знак = число >> 255
    y = число & ((1 << 255) - 1)
    if y >= P:
        return None
    x = _восстановить_x(y, знак)
    if x is None:
        return None
    return (x, y, 1, x * y % P)


def проверить(сообщение: bytes, подпись: bytes, ключ: bytes) -> bool:
    """Сходится ли подпись с сообщением и открытым ключом.

    Возвращает да или нет. Исключений на негодных входных данных не бросает:
    негодная подпись — это ответ «нет», а не поломка станка.
    """
    if len(подпись) != 64 or len(ключ) != 32:
        return False

    точка_ключа = _точка_из_байтов(ключ)
    if точка_ключа is None:
        return False
    точка_r = _точка_из_байтов(подпись[:32])
    if точка_r is None:
        return False

    s = int.from_bytes(подпись[32:], "little")
    if s >= L:
        # Подпись с завышенным s описанием запрещена: иначе одну и ту же
        # подпись можно записать несколькими способами, и «та же подпись»
        # перестаёт значить то же самое.
        return False

    слепок = hashlib.sha512(подпись[:32] + ключ + сообщение).digest()
    k = int.from_bytes(слепок, "little") % L

    слева = _умножить(ОСНОВАНИЕ, s)
    справа = _сложить(точка_r, _умножить(точка_ключа, k))
    return _в_плоские(слева) == _в_плоские(справа)


__all__ = ["ПодписьНеСошлась", "проверить"]
