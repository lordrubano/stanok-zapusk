def _имя(узел) -> str:
    """Местное имя узла без пространства имён.

    У CAMT пространство имён несёт номер версии сообщения, и привязка к нему
    сломала бы разбор на следующей версии — при том что состав нужных нам
    полей от версии к версии не меняется.
    """
    метка = узел.tag
    return метка.rsplit("}", 1)[-1] if "}" in метка else метка


def _найти(узел, *путь):
    """Первый потомок по цепочке местных имён либо None."""
    текущий = узел
    for шаг in путь:
        следующий = None
        for ребёнок in текущий:
            if _имя(ребёнок) == шаг:
                следующий = ребёнок
                break
        if следующий is None:
            return None
        текущий = следующий
    return текущий


def _текст(узел, *путь) -> str | None:
    найден = _найти(узел, *путь) if путь else узел
    if найден is None:
        return None
    значение = найден.text
    return значение if значение is None else значение.strip()


def _все(узел, имя: str):
    for ребёнок in узел.iter():
        if _имя(ребёнок) == имя:
            yield ребёнок


def _свойства(пары) -> tuple[tuple[str, object], ...]:
    """Оставляет только заполненное: пустое поле — не то же, что поле со смыслом."""
    return tuple((ключ, значение) for ключ, значение in пары if значение not in (None, ""))


# ------------------------------------------------------------- CAMT.053


class ВыпискаCAMT:
    """ISO 20022 camt.053: выписка по счёту в XML.

    Разбирается через общий безопасный разбор XML: объявление типа документа и
    объявление сущности отвергают файл целиком. Это одна из причин своего
    разбора — сторонняя библиотека разбирала бы XML сама и мимо запрета.
    """

    имя = "камт-053"
    версия = "1"
    форматы = frozenset({"camt", "camt053", "xml"})

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        document_id = getattr(конверт, "document_id", "") or ""
        корень = разобрать(данные, "camt.053")
        выписки = list(_все(корень, "Stmt"))
        if not выписки:
            raise ValueError("в сообщении нет ни одной выписки Stmt")

        for номер, выписка in enumerate(выписки, start=1):
            основа = f"выписка[{номер}]"
            yield self._заголовок(document_id, выписка, номер, основа)
            for место, остаток in enumerate(_все(выписка, "Bal"), start=1):
                yield self._остаток(document_id, остаток, номер,
                                    f"{основа}/остаток[{место}]")
            for место, проводка in enumerate(_все(выписка, "Ntry"), start=1):
                yield self._проводка(document_id, проводка, номер,
                                     f"{основа}/проводка[{место}]")

    def _заголовок(self, document_id, выписка, номер, путь) -> SourceObject:
        счёт = _найти(выписка, "Acct")
        свойства = _свойства([
            ("вид", "заголовок выписки"),
            ("идентификатор", _текст(выписка, "Id")),
            ("номер_страницы", _текст(выписка, "LglSeqNb")),
            ("создано", _текст(выписка, "CreDtTm")),
            ("счёт_iban", _текст(счёт, "Id", "IBAN") if счёт is not None else None),
            ("счёт_прочее",
             _текст(счёт, "Id", "Othr", "Id") if счёт is not None else None),
            ("валюта_счёта", _текст(счёт, "Ccy") if счёт is not None else None),
        ])
        return SourceObject(
            document_id=document_id, страница=номер,
            система_координат="сообщение camt.053",
            структурный_путь=путь, сырой_текст=None,
            полигон=None, свойства=свойства)

    def _остаток(self, document_id, остаток, номер, путь) -> SourceObject:
        сумма = _найти(остаток, "Amt")
        вид = _найти(остаток, "Tp")
        свойства = _свойства([
            ("вид", "остаток"),
            ("код_остатка", _текст(вид, "CdOrPrtry", "Cd") if вид is not None else None),
            # Сумма — строка ровно как записана. Ни округления, ни разделителей.
            ("сумма", _текст(сумма) if сумма is not None else None),
            ("валюта", сумма.get("Ccy") if сумма is not None else None),
            ("признак", _текст(остаток, "CdtDbtInd")),
            ("дата", _текст(остаток, "Dt", "Dt")),
        ])
        return SourceObject(
            document_id=document_id, страница=номер,
            система_координат="сообщение camt.053",
            структурный_путь=путь,
            сырой_текст=_текст(сумма) if сумма is not None else None,
            полигон=None, свойства=свойства)

    def _проводка(self, document_id, проводка, номер, путь) -> SourceObject:
        сумма = _найти(проводка, "Amt")
        свойства = _свойства([
            ("вид", "проводка"),
            ("сумма", _текст(сумма) if сумма is not None else None),
            ("валюта", сумма.get("Ccy") if сумма is not None else None),
            ("признак", _текст(проводка, "CdtDbtInd")),
            ("состояние", _текст(проводка, "Sts")),
            ("дата_проводки", _текст(проводка, "BookgDt", "Dt")),
            ("дата_валютирования", _текст(проводка, "ValDt", "Dt")),
            ("ссылка", _текст(проводка, "NtryRef")),
            ("ссылка_банка", _текст(проводка, "AcctSvcrRef")),
        ])
        return SourceObject(
            document_id=document_id, страница=номер,
            система_координат="сообщение camt.053",
            структурный_путь=путь,
            сырой_текст=_текст(сумма) if сумма is not None else None,
            полигон=None, свойства=свойства)


# ----------------------------------------------------------------- MT940

_ПОЛЕ = re.compile(r"^:(\d{2}[A-Z]?):(.*)$")


class ВыпискаMT940:
    """SWIFT MT940: выписка полями с двоеточиями.

    Отдаётся построчная структура сообщения: поле, его порядковый номер и
    содержимое как записано, включая продолжения. Разбор поля :61: на подполя
    здесь не делается — см. ``KNOWN_LIMITATIONS``.
    """

    имя = "мт940"
    версия = "1"
    форматы = frozenset({"mt940", "sta", "940"})
    кодировки = ("utf-8", "ascii")

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        document_id = getattr(конверт, "document_id", "") or ""
        текст = self._раскодировать(данные)
        собранные = self._поля(текст)
        if not собранные:
            raise ValueError("в сообщении нет ни одного поля MT940")

        сообщение = 1
        for место, (метка, содержимое, строка_с) in enumerate(собранные, start=1):
            # Метка :20: начинает новое сообщение; в файле их бывает несколько.
            if метка == "20" and место > 1:
                сообщение += 1
            yield SourceObject(
                document_id=document_id, страница=сообщение,
                система_координат="сообщение mt940",
                структурный_путь=f"сообщение[{сообщение}]/поле[:{метка}:][{место}]",
                сырой_текст=содержимое,
                полигон=None,
                свойства=_свойства([
                    ("поле", метка),
                    ("строка_файла", строка_с),
                    ("продолжений", содержимое.count("\n")),
                ]))

    def _поля(self, текст: str):
        собранные: list[list] = []
        for номер, строка in enumerate(текст.splitlines(), start=1):
            совпало = _ПОЛЕ.match(строка)
            if совпало:
                собранные.append([совпало.group(1), совпало.group(2), номер])
            elif собранные and строка.strip() not in ("", "-"):
                # Продолжение предыдущего поля: перевод строки сохраняем, он
                # часть записанного и по нему считаются продолжения.
                собранные[-1][1] += "\n" + строка
        return [(метка, содержимое, строка) for метка, содержимое, строка in собранные]

    def _раскодировать(self, данные: bytes) -> str:
        for кодировка in self.кодировки:
            try:
                return данные.decode(кодировка)
            except UnicodeDecodeError:
                continue
        raise ValueError(
            "сообщение не прочитано ни в одной из объявленных кодировок: "
            + ", ".join(self.кодировки))


# -------------------------------------------------------------- OFX/QFX

_OFX_МЕТКА = re.compile(r"<(/?)([A-Za-z0-9._]+)>([^<]*)", re.DOTALL)


class ВыпискаOFX:
    """OFX и QFX: выписка метками, в старом виде без закрывающих меток.

    Старый OFX — не XML: значения стоят сразу за меткой, а закрывающих меток у
    простых полей нет. Поэтому разбор идёт своим проходом по меткам, а не
    разборщиком XML: тот на таком входе либо падает, либо молча теряет поля.
    """

    имя = "офх"
    версия = "1"
    форматы = frozenset({"ofx", "qfx"})
    кодировки = ("utf-8", "cp1251", "latin-1")

    # Метки, за которыми стоит наблюдать: они несут деньги и время.
    ДЕНЕЖНЫЕ = frozenset({"TRNAMT", "BALAMT", "AVAILBAL", "AMOUNT"})

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        document_id = getattr(конверт, "document_id", "") or ""
        текст = self._раскодировать(данные)
        тело = текст[текст.find("<OFX>"):] if "<OFX>" in текст.upper() else текст
        if "<" not in тело:
            raise ValueError("в файле нет ни одной метки OFX")

        путь: list[str] = []
        номер_проводки = 0
        поля: dict[str, str] = {}
        текущая = None
        нашлось = False

        for закрывающая, метка, значение in _OFX_МЕТКА.findall(тело):
            метка = метка.upper()
            значение = значение.strip()
            if закрывающая:
                if метка == "STMTTRN" and текущая is not None:
                    нашлось = True
                    yield self._проводка(document_id, номер_проводки, поля)
                    текущая, поля = None, {}
                if путь and путь[-1] == метка:
                    путь.pop()
                continue

            if метка == "STMTTRN":
                номер_проводки += 1
                текущая, поля = метка, {}
                путь.append(метка)
                continue
            if not значение:
                путь.append(метка)
                continue

            if текущая is not None:
                поля[метка] = значение
            else:
                нашлось = True
                yield self._поле(document_id, путь, метка, значение)

        if not нашлось:
            raise ValueError("в файле не нашлось ни одного значения OFX")

    def _поле(self, document_id, путь, метка, значение) -> SourceObject:
        адрес = "/".join([*путь, метка]) if путь else метка
        return SourceObject(
            document_id=document_id, страница=1,
            система_координат="сообщение ofx",
            структурный_путь=адрес, сырой_текст=значение, полигон=None,
            свойства=_свойства([
                ("вид", "поле"),
                ("метка", метка),
                ("денежное", метка in self.ДЕНЕЖНЫЕ),
            ]))

    def _проводка(self, document_id, номер, поля) -> SourceObject:
        свойства = [("вид", "проводка")]
        свойства.extend(sorted(поля.items()))
        return SourceObject(
            document_id=document_id, страница=1,
            система_координат="сообщение ofx",
            структурный_путь=f"проводка[{номер}]",
            сырой_текст=поля.get("TRNAMT"),
            полигон=None, свойства=_свойства(свойства))

    def _раскодировать(self, данные: bytes) -> str:
        for кодировка in self.кодировки:
            try:
                return данные.decode(кодировка)
            except UnicodeDecodeError:
                continue
        raise ValueError("файл не прочитан ни в одной из объявленных кодировок")


# ------------------------------------------------------------------ CSV


@dataclass(frozen=True, slots=True)
class ПрофильCSV:
    """Объявленный вид согласованного CSV.

    Разделитель и кодировка объявляются, а не угадываются. Угаданный
    разделитель однажды угадается неверно, и строка молча съедет на столбец —
    подпись останется, а сумма встанет не в тот столбец.
    """

    разделитель: str = ";"
    кодировка: str = "utf-8"
    кавычка: str = '"'
    есть_заголовок: bool = True


class ВыпискаCSV:
    """Согласованный CSV: ячейка за ячейкой, с адресом строки и столбца."""

    имя = "согласованный-csv"
    версия = "1"
    форматы = frozenset({"csv"})

    def __init__(self, профиль: ПрофильCSV | None = None) -> None:
        self.профиль = профиль

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        if self.профиль is None:
            raise ValueError(
                "профиль CSV не объявлен: разделитель и кодировка должны быть "
                "заданы, угадывать их запрещено")
        document_id = getattr(конверт, "document_id", "") or ""
        try:
            текст = данные.decode(self.профиль.кодировка)
        except UnicodeDecodeError as беда:
            raise ValueError(
                f"файл не читается в объявленной кодировке "
                f"{self.профиль.кодировка}: {беда}") from беда

        читатель = csv.reader(
            io.StringIO(текст, newline=""),
            delimiter=self.профиль.разделитель,
            quotechar=self.профиль.кавычка)
        заголовок: list[str] = []
        номер_строки = 0
        for место, строка in enumerate(читатель, start=1):
            if место == 1 and self.профиль.есть_заголовок:
                заголовок = [ячейка.strip() for ячейка in строка]
                continue
            номер_строки += 1
            for столбец, ячейка in enumerate(строка, start=1):
                имя_столбца = (заголовок[столбец - 1]
                               if столбец - 1 < len(заголовок) else "")
                yield SourceObject(
                    document_id=document_id, страница=1,
                    система_координат="строка-столбец",
                    структурный_путь=f"строка[{номер_строки}]/поле[{столбец}]",
                    # Значение как записано: ни обрезки пробелов, ни разбора
                    # числа. Обрезка съедает значащий пробел, разбор — точность.
                    сырой_текст=ячейка,
                    полигон=None,
                    свойства=_свойства([
                        ("вид", "ячейка"),
                        ("столбец", столбец),
                        ("заголовок", имя_столбца),
                        ("строка_файла", место),
                    ]))


