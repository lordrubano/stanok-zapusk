# -*- coding: utf-8 -*-
"""Адаптеры структурированных банковских форматов: CAMT.053, MT940, OFX/QFX, CSV.

Шаг 27 плана. Нормативная основа — чертёж v3.0, раздел 5.1 (компонент 3
«Адаптеры извлечения») и раздел 5.3, где для этих форматов предписан
«детерминированный профильный парсер», а модель прямо названа не источником
структурированных значений.

Это единственные форматы, где данные приходят **уже разобранными**. Здесь нет
распознавания — значит, нет и его ошибок, и нет права на догадку. Разбор обязан
быть детерминированным: одни и те же байты обязаны давать один и тот же результат
всегда, без зависимости от настроек, локали и от того, что удалось угадать.

**Суммы и остатки берутся как записаны.** Ни одно денежное значение не
превращается в число языка. `1234,56` остаётся строкой `1234,56` — с запятой,
как в источнике. Истолкование запятой, знака и валюты — дело типизатора
(шаг 29); здесь оно было бы догадкой, а догадка о деньгах дорого стоит.

**Балансовых проверок здесь нет.** Сходится ли остаток с оборотами — вопрос
валидатора (Фаза 3). Адаптер, проверяющий баланс, однажды «поправит» источник
под свою проверку, и первичные данные перестанут быть первичными.

Решение о готовых библиотеках принято и обосновано в отчёте по шагу: разбор
написан свой. Коротко: готовые библиотеки ценны ровно тем, что нам запрещено
делать — они истолковывают суммы и даты; XML они разбирают своим разборщиком в
обход запрета внешних сущностей; а каждая новая зависимость требует надзора за
лицензией и цепочкой поставки. Розетка из шага 25 делает это решение обратимым:
заменить свой разбор на библиотечный можно, не трогая ядро.
"""

from __future__ import annotations

import csv
import io
import re
from collections.abc import Iterator
from dataclasses import dataclass

from .adapters import SourceObject
from .xmlsafe import разобрать


