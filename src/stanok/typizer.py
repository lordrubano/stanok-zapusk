# -*- coding: utf-8 -*-
"""Типизатор: истолкование сырых значений в точные типы.

Шаг 29 плана. Нормативная основа — чертёж v3.0, раздел 5.1 (компонент 5:
применение шаблона, Decimal, дат, словарей и нормализации, выход
``TypedRecord[]``) и раздел 6.1 (состав ``TypedRecord``: поля, десятичные
строки, даты, **исходные представления**, версия шаблона).

Три правила, которым здесь подчинено всё.

**1. Точная десятичная арифметика везде.** Двоичная дробь в денежном пути
запрещена. Не «нежелательна» — запрещена: `0.1 + 0.2` в ней даёт
`0.30000000000000004`, и баланс перестаёт сходиться на копейку, которой никто
не переводил. Число языка, попавшее на вход, отвергается сразу: оно уже
потеряло точность до нас, и починить это нельзя.

**2. Оригинал хранится рядом и не перезаписывается.** У каждого поля два
значения: ``raw`` — как было записано в источнике, и ``value`` — как истолковано.
Первое неприкосновенно. Истолкование можно переделать, оригинал восстановить
нельзя.

**3. Неоднозначное не угадывается.** `03.04.2026` — это третье апреля или
четвёртое марта, и по самой записи узнать нельзя. `1234` без разделителя — это
тысяча двести тридцать четыре рубля или двенадцать рублей тридцать четыре
копейки. Правило истолкования объявляет оснастка. Не объявлено — **отказ**, а не
догадка: угаданное однажды угадается неверно и уйдёт в результат молча, потому
что выглядеть будет как обычное значение.

Отказ здесь — состояние, как и в шагах 23–28: истолкование возвращает результат
с причиной, а не бросает исключение.
"""

