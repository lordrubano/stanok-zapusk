"""Вынос вершины цепи наружу: розетка есть, вилка не вставлена.

Решение владельца от 06.08.2026: механизм готовится сейчас, наружу не
включается. Устройство — как у внешнего резерва распознавателя (шаг 31):
розетка заведена, получателя в ней нет, и станок говорит это прямо.

## Общий механизм, а не блокчейн

Публикация в цепь блоков, отправка стороннему хранителю, штамп времени
удостоверяющего центра — **разные получатели одного и того же**: отпечатка
вершины с указанием времени. Различаются они тем, кому отдают и что получают в
ответ, а не тем, что отдают.

Поэтому здесь заведён один механизм и одна розетка. Вставится любой получатель
без переделки: от него требуется имя, версия и умение принять вершину и вернуть
квитанцию.

## Получателя нет — и это сказано, а не умолчано

Розетка пуста, пока в неё не воткнули. Вынос без получателя **не отказ**: он
происходит, записывается в учёт и честно называет себя выносом никому.
Молчаливое «всё в порядке» тут было бы худшим из возможных ответов: механизм,
который выглядит работающим и никому ничего не отдаёт, опаснее отсутствующего.

## Наружу не ходит ничего

В этом модуле нет и не будет ни одного обращения в сеть: сеть — дело
получателя, а получателя нет. Автономность станка (шаг 65) этим механизмом не
трогается, и проверяется это сторожем, а не обещанием.

## Чего вынос без получателя не даёт

Прямо, чтобы не выглядело большим, чем есть: **третьему лицу он не доказывает
ничего**. Все три файла — журнал, свидетельство вершины и учёт выносов — лежат
на одной машине, и тот, кто волен переписать один, волен переписать три.
Что он даёт на самом деле, перечислено в :data:`ЧТО_ДАЁТ_БЕЗ_ПОЛУЧАТЕЛЯ`.
"""

