# ------------------------------------------------------------ получатели


@dataclass(frozen=True, slots=True)
class Квитанция:
    """Что получатель вернул. Пустая квитанция — тоже ответ."""

    получатель: str
    версия: str
    принято: bool
    ссылка: str = ""
    подробность: str = ""

    def as_json(self) -> dict:
        return {"получатель": self.получатель, "версия": self.версия,
                "принято": self.принято, "ссылка": self.ссылка,
                "подробность": self.подробность}


class РозеткаНегодна(ValueError):
    """Получатель не годится: названо, чем именно."""


class РозеткаПолучателей:
    """Куда вставляется получатель вершины. Пуста, пока в неё не воткнули.

    Устроена как розетка распознавателей (шаг 25): контракт объявлен здесь,
    получатель приходит снаружи, и станок ничего о нём заранее не знает.
    """

    def __init__(self) -> None:
        self._свои: list = []

    def подключить(self, получатель) -> None:
        имя = getattr(получатель, "имя", "")
        версия = getattr(получатель, "версия", "")
        принять = getattr(получатель, "принять", None)
        if not имя:
            raise РозеткаНегодна("у получателя нет имени")
        if not версия:
            raise РозеткаНегодна(f"{имя}: у получателя нет версии")
        if not callable(принять):
            raise РозеткаНегодна(
                f"{имя}: получатель не умеет принимать вершину")
        if any(getattr(с, "имя", "") == имя for с in self._свои):
            raise РозеткаНегодна(f"{имя}: такой получатель уже подключён")
        self._свои.append(получатель)

    @property
    def пуста(self) -> bool:
        return not self._свои

    def перечень(self) -> tuple[str, ...]:
        return tuple(f"{getattr(с, 'имя', '')}/{getattr(с, 'версия', '')}"
                     for с in self._свои)

    def получатели(self) -> tuple:
        return tuple(self._свои)

    def свод(self) -> dict:
        return {"версия": ANCHOR_VERSION, "получателей": len(self._свои),
                "перечень": list(self.перечень()),
                "пуста": self.пуста}


РОЗЕТКА = РозеткаПолучателей()
"""Общая розетка станка. Пуста, и это её нормальное состояние сегодня."""


# ------------------------------------------------------------ вынос


@dataclass(frozen=True, slots=True)
class Вынос:
    """Один вынос вершины: когда, какая, кому и чем кончилось."""

    когда: str
    вершина: str
    событий: int
    исход: str
    получатель: str = ""
    квитанции: tuple = ()
    почему: str = ""

    @property
    def кому_то_отдано(self) -> bool:
        return self.исход == ПРИНЯТО

    def as_json(self) -> dict:
        return {
            "schema_version": ANCHOR_VERSION,
            "род": СОБЫТИЕ_ВЫНОСА,
            "когда": self.когда,
            "вершина": self.вершина,
            "событий": self.событий,
            "исход": self.исход,
            "получатель": self.получатель,
            "квитанции": [к.as_json() if hasattr(к, "as_json") else dict(к)
                          for к in self.квитанции],
            "почему": self.почему,
        }


def вынести(путь_журнала, путь_учёта, когда: str, *,
            розетка: РозеткаПолучателей = РОЗЕТКА,
            путь_свидетельства=None, кто: str = "станок") -> Вынос:
    """Выносит вершину цепи. Получателя нет — вынос всё равно происходит.

    Порядок не случаен: сперва вершина отделяется от журнала (свидетельство
    шага 58), затем предлагается получателям, затем — что бы ни вышло — вынос
    ложится в собственный учёт. Учёт ведётся **всегда**: вынос никому — тоже
    сведение, и умолчать его значило бы потерять единственное, что этот
    механизм сегодня даёт.
    """
    вершина = history.прочитать_вершину(путь_журнала)
    событий = len(history.прочитать(путь_журнала))

    if путь_свидетельства is not None:
        history.закрепить_вершину(путь_журнала, путь_свидетельства, когда, кто)

    квитанции: list[Квитанция] = []
    беды: list[str] = []
    for получатель in розетка.получатели():
        имя = getattr(получатель, "имя", "")
        версия = getattr(получатель, "версия", "")
        try:
            ответ = получатель.принять(вершина, когда)
        except Exception as беда:  # noqa: BLE001 — беда получателя не наша беда
            беды.append(f"{имя}: {type(беда).__name__}: {беда}")
            квитанции.append(Квитанция(имя, версия, False,
                                       подробность=str(беда)[:200]))
            continue
        свой = ответ if isinstance(ответ, dict) else {}
        квитанции.append(Квитанция(
            имя, версия, bool(свой.get("принято", True)),
            ссылка=str(свой.get("ссылка", "")),
            подробность=str(свой.get("подробность", ""))))

    if розетка.пуста:
        исход, почему = НИКОМУ, (
            f"{ПОЛУЧАТЕЛЯ_НЕТ}: получатель вершины не подключён. Вершина "
            "отделена от журнала и записана в учёт, но никому не отдана — "
            "третьему лицу этот вынос не доказывает ничего")
    elif квитанции and all(к.принято for к in квитанции):
        исход, почему = ПРИНЯТО, "приняли: " + ", ".join(
            к.получатель for к in квитанции)
    else:
        исход = ОТКАЗ_ПОЛУЧАТЕЛЯ
        почему = "; ".join(беды) or "получатель не принял вершину"

    вынос = Вынос(когда=когда, вершина=вершина, событий=событий, исход=исход,
                  получатель=", ".join(розетка.перечень()),
                  квитанции=tuple(квитанции), почему=почему)
    записать(вынос, путь_учёта)
    return вынос


def записать(вынос: Вынос, путь_учёта) -> str:
    """Кладёт вынос в собственный учёт. Учёт — цепь того же устройства."""
    return journal.append_record(Path(путь_учёта), вынос.as_json(),
                                 схема=journal.нормализовать_событие,
                                 доверяя_хвосту=True)


def прочитать_учёт(путь_учёта) -> tuple[dict, ...]:
    """Все выносы по порядку. Цепь проверяется при чтении."""
    место = Path(путь_учёта)
    if not место.exists():
        return ()
    journal.verify_journal(место, схема=journal.нормализовать_событие)
    свои = []
    for строка in место.read_bytes().split(b"\n"):
        if строка.strip():
            свои.append(json.loads(строка.decode("utf-8")))
    return tuple(свои)


def последний(путь_учёта) -> dict | None:
    свои = прочитать_учёт(путь_учёта)
    return свои[-1] if свои else None


def окно_без_выноса(путь_журнала, путь_учёта) -> dict:
    """Сколько событий журнала не покрыто ни одним выносом.

    Это и есть незакрытое окно: события после последнего выноса ничем не
    прикрыты — ни сегодня, ни с получателем.
    """
    событий = len(history.прочитать(путь_журнала))
    свой = последний(путь_учёта)
    вынесено = int(свой.get("событий", 0)) if свой else 0
    return {"версия": ANCHOR_VERSION, "событий_в_журнале": событий,
            "вынесено_на_последнем": вынесено,
            "окно": max(0, событий - вынесено),
            "выносов": len(прочитать_учёт(путь_учёта)),
            "почему": ("события после последнего выноса не прикрыты ничем: "
                       "сузить окно можно только частотой выносов")}


def сверить(путь_журнала, путь_учёта) -> dict:
    """Сходится ли нынешняя вершина с последним вынесенным.

    Расхождение не значит подделки: журнал мог законно вырасти. Значит оно
    ровно то, что сказано, — вершина другая, и с какого места другая, знает
    только сам журнал.
    """
    вершина = history.прочитать_вершину(путь_журнала)
    свой = последний(путь_учёта)
    if свой is None:
        return {"версия": ANCHOR_VERSION, "выносов": 0, "сошлось": None,
                "почему": f"{ПОЛУЧАТЕЛЯ_НЕТ}: выносов не было — сверять не с чем"}
    сошлось = свой.get("вершина") == вершина
    return {
        "версия": ANCHOR_VERSION,
        "выносов": len(прочитать_учёт(путь_учёта)),
        "сошлось": сошлось,
        "вершина_сейчас": вершина,
        "вершина_вынесенная": свой.get("вершина"),
        "почему": ("вершина та же, что вынесена последней" if сошлось else
                   "вершина изменилась после последнего выноса: журнал вырос "
                   "либо был переписан, и различить это отсюда нельзя"),
    }


def _сейчас() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


