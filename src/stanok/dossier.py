def _имя_или_отпечаток(документ: str, скрыть: bool) -> str:
    if not скрыть or not документ:
        return документ
    import hashlib

    отпечаток = hashlib.sha256(документ.encode("utf-8")).hexdigest()
    return f"документ с отпечатком имени {отпечаток[:16]}"


def собрать(проводка=None, *, состав=None, свидетельство=None,
            документ: str = "", когда: str = "", выпуск: str = "",
            скрыть_имя: bool = False) -> dict:
    """Складывает доказательный пакет из уже сделанного.

    Ни одно число здесь не считается заново: всё берётся у тех частей станка,
    которые за него отвечают.

    ``скрыть_имя`` — для клиента, которому и имя файла показывать не хочется.
    Доказательная сила от этого не меняется: подтверждают пакет отпечатки и
    подпись, а не имя.
    """
    доводы: list[Довод] = []
    if проводка is not None:
        доводы.extend(_доводы_о_чтении(проводка))
        доводы.extend(_доводы_о_покрытии(getattr(проводка, "карта", None)))
        доводы.extend(_доводы_о_происхождении(
            _свод_происхождения(проводка)))
        доводы.extend(_доводы_о_решениях(проводка))
    доводы.extend(_доводы_об_изделии(состав, свидетельство))

    return {
        "версия": DOSSIER_VERSION,
        "документ": _имя_или_отпечаток(документ, скрыть_имя),
        "о_содержимом": О_СОДЕРЖИМОМ,
        "когда": когда,
        "выпуск": выпуск,
        "главное_ограничение": ГЛАВНОЕ_ОГРАНИЧЕНИЕ,
        "автодопуск_есть": АВТОДОПУСК_ЕСТЬ,
        "доля_ошибок_измерена": ДОЛЯ_ОШИБОК_ИЗМЕРЕНА,
        "доводы": [д.as_json() for д in доводы],
        "чего_не_утверждается": list(ЧЕГО_НЕ_УТВЕРЖДАЕТСЯ),
        "для_машины": _для_машины(проводка, состав, свидетельство),
    }


def _свод_происхождения(проводка) -> dict:
    """Берёт готовый свод происхождения, а не пересчитывает свидетельства."""
    свои = getattr(проводка, "происхождение", None)
    if not свои:
        return {}
    from .evidence import свод as свод_полей

    все = [с for группа in свои.values() for с in группа]
    return свод_полей(все) if все else {}


def _для_машины(проводка, состав, свидетельство) -> dict:
    """Раздел для машины: коды и точные числа, внизу и отдельно."""
    свой: dict = {"версия": DOSSIER_VERSION}
    if проводка is not None:
        свой["состояние_запуска"] = getattr(проводка, "состояние_запуска", "")
        свой["записей"] = len(getattr(проводка, "записи", ()))
        свой["сорвалось"] = list(getattr(проводка, "сорвалось", ()))
        карта = getattr(проводка, "карта", None)
        if карта is not None:
            свой["покрытие"] = карта.as_json()
    if состав:
        свой["состав"] = {"версия_изделия": состав.get("версия"),
                          "отпечаток_изделия": состав.get("отпечаток_изделия"),
                          "собрано": состав.get("собрано")}
    if свидетельство:
        свой["подпись"] = {"издатель": свидетельство.get("издатель"),
                           "открытый_ключ": свидетельство.get("открытый_ключ"),
                           "отпечаток": свидетельство.get("отпечаток")}
    return свой


def чего_не_утверждается() -> tuple[str, ...]:
    """Отдельная опора пакета: где кончается доказанное."""
    return ЧЕГО_НЕ_УТВЕРЖДАЕТСЯ


