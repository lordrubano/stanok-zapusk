def как_текст(пакет: dict) -> str:
    """Пакет словами — для человека, который станка не видел.

    Порядок разделов не случаен: сперва то, чего пакет не утверждает, потом
    утверждения. Обратный порядок читается как реклама с оговоркой внизу.
    """
    н = chr(10)
    строки = ["# Доказательный пакет", ""]
    если_есть = пакет.get("документ")
    if если_есть:
        строки.append(f"Документ: {если_есть}.")
    if пакет.get("когда"):
        строки.append(f"Обработан: {пакет['когда']}.")
    if пакет.get("выпуск"):
        строки.append(f"Выпуск станка: {пакет['выпуск']}.")
    строки.append("")

    строки += ["## Прочтите это первым", "",
               пакет.get("главное_ограничение", ГЛАВНОЕ_ОГРАНИЧЕНИЕ), "",
               пакет.get("о_содержимом", О_СОДЕРЖИМОМ), ""]

    строки += ["## Чего этот пакет не утверждает", ""]
    for что in пакет.get("чего_не_утверждается", ()):
        строки.append(f"* Не утверждается, {что}.")
    строки.append("")

    строки += ["## Что станок сделал и чем это подтверждено", "",
               "| О чём | Что установлено | Чем подтверждено |",
               "|---|---|---|"]
    for довод in пакет.get("доводы", ()):
        строки.append(f"| {довод['о_чём']} | {довод['сказано']} | "
                      f"{довод['подтверждено']} |")
    строки.append("")

    строки += ["## Как проверить это самому", "",
               "Ничего из перечисленного не нужно принимать на слово.", "",
               "* подпись изделия — `python ядро-1.pyz --проверить-подпись "
               "ядро-1.pyz --ключ-издателя <ключ из договора>`;",
               "* состав изделия — `python ядро-1.pyz --состав ядро-1.pyz`;",
               "* лицензии составных частей — `python ядро-1.pyz --лицензии "
               "ядро-1.pyz`.", "",
               "Ни одна из этих проверок не требует сети и не требует нашего "
               "участия.", ""]

    строки += ["## Для машины", "", "```json",
               json.dumps(пакет.get("для_машины", {}), ensure_ascii=False,
                          indent=1, sort_keys=True),
               "```", ""]
    return н.join(строки)


def записать(пакет: dict, куда) -> tuple[Path, Path]:
    """Кладёт пакет двумя видами: словами и числами. Оба — один и тот же пакет."""
    место = Path(куда)
    место.mkdir(parents=True, exist_ok=True)
    словами = место / "доказательный-пакет.md"
    числами = место / "доказательный-пакет.json"
    словами.write_text(как_текст(пакет), encoding="utf-8")
    числами.write_text(json.dumps(пакет, ensure_ascii=False, indent=1),
                       encoding="utf-8")
    return словами, числами


