# -*- coding: utf-8 -*-
"""Доказательный пакет: то, что клиент показывает своему аудитору.

Шаг 76 плана. Нормативная основа — чертёж v3.0, раздел 12.

## Пакет собирается из сделанного, а не пишется заново

Ни одна цифра здесь не считается второй раз. Всё, что в пакет попадает, уже
посчитано и записано раньше — и записано теми частями станка, которые за это
отвечают:

| Что в пакете | Откуда взято |
|---|---|
| паспорт запуска | шаг 18, журнал прогонов |
| карта покрытия и исключения с причинами | шаг 33 |
| происхождение полей | шаг 35 |
| решения по записям | шаг 45, движок политик |
| перечень состава выпуска | шаг 73 |
| подпись авторства | шаг 74 |

Пересчёт был бы вторым мнением о том же — а два мнения об одном числе означают,
что верить нельзя ни одному. Здесь одно.

## Читает его аудитор, а не оператор

Оператор знает станок, аудитор — нет. Поэтому пакет говорит словами, а не
кодами: каждый ответ выговаривается целиком, каждое число объяснено, и всякий
раз сказано, **чем оно подтверждено**. Коды остаются в разделе для машины —
внизу и отдельно.

## В пакет не попадает ничего, чего станок не может доказать

Правило простое и жёсткое: **утверждается состав, а не отсутствие бед**.

Станок может доказать, что документ прочитан так-то, что столько-то объектов
учтено, что каждое исключение объяснено, что вот это число взято отсюда, что
изделие собрано из вот этого и подписано вот этим ключом.

Станок не может доказать, что в результате нет ошибок; что документ не был
подменён до того, как попал к нему; что оператор, подтвердивший запись,
подтвердил её правильно. Всё это в пакет не попадает — ни прямо, ни намёком.
Раздел :func:`чего_не_утверждается` — не оговорка мелким шрифтом, а часть
пакета, идущая перед выводами.

## Главное ограничение объявляется в самом пакете

Сегодня **ни одна запись не допущена автоматически, доля ошибок не измерена**.
Разметчиков нет, эталонов нет, и потому нет права говорить о точности. Пакет,
умалчивающий об этом, врал бы аудитору — не цифрой, а умолчанием, что хуже:
цифру можно проверить, умолчание нельзя.

Ограничение стоит **первым разделом**, а не последним, и снимается оно не
кодом, а измерением на размеченном корпусе.
"""

