# -*- coding: utf-8 -*-
"""Неизменяемая история решений человека: журнал действий оператора.

Шаг 58 плана. Нормативная основа — чертёж v3.0, раздел 12: «неизменяемые
значения до и после, оператор, время и основание», «журнал событий является
добавляемым, для него допускается цепной хеш».

**Второго журнала здесь не заводится.** Механизм добавляемой записи с цепным
хешем сделан на шаге 18, и он же используется: `journal.append_record`,
`journal.verify_journal`. Свой хеш, свой формат и своя проверка означали бы два
разных представления об одном и том же — и однажды они разошлись бы.

Что добавляет этот шаг сверх шага 18:

* **форма события действия** — что именно кладётся в журнал, чтобы через месяц
  по нему можно было ответить на вопрос «почему эта запись принята вручную»;
* **привязку к устойчивому адресу источника**, а не к номеру записи;
* **чтение истории**: что человек решал об этой записи и об этом документе.

## Почему привязка идёт не по номеру записи

Номер `зп-27` — **позиционный**: двадцать седьмая по счёту операция этого
разбора. Перепроведи документ новой версией оснастки, у которой иначе
определяется граница операции, — и `зп-27` укажет на другую операцию. Решения
человека при этом молча переехали бы на чужие записи, и заметить это было бы
нечем.

Поэтому событие несёт **document_id** (отпечаток исходных байтов, раздел 6.2) и
**якоря областей источника** — адреса, которые не зависят ни от разбора, ни от
версии оснастки. По ним прежние решения находятся и после перепроводки.

## Что значит «переживает перепроводку»

Журнал не переписывается при новом запуске **вообще**: он добавляемый, и новый
запуск только дописывает. Прежние решения человека остаются на месте и находятся
по документу и якорю. Возврат оснастки, из-за которого документ перепроводится
новой версией, работу оператора не стирает — иначе он был бы не сигналом о
настройке, а тихим уничтожением чужого труда.

Найденное решение — не приказ новому разбору. История говорит: «здесь человек
уже решал, вот что и вот почему»; применять ли это к новой записи, решает
человек, а не станок. Молчаливый перенос ручного допуска на запись, разобранную
иначе, был бы допуском того, чего никто не смотрел.

## Вершина цепи

Цепь ловит правку внутри журнала, но **полная пересборка** тем, у кого есть
доступ на запись, проходит мимо — если вершина не сохранена снаружи. Это
названо оговоркой шага 18 и остаётся верным.

Здесь сделано то, что можно сделать средствами станка: вершина **выносится** —
:func:`закрепить_вершину` кладёт её отдельным свидетельством с числом записей и
временем, а :func:`сверить_с_закреплённой` сверяет журнал с последним таким
свидетельством. Пересборка журнала, не совпавшая с закреплённой вершиной,
обнаруживается.

**Чего это не решает и что остаётся владельцу.** Свидетельство лежит на той же
машине и пишется тем же станком: тот, кто может пересобрать журнал, может
пересобрать и его. Настоящая независимость требует, чтобы вершина уходила туда,
где станок не хозяин, — и выбор такого места есть решение владельца, а не
исполнителя. Годятся три пути, и они различаются ценой доверия: публикация
вершины в ящик отправки (внешнее хранилище, чужие отпечатки, но тот же владелец
доступа); отправка вершины стороне, которая не может её переписать; заверение у
службы штампов времени. Пока не выбрано — вопрос **открытый**, и станок не
делает вид, что он закрыт.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from . import journal
from .operator import ВЕРНУТЬ_ОСНАСТКУ, ДЕЙСТВИЯ


HISTORY_VERSION = "operator-history/1"

СОБЫТИЕ_ДЕЙСТВИЯ = "действие оператора"
СОБЫТИЕ_ВОЗВРАТА = "возврат оснастки"

KNOWN_LIMITATIONS = (
    "Вершина цепи закрепляется свидетельством на той же машине. Тот, кто может "
    "пересобрать журнал, может пересобрать и свидетельство: независимое "
    "хранение вершины — решение владельца, и оно не принято.",
    "История находит прежние решения по документу и якорю области, но не "
    "переносит их на новые записи: перенос — суждение человека, а не станка.",
    "Событие хранит имя оператора строкой. Проверки, что за именем стоит тот "
    "самый человек, здесь нет: это роли и учётные записи, шаг 60.",
    "Журнал общий для всех документов и растёт без границы. Разделение по "
    "периодам, перенос в архив и сжатие — эксплуатация, шаг 63.",
)


class ИсторияНегодна(ValueError):
    """История не может быть записана или прочитана: сказано, почему."""


# ------------------------------------------------------- запись события


def _обязательно(значение, чего: str) -> str:
    строка = str(значение or "").strip()
    if not строка:
        raise ИсторияНегодна(
            f"в событие не положено {чего}: без него история отвечает "
            "«что-то решили», а спрашивают «почему решили так»")
    return строка


def событие_действия(итог, document_id: str, якоря=()) -> dict:
    """Событие одного действия оператора в виде, пригодном для журнала.

    ``итог`` — то, что вернуло исполнение действия (шаг 57). Здесь оно не
    пересчитывается и не толкуется: складывается как есть, вместе с адресом
    документа и якорями областей.
    """
    действие = итог.действие
    if действие.вид not in ДЕЙСТВИЯ:
        raise ИсторияНегодна(f"действия {действие.вид!r} не существует")
    if действие.вид == ВЕРНУТЬ_ОСНАСТКУ:
        raise ИсторияНегодна(
            "возврат оснастки — не действие над записью; для него есть "
            "«событие_возврата»")

    свои_якоря = tuple(str(я) for я in якоря)
    if not свои_якоря:
        raise ИсторияНегодна(
            "событие без якоря области источника не переживёт перепроводку: "
            "номер записи позиционный и после новой оснастки укажет на чужую")

    событие = {
        "schema_version": HISTORY_VERSION,
        "род": СОБЫТИЕ_ДЕЙСТВИЯ,
        "document_id": _обязательно(document_id, "имя документа"),
        "record_id": _обязательно(действие.record_id, "имя записи"),
        "якоря": list(свои_якоря),
        "действие": действие.вид,
        "оператор": _обязательно(действие.оператор, "имя оператора"),
        "основание": _обязательно(действие.основание, "основание"),
        "время": _обязательно(действие.время, "время"),
        "было": итог.событие.get("было"),
        "стало": итог.событие.get("стало"),
        "связка": действие.связка,
        "в_связке": действие.в_связке,
    }
    if итог.правка is not None:
        событие["поле"] = итог.правка.поле
        событие["было_значение"] = итог.правка.было_значение
        событие["было_сырьё"] = итог.правка.было_сырьё
        событие["стало_значение"] = итог.правка.стало
    return событие


def событие_возврата(возврат, document_id: str) -> dict:
    """Событие возврата оснастки. Записи в нём — свидетели, а не подсудимые."""
    return {
        "schema_version": HISTORY_VERSION,
        "род": СОБЫТИЕ_ВОЗВРАТА,
        "document_id": _обязательно(document_id, "имя документа"),
        "семейство": _обязательно(возврат.семейство, "семейство"),
        "версия_оснастки": _обязательно(возврат.версия_оснастки, "версия оснастки"),
        "оператор": _обязательно(возврат.оператор, "имя оператора"),
        "основание": _обязательно(возврат.основание, "основание"),
        "время": _обязательно(возврат.время, "время"),
        "замечено_на": list(возврат.замечено_на),
        "затронуто_записей": возврат.затронуто_записей,
        "меняет_статусы": False,
    }


def записать(путь, событие: dict) -> str:
    """Добавляет событие в журнал и возвращает новую вершину цепи.

    Добавляет — и только. Ни правки, ни удаления здесь нет и не будет: журнал
    добавляемый, и это свойство самого шага 18, а не обещание этого модуля.
    """
    try:
        # Доверяем хвосту: перечитывать весь журнал ради каждой строки стоит
        # квадрата, а неизменность от этого не растёт — подделка ловится при
        # чтении истории и при сверке с закреплённой вершиной.
        return journal.append_record(
            путь, событие, схема=journal.нормализовать_событие,
            доверяя_хвосту=True)
    except journal.JournalError as беда:
        raise ИсторияНегодна(f"событие не легло в журнал: {беда}") from беда


def записать_все(путь, события) -> str:
    """Кладёт события подряд. Вершина возвращается от последнего."""
    вершина = ""
    for событие in события:
        вершина = записать(путь, событие)
    return вершина or прочитать_вершину(путь)


# --------------------------------------------------------- чтение


def прочитать(путь) -> tuple[dict, ...]:
    """Все события журнала по порядку. Цепь проверяется при чтении.

    Проверка не откладывается «на потом»: история, прочитанная без проверки
    цепи, ничем не отличается от простого списка, а списку веры нет.
    """
    место = Path(путь)
    if not место.exists():
        return ()
    journal.verify_journal(место, схема=journal.нормализовать_событие)
    события = []
    for строка in место.read_bytes().split(b"\n"):
        if строка.strip():
            события.append(json.loads(строка.decode("utf-8")))
    return tuple(события)


def прочитать_вершину(путь) -> str:
    """Вершина цепи журнала. Пустой журнал даёт начало цепи."""
    место = Path(путь)
    if not место.exists():
        return journal.CHAIN_START
    return journal.verify_journal(место, схема=journal.нормализовать_событие)


def по_записи(события, document_id: str, record_id: str) -> tuple[dict, ...]:
    """Что человек решал об этой записи этого документа."""
    return tuple(с for с in события
                 if с.get("document_id") == document_id
                 and с.get("record_id") == record_id)


def по_якорю(события, document_id: str, якорь: str) -> tuple[dict, ...]:
    """Что человек решал об области источника — хоть до, хоть после перепроводки.

    Это и есть тот путь, которым история переживает перепроводку: якорь области
    не зависит ни от порядка записей, ни от версии оснастки.
    """
    return tuple(с for с in события
                 if с.get("document_id") == document_id
                 and якорь in (с.get("якоря") or ()))


def по_документу(события, document_id: str) -> tuple[dict, ...]:
    return tuple(с for с in события if с.get("document_id") == document_id)


@dataclass(frozen=True, slots=True)
class Прежнее:
    """Прежние решения человека, найденные для новой записи."""

    record_id: str
    якоря: tuple
    события: tuple
    прежние_record_id: tuple = ()

    @property
    def есть(self) -> bool:
        return bool(события_с_действием(self.события))

    def as_json(self) -> dict:
        return {"record_id": self.record_id, "якоря": list(self.якоря),
                "событий": len(self.события),
                "прежние_record_id": list(self.прежние_record_id),
                "есть": self.есть}


def события_с_действием(события) -> tuple[dict, ...]:
    return tuple(с for с in события if с.get("род") == СОБЫТИЕ_ДЕЙСТВИЯ)


def найти_прежнее(события, document_id: str, запись: dict) -> Прежнее:
    """Ищет прежние решения для записи **нового** разбора того же документа.

    Ищется по якорям областей источника. Найденное не применяется само: это
    сведения для человека, а не приказ станку. Молчаливый перенос ручного
    допуска на иначе разобранную запись был бы допуском того, чего никто не
    смотрел.
    """
    якоря = tuple(str(я) for я in (запись.get("source_anchor_ids") or ()))
    найденные, прежние_имена = [], []
    for якорь in якоря:
        for событие in по_якорю(события, document_id, якорь):
            if событие not in найденные:
                найденные.append(событие)
                имя = событие.get("record_id")
                if имя and имя not in прежние_имена:
                    прежние_имена.append(имя)
    return Прежнее(запись.get("record_id", ""), якоря, tuple(найденные),
                   tuple(прежние_имена))


# ------------------------------------------------------- вершина цепи


ВЕРШИНА_ВЕРСИЯ = "chain-head/1"


def закрепить_вершину(путь_журнала, путь_свидетельства, время: str,
                      кто: str = "станок") -> dict:
    """Выносит вершину цепи отдельным свидетельством.

    Свидетельство добавляется, а не переписывается: прежние остаются, и по ним
    видно, как журнал рос. Совпадение с последним свидетельством — то немногое,
    чем средствами самой машины можно поймать полную пересборку.
    """
    вершина = прочитать_вершину(путь_журнала)
    события = прочитать(путь_журнала)
    свидетельство = {
        "schema_version": ВЕРШИНА_ВЕРСИЯ,
        "вершина": вершина,
        "событий": len(события),
        "время": _обязательно(время, "время"),
        "кто": _обязательно(кто, "кто закрепил"),
    }
    место = Path(путь_свидетельства)
    место.parent.mkdir(parents=True, exist_ok=True)
    с_переводом = json.dumps(свидетельство, ensure_ascii=False,
                             sort_keys=True) + "\n"
    with место.open("a", encoding="utf-8") as файл:
        файл.write(с_переводом)
    return свидетельство


def последняя_закреплённая(путь_свидетельства) -> dict | None:
    место = Path(путь_свидетельства)
    if not место.exists():
        return None
    строки = [с for с in место.read_text(encoding="utf-8").split("\n") if с.strip()]
    return json.loads(строки[-1]) if строки else None


def сверить_с_закреплённой(путь_журнала, путь_свидетельства) -> dict:
    """Сверяет журнал с последней закреплённой вершиной.

    Три исхода, и каждый называется своим именем: свидетельства нет вовсе;
    журнал вырос (это обычное дело — цепь продолжена от закреплённой вершины);
    журнал разошёлся со свидетельством (это пересборка, и её надо объяснять).
    """
    закреплённая = последняя_закреплённая(путь_свидетельства)
    if закреплённая is None:
        return {"исход": "не закреплялась",
                "объяснение": "вершина ни разу не выносилась: полная пересборка "
                              "журнала обнаружена не будет"}
    события = прочитать(путь_журнала)
    вершина = прочитать_вершину(путь_журнала)
    если_столько = закреплённая.get("событий", 0)
    if вершина == закреплённая.get("вершина") and len(события) == если_столько:
        return {"исход": "сошлось", "вершина": вершина, "событий": len(события)}
    if len(события) > если_столько:
        # Журнал мог только вырасти: проверяем, что прежняя вершина в нём есть.
        хеши = [с.get("hash") for с in события[:если_столько]]
        если_прежняя = хеши[-1] if хеши else journal.CHAIN_START
        if если_прежняя == закреплённая.get("вершина"):
            return {"исход": "дописан",
                    "было_событий": если_столько,
                    "стало_событий": len(события),
                    "вершина": вершина}
    return {
        "исход": "разошёлся",
        "объяснение": "журнал не продолжает закреплённую вершину: это полная "
                      "пересборка, и она обязана быть объяснена",
        "закреплено_событий": если_столько,
        "в_журнале_событий": len(события),
        "закреплённая_вершина": закреплённая.get("вершина"),
        "вершина_журнала": вершина,
    }


def свод(события) -> dict:
    """Что говорит история: сколько решений, чьих и о чём."""
    события = tuple(события)
    действия = события_с_действием(события)
    return {
        "версия": HISTORY_VERSION,
        "событий": len(события),
        "действий": len(действия),
        "возвратов_оснастки": len(события) - len(действия),
        "документов": len({с.get("document_id") for с in события}),
        "записей": len({(с.get("document_id"), с.get("record_id"))
                        for с in действия}),
        "операторов": sorted({с.get("оператор") for с in события if с.get("оператор")}),
        "по_действиям": {вид: sum(1 for с in действия
                                  if с.get("действие") == вид)
                         for вид in ДЕЙСТВИЯ if вид != ВЕРНУТЬ_ОСНАСТКУ},
    }


