# -*- coding: utf-8 -*-
"""Четыре действия оператора: подтвердить, исправить, отклонить, вернуть оснастку.

Шаг 57 плана. Нормативная основа — чертёж v3.0, **раздел 12** «Консоль проверки
и журнал решений»: действия оператора, неизменяемые значения до и после,
оператор, время и основание.

**Непереговорное: первичный результат не переписывается никогда.** Исправление
живёт отдельной записью — что было, что стало, кто и почему. Разобранное
станком остаётся ровно таким, каким станок его отдал. Стоит один раз переписать
поле поверх — и доказательная связь «значение → область страницы → правило»
рвётся: значение в записи будет уже не тем, к чему ведёт происхождение. Именно
эту связь продукт и продаёт, а не удобство правки.

Отсюда устройство: исправление даёт **производную копию** записи, в которой
видно и прежнее значение, и новое, и чьё оно. Первичная запись при этом остаётся
той же самой — проверка на это стоит и сравнивает предмет, а не его вид.

**У каждого действия обязательно основание — строка от человека.** Не потому,
что так строже, а потому, что через месяц никто не вспомнит, почему запись
принята вручную, а спросить могут. Основание в одну строку: перевод строки в нём
запрещён — многострочное объяснение уходит в приложенные к событию заметки, а не
в поле, которое читают списком.

**Связки разрешаются осознанно, а не молча.** Оператор, разрешивший двоякую дату
у одной записи, может применить то же решение ко всей связке одинаковых
сомнений, но обязан **назвать число** записей, которых это коснётся. Не
совпало — отказ. Молчаливое «применить ко всем» превращает решение человека в
неподотчётную массовую правку.

**Возврат оснастки — не действие над записью.** Он говорит: виновата настройка,
а не документ. Отличий от отклонения три, и они существенны:

* отклонение судит **запись** по существу и её жизнь заканчивает; возврат
  оснастки не меняет ни одного статуса записи — они остаются ждать человека;
* отклонённая запись переразбору не подлежит: разбор был верен, негодны данные.
  Записи при возврате, наоборот, **обязаны быть перепроведены** новой версией
  оснастки — они не виноваты;
* отклонение адресовано записи, возврат — **семейству и версии оснастки**, и
  потому один возврат покрывает тысячи записей сразу.

**Чего здесь нет.** Хранения событий в неизменяемом журнале (шаг 58),
разграничения ролей (шаг 60), запрета исправленного результата как нового
источника (шаг 59) и измерения ручного труда (шаг 61). Здесь действия
**производятся** и обретают форму, пригодную для журнала, — но не хранятся.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace

from . import decision as реш


OPERATOR_VERSION = "operator-actions/1"

ПОДТВЕРДИТЬ = "подтвердить"
ИСПРАВИТЬ = "исправить"
ОТКЛОНИТЬ = "отклонить"
ВЕРНУТЬ_ОСНАСТКУ = "вернуть оснастку"

ДЕЙСТВИЯ = (ПОДТВЕРДИТЬ, ИСПРАВИТЬ, ОТКЛОНИТЬ, ВЕРНУТЬ_ОСНАСТКУ)
"""Четыре действия раздела 12. Перечень закрыт: пятого не бывает."""

# Действия над записью — три из четырёх. Четвёртое обращено к оснастке.
НАД_ЗАПИСЬЮ = (ПОДТВЕРДИТЬ, ИСПРАВИТЬ, ОТКЛОНИТЬ)

_НАИМЕНЬШЕЕ_ОСНОВАНИЕ = 3

KNOWN_LIMITATIONS = (
    "События действий здесь только рождаются. Хранение в добавляемом журнале с "
    "цепным хешем — шаг 58; до него событие живёт ровно столько, сколько его "
    "держит вызывающий.",
    "Ролей нет: любой оператор может всё. Разграничение разметчика, "
    "проверяющего и администратора — шаг 60.",
    "Исправленная запись помечена производной, но запрет использовать её как "
    "новый источник здесь не принуждается — это шаг 59.",
    "Время действия принимается снаружи и не берётся из часов машины: ядро "
    "детерминированно, а время события — свидетельство, и подделывать его "
    "часами станка нельзя.",
    "Основание проверяется на длину и на одну строку, но не на осмысленность. "
    "Отличить объяснение от отписки может только человек, читающий журнал.",
)


class ДействиеНегодно(ValueError):
    """Действие не может быть исполнено: сказано, чего не хватает."""


# ------------------------------------------------------------- действие


@dataclass(frozen=True, slots=True)
class Действие:
    """Одно действие оператора. Неизменяемо с рождения."""

    вид: str
    оператор: str
    основание: str
    время: str
    record_id: str | None = None
    поле: str | None = None
    стало: str | None = None
    семейство: str | None = None
    версия_оснастки: str | None = None
    связка: str | None = None
    в_связке: int = 1
    роль: str | None = None
    """Чем позволено то, что делается. Роль принуждается, а не называется.

    Не обязательна по подписи, но обязательна по делу: действие без роли
    исполняется только там, где ролей ещё нет вовсе, и :func:`исполнить`
    говорит об этом отказом, если роль подана негодная. Проверка личности —
    не здесь и не в станке вовсе (шаг 60).
    """

    def __post_init__(self) -> None:
        if self.вид not in ДЕЙСТВИЯ:
            raise ДействиеНегодно(
                f"действия {self.вид!r} не существует; их четыре: "
                + ", ".join(ДЕЙСТВИЯ))
        if not (self.оператор or "").strip():
            raise ДействиеНегодно("действие без оператора свидетельством не "
                                  "является: некому отвечать")
        if not (self.время or "").strip():
            raise ДействиеНегодно("действие без времени свидетельством не "
                                  "является: неизвестно, когда решено")
        основание = (self.основание or "").strip()
        if len(основание) < _НАИМЕНЬШЕЕ_ОСНОВАНИЕ:
            raise ДействиеНегодно(
                "основание обязательно: через месяц никто не вспомнит, почему "
                "так решено, а спросить могут")
        if "\n" in основание or "\r" in основание:
            raise ДействиеНегодно(
                "основание — одна строка; длинное объяснение читают не списком")

        if self.вид in НАД_ЗАПИСЬЮ and not (self.record_id or "").strip():
            raise ДействиеНегодно(
                f"действие {self.вид!r} обращено к записи, а запись не названа")
        if self.вид == ИСПРАВИТЬ:
            if not (self.поле or "").strip():
                raise ДействиеНегодно("исправление без поля: непонятно, что "
                                      "именно правится")
            if self.стало is None:
                raise ДействиеНегодно("исправление без нового значения")
        elif self.поле is not None or self.стало is not None:
            raise ДействиеНегодно(
                f"действие {self.вид!r} значения не меняет: поле и новое "
                "значение здесь лишние. Чтобы изменить значение, есть "
                "исправление")
        if self.вид == ВЕРНУТЬ_ОСНАСТКУ:
            if not (self.семейство or "").strip() or \
                    not (self.версия_оснастки or "").strip():
                raise ДействиеНегодно(
                    "возврат обращён к оснастке, а семейство и версия не "
                    "названы: возвращать нечего")

    def as_json(self) -> dict:
        return {
            "версия": OPERATOR_VERSION,
            "вид": self.вид,
            "оператор": self.оператор,
            "основание": self.основание,
            "время": self.время,
            "record_id": self.record_id,
            "поле": self.поле,
            "стало": self.стало,
            "семейство": self.семейство,
            "версия_оснастки": self.версия_оснастки,
            "связка": self.связка,
            "в_связке": self.в_связке,
            "роль": self.роль,
        }


# -------------------------------------------------------------- правка


@dataclass(frozen=True, slots=True)
class Правка:
    """Исправление, хранимое **отдельно** от записи. Раздел 12.

    Здесь лежит и прежнее значение, и новое: «неизменяемые значения до и после».
    Прежнее берётся из самой записи в миг правки, а не со слов оператора.
    """

    record_id: str
    поле: str
    было_значение: str | None
    было_сырьё: str | None
    стало: str
    оператор: str
    основание: str
    время: str
    связка: str | None = None

    def as_json(self) -> dict:
        return {
            "версия": OPERATOR_VERSION,
            "record_id": self.record_id,
            "поле": self.поле,
            "было_значение": self.было_значение,
            "было_сырьё": self.было_сырьё,
            "стало": self.стало,
            "оператор": self.оператор,
            "основание": self.основание,
            "время": self.время,
            "связка": self.связка,
        }


def _поле_записи(запись: dict, имя: str) -> dict:
    поля = запись.get("fields") or {}
    if имя not in поля:
        raise ДействиеНегодно(
            f"поля {имя!r} в записи нет; в ней есть: "
            + (", ".join(sorted(поля)) or "ни одного"))
    поле = поля[имя]
    return поле if isinstance(поле, dict) else {"value": поле, "raw": None}


def правка(запись: dict, действие: Действие) -> Правка:
    """Строит правку по действию. Запись при этом **не трогается**."""
    if действие.вид != ИСПРАВИТЬ:
        raise ДействиеНегодно(
            f"правку создаёт только исправление, а действие — {действие.вид!r}")
    было = _поле_записи(запись, действие.поле)
    if str(было.get("value")) == str(действие.стало):
        raise ДействиеНегодно(
            f"поле {действие.поле!r} уже равно {действие.стало!r}: правка, "
            "ничего не меняющая, засоряет доказательство")
    return Правка(
        record_id=запись.get("record_id", ""),
        поле=действие.поле,
        было_значение=(None if было.get("value") is None
                       else str(было.get("value"))),
        было_сырьё=(None if было.get("raw") is None else str(было.get("raw"))),
        стало=str(действие.стало),
        оператор=действие.оператор,
        основание=действие.основание,
        время=действие.время,
        связка=действие.связка)


def исправленная(запись: dict, правки) -> dict:
    """Производная копия записи с наложенными правками.

    **Первичная запись не меняется.** Возвращается новая, и в ней прямо
    сказано, что она производная и чем отличается: иначе однажды её примут за
    разобранное станком, и продукт лишится того единственного, что продаёт.
    """
    правки = tuple(правки)
    копия = {ключ: значение for ключ, значение in запись.items()}
    копия["fields"] = {имя: (dict(поле) if isinstance(поле, dict) else поле)
                       for имя, поле in (запись.get("fields") or {}).items()}
    for п in правки:
        поле = копия["fields"].get(п.поле)
        if not isinstance(поле, dict):
            поле = {"value": поле, "raw": None}
            копия["fields"][п.поле] = поле
        поле["value"] = п.стало
        поле["исправлено_оператором"] = True
    from .derived import пометить

    копия = пометить(копия, запись.get("record_id", ""))
    копия["исправления"] = [п.as_json() for п in правки]
    return копия


# ------------------------------------------------------------- итог


@dataclass(frozen=True, slots=True)
class ИтогДействия:
    """Чем кончилось действие: что стало с решением и что легло отдельно."""

    действие: Действие
    решение: object | None = None
    правка: Правка | None = None
    событие: dict = field(default_factory=dict)

    def as_json(self) -> dict:
        return {
            "действие": self.действие.as_json(),
            "статус": getattr(self.решение, "статус", None),
            "правка": self.правка.as_json() if self.правка else None,
            "событие": dict(self.событие),
        }


def _событие(действие: Действие, было: str | None, стало: str | None) -> dict:
    return {
        "версия": OPERATOR_VERSION,
        "действие": действие.вид,
        "оператор": действие.оператор,
        "время": действие.время,
        "основание": действие.основание,
        "record_id": действие.record_id,
        "было": было,
        "стало": стало,
        "связка": действие.связка,
        "в_связке": действие.в_связке,
    }


def _проверить_роль(действие: Действие) -> None:
    """Роль ограничивает действия. Не названа — не ограничивает ничего.

    Отсутствие роли не выдумывается за оператора: там, где ролей ещё нет,
    действие исполняется, и это видно в журнале пустой ролью. Названная роль
    принуждается: разметчик не допустит записи, администратор не подменит
    чужое решение.
    """
    if действие.роль is None:
        return
    from .roles import проверить_право

    проверить_право(действие.роль, действие.вид)


def исполнить(действие: Действие, запись: dict | None = None,
              решение=None) -> ИтогДействия:
    """Исполняет одно действие. Ничего не хранит и ничего не переписывает.

    Статус рождается там же, где и всегда, — в движке политик: подтверждение и
    отклонение проходят через него, а не ставят статус здесь. Иначе у статуса
    появилось бы второе место рождения, и правило «единственного места»
    перестало бы быть правилом.
    """
    _проверить_роль(действие)
    if действие.вид == ВЕРНУТЬ_ОСНАСТКУ:
        raise ДействиеНегодно(
            "возврат оснастки исполняется не над записью: для него есть "
            "«вернуть_оснастку», и ни одного статуса он не меняет")
    if запись is None:
        raise ДействиеНегодно(f"действие {действие.вид!r} требует записи")
    if (запись.get("record_id") or "") != действие.record_id:
        raise ДействиеНегодно(
            f"действие обращено к записи {действие.record_id!r}, а подана "
            f"{запись.get('record_id')!r}")

    было = getattr(решение, "статус", None)

    if действие.вид == ПОДТВЕРДИТЬ:
        новое = реш.допустить_вручную(решение, действие.оператор,
                                      действие.основание, действие.время)
        return ИтогДействия(действие, новое, None,
                            _событие(действие, было, новое.статус))

    if действие.вид == ОТКЛОНИТЬ:
        новое = реш.отклонить_вручную(решение, действие.оператор,
                                      действие.основание, действие.время)
        return ИтогДействия(действие, новое, None,
                            _событие(действие, было, новое.статус))

    своя = правка(запись, действие)
    # Исправление само по себе статуса не рождает: правка — это утверждение о
    # значении, а не о судьбе записи. Что с записью делать дальше, оператор
    # говорит отдельным действием, и это видно в журнале двумя событиями.
    событие = _событие(действие, своя.было_значение, своя.стало)
    событие["поле"] = действие.поле
    return ИтогДействия(действие, решение, своя, событие)


# ------------------------------------------------------------- связки


def по_связке(действие: Действие, record_ids, ожидалось: int) -> tuple:
    """Размножает решение оператора на всю связку одинаковых сомнений.

    ``ожидалось`` — число, которое оператор назвал **до** применения. Не сошлось
    с длиной связки — отказ: молчаливое «применить ко всем» превращает решение
    человека в неподотчётную массовую правку, а связка могла измениться с тех
    пор, как он на неё смотрел.

    Каждой записи достаётся своё действие со своим ``record_id``: в журнале
    остаётся столько событий, сколько записей затронуто, а не одно на всех.
    """
    record_ids = tuple(record_ids)
    if not действие.связка:
        raise ДействиеНегодно(
            "применение по связке требует названной связки: без неё непонятно, "
            "что у этих записей общего")
    if ожидалось != len(record_ids):
        raise ДействиеНегодно(
            f"оператор назвал {ожидалось} записей, а в связке {len(record_ids)}: "
            "применение по связке делается осознанно, а не молча")
    if действие.record_id and действие.record_id not in record_ids:
        raise ДействиеНегодно(
            "запись, с которой начали, в связку не входит")
    return tuple(
        replace(действие, record_id=record_id, в_связке=len(record_ids))
        for record_id in record_ids)


# --------------------------------------------------- возврат оснастки


@dataclass(frozen=True, slots=True)
class ВозвратОснастки:
    """Сигнал: виновата настройка, а не документ.

    Возврат не меняет ни одного статуса записи. Записи остаются ждать человека
    и будут перепроведены новой версией оснастки — они не виноваты, и
    отклонять их значило бы наказать документ за нашу же настройку.
    """

    семейство: str
    версия_оснастки: str
    оператор: str
    основание: str
    время: str
    замечено_на: tuple = ()
    затронуто_записей: int = 0

    @property
    def меняет_статусы(self) -> bool:
        """Всегда ложь. Свойство существует, чтобы это было видно в коде."""
        return False

    def as_json(self) -> dict:
        return {
            "версия": OPERATOR_VERSION,
            "семейство": self.семейство,
            "версия_оснастки": self.версия_оснастки,
            "оператор": self.оператор,
            "основание": self.основание,
            "время": self.время,
            "замечено_на": list(self.замечено_на),
            "затронуто_записей": self.затронуто_записей,
            "меняет_статусы": self.меняет_статусы,
            "записи_ждут_новой_оснастки": True,
        }


def вернуть_оснастку(действие: Действие, затронуто_записей: int = 0
                     ) -> ВозвратОснастки:
    """Обращает действие в сигнал о негодной настройке."""
    _проверить_роль(действие)
    if действие.вид != ВЕРНУТЬ_ОСНАСТКУ:
        raise ДействиеНегодно(
            f"возврат оснастки — отдельное действие, а подано {действие.вид!r}")
    return ВозвратОснастки(
        семейство=действие.семейство,
        версия_оснастки=действие.версия_оснастки,
        оператор=действие.оператор,
        основание=действие.основание,
        время=действие.время,
        замечено_на=((действие.record_id,) if действие.record_id else ()),
        затронуто_записей=затронуто_записей)


def оснастка_на_доработке(возвраты, семейство: str, версия: str) -> bool:
    """Возвращена ли эта версия оснастки на доработку.

    Пока возвращена, её разбор считается сомнительным целиком: одна и та же
    негодная настройка касается всех записей, разобранных ею, а не тех, на
    которых её заметили.
    """
    return any(в.семейство == семейство and в.версия_оснастки == версия
               for в in возвраты)


# --------------------------------------------------------------- свод


def свод(итоги, возвраты=()) -> dict:
    """Что сделал человек: по видам действий, правкам и возвратам."""
    итоги = tuple(итоги)
    по_видам = {вид: sum(1 for и in итоги if и.действие.вид == вид)
                for вид in ДЕЙСТВИЯ}
    по_связкам = sum(1 for и in итоги if и.действие.связка)
    return {
        "версия": OPERATOR_VERSION,
        "действий": len(итоги),
        "по_видам": по_видам,
        "правок": sum(1 for и in итоги if и.правка is not None),
        "по_связкам": по_связкам,
        "возвратов_оснастки": len(tuple(возвраты)),
        "операторов": sorted({и.действие.оператор for и in итоги}),
    }


