# -*- coding: utf-8 -*-
"""Карта покрытия источника: ожидаемое против обнаруженного.

Шаг 34 плана. Нормативная основа — чертёж v3.0, раздел 8.

**Главная слепая зона станка.** Балансы, подпись и цепной хеш заверяют то, что
найдено, и молчат о том, что не найдено. Ненайденная строка не оставляет следа
нигде — ни в суммах, ни в хешах, ни в журнале.

**Почему одного реестра обнаруженного мало.** Объявление «исчезнувших строк не
существует» само себя не исполняет. Если разборщик не увидел строку, он не
присвоит ей статус: не увиденное не попадает даже в перечень исключений. Карта
покрытия, построенная только на находках разборщика, отчитывается ровно о том,
что и так известно, и потому не стоит ничего.

**Отсюда устройство этого места.** Ожидаемое оценивается **независимо** от того,
что нашлось. Независимость здесь имеет точный смысл: счёт ведётся по сырому
источнику, минуя адаптер и сегментатор, другим кодом и другим способом. Если
адаптер потерял строку, два счёта разойдутся — и расхождение станет видимым.

Три вида ожиданий, и все три не зависят от разбора:

1. **Объявленное самим источником** — число проводок в сообщении, размер листа,
   число страниц. Это написал тот, кто источник создал, ещё до нас.
2. **Структурный пересчёт сырых байтов** — сколько в разметке элементов строк,
   сколько меток проводок, сколько показов текста. Считается прямым проходом,
   без разбора смыслов.
3. **Расхождение самих оценок между собой** — если объявленное и пересчитанное
   не сходятся, испорчен уже источник, и это тоже надо знать.

**Что обязано быть у каждого расхождения.** Причина. Разница между ожидаемым и
обнаруженным либо объяснена исключением с прямо названной причиной, либо
попадает в **необъяснённое**. Третьего не дано: строк, которые просто исчезли,
существовать не должно.

Статусы полноты (complete, partial, unknown) здесь не выставляются — это шаг 35.
Карта отдаёт факты, по которым статус потом ставится.

**Чем этот способ не является.** Независимая оценка — тоже детектор, и у неё
свои слепые пятна. Два независимых слепых пятна лучше одного, но доказательством
полноты не являются. Раздел 8.2 прямо требует метрику потери покрытия на
закрытом корпусе, и без корпуса полнота недоказуема.
"""

from __future__ import annotations

import re
import zipfile
from dataclasses import dataclass, field


COVERAGE_VERSION = "coverage-map/1"

KNOWN_LIMITATIONS = (
    "Независимая оценка — тоже детектор. Она считает сырую разметку прямым "
    "проходом и может ошибиться там же, где ошибётся адаптер, если оба неверно "
    "понимают формат. Совпадение двух счётов уменьшает риск, но полноты не "
    "доказывает.",
    "Метрика потери покрытия на закрытом корпусе не измерена: корпуса нет. "
    "Раздел 8.2 требует её прямо, и без неё полнота недоказуема.",
    "Ожидания для страничных источников считаются по числу показов текста, а не "
    "по числу строк выписки: сколько показов образуют строку, знает шаблон "
    "семейства (шаг 37). Поэтому для PDF сверяются объекты, а не записи.",
    "Продолжения таблиц между страницами не учитываются — это шаг 36.",
)


@dataclass(frozen=True, slots=True)
class Ожидание:
    """Сколько объектов ожидается, и на каком основании.

    ``откуда`` обязано называть **независимый** источник оценки: объявление
    самого документа или прямой пересчёт сырой разметки. Оценка, взятая у
    разбора, ожиданием не является — она пересказывает находки.
    """

    вид: str
    сколько: int
    откуда: str
    основание: str = ""

    def as_json(self) -> dict:
        return {"вид": self.вид, "сколько": self.сколько,
                "откуда": self.откуда, "основание": self.основание}


@dataclass(frozen=True, slots=True)
class Исключение:
    """Объект, намеренно не вошедший в разбор, и причина.

    Причина обязательна. Исключение без причины — это и есть исчезнувшая
    строка, только записанная в столбик.
    """

    адрес: str
    вид: str
    причина: str

    def as_json(self) -> dict:
        return {"адрес": self.адрес, "вид": self.вид, "причина": self.причина}


@dataclass(frozen=True, slots=True)
class Расхождение:
    """Разница между ожидаемым и обнаруженным по одному виду объектов."""

    вид: str
    ожидалось: int
    обнаружено: int
    объяснено: int
    откуда_ожидание: str

    @property
    def необъяснено(self) -> int:
        return self.ожидалось - self.обнаружено - self.объяснено

    @property
    def сходится(self) -> bool:
        return self.необъяснено == 0

    def as_json(self) -> dict:
        return {
            "вид": self.вид,
            "ожидалось": self.ожидалось,
            "обнаружено": self.обнаружено,
            "объяснено": self.объяснено,
            "необъяснено": self.необъяснено,
            "откуда_ожидание": self.откуда_ожидание,
        }


@dataclass(frozen=True, slots=True)
class КартаПокрытия:
    """Реестр ожидаемого и обнаруженного с причиной по каждому исключению."""

    schema_version: str = COVERAGE_VERSION
    ожидания: tuple[Ожидание, ...] = ()
    обнаружено: tuple[tuple[str, int], ...] = ()
    исключения: tuple[Исключение, ...] = ()
    расхождения: tuple[Расхождение, ...] = ()
    споры_ожиданий: tuple[str, ...] = ()

    @property
    def необъяснённое(self) -> int:
        """Сколько объектов исчезло без объяснения. Ноль — и только ноль."""
        return sum(max(0, р.необъяснено) for р in self.расхождения)

    @property
    def лишнее(self) -> int:
        """Сколько обнаружено сверх ожидаемого.

        Тоже беда, и не меньшая: лишнее означает, что либо оценка слепа, либо
        разбор придумал объекты, которых в источнике нет.
        """
        return sum(max(0, -р.необъяснено) for р in self.расхождения)

    @property
    def всё_объяснено(self) -> bool:
        return self.необъяснённое == 0 and self.лишнее == 0

    def as_json(self) -> dict:
        return {
            "schema_version": self.schema_version,
            "ожидания": [о.as_json() for о in self.ожидания],
            "обнаружено": dict(self.обнаружено),
            "исключения": [и.as_json() for и in self.исключения],
            "расхождения": [р.as_json() for р in self.расхождения],
            "необъяснённое": self.необъяснённое,
            "лишнее": self.лишнее,
            "всё_объяснено": self.всё_объяснено,
            "споры_ожиданий": list(self.споры_ожиданий),
        }


# ------------------------------------------------------------- сборка карты


def построить(ожидания, сегментация=None, исключения=(), обнаружено=None) -> КартаПокрытия:
    """Складывает карту из независимых ожиданий и того, что нашёл разбор.

    ``сегментация`` даёт и обнаруженное, и часть исключений: неразобранное там
    уже несёт причину по каждому объекту, и переписывать её заново незачем.
    """
    ожидания = tuple(ожидания)
    свои_исключения = list(исключения)
    найдено: dict[str, int] = dict(обнаружено or {})

    if сегментация is not None:
        найдено.setdefault("объект источника", _учтено_содержательно(сегментация))
        найдено.setdefault("страница", len(сегментация.страницы))
        найдено.setdefault("запись", len(сегментация.кандидаты))
        for н in сегментация.неразобранное:
            свои_исключения.append(
                Исключение(н.адрес, "объект источника", н.причина))

    объяснено: dict[str, int] = {}
    for исключение in свои_исключения:
        объяснено[исключение.вид] = объяснено.get(исключение.вид, 0) + 1

    расхождения = []
    for ожидание in ожидания:
        расхождения.append(Расхождение(
            ожидание.вид, ожидание.сколько,
            найдено.get(ожидание.вид, 0),
            объяснено.get(ожидание.вид, 0),
            ожидание.откуда))

    return КартаПокрытия(
        COVERAGE_VERSION, ожидания,
        tuple(sorted(найдено.items())), tuple(свои_исключения),
        tuple(расхождения), _споры(ожидания))


def _учтено_содержательно(сегментация) -> int:
    """Сколько объектов источника разложено по строкам.

    Устройство (страницы) сюда не входит: это разметка, а не содержимое.
    Неразобранное тоже не входит — оно учитывается исключениями.
    """
    return sum(len(строка.ячейки) for строка in сегментация.строки)


def _споры(ожидания) -> tuple[str, ...]:
    """Оценки одного и того же вида, не сошедшиеся между собой.

    Если объявленное источником и пересчитанное по разметке расходятся, спорить
    надо не о разборе, а об источнике: он уже испорчен или понят неверно.
    Молча выбрать «более правдоподобную» оценку нельзя — это догадка.
    """
    по_видам: dict[str, list] = {}
    for ожидание in ожидания:
        по_видам.setdefault(ожидание.вид, []).append(ожидание)
    споры = []
    for вид, свои in sorted(по_видам.items()):
        значения = {о.сколько for о in свои}
        if len(значения) > 1:
            откуда = ", ".join(f"{о.откуда}={о.сколько}" for о in свои)
            споры.append(f"{вид}: оценки не сошлись между собой ({откуда})")
    return tuple(споры)


# ---------------------------------------- независимые оценки ожидаемого
#
# Всё ниже читает СЫРОЙ источник и не пользуется ни адаптерами, ни
# сегментатором. В этом весь смысл: если адаптер потерял строку, здешний счёт
# её всё равно увидит, и расхождение станет видимым.

_XLSX_СТРОКА = re.compile(rb"<row[\s>]")
_XLSX_ЯЧЕЙКА = re.compile(rb"<c[\s>]")
_XLSX_РАЗМЕР = re.compile(rb'<dimension\s+ref="([A-Z]+)(\d+):([A-Z]+)(\d+)"')
_MT940_ПРОВОДКА = re.compile(rb"^:61:", re.MULTILINE)
_OFX_ПРОВОДКА = re.compile(rb"<STMTTRN>", re.IGNORECASE)
_CAMT_ПРОВОДКА = re.compile(rb"<(?:\w+:)?Ntry[\s>]")
_CAMT_ОБЪЯВЛЕНО = re.compile(rb"<(?:\w+:)?NbOfNtries>\s*(\d+)\s*<")
_PDF_СТРАНИЦА = re.compile(rb"/Type\s*/Page[^s]")
_PDF_ПОКАЗ = re.compile(rb"(?:Tj|TJ|'|\")\s")


def ожидания_из_книги(данные: bytes) -> tuple[Ожидание, ...]:
    """Строки и ячейки книги, посчитанные прямо по разметке листов."""
    строк = ячеек = 0
    объявлено_строк = 0
    try:
        with zipfile.ZipFile(__import__("io").BytesIO(данные)) as пакет:
            for имя in пакет.namelist():
                if not имя.startswith("xl/worksheets/") or not имя.endswith(".xml"):
                    continue
                лист = пакет.read(имя)
                строк += len(_XLSX_СТРОКА.findall(лист))
                ячеек += len(_XLSX_ЯЧЕЙКА.findall(лист))
                размер = _XLSX_РАЗМЕР.search(лист)
                if размер:
                    объявлено_строк += (int(размер.group(4)) - int(размер.group(2)) + 1)
    except (zipfile.BadZipFile, OSError, ValueError):
        return ()

    ожидания = [
        Ожидание("объект источника", ячеек, "пересчёт разметки листов",
                 "число элементов ячеек в сырой разметке"),
        Ожидание("запись", строк, "пересчёт разметки листов",
                 "число элементов строк в сырой разметке"),
    ]
    if объявлено_строк:
        ожидания.append(Ожидание(
            "запись", объявлено_строк, "объявленный размер листа",
            "поле dimension, записанное создателем книги"))
    return tuple(ожидания)


def ожидания_из_mt940(данные: bytes) -> tuple[Ожидание, ...]:
    """Проводки сообщения, посчитанные по меткам :61:."""
    сколько = len(_MT940_ПРОВОДКА.findall(данные))
    return (Ожидание("проводка", сколько, "пересчёт меток сообщения",
                     "число полей :61: в сыром тексте"),)


def ожидания_из_ofx(данные: bytes) -> tuple[Ожидание, ...]:
    сколько = len(_OFX_ПРОВОДКА.findall(данные))
    return (Ожидание("проводка", сколько, "пересчёт меток сообщения",
                     "число меток STMTTRN в сыром тексте"),)


def ожидания_из_camt(данные: bytes) -> tuple[Ожидание, ...]:
    """Проводки сообщения: и пересчитанные, и объявленные самим банком."""
    ожидания = [Ожидание(
        "проводка", len(_CAMT_ПРОВОДКА.findall(данные)),
        "пересчёт разметки сообщения", "число элементов Ntry в сырой разметке")]
    объявлено = _CAMT_ОБЪЯВЛЕНО.search(данные)
    if объявлено:
        ожидания.append(Ожидание(
            "проводка", int(объявлено.group(1)), "объявление самого банка",
            "поле NbOfNtries в сводке сообщения"))
    return tuple(ожидания)


def ожидания_из_csv(данные: bytes, кодировка: str = "utf-8",
                    есть_заголовок: bool = True) -> tuple[Ожидание, ...]:
    """Строки согласованного CSV, посчитанные по переводам строк."""
    try:
        текст = данные.decode(кодировка)
    except (UnicodeDecodeError, LookupError):
        return ()
    строки = [строка for строка in текст.splitlines() if строка.strip()]
    сколько = max(0, len(строки) - (1 if есть_заголовок and строки else 0))
    return (Ожидание("запись", сколько, "пересчёт строк файла",
                     "число непустых строк за вычетом заголовка"),)


def _без_литералов(поток: bytes, срок=None) -> bytes:
    """Убирает строковые литералы: оператора внутри строки не бывает.

    Без этого «Tj» внутри текста документа сошло бы за оператор вывода, и
    оценка кричала бы о пропаже там, где ничего не пропало.
    """
    итог = bytearray()
    место, длина = 0, len(поток)
    while место < длина:
        if срок is not None:
            срок.тик()
        знак = поток[место : место + 1]
        if знак == b"(":
            глубина, место = 1, место + 1
            while место < длина and глубина:
                if срок is not None:
                    срок.тик()
                текущий = поток[место : место + 1]
                if текущий == b"\\":
                    место += 2
                    continue
                if текущий == b"(":
                    глубина += 1
                elif текущий == b")":
                    глубина -= 1
                место += 1
            итог += b" "
            continue
        if знак == b"<" and поток[место : место + 2] != b"<<":
            конец = поток.find(b">", место)
            место = конец + 1 if конец >= 0 else длина
            итог += b" "
            continue
        итог += знак
        место += 1
    return bytes(итог)


def ожидания_из_pdf(данные: bytes, срок=None) -> tuple[Ожидание, ...]:
    """Страницы и показы текста, посчитанные по сырому файлу.

    Считаются **только потоки содержимого страниц**. Счёт по всем потокам файла
    даёт ложную тревогу: в таблицах толкования шрифтов и прочих служебных
    потоках те же две буквы встречаются во множестве, и оценка кричала бы о
    сотне пропаж там, где не пропало ничего. Ложная тревога в карте покрытия
    опаснее молчания: она приучает не смотреть.

    Показ текста — это не строка выписки: сколько показов образуют строку,
    знает шаблон семейства. Поэтому для страничных источников сверяются
    объекты, а не записи.
    """
    from .deadline import место as срок_места
    from .pdfread import PDFНеЧитается, прочитать

    # Пересчёт идёт тем же путём, что и чтение: по местам в потоке. Значит, и
    # стеречь его надо тем же — иначе независимый счёт стал бы тем единственным
    # местом, где станок снова умеет молчать.
    свой = срок if срок is not None else срок_места("чтение устройства PDF")
    страниц = len(_PDF_СТРАНИЦА.findall(данные))
    показов = 0
    try:
        документ = прочитать(данные, свой)
    except PDFНеЧитается:
        документ = None
    if документ is not None:
        страниц = max(страниц, len(документ.страницы))
        for страница in документ.страницы:
            значение = страница.get("/Contents")
            список = значение if isinstance(значение, list) else [значение]
            for ссылка in список:
                поток = документ.поток(ссылка)
                if поток:
                    показов += len(_PDF_ПОКАЗ.findall(_без_литералов(поток, свой)))

    ожидания = [Ожидание("страница", страниц, "пересчёт объектов файла",
                         "число объектов с типом Page")]
    if показов:
        ожидания.append(Ожидание(
            "объект источника", показов, "пересчёт операторов вывода",
            "число операторов показа текста в потоках содержимого"))
    return tuple(ожидания)


