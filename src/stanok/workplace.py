def очередь_html(свод_очереди: dict) -> str:
    строки = ["<h1>Очередь</h1>"]
    сл = свод_очереди["следующее_действие"]
    # Карточка ведёт туда, куда зовёт. Прежде она была простым блоком: человек
    # нажимал на «Разобрать группу» и не попадал никуда — а это первое место,
    # куда он нажмёт.
    куда = сл.get("куда") or "/группа"
    строки.append(
        f'<div class="glavnoe"><a class="chto" href="{_т(куда)}">'
        f'{_т(сл["что"])}</a>'
        f'<div class="tih">{_т(сл["почему"])}</div></div>')
    from .oblik import ЦВЕТ_ОЧЕРЕДИ

    строки.append('<div class="plitki">')
    for имя in ОЧЕРЕДИ:
        сколько = свод_очереди["счётчики"][имя]
        единица = свод_очереди["единицы"][имя]
        цвет = ЦВЕТ_ОЧЕРЕДИ.get(имя, "pl-seraya") if сколько else "pl-seraya"
        куда = КУДА_ОЧЕРЕДЬ.get(имя, "/")
        строки.append(
            f'<a class="plitka {цвет}" href="{_т(куда)}">'
            f'<div class="p">{_т(имя)}</div>'
            f'<div class="n">{сколько}</div>'
            f'<div class="p" style="margin:6px 0 0;text-transform:none;'
            f'letter-spacing:0">{_т(единица)}</div></a>')
    строки.append("</div>")
    строки.append(f'<p class="tih">{_т(свод_очереди["оговорка"])}. '
                  f'Групп однородных сомнений: {свод_очереди["групп"]}.</p>')
    return "".join(строки)


def группа_html(группа: РаскрытаяГруппа) -> str:
    """Раскрытие группы: все шесть пунктов части V, ни одного пропущенного."""
    строки = ["<h1>Группа однородных сомнений</h1>",
              '<table class="raskrytie">']
    for имя, значение in (
            ("Правило группировки", группа.правило),
            ("Шаблон", f"{группа.шаблон}, версия {группа.версия_шаблона}"),
            ("Затронуто", f"{группа.документов} док., {группа.записей} зап."),
            ("Критические поля",
             ", ".join(группа.критические) or "денежных и датированных нет"),
            ("Ожидаемое изменение", группа.ожидаемое)):
        строки.append(f"<tr><th>{_т(имя)}</th><td>{_т(значение)}</td></tr>")
    строки.append("</table>")

    строки.append("<h2>Примеры</h2><table><tr><th>Откуда</th>"
                  "<th>В источнике</th><th>Прочитано</th><th>Место</th></tr>")
    for п in группа.примеры:
        строки.append(
            f"<tr><td>{_т(п.откуда)}</td><td><code>{_т(п.сырьё)}</code></td>"
            f"<td><code>{_т(п.значение)}</code></td>"
            f"<td class=tih>{_т(п.место)}</td></tr>")
    строки.append("</table>")
    строки.append(f'<div class="knopka">{_т(группа.надпись_кнопки)}</div>')
    строки.append('<p class="tih">Число записей называет оператор. Не сошлось '
                  "— отказ. Решение отменяемо: отмена не стирает прежнее.</p>")
    return "".join(строки)


def разбор_html(экран, контекст: Контекст) -> str:
    """Режим 3: слева источник с уровнем, справа значения и причина словами."""
    строки = ['<h1>Разбор записи</h1><div class="dve">']

    строки.append('<div class="istochnik"><h2>Источник</h2>')
    строки.append(f'<p class="tih">{_т(контекст.место)} — уровень: '
                  f'<b>{_т(контекст.уровень)}</b></p>')
    строки.append("<pre>")
    for номер, с in enumerate(контекст.строки):
        метка = " class=otmecheno" if номер == контекст.отмеченная else ""
        строки.append(f"<span{метка}>{_т(с)}</span>\n")
    строки.append("</pre>")
    строки.append(f'<p class="tih">Видно: {_т(контекст.что_видно)}.<br>'
                  f"Не видно: {_т(контекст.чего_не_видно)}.</p>")
    строки.append('<p class="tih">Уровни: '
                  + " → ".join(f"<b>{_т(у)}</b>" if у == контекст.уровень
                               else _т(у) for у in УРОВНИ) + "</p></div>")

    строки.append('<div class="znachenia"><h2>Значения</h2>')
    главное = экран.главное
    if главное is not None:
        # Распознанное и итоговое значения в станке совпадают: между
        # распознаванием и выдачей значение не меняется. Прежде они стояли
        # двумя строками с одним и тем же числом — одно значение выглядело
        # двумя подтверждениями. Теперь совпадение сказано словами.
        распознанное = _значение_поля(экран, главное.поле)
        строки.append("<table>")
        for имя, значение in (("Исходное написание", главное.сырьё or ""),
                              ("Распознанное", распознанное)):
            строки.append(f"<tr><th>{_т(имя)}</th>"
                          f"<td><code>{_т(значение)}</code></td></tr>")
        строки.append(
            '<tr><th>Итоговое</th><td><code>' + _т(распознанное) + "</code>"
            '<div class="tih">то же значение: между распознаванием и выдачей '
            "оно не меняется</div></td></tr>")
        строки.append("</table>")
        строки.append(f'<div class="prichina"><b>Причина сомнения.</b> '
                      f"{_т(главное.словами)}</div>")
    else:
        строки.append('<p class="tih">Сомнений по этой записи нет.</p>')
    строки.append('<div class="deystvia">Подтвердить · Исправить · '
                  "Отклонить · Вернуть шаблон<br>"
                  '<span class="tih">К каждому — основание одной строкой</span>'
                  "</div></div></div>")
    return "".join(строки)


