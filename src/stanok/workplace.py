"""Рабочее место оператора: очередь и разбор исключений.

Шаг 79 плана. Нормативная основа — ТЗ на интерфейс станка, редакция 1.0,
части III (режимы 1 и 3) и V (групповое решение).

## Почему разбор по одной записи обесценил бы всю работу

На первом семействе документов **почти треть записей уходит человеку**, и
уходит не порознь: 182 записи одного настоящего документа отличаются друг от
друга только числами в одной и той же двоякой дате. Экран, где их разбирают по
одной, превращает работу станка в работу писца.

Поэтому главный предмет этого места — не запись, а **группа**. Запись
открывается тогда, когда группа не помогла.

## Контекст источника раздвигается, а не показывается куском

Показать только область поля — опасно: значение может быть **прочитано верно, а
относиться к другой строке**, и по одному полю этого не увидеть никогда. Потому
контекст имеет пять уровней, и оператор раздвигает его сам:

:data:`ПОЛЕ` → :data:`СТРОКА` → :data:`СОСЕДИ` → :data:`ТАБЛИЦА` →
:data:`СТРАНИЦА`

Каждый уровень честно говорит, что именно видно и чего не видно: «видна одна
строка, соседних не видно» — не украшение, а предупреждение о слепом пятне.

## Групповое решение раскрывается целиком

Ввод числа защищает от случайного нажатия, но **не доказывает однородность
группы**. Поэтому перед применением показывается всё шесть пунктов части V ТЗ:
правило группировки, шаблон с версией, число документов и записей, примеры из
начала, середины и конца, критические денежные и датированные поля, ожидаемое
изменение. Кнопка называет число прямо: «Применить решение к 182 записям этой
группы».

Решение **отменяемо**: отмена не стирает прежнее, а кладёт поверх своё событие
— по тому же правилу, по которому исправление не переписывает первичный
результат (шаги 57 и 58).
"""

