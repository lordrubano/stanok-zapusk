def _сейчас_строкой() -> str:
    from datetime import datetime, timezone

    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _по_важности(связки) -> tuple:
    """Читаемые текущее["группы"] впереди служебной.

    Крупнейшая связка на любом документе — «слагаемое допуска не выполнено»:
    её даёт движок политик каждой записи, ушедшей человеку. Разбирать её
    оператору незачем — она о том, что автодопуск выключен, а не о документе.
    Стоя первой, она уводит человека разбирать не то, и это названо дефектом
    в разборе первых прогонов.

    Порядок здесь меняется, а сами связки — нет: их считает шаг 55.
    """
    свои = list(связки)
    служебные = [с for с in свои if с.род == console.НЕ_ХВАТАЕТ_СЛАГАЕМОГО]
    читаемые = [с for с in свои if с.род != console.НЕ_ХВАТАЕТ_СЛАГАЕМОГО]
    return tuple([*читаемые, *служебные])


def _спорное_поле(экран) -> str:
    """Поле, из-за которого запись открыта. Оператору его подставляем."""
    for сомнение in getattr(экран, "сомнения", ()) or ():
        if getattr(сомнение, "поле", None):
            return str(сомнение.поле)
    return ""


def _записи_связки(связка) -> list[str]:
    """Записи связки без повторов: одна запись — одно решение."""
    свои: list[str] = []
    for имя in getattr(связка, "record_ids", ()) or ():
        if имя not in свои:
            свои.append(имя)
    return свои


def _поля_формы(тело: bytes, тип: str) -> dict:
    """Разбирает поданную форму. Своего разбора ровно столько, сколько нужно.

    Поля формы — такой же недоверенный вход, как имя файла (шаг 80): они
    приходят от того же, от кого документ, и обезвреживаются при показе теми же
    двойниками защит книги Excel.
    """
    from urllib.parse import parse_qs

    if "multipart/form-data" in (тип or ""):
        from .reception import _части_поданного

        свои = {}
        for имя, байты in _части_поданного(тело, тип):
            свои[имя] = байты.decode("utf-8", errors="replace").strip()
        return свои
    разобрано = parse_qs(тело.decode("utf-8", errors="replace"),
                         keep_blank_values=True)
    return {имя: значения[0] for имя, значения in разобрано.items()}


