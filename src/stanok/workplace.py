# --------------------------------------------------------- контекст


@dataclass(frozen=True, slots=True)
class Контекст:
    """Источник вокруг поля на одном из пяти уровней."""

    уровень: str
    место: str
    строки: tuple[str, ...]
    отмеченная: int | None
    что_видно: str
    чего_не_видно: str

    def as_json(self) -> dict:
        return {"уровень": self.уровень, "место": self.место,
                "строк": len(self.строки), "отмеченная": self.отмеченная,
                "что_видно": self.что_видно,
                "чего_не_видно": self.чего_не_видно}


def _строка_ячеек(фрагмент) -> str:
    return "  ".join(я.текст for я in фрагмент.ячейки if я.текст)


def строки_источника(проводка) -> tuple[tuple[int | None, str], ...]:
    """Строки документа с номерами страниц — для широких уровней контекста.

    Номер страницы здесь не украшение: без него уровень «страница» показал бы
    весь документ и назвал его страницей. Врать о том, что видно, нельзя —
    на этом держится вся польза расширяемого контекста.

    Берутся из той же сегментации, из которой собран экран: два разных
    источника строк дали бы два разных документа на одном экране.
    """
    свои = getattr(getattr(проводка, "сегментация", None), "строки", ())
    готовые = []
    for с in свои:
        текст = " ".join(я.текст for я in getattr(с, "ячейки", ()) if я.текст)
        готовые.append((getattr(с, "страница", None),
                        текст or str(getattr(с, "адрес", ""))))
    return tuple(готовые)


def раскрыть(экран, уровень: str = СОСЕДИ, строки_источника=()) -> Контекст:
    """Контекст источника нужного уровня.

    ``строки_источника`` — строки документа целиком; нужны для уровней
    «таблица» и «страница». Без них эти уровни честно говорят, что шире
    соседей не видно, — вместо того чтобы молча показать соседей и назвать их
    страницей.
    """
    if уровень not in УРОВНИ:
        raise ValueError(f"неизвестный уровень контекста: {уровень!r}. "
                         f"Известны: {', '.join(УРОВНИ)}")
    фрагмент = экран.фрагмент
    если_нет = Контекст(уровень, фрагмент.место or "место неизвестно", (),
                        None, "ничего", "источник не найден вовсе")
    if фрагмент is None or not фрагмент.ячейки and not фрагмент.выше:
        return если_нет

    своя = _строка_ячеек(фрагмент)

    if уровень == ПОЛЕ:
        отмеченные = [я.текст for я in фрагмент.ячейки if я.отмечена]
        видно = отмеченные or [своя]
        return Контекст(
            ПОЛЕ, фрагмент.место, tuple(видно), 0,
            "только само значение",
            "не видно, к той ли строке оно относится — раздвиньте до строки")

    if уровень == СТРОКА:
        return Контекст(
            СТРОКА, фрагмент.место, (своя,), 0,
            "вся строка записи",
            "не видно соседних строк — не проверить, не съехала ли граница "
            "операции")

    if уровень == СОСЕДИ:
        строки = (*фрагмент.выше, своя, *фрагмент.ниже)
        return Контекст(
            СОСЕДИ, фрагмент.место, строки, len(фрагмент.выше),
            "строка записи и её соседи сверху и снизу",
            "не видно таблицы целиком — не проверить, та ли это колонка")

    пары = [(с[0], str(с[1])) if isinstance(с, tuple) else (None, str(с))
            for с in строки_источника]
    if not пары:
        return Контекст(
            уровень, фрагмент.место, (*фрагмент.выше, своя, *фрагмент.ниже),
            len(фрагмент.выше), "строка записи и её соседи",
            f"шире не видно: строки источника для уровня «{уровень}» не поданы")

    if уровень == ТАБЛИЦА:
        свои = [т for _, т in пары]
        середина = _где_строка(свои, своя)
        начало = max(0, середина - СТРОК_ТАБЛИЦЫ // 2)
        кусок = свои[начало:начало + СТРОК_ТАБЛИЦЫ]
        return Контекст(
            ТАБЛИЦА, фрагмент.место, tuple(кусок), середина - начало,
            f"{len(кусок)} строк вокруг записи",
            "не видно верха страницы — не проверить заголовки колонок")

    # Страница — это именно та страница, где лежит запись, а не весь документ.
    номер = фрагмент.страница
    своя_страница = [т for стр, т in пары if стр == номер] if номер else []
    if not своя_страница:
        свои = [т for _, т in пары]
        середина = _где_строка(свои, своя)
        начало = max(0, середина - СТРОК_СТРАНИЦЫ // 2)
        кусок = свои[начало:начало + СТРОК_СТРАНИЦЫ]
        return Контекст(
            СТРАНИЦА, фрагмент.место, tuple(кусок), середина - начало,
            f"{len(кусок)} строк вокруг записи",
            "номер страницы у записи неизвестен: показано окно вокруг неё, "
            "а не страница целиком")

    середина = _где_строка(своя_страница, своя)
    урезано = ""
    if len(своя_страница) > СТРОК_СТРАНИЦЫ:
        начало = max(0, середина - СТРОК_СТРАНИЦЫ // 2)
        своя_страница = своя_страница[начало:начало + СТРОК_СТРАНИЦЫ]
        середина -= начало
        урезано = (f"страница длиннее {СТРОК_СТРАНИЦЫ} строк — показана "
                   "середина вокруг записи, и это сказано, а не скрыто")
    return Контекст(
        СТРАНИЦА, фрагмент.место, tuple(своя_страница), середина,
        f"страница {номер} целиком, {len(своя_страница)} строк",
        урезано or "шире страницы уровней нет: дальше — сам документ")


def _где_строка(строки, своя: str) -> int:
    for номер, с in enumerate(строки):
        if с == своя or (своя and своя in с):
            return номер
    return 0


def шире(уровень: str) -> str:
    """Следующий уровень наружу. У самого широкого — он же."""
    место = УРОВНИ.index(уровень)
    return УРОВНИ[min(место + 1, len(УРОВНИ) - 1)]


def уже(уровень: str) -> str:
    место = УРОВНИ.index(уровень)
    return УРОВНИ[max(место - 1, 0)]


# --------------------------------------------------------- группа


# Что считается критическим полем: деньги и даты. Ошибка в них дороже всех
# прочих, и в раскрытии группы они называются отдельно (часть V, пункт 5).
def _род_значения(значение) -> str | None:
    if isinstance(значение, (_дата.date, _дата.datetime)):
        return "дата"
    if isinstance(значение, Decimal):
        return "деньги"
    return None


@dataclass(frozen=True, slots=True)
class Пример:
    """Одна запись группы, показанная оператору как образец."""

    откуда: str
    record_id: str
    сырьё: str
    значение: str
    место: str

    def as_json(self) -> dict:
        return {"откуда": self.откуда, "record_id": self.record_id,
                "сырьё": self.сырьё, "значение": self.значение,
                "место": self.место}


@dataclass(frozen=True, slots=True)
class РаскрытаяГруппа:
    """Группа, раскрытая по всем шести пунктам части V ТЗ.

    Ввод числа защищает от случайного нажатия, но однородности не доказывает.
    Доказывает — вот это.
    """

    правило: str
    шаблон: str
    версия_шаблона: str
    документов: int
    записей: int
    примеры: tuple[Пример, ...]
    критические: tuple[str, ...]
    ожидаемое: str
    record_ids: tuple[str, ...] = ()

    @property
    def надпись_кнопки(self) -> str:
        """Кнопка называет число прямо, а не «решить все»."""
        return (f"Применить решение к {self.записей} "
                f"{_записей_дательный(self.записей)} этой группы")

    def as_json(self) -> dict:
        return {"версия": WORKPLACE_VERSION, "правило": self.правило,
                "шаблон": self.шаблон, "версия_шаблона": self.версия_шаблона,
                "документов": self.документов, "записей": self.записей,
                "примеры": [п.as_json() for п in self.примеры],
                "критические": list(self.критические),
                "ожидаемое": self.ожидаемое,
                "надпись_кнопки": self.надпись_кнопки}


def _записей_дательный(сколько: int) -> str:
    """«к 1 записи», «к 182 записям» — падеж кнопки применения."""
    сотня = сколько % 100
    if 11 <= сотня <= 14:
        return "записям"
    return "записи" if сколько % 10 == 1 else "записям"


def _записей_счётом(сколько: int) -> str:
    """«1 запись», «2 записи», «182 записи», «5 записей» — счёт."""
    сотня = сколько % 100
    if 11 <= сотня <= 14:
        return "записей"
    последняя = сколько % 10
    if последняя == 1:
        return "запись"
    if 2 <= последняя <= 4:
        return "записи"
    return "записей"


def _экран_по_id(экраны, record_id: str):
    for э in экраны:
        if э.record_id == record_id:
            return э
    return None


def примеры_группы(связка, экраны) -> tuple[Пример, ...]:
    """Начало, середина и конец группы — по пункту 4 части V.

    Три места нарочно: беда однородности живёт по краям. Показать три подряд с
    начала значило бы показать три раза одно и то же.
    """
    свои = list(связка.record_ids)
    if not свои:
        return ()
    места = [("из начала", 0)]
    if len(свои) > 2:
        места.append(("из середины", len(свои) // 2))
    if len(свои) > 1:
        места.append(("из конца", len(свои) - 1))

    готовые = []
    for откуда, место in места:
        экран = _экран_по_id(экраны, свои[место])
        if экран is None:
            continue
        сомнение = next((с for с in экран.сомнения if с.род == связка.род),
                        None)
        готовые.append(Пример(
            откуда, экран.record_id,
            (сомнение.сырьё if сомнение else "") or "",
            _значение_поля(экран, сомнение.поле if сомнение else None),
            экран.фрагмент.место if экран.фрагмент else "место неизвестно"))
    return tuple(готовые)


def _значение_поля(экран, поле: str | None) -> str:
    if not поле:
        return ""
    for п in экран.поля:
        if п.имя == поле:
            return "" if п.значение is None else str(п.значение)
    return ""


def критические_поля(связка, экраны) -> tuple[str, ...]:
    """Денежные и датированные поля затронутых записей — пункт 5 части V."""
    свои: dict[str, str] = {}
    for record_id in связка.record_ids:
        экран = _экран_по_id(экраны, record_id)
        if экран is None:
            continue
        for п in экран.поля:
            род = _род_значения(п.значение)
            if род:
                свои[п.имя] = род
    return tuple(f"{имя} ({род})" for имя, род in sorted(свои.items()))


def раскрыть_группу(связка, экраны, шаблон: str = "не назван",
                    версия_шаблона: str = "не названа",
                    документов: int = 1,
                    ожидаемое: str = "") -> РаскрытаяГруппа:
    """Складывает всё, что нужно увидеть до применения решения к группе."""
    правило = (f"одинаковый род сомнения: {связка.род}"
               + (f"; поля: {', '.join(связка.поля)}" if связка.поля else ""))
    если_нет = (f"все {связка.сколько} {_записей_счётом(связка.сколько)} "
                "группы получат одно и то же решение и одно основание; "
                "первичные значения не меняются, решение ложится отдельным "
                "слоем")
    return РаскрытаяГруппа(
        правило=правило,
        шаблон=шаблон,
        версия_шаблона=версия_шаблона,
        документов=документов,
        записей=связка.сколько,
        примеры=примеры_группы(связка, экраны),
        критические=критические_поля(связка, экраны),
        ожидаемое=ожидаемое or если_нет,
        record_ids=tuple(связка.record_ids))


# --------------------------------------------------------- отмена


@dataclass(frozen=True, slots=True)
class ОтменаГруппы:
    """Отмена группового решения. Не стирает прежнее, а кладёт поверх своё."""

    отменяет: str
    записей: int
    оператор: str
    время: str
    основание: str
    действия: tuple = field(default=())

    def as_json(self) -> dict:
        return {"версия": WORKPLACE_VERSION, "род": "отмена группы",
                "отменяет": self.отменяет, "записей": self.записей,
                "оператор": self.оператор, "время": self.время,
                "основание": self.основание}


def отменить_группу(итоги, оператор: str, время: str, основание: str,
                    ожидалось: int) -> ОтменаГруппы:
    """Отменяет групповое решение — по тем же правилам, что и применение.

    Число записей называет оператор, и оно сверяется: отмена не своей группы
    так же опасна, как её применение вслепую. Само отменяемое решение остаётся
    в истории — иначе отмена стала бы подчисткой.
    """
    свои = tuple(итоги)
    if len(свои) != ожидалось:
        raise ValueError(
            f"отмена не сошлась: названо {ожидалось}, а в группе {len(свои)}. "
            "Группа могла измениться с тех пор, как вы на неё смотрели")
    if not основание or len(основание.strip()) < 3:
        raise ValueError("отмена без основания не принимается: оно нужно тому, "
                         "кто будет разбираться потом")
    первое = свои[0] if свои else None
    отменяет = getattr(getattr(первое, "действие", None), "род", "групповое "
                       "решение")
    return ОтменаГруппы(отменяет=str(отменяет), записей=len(свои),
                        оператор=оператор, время=время,
                        основание=основание.strip(), действия=свои)


# --------------------------------------------------------- очередь


def очередь(проводка, экраны=None) -> dict:
    """Шесть счётчиков режима 1 и одно следующее действие.

    Числа — документы, кроме «проверить»: там записи. Партии как объекта учёта
    ещё нет (шаг 86), и потому счёт идёт по одному документу — на экране это
    сказано словами, а не скрыто.
    """
    экраны = console.собрать_экраны(проводка) if экраны is None else экраны
    состояние = getattr(проводка, "состояние_запуска", "")
    сорвалось = list(getattr(проводка, "сорвалось", ()))

    свои = {имя: 0 for имя in ОЧЕРЕДИ}
    if состояние == "blocked" or "разбор" in сорвалось:
        свои["заблокировано"] = 1
    elif экраны:
        # Записи, ушедшие человеку, а не все подряд. Прежде здесь стояло
        # число всех записей: плитка говорила 840 там, где человеку
        # уходит 231, и спорила с карточкой над собой на том же экране.
        свои["проверить"] = _ушло_человеку(экраны, проводка)
    elif состояние == "ok":
        свои["готово"] = 1
    else:
        свои["обрабатываются"] = 1

    # Группы — только из ждущих человека. Закрытая запись в группу не идёт:
    # иначе очередь предлагает разобрать то, что уже разобрано.
    группы = _по_важности(console.связки(
        [э for э in экраны if (э.статус or "review") == "review"]))
    return {
        "версия": WORKPLACE_VERSION,
        "счётчики": свои,
        "единицы": {и: ("записи" if и == "проверить" else "документы")
                    for и in ОЧЕРЕДИ},
        "следующее_действие": _следующее(свои, группы),
        "групп": len(группы),
        "оговорка": ("счёт идёт по одному документу: партии как объекта учёта "
                     "ещё нет"),
    }


def _ушло_человеку(экраны, проводка) -> int:
    """Сколько записей ждёт человека.

    Судья — движок политик (шаг 45): статус review и есть «ушло человеку».
    Решений нет вовсе — считаются записи с сомнением: это те же записи, потому
    что решение в review рождается ровно из неразрешённого сомнения.

    **Ноль — это ответ, а не отсутствие ответа.** Прежде здесь стояло «если
    насчитали ноль, считай по сомнениям», и оттого экран оператора, закрывшего
    все записи до единой, показывал их все ждущими: работа сделана, а очередь
    полна. Найдено проходом браузерного пути на настоящем документе.
    """
    решения = list(getattr(проводка, "решения", ()) or ())
    if решения:
        return sum(1 for р in решения
                   if getattr(р, "статус", None) == "review"
                   or not getattr(р, "статус_рождён", True))
    return sum(1 for э in экраны if э.сомнения)


def _следующее(счётчики, группы) -> dict:
    """Одно главное действие крупно — не список задач."""
    if счётчики.get("заблокировано"):
        return {"что": "Разобрать причину блокировки", "куда": "/журнал",
                "почему": "документ не прошёл разбор — дальше идти нельзя"}
    if счётчики.get("проверить"):
        сколько = счётчики["проверить"]
        if группы:
            первая = группы[0]
            return {
                "куда": "/группа",
                "что": f"Разобрать группу «{первая.род}» — {первая.сколько} "
                       f"{_записей_счётом(первая.сколько)}",
                "почему": (f"на проверке {сколько} {_записей_счётом(сколько)}, "
                           f"из них {первая.сколько} отличаются "
                           "только числами: это одно решение, а не "
                           f"{первая.сколько}")}
        return {"что": f"Разобрать {сколько} {_записей_счётом(сколько)}",
                "куда": "/запись",
                "почему": "групп не выделено — записи разные"}
    if счётчики.get("готово"):
        return {"что": "Проверить выпуск", "куда": "/выпуск",
                "почему": "разбор прошёл целиком"}
    return {"что": "Ждать", "куда": "/журнал",
            "почему": "идёт обработка"}


