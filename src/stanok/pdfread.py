# -*- coding: utf-8 -*-
"""Чтение устройства PDF: объекты, страницы, потоки содержимого.

Нижняя половина шага 28. Здесь только чтение устройства файла — без смыслов.
Верхняя половина, извлечение текста с координатами, лежит в ``adapter_pdf``.

Разбор свой, без сторонних библиотек. Причины те же, что и в шаге 27, плюс своя:
на машине нет ни одной библиотеки PDF, а добавление тяжёлой зависимости с
собственным разбором недоверенного входа — решение владельца, а не исполнителя.

Что читается: перекрёстные ссылки не разбираются вовсе. Объекты находятся
прямым проходом по файлу — так читается и файл с повреждённой таблицей ссылок,
и файл с приращениями, где таблица указывает на старую редакцию объекта.
Порядок прохода задан явно: при повторе номера берётся **последнее** вхождение,
то есть самая поздняя редакция объекта, как и предписывает приращение.
"""

from __future__ import annotations

import re
import zlib
from dataclasses import dataclass, field

from .deadline import место as срок_места


KNOWN_LIMITATIONS = (
    "Из способов сжатия потоков поддержан FlateDecode. Прочие (LZW, RunLength, "
    "ASCII85 и составные цепочки) не разжимаются: такая страница честно "
    "объявляется нечитаемой, а не выдаётся за пустую.",
    "Потоки объектов (ObjStm) не разбираются: объекты, спрятанные внутрь них, "
    "прямым проходом не находятся. Страницы такого файла объявляются "
    "ненайденными, а не молча пропускаются.",
    "Зашифрованный PDF не разбирается: это политика шага 23, и она его "
    "отвергает до разбора.",
)


class PDFНеЧитается(ValueError):
    """Файл не является читаемым PDF."""

    код = "E_PDF_UNREADABLE"


# ------------------------------------------------------------- лексика

_ОБЪЕКТ = re.compile(rb"(?<![0-9])(\d{1,10})\s+(\d{1,5})\s+obj\b")
_ССЫЛКА = re.compile(rb"(\d{1,10})\s+(\d{1,5})\s+R\b")
_ИМЯ = re.compile(rb"/([^\s/\[\]()<>{}]+)")
_ЧИСЛО = re.compile(rb"[-+]?\d*\.?\d+")


@dataclass(frozen=True, slots=True)
class Ссылка:
    номер: int
    поколение: int


@dataclass
class Объект:
    """Косвенный объект: словарь или иное значение, при нём — поток."""

    значение: object
    поток: bytes | None = None
    сырой_поток: bytes | None = None


def _пропустить_пробелы(данные: bytes, место: int, срок=None) -> int:
    """Проходит пробелы и примечания. Отметка срока здесь не лишняя.

    Порка нашла это место делом: стоит пропасть ветке «иначе», как цикл
    перестаёт продвигаться, и разбор виснет навсегда. Отметка стоит один
    оборот, а без неё у этого цикла нет ни одного места, где срок можно было
    бы спросить, — и молчание снова стало бы возможным исходом.
    """
    длина = len(данные)
    while место < длина:
        if срок is not None:
            срок.тик()
        знак = данные[место : место + 1]
        if знак in b" \t\r\n\f\x00":
            место += 1
        elif знак == b"%":
            конец = данные.find(b"\n", место)
            место = длина if конец < 0 else конец + 1
        else:
            break
    return место


def _разобрать_значение(данные: bytes, место: int, срок=None):
    """Разбирает одно значение PDF, возвращает (значение, новое место).

    Срок передаётся вглубь разбора, а не остаётся снаружи: зациклиться разбор
    может на любой глубине, и отметка нужна там, где крутится цикл.
    """
    место = _пропустить_пробелы(данные, место, срок)
    if место >= len(данные):
        return None, место
    знак = данные[место : место + 1]

    if знак == b"<" and данные[место : место + 2] == b"<<":
        return _разобрать_словарь(данные, место + 2, срок)
    if знак == b"<":
        конец = данные.find(b">", место)
        if конец < 0:
            raise PDFНеЧитается("незакрытая шестнадцатеричная строка")
        цифры = re.sub(rb"[^0-9A-Fa-f]", b"", данные[место + 1 : конец])
        if len(цифры) % 2:
            цифры += b"0"
        return bytes.fromhex(цифры.decode("ascii")), конец + 1
    if знак == b"(":
        return _разобрать_строку(данные, место, срок)
    if знак == b"[":
        массив, место = [], место + 1
        while True:
            if срок is not None:
                срок.тик()
            место = _пропустить_пробелы(данные, место, срок)
            if данные[место : место + 1] == b"]":
                return массив, место + 1
            if место >= len(данные):
                raise PDFНеЧитается("незакрытый массив")
            значение, место = _разобрать_значение(данные, место, срок)
            массив.append(значение)
    if знак == b"/":
        совпало = _ИМЯ.match(данные, место)
        if not совпало:
            return "", место + 1
        return "/" + совпало.group(1).decode("latin-1"), совпало.end()
    if данные[место : место + 4] == b"true":
        return True, место + 4
    if данные[место : место + 5] == b"false":
        return False, место + 5
    if данные[место : место + 4] == b"null":
        return None, место + 4

    ссылка = _ССЫЛКА.match(данные, место)
    if ссылка:
        return Ссылка(int(ссылка.group(1)), int(ссылка.group(2))), ссылка.end()
    число = _ЧИСЛО.match(данные, место)
    if число:
        текст = число.group(0)
        значение = float(текст) if b"." in текст else int(текст)
        return значение, число.end()
    return None, место + 1


def _разобрать_словарь(данные: bytes, место: int, срок=None):
    словарь = {}
    while True:
        if срок is not None:
            срок.тик()
        место = _пропустить_пробелы(данные, место, срок)
        if данные[место : место + 2] == b">>":
            return словарь, место + 2
        if место >= len(данные):
            raise PDFНеЧитается("незакрытый словарь")
        ключ, место = _разобрать_значение(данные, место, срок)
        if not isinstance(ключ, str) or not ключ.startswith("/"):
            continue
        значение, место = _разобрать_значение(данные, место, срок)
        словарь[ключ] = значение


def _разобрать_строку(данные: bytes, место: int, срок=None):
    место += 1
    куски = bytearray()
    глубина = 1
    while место < len(данные):
        if срок is not None:
            срок.тик()
        знак = данные[место]
        if знак == 0x5C:  # обратная косая
            следующий = данные[место + 1 : место + 2]
            подстановка = {b"n": b"\n", b"r": b"\r", b"t": b"\t", b"b": b"\b",
                           b"f": b"\f", b"(": b"(", b")": b")", b"\\": b"\\"}
            if следующий in подстановка:
                куски += подстановка[следующий]
                место += 2
                continue
            восьмеричные = re.match(rb"[0-7]{1,3}", данные[место + 1 : место + 4])
            if восьмеричные:
                куски.append(int(восьмеричные.group(0), 8) & 0xFF)
                место += 1 + len(восьмеричные.group(0))
                continue
            место += 2
            continue
        if знак == 0x28:
            глубина += 1
        elif знак == 0x29:
            глубина -= 1
            if глубина == 0:
                return bytes(куски), место + 1
        куски.append(знак)
        место += 1
    raise PDFНеЧитается("незакрытая строка")


# ------------------------------------------------------------- документ


@dataclass
class Документ:
    """Прочитанное устройство файла: объекты и страницы."""

    объекты: dict[int, Объект] = field(default_factory=dict)
    страницы: list[dict] = field(default_factory=list)
    зашифрован: bool = False

    def раскрыть(self, значение):
        """Разворачивает косвенную ссылку до значения."""
        видано = set()
        while isinstance(значение, Ссылка):
            if значение.номер in видано:
                return None
            видано.add(значение.номер)
            объект = self.объекты.get(значение.номер)
            значение = объект.значение if объект else None
        return значение

    def поток(self, значение) -> bytes | None:
        if isinstance(значение, Ссылка):
            объект = self.объекты.get(значение.номер)
            return объект.поток if объект else None
        return None


def _разжать(словарь: dict, сырое: bytes) -> bytes | None:
    """Разжимает поток. None означает «способ сжатия не поддержан»."""
    фильтр = словарь.get("/Filter")
    if фильтр is None:
        return сырое
    фильтры = фильтр if isinstance(фильтр, list) else [фильтр]
    if фильтры != ["/FlateDecode"]:
        return None
    try:
        return zlib.decompress(сырое)
    except zlib.error:
        try:
            # Обрезанный хвост встречается у файлов, записанных с ошибкой:
            # разжимаем сколько сможем, но молчать об этом нельзя.
            распаковщик = zlib.decompressobj()
            return распаковщик.decompress(сырое)
        except zlib.error:
            return None


def прочитать(данные: bytes, срок=None) -> Документ:
    """Читает устройство файла: объекты и дерево страниц.

    Срок обязателен по сути дела, но не по подписи: не переданный заводится
    здесь же со своим утверждённым потолком. Чтение без срока в станке
    невозможно — забыть его передать можно, остаться без него нельзя.
    """
    if not данные.startswith(b"%PDF-"):
        raise PDFНеЧитается("файл не начинается с признака %PDF-")

    срок = срок_места("чтение устройства PDF", срок)
    документ = Документ()
    for совпало in _ОБЪЕКТ.finditer(данные):
        срок.тик()
        номер = int(совпало.group(1))
        значение, место = _разобрать_значение(данные, совпало.end(), срок)
        поток = None
        сырой = None
        место = _пропустить_пробелы(данные, место, срок)
        if данные[место : место + 6] == b"stream":
            место += 6
            if данные[место : место + 2] == b"\r\n":
                место += 2
            elif данные[место : место + 1] in (b"\n", b"\r"):
                место += 1
            конец = данные.find(b"endstream", место)
            if конец < 0:
                конец = len(данные)
            сырой = данные[место:конец]
            if isinstance(значение, dict):
                поток = _разжать(значение, сырой)
        # Повтор номера — это приращение: берём последнюю редакцию.
        документ.объекты[номер] = Объект(значение, поток, сырой)

    if b"/Encrypt" in данные:
        документ.зашифрован = True

    документ.страницы = _страницы(документ, данные, срок)
    return документ


def _корень(документ: Документ, данные: bytes, срок=None):
    место = данные.rfind(b"trailer")
    while место >= 0:
        if срок is not None:
            срок.тик()
        значение, _ = _разобрать_значение(данные, место + len(b"trailer"), срок)
        if isinstance(значение, dict) and "/Root" in значение:
            корень = документ.раскрыть(значение["/Root"])
            if isinstance(корень, dict):
                return корень
        место = данные.rfind(b"trailer", 0, место)
    # Файл без пригодного трейлера: ищем каталог прямым перебором объектов.
    for объект in документ.объекты.values():
        if isinstance(объект.значение, dict) and объект.значение.get("/Type") == "/Catalog":
            return объект.значение
    return None


def _страницы(документ: Документ, данные: bytes, срок=None) -> list[dict]:
    корень = _корень(документ, данные, срок)
    собранные: list[dict] = []
    if isinstance(корень, dict):
        дерево = документ.раскрыть(корень.get("/Pages"))
        if isinstance(дерево, dict):
            _обойти(документ, дерево, {}, собранные, set(), срок)
    if собранные:
        return собранные
    # Дерева нет или оно повреждено — берём страницы прямым перебором.
    for номер in sorted(документ.объекты):
        значение = документ.объекты[номер].значение
        if isinstance(значение, dict) and значение.get("/Type") == "/Page":
            собранные.append(значение)
    return собранные


_НАСЛЕДУЕМОЕ = ("/Resources", "/MediaBox", "/CropBox", "/Rotate")


def _обойти(документ, узел, наследство, собранные, видано, срок=None):
    if срок is not None:
        срок.тик()
    свой = dict(наследство)
    for ключ in _НАСЛЕДУЕМОЕ:
        if ключ in узел:
            свой[ключ] = узел[ключ]

    дети = документ.раскрыть(узел.get("/Kids"))
    if not isinstance(дети, list):
        страница = dict(свой)
        страница.update(узел)
        собранные.append(страница)
        return
    for ссылка in дети:
        ключ = ссылка.номер if isinstance(ссылка, Ссылка) else id(ссылка)
        if ключ in видано:
            continue
        видано.add(ключ)
        ребёнок = документ.раскрыть(ссылка)
        if isinstance(ребёнок, dict):
            _обойти(документ, ребёнок, свой, собранные, видано, срок)


