class ОснасткаНегодна(ValueError):
    """Пакет оснастки не годится. Причины перечислены человеческим языком."""

    def __init__(self, беды, код: str = "E_TOOLING_INVALID") -> None:
        self.беды = tuple(беды)
        self.код = код
        super().__init__("; ".join(self.беды))


class ВерсияНеПоддержана(ОснасткаНегодна):
    """Пакет написан на версии языка, которой это ядро не знает.

    Отдельная порода намеренно: это не «пакет заполнен с ошибками», а «читать
    его нечем». Смешивать эти два случая нельзя — они требуют разных действий
    от человека: один правит бланк, другой обновляет ядро или берёт другой
    пакет.
    """

    def __init__(self, беды) -> None:
        super().__init__(беды, "E_TOOLING_VERSION")


@dataclass(frozen=True, slots=True)
class Оснастка:
    """Прочитанный и проверенный пакет семейства."""

    язык: str
    содержимое: dict

    def __post_init__(self) -> None:
        # Второй рубеж. Загрузчик версию уже проверил, но собрать оснастку
        # можно и в обход него — а ядро, взявшееся работать с пакетом чужой
        # версии, поведёт себя непредсказуемо и об этом не скажет.
        if self.язык not in ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ:
            raise ВерсияНеПоддержана([_объяснить_версию(self.язык)])

    # ------------------------------------------------------- опознание

    @property
    def семейство(self) -> str:
        return self.содержимое["идентификация"]["семейство"]

    @property
    def версия(self) -> str:
        """Версия шаблона в виде «семейство/версия формы» — как в record/1."""
        опознание = self.содержимое["идентификация"]
        return f"{опознание['семейство']}/{опознание['версия_формы']}"

    def подходит(self, текст: str) -> tuple[bool, str]:
        """Относится ли документ к этому семейству, и почему.

        Отрицательные признаки сильнее положительных: если документ прямо
        объявлен чужим, никакое совпадение не делает его своим. Так справка не
        станет выпиской из-за общего слова в шапке.
        """
        опознание = self.содержимое["идентификация"]
        для_сличения = (текст or "").casefold()
        for признак in опознание["отрицательные_признаки"]:
            значение = str(признак.get("значение", "")).casefold()
            if значение and значение in для_сличения:
                return False, f"отрицательный признак: {признак.get('значение')}"
        совпавшие = [
            признак.get("значение") for признак in опознание["признаки_выбора"]
            if str(признак.get("значение", "")).casefold() in для_сличения
        ]
        if not совпавшие:
            return False, "ни один признак выбора не найден"
        return True, "совпали признаки: " + ", ".join(совпавшие)

    # --------------------------------------------------- что даёт станку

    def правила_истолкования(self):
        """Правила для типизатора шага 29, взятые прямо из пакета."""
        from .typizer import ПравилаОснастки

        нормализация = self.содержимое["нормализация"]
        return ПравилаОснастки(
            порядок_даты=нормализация.get("порядок_даты"),
            разделитель_дробной=нормализация.get("разделитель_дробной"),
            разделитель_групп=нормализация.get("разделитель_групп"),
            неявные_копейки=нормализация.get("неявные_копейки"),
            знак_в_скобках=bool(нормализация.get("знак_в_скобках", False)),
            валюта=нормализация.get("валюта"),
            обозначения_валюты=tuple(
                нормализация.get("обозначения_валюты") or ()),
            словари=нормализация.get("словари"))

    def ожидания(self, наблюдения=None):
        """Ожидаемая структура — недостающий механизм полноты раздела 8.2.

        ``наблюдения`` — измеренные величины, на которые опираются объявленные
        ожидания вида «сколько строк объявлено самим документом». Чего нет в
        наблюдениях, того оснастка не выдумывает.
        """
        from .coverage import Ожидание

        наблюдения = наблюдения or {}
        собранные = []
        for ожидаемое in self.содержимое["покрытие"]["ожидаемые"]:
            вид = ожидаемое["вид"]
            если_число = ожидаемое.get("сколько")
            если_наблюдение = ожидаемое.get("считать_по")
            if если_наблюдение is not None:
                если_число = наблюдения.get(если_наблюдение)
                if если_число is None:
                    continue
            if если_число is None:
                continue
            собранные.append(Ожидание(
                вид, int(если_число), "ожидаемая структура шаблона",
                f"{self.версия}: {ожидаемое.get('основание', 'объявлено оснасткой')}"))
        return tuple(собранные)

    @property
    def шапка_повторяется(self):
        """Обязана ли шапка повторяться на продолжении. None — не объявлено."""
        return self.содержимое["адресация"]["продолжение"].get("шапка_повторяется")

    @property
    def граница_записи(self):
        """Правило границы операции. ``None`` — семейство его не объявило."""
        return self.содержимое["адресация"].get("граница_записи")

    @property
    def конец_таблицы(self) -> tuple[str, ...]:
        """Признаки последней строки таблицы, объявленные оснасткой."""
        правило = self.содержимое["адресация"]["продолжение"]
        return tuple(str(з) for з in правило.get("конец_таблицы", ()))

    @property
    def поля(self) -> tuple[dict, ...]:
        return tuple(self.содержимое["схема"]["поля"])

    @property
    def критические_поля(self) -> tuple[str, ...]:
        return tuple(self.содержимое["риск"]["критические_поля"])

    @property
    def контрольные_итоги(self) -> tuple[dict, ...]:
        """Объявленные итоги. Здесь они не вычисляются — это шаг 41.

        Итог назван видом из закрытого набора и именами полей семейства.
        Выражения в нём нет и быть не может: исполняет соотношение ядро.
        """
        return tuple(self.содержимое["проверки"]["итоги"])

    @property
    def межполевые_правила(self) -> tuple[dict, ...]:
        """Объявленные межполевые правила. Исполняет их ядро — шаг 42.

        Пустой ответ означает, что семейство их не объявило, и уровень честно
        даёт «неизвестно»: правило конкретного банка, вписанное в ядро, и было
        бы его пересборкой ради клиента.
        """
        объявленные = (self.содержимое["проверки"] or {}).get("межполевые")
        return tuple(объявленные) if isinstance(объявленные, list) else ()

    @property
    def правило_округления(self):
        """Как округлять при сравнении итогов. ``None`` — не объявлено.

        Не объявлено — значит, сравнение, которому округление понадобилось,
        даёт «неизвестно». Умолчания здесь нет намеренно: ``Decimal``
        округляет половину к чётному, банк обычно вверх, и разница — деньги.
        """
        return (self.содержимое["проверки"] or {}).get("округление")

    def as_json(self) -> dict:
        return {"язык": self.язык, "версия": self.версия,
                "семейство": self.семейство,
                "полей": len(self.поля),
                "ожидаемых": len(self.содержимое["покрытие"]["ожидаемые"]),
                "итогов": len(self.контрольные_итоги)}


# ------------------------------------------------------------- разбор


def _объяснить_версию(язык) -> str:
    известные = ", ".join(sorted(ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ))
    return (f"версия языка {язык!r} этим ядром не поддерживается; "
            f"ядро умеет читать: {известные}. Пакет не читается — не потому, "
            "что заполнен неверно, а потому, что читать его нечем")


def проверить(содержимое: Any) -> tuple[str, ...]:
    """Перечисляет недостатки пакета человеческим языком.

    Отвечает списком, а не первой попавшейся бедой: заполняющий бланк должен
    видеть всё, что нужно поправить, а не исправлять по одному за раз.

    Исключение — чужая версия языка. О ней говорится **одна** беда и разбор
    прекращается: судить содержимое чужой версии по своим правилам нельзя.
    Раздел, обязательный у нас, там может не существовать вовсе, а знакомое
    имя — значить другое. Перечислять такие «недостатки» значило бы уводить
    человека чинить то, что не сломано.
    """
    беды: list[str] = []
    if not isinstance(содержимое, dict):
        return ("пакет должен быть объектом с девятью разделами",)

    язык = содержимое.get("язык")
    if not isinstance(язык, str) or not язык.strip():
        беды.append("не указан раздел «язык»: без него нельзя понять, "
                    "по какому договору читать пакет")
    elif язык not in ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ:
        return (_объяснить_версию(язык),)

    for группа in ГРУППЫ:
        если_есть = содержимое.get(группа)
        if если_есть is None:
            беды.append(f"нет обязательного раздела «{группа}» (раздел 7 чертежа)")
            continue
        if not isinstance(если_есть, dict):
            беды.append(f"раздел «{группа}» должен быть объектом")
            continue
        for ключ in _ОБЯЗАТЕЛЬНО_В_ГРУППЕ[группа]:
            if ключ not in если_есть:
                беды.append(f"в разделе «{группа}» нет обязательного «{ключ}»")

    лишние = sorted(set(содержимое) - set(ГРУППЫ) - {"язык"})
    if лишние:
        беды.append("лишние разделы, которых язык не знает: " + ", ".join(лишние))

    беды.extend(_беды_версии(содержимое, язык))
    беды.extend(_беды_кода(содержимое))
    беды.extend(_беды_нормализации(содержимое))
    беды.extend(_беды_схемы(содержимое))
    беды.extend(_беды_покрытия(содержимое))
    беды.extend(_беды_проверок(содержимое))
    беды.extend(_беды_допуска(содержимое))
    беды.extend(_беды_адресации(содержимое))
    return tuple(беды)


def _беды_версии(содержимое, язык) -> list[str]:
    """Не объявлено ли в первой версии языка то, что появилось во второй.

    Молча принять такое объявление было бы хуже всего: первая версия его не
    исполняет, и оснастка тихо работала бы не так, как написано.
    """
    if язык != "tooling/1":
        return []
    беды = []
    for группа, ключи in НОВОЕ_ВО_ВТОРОЙ.items():
        раздел = содержимое.get(группа)
        if not isinstance(раздел, dict):
            continue
        for ключ in ключи:
            if ключ in раздел:
                беды.append(
                    f"в разделе «{группа}» объявлено «{ключ}», а это правило "
                    "появилось в языке tooling/2. Первая версия его не "
                    "исполняет: поднимите язык оснастки до tooling/2 либо "
                    "уберите правило")
    return беды


def _беды_нормализации(содержимое) -> list[str]:
    """Разбирает перечень обозначений валюты (язык tooling/2).

    Обозначение без валюты и валюта без обозначения одинаково негодны: первое
    нечем истолковать, второе нечего искать в ячейке.
    """
    беды = []
    нормализация = содержимое.get("нормализация")
    if not isinstance(нормализация, dict):
        return беды
    перечень = нормализация.get("обозначения_валюты")
    if перечень is None:
        return беды
    if not isinstance(перечень, list) or not перечень:
        return ["раздел «нормализация»: «обозначения_валюты» должны быть "
                "непустым перечнем; пустой перечень ничего не объявляет, а "
                "отсутствие раздела — законно"]
    видены = set()
    for место, свой in enumerate(перечень, start=1):
        где = f"обозначение валюты №{место}"
        if not isinstance(свой, dict):
            беды.append(f"{где}: описание должно быть объектом")
            continue
        обозначение = str(свой.get("обозначение", "")).strip()
        валюта = str(свой.get("валюта", "")).strip()
        if not обозначение:
            беды.append(f"{где}: не сказано, какое обозначение искать в ячейке")
        if not валюта:
            беды.append(
                f"{где}: не сказано, какая валюта за обозначением "
                f"{обозначение!r}. Вырезанное обозначение становится значением "
                "поля валюты, а не выбрасывается")
        if обозначение and обозначение.casefold() in видены:
            беды.append(f"{где}: обозначение {обозначение!r} объявлено дважды")
        видены.add(обозначение.casefold())
        if not свой.get("основание"):
            беды.append(f"{где}: нет основания — измеренного или названного "
                        "словами повода считать это обозначение валютой")
    return беды


def _беды_кода(значение, путь: str = "") -> list[str]:
    """Ищет в пакете следы кода. Пакет — данные, и код в нём недопустим."""
    беды = []
    if isinstance(значение, dict):
        for ключ, вложенное in значение.items():
            имя = str(ключ).casefold()
            if имя in _ЗАПРЕЩЁННЫЕ_КЛЮЧИ:
                беды.append(
                    f"{путь or 'пакет'}: поле «{ключ}» недопустимо — оснастка "
                    "является данными, исполнять её станок не станет")
            беды.extend(_беды_кода(вложенное, f"{путь}/{ключ}" if путь else str(ключ)))
    elif isinstance(значение, list):
        for место, вложенное in enumerate(значение):
            беды.extend(_беды_кода(вложенное, f"{путь}[{место}]"))
    return беды


def _беды_схемы(содержимое) -> list[str]:
    беды = []
    схема = содержимое.get("схема")
    if not isinstance(схема, dict):
        return беды
    поля = схема.get("поля")
    if not isinstance(поля, list) or not поля:
        беды.append("в разделе «схема» нет ни одного поля: описывать нечего")
        return беды
    имена = set()
    for место, поле in enumerate(поля, start=1):
        где = f"поле №{место}"
        if not isinstance(поле, dict):
            беды.append(f"{где}: описание поля должно быть объектом")
            continue
        for ключ in _ПОЛЕ_ОБЯЗАТЕЛЬНО:
            if ключ not in поле:
                беды.append(f"{где}: не указано «{ключ}»")
        имя = поле.get("имя")
        if имя in имена:
            беды.append(f"{где}: имя «{имя}» уже занято другим полем")
        имена.add(имя)
        тип = поле.get("тип")
        if тип is not None and тип not in _ТИПЫ_ПОЛЕЙ:
            беды.append(
                f"{где}: неизвестный тип «{тип}»; язык знает такие: "
                + ", ".join(sorted(_ТИПЫ_ПОЛЕЙ)))
        if тип == "словарь" and not поле.get("словарь"):
            беды.append(f"{где}: для типа «словарь» надо назвать словарь")
    return беды


def _беды_покрытия(содержимое) -> list[str]:
    беды = []
    покрытие = содержимое.get("покрытие")
    if not isinstance(покрытие, dict):
        return беды
    ожидаемые = покрытие.get("ожидаемые")
    if not isinstance(ожидаемые, list) or not ожидаемые:
        беды.append(
            "в разделе «покрытие» нет ожидаемых объектов: без них полноту "
            "доказывать нечем, и статус останется unknown")
        return беды
    for место, ожидаемое in enumerate(ожидаемые, start=1):
        если_не_объект = not isinstance(ожидаемое, dict)
        if если_не_объект or "вид" not in ожидаемое:
            беды.append(f"ожидаемое №{место}: не указан «вид» объекта")
            continue
        if "сколько" not in ожидаемое and "считать_по" not in ожидаемое:
            беды.append(
                f"ожидаемое №{место}: не сказано ни «сколько», ни «считать_по» — "
                "ожидание без числа ничего не проверяет")
    return беды


def _беды_проверок(содержимое) -> list[str]:
    """Разбирает раздел «проверки»: контрольные итоги и правило округления.

    Итог объявляется **видом** из закрытого набора и именами полей, а не
    выражением. Вид без своих обязательных имён негоден: соотношение, в котором
    не сказано, что считать остатком, ничего не проверяет — и, что хуже, тихо
    сходится с самим собой.
    """
    беды = []
    проверки = содержимое.get("проверки")
    if not isinstance(проверки, dict):
        return беды

    итоги = проверки.get("итоги")
    if not isinstance(итоги, list) or not итоги:
        беды.append("в разделе «проверки» нет ни одного контрольного итога: "
                    "документ не будет проверять сам себя")
    else:
        for место, итог in enumerate(итоги, start=1):
            беды.extend(_беды_итога(место, итог))

    округление = проверки.get("округление")
    if округление is not None:
        беды.extend(_беды_округления(округление))

    последовательность = проверки.get("последовательность")
    if последовательность is not None and not isinstance(последовательность,
                                                         dict):
        # Найдено при написании второй оснастки: перечень вместо объекта
        # проходил проверку языка и валил конвейер посреди работы — на этапе
        # проверки пропусков, за десять этапов от объявления. Отказ обязан
        # приходить здесь, при чтении оснастки, а не там.
        беды.append(
            "раздел «проверки»: «последовательность» должна быть объектом с "
            "полем и правилом пропусков, а подано "
            f"{type(последовательность).__name__}. Нет правила — не пишите "
            "раздел вовсе: отсутствие даёт «неизвестно», а негодное "
            "объявление роняет разбор посреди работы")
    if isinstance(последовательность, dict):
        if (последовательность.get("пропуски") == "не_образуют_последовательности"
                and not последовательность.get("основание")):
            беды.append(
                "раздел «проверки»: объявлено, что номера не образуют "
                "последовательности, но основания нет — такое объявление "
                "снимает проверку пропусков целиком")

    межполевые = проверки.get("межполевые")
    if межполевые is not None:
        if not isinstance(межполевые, list):
            беды.append("раздел «проверки»: «межполевые» должны быть списком")
        else:
            имена = set()
            for место, правило in enumerate(межполевые, start=1):
                беды.extend(_беды_межполевого(место, правило))
                имя = правило.get("имя") if isinstance(правило, dict) else None
                if имя and имя in имена:
                    # Правило узнаётся в отчёте по имени. Два одноимённых
                    # правила неразличимы, и прошедшее прикрыло бы нарушенное.
                    беды.append(
                        f"межполевое правило №{место}: имя «{имя}» уже занято "
                        "другим правилом — в отчёте их будет не различить")
                имена.add(имя)
    return беды


def _беды_адресации(содержимое) -> list[str]:
    """Разбирает границу записи: где кончается одна операция и начинается
    следующая.

    Правило объявляется семейством и исполняется ядром — довод тот же, что и у
    межполевых правил шага 42. Полоса записывается десятичными строками:
    доля с дробной частью, записанная числом JSON, приходит двоичной и уже
    неточна.
    """
    from .records import ВИДЫ_ГРАНИЦЫ

    беды = []
    адресация = содержимое.get("адресация")
    if not isinstance(адресация, dict):
        return беды
    правило = адресация.get("граница_записи")
    if правило is None:
        return беды
    если_не_объект = not isinstance(правило, dict)
    if если_не_объект:
        return ["раздел «адресация»: «граница_записи» должна быть объектом"]

    вид = правило.get("вид")
    if вид not in ВИДЫ_ГРАНИЦЫ:
        беды.append(
            f"раздел «адресация»: вид границы записи «{вид}» неизвестен; "
            "язык знает такие: " + ", ".join(sorted(ВИДЫ_ГРАНИЦЫ)))
        return беды

    полоса = правило.get("полоса")
    if not isinstance(полоса, dict):
        return беды + ["раздел «адресация»: у границы записи нет «полосы»"]
    for край in ("от", "до"):
        значение = полоса.get(край)
        if not isinstance(значение, str):
            беды.append(
                f"раздел «адресация»: край полосы «{край}» записан как "
                f"{значение!r}; края записываются десятичными строками")
    if not правило.get("основание"):
        беды.append("раздел «адресация»: у границы записи нет «основания» — "
                    "числа полосы подобраны под семейство, и чем именно они "
                    "измерены, обязано быть сказано")

    реквизиты = адресация.get("реквизиты")
    if isinstance(реквизиты, list):
        for место, реквизит in enumerate(реквизиты, start=1):
            if not isinstance(реквизит, dict):
                беды.append(f"реквизит №{место}: описание должно быть объектом")
                continue
            if not реквизит.get("имя") or not реквизит.get("метка"):
                беды.append(f"реквизит №{место}: нужны «имя» и «метка»")
            правится = реквизит.get("отбросить_хвост") or реквизит.get("словарь")
            if правится and not реквизит.get("основание"):
                беды.append(
                    f"реквизит {реквизит.get('имя')!r}: значение правится "
                    "хвостом или словарём, а основания нет — чем это измерено, "
                    "обязано быть сказано")
    return беды


def _беды_допуска(содержимое) -> list[str]:
    """Разбирает «риск» и «допуск»: класс риска, пороги, контрольная выборка.

    Пороги и доли записываются десятичными строками по тому же доводу, что и
    границы межполевых правил: дробь, записанная числом JSON, приходит двоичной
    и уже неточна.

    Режим перепроверки здесь **не объявляется**: его назначает измеренная
    метрика (шаг 44). Объявить можно только класс риска — он версионирован и
    решением на ходу не является.
    """
    беды = []
    риск = содержимое.get("риск")
    if isinstance(риск, dict) and "класс" in риск:
        if риск.get("класс") not in _КЛАССЫ_РИСКА:
            беды.append(
                f"раздел «риск»: неизвестный класс «{риск.get('класс')}»; "
                "язык знает такие: " + ", ".join(sorted(_КЛАССЫ_РИСКА)))

    допуск = содержимое.get("допуск")
    if not isinstance(допуск, dict):
        return беды

    пороги = допуск.get("пороги")
    if пороги is not None:
        if not isinstance(пороги, dict):
            беды.append("раздел «допуск»: «пороги» должны быть объектом")
        else:
            for имя, значение in sorted(пороги.items()):
                if not isinstance(значение, str):
                    беды.append(
                        f"раздел «допуск»: порог «{имя}» записан как "
                        f"{значение!r}; порог надо записывать десятичной "
                        "строкой, иначе дробь приходит двоичной и уже неточна")

    выборка = допуск.get("контрольная_выборка")
    if выборка is not None:
        беды.extend(_беды_выборки(выборка))
    return беды


def _беды_выборки(выборка) -> list[str]:
    """Случайная контрольная выборка. Ноль и отсутствие — не одно и то же.

    Доля, объявленная нулём, означала бы стабильный режим без выборки, то есть
    проверку ровно того, что назвали триггеры. Язык такого не принимает.
    """
    if not isinstance(выборка, dict):
        return ["раздел «допуск»: «контрольная_выборка» должна быть объектом"]
    доля = выборка.get("доля")
    if not isinstance(доля, str):
        return ["раздел «допуск»: у контрольной выборки нет доли, записанной "
                "десятичной строкой"]
    try:
        число = Decimal(доля)
    except InvalidOperation:
        return [f"раздел «допуск»: доля выборки {доля!r} не читается как число"]
    if not число.is_finite() or число <= 0 or число > 1:
        return [f"раздел «допуск»: доля выборки {доля} вне 0…1 либо равна нулю; "
                "нулевая доля — это стабильный режим без выборки, где "
                "проверяется ровно то, что назвали триггеры"]
    return []


def _беды_межполевого(место, правило) -> list[str]:
    """Разбирает одно межполевое правило.

    Правило без имени поля или без своей ссылки негодно: условие, в котором не
    сказано, что с чем сличать, ничего не проверяет — и, что хуже, отчитывается
    о проверке, которой не было.
    """
    где = f"межполевое правило №{место}"
    if not isinstance(правило, dict):
        return [f"{где}: описание правила должно быть объектом"]

    беды = []
    if not правило.get("имя"):
        беды.append(f"{где}: не указано «имя» — по нему правило узнаётся в отчёте")
    if not правило.get("описание"):
        беды.append(f"{где}: нет «описания» — условие записывается словами")

    вид = правило.get("вид")
    if вид not in _ВИДЫ_МЕЖПОЛЕВЫХ:
        return беды + [
            f"{где}: {'не указан «вид»' if вид is None else f'неизвестный вид «{вид}»'}; "
            "язык знает такие: " + ", ".join(sorted(_ВИДЫ_МЕЖПОЛЕВЫХ))]

    for ключ in _ВИДЫ_МЕЖПОЛЕВЫХ[вид]:
        if not правило.get(ключ):
            беды.append(f"{где} (вид «{вид}»): не указано «{ключ}»")

    если_критическое = правило.get("критическое")
    if если_критическое is not None and not isinstance(если_критическое, bool):
        беды.append(f"{где}: «критическое» должно быть да или нет, а не "
                    f"{если_критическое!r}")

    if вид == "порядок_дат":
        есть_позже = правило.get("не_позже") is not None
        есть_раньше = правило.get("не_раньше") is not None
        if not есть_позже and not есть_раньше:
            беды.append(f"{где}: не сказано ни «не_позже», ни «не_раньше» — "
                        "порядок дат не объявлен")
        if есть_позже and есть_раньше:
            беды.append(f"{где}: объявлены сразу «не_позже» и «не_раньше»; "
                        "исполнить можно только одно, и половина правила "
                        "осталась бы непроверенной")
        for ключ in ("не_позже", "не_раньше"):
            if правило.get(ключ) is not None:
                беды.extend(_беды_ссылки(f"{где}/{ключ}", правило[ключ]))
    if вид == "валюта_совпадает" and правило.get("совпадает_с") is not None:
        беды.extend(_беды_ссылки(f"{где}/совпадает_с", правило["совпадает_с"]))
    if вид == "состав_при_значении":
        if not правило.get("требуются") and not правило.get("запрещены"):
            беды.append(f"{где}: не перечислено ни «требуются», ни «запрещены» — "
                        "состав полей не объявлен")
    if вид == "границы_значения":
        беды.extend(_беды_границ(где, правило))
    return беды


def _беды_ссылки(где, ссылка) -> list[str]:
    """Ссылка указывает либо на поле записи, либо на реквизит документа."""
    if not isinstance(ссылка, dict):
        return [f"{где}: ссылка должна быть объектом «поле» или «реквизит»"]
    если_поле = bool(ссылка.get("поле"))
    если_реквизит = bool(ссылка.get("реквизит"))
    if если_поле == если_реквизит:
        return [f"{где}: в ссылке должно быть ровно одно из «поле» и "
                "«реквизит»; величина, взятая откуда-то ещё, документом не "
                "сообщалась"]
    return []


def _беды_границ(где, правило) -> list[str]:
    """Границы записываются десятичными строками, а не числами JSON.

    Число с дробной частью в JSON приходит двоичной дробью и уже потеряло
    точность — ровно то, что запрещено в денежном пути.
    """
    беды = []
    if правило.get("не_меньше") is None and правило.get("не_больше") is None:
        беды.append(f"{где}: не объявлено ни «не_меньше», ни «не_больше»")
    for ключ in ("не_меньше", "не_больше"):
        значение = правило.get(ключ)
        if значение is None or isinstance(значение, str):
            continue
        if isinstance(значение, bool) or not isinstance(значение, int):
            беды.append(
                f"{где}: граница «{ключ}» записана как {значение!r}; границу "
                "надо записывать десятичной строкой, иначе дробь приходит "
                "двоичной и уже неточна")
    return беды


def _беды_итога(место, итог) -> list[str]:
    где = f"контрольный итог №{место}"
    if not isinstance(итог, dict):
        return [f"{где}: описание итога должно быть объектом"]

    беды = []
    if not итог.get("описание"):
        беды.append(f"{где}: нет «описания» — соотношение записывается словами")

    вид = итог.get("вид")
    if вид is None:
        return беды + [
            f"{где}: не указан «вид»; язык знает такие: "
            + ", ".join(sorted(_ВИДЫ_ИТОГОВ))]
    if вид not in _ВИДЫ_ИТОГОВ:
        return беды + [
            f"{где}: неизвестный вид «{вид}»; язык знает такие: "
            + ", ".join(sorted(_ВИДЫ_ИТОГОВ))]

    for ключ in _ВИДЫ_ИТОГОВ[вид]:
        if not итог.get(ключ):
            беды.append(f"{где} (вид «{вид}»): не указано «{ключ}»")

    if вид == "баланс" and итог.get("знак") is not None:
        беды.extend(_беды_знака(где, итог.get("знак")))
    return беды


def _беды_знака(где, знак) -> list[str]:
    """Правило знака операции: минус в колонке или отдельный признак.

    Общего умолчания нет: у одной выписки списание — отрицательная сумма, у
    другой — признак «Д» при всегда положительной. Выбрать за банк нельзя.
    """
    if not isinstance(знак, dict):
        return [f"{где}: «знак» должен быть объектом"]
    if знак.get("по_знаку"):
        return []
    if not знак.get("по_полю"):
        return [f"{где}: в «знаке» не сказано ни «по_знаку», ни «по_полю» — "
                "отнести операцию к поступлению или списанию будет нечем"]
    беды = []
    for ключ in ("поступление", "списание"):
        значения = знак.get(ключ)
        if not isinstance(значения, list) or not значения:
            беды.append(f"{где}: в «знаке» не перечислены значения «{ключ}»")
    return беды


def _беды_округления(округление) -> list[str]:
    if not isinstance(округление, dict):
        return ["раздел «проверки»: «округление» должно быть объектом"]
    беды = []
    правило = округление.get("правило")
    if правило not in _ПРАВИЛА_ОКРУГЛЕНИЯ:
        беды.append(
            f"раздел «проверки»: неизвестное правило округления «{правило}»; "
            "язык знает такие: " + ", ".join(sorted(_ПРАВИЛА_ОКРУГЛЕНИЯ)))
    разрядов = округление.get("разрядов")
    if not isinstance(разрядов, int) or isinstance(разрядов, bool) or разрядов < 0:
        беды.append("раздел «проверки»: у округления не указано целое число "
                    "«разрядов»")
    return беды


def загрузить(данные) -> Оснастка:
    """Читает пакет из объекта, строки или байтов. Негодный — отвергает.

    Разбор строгий и без снисхождения: пакет ставится как данные, и ошибка в
    нём проявится не здесь, а на выписке клиента.
    """
    содержимое = данные
    if isinstance(данные, (bytes, bytearray)):
        try:
            содержимое = json.loads(bytes(данные).decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as беда:
            raise ОснасткаНегодна([f"пакет не читается как JSON: {беда}"]) from беда
    elif isinstance(данные, str):
        try:
            содержимое = json.loads(данные)
        except ValueError as беда:
            raise ОснасткаНегодна([f"пакет не читается как JSON: {беда}"]) from беда

    беды = проверить(содержимое)
    if беды:
        язык = содержимое.get("язык") if isinstance(содержимое, dict) else None
        if isinstance(язык, str) and язык not in ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ:
            # Отказ, а не молчаливая попытка. Признака «прочитать всё равно»
            # здесь нет и быть не должно.
            raise ВерсияНеПоддержана(беды)
        raise ОснасткаНегодна(беды)
    return Оснастка(содержимое["язык"], содержимое)


def выбрать_по_форме(оснастки, текст: str) -> tuple[object | None, tuple[str, ...]]:
    """Какая оснастка признала документ своим. Возвращает её и объяснения.

    Спрашиваются **все**, а не берётся первая совпавшая: если своим документ
    признали двое, выбирать между ними наугад нельзя — это молчаливый выбор
    того, чем разбирать, и он однажды окажется неверным. Двое — отказ, и оба
    названы.

    Не признал никто — тоже отказ, и сказано, чем именно каждая не подошла:
    иначе человек видит «не разобралось» и не знает, чего недостаёт.
    """
    подошли, объяснения = [], []
    for оснастка in оснастки:
        свой, почему = оснастка.подходит(текст)
        объяснения.append(f"{оснастка.версия}: {почему}")
        if свой:
            подошли.append(оснастка)
    if len(подошли) == 1:
        return подошли[0], tuple(объяснения)
    if len(подошли) > 1:
        имена = ", ".join(о.версия for о in подошли)
        return None, (f"документ признали своим сразу {len(подошли)}: {имена}. "
                      "Выбирать между ними наугад нельзя",) + tuple(объяснения)
    return None, tuple(объяснения)


def механизмы_с_оснасткой(оснастка, механизмы=None) -> tuple[str, ...]:
    """Набор механизмов полноты с учётом применённой оснастки.

    Ожидаемая структура шаблона появляется тогда и только тогда, когда шаблон
    действительно применён к этому документу. Числить её наличной вообще, «раз
    язык написан», значило бы засчитывать проверку, которая не состоялась.
    """
    from .completeness import ДОСТУПНЫЕ_МЕХАНИЗМЫ

    основа = tuple(механизмы if механизмы is not None else ДОСТУПНЫЕ_МЕХАНИЗМЫ)
    if оснастка is None:
        return основа
    добавка = "ожидаемая структура шаблона"
    return основа if добавка in основа else основа + (добавка,)


