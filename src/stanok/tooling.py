"""Язык оснастки: версионированная политика семейства документов.

Шаг 37 плана. Нормативная основа — чертёж v3.0, раздел 7 (контракт шаблона),
раздел 5.1 и раздел 9.

**Решение владельца, определяющее всё устройство.** Ядро и пакеты оснастки —
два раздельных изделия. Ядро не пересобирается ради нового банка; пакет ставится
**как данные**. Отсюда три следствия, которым подчинено всё ниже.

1. **Оснастка — это данные, а не код.** Пакет не исполняется: в нём нет и не
   может быть ни выражений, ни вызовов, ни ссылок на код станка. Формулы
   контрольных итогов записываются словами и **не вычисляются здесь** — их
   исполняет валидатор (шаг 41). Пакет, пришедший от клиента, — недоверенный
   вход ровно как документ, и исполнять его нельзя по той же причине.
2. **Ядро не знает ни одного банка по имени.** В этом файле нет ни одного
   названия семейства — есть только схема, которой семейство описывается. Тот же
   довод, что и в розетке шага 25: список известных имён и был бы пересборкой
   ядра ради нового клиента.
3. **Новое семейство вводится без программирования.** Пакет — это заполненный
   бланк из девяти разделов. Проверяльщик разбирает его и отвечает списком
   недостатков **человеческим языком**, а не следом исключения.

**Оснастка — не набор выражений поиска.** Раздел 7 перечисляет девять
обязательных групп, и все девять обязательны: без «Покрытия» нельзя знать
ожидаемое, без «Версионирования» нельзя откатиться, без «Риска» нельзя решить,
что проверять человеком. Пакет без любой из групп негоден.

Что оснастка даёт станку:

* **ожидаемую структуру** — недостающий механизм полноты из раздела 8.2;
* **границу таблицы** — то, что шаг 36 честно объявил неразрешимым без шаблона;
* **правила истолкования** — для типизатора шага 29;
* **схему полей, контрольные итоги и правила допуска** — объявленными;
  исполняют их валидатор и движок политик, каждый своим шагом.
"""

