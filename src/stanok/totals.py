"""Итоги, балансы и контрольные соотношения. Валюты — раздельно.

Шаг 41 плана. Нормативная основа — чертёж v3.0, раздел 10 (политика допуска) и
раздел 9 (уровень 6: начальный остаток + поступления − списания = конечный
остаток; суммы страниц и документа).

Это уровень, ради которого банковская вертикаль выбрана первой: **документ
проверяет сам себя**. Он несёт не только строки, но и напечатанные в нём итоги,
и они дают независимое от нашего разбора утверждение о том, что в нём должно
быть. Совпадение разбора с этим утверждением — сильнейшее свидетельство, какое
вообще доступно без второго прочтения.

**Валюты не смешиваются в одной проверке никогда.** Сложенные разные валюты
дают правдоподобное число, которое ничего не значит: оно похоже на деньги,
печатается как деньги и не является ничем. Хуже того, такая сумма сходится
случайно и тем самым **подтверждает** разбор, который на деле сломан. Поэтому
запрет здесь не соглашение, а устройство: сложение идёт через :func:`сложить`,
и оно **отказывается** складывать разные валюты — не предупреждает, а
прекращает работу. Денежное поле без объявленной валюты в сумму не входит
вовсе; вместо суммы объявляется «неизвестно».

**Сходящийся баланс — необходимое условие, но не достаточное.** Он не ловит
ничего из перечисленного в :data:`ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СХОДЯЩИЙСЯ_БАЛАНС`, и
принимать его за доказательство правильности нельзя. Поэтому перечень
неотделим от результата: он лежит в :func:`свод` и уходит вместе с ним, чтобы
читающий отчёт видел границу утверждения там же, где и само утверждение.

**Арифметика точная десятичная.** Двоичная дробь в денежный путь не допускается
(её отвергает ещё типизатор шага 29); сложение идёт с ловушкой на потерю
разрядов — потеря даёт отказ, а не тихо округлённый итог. **Округление — только
по объявленному оснасткой правилу.** Умолчание языка здесь запрещено:
``Decimal`` по умолчанию округляет половину к чётному, банк же обычно печатает
половину вверх, и это разные деньги. Правило не объявлено, а округлять
пришлось — «неизвестно», а не тихий выбор за банк.
"""

