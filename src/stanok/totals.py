class ВалютыСмешаны(ValueError):
    """Попытка сложить разные валюты в одной сумме.

    Отказ, а не предупреждение. Правдоподобное число, полученное сложением
    разных валют, опаснее отсутствия числа: оно печатается как деньги, сходится
    с другим таким же и тем самым **подтверждает** сломанный разбор.
    """

    код = "E_TOTALS_CURRENCY_MIX"


class СложениеНеточно(ValueError):
    """Сложение потеряло разряды. Такой итог деньгами не является."""

    код = "E_TOTALS_INEXACT"


@dataclass(frozen=True, slots=True)
class ОбъявленныйИтог:
    """Итог, напечатанный в самом документе.

    Это не наш результат, а утверждение документа о себе — то самое независимое
    свидетельство, ради которого уровень существует. Валюта обязательна: итог
    без валюты не с чем сравнивать, потому что неизвестно, чего он итог.

    ``охват`` — записи, которые итог покрывает (их ``record_id``). ``None``
    означает весь документ. Через охват выражаются и суммы страниц, и общий
    итог, и любая иная контрольная зона.
    """

    имя: str
    значение: Decimal | None
    валюта: str | None
    охват: tuple[str, ...] | None = None
    адрес: str | None = None

    def as_json(self) -> dict:
        return {
            "имя": self.имя,
            "значение": None if self.значение is None else str(self.значение),
            "валюта": self.валюта,
            "охват": None if self.охват is None else list(self.охват),
            "адрес": self.адрес,
        }


@dataclass(frozen=True, slots=True)
class Сумма:
    """Одно денежное значение записи вместе с его валютой и местом."""

    место: int
    record_id: str
    значение: Decimal
    валюта: str


def _результат(rule_id, статус, критичность, входы, вычисления, причина):
    return RuleResult(rule_id, TOTALS_VERSION, статус, критичность,
                      tuple(входы), вычисления, причина)


# ------------------------------------------------------- точное сложение


def сложить(суммы) -> Decimal:
    """Складывает денежные значения одной валюты. Разные валюты — отказ.

    Единственное место сложения денег во всём уровне. Единственное намеренно:
    рассеянное по коду сложение рано или поздно сложило бы разные валюты в
    какой-нибудь одной ветке, и заметить это было бы нечем — итог выглядел бы
    как обычное число.

    Ловушка ``Inexact`` включена: если разрядности не хватило и часть значения
    потерялась, будет отказ, а не молча округлённый итог.
    """
    суммы = list(суммы)
    валюты = {валюта for _, валюта in суммы}
    if len(валюты) > 1:
        raise ВалютыСмешаны(
            "сложение разных валют запрещено: "
            + ", ".join(sorted(str(в) for в in валюты))
            + ". Сложенные разные валюты дают правдоподобное число, которое "
              "ничего не значит")
    if None in валюты:
        raise ВалютыСмешаны(
            "в сумму попало значение без объявленной валюты: неизвестно, чего "
            "это сумма")
    with localcontext() as контекст:
        контекст.prec = ТОЧНОСТЬ_СЛОЖЕНИЯ
        контекст.traps[Inexact] = True
        итог = Decimal(0)
        try:
            for значение, _ in суммы:
                итог += значение
        except Inexact as беда:      # pragma: no cover — запас прочности
            raise СложениеНеточно(
                "сложение потеряло разряды: такой итог деньгами не является"
            ) from беда
    return итог


def вычесть(левое: Decimal, правое: Decimal, валюта) -> Decimal:
    """Разность двух значений одной валюты — тем же точным сложением.

    Отдельная обёртка, а не ``левое - правое``: вычитание в обычном контексте
    прошло бы мимо и ловушки на потерю разрядов, и запрета на смешение валют.
    Одна такая забытая строка — и весь запрет держится только на внимательности.
    """
    return сложить(((левое, валюта), (-правое, валюта)))


def _окно(суммы, валюта) -> tuple[tuple[Decimal, str], ...]:
    return tuple((сумма.значение, сумма.валюта) for сумма in суммы
                 if сумма.валюта == валюта)


# --------------------------------------------------- чтение денег записи


def _правила(оснастка) -> dict:
    if оснастка is None:
        return {}
    return оснастка.содержимое.get("проверки") or {}


def _объявленный_итог(оснастка, вид):
    свои = _объявленные_итоги(оснастка, вид)
    return свои[0] if свои else None


def _объявленные_итоги(оснастка, вид) -> tuple:
    """Все объявления этого вида, а не первое попавшееся.

    Первый настоящий документ показал, зачем: у выписки два напечатанных
    итога — обороты по дебету и обороты по кредиту, — и исполнение только
    первого оставляло вторую половину записей непокрытой. Непокрытая запись
    даёт «неизвестно», то есть выглядит как недосмотр там, где документ всё о
    себе сказал.
    """
    return tuple(итог for итог in (_правила(оснастка).get("итоги") or ())
                 if isinstance(итог, dict) and итог.get("вид") == вид)


def _поле(запись, имя) -> dict:
    return (запись.get("fields") or {}).get(имя) or {}


def собрать_суммы(записи, имя_поля) -> tuple[tuple[Сумма, ...], tuple[RuleResult, ...]]:
    """Достаёт денежные значения записей вместе с валютой.

    Возвращает суммы и беды. **При любой беде сумма не считается вовсе.**
    Посчитать её, пропустив непрочитанные записи, значило бы выдать
    правдоподобное число: оно сойдётся или не сойдётся с итогом документа, но
    ни то ни другое ничего не будет означать.
    """
    суммы: list[Сумма] = []
    беды: list[RuleResult] = []
    for место, запись in enumerate(записи, start=1):
        record_id = запись.get("record_id") or f"№{место}"
        поле = _поле(запись, имя_поля)
        значение = поле.get("value")
        валюта = поле.get("currency")

        if isinstance(значение, float):
            беды.append(_результат(
                "деньги/двоичная_дробь", НАРУШЕНО, КРИТИЧЕСКОЕ, (record_id,),
                f"поле {имя_поля!r} пришло двоичной дробью: {значение!r}",
                "двоичная дробь в денежном пути запрещена: значение потеряло "
                "точность до того, как попало сюда"))
            continue
        if not isinstance(значение, Decimal):
            беды.append(_результат(
                "деньги/значение", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (record_id,),
                f"поле {имя_поля!r} без истолкованного значения: {значение!r}",
                "складывать нечего: неистолкованное поле не число, и подменять "
                "его нулём значило бы придумать деньги"))
            continue
        if not значение.is_finite():
            беды.append(_результат(
                "деньги/не_число", НАРУШЕНО, КРИТИЧЕСКОЕ, (record_id,),
                f"поле {имя_поля!r} не является конечным числом: {значение}",
                "нечисло сравнивается со всем подряд ложно и потому прошло бы "
                "любую проверку молча"))
            continue
        if not валюта:
            беды.append(_результат(
                "валюта/объявлена", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (record_id,),
                f"у поля {имя_поля!r} нет объявленной валюты",
                "значение без валюты в сумму не входит: сложить его с другими "
                "значило бы получить правдоподобное число, которое ничего не "
                "значит"))
            continue
        суммы.append(Сумма(место, record_id, значение, валюта))
    return tuple(суммы), tuple(беды)


# ---------------------------------------------------- знак операции


def _разнести(записи, суммы, правило) -> tuple[dict, tuple[RuleResult, ...]]:
    """Делит суммы на поступления и списания по объявленному правилу.

    Общего правила нет и быть не может: у одной выписки списание — это минус в
    той же колонке, у другой — отдельный признак при всегда положительной
    сумме. Не объявлено — «неизвестно», как и с порядком в шаге 40.
    """
    по_записям = {запись.get("record_id"): запись for запись in записи}
    поступления: list[Сумма] = []
    списания: list[Сумма] = []
    беды: list[RuleResult] = []

    по_знаку = bool(правило.get("по_знаку"))
    имя_признака = правило.get("по_полю")

    for сумма in суммы:
        if по_знаку:
            (списания if сумма.значение < 0 else поступления).append(сумма)
            continue

        запись = по_записям.get(сумма.record_id) or {}
        признак = _поле(запись, имя_признака).get("value")
        если_поступление = признак in (правило.get("поступление") or ())
        если_списание = признак in (правило.get("списание") or ())
        if если_поступление == если_списание:
            беды.append(_результат(
                "знак/признак", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (сумма.record_id,),
                f"признак {признак!r} не отнесён ни к поступлению, ни к "
                f"списанию" if not если_поступление
                else f"признак {признак!r} объявлен и поступлением, и списанием",
                "отнести операцию к поступлению или списанию нечем: правило "
                "оснастки её не описывает"))
            continue
        if сумма.значение < 0:
            # Сумма отрицательна, а знак берётся из признака: два источника
            # знака сразу. Какой из них верен — не наше дело угадывать.
            беды.append(_результат(
                "знак/противоречие", НАРУШЕНО, КРИТИЧЕСКОЕ, (сумма.record_id,),
                f"сумма {сумма.значение} отрицательна при признаке {признак!r}",
                "знак задан дважды и по-разному: признаком операции и знаком "
                "самой суммы. Выбрать за банк один из них проверка не станет"))
            continue
        (поступления if если_поступление else списания).append(сумма)

    return {"поступления": tuple(поступления), "списания": tuple(списания)}, tuple(беды)


# ------------------------------------------------------------ сравнение


def _правило_округления(оснастка):
    return _правила(оснастка).get("округление")


def _сравнить(вычислено: Decimal, объявлено: Decimal, округление):
    """Сравнивает два точных значения. Округляет только по объявленному правилу.

    Разряды совпали — сравнение точное, и округление тут вообще ни при чём.
    Разошлись — округлять придётся, и тогда правило обязано быть объявлено:
    умолчание языка (половина к чётному) отличается от того, как печатает банк
    (обычно половина вверх), и разница эта — настоящие деньги.
    """
    if вычислено.as_tuple().exponent == объявлено.as_tuple().exponent:
        return вычислено, объявлено, "разряды совпали, сравнение точное"

    if not isinstance(округление, dict):
        return None, None, None
    разрядов = округление.get("разрядов")
    режим = РЕЖИМЫ_ОКРУГЛЕНИЯ.get(округление.get("правило"))
    if режим is None or not isinstance(разрядов, int) or isinstance(разрядов, bool):
        return None, None, None

    квант = Decimal(1).scaleb(-разрядов)
    объяснение = (f"разряды разошлись; округлено до {разрядов} по правилу "
                  f"«{округление.get('правило')}», объявленному оснасткой")
    with localcontext() as контекст:
        контекст.prec = ТОЧНОСТЬ_СЛОЖЕНИЯ
        try:
            return (вычислено.quantize(квант, rounding=режим),
                    объявлено.quantize(квант, rounding=режим), объяснение)
        except ArithmeticError:
            # Число такой величины, что округлить его до объявленной сетки
            # нельзя. Молча вернуть неокруглённое значило бы сравнить не то,
            # что сравнивается.
            return None, None, None


def _беда_округления(rule_id, входы, вычислено, объявлено):
    return _результат(
        rule_id, НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, входы,
        f"вычислено {вычислено}, объявлено {объявлено}: разрядность разная",
        "сравнить нечем: округлять пришлось бы, а правило округления оснасткой "
        "не объявлено. Умолчание языка округляет половину к чётному, банк "
        "обычно вверх — это разные деньги, и выбирать за банк проверка не "
        "станет")


