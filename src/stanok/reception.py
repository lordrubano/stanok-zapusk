_КОНЕЦ_ШАПКИ = b"\r\n\r\n"
_КАВЫЧКА = chr(34)


def _части_поданного(тело: bytes, тип: str) -> list:
    """Разбирает поданное на части: имя файла и его байты.

    Разбор свой и намеренно скупой: читается ровно то, что нужно, — имя и
    содержимое. Проверять содержимое будет приём шага 20, и подменять его
    здесь своими правилами значило бы завести вторую дверь в станок.
    """
    метка = ""
    for кусок in тип.split(";"):
        кусок = кусок.strip()
        if кусок.startswith("boundary="):
            метка = кусок[len("boundary="):].strip(_КАВЫЧКА)
    if not метка:
        return []

    разделитель = ("--" + метка).encode("utf-8")
    части = []
    for сырая in тело.split(разделитель):
        if _КОНЕЦ_ШАПКИ not in сырая:
            continue
        шапка, _, содержимое = сырая.partition(_КОНЕЦ_ШАПКИ)
        имя = _имя_из_шапки(шапка)
        if имя is None:
            continue
        части.append((имя, содержимое.rstrip(b"\r\n-")))
    return части


def _имя_из_шапки(шапка: bytes) -> str | None:
    """Имя файла из шапки части. Недоверенное — как и всё остальное."""
    текст = шапка.decode("utf-8", errors="replace")
    if "filename=" not in текст:
        return None
    хвост = текст.split("filename=", 1)[1]
    if _КАВЫЧКА in хвост:
        имя = хвост.split(_КАВЫЧКА)[1]
    else:
        имя = хвост.split(";")[0]
    return имя.strip().strip(_КАВЫЧКА) or None


# Расширения, которые станок вообще умеет читать. Список закрытый и служит
# **выбору движка**, а не доверию: содержимое проверяет разбор, и текстовый
# файл, названный «.pdf», отвергнется им, а не этим списком.
ЗНАКОМЫЕ_РАСШИРЕНИЯ = (".pdf", ".xlsx", ".xls", ".docx", ".csv", ".ofx", ".txt")


def _расширение(имя: str) -> str:
    """Расширение из имени клиента — единственное, что из него берётся.

    Байты кладутся под отпечатком содержимого, а не под именем клиента: имя не
    годится как путь никогда. Но совсем без расширения файл лишается признака,
    по которому выбирается движок разбора, и станок молча не находит в PDF ни
    одного знака. Куплено пробой браузерного пути: положенная выписка не
    опозналась ни одной оснасткой — просто потому, что читать её было нечем.
    """
    свой = Path(safe_name(имя)).suffix.lower()
    return свой if свой in ЗНАКОМЫЕ_РАСШИРЕНИЯ else ""


def принять_поданное(тело: bytes, тип: str, куда=None,
                     limits: IntakeLimits = APPROVED_LIMITS,
                     policy: Policy = APPROVED_POLICY) -> Приёмная:
    """Приём того, что положили на экран.

    Байты кладутся под **своим** именем — отпечатком содержимого, а не именем
    клиента: имя клиента не годится как путь никогда, и обезвреженное тоже —
    два разных файла могут дать одно обезвреженное имя и затереть друг друга.
    Проверяет байты готовый приём шага 20.
    """
    import hashlib
    import tempfile

    части = [(имя, байты) for имя, байты in _части_поданного(тело, тип)
             if байты]
    приёмная = Приёмная(положено=len(части))
    место = Path(куда) if куда else Path(tempfile.mkdtemp(prefix="priyom-"))
    место.mkdir(parents=True, exist_ok=True)

    for имя, байты in части:
        свой = место / (hashlib.sha256(байты).hexdigest() + _расширение(имя))
        свой.write_bytes(байты)
        паспорт = _провести_через_приём(свой, имя, limits, policy)
        отказы = getattr(паспорт, "refusals", ())
        приёмная.файлы.append(Приёмка(
            объявленное_имя=имя,
            имя_станка=safe_name(имя),
            состояние=ОТВЕРГНУТ if отказы else ПРИНЯТ,
            почему=_причина_отказа(паспорт),
            байт=len(байты),
            отпечаток=getattr(паспорт, "document_id", None),
            путь=str(свой)))
    return приёмная


