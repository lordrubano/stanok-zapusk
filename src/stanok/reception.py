# -*- coding: utf-8 -*-
"""Приём документов на экране: зона перетаскивания над готовым приёмом.

Шаг 80 плана. Нормативная основа — ТЗ на интерфейс 1.0 (часть III, режим 1) и
пакет интерфейса 1.2 как образец вида.

## Ничего не разбирает — только показывает разбор приёма

Проверки входа сделаны на шаге 20 и защищены с тех пор: пределы, отказ как
состояние, обезвреженное имя. Здесь **не появляется ни одной новой проверки** —
появляется лицо над сделанным: положено столько, принято столько, отвергнуто
столько, и по каждому файлу сказано почему.

## Сходимость счёта видна сразу

Три числа обязаны сходиться: **положено = принято + отвергнуто + ждёт**. Если
не сходятся — это первое, что должен увидеть оператор, и работа не начинается.
Файл, потерявшийся между «положено» и «принято», страшнее отвергнутого:
отвергнутый назван, потерянный молчит.

## Имя файла — недоверенный вход

Имя приходит от того же, от кого документ, и вредит теми же способами:

* **как разметка** — двойники защит шага 78 действуют здесь целиком: имя
  обезвреживается при показе и проверяется обратным чтением готовой страницы;
* **как путь** — `../`, двоеточие тома, зарезервированные имена Windows и
  переопределение направления письма («счёт<RLO>fdp.exe» показывается как
  «счётexe.pdf»). Всё это снимает :func:`stanok.intake.safe_name`, и здесь
  показывается **и то, и другое**: как назвал клиент и как станок это принял.
  Прятать исходное имя нельзя — по нему клиент свой файл и узнаёт.

## Партия — не здесь

Партия как объект учёта заведена шагом 86 и живёт отдельным модулем
(:mod:`stanok.batch`). Здесь — судьба **файлов одной подачи**: приём судит о
файле, партия складывает файлы в набор. Смешивать их значило бы завести второе
место, где рождается состояние набора.
"""

