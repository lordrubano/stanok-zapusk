from .node import обезвредить

RECEPTION_VERSION = "reception/1"

# Три состояния файла на экране. Больше нет и не должно быть: «может быть»
# здесь означало бы, что станок не знает своей же работы.
ПРИНЯТ = "принят"
ОТВЕРГНУТ = "отвергнут"
ЖДЁТ = "ждёт"

СОСТОЯНИЯ = (ПРИНЯТ, ОТВЕРГНУТ, ЖДЁТ)

# Почему счёт может не сойтись. Не «ошибка», а названная беда.
СЧЁТ_НЕ_СОШЁЛСЯ = "E_RECEPTION_COUNT_MISMATCH"

KNOWN_LIMITATIONS = (
    "Приёмная знает только свою подачу: клиент, период и состояние набора — "
    "дело партии (шаг 86), и берутся они оттуда, а не отсюда.",
    "Экран показывает приём и только приём. Что станет с принятым документом "
    "дальше, решает конвейер, и его ход — шаг 81.",
    "Отвергнутый файл здесь не хранится: станок держит его паспорт с причиной, "
    "а сам файл остаётся у клиента. Замена такого файла — действие партии, и "
    "кнопки для неё на экране пока нет.",
    "Порядок файлов на экране — тот, в котором их подали. Сортировки по "
    "состоянию нет: она скрыла бы, что положено и что доехало.",
)


@dataclass(frozen=True, slots=True)
class Приёмка:
    """Судьба одного файла: как назван, как принят, что с ним."""

    объявленное_имя: str
    имя_станка: str
    состояние: str
    почему: str = ""
    байт: int | None = None
    отпечаток: str | None = None
    # Где лежат принятые байты. Без этого принятый файл некому разобрать:
    # экран знал, что документ принят, и не знал, где он. Путь — наш, под
    # отпечатком содержимого, а не под именем клиента.
    путь: str = ""

    @property
    def имя_изменено(self) -> bool:
        """Станок принял имя иначе, чем его назвали. Это надо видеть."""
        return self.объявленное_имя != self.имя_станка

    def as_json(self) -> dict:
        return {"объявленное_имя": self.объявленное_имя,
                "имя_станка": self.имя_станка,
                "имя_изменено": self.имя_изменено,
                "состояние": self.состояние, "почему": self.почему,
                "байт": self.байт, "отпечаток": self.отпечаток,
                # Путь наружу не отдаётся: это устройство нашей машины, а не
                # сведения о документе.
                }


@dataclass
class Приёмная:
    """Что положили, что принято, что отвергнуто. Счёт сходится или нет."""

    положено: int = 0
    файлы: list = field(default_factory=list)

    @property
    def принято(self) -> int:
        return sum(1 for ф in self.файлы if ф.состояние == ПРИНЯТ)

    @property
    def отвергнуто(self) -> int:
        return sum(1 for ф in self.файлы if ф.состояние == ОТВЕРГНУТ)

    @property
    def ждёт(self) -> int:
        return sum(1 for ф in self.файлы if ф.состояние == ЖДЁТ)

    @property
    def сошлось(self) -> bool:
        """Положено = принято + отвергнуто + ждёт. Иначе файл потерялся."""
        return self.положено == self.принято + self.отвергнуто + self.ждёт

    @property
    def потеряно(self) -> int:
        return max(0, self.положено - len(self.файлы))

    def свод(self) -> dict:
        свой = {
            "версия": RECEPTION_VERSION,
            "положено": self.положено,
            "принято": self.принято,
            "отвергнуто": self.отвергнуто,
            "ждёт": self.ждёт,
            "сошлось": self.сошлось,
            "файлы": [ф.as_json() for ф in self.файлы],
        }
        if not self.сошлось:
            свой["почему_не_сошлось"] = (
                f"{СЧЁТ_НЕ_СОШЁЛСЯ}: положено {self.положено}, а судьба "
                f"известна у {len(self.файлы)}. Потерянный файл опаснее "
                "отвергнутого: отвергнутый назван, потерянный молчит")
        return свой


def _провести_через_приём(путь: Path, объявленное: str,
                          limits: IntakeLimits, policy: Policy):
    """Готовый приём целиком: пределы шага 20 **и** политика шага 23.

    Одного приёма мало: он судит о файле как о файле — есть ли, не пуст ли, не
    длиннее ли предела. Что внутри — шифрованное, макросодержащее, вовсе не тот
    формат — решает политика, и без неё экран показывал бы «принято» там, где
    станок работать откажется.
    """
    паспорт = принять(путь, limits=limits, source_name=объявленное)
    if not getattr(паспорт, "refusals", ()):
        приговор = осмотреть_файл_политикой(путь, policy=policy, limits=limits)
        паспорт = внести_в_паспорт(паспорт, приговор)
    return паспорт


def _причина_отказа(паспорт) -> str:
    """Первая причина отказа словами. Код остаётся в подробностях."""
    отказы = getattr(паспорт, "refusals", ())
    if not отказы:
        return ""
    первый = отказы[0]
    словами = getattr(первый, "message", "") or getattr(первый, "reason", "")
    return str(словами) or str(первый)


def принять_файлы(пути, положено: int | None = None,
                  limits: IntakeLimits = APPROVED_LIMITS,
                  policy: Policy = APPROVED_POLICY) -> Приёмная:
    """Проводит файлы через готовый приём шага 20 и складывает их судьбу.

    ``положено`` — сколько файлов подал клиент. Подаётся отдельно от списка
    нарочно: расхождение между «сколько положили» и «сколько дошло» — это и
    есть потеря, и узнать о ней иначе неоткуда.
    """
    свои = [Path(п) for п in пути]
    приёмная = Приёмная(положено=len(свои) if положено is None else положено)
    for путь in свои:
        объявленное = путь.name
        паспорт = _провести_через_приём(путь, объявленное, limits, policy)
        отказы = getattr(паспорт, "refusals", ())
        приёмная.файлы.append(Приёмка(
            объявленное_имя=объявленное,
            имя_станка=safe_name(объявленное),
            состояние=ОТВЕРГНУТ if отказы else ПРИНЯТ,
            почему=_причина_отказа(паспорт),
            байт=getattr(паспорт, "byte_size", None),
            отпечаток=getattr(паспорт, "document_id", None)))
    return приёмная


# --------------------------------------------------------------- показ


def _т(значение) -> str:
    return обезвредить(значение)


_ЦВЕТ = {ПРИНЯТ: ("t-zel", "#1e8e3e"), ОТВЕРГНУТ: ("t-kras", "#c5221f"),
         ЖДЁТ: ("t-ser", "#8593a8")}


def плитки_html(приёмная: Приёмная) -> str:
    """Три числа сходимости плитками — тем же видом, что очереди на макете."""
    свои = [("положено", приёмная.положено, "pl-seraya"),
            ("принято", приёмная.принято, "pl-zelenaya"),
            ("отвергнуто", приёмная.отвергнуто, "pl-krasnaya"),
            ("ждёт", приёмная.ждёт, "pl-seraya")]
    куски = []
    for имя, сколько, цвет in свои:
        куски.append(f'<div class="plitka {цвет}"><div class="p">{_т(имя)}'
                     f'</div><div class="n">{сколько}</div></div>')
    return f'<div class="plitki">{"".join(куски)}</div>'


def файлы_html(приёмная: Приёмная) -> str:
    """Список файлов: как назван, как принят, что с ним и почему."""
    строки = ['<table class="dok"><tr><th>Файл</th><th>Состояние</th>'
              "<th>Причина</th><th>Размер</th></tr>"]
    for ф in приёмная.файлы:
        точка, цвет = _ЦВЕТ[ф.состояние]
        имя = _т(ф.объявленное_имя)
        если_изменено = ""
        if ф.имя_изменено:
            если_изменено = (f'<div class="tih">станок принял как '
                             f"<code>{_т(ф.имя_станка)}</code></div>")
        размер = f"{ф.байт} б" if ф.байт is not None else "—"
        строки.append(
            f"<tr><td><code>{имя}</code>{если_изменено}</td>"
            f'<td><span class="tochka {точка}"></span>{_т(ф.состояние)}</td>'
            f"<td>{_т(ф.почему) or '—'}</td><td>{_т(размер)}</td></tr>")
    строки.append("</table>")
    return "".join(строки)


def сходимость_html(приёмная: Приёмная) -> str:
    """Сошёлся счёт или нет — до списка файлов, а не после."""
    if приёмная.сошлось:
        return ('<div class="sopost"><div class="sost sost-zel">● Счёт сошёлся: '
                f"положено {приёмная.положено} = принято {приёмная.принято} + "
                f"отвергнуто {приёмная.отвергнуто} + ждёт {приёмная.ждёт}"
                "</div></div>")
    свой = приёмная.свод().get("почему_не_сошлось", "")
    return ('<div class="vrezka"><b>⚠ Счёт не сошёлся</b>'
            f"<span>{_т(свой)}</span></div>")


def оговорка_html() -> str:
    """Что показывает эта часть экрана и чего не показывает."""
    return ('<div class="tih">Здесь судьба файлов последней подачи. Клиент, '
            "период, состояние набора и счёт за все подачи — выше, в партии "
            "(шаг 86): приём судит о файле, партия складывает файлы в "
            "набор.</div>")


