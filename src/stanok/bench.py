# Семь условий раздела 17.3. Неизвестное — невыполненное.
УСЛОВИЯ_ДОПУСКА = (
    "объявлены владелец, версия, риск и область применения",
    "закрытый корпус не использовался для настройки",
    "far, покрытие, критические поля и нагрузка проверки в объявленных пределах",
    "испытания безопасности и воспроизводимости выполнены",
    "случайная контрольная выборка и слежение за дрейфом настроены",
    "ограничения и неподдерживаемые случаи названы",
    "отчёт допуска подписан",
)


@dataclass(frozen=True, slots=True)
class Допуск:
    """Итог 17.3. Балл надёжности до испытаний не присваивается."""

    допущен: bool
    невыполненные: tuple
    измерение: "Измерение | None" = None

    def as_json(self) -> dict:
        return {"допущен": self.допущен,
                "невыполненные": list(self.невыполненные),
                "балл_надёжности": None,
                "почему_нет_балла": "балл надёжности до испытаний не "
                                    "присваивается (раздел 17.3)"}


def проверить_допуск(измерение: Измерение, объявлено: dict) -> Допуск:
    """Допускает шаблон или называет невыполненные слагаемые поимённо.

    Причина отказа обязана называть слагаемое: «не прошло» — не причина.
    """
    невыполненные = []

    def слагаемое(номер: int, выполнено):
        if выполнено is not True:
            невыполненные.append(
                f"{УСЛОВИЯ_ДОПУСКА[номер]}: "
                + ("неизвестно" if выполнено is None else "не выполнено"))

    слагаемое(0, объявлено.get("паспорт"))
    слагаемое(1, объявлено.get("закрытый_корпус_не_трогали"))

    # Слагаемое 17.3 о пределах разложено поимённо: общее «не прошло» ничего не
    # называет, а причина отказа обязана называть слагаемое.
    for имя in (ГЛАВНАЯ, "потеря_покрытия", "ошибка_критических_полей",
                "нагрузка_проверки"):
        оценка = измерение.оценки[имя]
        if оценка.в_пороге is True:
            continue
        if оценка.в_пороге is False:
            почему = "вне объявленного предела"
        elif оценка.значение is None:
            почему = "метрика неизвестна: " + (оценка.почему_неизвестно
                                               or "мерить нечего")
        else:
            почему = "предел не объявлен: сравнивать не с чем"
        невыполненные.append(f"{имя}: {почему}")
    слагаемое(3, объявлено.get("испытания"))
    слагаемое(4, объявлено.get("выборка_и_дрейф"))
    слагаемое(5, объявлено.get("ограничения_названы"))
    слагаемое(6, объявлено.get("отчёт_подписан"))

    return Допуск(not невыполненные, tuple(невыполненные), измерение)


# ------------------------------------------------------------------ свод


def свод(измерение: Измерение, допуск: Допуск | None = None) -> dict:
    """То, что кладётся в отчёт. Ноль ошибок здесь всегда с числом наблюдений."""
    главная = измерение.главная
    граница = главная.граница()
    свой = {
        "версия": BENCH_VERSION,
        "метрик": len(МЕТРИКИ),
        "главная": главная.as_json(),
        "счёт_наблюдений": измерение.счёт.as_json(),
        "известны": sorted(имя for имя, о in измерение.оценки.items()
                           if о.известна),
        "неизвестны": {имя: о.почему_неизвестно
                       for имя, о in измерение.оценки.items()
                       if not о.известна},
        "слабейший_сегмент": измерение.слабейший,
        "ограничения": list(KNOWN_LIMITATIONS),
    }
    if граница is not None:
        свой["при_нуле_ошибок"] = граница.словами()
    if допуск is not None:
        свой["допуск"] = допуск.as_json()
    return свой


