"""Стенд измерения: девять метрик раздела 17. Шаг 51.

Стенд строится **до** размеченного корпуса намеренно. Метрики, посчитанные
наспех в тот день, когда документы наконец появились, — это метрики, подогнанные
под то, что получилось. Стенд, написанный заранее, считает то, что объявлено.

Три вещи, ради которых он существует именно в таком виде.

**Главная метрика — доля ошибочного автодопуска.** Сколько неверных записей
прошло в результат, не попав к человеку. Остальные восемь её не заменяют: нулевой
FAR легко получить, отправив человеку всё, и потому рядом всегда стоит доля
автоматизации. Но годен ли шаблон — решает FAR.

**Ноль обнаруженных ошибок — не «ошибок нет».** При нуле стенд обязан назвать
верхнюю границу по правилу трёх и сказать, скольких наблюдений не хватает до
объявленного порога. Отчёт «ошибок не найдено» без числа наблюдений — не
измерение, а его отсутствие.

**Наблюдения считаются по документам и источникам, а не по строкам.** Тысяча
строк одной выписки — это одно испытание оснастки на одной вёрстке одного банка,
а не тысяча испытаний. Точечная доля считается по записям, потому что так она
определена в 17.1, — но статистическая граница считается по независимому счёту, и
связывающей берётся самая скупая из оценок.

Неизвестное здесь **не считается верным**. Запись без эталона не улучшает ни
одной метрики: она уходит в отдельный счёт «неизвестно», и метрика, у которой
неизвестного больше, чем измеренного, объявляет об этом прямо.
"""

