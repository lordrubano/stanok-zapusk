@dataclass(frozen=True, slots=True)
class Наблюдение:
    """Одна разобранная запись со всем, чем она относится к сегменту.

    ``источник`` — то, по чему считается независимость. Две выписки одного счёта
    — один источник, сколько бы строк в них ни было.
    """

    record_id: str
    документ: str
    источник: str
    семейство: str
    шаблон: str
    версия_шаблона: str
    статус: str
    значения: dict = field(default_factory=dict)
    класс_риска: str = "неизвестен"
    подгруппа: str = ""
    пригодна: bool = True

    def __post_init__(self):
        for имя in ("record_id", "документ", "источник", "шаблон",
                    "версия_шаблона"):
            if not str(getattr(self, имя) or "").strip():
                raise МеркаНеОбъявлена(
                    f"наблюдение {self.record_id!r}: не объявлено «{имя}»")


