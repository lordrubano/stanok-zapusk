@dataclass(frozen=True, slots=True)
class Счёт:
    """Сколько независимых наблюдений стоит за оценкой.

    Записей всегда больше всего, источников — меньше всего. Число, которым
    подпирается статистика, — самое скупое из трёх.
    """

    записей: int = 0
    документов: int = 0
    источников: int = 0

    @property
    def связывающий(self) -> int:
        return self.источников

    def as_json(self) -> dict:
        return {"записей": self.записей, "документов": self.документов,
                "источников": self.источников,
                "связывающий": self.связывающий}


def _счёт(наблюдения) -> Счёт:
    свои = tuple(наблюдения)
    return Счёт(len(свои), len({н.документ for н in свои}),
                len({н.источник for н in свои}))


@dataclass(frozen=True, slots=True)
class Граница:
    """Верхняя граница по правилу трёх и чего не хватает до порога."""

    наблюдений: int
    по_чему: str
    граница: Decimal | None
    порог: Decimal | None = None
    нужно: int | None = None

    @property
    def не_хватает(self) -> int | None:
        if self.нужно is None:
            return None
        return max(0, self.нужно - self.наблюдений)

    @property
    def достаточно(self) -> bool | None:
        нехватка = self.не_хватает
        return None if нехватка is None else нехватка == 0

    def словами(self) -> str:
        кому = ПО_СЧЁТУ.get(self.по_чему, self.по_чему)
        if self.граница is None:
            return (f"наблюдений по {кому} нет вовсе: "
                    "вероятность ошибки неизвестна")
        сказано = (f"ошибок не обнаружено на {self.наблюдений} наблюдениях "
                   f"по {кому}; это не «ошибок нет», а верхняя граница "
                   f"вероятности ошибки около {self.граница}")
        if self.нужно is None:
            if self.порог is None:
                return сказано + "; порог не объявлен, и сравнивать не с чем"
            # Нулевой или отрицательный порог правилом трёх недостижим ни при
            # каком числе наблюдений: 3/N положительно всегда. Сказать «не
            # хватает столько-то» здесь значило бы обещать достижимое.
            return (сказано + f"; объявленный порог {self.порог} правилом трёх "
                    "недостижим при любом числе наблюдений: граница 3/N "
                    "положительна всегда")
        if self.не_хватает:
            return (сказано + f"; до объявленного порога {self.порог} не "
                    f"хватает {self.не_хватает} наблюдений по {кому} "
                    f"(нужно {self.нужно})")
        return сказано + f"; объявленного порога {self.порог} граница достигла"


def правило_трёх(наблюдений: int, порог: Decimal | None = None,
                 по_чему: str = СВЯЗЫВАЮЩИЙ) -> Граница:
    """Верхняя граница при нуле ошибок и нехватка до объявленного порога."""
    if наблюдений <= 0:
        return Граница(0, по_чему, None, порог, _нужно(порог))
    with localcontext() as ктx:
        ктx.prec = 12
        граница = ПРАВИЛО_ТРЁХ / Decimal(наблюдений)
    return Граница(наблюдений, по_чему, граница, порог, _нужно(порог))


def _нужно(порог: Decimal | None) -> int | None:
    """Сколько независимых чистых наблюдений нужно, чтобы граница влезла в порог."""
    if порог is None or порог <= 0:
        return None
    точное = ПРАВИЛО_ТРЁХ / порог
    целое = int(точное)
    return целое if Decimal(целое) == точное else целое + 1


@dataclass(frozen=True, slots=True)
class Оценка:
    """Одна метрика на одном сегменте."""

    имя: str
    числитель: int = 0
    знаменатель: int = 0
    неизвестно: int = 0
    счёт: Счёт = field(default_factory=Счёт)
    почему_неизвестно: str = ""
    порог: Decimal | None = None
    подробности: dict = field(default_factory=dict)

    @property
    def значение(self) -> Decimal | None:
        if self.знаменатель <= 0:
            return None
        with localcontext() as ктx:
            ктx.prec = 12
            return Decimal(self.числитель) / Decimal(self.знаменатель)

    @property
    def известна(self) -> bool:
        return self.значение is not None

    @property
    def неизвестного_больше_измеренного(self) -> bool:
        """Метрика, у которой неизвестного больше, чем измеренного, — не
        метрика, а её видимость."""
        return self.неизвестно > self.знаменатель

    @property
    def в_пороге(self) -> bool | None:
        """``None`` — неизвестно, и воротами это считается невыполненным."""
        значение = self.значение
        if значение is None or self.порог is None:
            return None
        return значение <= self.порог

    def граница(self) -> Граница | None:
        """Правило трёх. Считается при нуле обнаруженных ошибок."""
        if self.числитель != 0 or self.знаменатель <= 0:
            return None
        return правило_трёх(self.счёт.связывающий, self.порог)

    def as_json(self) -> dict:
        значение = self.значение
        граница = self.граница()
        свой = {
            "имя": self.имя,
            "числитель": self.числитель,
            "знаменатель": self.знаменатель,
            "неизвестно": self.неизвестно,
            "значение": None if значение is None else str(значение),
            "счёт": self.счёт.as_json(),
            "порог": None if self.порог is None else str(self.порог),
            "в_пороге": self.в_пороге,
        }
        if self.почему_неизвестно:
            свой["почему_неизвестно"] = self.почему_неизвестно
        if self.неизвестного_больше_измеренного:
            свой["предупреждение"] = (
                "неизвестного больше измеренного: метрике верить нельзя")
        if граница is not None:
            свой["при_нуле_ошибок"] = {
                "наблюдений": граница.наблюдений,
                "по_чему": граница.по_чему,
                "верхняя_граница": None if граница.граница is None
                else str(граница.граница),
                "нужно_наблюдений": граница.нужно,
                "не_хватает": граница.не_хватает,
                "сказано": граница.словами(),
            }
        if self.подробности:
            свой["подробности"] = self.подробности
        return свой


# ------------------------------------------------------- девять метрик


def far_автодопуска(наблюдения, эталон, критические, порог=None) -> Оценка:
    """Ошибочные ``ACCEPTED_AUTO`` / все ``ACCEPTED_AUTO``. Главный показатель.

    Неверная запись, прошедшая мимо человека, — это то, ради чего вся машина
    может оказаться негодной. Записи автодопуска без эталона в знаменатель не
    идут: неизвестное не улучшает главную метрику.
    """
    свои = [н for н in наблюдения if н.статус == ACCEPTED_AUTO]
    ошибочных = измеренных = неизвестных = 0
    измеримые = []
    for н in свои:
        верна = _сличить(н, эталон, критические)
        if верна is None:
            неизвестных += 1
            continue
        измеренных += 1
        измеримые.append(н)
        if not верна:
            ошибочных += 1
    return Оценка(
        "far_автодопуска", ошибочных, измеренных, неизвестных, _счёт(измеримые),
        "" if измеренных else "ни одна автодопущенная запись не имеет эталона",
        порог)


def доля_автоматизации(наблюдения, эталон, критические, порог=None) -> Оценка:
    """Корректные ``ACCEPTED_AUTO`` / все пригодные записи.

    Стоит рядом с FAR не случайно: нулевой FAR получается отправкой человеку
    всего, и без этой метрики он был бы похвалой безделью.
    """
    пригодные = [н for н in наблюдения if н.пригодна]
    верных = неизвестных = 0
    for н in пригодные:
        if н.статус != ACCEPTED_AUTO:
            continue
        верна = _сличить(н, эталон, критические)
        if верна is None:
            неизвестных += 1
        elif верна:
            верных += 1
    return Оценка("доля_автоматизации", верных, len(пригодные), неизвестных,
                  _счёт(пригодные),
                  "" if пригодные else "пригодных записей нет", порог)


def нагрузка_проверки(наблюдения, порог=None) -> Оценка:
    """REVIEW / все записи. Стоимость эксплуатации.

    Эталона не требует: сколько записей ушло человеку, известно из решений.
    """
    свои = list(наблюдения)
    ушедших = sum(1 for н in свои if н.статус == REVIEW)
    return Оценка("нагрузка_проверки", ушедших, len(свои), 0, _счёт(свои),
                  "" if свои else "записей нет", порог)


def ошибка_критических_полей(наблюдения, эталон, критические,
                             порог=None) -> Оценка:
    """Неверные денежные и опознавательные поля / все такие поля.

    Считается по полям, а не по записям: запись неверна и от одного поля, и от
    пяти, а цена этого разная.
    """
    верных = неверных = неизвестных = 0
    свои = list(наблюдения)
    for н in свои:
        в, нв, ни = _поля_врозь(н, эталон, критические)
        верных += в
        неверных += нв
        неизвестных += ни
    измерено = верных + неверных
    return Оценка("ошибка_критических_полей", неверных, измерено, неизвестных,
                  _счёт(свои),
                  "" if измерено else "ни одно критическое поле не размечено",
                  порог, {"полей_на_запись": len(tuple(критические))})


def потеря_покрытия(покрытие: Покрытие | None, порог=None) -> Оценка:
    """Необнаруженные или неизвестные объекты / все эталонные объекты.

    Главная слепая зона хешей: хеш совпал на том, что нашлось, и молчит о том,
    что не нашлось вовсе.
    """
    if покрытие is None or покрытие.эталонных <= 0:
        return Оценка("потеря_покрытия", 0, 0, 0, Счёт(),
                      "эталонных объектов не объявлено: покрытие неизвестно",
                      порог)
    потеряно = (max(0, покрытие.эталонных - покрытие.обнаруженных)
                + покрытие.неизвестных)
    return Оценка("потеря_покрытия", потеряно, покрытие.эталонных, 0,
                  Счёт(покрытие.эталонных, 0, 0), "", порог,
                  {"обнаружено": покрытие.обнаруженных,
                   "неизвестных": покрытие.неизвестных})


def ложная_тревога(наблюдения, эталон, критические, порог=None) -> Оценка:
    """Правильные записи, ошибочно отправленные в REVIEW или REJECTED.

    Знаменатель — все правильные записи: метрика отвечает на вопрос «как часто
    верную запись зря беспокоят», а не «какая доля проверки была напрасной».
    """
    верных = []
    тревог = неизвестных = 0
    for н in наблюдения:
        верна = _сличить(н, эталон, критические)
        if верна is None:
            неизвестных += 1
            continue
        if not верна:
            continue
        верных.append(н)
        if н.статус in (REVIEW, REJECTED):
            тревог += 1
    return Оценка("ложная_тревога", тревог, len(верных), неизвестных,
                  _счёт(верных),
                  "" if верных else "ни одна запись не подтверждена эталоном",
                  порог)


def _доля_целых(значения, доля: str) -> Decimal | None:
    """Порядковый процентиль: значение, ниже которого лежит объявленная доля.

    Берётся ближайший ранг, без вымышленной середины между наблюдениями: p95 на
    трёх замерах — это третий замер, а не выдуманное число между вторым и
    третьим.
    """
    свои = sorted(значения)
    if not свои:
        return None
    место = (Decimal(доля) * Decimal(len(свои))).to_integral_value(
        rounding=ROUND_CEILING)
    номер = max(1, min(len(свои), int(место)))
    return свои[номер - 1]


def производительность(замеры, порог=None) -> Оценка:
    """Страницы и записи, p50 и p95 по классам документов.

    Порога у неё нет: производительность планируют, а не допускают, — и потому
    её место в своде рядом с прочими, а не в воротах.
    """
    свои = list(замеры)
    if not свои:
        return Оценка("производительность", 0, 0, 0, Счёт(),
                      "замеров времени нет", порог)
    по_классам = {}
    for класс in sorted({з.класс for з in свои}):
        свои_класса = [з for з in свои if з.класс == класс]
        секунды = [з.секунд for з in свои_класса]
        по_классам[класс] = {
            "документов": len(свои_класса),
            "страниц": sum(з.страниц for з in свои_класса),
            "записей": sum(з.записей for з in свои_класса),
            "p50_секунд": str(_доля_целых(секунды, "0.50")),
            "p95_секунд": str(_доля_целых(секунды, "0.95")),
        }
    return Оценка("производительность", 0, len(свои), 0,
                  Счёт(0, len({з.документ for з in свои}), 0), "", порог,
                  {"по_классам": по_классам})


def полная_стоимость(стоимости, порог=None) -> Оценка:
    """Вычисления, API, хранение и минуты проверки — на документ."""
    свои = list(стоимости)
    if not свои:
        return Оценка("полная_стоимость", 0, 0, 0, Счёт(),
                      "слагаемые стоимости не объявлены", порог)
    всего = sum((с.всего for с in свои), Decimal(0))
    сложить = lambda имя: sum((getattr(с, имя) for с in свои), Decimal(0))
    with localcontext() as ктx:
        ктx.prec = 12
        на_документ = всего / Decimal(len(свои))
    return Оценка("полная_стоимость", 0, len(свои), 0,
                  Счёт(0, len({с.документ for с in свои}), 0), "", порог,
                  {"всего": str(всего),
                   "на_документ": str(на_документ),
                   "вычисления": str(сложить("вычисления")),
                   "api": str(сложить("api")),
                   "хранение": str(сложить("хранение")),
                   "минут_проверки": str(сложить("минут_проверки"))})


def дрейф_шаблона(текущие: dict, допущенные: dict | None) -> Оценка:
    """Изменение ошибок и нагрузки проверки против допущенной версии.

    Первой версии сравнивать не с чем, и дрейф у неё **неизвестен, а не нулевой**:
    отсутствие сравнения — не доказательство неизменности.
    """
    if not допущенные:
        return Оценка("дрейф_шаблона", 0, 0, 0, Счёт(),
                      "допущенной версии для сравнения нет: дрейф неизвестен")
    сдвиги = {}
    ушедших = 0
    for имя in (ГЛАВНАЯ, "нагрузка_проверки", "ошибка_критических_полей"):
        было, стало = допущенные.get(имя), текущие.get(имя)
        if было is None or стало is None:
            сдвиги[имя] = None
            continue
        сдвиг = Decimal(str(стало)) - Decimal(str(было))
        сдвиги[имя] = str(сдвиг)
        if сдвиг > 0:
            ушедших += 1
    измеренных = sum(1 for з in сдвиги.values() if з is not None)
    return Оценка("дрейф_шаблона", ушедших, измеренных,
                  len(сдвиги) - измеренных, Счёт(), "", None,
                  {"сдвиги": сдвиги,
                   "ухудшилось": ушедших,
                   "как_читать": "положительный сдвиг — ухудшение: ошибок или "
                                 "ручного труда стало больше"})


# ------------------------------------------------------------- сегменты


ПО_ЧЕМУ = ("семейство", "шаблон", "версия_шаблона", "класс_риска", "подгруппа")


def сегменты(наблюдения, по_чему=ПО_ЧЕМУ) -> dict:
    """Делит наблюдения по объявленным меркам.

    «Средняя по системе не заменяет слабейший критический сегмент» — раздел
    17.1. Поэтому сегменты считаются всегда, а не по просьбе.
    """
    свои = {}
    for н in наблюдения:
        for мерка in по_чему:
            значение = str(getattr(н, мерка, "") or "")
            if not значение:
                continue
            свои.setdefault(f"{мерка}={значение}", []).append(н)
    return свои


# ----------------------------------------------------------------- стенд


@dataclass(frozen=True, slots=True)
class Измерение:
    """Всё измеренное на одном прогоне стенда."""

    версия: str
    оценки: dict
    счёт: Счёт
    по_сегментам: dict = field(default_factory=dict)
    слабейший: dict | None = None

    @property
    def главная(self) -> Оценка:
        return self.оценки[ГЛАВНАЯ]

    def as_json(self) -> dict:
        return {
            "версия": self.версия,
            "счёт": self.счёт.as_json(),
            "главная_метрика": ГЛАВНАЯ,
            "оценки": {имя: о.as_json() for имя, о in self.оценки.items()},
            "по_сегментам": {
                имя: {м: о.as_json() for м, о in оценки.items()}
                for имя, оценки in self.по_сегментам.items()},
            "слабейший_сегмент": self.слабейший,
        }


def измерить(наблюдения, эталон, критические, пороги: Пороги | None = None,
             покрытие: Покрытие | None = None, замеры=(), стоимости=(),
             допущенные: dict | None = None, по_сегментам: bool = True) -> Измерение:
    """Считает все девять метрик разом.

    Разом — намеренно: метрика, посчитанная в одиночку, легко оказывается той
    самой, которая вышла удачной. Девять считаются вместе или не считаются.
    """
    свои = list(наблюдения)
    эталон = dict(эталон or {})
    критические = tuple(критические)
    пороги = пороги or Пороги()

    оценки = _девять(свои, эталон, критические, пороги, покрытие, замеры,
                     стоимости, допущенные)
    измерение_сегментов = {}
    if по_сегментам:
        for имя, часть in сегменты(свои).items():
            измерение_сегментов[имя] = _девять(
                часть, эталон, критические, пороги, None, (), (), None)

    return Измерение(BENCH_VERSION, оценки, _счёт(свои), измерение_сегментов,
                     _слабейший(измерение_сегментов))


def _девять(наблюдения, эталон, критические, пороги, покрытие, замеры,
            стоимости, допущенные) -> dict:
    главная = far_автодопуска(наблюдения, эталон, критические,
                              пороги.для("far_автодопуска"))
    нагрузка = нагрузка_проверки(наблюдения, пороги.для("нагрузка_проверки"))
    критические_поля = ошибка_критических_полей(
        наблюдения, эталон, критические,
        пороги.для("ошибка_критических_полей"))
    текущие = {
        ГЛАВНАЯ: None if главная.значение is None else str(главная.значение),
        "нагрузка_проверки": None if нагрузка.значение is None
        else str(нагрузка.значение),
        "ошибка_критических_полей": None if критические_поля.значение is None
        else str(критические_поля.значение),
    }
    оценки = {
        ГЛАВНАЯ: главная,
        "доля_автоматизации": доля_автоматизации(
            наблюдения, эталон, критические, пороги.для("доля_автоматизации")),
        "нагрузка_проверки": нагрузка,
        "ошибка_критических_полей": критические_поля,
        "потеря_покрытия": потеря_покрытия(покрытие,
                                           пороги.для("потеря_покрытия")),
        "ложная_тревога": ложная_тревога(наблюдения, эталон, критические,
                                         пороги.для("ложная_тревога")),
        "производительность": производительность(замеры),
        "полная_стоимость": полная_стоимость(стоимости),
        "дрейф_шаблона": дрейф_шаблона(текущие, допущенные),
    }
    # Порядок ключей — порядок таблицы 17.1, и десятой метрики здесь не будет.
    assert tuple(оценки) == МЕТРИКИ, "состав метрик разошёлся с разделом 17.1"
    return оценки


def _слабейший(по_сегментам: dict) -> dict | None:
    """Сегмент с худшей главной метрикой. Средняя по системе его не заменяет."""
    худший = None
    for имя, оценки in по_сегментам.items():
        значение = оценки[ГЛАВНАЯ].значение
        if значение is None:
            continue
        if худший is None or значение > худший[1]:
            худший = (имя, значение)
    if худший is None:
        return None
    return {"сегмент": худший[0], "метрика": ГЛАВНАЯ,
            "значение": str(худший[1])}


