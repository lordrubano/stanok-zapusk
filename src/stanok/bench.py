# ------------------------------------------------------------- сличение


def _сличить(наблюдение: Наблюдение, эталон: dict, критические) -> bool | None:
    """Верна ли запись. ``None`` — эталона нет, и это не «верна».

    Сличение дословное: эталон хранит то, что человек увидел в документе, и
    «переписать по-своему» тут значит подогнать эталон под разбор.
    """
    свой = эталон.get(наблюдение.record_id)
    if свой is None:
        return None
    for поле in критические:
        если_эталон = свой.get(поле)
        if если_эталон is None:
            return None
        if str(наблюдение.значения.get(поле, "")) != str(если_эталон):
            return False
    return True


def _поля_врозь(наблюдение: Наблюдение, эталон: dict,
                критические) -> tuple[int, int, int]:
    """Считает критические поля по одному: верных, неверных, неизвестных.

    Запись целиком неверна и от одного поля, и от пяти. Цена ошибки при этом
    разная, и потому поля считаются отдельно от записей.
    """
    свой = эталон.get(наблюдение.record_id)
    верных = неверных = неизвестных = 0
    for поле in критические:
        ожидание = None if свой is None else свой.get(поле)
        if ожидание is None:
            неизвестных += 1
        elif str(наблюдение.значения.get(поле, "")) == str(ожидание):
            верных += 1
        else:
            неверных += 1
    return верных, неверных, неизвестных


