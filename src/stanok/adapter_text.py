# -*- coding: utf-8 -*-
"""Образцовый адаптер: сплошной текст построчно.

Часть шага 25, но **не** штатный маршрут. Нативные маршруты DOCX и XLSX — шаг
26, банковские форматы — шаг 27, разбор PDF — шаг 28. Этот адаптер существует
затем, чтобы розетка была проверена на настоящей работе, а не только на
подставных вилках, и чтобы у следующих адаптеров был образец контракта.

Ядро о нём не знает и знать не должно: подключение делает тот, кто собирает
станок, а не сам станок. Поэтому здесь нет ни одной строки, которая сама себя
куда-то втыкает.

Что даёт на выходе: по объекту источника на строку. Страница одна, полигона
нет — у сплошного текста области на странице не существует, а выдумывать её
значило бы дать ложный адрес.
"""

from __future__ import annotations

from collections.abc import Iterator

from .adapters import SourceObject


class ТекстПострочно:
    """Читает сплошной текст и отдаёт по объекту источника на строку."""

    имя = "текст-построчно"
    версия = "1"
    форматы = frozenset({"txt", "csv", "md"})

    # Кодировка одна и строгая. Перебор кодировок выглядит заботливым, но
    # однобайтовые кодировки принимают почти любые байты и превращают их в
    # правдоподобную кашу: текст выглядит настоящим и уходит дальше
    # незамеченным. Неизвестное не равно правильному — лучше отказ.
    #
    # Кодировку, отличную от UTF-8, объявляет шаблон семейства (шаг 37), и
    # тогда она придёт сюда явно, а не будет угадана.
    кодировки = ("utf-8",)

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        текст = self._раскодировать(данные)
        document_id = getattr(конверт, "document_id", "") or ""
        for номер, строка in enumerate(текст.splitlines(), start=1):
            yield SourceObject(
                document_id=document_id,
                страница=1,
                система_координат="без координат",
                структурный_путь=f"строка[{номер}]",
                сырой_текст=строка,
                полигон=None,
            )

    def _раскодировать(self, данные: bytes) -> str:
        for кодировка in self.кодировки:
            try:
                return данные.decode(кодировка)
            except UnicodeDecodeError:
                continue
        raise ValueError(
            "текст не прочитан ни в одной из известных кодировок: "
            + ", ".join(self.кодировки))


__all__ = ["ТекстПострочно"]
