# -*- coding: utf-8 -*-
"""Предупреждения о значении: где станок решал, а не читал.

Работа вне нумерации, Фаза 4. Нормативная основа — чертёж v3.0, раздел 10.1
(слагаемое ``no_value_warning``).

**Определение утверждено владельцем 04.08.2026.** Предупреждение о значении
возникает в двух случаях:

1. **значение получено правилом, разрешившим неоднозначность** — сырьё
   допускало несколько прочтений, и выбор между ними сделало объявление
   оснастки, а не сам документ;
2. **нормализация изменила написание** — итог отличается от того, что стоит в
   источнике, не только видом, но и знаками.

До сих пор такого понятия в станке не было вовсе, и слагаемое допуска оставалось
неизвестным просто потому, что никто не сказал, что это.

**Предупреждение — не ошибка.** Правило, разрешившее неоднозначность, могло
разрешить её верно; нормализация могла изменить написание к лучшему. Оно
означает другое: **здесь станок решал, а не читал**, и решение стоит на
объявлении семейства. Ошибись объявление — ошибётся и значение, а по самому
значению этого видно не будет.

Отсюда и место предупреждения в формуле допуска: оно **блокирует
автоматический допуск**, а не понижает уверенность. Запись, где станок решал,
смотрит человек.

**Предупреждение не выносит суждения о верности.** Оно называет место и правило,
которым это место разрешено, — и молчит о том, верен ли выбор. Судить о верности
может только сверка с бумагой, а её нет.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass


WARNINGS_VERSION = "value-warnings/1"

# Разрешение неоднозначности и правка написания — два разных рода, и смешивать
# их нельзя: первое про выбор прочтения, второе про то, что итог отличается от
# написанного.
РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ = "правило разрешило неоднозначность"
ИЗМЕНЕНО_НАПИСАНИЕ = "нормализация изменила написание"

KNOWN_LIMITATIONS = (
    "Неоднозначность распознаётся по виду сырья и объявленным правилам, а не "
    "по следу, оставленному типизатором: своей записи о применённом правиле он "
    "не ведёт. Способ верен для тех неоднозначностей, что типизатор объявил "
    "(порядок даты, неявные копейки, знак в скобках); для будущих правил "
    "придётся дополнять и это место.",
    "Изменение написания сравнивается с NFC-приведением сырья. Правка "
    "пробелов, которую делает нормализация текста, здесь предупреждением не "
    "считается: это приведение вида, а не знаков.",
    "Предупреждение молчит о верности выбора. Верен он или нет, показывает "
    "только сверка с бумагой.",
)

_ЧИСЛОВАЯ_ДАТА = re.compile(r"^(\d{1,2})[./-](\d{1,2})[./-](\d{4})$")
_БЕЗ_РАЗДЕЛИТЕЛЯ = re.compile(r"^[+-]?\d+$")
_В_СКОБКАХ = re.compile(r"^\(.*\)$")


@dataclass(frozen=True, slots=True)
class Предупреждение:
    """Место, где станок решал, и правило, которым решил."""

    поле: str
    род: str
    сырьё: str | None
    правило: str
    пояснение: str = ""

    def as_json(self) -> dict:
        return {"версия": WARNINGS_VERSION, "поле": self.поле, "род": self.род,
                "сырьё": self.сырьё, "правило": self.правило,
                "пояснение": self.пояснение}


def _неоднозначная_дата(сырьё: str) -> bool:
    """Сырьё, которое читается двумя способами и разрешается объявлением.

    ``03.04.2026`` — третье апреля или четвёртое марта. ``17.04.2026``
    однозначно: семнадцатого месяца не бывает, и правило порядка тут ничего не
    решало, только подтвердило.
    """
    совпало = _ЧИСЛОВАЯ_ДАТА.match(сырьё.strip())
    if not совпало:
        return False
    первое, второе = int(совпало.group(1)), int(совпало.group(2))
    if первое == второе:
        # 12.12 читается двояко только на словах: оба прочтения дают одну и ту
        # же дату, и объявление семейства здесь ничего не решило. Считать это
        # предупреждением значило бы гнать человека смотреть на пустое место —
        # а именно эти места и составляют главную долю его труда.
        return False
    return первое <= 12 and второе <= 12


def предупреждения_поля(поле: str, истолкование, правила) -> tuple:
    """Предупреждения по одному полю. Пустой ответ — станок только читал."""
    сырьё = getattr(истолкование, "raw", None)
    значение = getattr(истолкование, "value", None)
    вид = getattr(истолкование, "вид", "") or ""
    if сырьё is None or значение is None:
        # Поле без истолкования — это отказ, а не предупреждение. Смешивать их
        # нельзя: отказ виден сам по себе, предупреждение — нет.
        return ()

    свои = []
    текст = str(сырьё).strip()

    if вид == "дата" and _неоднозначная_дата(текст):
        свои.append(Предупреждение(
            поле, РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ, сырьё,
            f"порядок частей даты {правила.порядок_даты!r}",
            "обе первые части не больше двенадцати: запись читается и как день "
            "с месяцем, и как месяц с днём"))

    if вид == "деньги":
        без_знаков = текст.strip("()")
        if _БЕЗ_РАЗДЕЛИТЕЛЯ.match(без_знаков.replace(" ", "").replace(" ", "")):
            if правила.неявные_копейки is not None:
                свои.append(Предупреждение(
                    поле, РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ, сырьё,
                    f"неявные копейки: {'да' if правила.неявные_копейки else 'нет'}",
                    "в записи нет разделителя дробной части: она читается и как "
                    "целое, и как сумма с копейками"))
        if _В_СКОБКАХ.match(текст) and правила.знак_в_скобках:
            свои.append(Предупреждение(
                поле, РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ, сырьё,
                "знак в скобках означает минус",
                "скобки означают минус не везде: это соглашение семейства"))

    приведённое = unicodedata.normalize("NFC", str(сырьё))
    if приведённое != str(сырьё):
        свои.append(Предупреждение(
            поле, ИЗМЕНЕНО_НАПИСАНИЕ, сырьё, "приведение к NFC",
            "итог отличается от источника знаками, а не только видом"))
    elif (вид == "текст" and isinstance(значение, str)
            and _без_пробелов(значение) != _без_пробелов(сырьё)):
        свои.append(Предупреждение(
            поле, ИЗМЕНЕНО_НАПИСАНИЕ, сырьё, "нормализация текста",
            "истолкованное написание не совпадает с исходным по знакам"))

    return tuple(свои)


def _без_пробелов(значение) -> str:
    """Написание без учёта расстановки пробелов.

    Свёртка пробельных цепочек — приведение **вида**, а не знаков, и
    предупреждением она не является: иначе предупреждение получало бы каждое
    поле, где в источнике два пробела подряд, и слагаемое допуска обращалось бы
    в шум. Первый прогон показал это буквально: у каждой записи обоих
    документов поле с реквизитом банка набрано с выравнивающими пробелами,
    и предупреждение приходило на все 4 145 записей разом.
    """
    return " ".join(str(значение).split())


def предупреждения_записи(поля: dict, правила) -> tuple:
    """Предупреждения по всем полям записи."""
    свои = []
    for имя in sorted(поля):
        свои.extend(предупреждения_поля(имя, поля[имя], правила))
    return tuple(свои)


def нет_предупреждений(предупреждения) -> bool:
    """Условие ``no_value_warning`` формулы 10.1.

    Истинно, когда станок нигде не решал, а только читал. Пустой набор здесь —
    именно то, что требуется, и это единственное слагаемое формулы, где
    пустота означает выполнение: предупреждений действительно может не быть.
    """
    return not tuple(предупреждения)


def свод(предупреждения) -> dict:
    предупреждения = tuple(предупреждения)
    по_родам: dict[str, int] = {}
    по_полям: dict[str, int] = {}
    для_правил: dict[str, int] = {}
    for п in предупреждения:
        по_родам[п.род] = по_родам.get(п.род, 0) + 1
        по_полям[п.поле] = по_полям.get(п.поле, 0) + 1
        для_правил[п.правило] = для_правил.get(п.правило, 0) + 1
    return {
        "версия": WARNINGS_VERSION,
        "предупреждений": len(предупреждения),
        "по_родам": по_родам,
        "по_полям": по_полям,
        "по_правилам": для_правил,
        "нет_предупреждений": нет_предупреждений(предупреждения),
    }


__all__ = ["WARNINGS_VERSION", "KNOWN_LIMITATIONS", "ИЗМЕНЕНО_НАПИСАНИЕ",
           "Предупреждение", "РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ", "нет_предупреждений",
           "предупреждения_записи", "предупреждения_поля", "свод"]
