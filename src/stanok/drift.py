# -*- coding: utf-8 -*-
"""Обнаружение дрейфа формы: банк поменял вёрстку — станок замечает первым.

Шаг 66 плана, последний в Фазе 6. Нормативная основа — чертёж v3.0, раздел 19.

**На этом стоит подписка на оснастку.** Банк меняет форму без предупреждения, и
клиент узнаёт об этом, когда сверка перестала сходиться, — то есть месяцем
позже и уже с испорченными данными. Станок обязан заметить раньше.

## Дрейф — не отказ

Документ может разобраться **успешно и при этом иначе, чем прежде**: полосы
колонок сдвинулись, шапка изменилась, поехала граница операции, изменилась доля
сомнительных записей. Каждое по отдельности законно; вместе это значит, что
форма поехала.

Поэтому дрейф не ловится отказом. Он ловится **сличением слепков**: у формы
снимается набор признаков, и новый документ сравнивается с тем, каким семейство
было прежде.

## Признаки не зависят от периода — иначе ловилась бы не форма, а календарь

Выписка за другой период законно отличается числом страниц, числом операций,
датами и суммами. Всё это в слепок **не входит**. Входит только то, что у одной
и той же формы обязано быть одинаковым в любом периоде:

* **полосы колонок** — доли листа, где стоят ячейки каждой колонки;
* **шапка** — набор заголовков и их места;
* **граница операции** — полоса, с которой начинается первая строка;
* **ориентация листа и поворот страниц**;
* **число колонок**;
* **доли**: сколько строк имеют ожидаемое число ячеек, сколько записей
  вызывают сомнение, сколько полей осталось неистолкованными.

Доли — числа от нуля до единицы, и от длины выписки они не зависят. Число
страниц, число записей и период не входят в слепок вовсе.

## Три исхода, а не два

* **форма та же** — расхождений в пределах допусков;
* **дрейф** — что-то поехало: полосы, доли, граница. Разбор ещё идёт, но
  оснастку пора смотреть;
* **другая форма** — расхождение по устройству: иное число колонок, иная
  ориентация, чужая шапка. Это не дрейф, а другой документ, и разбирать его
  прежней оснасткой нельзя.

Различие между вторым и третьим не косметическое: дрейф — повод проверить
оснастку, чужая форма — повод остановиться.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal


DRIFT_VERSION = "form-drift/1"

ТА_ЖЕ_ФОРМА = "форма та же"
ДРЕЙФ = "дрейф"
ДРУГАЯ_ФОРМА = "другая форма"

# Допуски. Числа объявлены здесь, а не спрятаны в вызове: менять их — решение.
ДОПУСК_ПОЛОСЫ = Decimal("0.01")
"""На сколько долей листа полоса колонки вправе съехать. Один процент ширины —
это порядка шести миллиметров на листе А4: меньше бывает от округления, больше
означает, что вёрстка поехала."""

ДОПУСК_ДОЛИ = Decimal("0.10")
"""На сколько вправе измениться доля — сомнительных записей, целых строк.
Десять процентных пунктов: обычная разница между периодами меньше, а сдвиг
формы больше."""

KNOWN_LIMITATIONS = (
    "Допуски назначены рассуждением, а не измерены: чтобы измерить обычный "
    "разброс формы, нужен ряд документов одного семейства за разные периоды, "
    "и его нет.",
    "Слепок описывает вёрстку, а не смысл. Банк, поменявший содержание колонок "
    "местами и сохранивший их места, для этих признаков неотличим от прежнего.",
    "Медленный дрейф — по чуть-чуть от периода к периоду — ловится только "
    "сравнением с первым слепком, а не с предыдущим. Оба сравнения нужны, и "
    "второе здесь не делается.",
    "Доля сомнительных записей зависит и от содержания документа: месяц с "
    "необычными операциями сдвинет её без всякого дрейфа формы.",
)


@dataclass(frozen=True, slots=True)
class Слепок:
    """Признаки формы, не зависящие от периода."""

    семейство: str
    версия_оснастки: str
    колонок: int
    ориентация: str
    поворот: int
    полосы: tuple = ()          # ((имя, левая, правая), …) — доли листа
    шапка: tuple = ()           # набор заголовков
    граница: tuple = ()         # (левая, правая) полосы начала операции
    доля_целых_строк: str = "0"
    доля_сомнительных: str = "0"
    доля_неистолкованных: str = "0"

    def as_json(self) -> dict:
        return {
            "версия": DRIFT_VERSION,
            "семейство": self.семейство,
            "версия_оснастки": self.версия_оснастки,
            "колонок": self.колонок,
            "ориентация": self.ориентация,
            "поворот": self.поворот,
            "полосы": [list(п) for п in self.полосы],
            "шапка": list(self.шапка),
            "граница": list(self.граница),
            "доля_целых_строк": self.доля_целых_строк,
            "доля_сомнительных": self.доля_сомнительных,
            "доля_неистолкованных": self.доля_неистолкованных,
        }


@dataclass(frozen=True, slots=True)
class Сдвиг:
    """Одно расхождение между слепками."""

    признак: str
    было: str
    стало: str
    отклонение: str = ""
    устройство: bool = False
    """Расхождение по устройству — не дрейф, а другая форма."""

    def as_json(self) -> dict:
        return {"признак": self.признак, "было": self.было, "стало": self.стало,
                "отклонение": self.отклонение, "устройство": self.устройство}


def _доля(сколько: int, всего: int) -> str:
    if not всего:
        return "0"
    return str((Decimal(сколько) / Decimal(всего)).quantize(Decimal("0.001")))


def снять_слепок(проводка, оснастка, экраны=()) -> Слепок:
    """Снимает признаки формы с проведённого документа.

    Ни числа страниц, ни числа записей здесь нет: слепок описывает форму, а не
    объём. Иначе выписка за год «дрейфовала» бы относительно выписки за месяц.
    """
    from .columns import колонки

    объекты = tuple(getattr(проводка, "объекты", ()))
    строки = tuple(getattr(getattr(проводка, "сегментация", None), "строки", ()))
    страницы = [о for о in объекты if о.свойство("вид") == "страница"]
    поворот = int(страницы[0].свойство("поворот") or 0) if страницы else 0
    ширина = страницы[0].свойство("ширина_пунктов") if страницы else None
    высота = страницы[0].свойство("высота_пунктов") if страницы else None
    ориентация = "неизвестна"
    if ширина and высота:
        ориентация = "альбомный" if float(ширина) > float(высота) else "книжный"

    объявленные = колонки(оснастка) or ()
    полосы = tuple(
        (к.get("имя", ""), str(к.get("слева", "")), str(к.get("справа", "")))
        for к in объявленные)
    граница_правило = getattr(оснастка, "граница_записи", None)
    граница = ()
    if isinstance(граница_правило, dict):
        граница = (str(граница_правило.get("слева", "")),
                   str(граница_правило.get("справа", "")))

    ожидаемых_ячеек = len(объявленные) - 1 if объявленные else 0
    целых = sum(1 for с in строки if len(с.ячейки) >= max(1, ожидаемых_ячеек))
    записи = tuple(getattr(проводка, "записи", ()))
    неистолкованных = sum(
        1 for з in записи for поле in (з.get("fields") or {}).values()
        if isinstance(поле, dict) and поле.get("error"))
    полей = sum(len(з.get("fields") or {}) for з in записи)
    с_сомнением = sum(1 for э in экраны if getattr(э, "сомнения", ()))

    шапка = _шапка(строки, len(страницы))

    return Слепок(
        семейство=getattr(оснастка, "семейство", "") or "",
        версия_оснастки=getattr(оснастка, "версия", "") or "",
        колонок=len(объявленные),
        ориентация=ориентация,
        поворот=поворот,
        полосы=полосы,
        шапка=шапка,
        граница=граница,
        доля_целых_строк=_доля(целых, len(строки)),
        доля_сомнительных=_доля(с_сомнением, len(экраны) or len(записи)),
        доля_неистолкованных=_доля(неистолкованных, полей))


def _шапка(строки, страниц: int) -> tuple:
    """Строки, повторяющиеся на большинстве страниц, — это и есть шапка.

    Первые строки страницы брать нельзя: у первой страницы там реквизиты — счёт,
    период, остатки, — и они законно меняются от выписки к выписке. Шапка же
    печатается на каждой странице, и потому узнаётся повторяемостью, а не
    местом. Это и делает признак независимым от периода: чужой период поменяет
    реквизиты, но не заголовки колонок.
    """
    if страниц < 2:
        return ()
    по_страницам: dict[str, set] = {}
    for строка in строки:
        текст = (строка.текст or "").strip()[:48]
        if текст:
            по_страницам.setdefault(текст, set()).add(строка.страница)
    # Девять десятых страниц, а не половина: в длинной выписке случайные
    # повторы встречаются на многих страницах, и половина набирает лишнего.
    # Настоящая шапка печатается на каждой странице.
    порог = max(2, int(страниц * 0.9))
    повторяющиеся = sorted(т for т, где in по_страницам.items()
                           if len(где) >= порог)
    return tuple(повторяющиеся[:12])


def _числом(значение: str) -> Decimal | None:
    try:
        return Decimal(str(значение))
    except Exception:      # noqa: BLE001 — значение может быть чем угодно
        return None


def сличить(было: Слепок, стало: Слепок, допуск_полосы: Decimal = ДОПУСК_ПОЛОСЫ,
            допуск_доли: Decimal = ДОПУСК_ДОЛИ) -> dict:
    """Сличает два слепка и называет каждое расхождение.

    Расхождения по устройству — число колонок, ориентация, поворот, шапка —
    означают **другую форму**, а не дрейф: разбирать такой документ прежней
    оснасткой нельзя. Съехавшие полосы и уплывшие доли означают дрейф: разбор
    ещё идёт, но оснастку пора смотреть.
    """
    сдвиги: list[Сдвиг] = []

    for признак in ("колонок", "ориентация", "поворот"):
        если_было, если_стало = getattr(было, признак), getattr(стало, признак)
        if если_было != если_стало:
            сдвиги.append(Сдвиг(признак, str(если_было), str(если_стало),
                                устройство=True))

    if было.шапка and стало.шапка and set(было.шапка) != set(стало.шапка):
        прежняя, нынешняя = set(было.шапка), set(стало.шапка)
        общее = прежняя & нынешняя
        # Вложенность — не дрейф. В длинной выписке на всех страницах повторится
        # больше строк, чем в короткой, и разность наборов тут говорит о длине
        # документа, а не о форме. Дрейф — когда строки **и** пропали, **и**
        # появились: набор не вырос, а сменился.
        вложено = прежняя <= нынешняя or нынешняя <= прежняя
        if not общее:
            сдвиги.append(Сдвиг(
                "шапка", f"{len(прежняя)} строк", f"{len(нынешняя)} строк",
                "общих нет", устройство=True))
        elif not вложено:
            сдвиги.append(Сдвиг(
                "шапка", f"{len(прежняя)} строк", f"{len(нынешняя)} строк",
                f"пропало {len(прежняя - нынешняя)}, "
                f"появилось {len(нынешняя - прежняя)}"))

    прежние = {имя: (слева, справа) for имя, слева, справа in было.полосы}
    for имя, слева, справа in стало.полосы:
        if имя not in прежние:
            сдвиги.append(Сдвиг(f"полоса {имя}", "нет", f"{слева}…{справа}",
                                устройство=True))
            continue
        было_слева, было_справа = прежние[имя]
        for край, прежнее, нынешнее in (("слева", было_слева, слева),
                                        ("справа", было_справа, справа)):
            п, н = _числом(прежнее), _числом(нынешнее)
            if п is None or н is None:
                continue
            отклонение = abs(н - п)
            if отклонение > допуск_полосы:
                сдвиги.append(Сдвиг(f"полоса {имя} {край}", str(п), str(н),
                                    str(отклонение)))
    for имя in прежние:
        if имя not in {и for и, _, _ in стало.полосы}:
            сдвиги.append(Сдвиг(f"полоса {имя}", "была", "нет",
                                устройство=True))

    for признак in ("доля_целых_строк", "доля_сомнительных",
                    "доля_неистолкованных"):
        п, н = _числом(getattr(было, признак)), _числом(getattr(стало, признак))
        if п is None or н is None:
            continue
        отклонение = abs(н - п)
        if отклонение > допуск_доли:
            сдвиги.append(Сдвиг(признак, str(п), str(н), str(отклонение)))

    if any(с.устройство for с in сдвиги):
        вердикт = ДРУГАЯ_ФОРМА
    elif сдвиги:
        вердикт = ДРЕЙФ
    else:
        вердикт = ТА_ЖЕ_ФОРМА

    return {
        "версия": DRIFT_VERSION,
        "вердикт": вердикт,
        "сдвигов": len(сдвиги),
        "по_устройству": sum(1 for с in сдвиги if с.устройство),
        "сдвиги": [с.as_json() for с in сдвиги],
        "разбор_шёл": вердикт != ДРУГАЯ_ФОРМА,
        "что_делать": {
            ТА_ЖЕ_ФОРМА: "ничего: форма прежняя",
            ДРЕЙФ: "посмотреть оснастку: разбор идёт, но форма поехала",
            ДРУГАЯ_ФОРМА: "остановиться: это другая форма, прежней оснасткой "
                          "её разбирать нельзя",
        }[вердикт],
    }


def дрейфует(итог: dict) -> bool:
    """Нужно ли вмешательство человека по итогу сличения."""
    return итог.get("вердикт") != ТА_ЖЕ_ФОРМА


