# -*- coding: utf-8 -*-
"""Статусы полноты и блокировка автоматического допуска.

Шаг 35 плана. Нормативная основа — чертёж v3.0, раздел 8.

Три статуса из раздела 8.1:

* ``complete`` — ожидаемая структура подтверждена. Автодопуск разрешён при
  прохождении остальных правил;
* ``partial`` — известна **конкретная** непокрытая область или объект.
  Автодопуск запрещён;
* ``unknown`` — система не может доказать полноту. Автодопуск запрещён.

**Главное правило: unknown блокирует автодопуск безусловно.** Не понижает
уверенность, не добавляет предупреждение — блокирует. Обхода нет и быть не
должно: разрешение допуска здесь не принимает ни доводов, ни настроек, ни
признака «всё равно пропустить». Такой признак однажды окажется взведён, и никто
не вспомнит кем.

**Почему ноль необъяснённого — это ещё не полнота.** Ноль расхождений при слепой
оценке означает не то, что всё на месте, а то, что сверять было не с чем.
Различие обязано быть видно в самом статусе, поэтому:

* нет независимых ожиданий вовсе — ``unknown``, а не ``complete``;
* оценки спорят между собой — ``unknown``: какая из них верна, неизвестно;
* всё сошлось, но **не набрана совокупность механизмов** раздела 8.2 —
  тоже ``unknown``, и в причинах прямо перечислено, чего недостаёт.

Раздел 8.2 говорит прямо: «Одного реестра обнаруженных строк недостаточно.
Обязательна совокупность». Значит, полнота — это не «расхождений не нашли», а
«нашлось чем искать, и не нашли». Сегодня совокупность не набрана, и статус
``complete`` недостижим по построению. Это не изъян, а честное состояние дел:
недостающие механизмы придут своими шагами.
"""

from __future__ import annotations

from dataclasses import dataclass


COMPLETENESS_VERSION = "completeness/1"

# Механизмы покрытия из раздела 8.2, слово в слово по смыслу и по порядку.
# Совокупность обязательна: полнота не доказывается ни одним из них поодиночке.
МЕХАНИЗМЫ = (
    "реестр страниц, областей, таблиц, строк и исключений",
    "ожидаемая структура шаблона",
    "счётчики объектов и продолжений таблиц",
    "контроль порядка и повторов",
    "суммы, балансы и иные инварианты",
    "независимая проверка критических или подозрительных зон",
    "метрика потери покрытия на закрытом корпусе",
)

# Чем станок располагает сегодня. Список не обещание, а опись: он пополняется
# по мере закрытия шагов и служит основанием для статуса, а не украшением.
ДОСТУПНЫЕ_МЕХАНИЗМЫ = (
    "реестр страниц, областей, таблиц, строк и исключений",   # шаги 32 и 34
    "счётчики объектов и продолжений таблиц",                 # шаги 34 и 36
    "контроль порядка и повторов",                            # шаг 40
    "суммы, балансы и иные инварианты",                       # шаг 41
)

ГДЕ_ПОЯВЯТСЯ = {
    "ожидаемая структура шаблона": "шаг 37, язык оснастки; засчитывается только "
                                   "с приложенной к документу оснасткой",
    "независимая проверка критических или подозрительных зон":
        "шаг 43 построил контур, но распознавателя видимых знаков в станке нет: "
        "механизм засчитывается, когда в розетку перепроверки включён движок",
    "метрика потери покрытия на закрытом корпусе": "шаг 50, корпус",
}

KNOWN_LIMITATIONS = (
    "Статус complete сегодня недостижим: совокупность механизмов раздела 8.2 "
    "не набрана. Это состояние дел, а не изъян счётчика — недостающие "
    "механизмы приходят своими шагами.",
    "Счётчик продолжений таблиц сшивает только доказуемое: совпадение "
    "столбцов и дословно повторённую шапку. Случай, требующий шаблона "
    "семейства, механизм объявляет нерешённым — и такой документ получает "
    "unknown, сколько бы механизмов ни было в наличии.",
    "Статус ставится по документу целиком и по каждому виду объектов. "
    "Постраничный статус потребует ожиданий в разрезе страниц; у нынешних "
    "оценок такого разреза нет.",
)


@dataclass(frozen=True, slots=True)
class Полнота:
    """Статус полноты и вытекающее из него право на автоматический допуск."""

    статус: str
    причины: tuple[str, ...] = ()
    недостающие_механизмы: tuple[str, ...] = ()
    по_видам: tuple[tuple[str, str], ...] = ()
    schema_version: str = COMPLETENESS_VERSION

    @property
    def автодопуск_разрешён(self) -> bool:
        """Разрешён ли автоматический допуск.

        Единственное место, где это решается, и решается оно только статусом.
        Ни доводов, ни настроек, ни признака «пропустить всё равно» здесь нет
        намеренно: такой признак однажды окажется взведён, и никто не вспомнит
        кем. Раздел 8.1: при partial и unknown автодопуск запрещён.
        """
        return self.статус == "complete"

    def as_json(self) -> dict:
        return {
            "schema_version": self.schema_version,
            "статус": self.статус,
            "автодопуск_разрешён": self.автодопуск_разрешён,
            "причины": list(self.причины),
            "недостающие_механизмы": list(self.недостающие_механизмы),
            "по_видам": dict(self.по_видам),
        }


def оценить(карта, механизмы=ДОСТУПНЫЕ_МЕХАНИЗМЫ, неуверенности=()) -> Полнота:
    """Ставит статус полноты по карте покрытия и набору механизмов.

    ``карта`` — карта покрытия шага 34. ``механизмы`` — чем станок располагает
    на самом деле; передаётся явно, чтобы статус нельзя было улучшить, забыв
    про недостающее. ``неуверенности`` — случаи, которые механизм обнаружил, но
    решить не смог: например, сшивка продолжений таблиц, требующая шаблона.

    Наличие механизма и его применимость к этому документу — разные вещи.
    Механизм есть, а решить он не смог — значит, полнота не доказана, и статус
    ``unknown``. Считать иначе означало бы засчитывать несостоявшуюся проверку
    как пройденную.
    """
    механизмы = tuple(механизмы)
    неуверенности = tuple(неуверенности)
    причины: list[str] = []
    по_видам: dict[str, str] = {}

    ожидания = getattr(карта, "ожидания", ())
    расхождения = getattr(карта, "расхождения", ())
    споры = tuple(getattr(карта, "споры_ожиданий", ()))

    # 0. Механизм не смог решить — доказательства нет, каким бы полным ни был
    # набор механизмов.
    if неуверенности:
        for неуверенность in неуверенности:
            причины.append(f"механизм не смог решить: {неуверенность}")
        return Полнота("unknown", tuple(причины), _недостающие(механизмы), ())

    # 1. Проверять было нечем.
    if not ожидания:
        причины.append(
            "независимых ожиданий нет: сверять обнаруженное не с чем, "
            "и ноль расхождений здесь означает незнание, а не полноту")
        return Полнота("unknown", tuple(причины), _недостающие(механизмы), ())

    # 2. Сами оценки не сошлись между собой.
    for спор in споры:
        причины.append(f"оценки ожидаемого противоречат друг другу: {спор}")

    # 3. Известные непокрытые объекты — это partial, и он конкретен.
    непокрытые = []
    лишние = []
    for расхождение in расхождения:
        if расхождение.необъяснено > 0:
            непокрытые.append(расхождение)
            по_видам[расхождение.вид] = "partial"
        elif расхождение.необъяснено < 0:
            лишние.append(расхождение)
            по_видам[расхождение.вид] = "partial"
        else:
            по_видам.setdefault(расхождение.вид, "сошлось")

    for расхождение in непокрытые:
        причины.append(
            f"{расхождение.вид}: не объяснено {расхождение.необъяснено} "
            f"из {расхождение.ожидалось} (оценка: {расхождение.откуда_ожидание})")
    for расхождение in лишние:
        причины.append(
            f"{расхождение.вид}: обнаружено на {-расхождение.необъяснено} больше "
            f"ожидаемого — либо оценка слепа, либо разбор придумал объекты")

    недостающие = _недостающие(механизмы)

    if споры:
        # Спор оценок — это не «известна конкретная непокрытая область», а
        # невозможность доказать полноту: неизвестно даже, чему верить.
        по_видам = {вид: "unknown" for вид in по_видам}
        return Полнота("unknown", tuple(причины), недостающие,
                       tuple(sorted(по_видам.items())))

    if непокрытые or лишние:
        return Полнота("partial", tuple(причины), недостающие,
                       tuple(sorted(по_видам.items())))

    # 4. Всё сошлось. Но сошлось — ещё не доказано.
    if недостающие:
        причины.append(
            "расхождений нет, но совокупность механизмов раздела 8.2 не "
            "набрана: доказать полноту нечем")
        for механизм in недостающие:
            где = ГДЕ_ПОЯВЯТСЯ.get(механизм, "отдельным шагом")
            причины.append(f"недостаёт: {механизм} ({где})")
        по_видам = {вид: "unknown" for вид in по_видам}
        return Полнота("unknown", tuple(причины), недостающие,
                       tuple(sorted(по_видам.items())))

    причины.append("ожидаемая структура подтверждена, расхождений нет, "
                   "совокупность механизмов раздела 8.2 набрана")
    по_видам = {вид: "complete" for вид in по_видам}
    return Полнота("complete", tuple(причины), (),
                   tuple(sorted(по_видам.items())))


def _недостающие(механизмы) -> tuple[str, ...]:
    есть = set(механизмы)
    return tuple(механизм for механизм in МЕХАНИЗМЫ if механизм not in есть)


def блокирует_допуск(полнота: Полнота) -> bool:
    """Прямая формулировка правила для читающего код.

    Существует затем, чтобы намерение было видно в одном месте: допуск
    разрешает только complete, всё остальное блокирует.
    """
    return not полнота.автодопуск_разрешён


