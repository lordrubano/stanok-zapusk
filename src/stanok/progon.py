# -*- coding: utf-8 -*-
"""Прогон на диске: результат разбора переживает закрытие окна.

## Зачем

Экраны оператора строятся из проводки — того, что конвейер узнал о документе.
Пока проводка живёт только в памяти процесса, станок умеет показывать лишь тот
документ, который назван ему при запуске: положенный через браузер файл
разобрать было **некому и негде**, а разобранный — некуда деть.

Здесь проводка кладётся на диск и поднимается обратно так, что экраны не
замечают разницы. Это и есть условие браузерного пути: положил файл — увидел
разбор, закрыл окно — вернулся и увидел то же самое.

## Как

Своего описания у каждого типа не заводится: почти всё в станке — это
неизменяемые записи (`dataclass`), и они кладутся общим правилом. Тип
запоминается по имени и восстанавливается по нему же; кортеж остаётся кортежем
(иначе неизменяемая запись перестала бы быть хешируемой), точное число остаётся
точным, дата — датой.

**Правило проверки:** восстановленная проводка не «похожа» на исходную, а даёт
**те же экраны**. Так это и проверяется — сборкой экранов из обеих и сличением,
а не сравнением полей по списку, который легко разойдётся с действительностью.

## Чего здесь нет

Объекты источника целиком не сохраняются: они нужны разбору, а не экранам, и
весят больше всего остального вместе взятого. Кто попросит их у поднятой с
диска проводки, получит пустой список — и это сказано здесь, а не обнаружится
на экране.
"""

from __future__ import annotations

import dataclasses
import gzip
import json
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

PROGON_VERSION = "progon/1"

# Имя файла, под которым прогон живёт в папке партии.
ИМЯ_ФАЙЛА = "progon.json.gz"

# Типы, которые кладутся и поднимаются. Список закрытый: неизвестный тип не
# восстанавливается молча пустышкой, а называется бедой. Молчаливое
# восстановление «чем-нибудь» дало бы экран, который врёт о содержимом.
def _реестр() -> dict[str, type]:
    from . import (adapters, anchors, completeness, coverage, decision,
                   evidence, pipeline, segmenter, value_warnings)

    свои: dict[str, type] = {}
    for модуль in (pipeline, segmenter, coverage, completeness, decision,
                   evidence, value_warnings, adapters, anchors):
        for имя in dir(модуль):
            это = getattr(модуль, имя)
            if isinstance(это, type) and dataclasses.is_dataclass(это):
                свои.setdefault(f"{модуль.__name__.split('.')[-1]}.{имя}", это)
    return свои


class ПрогонНеЧитается(ValueError):
    """Прогон на диске негоден: испорчен, чужой версии или неизвестного типа."""

    код = "E_RUN_UNREADABLE"


# ------------------------------------------------------------ укладка


def _уложить(это):
    if это is None or isinstance(это, (str, int, float, bool)):
        return это
    if isinstance(это, Decimal):
        return {"__точное__": str(это)}
    if isinstance(это, datetime):
        return {"__время__": это.isoformat()}
    if isinstance(это, date):
        return {"__дата__": это.isoformat()}
    if isinstance(это, tuple):
        return {"__кортеж__": [_уложить(з) for з in это]}
    if isinstance(это, (set, frozenset)):
        return {"__набор__": sorted(_уложить(з) for з in это)}
    if isinstance(это, list):
        return [_уложить(з) for з in это]
    if isinstance(это, dict):
        return {"__словарь__": [[_уложить(к), _уложить(з)]
                                for к, з in это.items()]}
    if dataclasses.is_dataclass(это) and not isinstance(это, type):
        имя = f"{type(это).__module__.split('.')[-1]}.{type(это).__name__}"
        поля = {п.name: _уложить(getattr(это, п.name))
                for п in dataclasses.fields(это)}
        return {"__запись__": имя, "поля": поля}
    # Всё прочее кладётся как строка и честно помечается: подняв такое, станок
    # не притворится, будто вернул исходный предмет.
    return {"__текстом__": str(это)}


def _поднять(это, реестр):
    if isinstance(это, list):
        return [_поднять(з, реестр) for з in это]
    if not isinstance(это, dict):
        return это
    if "__точное__" in это:
        return Decimal(это["__точное__"])
    if "__время__" in это:
        return datetime.fromisoformat(это["__время__"])
    if "__дата__" in это:
        return date.fromisoformat(это["__дата__"])
    if "__кортеж__" in это:
        return tuple(_поднять(з, реестр) for з in это["__кортеж__"])
    if "__набор__" in это:
        return frozenset(_поднять(з, реестр) for з in это["__набор__"])
    if "__словарь__" in это:
        return {_поднять(к, реестр): _поднять(з, реестр)
                for к, з in это["__словарь__"]}
    if "__текстом__" in это:
        return это["__текстом__"]
    if "__запись__" in это:
        имя = это["__запись__"]
        тип = реестр.get(имя)
        if тип is None:
            raise ПрогонНеЧитается(
                f"{ПрогонНеЧитается.код}: неизвестный тип «{имя}». Прогон "
                "собран другой сборкой станка")
        поля = {к: _поднять(з, реестр) for к, з in это["поля"].items()}
        известные = {п.name for п in dataclasses.fields(тип)}
        лишние = set(поля) - известные
        if лишние:
            raise ПрогонНеЧитается(
                f"{ПрогонНеЧитается.код}: у «{имя}» поля, которых нет в этой "
                f"сборке: {', '.join(sorted(лишние))}")
        return тип(**поля)
    return {к: _поднять(з, реестр) for к, з in это.items()}


# ------------------------------------------------------------ прогон целиком

# Что кладётся. Объектов источника здесь нет намеренно: они нужны разбору, а не
# экранам, и весят больше всего остального.
ПОЛЯ = ("журнал", "записи", "решения", "состояние_запуска", "сегментация",
        "карта", "полнота", "происхождение", "предупреждения", "опознан",
        "повторы_в_колонках", "версия")


def в_json(проводка, *, документ: str = "", оснастка: str = "") -> dict:
    """Прогон как данные. Документ и оснастка — чтобы знать, чей это разбор."""
    свои = {поле: _уложить(getattr(проводка, поле, None)) for поле in ПОЛЯ}
    return {
        "версия_прогона": PROGON_VERSION,
        "документ": документ,
        "оснастка": оснастка,
        "поля": свои,
    }


def из_json(данные) -> object:
    """Проводка из данных. Экраны не должны замечать, что она с диска."""
    from .pipeline import Проводка

    if not isinstance(данные, dict) or "поля" not in данные:
        raise ПрогонНеЧитается(f"{ПрогонНеЧитается.код}: это не прогон")
    если_версия = данные.get("версия_прогона")
    if если_версия != PROGON_VERSION:
        raise ПрогонНеЧитается(
            f"{ПрогонНеЧитается.код}: прогон версии «{если_версия}», а станок "
            f"понимает «{PROGON_VERSION}»")

    реестр = _реестр()
    поля = {к: _поднять(з, реестр) for к, з in данные["поля"].items()}
    проводка = Проводка()
    for имя, значение in поля.items():
        if имя in ("журнал", "записи", "решения"):
            значение = list(значение or ())
        setattr(проводка, имя, значение)
    return проводка


def сохранить(проводка, куда, *, документ: str = "", оснастка: str = "") -> Path:
    """Кладёт прогон рядом с партией. Пишется сторонним именем и переносится.

    Тот же порядок, что у итога шага 64: под настоящим именем половины не
    бывает. Оборвись запись на середине — прежний прогон останется целым.
    """
    куда = Path(куда)
    куда.mkdir(parents=True, exist_ok=True)
    свой = куда / ИМЯ_ФАЙЛА
    временный = куда / (ИМЯ_ФАЙЛА + ".пишется")
    данные = в_json(проводка, документ=документ, оснастка=оснастка)
    # Кладётся сжатым: прогон настоящей выписки на 51 страницу — это 45
    # мегабайт несжатого текста, и главное в нём — происхождение каждого
    # значения. Сжатие ничего не выбрасывает: те же данные, просто без повторов.
    временный.write_bytes(gzip.compress(
        json.dumps(данные, ensure_ascii=False, allow_nan=False).encode("utf-8"),
        mtime=0))
    временный.replace(свой)
    return свой


def сведения(откуда) -> dict:
    """Чей это разбор: документ и версия оснастки. Пусто — прогона нет.

    Нужно затем, что сама оснастка в прогоне не лежит (она приходит пакетом и
    живёт отдельно), а без неё книга выходит **без единой колонки**: сборка
    берёт их из оснастки. Куплено проверкой комплекта на чистом месте — после
    перезапуска станка книга стала пустой, хотя все 827 записей были на месте.
    """
    свой = Path(откуда)
    if свой.is_dir():
        свой = свой / ИМЯ_ФАЙЛА
    if not свой.is_file():
        return {}
    try:
        данные = json.loads(gzip.decompress(свой.read_bytes()).decode("utf-8"))
    except (OSError, ValueError) as беда:
        raise ПрогонНеЧитается(
            f"{ПрогонНеЧитается.код}: файл прогона испорчен: {беда}") from беда
    return {"документ": данные.get("документ", ""),
            "оснастка": данные.get("оснастка", "")}


def прочитать(откуда) -> object | None:
    """Прогон из папки партии. Нет файла — ``None``, и это не беда."""
    свой = Path(откуда)
    if свой.is_dir():
        свой = свой / ИМЯ_ФАЙЛА
    if not свой.is_file():
        return None
    try:
        данные = json.loads(gzip.decompress(свой.read_bytes()).decode("utf-8"))
    except (OSError, ValueError) as беда:
        raise ПрогонНеЧитается(
            f"{ПрогонНеЧитается.код}: файл прогона испорчен: {беда}") from беда
    return из_json(данные)


