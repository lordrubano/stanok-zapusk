# -*- coding: utf-8 -*-
"""Три режима перепроверки и переходы между ними по метрикам.

Шаг 44 плана. Нормативная основа — чертёж v3.0, раздел 11 (состояния и выходные
контуры), раздел 5.4 (режимы независимой перепроверки) и раздел 17 (метрики,
правило трёх, допуск шаблона).

Шаг 43 сличает два прочтения одного места. Он не решает, **сколько** записей
идёт этим путём: сплошная перепроверка стоит как второй разбор, а выборочная
оставляет непроверенное. Здесь назначается объём — и назначается он метрикой.

**Переход из калибровочного в стабильный совершается по измеренной доле ошибок,
а не по решению человека и не по числу обработанных документов.** Ни в одной
здешней подписи нет ни признака ручного перевода, ни счётчика документов,
влияющего на режим: число обработанного записывается, но воротам не
предъявляется. Тысяча документов без единого замера ошибок — это тысяча
документов и ноль знания. Пока доли ошибок нет, режим калибровочный, и **выйти
из него нечем**.

**Ноль ошибок сам по себе ворот не открывает.** Ноль на пяти наблюдениях даёт
долю ошибок 0,00 и прошёл бы любой порог — поэтому ворота спрашивают не только
долю, но и правило трёх (раздел 17.2): при нуле ошибок на N наблюдениях верхняя
граница вероятности ошибки около 3/N, и пока эта граница выше порога, доказано
ничего не было. Малое N — не хорошая статистика, а её отсутствие.

**Случайная доля в стабильном режиме обязательна.** Без неё проверяется ровно
то, что назвали триггеры, и **слепое пятно триггеров становится слепым пятном
системы**: ошибка, которую ни один триггер не описывает, не будет найдена
никогда — не потому, что её нет, а потому, что туда никто не смотрит. Поэтому
здесь два устройства, а не одно обещание:

1. стабильный режим без объявленной доли выборки не работает — :func:`отобрать`
   отказывает, а не берёт молчаливый ноль;
2. случайная доля отбирается **из записей, которых не назвал ни один триггер**.
   Иначе триггеры съедали бы квоту: назвали двенадцать процентов при квоте в
   десять — и случайных не осталось бы вовсе, а отчёт показывал бы полное
   выполнение выборки.

**Случайность здесь детерминированная.** Отбор идёт по отпечатку зерна запуска и
имени записи: та же подача с тем же зерном даёт ту же выборку. Иначе запуск
нельзя ни повторить, ни проверить, а «случайно выбранное» становится
непроверяемым утверждением о самом себе.

**Неизвестность ведёт к перепроверке, а не к пропуску.** На прежних уровнях
неизвестное блокировало автодопуск. Здесь оно означает другое: не знать, низка
ли уверенность записи, — само по себе повод посмотреть.
"""

