@dataclass(frozen=True, slots=True)
class Наблюдение:
    """Что о слагаемом установил тот уровень, чьё это дело.

    ``источник`` обязателен: решение без указания, кто наблюдал, невозможно ни
    объяснить, ни оспорить.
    """

    слагаемое: str
    состояние: str
    источник: str
    критично: bool = False
    подробность: str = ""

    def as_json(self) -> dict:
        return {"слагаемое": self.слагаемое, "состояние": self.состояние,
                "источник": self.источник, "критично": self.критично,
                "подробность": self.подробность}


def из_правил(слагаемое: str, итоги, источник: str = "") -> Наблюдение:
    """Мост от уровней 39–44: перечень правил — в одно наблюдение.

    Перевод намеренно суров и совпадает с прежними уровнями:

    * все правила прошли — ``да``;
    * есть нарушение — ``нет``; критичность берётся от нарушений;
    * нарушений нет, но есть неизвестное — ``неизвестно``;
    * правил нет вовсе — ``неизвестно``. Пустой перечень означает, что не
      проверялось ничего, и считать это прохождением нельзя;
    * статус правила не опознан — ``неизвестно``. Раньше здесь считалось «нет
      нарушений и нет неизвестного, значит прошло», и всё неопознанное попадало
      в успех: сломавшийся уровень выдавал бы записи в допуск. «Да» теперь
      требует, чтобы **каждое** правило прошло явно.
    """
    итоги = tuple(итоги)
    если_нет = tuple(и for и in итоги if и.статус == НАРУШЕНО)
    если_неясно = tuple(и for и in итоги if и.статус == НЕИЗВЕСТНО)
    чужие = tuple(и for и in итоги
                  if и.статус not in (ПРОШЛО, НАРУШЕНО, НЕИЗВЕСТНО))
    версии = sorted({и.версия for и in итоги})
    откуда = источник or (", ".join(версии) if версии else "наблюдений нет")

    if not итоги:
        return Наблюдение(слагаемое, НЕ_ИЗВЕСТНО, откуда, False,
                          "перечень правил пуст: не проверялось ничего")
    if если_нет:
        критично = any(и.критичность == "критическое" for и in если_нет)
        первое = если_нет[0]
        return Наблюдение(
            слагаемое, НЕТ, откуда, критично,
            f"нарушений {len(если_нет)}, первое — {первое.rule_id}: "
            f"{первое.вычисления}")
    if если_неясно:
        первое = если_неясно[0]
        return Наблюдение(
            слагаемое, НЕ_ИЗВЕСТНО, откуда, False,
            f"неизвестного {len(если_неясно)}, первое — {первое.rule_id}: "
            f"{первое.вычисления}")
    if чужие:
        первое = чужие[0]
        return Наблюдение(
            слагаемое, НЕ_ИЗВЕСТНО, откуда, False,
            f"статус {первое.статус!r} правила {первое.rule_id} не опознан; "
            f"таких правил {len(чужие)}")
    if any(и.статус != ПРОШЛО for и in итоги):   # pragma: no cover — запас
        return Наблюдение(слагаемое, НЕ_ИЗВЕСТНО, откуда, False,
                          "не все правила прошли явно")
    return Наблюдение(слагаемое, ДА, откуда, False,
                      f"правил {len(итоги)}, все прошли")


КЛЮЧ_ПЕРЕПРОВЕРКИ = "independent_check_passed_or_not_required_by_versioned_policy"


def из_плана(отбор, record_id: str, итоги_сличения, политика: Политика) -> Наблюдение:
    """Слагаемое перепроверки: пройдена или не требуется **этой** политикой.

    Освобождение от перепроверки версионировано. План, составленный при одной
    версии политики и предъявленный другой, не освобождает ни от чего: пороги,
    доля выборки и состав триггеров той версии здесь уже не действуют, а
    выглядит такое освобождение точно так же, как настоящее.
    """
    _проверить_политику(политика)
    if not getattr(отбор, "политика", ""):
        return Наблюдение(
            КЛЮЧ_ПЕРЕПРОВЕРКИ, НЕ_ИЗВЕСТНО, f"шаг 44, {отбор.версия}", False,
            "план перепроверки не привязан ни к какой версии политики: "
            "освобождать по нему нечем")
    if отбор.политика != политика.версия:
        return Наблюдение(
            КЛЮЧ_ПЕРЕПРОВЕРКИ, НЕ_ИЗВЕСТНО, f"шаг 44, {отбор.версия}", False,
            f"план составлен при политике {отбор.политика!r}, а решает "
            f"{политика.версия!r}: чужое освобождение не переносится")

    if record_id in отбор.основания:
        # Политика назначила запись на перепроверку — значит, всё решает
        # сличение, и пустой его перечень пройденным не считается.
        return из_правил(КЛЮЧ_ПЕРЕПРОВЕРКИ, итоги_сличения,
                         источник=f"шаг 43 по плану {отбор.режим}")
    return Наблюдение(
        КЛЮЧ_ПЕРЕПРОВЕРКИ, ДА, f"шаг 44, {отбор.версия}", False,
        f"перепроверка не требуется политикой {политика.версия} в режиме "
        f"{отбор.режим}")


def _разложить(наблюдения) -> dict:
    """Наблюдения по слагаемым. Чужого не принимает, недостающее объявляет."""
    по_ключам: dict = {}
    for наблюдение in наблюдения:
        if наблюдение.слагаемое not in _ВОПРОСЫ:
            raise НаблюдениеНегодно(
                f"слагаемого {наблюдение.слагаемое!r} в формуле 10.1 нет; "
                "формула закрыта: " + ", ".join(КЛЮЧИ))
        if наблюдение.состояние not in (ДА, НЕТ, НЕ_ИЗВЕСТНО):
            raise НаблюдениеНегодно(
                f"состояние {наблюдение.состояние!r} неизвестно; их три: "
                f"{ДА}, {НЕТ}, {НЕ_ИЗВЕСТНО}")
        прежнее = по_ключам.get(наблюдение.слагаемое)
        if прежнее is not None and прежнее.состояние != наблюдение.состояние:
            raise НаблюдениеНегодно(
                f"о слагаемом {наблюдение.слагаемое!r} подано два разных "
                f"наблюдения: {прежнее.состояние} и {наблюдение.состояние}; "
                "выбрать одно из них движок не станет")
        по_ключам[наблюдение.слагаемое] = наблюдение

    for ключ in КЛЮЧИ:
        if ключ not in по_ключам:
            # Умолчания «раз не сказали, значит в порядке» здесь нет: оно и
            # было бы способом обойти формулу молчанием.
            по_ключам[ключ] = Наблюдение(
                ключ, НЕ_ИЗВЕСТНО, "не наблюдалось", False,
                f"наблюдение о слагаемом не подано ({_ОТКУДА[ключ]})")
    return по_ключам


# ---------------------------------------------------------- решение


@dataclass(frozen=True, slots=True)
class Решение:
    """Решение по записи. Состав — раздел 6.1 (``RecordDecision``)."""

    record_id: str
    статус: str | None
    режим: str
    основание: str
    политика: str
    версия: str = DECISION_VERSION
    невыполненные: tuple = ()
    событие: dict | None = None

    @property
    def статус_рождён(self) -> bool:
        return self.статус is not None

    @property
    def лист(self) -> str | None:
        """Выходной контур, раздел 11.3."""
        return _ЛИСТЫ.get(self.статус) if self.статус else None

    @property
    def способ_допуска(self) -> str | None:
        """Автоматический или оператором. В саму запись не попадает.

        Раздел 11.3 требует на листе DATA явного способа допуска — берётся он
        отсюда, а не из канонической записи: запись говорит, что решено, а
        решение — как.
        """
        return СПОСОБ_ДОПУСКА.get(self.статус) if self.статус else None

    @property
    def каноническое_решение(self) -> str | None:
        """Значение поля ``decision`` канонической записи (раздел 6.3)."""
        return КАНОНИЧЕСКОЕ_РЕШЕНИЕ.get(self.статус) if self.статус else None

    def as_json(self) -> dict:
        return {
            "record_id": self.record_id,
            "статус": self.статус,
            "режим": self.режим,
            "основание": self.основание,
            "политика": self.политика,
            "версия": self.версия,
            "лист": self.лист,
            "способ_допуска": self.способ_допуска,
            "каноническое_решение": self.каноническое_решение,
            "невыполненные": [н.as_json() for н in self.невыполненные],
            "событие": self.событие,
        }


def _перечислить(невыполненные) -> str:
    """Называет слагаемые поимённо. Общего «не прошло» здесь не бывает."""
    части = []
    for наблюдение in невыполненные:
        части.append(
            f"{наблюдение.слагаемое} ({_ВОПРОСЫ[наблюдение.слагаемое]}) — "
            f"{наблюдение.состояние}, наблюдал {наблюдение.источник}"
            + (f": {наблюдение.подробность}" if наблюдение.подробность else ""))
    return "; ".join(части)


def решить(record_id: str, наблюдения, политика: Политика,
           состояние_запуска: str = COMPLETED) -> Решение:
    """Единственное место, где рождается статус записи.

    Порядок разбирательства — раздел 10.2, и он не переставляется.
    """
    _проверить_политику(политика)
    по_ключам = _разложить(наблюдения)

    # 1. Блокировка запуска выше любых решений по записям.
    # 2. Технический сбой не превращается в бизнес-отклонение.
    #
    # В обоих случаях статус записи **не рождается вовсе**. Поставить здесь
    # rejected значило бы объявить запись негодной по деловому существу, тогда
    # как её никто и не смотрел.
    if состояние_запуска in (BLOCKED, FAILED):
        почему = ("запуск заблокирован политикой безопасности или данных"
                  if состояние_запуска == BLOCKED
                  else "технический сбой запуска")
        return Решение(
            record_id, None, состояние_запуска,
            f"{почему}: решения по записям не рождаются, и деловым отклонением "
            "это не является", политика.версия)

    если_нет = tuple(по_ключам[ключ] for ключ in КЛЮЧИ
                     if по_ключам[ключ].состояние == НЕТ)
    если_неясно = tuple(по_ключам[ключ] for ключ in КЛЮЧИ
                        if по_ключам[ключ].состояние == НЕ_ИЗВЕСТНО)

    # 3. Критическое нарушение даёт rejected.
    критические = tuple(н for н in если_нет if н.критично)
    if критические:
        return Решение(
            record_id, REJECTED, состояние_запуска,
            "критическое нарушение: " + _перечислить(критические),
            политика.версия, невыполненные=если_нет + если_неясно)

    # 4. Неопределённость или исправимый конфликт дают review.
    #
    # Неизвестность приравнивается к невыполнению: раздел 10.1 запрещает
    # автодопуск при любом unknown. Уверенность здесь не понижается — понижать
    # нечего, слагаемое либо выполнено, либо нет.
    if если_нет or если_неясно:
        разряды = []
        if если_нет:
            разряды.append("исправимые нарушения: " + _перечислить(если_нет))
        if если_неясно:
            разряды.append("неизвестное (приравнено к невыполнению): "
                           + _перечислить(если_неясно))
        return Решение(
            record_id, REVIEW, состояние_запуска, "; ".join(разряды),
            политика.версия, невыполненные=если_нет + если_неясно)

    # 5. accepted_auto возможен только по формуле 10.1 — и только здесь.
    return Решение(
        record_id, ACCEPTED_AUTO, состояние_запуска,
        f"выполнены все {len(КЛЮЧИ)} слагаемых формулы 10.1 политики "
        f"{политика.версия}", политика.версия)


def допустить_вручную(решение: Решение, оператор: str, основание: str,
                      время: str) -> Решение:
    """Ручной допуск. Создаётся только событием оператора, раздел 10.2.6.

    Считается отдельно от автоматического и никогда с ним не смешивается: доля
    автоматизации, посчитанная вместе с ручным допуском, показывала бы работу
    станка там, где работал человек.
    """
    if not решение.статус_рождён:
        raise ПолитикаНегодна(
            "запуск заблокирован или сорван: ручной допуск поверх нерождённого "
            "статуса означал бы допуск записи, которую никто не обрабатывал")
    if решение.статус not in (REVIEW, REJECTED):
        raise ПолитикаНегодна(
            f"ручной допуск возможен только из {REVIEW} и {REJECTED}, а статус "
            f"{решение.статус}")
    if not (оператор and основание and время):
        raise ПолитикаНегодна(
            "событие проверки без оператора, основания или времени "
            "неизменяемым свидетельством не является")

    from dataclasses import replace

    событие = {"оператор": оператор, "время": время, "основание": основание,
               "было": решение.статус}
    return replace(
        решение, статус=ACCEPTED_MANUAL,
        основание=(f"оператор {оператор} допустил запись вручную: {основание}; "
                   f"было {решение.статус}"),
        событие=событие)


def отклонить_вручную(решение: Решение, оператор: str, основание: str,
                      время: str) -> Решение:
    """Отклонение оператором. Такое же событие, как ручной допуск, — раздел 12.

    Отклонение движком и отклонение человеком приходят к одному статусу, но
    рождаются по-разному, и смешивать их нельзя: первое стоит на нарушении
    правила, второе — на суждении человека. Основание при втором обязательно
    именно поэтому: правило можно перечитать, а суждение — только вспомнить.

    Отклонить можно только то, что ждёт человека или уже отклонено движком.
    Отклонять допущенное значило бы отменять решение задним числом, а для этого
    есть другой путь: сперва вернуть в review, и такого пути пока нет.
    """
    if not решение.статус_рождён:
        raise ПолитикаНегодна(
            "запуск заблокирован или сорван: отклонение поверх нерождённого "
            "статуса означало бы решение о записи, которую никто не обрабатывал")
    if решение.статус not in (REVIEW, REJECTED):
        raise ПолитикаНегодна(
            f"отклонение оператором возможно только из {REVIEW} и {REJECTED}, "
            f"а статус {решение.статус}")
    if not (оператор and основание and время):
        raise ПолитикаНегодна(
            "событие проверки без оператора, основания или времени "
            "неизменяемым свидетельством не является")

    from dataclasses import replace

    событие = {"оператор": оператор, "время": время, "основание": основание,
               "было": решение.статус, "действие": "отклонить"}
    return replace(
        решение, статус=REJECTED,
        основание=(f"оператор {оператор} отклонил запись: {основание}; "
                   f"было {решение.статус}"),
        событие=событие)


def проставить(запись: dict, решение: Решение) -> dict:
    """Ставит статус в каноническую запись. Не правит ничего другого.

    Отдельная и единственная функция для этого затем, чтобы отметку в записи
    ставил тот же движок, что её родил: сборщик записи (шаг 29) статуса больше
    не выдумывает.
    """
    if not решение.статус_рождён:
        raise ПолитикаНегодна(
            "статус не рождён: ставить в запись нечего")
    чьё = запись.get("record_id")
    if чьё is not None and чьё != решение.record_id:
        # Отметка, поставленная в чужую запись, выглядит как своя и не
        # обнаруживается ничем: обе записи остаются с правдоподобным статусом.
        raise ПолитикаНегодна(
            f"решение вынесено по записи {решение.record_id!r}, а ставится в "
            f"{чьё!r}: чужой статус выглядел бы как собственный")
    каноническое = решение.каноническое_решение
    if каноническое is None:
        raise ПолитикаНегодна(
            f"состоянию {решение.статус!r} не назначено каноническое решение: "
            "запись с ним не пройдёт ни канонизацию, ни обратимость")
    свой = dict(запись)
    свой["decision"] = каноническое
    return свой


# ------------------------------------------------------ запуск и свод


def решить_запуск(решения, технический_сбой: bool = False,
                  блокировка: bool = False) -> str:
    """Состояние запуска, раздел 11.2. Порядок тот же, что в 10.2."""
    if блокировка:
        return BLOCKED
    if технический_сбой:
        return FAILED
    решения = tuple(решения)
    if not решения:
        return PARTIAL
    if any(not р.статус_рождён or р.статус == REVIEW for р in решения):
        # Запись в REVIEW ждёт человека: конечного состояния у неё нет.
        return PARTIAL
    return COMPLETED


def свод(решения) -> dict:
    """Счётчики по решениям. Автоматический и ручной допуск — раздельно."""
    решения = tuple(решения)
    считано = {статус: sum(1 for р in решения if р.статус == статус)
               for статус in (ACCEPTED_AUTO, ACCEPTED_MANUAL, REVIEW, REJECTED)}
    без_статуса = sum(1 for р in решения if not р.статус_рождён)
    пригодных = len(решения) - без_статуса
    return {
        "версия": DECISION_VERSION,
        "всего": len(решения),
        "без_статуса": без_статуса,
        **считано,
        # Доля автоматизации, раздел 17.1: ручной допуск в неё не входит —
        # иначе она показывала бы работу станка там, где работал человек.
        "доля_автоматизации": (
            None if not пригодных
            else str(Decimal(считано[ACCEPTED_AUTO]) / Decimal(пригодных))),
        "листы": {лист: sum(1 for р in решения if р.лист == лист)
                  for лист in ("DATA", "REVIEW", "REJECTED")},
        "решения": [р.as_json() for р in решения],
    }


