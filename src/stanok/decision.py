@dataclass(frozen=True, slots=True)
class Политика:
    """Версионированная и подписанная политика допуска."""

    версия: str
    владелец: str
    дата_утверждения: str
    откат: str = ""
    приоритеты: tuple[str, ...] = ПРИОРИТЕТЫ
    подпись: str = ""

    def содержание(self) -> dict:
        """То, что подписывается. Подпись в него не входит."""
        return {
            "версия": self.версия,
            "владелец": self.владелец,
            "дата_утверждения": self.дата_утверждения,
            "откат": self.откат,
            "приоритеты": list(self.приоритеты),
            "формула": list(КЛЮЧИ),
        }

    @property
    def отпечаток(self) -> str:
        материал = json.dumps(self.содержание(), ensure_ascii=False,
                              allow_nan=False, sort_keys=True,
                              separators=(",", ":")).encode("utf-8")
        return hashlib.sha256(материал).hexdigest()

    def беды(self) -> tuple[str, ...]:
        """Почему политика негодна. Пустой ответ — годна."""
        беды = []
        for имя, значение in (("версия", self.версия), ("владелец", self.владелец),
                              ("дата_утверждения", self.дата_утверждения)):
            if not значение:
                беды.append(f"политика без «{имя}»: отозвать и откатить её будет нечем")
        if tuple(self.приоритеты) != ПРИОРИТЕТЫ:
            беды.append(
                "приоритеты отказа не те, что объявлены разделом 10.2, или "
                "переставлены местами; нормативный порядок: "
                + "; ".join(ПРИОРИТЕТЫ))
        if not self.подпись:
            беды.append("политика не подписана: неподписанная политика не "
                        "работает вовсе")
        elif self.подпись != self.отпечаток:
            беды.append("подпись не совпадает с содержанием: политику правили "
                        "после подписания")
        return tuple(беды)


def прочитать_политику(путь) -> Политика:
    """Читает политику допуска из файла, утверждённого владельцем.

    Политика — документ владельца, а не настройка станка: без неё статус не
    рождается вовсе. Поэтому она приходит файлом и проверяется тем же счётом,
    что и подписывалась: правку после утверждения видно.

    Отпечаток здесь — защита от невнимательности, а не от умысла: он
    доказывает, что содержание не менялось после утверждения, но не то, кто
    именно утверждал. Это сказано прямо, чтобы на него не полагались как на
    подпись поставки.
    """
    from pathlib import Path

    свой = Path(путь)
    if not свой.is_file():
        raise ПолитикаНегодна(f"файла политики нет: {свой}")
    try:
        содержимое = json.loads(свой.read_text(encoding="utf-8"))
    except (OSError, ValueError) as беда:
        raise ПолитикаНегодна(f"политика не читается: {беда}") from беда
    if not isinstance(содержимое, dict):
        raise ПолитикаНегодна("политика должна быть объектом с полями")

    приоритеты = содержимое.get("приоритеты")
    политика = Политика(
        версия=str(содержимое.get("версия", "")),
        владелец=str(содержимое.get("владелец", "")),
        дата_утверждения=str(содержимое.get("дата_утверждения", "")),
        откат=str(содержимое.get("откат", "")),
        приоритеты=(tuple(приоритеты) if приоритеты is not None else ПРИОРИТЕТЫ),
        подпись=str(содержимое.get("подпись", "")),
    )
    беды = политика.беды()
    if беды:
        # Отпечаток называется прямо в отказе: иначе владелец, у которого файл
        # ещё не заверен, не знает, что именно вписать, и вписывает наугад.
        raise ПолитикаНегодна(
            "; ".join(беды) + f". Отпечаток этого содержания: {политика.отпечаток}")
    return политика


def подписать(политика: Политика) -> Политика:
    """Подписывает политику отпечатком её канонического содержания."""
    from dataclasses import replace

    return replace(политика, подпись=политика.отпечаток)


def _проверить_политику(политика) -> None:
    if политика is None:
        raise ПолитикаНегодна(
            "политика не приложена: статус рождается только по политике, и "
            "без неё решать нечем")
    беды = политика.беды()
    if беды:
        raise ПолитикаНегодна("; ".join(беды))


