@dataclass
class Этап:
    """Что делал этап и чем кончил."""

    имя: str
    получилось: bool
    сказано: str = ""

    def as_json(self) -> dict:
        return {"этап": self.имя, "получилось": self.получилось,
                "сказано": self.сказано}


@dataclass
class Проводка:
    """Всё, что конвейер узнал о документе, и чем кончил."""

    версия: str = PIPELINE_VERSION
    паспорт: object | None = None
    журнал: list = field(default_factory=list)
    объекты: tuple = ()
    сегментация: object | None = None
    карта: object | None = None
    полнота: object | None = None
    записи: list = field(default_factory=list)
    отбор: object | None = None
    опознан: bool | None = None
    повторы_в_колонках: dict = field(default_factory=dict)
    происхождение: dict = field(default_factory=dict)
    предупреждения: dict = field(default_factory=dict)
    решения: list = field(default_factory=list)
    состояние_запуска: str = реш.PARTIAL
    отметчик: object | None = None

    def этап(self, имя, получилось, сказано=""):
        self.журнал.append(Этап(имя, получилось, сказано))
        # Отметка хода (шаг 81). Кладётся после того, как этап записан: она
        # говорит о **завершённом** действии, а не о начатом. Беда отметчика
        # работу не валит — иначе наблюдатель за остановкой сам стал бы
        # причиной остановки.
        if self.отметчик is not None:
            try:
                self.отметчик(имя)
            except Exception:  # noqa: BLE001 — отметка не сторож работы
                pass

    @property
    def сорвалось(self) -> tuple[str, ...]:
        return tuple(э.имя for э in self.журнал if not э.получилось)

    def as_json(self) -> dict:
        return {
            "версия": self.версия,
            "состояние_запуска": self.состояние_запуска,
            "опознан": self.опознан,
            "происхождение": свод_происхождения(
                [с for свои in self.происхождение.values() for с in свои]),
            "предупреждения": свод_предупреждений(
                [п for свои in self.предупреждения.values() for п in свои]),
            "этапов": len(self.журнал),
            "сорвалось": list(self.сорвалось),
            "записей": len(self.записи),
            "решений": len(self.решения),
            "журнал": [э.as_json() for э in self.журнал],
            "решения_по_записям": [р.as_json() for р in self.решения],
        }


def _весь_текст(объекты) -> str:
    """Весь текст источника — то, по чему опознаётся семейство."""
    return " ".join(о.сырой_текст or "" for о in объекты)


def _наблюдение(ключ, состояние, источник, подробность=""):
    return реш.Наблюдение(ключ, состояние, источник, False, подробность)


def провести(путь, *, оснастка=None, политика=None, розетка=РОЗЕТКА,
             перепроверка: РозеткаПерепроверки | None = None,
             метрики=None, зерно: str | None = None, реквизиты=None,
             объявленные_итоги=(), пределы=APPROVED_LIMITS, срок=None,
             клетка: bool = True, пути_клетки=None, отметчик=None) -> Проводка:
    """Ведёт документ от приёма до решения. Ничего не выдумывает.

    Срок на файл заводится здесь и делится между долгими местами. Он не
    добавляет проводке нового исхода: истёкший срок — это отказ по пределу,
    такой же, как превышение размера или числа страниц, и запуск от него
    блокируется, а не отклоняется по существу.

    Разбор недоверенного входа по умолчанию идёт **в клетке шага 24** —
    отдельным процессом под пределами операционной системы. Выключить её можно
    только нарочно: ``клетка=False``, и тогда конвейер говорит об этом вслух
    отдельным этапом.

    ``пути_клетки`` — где дочернему процессу искать движок. Своё ядро он находит
    всегда; сторонний пакет оснастки лежит там, где его положили, и назвать это
    место обязан тот, кто его подключил.

    ``отметчик`` — куда класть отметку хода (шаг 81). Не подан — конвейер
    работает ровно как прежде и не пишет ничего: наблюдатель за остановкой
    заводится тем, кто запускает, а не самим разбором.
    """
    проводка = Проводка(отметчик=отметчик)
    срок = срок if срок is not None else на_файл(пределы)
    try:
        return _провести(проводка, путь, оснастка=оснастка, политика=политика,
                         розетка=розетка, перепроверка=перепроверка,
                         метрики=метрики, зерно=зерно, реквизиты=реквизиты,
                         объявленные_итоги=объявленные_итоги, пределы=пределы,
                         срок=срок, клетка=клетка,
                         пути_клетки=пути_клетки)
    except СрокИстёк as вышел:
        # Молчание перестало быть возможным исходом: место названо, время
        # названо, предел назван. Частичного разбора при этом не выдаётся —
        # недоделанное не выдаётся за сделанное.
        проводка.этап("срок", False, str(вышел))
        проводка.паспорт = _с_отказом(проводка.паспорт, (вышел.отказ,))
        проводка.записи = []
        проводка.решения = []
        проводка.состояние_запуска = реш.BLOCKED
        return проводка


def _извлечь(розетка, паспорт, данные, путь, пределы, срок, клетка, проводка,
             пути_клетки=None):
    """Извлечение объектов источника: в клетке шага 24 либо в своём процессе.

    **Разбор недоверенного входа идёт в отдельном процессе.** Это единственное
    место станка, где чужой формат встречается с чужим содержимым, и держать
    его надо не вежливостью разбора, а операционной системой: зациклившийся
    движок убивают по часам, прожорливому не дают взять лишнего.

    Мягкий срок при этом не отменяется, а остаётся первым рубежом: он приходит
    раньше, называет место поимённо и не стоит целого процесса. Клетка — рубеж
    второй, и она срабатывает там, где первый бессилен: в чужом цикле, где
    отметку поставить негде.
    """
    if not клетка:
        проводка.этап("клетка", False, "изоляция выключена вызывающим")
        return розетка.извлечь(паспорт, данные, срок=срок)

    формат = (getattr(паспорт, "suffix", "") or "").lower().lstrip(".")
    вилка = розетка.выбрать(формат)
    точка = точка_входа(вилка.адаптер) if вилка is not None else None
    if точка is None:
        # Движок, которого нельзя назвать модулем и классом, дочернему процессу
        # не передать. Выполнить его в своём процессе молча значило бы обойти
        # клетку тайком, поэтому здесь об этом сказано вслух.
        проводка.этап(
            "клетка", False,
            "движок не назван модулем и классом: разбор в своём процессе"
            if вилка is not None else f"нет адаптера для формата {формат}")
        return розетка.извлечь(паспорт, данные, срок=срок)

    # Клетке достаётся **остаток** срока файла, а не полный предел. Иначе
    # отдельный процесс получал бы своё время поверх общего, и предел на файл
    # переставал быть пределом ровно там, где принуждение наконец появилось.
    срок.проверить()
    остаток = max(1, int(срок.остаток()))
    свои_пределы = replace(пределы, max_duration_seconds=min(
        пределы.max_duration_seconds, остаток))

    отчёт = запустить_в_клетке(
        "stanok.handlers", "извлечь",
        {"путь": str(путь), "формат": формат,
         "движок": точка,
         "document_id": getattr(паспорт, "document_id", "") or ""},
        limits=свои_пределы,
        путь=[str(Path(__file__).resolve().parents[1]), *(пути_клетки or ())])
    измерения = отчёт.измерения or {}
    if not отчёт.получилось:
        проводка.этап(
            "клетка", False,
            f"{отчёт.код}: {отчёт.объяснение}"
            + f"; в клетке {измерения.get('в_клетке', 0)}")
        return Извлечение(
            EXTRACTION_VERSION, (), точка["класс"], "",
            (Refusal(отчёт.код or "E_SANDBOX_FAILED", отчёт.объяснение),))

    ответ = отчёт.значение or {}
    проводка.этап(
        "клетка", bool(измерения.get("в_клетке")),
        f"отдельный процесс: {измерения.get('duration_seconds', 0)} с, "
        f"память {измерения.get('memory_bytes', 0)} байт, "
        + ("пределы держит система" if измерения.get("в_клетке")
           else "ПРЕДЕЛЫ НЕ ПРИНУЖДАЮТСЯ: клетка не встала"))
    отказы = tuple(Refusal(о["code"], о["message"])
                   for о in ответ.get("refusals", ()))
    объекты = tuple(объект_из_json(з) for з in ответ.get("объекты", ()))
    return Извлечение(EXTRACTION_VERSION, объекты, ответ.get("движок", ""),
                      ответ.get("версия_движка", ""), отказы)


def _с_отказом(паспорт, отказы):
    """Вносит отказы в паспорт входа, если паспорт уже составлен.

    Паспорт неизменяем, и правится он тем же порядком, что в приёме: возвратом
    нового. Прежние отказы сохраняются — вынесенный отказ не отменяется
    последующим.
    """
    if паспорт is None:
        return None
    return replace(паспорт, refusals=tuple(паспорт.refusals) + tuple(отказы))


def _провести(проводка, путь, *, оснастка, политика, розетка, перепроверка,
              метрики, зерно, реквизиты, объявленные_итоги, пределы,
              срок, клетка, пути_клетки) -> Проводка:

    # 1. Приём как недоверенного входа (шаги 20–22).
    try:
        паспорт = accept_file(путь, limits=пределы)
        проводка.паспорт = паспорт
        проводка.этап("приём", паспорт.accepted,
                      "принят" if паспорт.accepted else str(паспорт.refusal))
    except IntakeError as беда:
        проводка.этап("приём", False, str(беда))
        проводка.состояние_запуска = реш.BLOCKED
        return проводка

    # 2. Политика негодных файлов (шаг 23).
    if паспорт.accepted:
        вердикт = осмотреть_файл_политикой(путь)
        паспорт = внести_в_паспорт(паспорт, вердикт)
        проводка.паспорт = паспорт
        проводка.этап("политика входа", паспорт.accepted,
                      "; ".join(о.message for о in вердикт.refusals) or "годен")

    if not паспорт.accepted:
        # Раздел 10.2: блокировка запуска выше любых решений по записям.
        проводка.состояние_запуска = реш.BLOCKED
        return проводка

    # 3. Чтение байтов и извлечение через розетку (шаги 25–28).
    данные = _прочитать(путь, проводка)
    if данные is None:
        проводка.состояние_запуска = реш.FAILED
        return проводка

    # 3а. Результат станка не бывает его входом (шаг 59).
    #
    # Разбор разобранного превращает суждение оператора в «прочитанное из
    # бумаги»: у исправленного значения появились бы координаты и происхождение,
    # и через два круга прочитанное стало бы неотличимо от додуманного.
    if метка_в_байтах(данные):
        код, объяснение = отказ_приёма("файл")
        проводка.этап("производное", False, объяснение)
        проводка.паспорт = _с_отказом(паспорт, (Refusal(код, объяснение),))
        проводка.состояние_запуска = реш.BLOCKED
        return проводка

    извлечение = _извлечь(розетка, паспорт, данные, путь, пределы, срок,
                          клетка, проводка, пути_клетки)
    if not извлечение.получилось:
        проводка.этап("извлечение", False,
                      "; ".join(о.message for о in извлечение.refusals))
        # Розетка обращает любую беду адаптера в отказ, и превышение предела
        # приходит оттуда же — от мягкого срока или от клетки, — но исход у
        # него другой: это нарушение объявленного предела, а такое блокирует
        # запуск (раздел 10.2), а не объявляет разбор несостоявшимся по вине
        # документа. Различаются они по коду, а не по тому, кто их принёс.
        по_пределу = [о for о in извлечение.refusals
                      if о.code and о.code.startswith("E_LIMIT_")]
        if по_пределу:
            проводка.паспорт = _с_отказом(паспорт, по_пределу)
            проводка.состояние_запуска = реш.BLOCKED
        else:
            проводка.состояние_запуска = реш.FAILED
        return проводка
    проводка.объекты = tuple(извлечение.объекты)
    проводка.этап("извлечение", True,
                  f"{извлечение.движок}: объектов {len(проводка.объекты)}")

    # Метка могла быть спрятана внутрь сжатого контейнера — в байтах файла её
    # не видно, а в извлечённом содержимом видно. Проверяем до сборки записей:
    # разбирать дальше значило бы делать ровно то, что запрещено.
    if метка_в_объектах(проводка.объекты):
        код, объяснение = отказ_приёма("содержимое")
        проводка.этап("производное", False, объяснение)
        проводка.паспорт = _с_отказом(паспорт, (Refusal(код, объяснение),))
        проводка.состояние_запуска = реш.BLOCKED
        return проводка

    # 3а. Опознание формы. Спрашивается **до** разбора и всерьёз.
    #
    # Третий настоящий документ показал, зачем: чужую выписку конвейер прогнал
    # своей оснасткой и получил ноль записей — но не потому, что проверил
    # признаки, а потому, что вёрстка разошлась сильно. Разойдись она слабее,
    # чужой документ разобрался бы как свой, тихо и неверно. Признаки выбора
    # существуют ровно затем, чтобы этого не случилось, и спрашивать их надо
    # раньше, чем прикладывать полосы колонок.
    if оснастка is not None:
        свой, почему = оснастка.подходит(_весь_текст(проводка.объекты))
        проводка.опознан = свой
        проводка.этап("опознание формы", свой, почему)
        if not свой:
            # Дальше идти нельзя: всё, что ниже, разбирает документ **этого**
            # семейства. Приложить его правила к чужому документу значит
            # получить правдоподобный разбор чужого — худший из исходов.
            проводка.этап(
                "разбор", False,
                "разбор не начинался: документ не опознан как документ "
                f"семейства {оснастка.версия}")
            return проводка

    # 4. Сегментация (шаг 32) и адреса (шаг 33).
    # Сборка страниц — одно долгое место на все свои этапы: сегментация,
    # сшивка продолжений и границы записей делят один потолок, а не берут по
    # потолку каждая.
    сборка = срок.место("сборка страниц")
    сегментация = разложить(проводка.объекты, срок=сборка)
    проводка.сегментация = сегментация
    проводка.этап("сегментация", сегментация.учёт_сходится,
                  f"кандидатов {len(сегментация.кандидаты)}, "
                  f"неразобранного {len(сегментация.неразобранное)}")
    адреса = _адреса(проводка.объекты, проводка)

    # 5. Продолжения таблиц (шаг 36) и карта покрытия (шаг 34).
    #
    # Оснастка здесь не украшение: вопрос «продолжение это или новая таблица
    # той же формы» по одному устройству страницы неразрешим, и разрешает его
    # только объявление семейства о шапке. Без него сшивка честно отвечает
    # «не знаю», неизвестность идёт в полноту, а ворота приравнивают её к
    # невыполнению — то есть выпуск закрыт навсегда по причине, которая на
    # деле объявлена и лежит в пакете. Прежде оснастка сюда не доходила.
    сшивка = сшить(сегментация, оснастка=оснастка, срок=сборка)
    # Сшивка удалась не тогда, когда её сделали, а тогда, когда после неё не
    # осталось нерешённого. Тот же довод, что нашло испытание шага 64: успех,
    # объявленный по числу выполненных действий, ничего не говорит об итоге.
    нерешённое = неуверенности(сшивка)
    проводка.этап(
        "продолжения", not нерешённое,
        f"таблиц после сшивки {len(сшивка.таблицы)}, "
        f"нерешённого {len(нерешённое)}"
        + (f"; {нерешённое[0][:100]}" if нерешённое else ""))
    ожидания = оснастка.ожидания(_наблюдения_ожиданий(сегментация)) if оснастка else ()
    карта = построить(ожидания, сегментация)
    проводка.карта = карта
    проводка.этап("покрытие", not карта.расхождения,
                  f"ожиданий {len(карта.ожидания)}, расхождений {len(карта.расхождения)}")

    # 6. Полнота (шаг 35).
    полнота = оценить(карта, механизмы_с_оснасткой(оснастка),
                      неуверенности(сшивка))
    проводка.полнота = полнота
    проводка.этап("полнота", полнота.статус == "complete", полнота.статус)

    # 7. Реквизиты документа и типизация (шаг 29).
    свои_реквизиты, не_найдены = прочитать_реквизиты(сегментация.строки, оснастка)
    if свои_реквизиты or не_найдены:
        проводка.этап("реквизиты", not не_найдены,
                      f"прочитано {len(свои_реквизиты)}"
                      + (f", не найдено: {', '.join(не_найдены)}" if не_найдены else ""))
        реквизиты = {**свои_реквизиты, **(реквизиты or {})}
        свои_итоги, беды_итогов = _итоги_из_реквизитов(
            свои_реквизиты, оснастка)
        if свои_итоги or беды_итогов:
            проводка.этап("итоги документа", not беды_итогов,
                          f"прочитано {len(свои_итоги)}"
                          + ("; " + "; ".join(беды_итогов) if беды_итогов else ""))
            объявленные_итоги = tuple(объявленные_итоги) + свои_итоги
    записи = _записи(сегментация, оснастка, проводка, сборка)
    проводка.записи = записи

    # 8–11. Проверки уровней 4–7 и перепроверка.
    общие, по_записям = _проверки(записи, оснастка, реквизиты,
                                  объявленные_итоги, проводка)

    # 12. Режимы перепроверки (шаг 44).
    отбор = _отбор(записи, оснастка, метрики, зерно, политика, проводка)
    проводка.отбор = отбор

    # 13. Решение по каждой записи (шаг 45).
    if политика is None:
        проводка.этап("решение", False, "политика допуска не приложена")
        return проводка

    проводка.решения = _решения(записи, общие, по_записям, полнота, отбор,
                                перепроверка, политика, проводка, срок)
    проводка.состояние_запуска = реш.решить_запуск(проводка.решения)
    # Этап удался не оттого, что состояние вычислено, а оттого, каким оно
    # вышло: заблокированный и сорванный запуск успехом не бывает.
    проводка.этап(
        "состояние запуска",
        проводка.состояние_запуска not in (реш.BLOCKED, реш.FAILED),
        проводка.состояние_запуска)
    return проводка


