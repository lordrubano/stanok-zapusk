def _прочитать(путь, проводка):
    try:
        with open(путь, "rb") as файл:
            данные = файл.read()
    except OSError as беда:
        проводка.этап("чтение", False, str(беда))
        return None
    проводка.этап("чтение", True, f"байт {len(данные)}")
    return данные


def _адреса(объекты, проводка) -> dict:
    """Адреса областей источника. Объект без устойчивого адреса — не беда сама
    по себе, но и не адрес: молчаливо выдумывать его нельзя."""
    собранные = {}
    без_адреса = 0
    for место, объект in enumerate(объекты):
        try:
            собранные[место] = якорь_объекта(объект).идентификатор
        except (ЯкорьНевозможен, Exception):
            без_адреса += 1
    проводка.этап("адреса", без_адреса == 0,
                  f"с адресом {len(собранные)}, без адреса {без_адреса}")
    return собранные


def _отметить_страницу(проводка, запись, всего: int) -> None:
    """Отметка хода по страницам (шаг 81): «страница 412 из 860».

    Этапов на длинном документе мало, а идут они долго: без страниц отметка
    стояла бы неподвижно минутами, и наблюдатель звал бы беду на исправной
    работе. Страница — самое мелкое движение, которое конвейер видит сам.
    """
    отметчик = getattr(проводка, "отметчик", None)
    класть = getattr(отметчик, "страница", None)
    if класть is None:
        return
    номер = getattr(getattr(запись, "первая", None), "страница", None)
    if номер is None:
        return
    try:
        класть(int(номер), всего or None)
    except Exception:  # noqa: BLE001 — отметка не сторож работы
        pass


def _наблюдения_ожиданий(сегментация) -> dict:
    """Измеренное, на которое опираются объявленные оснасткой ожидания."""
    return {"строк_объявлено": None}


def _записи(сегментация, оснастка, проводка, срок=None):
    """Собирает записи по границе операции и раскладывает поля по колонкам.

    Раньше ячейки шли в поля по порядку — первая в первое объявленное поле. На
    настоящем документе это было бы неверно: колонок восемь, заполненных ячеек
    семь, одна колонка пуста, а две делят одно поле. Теперь и граница операции,
    и место каждой колонки объявлены оснасткой.
    """
    if оснастка is None:
        проводка.этап("типизация", False,
                      "оснастка не приложена: правил истолкования нет")
        return []

    сборка = собрать_записи(сегментация.строки, оснастка, срок=срок)
    проводка.этап("границы операций", not сборка.беды and сборка.учёт_сходится,
                  f"записей {len(сборка.записи)}, вне записей "
                  f"{len(сборка.вне_записей)}, учёт "
                  f"{'сошёлся' if сборка.учёт_сходится else 'НЕ сошёлся'}"
                  + (f"; {сборка.беды[0]}" if сборка.беды else ""))
    if not колонки(оснастка):
        проводка.этап("типизация", False,
                      "колонки оснасткой не объявлены: раскладывать поля не по чему")
        return []

    правила = оснастка.правила_истолкования()
    записи, беды, лишних = [], 0, 0
    происхождение: dict = {}
    предупреждения: dict = {}
    повторы: dict = {}
    всего_страниц = len(getattr(сегментация, "страницы", ()) or ())
    for место, запись in enumerate(сборка.записи, start=1):
        if срок is not None:
            срок.тик()
        _отметить_страницу(проводка, запись, всего_страниц)
        сырые, лишние, свои_повторы = разложить_по_колонкам(запись.первая,
                                                            оснастка)
        лишних += len(лишние)
        if свои_повторы:
            повторы[f"зп-{место}"] = свои_повторы
        поля, сколько, свои = _истолковать(сырые, оснастка, правила)
        беды += сколько
        предупреждения[f"зп-{место}"] = предупреждения_записи(поля, правила)
        собранные = собрать_запись(f"зп-{место}", поля, оснастка.версия,
                                   [запись.адрес])
        происхождение[собранные["record_id"]] = свои
        записи.append(собранные)
    проводка.этап("типизация", беды == 0,
                  f"записей {len(записи)}, неистолкованных полей {беды}, "
                  f"ячеек вне объявленных колонок {лишних}")
    сколько_повторов = sum(len(с) for с in повторы.values())
    проводка.повторы_в_колонках = повторы
    проводка.этап(
        "повторы в колонках", сколько_повторов == 0,
        f"колонок с повтором {сколько_повторов} в {len(повторы)} записях"
        if сколько_повторов else "ни одна колонка не получила двух ячеек")
    свод = свод_происхождения(
        [с for свои in происхождение.values() for с in свои])
    проводка.этап("происхождение", свод["происхождение_полно"],
                  f"полей {свод['полей']}, прослеживается "
                  f"{свод['прослеживается']}, без адреса {свод['без_адреса']}")
    проводка.происхождение = происхождение
    проводка.предупреждения = предупреждения
    сводка = свод_предупреждений(
        [п for свои in предупреждения.values() for п in свои])
    проводка.этап("предупреждения о значении", сводка["нет_предупреждений"],
                  f"предупреждений {сводка['предупреждений']}"
                  + (f", по родам: {сводка['по_родам']}"
                     if сводка["предупреждений"] else ""))
    return записи


def _истолковать(сырые, оснастка, правила):
    """Истолковывает значения по схеме семейства и собирает происхождение.

    Происхождение собирается здесь, а не отдельным проходом, по существу дела:
    только в этот миг рядом оказываются ячейка источника, применённое правило и
    полученное значение. Собранное позже пришлось бы восстанавливать по
    догадке, а догадка свидетельством не бывает.
    """
    from .typizer import (истолковать_дату, истолковать_деньги,
                          истолковать_словарь, истолковать_текст)

    поля, беды, свидетельства = {}, 0, []
    for описание in оснастка.поля:
        имя, тип = описание["имя"], описание.get("тип")
        ячейка = сырые.get(имя)
        if ячейка is None:
            continue
        сырое = getattr(ячейка, "текст", ячейка)
        откуда = getattr(ячейка, "откуда", "")
        если_выведено = getattr(ячейка, "ячейка", None)
        для_адреса = если_выведено if откуда else ячейка
        if тип == "деньги":
            истолкование = истолковать_деньги(сырое, правила)
        elif тип == "дата":
            истолкование = истолковать_дату(сырое, правила)
        elif тип == "словарь":
            истолкование = истолковать_словарь(сырое, описание.get("словарь"),
                                               правила)
        else:
            истолкование = истолковать_текст(сырое)
        if истолкование.отказ is not None:
            беды += 1
        поля[имя] = истолкование
        свидетельства.append(свидетельство(
            имя, для_адреса, истолкование, правила, описание, откуда))
    return поля, беды, tuple(свидетельства)


def _проверки(записи, оснастка, реквизиты, объявленные_итоги, проводка):
    """Уровни 4–7. Что судится по записи, а что по набору — разные вещи.

    Конвейер это и обнаружил: пока типы и межполевые правила сводились по
    всему набору, одна негодная строка топила все остальные — запись отвечала
    за чужую беду. Порядок, повторы и итоги по природе набора и остаются
    общими: пропуск в нумерации не принадлежит ни одной записи в отдельности.
    """
    из_правил = реш.из_правил
    общие = {}

    порядок = проверить_порядок(записи, оснастка)
    общие["order_and_duplicate_checks_passed"] = из_правил(
        "order_and_duplicate_checks_passed", порядок)
    _этап_правил(проводка, "проверка порядка", порядок)

    итоги = проверить_итоги(записи, объявленные_итоги, оснастка)
    общие["required_totals_passed"] = из_правил("required_totals_passed", итоги)
    _этап_правил(проводка, "проверка итогов", итоги)

    по_записям = {}
    всего_типов = всего_межполевых = 0
    нарушено_типов = нарушено_межполевых = 0
    for запись in записи:
        типы = проверить_запись(запись, оснастка)
        межполевые = проверить_межполевые([запись], реквизиты, оснастка)
        всего_типов += len(типы)
        всего_межполевых += len(межполевые)
        нарушено_типов += _нарушено(типы)
        нарушено_межполевых += _нарушено(межполевые)
        по_записям[запись["record_id"]] = [
            из_правил("required_types_valid", типы),
            из_правил("domain_rules_passed", межполевые),
        ]
    проводка.этап("проверка типов", нарушено_типов == 0,
                  f"правил {всего_типов}, нарушено {нарушено_типов}")
    проводка.этап("межполевые правила", нарушено_межполевых == 0,
                  f"правил {всего_межполевых}, нарушено {нарушено_межполевых}")
    return общие, по_записям


def _нарушено(правила) -> int:
    return sum(1 for п in правила if getattr(п, "статус", "") == "нарушено")


def _этап_правил(проводка, имя: str, правила) -> None:
    """Этап проверки удался, только если её правила прошли.

    Прежде здесь стояло число правил, и этап объявлял успех уже потому, что
    правила были посчитаны. Найдено испытанием шага 64: документ с вырезанной
    серединой шёл через конвейер без единого видимого возражения, хотя правила
    итогов внутри говорили «документ не сходится сам с собой». Половина
    выдавалась за целое — не в записи, а в том, что о ней рассказано.
    """
    правила = tuple(правила)
    нарушено = _нарушено(правила)
    неизвестно = sum(1 for п in правила
                     if getattr(п, "статус", "") == "неизвестно")
    сказано = f"правил {len(правила)}, нарушено {нарушено}"
    if неизвестно:
        сказано += f", неизвестно {неизвестно}"
    if нарушено:
        первое = next(п for п in правила if п.статус == "нарушено")
        сказано += f"; {getattr(первое, 'причина', '')[:120]}"
    проводка.этап(имя, bool(правила) and нарушено == 0, сказано)


def _отбор(записи, оснастка, метрики, зерно, политика, проводка):
    признаки = [Признаки(запись["record_id"]) for запись in записи]
    версия_политики = getattr(политика, "версия", "")
    try:
        отбор, основание = назначить(признаки, метрики, оснастка, зерно=зерно,
                                     политика=версия_политики)
    except Exception as беда:
        проводка.этап("режим перепроверки", False, f"{type(беда).__name__}: {беда}")
        return None
    проводка.этап("режим перепроверки", True,
                  f"{отбор.режим}: {основание.вычисления}")
    return отбор


def _решения(записи, общие, по_записям, полнота, отбор, перепроверка, политика,
             проводка, срок=None):
    # Распознавание изображения — долгое место со своим потолком, но запас оно
    # берёт из общего срока файла, а не заводит себе новый.
    срок_распознавания = (срок.место("распознавание изображения")
                          if срок is not None and перепроверка is not None
                          else None)
    решения = []
    for запись in записи:
        свои_свидетельства = проводка.происхождение.get(запись["record_id"], ())
        свои_предупреждения = проводка.предупреждения.get(запись["record_id"], ())
        наблюдения = list(общие.values())
        наблюдения.extend(по_записям.get(запись["record_id"], ()))
        наблюдения.append(_наблюдение(
            "coverage_complete",
            реш.ДА if полнота.статус == "complete" else реш.НЕ_ИЗВЕСТНО,
            "шаг 35", f"статус покрытия {полнота.статус}"))
        наблюдения.append(_наблюдение(
            "run_not_blocked", реш.ДА, "шаги 20–24",
            "приём и политика входа пройдены"))
        наблюдения.append(_наблюдение(
            "no_value_warning",
            реш.ДА if нет_предупреждений(свои_предупреждения) else реш.НЕТ,
            "предупреждения о значении",
            "станок нигде не решал, только читал"
            if нет_предупреждений(свои_предупреждения)
            else "; ".join(f"{п.поле}: {п.правило}"
                           for п in свои_предупреждения)))
        наблюдения.append(_наблюдение(
            "provenance_complete",
            реш.ДА if происхождение_полно(свои_свидетельства) else реш.НЕ_ИЗВЕСТНО,
            "происхождение поля",
            f"полей со свидетельством {len(свои_свидетельства)}, "
            + ("все прослеживаются до места на странице"
               if происхождение_полно(свои_свидетельства)
               else "не все прослеживаются до места на странице")))
        наблюдения.append(_наблюдение(
            "reversibility_check_passed",
            *_обратимость(запись, политика)))
        if отбор is not None:
            наблюдения.append(реш.из_плана(
                отбор, запись["record_id"],
                перепроверка.прочитать(None, b"", (), срок=срок_распознавания)
                if перепроверка else (),
                политика))
        решения.append(реш.решить(запись["record_id"], наблюдения, политика))
    проводка.этап("решение", bool(решения), f"решений {len(решения)}")
    return решения


def _обратимость(запись, политика):
    """Проверяет, что решённая запись канонизируется и читается обратно.

    Настоящая обратимость (раздел 9, уровень 9) сличает разбор с источником;
    здесь проверяется сериализация — то, что доступно без корпуса. Названо это
    своим именем в оговорках.
    """
    from .canonical import CanonicalError, canonical_record_bytes
    from .reverse import parse_canonical_record

    свой = dict(запись)
    свой["decision"] = "review"
    try:
        байты = canonical_record_bytes(свой)
        parse_canonical_record(байты)
    except (CanonicalError, ValueError) as беда:
        return реш.НЕТ, "шаги 14 и 16", str(беда)
    return реш.ДА, "шаги 14 и 16", "каноническая запись читается обратно"


