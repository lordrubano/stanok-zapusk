def _итоги_из_реквизитов(реквизиты, оснастка):
    """Обращает денежные реквизиты документа в объявленные итоги (шаг 41).

    Итог берётся из самого документа — это и есть то независимое утверждение,
    ради которого уровень итогов существует. Реквизит, который оснастка деньгами
    не объявила, итогом не становится: превращать в деньги что попало значило бы
    выдумать величину.
    """
    from .totals import ОбъявленныйИтог
    from .columns import реквизиты_объявлены

    правила = оснастка.правила_истолкования()
    валюта = реквизиты.get("валюта_счёта") or правила.валюта
    итоги, беды = [], []
    for объявление in реквизиты_объявлены(оснастка):
        имя = объявление.get("имя")
        if not объявление.get("деньги") or имя not in реквизиты:
            continue
        истолкование = _истолковать_деньги(реквизиты[имя], правила)
        if истолкование.отказ is not None:
            беды.append(f"{имя}: {истолкование.отказ.message}")
            continue
        итоги.append(ОбъявленныйИтог(имя, истолкование.value, валюта))
    return tuple(итоги), tuple(беды)


