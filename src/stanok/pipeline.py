"""Сквозной конвейер: документ от приёма до решения.

Работа вне нумерации, по решению владельца после глобальной проверки. Собран
затем, что глобальная проверка обнаружила: все уровни станка работают
поодиночке, а вместе их не соединял никто. Первая же попытка соединить нашла
сломанный стык движка с каноническим форматом, и это довод в пользу того, что
щели ищутся не чтением, а проводкой.

**Конвейер ничего не решает сам.** Он ведёт документ по этапам и складывает
наблюдения; статус рождается там же, где и раньше, — в движке политик. Ни один
этап здесь не улучшает результат другого и не подменяет его умолчанием.

**Этап, который не удался, конвейер не роняет.** Отказ — состояние, а не
падение: этап записывает беду в журнал проводки, а слагаемые, которые он должен
был наблюдать, остаются неизвестными. Неизвестное блокирует автодопуск, и это
верное поведение: сорвавшийся этап не должен ни отклонять запись по деловому
существу, ни тем более пропускать её.

**Чего конвейер не делает.** Он не извлекает реквизиты документа и напечатанные
в нём итоги: извлекателей нет, и выдумывать их здесь значило бы подсунуть
проверкам данные, которых в документе никто не видел. Их подают снаружи, и не
поданное честно остаётся неизвестным.
"""

