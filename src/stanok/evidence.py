# -*- coding: utf-8 -*-
"""Происхождение поля: откуда взялась каждая цифра.

Работа вне нумерации, Фаза 4. Нормативная основа — чертёж v3.0, раздел 6.1
(сущность ``FieldEvidence``: source_anchor_id, сырьё, движок, версия, правило
преобразования, итоговое значение) и раздел 6.2 (устойчивый адрес области).

**Этого не было вовсе.** Глобальная проверка нашла, что слагаемому допуска
«происхождение значения» приписан несуществующий источник: ``FieldEvidence`` в
станке не собирался ни одной строкой. Все данные для него были — адрес области,
имя и версия движка, правило истолкования, сырьё и итог, — но лежали в четырёх
разных местах и вместе не сводились.

**Ради чего.** Это не бухгалтерия ради бухгалтерии, а то самое обещание, ради
которого продукт и строится: **любую цифру в готовой таблице можно проследить до
места на странице оригинала**. Без происхождения на вопрос «откуда это число»
ответить нечем — а вопрос этот задаёт не проверяющий, а спорящая сторона.

**Что здесь не делается.** Происхождение ничего не проверяет и ничего не
исправляет. Оно свидетельствует. Поле без адреса не становится негодным — оно
становится **непрослеживаемым**, и это разные вещи: непрослеживаемое значение
может быть верным, но доказать его нельзя.

**Адрес не выдумывается.** Область, для которой устойчивый адрес построить
нельзя (шаг 33 отказывается его строить), остаётся без адреса, и причина
называется. Придуманный адрес хуже отсутствующего: он выглядит как ссылка и
ведёт в никуда.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from decimal import Decimal

from .anchors import ЯкорьНевозможен, якорь_объекта


EVIDENCE_VERSION = "field-evidence/1"

KNOWN_LIMITATIONS = (
    "Происхождение собирается для полей, пришедших из ячеек источника. Поле, "
    "заполненное правилом оснастки, а не ячейкой — как признак операции, "
    "который берётся из того, в какой колонке стоит сумма, — несёт адрес той "
    "самой колонки и правило, по которому выведен: своей ячейки у него нет.",
    "Правило преобразования записывается словами по объявлениям оснастки. Это "
    "описание применённого правила, а не исполнимая запись: повторить "
    "преобразование по нему может человек, но не станок.",
    "Область источника описывается адресом, страницей и полигоном в долях "
    "листа. Пикселей отображения здесь нет и быть не может: они не адрес "
    "(раздел 6.2).",
    "Цепочка «клетка Excel — поле записи — область страницы» строится по "
    "record_id и имени поля. Сама выгрузка ставит эти два признака рядом со "
    "значением; без них проследить цифру нельзя.",
)


@dataclass(frozen=True, slots=True)
class FieldEvidence:
    """Происхождение одного поля. Состав — раздел 6.1."""

    поле: str
    source_anchor_id: str | None
    сырьё: str | None
    движок: str
    версия_движка: str
    правило: str
    значение: str | None
    страница: int | None = None
    полигон: tuple | None = None
    система_координат: str = ""
    почему_без_адреса: str = ""

    @property
    def прослеживается(self) -> bool:
        """Можно ли по этому свидетельству дойти до места на странице."""
        return bool(self.source_anchor_id) and self.страница is not None

    def место(self) -> str:
        """Человеческое описание места на странице оригинала."""
        if not self.прослеживается:
            return f"место неизвестно: {self.почему_без_адреса or 'адреса нет'}"
        if self.полигон:
            левый = min(float(т[0]) for т in self.полигон)
            нижний = min(float(т[1]) for т in self.полигон)
            правый = max(float(т[0]) for т in self.полигон)
            верхний = max(float(т[1]) for т in self.полигон)
            return (f"страница {self.страница}, область по долям листа "
                    f"{левый:.3f}…{правый:.3f} по горизонтали и "
                    f"{нижний:.3f}…{верхний:.3f} по вертикали")
        return f"страница {self.страница}, область не построена"

    def as_json(self) -> dict:
        return {
            "версия": EVIDENCE_VERSION,
            "поле": self.поле,
            "source_anchor_id": self.source_anchor_id,
            "сырьё": self.сырьё,
            "движок": self.движок,
            "версия_движка": self.версия_движка,
            "правило": self.правило,
            "значение": self.значение,
            "страница": self.страница,
            "полигон": ([list(т) for т in self.полигон] if self.полигон
                        else None),
            "система_координат": self.система_координат,
            "прослеживается": self.прослеживается,
            "почему_без_адреса": self.почему_без_адреса,
        }


def _как_текст(значение) -> str | None:
    if значение is None:
        return None
    if isinstance(значение, (Decimal, date)):
        return str(значение)
    return значение if isinstance(значение, str) else repr(значение)


def правило_преобразования(вид: str, правила, описание=None) -> str:
    """Словами описывает, каким правилом получено значение.

    Берётся из объявлений оснастки, а не из головы: если правило не объявлено,
    так и сказано. Описание должно позволять человеку повторить преобразование
    руками — иначе оно не свидетельство, а украшение.
    """
    части = [f"истолкование «{вид}»"]
    if вид == "деньги":
        части.append(f"разделитель дробной {правила.разделитель_дробной!r}")
        части.append(f"разделитель групп {правила.разделитель_групп!r}")
        части.append("неявные копейки: "
                     + {True: "да", False: "нет", None: "не объявлено"}[
                         правила.неявные_копейки])
        части.append(f"знак в скобках: {'да' if правила.знак_в_скобках else 'нет'}")
        части.append(f"валюта {правила.валюта!r}")
    elif вид == "дата":
        части.append(f"порядок частей {правила.порядок_даты!r}")
    elif вид == "словарь":
        имя = (описание or {}).get("словарь")
        части.append(f"словарь {имя!r}")
    elif вид == "текст":
        части.append("нормализация NFC, оригинал сохранён рядом")
    return "; ".join(части)


def _адрес(объект):
    """Адрес области источника либо причина, почему его нет."""
    if объект is None:
        return None, None, None, "", "ячейка не несёт объекта источника"
    try:
        якорь = якорь_объекта(объект)
    except ЯкорьНевозможен as отказ:
        return None, объект.страница, None, "", str(отказ)
    except Exception as беда:      # pragma: no cover — запас прочности
        return None, объект.страница, None, "", f"адрес не построен: {беда}"
    return (якорь.идентификатор, якорь.страница, якорь.полигон,
            якорь.система, "")


def свидетельство(поле: str, ячейка, истолкование, правила,
                  описание=None, откуда: str = "") -> FieldEvidence:
    """Собирает происхождение одного поля.

    ``откуда`` — пояснение для поля, у которого своей ячейки нет: например,
    признак операции выведен из того, в какой колонке стояла сумма.
    """
    объект = getattr(ячейка, "объект", None)
    адрес, страница, полигон, система, почему = _адрес(объект)
    вид = getattr(истолкование, "вид", "") or ""
    правило = правило_преобразования(вид, правила, описание)
    if откуда:
        правило = f"{правило}; поле выведено: {откуда}"
    return FieldEvidence(
        поле=поле,
        source_anchor_id=адрес,
        сырьё=getattr(истолкование, "raw", None),
        движок=getattr(объект, "движок", "") or "",
        версия_движка=getattr(объект, "версия_движка", "") or "",
        правило=правило,
        значение=_как_текст(getattr(истолкование, "value", None)),
        страница=страница,
        полигон=полигон,
        система_координат=система,
        почему_без_адреса=почему,
    )


def происхождение_полно(свидетельства) -> bool:
    """Условие ``provenance_complete`` формулы 10.1.

    Истинно, только если **каждое** поле прослеживается до места на странице и
    несёт движок, правило и итоговое значение. Пустой набор истинным не
    считается: отсутствие свидетельств — не доказательство происхождения.
    """
    свидетельства = tuple(свидетельства)
    if not свидетельства:
        return False
    return all(с.прослеживается and с.движок and с.правило
               and с.значение is not None for с in свидетельства)


def свод(свидетельства) -> dict:
    свидетельства = tuple(свидетельства)
    без_адреса = tuple(с for с in свидетельства if not с.прослеживается)
    причины: dict[str, int] = {}
    for с in без_адреса:
        ключ = с.почему_без_адреса or "причина не названа"
        причины[ключ] = причины.get(ключ, 0) + 1
    return {
        "версия": EVIDENCE_VERSION,
        "полей": len(свидетельства),
        "прослеживается": len(свидетельства) - len(без_адреса),
        "без_адреса": len(без_адреса),
        "почему_без_адреса": причины,
        "движков": sorted({f"{с.движок}/{с.версия_движка}"
                           for с in свидетельства if с.движок}),
        "происхождение_полно": происхождение_полно(свидетельства),
    }


def след(свидетельства, поле: str) -> str:
    """Человеческий ответ на вопрос «откуда это число».

    Ровно то, ради чего продукт строится: от значения — к месту на странице
    оригинала, с указанием, чем прочитано и по какому правилу истолковано.
    """
    for свидетельство_ in свидетельства:
        if свидетельство_.поле != поле:
            continue
        return (f"{поле} = {свидетельство_.значение!r}; в источнике записано "
                f"{свидетельство_.сырьё!r}; {свидетельство_.место()}; прочитано "
                f"движком {свидетельство_.движок} версии "
                f"{свидетельство_.версия_движка}; {свидетельство_.правило}")
    return f"{поле}: свидетельства о происхождении нет"


