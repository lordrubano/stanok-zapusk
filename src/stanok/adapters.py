# -*- coding: utf-8 -*-
"""Единая розетка распознавателей: контракт и реестр адаптеров извлечения.

Шаг 25 плана. Нормативная основа — чертёж v3.0, раздел 5.1, компонент 3
«Адаптеры извлечения»: нативный разбор, PDF-разбор, локальный OCR или
разрешённый резерв, выход — ``SourceObject[]``. Состав объекта источника задан
разделом 6.1.

Ради чего шаг существует: **распознаватель обязан заменяться без правки ядра**.
Это не удобство разработки, а товарное свойство. Движки стареют, лицензии
меняются, поставщик уходит — и если замена движка требует правки ядра, то
меняется продукт, а не деталь.

Отсюда три правила, которым подчинено всё ниже:

1. **Ядро не знает ни одного распознавателя по имени.** В этом модуле нет ни
   одного имени движка — ни из матрицы маршрутизации чертежа, ни даже своего
   образцового адаптера. Выбор идёт по объявленным адаптером форматам и
   приоритету, а не по списку известных имён: такой список и был бы той самой
   правкой ядра, которой шаг призван избежать. На это есть проверка, и она
   читает этот файл — правило держится не обещанием.
2. **Адаптер подключается снаружи.** Розетка пуста, пока в неё не воткнули.
   Подключить, заменить и отключить можно, не трогая этот файл.
3. **Происхождение ставит розетка, а не адаптер.** Адаптер объявляет своё имя и
   версию один раз при подключении; в каждый объект источника они попадают уже
   от розетки. Иначе адаптер мог бы подписаться чужим именем, и доказательная
   модель потеряла бы смысл.

Что такое адаптер. Любой предмет с четырьмя свойствами — ни наследования, ни
общего предка не требуется:

* ``имя`` — как называется распознаватель;
* ``версия`` — версия движка, строкой;
* ``форматы`` — набор форматов, которые он берёт («txt», «pdf», «xlsx»);
* ``извлечь(конверт, данные)`` — отдаёт последовательность объектов источника.

Отказ — состояние, а не падение: и отсутствие адаптера, и поломка внутри него
возвращаются отчётом с причиной.
"""

