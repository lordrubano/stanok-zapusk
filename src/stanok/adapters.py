@dataclass(frozen=True, slots=True)
class SourceObject:
    """Объект источника до бизнес-истолкования. Состав — раздел 6.1.

    ``полигон`` — нормализованные доли страницы 0…1 либо None там, где области
    на странице нет вовсе (сплошной текст, ячейка книги). Пиксели конкретного
    отображения стабильным адресом не являются и сюда не попадают.
    """

    document_id: str
    страница: int
    система_координат: str
    структурный_путь: str
    сырой_текст: str | None = None
    полигон: tuple[tuple[str, str], ...] | None = None
    свойства: tuple[tuple[str, Any], ...] = ()
    движок: str = ""
    версия_движка: str = ""

    def свойство(self, имя: str, иначе=None):
        for ключ, значение in self.свойства:
            if ключ == имя:
                return значение
        return иначе

    def as_json(self) -> dict[str, Any]:
        return {
            "document_id": self.document_id,
            "страница": self.страница,
            "система_координат": self.система_координат,
            "структурный_путь": self.структурный_путь,
            "сырой_текст": self.сырой_текст,
            "полигон": [list(точка) for точка in self.полигон]
            if self.полигон else None,
            "свойства": dict(self.свойства),
            "движок": self.движок,
            "версия_движка": self.версия_движка,
        }


@dataclass(frozen=True, slots=True)
class Извлечение:
    """Чем кончилось извлечение: объекты источника и чем они получены."""

    schema_version: str
    объекты: tuple[SourceObject, ...] = ()
    движок: str = ""
    версия_движка: str = ""
    refusals: tuple[Refusal, ...] = ()

    @property
    def получилось(self) -> bool:
        return not self.refusals

    def as_json(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "движок": self.движок,
            "версия_движка": self.версия_движка,
            "объекты": [объект.as_json() for объект in self.объекты],
            "refusals": [
                {"code": отказ.code, "message": отказ.message}
                for отказ in self.refusals
            ],
        }


@dataclass(frozen=True, slots=True)
class Вилка:
    """Подключённый адаптер и условия, на которых он выбран."""

    адаптер: Any
    имя: str
    версия: str
    форматы: frozenset[str]
    приоритет: int = 0
    берёт_срок: bool = False
    """Умеет ли адаптер принять срок и стеречь его изнутри своих циклов.

    Не умеющий подключается, но его работа сроком не стережётся: прервать
    чужой цикл снаружи нечем. Молчаливым это не остаётся — розетка называет
    таких по имени (:meth:`Розетка.без_срока`), и станок может о них сказать.
    """


def _берёт_срок(извлечь) -> bool:
    """Принимает ли способ извлечения третий довод — срок.

    Спрашивается один раз, при подключении: разбирать подпись на каждом
    документе накладно, а меняться она между документами не может.
    """
    import inspect

    try:
        подпись = inspect.signature(извлечь)
    except (TypeError, ValueError):
        return False
    доводы = list(подпись.parameters.values())
    if any(д.kind is inspect.Parameter.VAR_POSITIONAL for д in доводы):
        return True
    return len([д for д in доводы
                if д.kind in (inspect.Parameter.POSITIONAL_ONLY,
                              inspect.Parameter.POSITIONAL_OR_KEYWORD)]) >= 3


class РозеткаError(ValueError):
    """Ошибка подключения: неисправная вилка, а не негодный вход."""


class Розетка:
    """Реестр адаптеров извлечения.

    Пуст, пока в него не воткнули. Ядро не подключает ничего само: список
    штатных адаптеров, встроенный сюда, и был бы тем самым знанием ядра о
    распознавателях, ради избавления от которого шаг и делается.
    """

    def __init__(self) -> None:
        self._вилки: list[Вилка] = []

    # ------------------------------------------------------------ подключение

    def подключить(self, адаптер: Any, *, приоритет: int = 0) -> Вилка:
        """Втыкает адаптер. Возвращает вилку — то, что можно вынуть.

        Требования к адаптеру проверяются здесь и сразу: неисправная вилка
        обязана быть видна при подключении, а не при первом документе.
        """
        имя = getattr(адаптер, "имя", None)
        версия = getattr(адаптер, "версия", None)
        форматы = getattr(адаптер, "форматы", None)
        извлечь = getattr(адаптер, "извлечь", None)

        if not isinstance(имя, str) or not имя.strip():
            raise РозеткаError("у адаптера нет имени")
        if not isinstance(версия, str) or not версия.strip():
            raise РозеткаError(f"{имя}: у адаптера нет версии")
        if not callable(извлечь):
            raise РозеткаError(f"{имя}: у адаптера нет способа извлечь")
        try:
            набор = frozenset(str(формат).lower().lstrip(".") for формат in форматы)
        except TypeError as беда:
            raise РозеткаError(f"{имя}: форматы должны быть набором") from беда
        if not набор:
            raise РозеткаError(f"{имя}: адаптер не объявил ни одного формата")
        if not isinstance(приоритет, int) or isinstance(приоритет, bool):
            raise РозеткаError(f"{имя}: приоритет должен быть целым числом")

        вилка = Вилка(адаптер, имя, версия, набор, приоритет,
                      _берёт_срок(извлечь))
        self._вилки.append(вилка)
        return вилка

    def без_срока(self) -> tuple[str, ...]:
        """Имена подключённых адаптеров, не принимающих срока.

        Их работа не стережётся предельным временем изнутри: у станка нет
        способа прервать чужой цикл снаружи. Перечень существует затем, чтобы
        эта дыра была предъявляемой, а не подразумеваемой.
        """
        return tuple(sorted(в.имя for в in self._вилки if not в.берёт_срок))

    def отключить(self, имя: str) -> int:
        """Вынимает все вилки с таким именем. Возвращает, сколько вынуто."""
        было = len(self._вилки)
        self._вилки = [вилка for вилка in self._вилки if вилка.имя != имя]
        return было - len(self._вилки)

    def подключённые(self) -> tuple[Вилка, ...]:
        return tuple(self._вилки)

    # ---------------------------------------------------------------- выбор

    def подходящие(self, формат: str) -> tuple[Вилка, ...]:
        """Вилки, берущие такой формат, от предпочтительной к запасной.

        Порядок задан приоритетом, а при равном приоритете — порядком
        подключения: подключённый позже считается более поздней заменой и идёт
        раньше. Так замена движка не требует трогать приоритеты остальных.
        """
        ключ = str(формат).lower().lstrip(".")
        годные = [(-вилка.приоритет, -место, вилка)
                  for место, вилка in enumerate(self._вилки)
                  if ключ in вилка.форматы]
        годные.sort(key=lambda пара: (пара[0], пара[1]))
        return tuple(вилка for _, _, вилка in годные)

    def выбрать(self, формат: str) -> Вилка | None:
        подходят = self.подходящие(формат)
        return подходят[0] if подходят else None

    # -------------------------------------------------------------- работа

    def извлечь(self, конверт, данные: bytes, *, формат: str | None = None,
                срок=None) -> Извлечение:
        """Извлекает объекты источника подходящим адаптером.

        Ничего не бросает из-за входа: нет адаптера — отказ с причиной,
        поломался адаптер — отказ с причиной. Истёкший срок — тоже причина, и
        отдельного пути ей не нужно: беда, знающая свой код, называет его сама,
        и наружу выходит отказ ``E_LIMIT_DURATION``, а не безликое «разбор не
        удался».
        """
        ключ = формат if формат is not None else _формат_конверта(конверт)
        вилка = self.выбрать(ключ)
        if вилка is None:
            return Извлечение(
                EXTRACTION_VERSION, (), "", "",
                (Refusal("E_NO_ADAPTER",
                         f"нет адаптера для формата {ключ or '<неизвестен>'}"),))

        try:
            добыто = (вилка.адаптер.извлечь(конверт, данные, срок)
                      if вилка.берёт_срок
                      else вилка.адаптер.извлечь(конверт, данные))
            объекты = tuple(добыто)
        except СрокИстёк as вышел:
            # Истёкший срок не заворачивается в «разбор не удался»: разбор не
            # провалился, ему не дали доработать. Причина уходит наружу теми
            # же словами, какими её назвало место, — иначе по журналу нельзя
            # отличить негодный документ от превышенного предела.
            return Извлечение(
                EXTRACTION_VERSION, (), вилка.имя, вилка.версия,
                (Refusal(вышел.код, f"{вилка.имя}: {вышел.отказ.message}"),))
        except MemoryError:
            # Память кончилась не оттого, что адаптер плох, а оттого, что ему
            # не дали взять лишнего: клетка шага 24 держит предел отказом в
            # выделении. Это превышение предела, и называться оно обязано так
            # же, как превышение размера или числа страниц.
            return Извлечение(
                EXTRACTION_VERSION, (), вилка.имя, вилка.версия,
                (Refusal("E_LIMIT_MEMORY",
                         f"{вилка.имя}: разбору отказано в памяти сверх "
                         "предела"),))
        except Exception as беда:  # noqa: BLE001 — адаптер чужой
            # Беда, знающая свой код, называет его сама. Иначе внятная причина
            # («объявление сущности запрещено») превратилась бы в безликое
            # «разбор не удался», и по журналу нельзя было бы отличить
            # нападение от порчи файла.
            код = getattr(беда, "код", None)
            return Извлечение(
                EXTRACTION_VERSION, (), вилка.имя, вилка.версия,
                (Refusal(код if isinstance(код, str) and код else "E_ADAPTER_FAILED",
                         f"{вилка.имя}: разбор не удался ({type(беда).__name__}: {беда})"),))

        плохие = [объект for объект in объекты if not isinstance(объект, SourceObject)]
        if плохие:
            return Извлечение(
                EXTRACTION_VERSION, (), вилка.имя, вилка.версия,
                (Refusal("E_ADAPTER_CONTRACT",
                         f"{вилка.имя}: адаптер вернул не объекты источника"),))

        # Происхождение ставит розетка. Значения, проставленные самим адаптером,
        # затираются намеренно: подписаться чужим именем он не должен.
        подписанные = tuple(
            replace(объект, движок=вилка.имя, версия_движка=вилка.версия)
            for объект in объекты)
        return Извлечение(EXTRACTION_VERSION, подписанные, вилка.имя, вилка.версия)


def _формат_конверта(конверт) -> str:
    """Формат по паспорту входа: расширение без точки.

    Полный маршрут определяет формат богаче — по семейству, шаблону и риску,
    но это классификатор и отдельный шаг. Здесь ровно то, что уже известно.
    """
    suffix = getattr(конверт, "suffix", "") or ""
    return str(suffix).lower().lstrip(".")


