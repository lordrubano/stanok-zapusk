# -*- coding: utf-8 -*-
"""Идемпотентный повтор запуска: тот же документ — тот же итог.

Шаг 62 плана, первый в Фазе 6. Нормативная основа — чертёж v3.0, раздел 19:
«идентификатор безопасного повтора», «для критического запуска должен быть
возможен повтор с теми же версиями либо документированный вывод, почему точное
воспроизведение недоступно».

Три вопроса, на которые шаг отвечает.

**Что такое «тот же запуск».** Не тот же файл на диске и уж точно не то же имя:
имя здесь не судья вовсе. Судья — **отпечаток байтов документа** (раздел 6.2) и
версии того, чем его обрабатывали: оснастки, политики, кода. Один и тот же
документ, обработанный другой оснасткой, — другой запуск, и его итог обязан
считаться заново. Другой документ, названный тем же именем, — тоже другой
запуск, и подменить им прежний нельзя.

**Что значит «повтор ничего не задваивает».** Повтор не создаёт вторых записей
и не пишет второй раз то, что уже записано. При этом сам факт повтора
**не теряется**: он ложится в реестр запусков отдельным событием. Journal
добавляемый: события не исчезают ни при повторе, ни при сбое.

**Что происходит после сбоя.** Незавершённый запуск виден по своей отметке:
«начат» есть, «кончен» нет. Повтор после такого сбоя проходит работу заново
целиком и обязан прийти к **тому же итогу**, что и непрерывный прогон. Не к
половине: половина — это не итог, а состояние, и выдавать её за результат
нельзя. Отпечаток итога сличается, и расхождение объявляется, а не
замалчивается.

**Почему это вообще возможно.** Разбор детерминирован: те же байты, та же
оснастка, тот же код дают тот же результат — на этом стоит весь станок. Повтор
безопасен ровно постольку, поскольку верно это. Отпечаток итога и есть та
проверка, которая не даёт принять «похоже, то же самое» за «то же самое».
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

from . import journal


RUN_VERSION = "run-repeat/1"

НАЧАТ = "начат"
КОНЧЕН = "кончен"
ПОВТОР = "повтор"
РАСХОЖДЕНИЕ = "расхождение"

СОСТОЯНИЯ = (НАЧАТ, КОНЧЕН, ПОВТОР, РАСХОЖДЕНИЕ)

KNOWN_LIMITATIONS = (
    "Повтор безопасен постольку, поскольку разбор детерминирован. Появится "
    "движок, чей ответ зависит от времени или случая, — и повтор перестанет "
    "быть повтором; отпечаток итога это обнаружит, но не исправит.",
    "Реестр запусков хранит отпечаток итога, а не сам итог. Сказать «вышло то "
    "же самое» он может, а выдать прежний результат вместо новой работы — "
    "нет: хранение результатов относится к пакету результата (раздел 13).",
    "Незавершённый запуск определяется по отсутствию отметки «кончен». Если "
    "станок убит между работой и отметкой, повтор сочтёт запуск сорванным и "
    "пройдёт работу заново: лишняя работа, а не потерянная.",
    "Версия кода в ключ подаётся снаружи. Станок не вычисляет её сам: то, чем "
    "он себя считает, и то, чем он является, — разные вещи, и первое не должно "
    "выдаваться за второе.",
)


class ЗапускНегоден(ValueError):
    """Запуск не может быть отмечен или повторён: сказано, почему."""


# ------------------------------------------------------------ ключ


def ключ(document_id: str, версия_оснастки: str = "", версия_политики: str = "",
         версия_кода: str = "") -> str:
    """Идентификатор безопасного повтора (раздел 19).

    Считается из отпечатка документа и версий того, чем его обрабатывали. Имя
    файла в ключ не входит: файл переименовывают, а документ от этого другим не
    становится — и наоборот, чужой документ, названный знакомым именем, обязан
    получить другой ключ.
    """
    если_пусто = str(document_id or "").strip()
    if not если_пусто:
        raise ЗапускНегоден(
            "ключ повтора считается от отпечатка документа, а его нет: "
            "отпечаток даёт приём (шаг 20), и без него повтор неотличим от "
            "первой обработки")
    основа = "\n".join([
        RUN_VERSION, если_пусто, str(версия_оснастки or ""),
        str(версия_политики or ""), str(версия_кода or "")])
    return hashlib.sha256(основа.encode("utf-8")).hexdigest()


def ключ_проводки(проводка, версия_оснастки: str = "",
                  версия_политики: str = "", версия_кода: str = "") -> str:
    """Ключ повтора по готовой проводке. Берёт отпечаток из её паспорта."""
    паспорт = getattr(проводка, "паспорт", None)
    return ключ(getattr(паспорт, "document_id", "") or "", версия_оснастки,
                версия_политики, версия_кода)


# -------------------------------------------------------- отпечаток итога


def отпечаток_итога(проводка) -> str:
    """Отпечаток того, чем кончилась работа. Сравним между запусками.

    В отпечаток идёт то, что обязано повториться: состояние запуска, число и
    содержание записей, статусы решений. **Время сюда не входит** — иначе
    повтор не совпал бы с собой никогда, и проверка стала бы бессмысленной.
    """
    записи = [
        {"record_id": з.get("record_id"), "template_version": з.get("template_version"),
         "fields": {имя: {"value": str(поле.get("value"))
                          if isinstance(поле, dict) else str(поле)}
                    for имя, поле in sorted((з.get("fields") or {}).items())}}
        for з in getattr(проводка, "записи", ())]
    решения = [{"record_id": р.record_id, "статус": р.статус}
               for р in getattr(проводка, "решения", ())]
    # Прочитанное входит в отпечаток отдельным хешем, а не одним числом.
    # Иначе два разных документа, из которых не собралось ни одной записи,
    # дали бы один отпечаток — и повтор объявил бы совпадением то, что им не
    # является. Найдено проверкой, а не рассуждением.
    прочитанное = hashlib.sha256()
    # Разделители между частями обязательны: без них «аб» и «в» неотличимы
    # от «а» и «бв», и два разных прочтения дали бы один отпечаток.
    разделитель, конец_записи = chr(31), chr(30)
    for объект in getattr(проводка, "объекты", ()):
        прочитанное.update(разделитель.join([
            str(объект.страница), объект.структурный_путь or "",
            объект.сырой_текст or "", конец_записи]).encode("utf-8"))

    свод = {
        "версия": RUN_VERSION,
        "состояние_запуска": getattr(проводка, "состояние_запуска", None),
        "опознан": getattr(проводка, "опознан", None),
        "объектов": len(getattr(проводка, "объекты", ())),
        "прочитанное": прочитанное.hexdigest(),
        "записей": len(записи),
        "записи": записи,
        "решения": решения,
    }
    байты = json.dumps(свод, ensure_ascii=False, sort_keys=True,
                       separators=(",", ":"), default=str).encode("utf-8")
    return hashlib.sha256(байты).hexdigest()


# --------------------------------------------------------- реестр запусков


def _записать(реестр, событие: dict) -> str:
    return journal.append_record(реестр, событие,
                                 схема=journal.нормализовать_событие,
                                 доверяя_хвосту=True)


def прочитать(реестр) -> tuple[dict, ...]:
    """Все отметки запусков. Цепь проверяется при чтении."""
    место = Path(реестр)
    if not место.exists():
        return ()
    journal.verify_journal(место, схема=journal.нормализовать_событие)
    события = []
    for строка in место.read_bytes().split(b"\n"):
        if строка.strip():
            события.append(json.loads(строка.decode("utf-8")))
    return tuple(события)


def отметить_начало(реестр, ключ_запуска: str, document_id: str, время: str,
                    подробности: dict | None = None) -> str:
    """Кладёт отметку «начат». Ставится **до** работы, а не после."""
    событие = {
        "schema_version": RUN_VERSION,
        "состояние": НАЧАТ,
        "ключ": ключ_запуска,
        "document_id": document_id,
        "время": время,
    }
    событие.update(подробности or {})
    return _записать(реестр, событие)


def отметить_конец(реестр, ключ_запуска: str, отпечаток: str, записей: int,
                   время: str) -> str:
    """Кладёт отметку «кончен» с отпечатком итога."""
    return _записать(реестр, {
        "schema_version": RUN_VERSION,
        "состояние": КОНЧЕН,
        "ключ": ключ_запуска,
        "отпечаток_итога": отпечаток,
        "записей": записей,
        "время": время,
    })


def отметить_повтор(реестр, ключ_запуска: str, время: str,
                    совпало: bool = True, отпечаток: str = "") -> str:
    """Кладёт отметку о повторе. Повтор не теряется, даже если ничего не делал."""
    return _записать(реестр, {
        "schema_version": RUN_VERSION,
        "состояние": ПОВТОР if совпало else РАСХОЖДЕНИЕ,
        "ключ": ключ_запуска,
        "отпечаток_итога": отпечаток,
        "время": время,
        "совпало": bool(совпало),
    })


def завершённый(события, ключ_запуска: str) -> dict | None:
    """Последняя отметка «кончен» для этого ключа, если она есть."""
    для_ключа = [с for с in события
                 if с.get("ключ") == ключ_запуска and с.get("состояние") == КОНЧЕН]
    return для_ключа[-1] if для_ключа else None


def незавершённые(события) -> tuple[str, ...]:
    """Ключи запусков, у которых есть «начат» и нет «кончен».

    Это и есть след сбоя: станок начал и не дошёл. Такой запуск не считается ни
    удавшимся, ни отсутствующим — он **сорванный**, и повтор обязан пройти
    работу заново.
    """
    начатые, кончённые = [], set()
    for событие in события:
        if событие.get("состояние") == НАЧАТ:
            начатые.append(событие.get("ключ"))
        elif событие.get("состояние") == КОНЧЕН:
            кончённые.add(событие.get("ключ"))
    видано, свои = set(), []
    for ключ_запуска in начатые:
        if ключ_запуска not in кончённые and ключ_запуска not in видано:
            видано.add(ключ_запуска)
            свои.append(ключ_запуска)
    return tuple(свои)


# ------------------------------------------------------------- повтор


@dataclass(frozen=True, slots=True)
class ИтогЗапуска:
    """Чем кончился запуск и был ли он повтором."""

    ключ: str
    род: str
    отпечаток: str
    записей: int
    проводка: object | None = None
    совпало: bool | None = None
    прежний_отпечаток: str = ""

    @property
    def повтор(self) -> bool:
        return self.род in (ПОВТОР, РАСХОЖДЕНИЕ)

    def as_json(self) -> dict:
        return {"версия": RUN_VERSION, "ключ": self.ключ, "род": self.род,
                "отпечаток_итога": self.отпечаток, "записей": self.записей,
                "совпало": self.совпало,
                "прежний_отпечаток": self.прежний_отпечаток}


ПЕРВЫЙ = "первый"
ПОСЛЕ_СБОЯ = "после сбоя"


def провести_идемпотентно(реестр, ключ_запуска: str, document_id: str,
                          работа, время: str, повторять: bool = True
                          ) -> ИтогЗапуска:
    """Проводит работу так, что повтор не задваивает и не теряет.

    ``работа`` — то, что надо сделать: зовётся без доводов и возвращает
    проводку. Она пройдётся заново и при повторе — но её итог не будет записан
    вторым разом; вместо этого отпечатки сличаются, и совпадение (или
    расхождение) объявляется отдельным событием.

    ``повторять=False`` — не делать работу заново, если запуск уже завершён.
    Тогда возвращается прежний отпечаток и род «повтор»: это дешёвый путь для
    случая, когда важно не потерять, а не пересчитать.
    """
    события = прочитать(реестр)
    прежний = завершённый(события, ключ_запуска)
    сорванный = ключ_запуска in незавершённые(события)

    if прежний is not None and not повторять:
        отметить_повтор(реестр, ключ_запуска, время, True,
                        прежний.get("отпечаток_итога", ""))
        return ИтогЗапуска(ключ_запуска, ПОВТОР,
                           прежний.get("отпечаток_итога", ""),
                           прежний.get("записей", 0), None, True,
                           прежний.get("отпечаток_итога", ""))

    отметить_начало(реестр, ключ_запуска, document_id, время)
    проводка = работа()
    отпечаток = отпечаток_итога(проводка)
    записей = len(getattr(проводка, "записи", ()))

    if прежний is None:
        отметить_конец(реестр, ключ_запуска, отпечаток, записей, время)
        род = ПОСЛЕ_СБОЯ if сорванный else ПЕРВЫЙ
        return ИтогЗапуска(ключ_запуска, род, отпечаток, записей, проводка)

    было = прежний.get("отпечаток_итога", "")
    совпало = было == отпечаток
    отметить_повтор(реестр, ключ_запуска, время, совпало, отпечаток)
    return ИтогЗапуска(ключ_запуска, ПОВТОР if совпало else РАСХОЖДЕНИЕ,
                       отпечаток, записей, проводка, совпало, было)


def свод(события) -> dict:
    """Что было с запусками: сколько, чем кончились, где сорвалось."""
    события = tuple(события)
    по_состояниям = {состояние: sum(1 for с in события
                                    if с.get("состояние") == состояние)
                     for состояние in СОСТОЯНИЯ}
    return {
        "версия": RUN_VERSION,
        "событий": len(события),
        "по_состояниям": по_состояниям,
        "ключей": len({с.get("ключ") for с in события}),
        "незавершённых": list(незавершённые(события)),
        "расхождений": по_состояниям[РАСХОЖДЕНИЕ],
    }


