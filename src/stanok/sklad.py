import hashlib
import json
import os
import re
import time
import urllib.error
import urllib.request
from pathlib import Path

SKLAD_VERSION = "sklad/1"

СКЛАД_НЕ_ОТВЕТИЛ = "E_SKLAD_UNREACHABLE"
СКЛАД_НЕ_НАСТРОЕН = "E_SKLAD_NOT_CONFIGURED"

# Спрашиваем напрямую, мимо посредника: с прокси в окружении ответ приходит от
# него, и доказывает он про него. Урок куплен ВН-51.
_БЕЗ_ПОСРЕДНИКА = urllib.request.build_opener(urllib.request.ProxyHandler({}))

