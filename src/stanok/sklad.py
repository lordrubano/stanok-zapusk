def отпечаток(байты: bytes) -> str:
    """Отпечаток содержимого — тот же, каким метит содержимое сам git.

    Взят чужой, а не свой: по нему прямо сравнивается лежащее в складе с
    лежащим на диске, без лишнего чтения и без своего учёта, который разошёлся
    бы с действительностью на первой же правке мимо станка.
    """
    голова = f"blob {len(байты)}\0".encode()
    return hashlib.sha1(голова + байты).hexdigest()  # noqa: S324 — так метит git


# ------------------------------------------------------------------ склады


class Склад:
    """Куда кладётся папка оператора. Устройство склада станку безразлично."""

    def метка(self, байты: bytes) -> str:
        """Отпечаток так, как метит его **этот** склад.

        Спрашивается у склада, а не считается одним способом на всех: метку в
        описи считает сам склад по тому, что у него лежит, и сравнивать с ней
        можно только тем же счётом. Разные склады метят по-разному — GitHub
        метит по-git, база считает своё, — и подставить сюда чужой счёт значило
        бы каждый раз видеть расхождение там, где его нет.
        """
        return отпечаток(байты)

    def опись(self) -> dict[str, str]:
        """Что лежит: имя файла → отпечаток."""
        raise NotImplementedError

    def прочитать(self, имя: str) -> bytes:
        raise NotImplementedError

    def записать(self, имя: str, байты: bytes) -> None:
        raise NotImplementedError

    def описание(self) -> str:
        raise NotImplementedError


class СкладПапкой(Склад):
    """Склад обычной папкой. Годен там, где машина папку переживает.

    Не подделка ради проверок: этим же складом станок работает на своей
    машине, где чужое хранилище незачем. Правила укладки у обоих складов
    одни — разные только руки.
    """

    def __init__(self, где) -> None:
        self.где = Path(где)
        self.где.mkdir(parents=True, exist_ok=True)

    def опись(self) -> dict[str, str]:
        return {п.name: отпечаток(п.read_bytes())
                for п in sorted(self.где.iterdir()) if п.is_file()}

    def прочитать(self, имя: str) -> bytes:
        return (self.где / имя).read_bytes()

    def записать(self, имя: str, байты: bytes) -> None:
        (self.где / имя).write_bytes(байты)

    def описание(self) -> str:
        return f"папка {self.где}"


class СкладGitHub(Склад):
    """Склад закрытым хранилищем GitHub. Переживает машину целиком."""

    ОСНОВАНИЕ = "https://api.github.com"

    def __init__(self, хранилище: str, путь: str, ключ: str,
                 ветка: str = "main") -> None:
        self.хранилище = хранилище.strip("/")
        self.путь = путь.strip("/")
        self.ключ = ключ
        self.ветка = ветка
        self._шапки_известного: dict[str, str] = {}

    # -------------------------------------------------------- разговор

    def _запрос(self, способ: str, адрес: str, тело=None) -> object:
        запрос = urllib.request.Request(адрес, method=способ)
        запрос.add_header("Authorization", f"Bearer {self.ключ}")
        запрос.add_header("Accept", "application/vnd.github+json")
        запрос.add_header("X-GitHub-Api-Version", "2022-11-28")
        запрос.add_header("User-Agent", "stanok")
        if тело is not None:
            запрос.add_header("Content-Type", "application/json")
            запрос.data = json.dumps(тело, ensure_ascii=False).encode("utf-8")
        try:
            with _БЕЗ_ПОСРЕДНИКА.open(запрос, timeout=30) as ответ:
                прочитано = ответ.read()
        except urllib.error.HTTPError as беда:
            if беда.code == 404:
                return None
            сказано = беда.read().decode("utf-8", "replace")[:300]
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: склад ответил {беда.code} на "
                f"{способ} {адрес}: {сказано}") from беда
        except OSError as беда:
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: до склада не достучаться: {беда}"
            ) from беда
        return json.loads(прочитано) if прочитано else None

    def _адрес(self, имя: str = "") -> str:
        путь = f"{self.путь}/{имя}" if имя else self.путь
        return (f"{self.ОСНОВАНИЕ}/repos/{self.хранилище}/contents/{путь}"
                f"?ref={self.ветка}")

    # -------------------------------------------------------- склад

    def опись(self) -> dict[str, str]:
        лежит = self._запрос("GET", self._адрес())
        if not лежит:
            return {}
        свои = {}
        for это in лежит:
            if это.get("type") == "file":
                свои[это["name"]] = это["sha"]
                self._шапки_известного[это["name"]] = это["sha"]
        return свои

    def прочитать(self, имя: str) -> bytes:
        # Содержимое берётся сырым: закодированное в JSON не проходит выше
        # мегабайта, а журнал решений перерастает мегабайт быстро.
        запрос = urllib.request.Request(self._адрес(имя))
        запрос.add_header("Authorization", f"Bearer {self.ключ}")
        запрос.add_header("Accept", "application/vnd.github.raw")
        запрос.add_header("X-GitHub-Api-Version", "2022-11-28")
        запрос.add_header("User-Agent", "stanok")
        try:
            with _БЕЗ_ПОСРЕДНИКА.open(запрос, timeout=60) as ответ:
                return ответ.read()
        except urllib.error.HTTPError as беда:
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: файл {имя} не читается: {беда.code}"
            ) from беда

    def записать(self, имя: str, байты: bytes) -> None:
        было = self._шапки_известного.get(имя)
        if было is None:
            лежит = self._запрос("GET", self._адрес(имя))
            было = лежит.get("sha") if isinstance(лежит, dict) else None
        тело = {
            "message": f"станок: {self.путь}/{имя}",
            "content": base64.b64encode(байты).decode("ascii"),
            "branch": self.ветка,
        }
        if было:
            тело["sha"] = было
        адрес = (f"{self.ОСНОВАНИЕ}/repos/{self.хранилище}/contents/"
                 f"{self.путь}/{имя}")
        ответ = self._запрос("PUT", адрес, тело)
        if isinstance(ответ, dict) and isinstance(ответ.get("content"), dict):
            self._шапки_известного[имя] = ответ["content"]["sha"]

    def описание(self) -> str:
        return f"хранилище {self.хранилище}, папка {self.путь}, ветка {self.ветка}"


class СкладБазой(Склад):
    """Склад базой площадки. Заведён ради одного: **владельцу нечего вписывать**.

    У склада GitHub есть свойство, которого у базы нет, — он бессрочный и хранит
    историю. И есть цена, которой у базы нет: **ключ**. Ключ узкий, но выдаёт
    его руками человек, и до первого станка ему приходится пройти страницу
    выдачи токенов. Площадка же свою базу заводит сама и строку подключения
    подставляет сама: в чертеже вместо поля для человека стоит ссылка на базу,
    и полей, которые заполняет владелец, не остаётся **ни одного**.

    Чем за это плачено, сказано прямо: бесплатная база площадки живёт 30 дней
    со дня заведения (плюс две недели отсрочки на переход на платную) — и это
    много больше засыпания, ради которого склад и заведён, но не «навсегда».
    Путь к бессрочному складу не закрыт и остаётся одним полем: вписан ключ —
    станок берёт GitHub, не вписан — базу.

    Метку описи считает **сама база** по тому, что у неё лежит (`sha256` в SQL,
    а не в станке). Это не украшение: перечитывание после укладки должно
    ловить склад, который сказал «положил» и не положил, — а оно ловит его
    только тогда, когда отпечаток приходит с той стороны.
    """

    ТАБЛИЦА = "stanok_sklad"

    def __init__(self, строка: str, полка: str) -> None:
        self.строка = строка
        self.полка = полка.strip("/")
        self._связь = None

    # -------------------------------------------------------- разговор

    def _соединение(self):
        if self._связь is not None and getattr(self._связь, "closed", 1) == 0:
            return self._связь
        try:
            import psycopg2
        except ImportError as беда:  # pragma: no cover — ставится сборкой
            raise RuntimeError(
                f"{СКЛАД_НЕ_НАСТРОЕН}: склад базой назван, а psycopg2 не "
                f"поставлен: {беда}") from беда
        try:
            self._связь = psycopg2.connect(self.строка, connect_timeout=15)
            self._связь.autocommit = True
            with self._связь.cursor() as курсор:
                курсор.execute(
                    f"CREATE TABLE IF NOT EXISTS {self.ТАБЛИЦА} ("
                    " polka text NOT NULL,"
                    " imya text NOT NULL,"
                    " bayty bytea NOT NULL,"
                    " PRIMARY KEY (polka, imya))")
        except Exception as беда:  # psycopg2.Error и всё, что под ним
            self._связь = None
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: до склада не достучаться: {беда}"
            ) from беда
        return self._связь

    def _спросить(self, запрос: str, доводы: tuple, ответ: bool = True):
        связь = self._соединение()
        try:
            with связь.cursor() as курсор:
                курсор.execute(запрос, доводы)
                return курсор.fetchall() if ответ else None
        except Exception as беда:
            self._связь = None
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: склад ответил бедой на запрос: {беда}"
            ) from беда

    # -------------------------------------------------------- склад

    def метка(self, байты: bytes) -> str:
        return hashlib.sha256(байты).hexdigest()

    def опись(self) -> dict[str, str]:
        строки = self._спросить(
            f"SELECT imya, encode(sha256(bayty), 'hex') FROM {self.ТАБЛИЦА} "
            "WHERE polka = %s", (self.полка,))
        return {имя: метка for имя, метка in строки}

    def прочитать(self, имя: str) -> bytes:
        строки = self._спросить(
            f"SELECT bayty FROM {self.ТАБЛИЦА} WHERE polka = %s AND imya = %s",
            (self.полка, имя))
        if not строки:
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: файла {имя} на полке {self.полка} нет")
        return bytes(строки[0][0])

    def записать(self, имя: str, байты: bytes) -> None:
        self._спросить(
            f"INSERT INTO {self.ТАБЛИЦА} (polka, imya, bayty) "
            "VALUES (%s, %s, %s) "
            "ON CONFLICT (polka, imya) DO UPDATE SET bayty = EXCLUDED.bayty",
            (self.полка, имя, _двоичное(байты)), ответ=False)

    def описание(self) -> str:
        # Строка подключения несёт пароль, а описание печатается в журнал
        # площадки. Печатать её целиком значило бы выложить пароль базы в
        # общий журнал — поэтому наружу идёт только машина и имя базы.
        return f"база {без_пароля(self.строка)}, полка {self.полка}"


def _двоичное(байты: bytes):
    """Байты так, как их принимает psycopg2. Без этого bytea приходит текстом."""
    import psycopg2

    return psycopg2.Binary(байты)


def без_пароля(строка: str) -> str:
    """Строка подключения без пароля — для журнала и экрана.

    Отдельной функцией и с проверкой: пароль, утёкший в журнал площадки, — не
    та беда, которую замечают вовремя.
    """
    без = re.sub(r"://([^:/@]+):[^@]*@", r"://\1@", строка)
    return без.split("?", 1)[0]


