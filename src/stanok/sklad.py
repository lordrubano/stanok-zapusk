# -*- coding: utf-8 -*-
"""Дальний склад: работа оператора переживает смерть машины, на которой шла.

Требование владельца от 07.08.2026: станки живут на арендованной площадке
(Render), бесплатный тариф. У бесплатного тарифа **файловая система не
переживает перезапуск**: служба засыпает после четверти часа тишины, просыпается
от первого обращения — и просыпается с чистым диском, каким он был при сборке.
Постоянного диска на этом тарифе не бывает вовсе.

Значит, рабочий каталог оператора — не хранилище, а черновик. Хранилище должно
быть **вне машины**, и переживать её целиком.

## Что выбрано и почему

Складов два, и выбор между ними — не вкус, а цена запуска для человека.

**База площадки** (`СкладБазой`) — то, чем станок живёт по умолчанию. Площадка
заводит её сама по чертежу и сама подставляет строку подключения: владельцу
**нечего вписывать вообще**, и запуск четырёх станков стоит ему двух движений.
Плата за это названа прямо: бесплатная база живёт 30 дней со дня заведения
(плюс две недели отсрочки). Это несравнимо дольше засыпания машины, ради
которого склад заведён, но это не «навсегда».

**Закрытое хранилище GitHub** (`СкладGitHub`) — то, на что станок переходит,
как только у него есть ключ. Оно бессрочно и **хранит историю**: видно не
только нынешнее состояние, но и каждое изменение со временем. Цена — ключ,
который человек выдаёт руками; ключ узкий, на одно хранилище и только на
содержимое.

Порядок жёсткий: есть ключ — GitHub, нет ключа — база. Так первый запуск не
упирается в страницу выдачи токенов, а бессрочность добирается одним полем и
без правки кода.

Что рассматривалось и отвергнуто:

* **постоянный диск Render** — не бывает на бесплатном тарифе;
* **быстрая память (Redis)** на бесплатном тарифе не переживает перезапуск —
  то же, от чего уходим.

## Чего склад не делает

Он не защищает и не разграничивает: у кого ключ, тот пишет всё. Он не годится
для настоящих документов клиентов, пока периметр не закрыт, — там чужое
хранилище, и это надо решать отдельно, а не молча.

Он не разрешает спор двух писателей: две машины, пишущие **одну** папку,
затрут друг друга. Здесь этого не бывает по устройству — у каждого оператора
своя папка, — но правило надо знать.
"""

