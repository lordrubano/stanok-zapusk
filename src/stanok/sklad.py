def восстановить(склад: Склад, каталог) -> list[str]:
    """Кладёт содержимое склада в папку. Возвращает имена принесённых файлов.

    Своё на диске не щадится: склад — источник правды, а папка после
    пробуждения машины и есть то, что надо заменить.
    """
    куда = Path(каталог)
    куда.mkdir(parents=True, exist_ok=True)
    принесено = []
    for имя, метка in склад.опись().items():
        свой = куда / имя
        if свой.is_file() and склад.метка(свой.read_bytes()) == метка:
            continue
        свой.write_bytes(склад.прочитать(имя))
        принесено.append(имя)
    return sorted(принесено)


def дождаться(склад: Склад, каталог, попыток: int = 5, пауза: float = 3.0,
              сказать=None) -> list[str]:
    """То же восстановление, но склад ждут, а не сдаются от первого отказа.

    Площадка заводит базу и службы разом, и первая служба может постучаться в
    базу раньше, чем та ответила. Без ожидания это выглядит у владельца как
    красный отказ сборки — при том, что через полминуты всё живо.

    Ждут **только доступности**: если склад отвечает, но отдаёт не то, беда
    идёт наверх сразу. Молчаливо подниматься без склада нельзя ни в одном
    случае — работа тогда пропадёт при первом же засыпании, и никто не узнает.
    """
    последняя = None
    for заход in range(1, попыток + 1):
        try:
            return восстановить(склад, каталог)
        except RuntimeError as беда:
            if СКЛАД_НЕ_ОТВЕТИЛ not in str(беда):
                raise
            последняя = беда
            if сказать is not None:
                сказать(f"склад не ответил (заход {заход} из {попыток}): "
                        f"{беда}")
            if заход < попыток:
                time.sleep(пауза)
    raise RuntimeError(
        f"{СКЛАД_НЕ_ОТВЕТИЛ}: склад так и не ответил. Заходов: {попыток}. "
        f"Последняя беда: {последняя}")


def сохранить(склад: Склад, каталог) -> list[str]:
    """Кладёт папку в склад. Возвращает имена уложенных файлов.

    Кладётся только изменившееся: отпечатки сравниваются с теми, что назвал
    склад. Несравнимого здесь нет — отпечаток один и тот же с обеих сторон.
    """
    откуда = Path(каталог)
    if not откуда.is_dir():
        return []
    лежит = склад.опись()
    уложено, ждём = [], {}
    for свой in sorted(откуда.iterdir()):
        if not свой.is_file():
            continue
        байты = свой.read_bytes()
        свой_отпечаток = склад.метка(байты)
        if лежит.get(свой.name) == свой_отпечаток:
            continue
        склад.записать(свой.name, байты)
        уложено.append(свой.name)
        ждём[свой.name] = свой_отпечаток

    if уложено:
        # Уложенное перечитывается у склада, а не считается уложенным по факту
        # ответа. Двойник обратного чтения книги: «я записал» и «там лежит» —
        # разные утверждения, и второе дороже. Молчаливое расхождение здесь
        # означало бы потерянную работу оператора, о которой никто не узнал.
        теперь = склад.опись()
        разошлось = [имя for имя, метка in ждём.items()
                     if теперь.get(имя) != метка]
        if разошлось:
            raise RuntimeError(
                f"{СКЛАД_НЕ_ОТВЕТИЛ}: уложено, но при перечитывании склада не "
                f"нашлось: {', '.join(разошлось)}. Работа на месте, в складе "
                "её нет — повторите действие.")
    return уложено


# ------------------------------------------------------------------ окружение


ХРАНИЛИЩЕ = "STANOK_SKLAD_REPO"
КЛЮЧ = "STANOK_SKLAD_KEY"
ВЕТКА = "STANOK_SKLAD_BRANCH"
ПАПКА = "STANOK_SKLAD_PATH"
СВОЯ_ПАПКА = "STANOK_SKLAD_DIR"
БАЗА = "STANOK_SKLAD_DB"


def из_окружения(окружение=None) -> Склад | None:
    """Склад по переменным окружения. Не назван — ``None``, и это не беда.

    На своей машине склад незачем: папка переживает закрытие окна. Молчаливое
    отсутствие склада там, где он нужен, — беда; но решать это здесь нельзя,
    потому что «нужен» знает пусковой файл, а не склад.

    Папочный склад назван первым нарочно: им проверяется весь путь целиком, не
    выходя в сеть, и им же можно работать на своей машине, где чужое хранилище
    незачем.

    GitHub стоит **выше базы** нарочно: база площадки заводится сама и потому
    работает без единого движения человека, но живёт 30 дней, а хранилище
    бессрочно. Вписал владелец ключ — станок берёт бессрочное, и переучивать
    его для этого не надо.
    """
    своё = os.environ if окружение is None else окружение
    своя = (своё.get(СВОЯ_ПАПКА) or "").strip()
    if своя:
        return СкладПапкой(своя)

    путь = (своё.get(ПАПКА) or "").strip()
    хранилище = (своё.get(ХРАНИЛИЩЕ) or "").strip()
    ключ = (своё.get(КЛЮЧ) or "").strip()
    if хранилище and ключ and путь:
        return СкладGitHub(хранилище, путь, ключ,
                           ветка=(своё.get(ВЕТКА) or "main").strip())

    строка = (своё.get(БАЗА) or "").strip()
    if строка and путь:
        return СкладБазой(строка, путь)
    return None


