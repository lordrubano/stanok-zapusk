# -*- coding: utf-8 -*-
"""Проверки порядка, повторов и пропусков последовательности.

Шаг 40 плана. Нормативная основа — чертёж v3.0, раздел 10 и раздел 9 (уровень 5:
позиции, дубликаты, пропуски последовательности и продолжения таблиц).

**Две одинаковые записи — не всегда дубликат.** Один и тот же платёж дважды в
один день на одну сумму бывает настоящим, и удалить его значит потерять деньги
клиента. Поэтому здесь ничего не удаляется и не склеивается — как и в шаге 39,
проверка называет, а не чинит.

Различать надо два разных явления, и различаются они **по адресу источника**:

* **повтор в источнике** — две записи с одинаковым содержимым, но с **разными**
  адресами. В источнике их две, и обе настоящие. Допустимы они или подозрительны
  — объявляет оснастка; сама проверка этого не решает;
* **повтор от разбора** — две записи с **одним и тем же** адресом. Такого в
  источнике нет: одна область не может быть двумя записями. Это задвоение,
  созданное станком, и оно всегда нарушение.

Адреса даёт шаг 33. Записи **без** адреса развести нельзя, и это прямо
объявляется неизвестным: молчаливое «повторов не найдено» на записях без адресов
означало бы, что искать было нечем.

**Пропуск в нумерации — не потерянная запись, но и не пустяк.** Он бывает и
особенностью банка (номера выдаются с запасом, часть отменена), и следом изъятой
строки. Различить их по самому пропуску нельзя — различие **объявляет оснастка**.
Не объявила — неизвестно, а не «всё в порядке».

**Чувствительность к порядку — свойство семейства.** У одной выписки строки
идут по дате, у другой — как пришли в банк. Общего правила нет, и выдумывать его
здесь значило бы объявлять нарушением обычную форму чужого банка.
"""

from __future__ import annotations

import json
from datetime import date
from decimal import Decimal

from .validator import (
    ИСПРАВИМОЕ,
    КРИТИЧЕСКОЕ,
    НАРУШЕНО,
    НЕИЗВЕСТНО,
    ПРОШЛО,
    RuleResult,
)


SEQUENCE_VERSION = "rules-order/1"

KNOWN_LIMITATIONS = (
    "Повтор в источнике и повтор от разбора различаются по адресу. Записи без "
    "адреса развести нельзя — правило честно даёт «неизвестно». Устойчивые "
    "адреса у банковских форматов появятся вместе с адресацией внутри "
    "сообщения (шаг 37 их объявляет, но проводки пока адреса не получают).",
    "Пропуски считаются по целым числам в объявленном поле. Номера с буквами "
    "или составные (серия и номер) потребуют правила разбора номера, и его "
    "объявляет оснастка; здесь такой номер даёт «неизвестно».",
    "Порядок проверяется по одному объявленному полю. Составной порядок "
    "(сперва по дате, затем по номеру) языком пока не выражается.",
)


def _результат(rule_id, статус, критичность, входы, вычисления, причина):
    return RuleResult(rule_id, SEQUENCE_VERSION, статус, критичность,
                      tuple(входы), вычисления, причина)


def _правила(оснастка):
    if оснастка is None:
        return {}
    return оснастка.содержимое.get("проверки") or {}


def _значение(запись, имя):
    поле = (запись.get("fields") or {}).get(имя) or {}
    return поле.get("value")


def _отпечаток(запись) -> str:
    """Содержимое записи без адресов: по нему узнаётся одинаковость."""
    поля = {}
    for имя, поле in sorted((запись.get("fields") or {}).items()):
        поля[имя] = [_как_текст(поле.get("raw")), _как_текст(поле.get("value"))]
    return json.dumps(поля, ensure_ascii=False, sort_keys=True)


def _как_текст(значение) -> str | None:
    if значение is None:
        return None
    if isinstance(значение, (Decimal, date)):
        return str(значение)
    return значение if isinstance(значение, str) else repr(значение)


def _адреса(запись) -> tuple[str, ...]:
    return tuple(sorted(запись.get("source_anchor_ids") or ()))


# ------------------------------------------------------------- повторы


def проверить_повторы(записи, оснастка=None) -> tuple[RuleResult, ...]:
    """Ищет повторы, разделяя источник и разбор. Ничего не удаляет."""
    записи = list(записи)
    итоги: list[RuleResult] = []

    по_адресам: dict[tuple, list] = {}
    без_адресов = []
    for место, запись in enumerate(записи, start=1):
        адреса = _адреса(запись)
        if адреса:
            по_адресам.setdefault(адреса, []).append((место, запись))
        else:
            без_адресов.append((место, запись))

    # 1. Повтор от разбора: один адрес — две записи. Такого в источнике нет.
    задвоенные = {адреса: свои for адреса, свои in по_адресам.items()
                  if len(свои) > 1}
    for адреса, свои in sorted(задвоенные.items()):
        места = ", ".join(str(место) for место, _ in свои)
        итоги.append(_результат(
            "повтор/разбор", НАРУШЕНО, КРИТИЧЕСКОЕ, адреса,
            f"один адрес источника у записей №{места}",
            "одна область источника не может быть двумя записями: это "
            "задвоение, созданное разбором, а не повтор в документе"))
    if not задвоенные and по_адресам:
        итоги.append(_результат(
            "повтор/разбор", ПРОШЛО, КРИТИЧЕСКОЕ,
            (f"записей с адресами: {sum(len(с) for с in по_адресам.values())}",),
            "совпавших адресов нет", "разбор ничего не задвоил"))

    # 2. Записи без адреса развести нечем.
    if без_адресов:
        места = ", ".join(str(место) for место, _ in без_адресов)
        итоги.append(_результат(
            "повтор/разбор", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (f"записи №{места}",),
            f"без адреса источника: {len(без_адресов)}",
            "развести повтор источника и задвоение разбора нечем: молчаливое "
            "«повторов нет» означало бы, что искать было нечем"))

    # 3. Повтор в источнике: содержимое то же, адреса разные.
    по_содержимому: dict[str, list] = {}
    for место, запись in enumerate(записи, start=1):
        по_содержимому.setdefault(_отпечаток(запись), []).append((место, запись))

    повторы = []
    for отпечаток, свои in sorted(по_содержимому.items()):
        if len(свои) < 2:
            continue
        адреса = {_адреса(запись) for _, запись in свои}
        if len(адреса) > 1 or (len(адреса) == 1 and next(iter(адреса)) == ()):
            повторы.append(свои)

    объявлено = (_правила(оснастка).get("повторы") or {}).get("в_источнике")
    for свои in повторы:
        места = ", ".join(str(место) for место, _ in свои)
        если_допустимы = объявлено == "допустимы"
        если_нет = объявлено == "недопустимы"
        статус = ПРОШЛО if если_допустимы else (НАРУШЕНО if если_нет else НЕИЗВЕСТНО)
        причина = {
            ПРОШЛО: "оснастка объявила повторы в источнике допустимыми: один и "
                    "тот же платёж дважды в день бывает настоящим",
            НАРУШЕНО: "оснастка объявила, что у этого семейства повторов не "
                      "бывает",
            НЕИЗВЕСТНО: "одинаковые записи с разными адресами: в источнике их "
                        "две. Настоящий это платёж дважды или нет — объявляет "
                        "оснастка, а она промолчала",
        }[статус]
        итоги.append(_результат(
            "повтор/источник", статус, ИСПРАВИМОЕ, (f"записи №{места}",),
            f"одинаковых записей: {len(свои)}, адреса разные", причина))

    if not повторы and записи:
        итоги.append(_результат(
            "повтор/источник", ПРОШЛО, ИСПРАВИМОЕ, (f"записей: {len(записи)}",),
            "одинаковых записей нет", "повторов в источнике не обнаружено"))
    return tuple(итоги)


# -------------------------------------------------------------- порядок


def проверить_порядок(записи, оснастка=None) -> tuple[RuleResult, ...]:
    """Проверяет порядок, если семейство его объявило.

    Чувствительность к порядку — свойство семейства. Выдумывать общее правило
    здесь значило бы объявлять нарушением обычную форму чужого банка.
    """
    записи = list(записи)
    объявлено = _правила(оснастка).get("порядок")
    if объявлено is None:
        return (_результат(
            "порядок/объявлен", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (),
            "правило порядка оснасткой не объявлено",
            "чувствительность к порядку — свойство семейства: у одной выписки "
            "строки идут по дате, у другой как пришли в банк"),)
    if объявлено.get("не_задан"):
        return (_результат(
            "порядок/объявлен", ПРОШЛО, ИСПРАВИМОЕ, (),
            "оснастка объявила порядок незначимым",
            "порядок для этого семейства не проверяется по объявлению, а не по "
            "умолчанию"),)

    имя = объявлено.get("поле")
    направление = объявлено.get("направление", "возрастание")
    значения = []
    for место, запись in enumerate(записи, start=1):
        значение = _значение(запись, имя)
        if значение is None:
            return (_результат(
                "порядок/последовательность", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (имя,),
                f"в записи №{место} поле {имя!r} без значения",
                "сравнивать нечем: порядок по неистолкованному полю не "
                "проверяется"),)
        значения.append((место, значение))

    беды = []
    for (место, прежнее), (следом, текущее) in zip(значения, значения[1:]):
        try:
            не_в_порядке = (текущее < прежнее if направление == "возрастание"
                            else текущее > прежнее)
        except TypeError:
            return (_результат(
                "порядок/последовательность", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (имя,),
                "значения поля несравнимы между собой",
                "сравнивать нечем: разнородные значения"),)
        if не_в_порядке:
            беды.append(f"№{место}→№{следом}: {прежнее} → {текущее}")

    if беды:
        return (_результат(
            "порядок/последовательность", НАРУШЕНО, ИСПРАВИМОЕ, (имя,),
            "; ".join(беды),
            f"объявлен порядок по полю {имя!r} на {направление}, и он нарушен"),)
    return (_результат(
        "порядок/последовательность", ПРОШЛО, ИСПРАВИМОЕ, (имя,),
        f"записей {len(значения)}, порядок по {имя!r} соблюдён",
        "порядок соответствует объявленному"),)


# ------------------------------------------------- пропуски нумерации


def проверить_пропуски(записи, оснастка=None) -> tuple[RuleResult, ...]:
    """Ищет пропуски в объявленной нумерации.

    Пропуск — не потерянная запись, но и не пустяк: он бывает особенностью
    банка и следом изъятой строки. Различие объявляет оснастка.
    """
    записи = list(записи)
    объявлено = _правила(оснастка).get("последовательность")
    if объявлено is None:
        return (_результат(
            "пропуски/объявлены", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (),
            "правило нумерации оснасткой не объявлено",
            "пропуск бывает и особенностью банка, и следом изъятой строки; "
            "различить их по самому пропуску нельзя"),)

    имя = объявлено.get("поле")
    политика = объявлено.get("пропуски")

    # Семейство вправе объявить, что его номера последовательности не
    # образуют. Это не отговорка: на первом настоящем документе измерено, что
    # в колонке номера стоят номера **чужих** платёжных документов — 1656
    # различных на 3318 операций, часть повторяется, диапазон в миллионы.
    # Искать пропуски в таком наборе бессмысленно, и объявить это честнее,
    # чем вечно возвращать «неизвестно».
    if политика == "не_образуют_последовательности":
        основание = объявлено.get("основание")
        if not основание:
            return (_результат(
                "пропуски/последовательность", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (имя,),
                "объявлено, что номера не образуют последовательности, но без "
                "основания",
                "такое объявление снимает проверку целиком, и чем оно измерено "
                "обязано быть сказано"),)
        return (_результат(
            "пропуски/последовательность", ПРОШЛО, ИСПРАВИМОЕ, (имя,),
            f"проверка снята объявлением: {основание}",
            "у этого семейства номера последовательности не образуют, и "
            "пропусков в них не бывает по устройству. Это прошло **по "
            "объявлению с основанием**, а не по умолчанию"),)

    номера = []
    for место, запись in enumerate(записи, start=1):
        значение = _значение(запись, имя)
        if isinstance(значение, bool) or not isinstance(значение, int):
            return (_результат(
                "пропуски/последовательность", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (имя,),
                f"в записи №{место} поле {имя!r} не целое число: {значение!r}",
                "считать пропуски не по чему: правило разбора такого номера "
                "оснасткой не объявлено"),)
        номера.append(значение)

    if len(номера) < 2:
        return (_результат(
            "пропуски/последовательность", ПРОШЛО, ИСПРАВИМОЕ, (имя,),
            f"записей {len(номера)}: пропускам взяться неоткуда",
            "последовательность короче двух записей"),)

    упорядоченные = sorted(номера)
    пропущенные = [номер for номер in range(упорядоченные[0], упорядоченные[-1] + 1)
                   if номер not in set(номера)]
    if not пропущенные:
        return (_результат(
            "пропуски/последовательность", ПРОШЛО, ИСПРАВИМОЕ, (имя,),
            f"с {упорядоченные[0]} по {упорядоченные[-1]} без пропусков",
            "нумерация сплошная"),)

    перечень = ", ".join(str(номер) for номер in пропущенные[:20])
    если_много = "" if len(пропущенные) <= 20 else f" и ещё {len(пропущенные) - 20}"
    статус = {
        "допустимы": ПРОШЛО,
        "недопустимы": НАРУШЕНО,
    }.get(политика, НЕИЗВЕСТНО)
    причина = {
        ПРОШЛО: "оснастка объявила пропуски нумерации обычными для этого "
                "семейства: номера выдаются с запасом, часть отменяется",
        НАРУШЕНО: "оснастка объявила нумерацию сплошной: пропуск здесь — след "
                  "изъятой строки",
        НЕИЗВЕСТНО: "пропуск найден, но объявления о нём нет: особенность банка "
                    "это или след изъятой строки — по самому пропуску не видно",
    }[статус]
    return (_результат(
        "пропуски/последовательность", статус, ИСПРАВИМОЕ, (имя,),
        f"пропущено {len(пропущенные)}: {перечень}{если_много}", причина),)


# ---------------------------------------------------------------- свод


def проверить_набор(записи, оснастка=None) -> tuple[RuleResult, ...]:
    """Все правила уровня 5 разом."""
    записи = list(записи)
    return (проверить_повторы(записи, оснастка)
            + проверить_порядок(записи, оснастка)
            + проверить_пропуски(записи, оснастка))


def порядок_проверен(итоги) -> bool:
    """Условие ``order_and_duplicate_checks_passed`` формулы 10.1."""
    итоги = tuple(итоги)
    return bool(итоги) and all(итог.статус == ПРОШЛО for итог in итоги)


