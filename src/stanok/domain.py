def _порядок_дат(правило, запись, реквизиты, record_id):
    """Одна дата не позже (не раньше) другой. Обе — из самого документа."""
    если_позже = правило.get("не_позже") is not None
    если_раньше = правило.get("не_раньше") is not None
    if если_позже and если_раньше:
        # Проверить можно только одно из двух, а объявлены оба. Взять первое и
        # промолчать о втором значило бы отчитаться о правиле, половина
        # которого не исполнялась.
        return _неизвестно(
            правило, record_id, "объявлены сразу «не_позже» и «не_раньше»",
            "какое из двух отношений проверять — не сказано, а исполнить "
            "половину правила и отчитаться за целое нельзя")

    левая, откуда_левой, беда = _разрешить({"поле": правило.get("поле")},
                                           запись, реквизиты)
    if беда:
        return _неизвестно(правило, record_id, беда)
    отношение = "не_позже" if если_позже else "не_раньше"
    правая, откуда_правой, беда = _разрешить(правило.get(отношение),
                                             запись, реквизиты)
    if беда:
        return _неизвестно(правило, record_id, беда)

    if not isinstance(левая, date) or not isinstance(правая, date):
        return _неизвестно(
            правило, record_id,
            f"{откуда_левой} и {откуда_правой}: не обе величины — даты",
            "сравнивать порядок дат можно только у дат; истолкование не "
            "состоялось или поле не датное")

    try:
        сошлось = левая <= правая if отношение == "не_позже" else левая >= правая
    except TypeError:
        # Дата и дата со временем между собой не сравниваются. Молчаливое
        # приведение одного к другому выдумало бы часы, которых в источнике нет.
        return _неизвестно(
            правило, record_id,
            f"{откуда_левой} и {откуда_правой}: величины несравнимы между собой",
            "дата и дата со временем сравнению не подлежат: приведение одной к "
            "другой выдумало бы точность, которой в источнике нет")
    словами = "не позже" if отношение == "не_позже" else "не раньше"
    вычисления = f"{откуда_левой} {левая} {словами} {откуда_правой} {правая}"
    if сошлось:
        return _результат(
            "межполевое/порядок_дат", ПРОШЛО, _важность(правило),
            (str(правило.get("имя")), record_id), вычисления,
            "даты внутри документа согласованы между собой. О том, верны ли "
            "они, правило не говорит ничего")
    return _результат(
        "межполевое/порядок_дат", НАРУШЕНО, _важность(правило),
        (str(правило.get("имя")), record_id), вычисления,
        "документ противоречит сам себе: объявленный порядок дат нарушен")


def _валюта_совпадает(правило, запись, реквизиты, record_id):
    """Валюта денежного поля против валюты счёта.

    Валюта берётся из самого поля канонической записи, а не угадывается по
    сумме: значение без валюты — это неизвестность, а не «наверное, рубли».
    """
    имя = правило.get("поле")
    if not _есть_поле(запись, имя):
        return _неизвестно(правило, record_id, f"поля {имя!r} в записи нет")
    валюта_поля = _поле(запись, имя).get("currency")
    if not валюта_поля:
        return _неизвестно(
            правило, record_id, f"у поля {имя!r} нет объявленной валюты",
            "валюта значения неизвестна: подставить сюда валюту счёта значило "
            "бы объявить совпадение, которого никто не наблюдал")

    ожидаемая, откуда, беда = _разрешить(правило.get("совпадает_с"),
                                         запись, реквизиты)
    if беда:
        return _неизвестно(правило, record_id, беда)
    вычисления = f"поле {имя!r}: {валюта_поля}; {откуда}: {ожидаемая}"
    if валюта_поля == ожидаемая:
        return _результат(
            "межполевое/валюта_совпадает", ПРОШЛО, _важность(правило),
            (str(правило.get("имя")), record_id), вычисления,
            "валюта значения совпадает с объявленной документом")
    return _результат(
        "межполевое/валюта_совпадает", НАРУШЕНО, _важность(правило),
        (str(правило.get("имя")), record_id), вычисления,
        "валюта значения не та, что объявлена документом: одно из двух прочитано "
        "неверно, и сложение таких значений дало бы бессмысленный итог")


def _состав_при_значении(правило, запись, реквизиты, record_id):
    """Код операции требует своего состава полей."""
    имя = правило.get("поле")
    if not _есть_поле(запись, имя):
        return _неизвестно(
            правило, record_id, f"поля {имя!r} в записи нет",
            "неизвестно даже, наступило ли условие правила")
    значение = _значение(запись, имя)
    когда = tuple(правило.get("когда") or ())
    входы = (str(правило.get("имя")), record_id)

    if значение is None:
        # Поле есть, а истолкования нет. Объявить, что условие не наступило,
        # значило бы засчитать правило пройденным на основании того, что
        # значение прочесть не удалось.
        return _неизвестно(
            правило, record_id, f"поле {имя!r} без истолкованного значения",
            "наступило ли условие правила, неизвестно: значение поля не "
            "прочтено, и вхолостую пройденным правило считать нельзя")

    if значение not in когда:
        # Условие не наступило — правило выполнено вхолостую. Объявляется всё
        # равно: по перечню должно быть видно, что правило рассматривалось, а
        # не выпало из проверки незамеченным.
        return _результат(
            "межполевое/состав_при_значении", ПРОШЛО, _важность(правило), входы,
            f"поле {имя!r} = {значение!r}: условие правила не наступило",
            "правило к этой записи не относится")

    требуются = tuple(правило.get("требуются") or ())
    запрещены = tuple(правило.get("запрещены") or ())
    нет_нужных = [поле for поле in требуются if not _непусто(запись, поле)]
    есть_лишние = [поле for поле in запрещены if _непусто(запись, поле)]

    if not нет_нужных and not есть_лишние:
        return _результат(
            "межполевое/состав_при_значении", ПРОШЛО, _важность(правило), входы,
            f"при {имя!r} = {значение!r} состав полей соблюдён "
            f"(требуется {len(требуются)}, запрещено {len(запрещены)})",
            "состав полей отвечает объявленному для этого значения. Верен ли "
            "сам код операции, правило не проверяет")

    беды = []
    if нет_нужных:
        беды.append("нет обязательных при этом значении: " + ", ".join(нет_нужных))
    if есть_лишние:
        беды.append("заполнены несовместимые с ним: " + ", ".join(есть_лишние))
    return _результат(
        "межполевое/состав_при_значении", НАРУШЕНО, _важность(правило), входы,
        f"при {имя!r} = {значение!r} " + "; ".join(беды),
        "состав полей противоречит значению, объявленному в самой записи: одно "
        "из двух прочитано неверно, и какое именно — отсюда не видно")


def _допустимые_при_значении(правило, запись, реквизиты, record_id):
    """Межполевая зависимость: значение одного поля сужает допустимые в другом."""
    имя = правило.get("поле")
    имя_следствия = правило.get("поле_следствия")
    входы = (str(правило.get("имя")), record_id)
    if not _есть_поле(запись, имя):
        return _неизвестно(правило, record_id, f"поля {имя!r} в записи нет",
                           "неизвестно, наступило ли условие правила")
    значение = _значение(запись, имя)
    if значение is None:
        return _неизвестно(
            правило, record_id, f"поле {имя!r} без истолкованного значения",
            "наступило ли условие правила, неизвестно: значение поля не "
            "прочтено, и вхолостую пройденным правило считать нельзя")
    if значение not in tuple(правило.get("когда") or ()):
        return _результат(
            "межполевое/допустимые_при_значении", ПРОШЛО, _важность(правило),
            входы, f"поле {имя!r} = {значение!r}: условие не наступило",
            "правило к этой записи не относится")

    следствие, откуда, беда = _разрешить({"поле": имя_следствия}, запись, реквизиты)
    if беда:
        return _неизвестно(правило, record_id, беда)
    допустимые = tuple(правило.get("допустимые") or ())
    вычисления = (f"при {имя!r} = {значение!r} {откуда} = {следствие!r}; "
                  f"допустимо: {', '.join(str(з) for з in допустимые)}")
    if следствие in допустимые:
        return _результат(
            "межполевое/допустимые_при_значении", ПРОШЛО, _важность(правило),
            входы, вычисления, "поля согласованы между собой")
    return _результат(
        "межполевое/допустимые_при_значении", НАРУШЕНО, _важность(правило),
        входы, вычисления,
        "поля противоречат друг другу: такое сочетание значений оснасткой "
        "объявлено невозможным для этого семейства")


def _границы_значения(правило, запись, реквизиты, record_id):
    """Бизнес-инвариант на величину. Границы объявлены строками, не числами.

    Строками намеренно: число с дробной частью, записанное в JSON, приходит
    двоичной дробью и уже потеряло точность — ровно то, что типизатор шага 29
    отвергает на входе.
    """
    имя = правило.get("поле")
    входы = (str(правило.get("имя")), record_id)
    значение, откуда, беда = _разрешить({"поле": имя}, запись, реквизиты)
    if беда:
        return _неизвестно(правило, record_id, беда)
    if isinstance(значение, bool) or not isinstance(значение, (Decimal, int)):
        return _неизвестно(
            правило, record_id, f"{откуда}: {значение!r} — не число",
            "сравнивать величину можно только у числа")
    if isinstance(значение, Decimal) and not значение.is_finite():
        return _результат(
            "межполевое/границы_значения", НАРУШЕНО, _важность(правило), входы,
            f"{откуда}: {значение}", "нечисло сравнивается со всем подряд ложно "
                                     "и прошло бы любую границу молча")

    беды = []
    части = []
    for ключ, словами, сошлось in (
            ("не_меньше", "не меньше", lambda з, г: з >= г),
            ("не_больше", "не больше", lambda з, г: з <= г)):
        если_объявлено = правило.get(ключ)
        if если_объявлено is None:
            continue
        граница = _как_число(если_объявлено)
        if граница is None:
            return _неизвестно(
                правило, record_id,
                f"граница «{ключ}» объявлена как {если_объявлено!r}",
                "граница должна быть записана десятичной строкой: число с "
                "дробной частью в JSON приходит двоичной дробью и уже неточно")
        части.append(f"{словами} {граница}")
        if not сошлось(Decimal(значение), граница):
            беды.append(f"{словами} {граница}")

    if not части:
        return _неизвестно(правило, record_id, "границы не объявлены",
                           "правило без границ ничего не проверяет")
    вычисления = f"{откуда} = {значение}; объявлено: " + ", ".join(части)
    if not беды:
        return _результат(
            "межполевое/границы_значения", ПРОШЛО, _важность(правило), входы,
            вычисления, "величина внутри объявленных семейством границ")
    return _результат(
        "межполевое/границы_значения", НАРУШЕНО, _важность(правило), входы,
        вычисления + "; нарушено: " + ", ".join(беды),
        "величина вне границ, объявленных семейством как возможные")


def _как_число(объявленное):
    if isinstance(объявленное, bool):
        return None
    if isinstance(объявленное, int):
        return Decimal(объявленное)
    if isinstance(объявленное, str):
        try:
            число = Decimal(объявленное)
        except InvalidOperation:
            return None
        return число if число.is_finite() else None
    return None


_ИСПОЛНИТЕЛИ = {
    "порядок_дат": _порядок_дат,
    "валюта_совпадает": _валюта_совпадает,
    "состав_при_значении": _состав_при_значении,
    "допустимые_при_значении": _допустимые_при_значении,
    "границы_значения": _границы_значения,
}


