def _результат(rule_id, статус, критичность, входы, вычисления, причина):
    return RuleResult(rule_id, DOMAIN_VERSION, статус, критичность,
                      tuple(входы), вычисления, причина)


def _правила(оснастка) -> tuple:
    if оснастка is None:
        return ()
    проверки = оснастка.содержимое.get("проверки") or {}
    объявленные = проверки.get("межполевые")
    return tuple(объявленные) if isinstance(объявленные, list) else ()


def _поле(запись, имя) -> dict:
    return (запись.get("fields") or {}).get(имя) or {}


def _значение(запись, имя):
    return _поле(запись, имя).get("value")


def _есть_поле(запись, имя) -> bool:
    return имя in (запись.get("fields") or {})


def _непусто(запись, имя) -> bool:
    """Поле есть, и в нём есть истолкованное значение.

    Пустая строка не считается заполнением: различие отсутствия, пустоты и
    неистолкованного установлено шагом 39 и здесь не размывается.
    """
    if not _есть_поле(запись, имя):
        return False
    значение = _значение(запись, имя)
    if значение is None:
        return False
    return not (isinstance(значение, str) and значение.strip() == "")


