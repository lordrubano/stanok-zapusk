def _разрешить(ссылка, запись, реквизиты):
    """Достаёт величину, на которую ссылается правило.

    Ссылка указывает либо на поле записи, либо на реквизит документа. Третьего
    вида ссылки нет: величина, взятая откуда-то ещё, была бы величиной, которую
    документ о себе не сообщал.

    Возвращает ``(значение, откуда, беда)``. Беда — человеческая причина, по
    которой сравнивать нечем.
    """
    if not isinstance(ссылка, dict):
        return None, "?", "ссылка правила не объявлена"
    if "поле" in ссылка:
        имя = ссылка["поле"]
        if not _есть_поле(запись, имя):
            return None, f"поле {имя!r}", f"поля {имя!r} в записи нет"
        значение = _значение(запись, имя)
        if значение is None:
            return None, f"поле {имя!r}", f"поле {имя!r} без истолкованного значения"
        return значение, f"поле {имя!r}", None
    if "реквизит" in ссылка:
        имя = ссылка["реквизит"]
        значение = (реквизиты or {}).get(имя)
        if значение is None:
            return None, f"реквизит {имя!r}", f"реквизит документа {имя!r} не приложен"
        return значение, f"реквизит {имя!r}", None
    return None, "?", "в ссылке не сказано ни «поле», ни «реквизит»"


def _неизвестно(правило, record_id, беда, причина=None):
    return _результат(
        f"межполевое/{правило.get('вид', 'без_вида')}", НЕИЗВЕСТНО,
        _важность(правило), (str(правило.get("имя")), record_id), беда,
        причина or "сравнить нечем: несравнённое не считается согласованным")


def _важность(правило) -> str:
    return КРИТИЧЕСКОЕ if правило.get("критическое") else ИСПРАВИМОЕ


