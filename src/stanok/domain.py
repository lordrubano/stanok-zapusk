def проверить_запись(запись, реквизиты=None, оснастка=None) -> tuple[RuleResult, ...]:
    """Все объявленные межполевые правила по одной записи.

    ``реквизиты`` — величины самого документа (дата выписки, валюта счёта и
    прочее), извлечённые адаптером. Правило, ссылающееся на неприложенный
    реквизит, даёт «неизвестно».
    """
    правила = _правила(оснастка)
    record_id = запись.get("record_id") or "запись без имени"
    if not правила:
        return (_результат(
            "правило/объявлены", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (record_id,),
            "межполевые правила оснасткой не объявлены",
            "какие поля с какими обязаны быть согласованы — свойство семейства; "
            "правило конкретного банка, вписанное в ядро, и было бы "
            "пересборкой ядра ради клиента"),)

    итоги = []
    for правило in правила:
        if not isinstance(правило, dict):
            итоги.append(_результат(
                "правило/негодное", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (record_id,),
                f"описание правила не является объектом: {правило!r}",
                "исполнить нечего"))
            continue
        исполнитель = _ИСПОЛНИТЕЛИ.get(правило.get("вид"))
        if исполнитель is None:
            итоги.append(_результат(
                "правило/неизвестный_вид", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ,
                (str(правило.get("имя")), record_id),
                f"вид {правило.get('вид')!r} этому ядру неизвестен",
                "молча пропущенное правило засчиталось бы пройденным и ничем "
                "не отличалось бы от выполненного"))
            continue
        итоги.append(исполнитель(правило, запись, реквизиты, record_id))
    return tuple(итоги)


def проверить_набор(записи, реквизиты=None, оснастка=None) -> tuple[RuleResult, ...]:
    итоги: list[RuleResult] = []
    for запись in записи:
        итоги.extend(проверить_запись(запись, реквизиты, оснастка))
    return tuple(итоги)


def доменные_правила_пройдены(итоги) -> bool:
    """Условие ``domain_rules_passed`` из формулы 10.1.

    Истинно только когда все правила прошли; одно ``неизвестно`` делает его
    ложным. Само по себе оно допуска не даёт и правильности прочтения не
    доказывает: см. :data:`ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СОГЛАСОВАННОСТЬ`.
    """
    итоги = tuple(итоги)
    return bool(итоги) and all(итог.статус == ПРОШЛО for итог in итоги)


def свод(итоги) -> dict:
    """Итог уровня вместе с границей того, что он доказывает."""
    итоги = tuple(итоги)
    return {
        "версия": DOMAIN_VERSION,
        "правил": len(итоги),
        "прошло": sum(1 for и in итоги if и.статус == ПРОШЛО),
        "нарушено": sum(1 for и in итоги if и.статус == НАРУШЕНО),
        "неизвестно": sum(1 for и in итоги if и.статус == НЕИЗВЕСТНО),
        "доменные_правила_пройдены": доменные_правила_пройдены(итоги),
        "не_доказывает": list(ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СОГЛАСОВАННОСТЬ),
        "результаты": [и.as_json() for и in итоги],
    }


