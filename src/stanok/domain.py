"""Доменные и межполевые правила. Объявляет оснастка, исполняет ядро.

Шаг 42 плана. Нормативная основа — чертёж v3.0, раздел 10 (политика допуска) и
раздел 9 (уровень 7: межполевые зависимости, коды операций, валюты и бизнес-
инварианты).

**Ни одного правила конкретного банка здесь нет и быть не может.** В этом файле
нет ни одного имени поля чужого семейства: имена приходят из пакета оснастки, и
те же самые правила работают на семействе, где поля названы иначе. Проверить это
можно не чтением, а переименованием: набор с полями под другими именами даёт тот
же результат до последнего слова. Довод тот же, что в розетке шага 25 и в языке
шага 37 — правило банка, вписанное в ядро, и есть пересборка ядра ради клиента.

Ядро исполняет **закрытый набор видов** правил, и это не ограничение, а замена
выражению: оснастка не пишет условие, а **называет** его и подставляет имена
своих полей. Пакет остаётся данными, а проверка — исполняемой. Вид, которого
ядро не знает, даёт «неизвестно», а не пропуск: молча пропущенное правило
засчиталось бы пройденным, ничем не отличаясь от выполненного.

**Межполевое правило судит согласованность полей между собой, а не соответствие
бумаге.** Дата операции не позже даты выписки, валюта суммы совпадает с валютой
счёта, код операции требует своего состава полей — всё это ловит **противоречия
внутри документа** и молчит о том, верно ли прочитан сам документ. Согласованные
между собой поля бывают все до одного прочитаны неверно, и ни одно правило этого
уровня такого не заметит. Перечень границы — в
:data:`ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СОГЛАСОВАННОСТЬ`, и он уходит вместе с результатом.

**Не объявлено — «неизвестно».** Как и на прежних уровнях: правил нет — правила
не проверены; поля, на которое правило ссылается, в записи нет — сравнить нечем.
Ни то ни другое не «в порядке».
"""

