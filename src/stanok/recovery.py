# -*- coding: utf-8 -*-
"""Восстановление после частичного сбоя: осмотр состояния и целая запись.

Шаг 64 плана. Нормативная основа — чертёж v3.0, раздел 19: «восстановление
обязано проверяться испытанием, а не наличием резервной копии».

Отсюда устройство шага: здесь не описание восстановления, а **средства, которые
можно испытать**, и испытание, которое их ломает по-настоящему — оборванный
журнал, недописанный итог, битая часть после нарезки, каталог без прав, конец
места на диске.

Два правила, на которых всё стоит.

**Половина не выдаётся за целое.** Итог пишется в сторонний файл и переносится
на своё имя одним движением; недописанное остаётся под временным именем и
итогом не считается. Читатель, увидевший файл под настоящим именем, знает: он
дописан. Не увидевший — знает, что итога нет. Третьего состояния — «файл есть,
но, кажется, неполный» — не существует, и это главное, что даёт шаг.

**Молчаливой починки не бывает.** Осмотр называет каждую беду своим кодом и
словами. Он ничего не чинит: чинить — значит решать за человека, что было
верным, а этого станок не знает. Единственное, что он делает сам, — убирает
свои же временные остатки, и то по прямой просьбе.
"""

from __future__ import annotations

import os
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from . import journal


RECOVERY_VERSION = "recovery/1"

ВРЕМЕННОЕ = ".недописано"

# Коды бед. Каждый — про одну беду, и каждый выговаривается словами.
ЖУРНАЛ_ОБОРВАН = "E_JOURNAL_BROKEN"
ЧАСТЬ_БИТА = "E_PART_BROKEN"
СТЫК_РАЗОРВАН = "E_PART_LINK_BROKEN"
ИТОГ_НЕДОПИСАН = "E_RESULT_INCOMPLETE"
ИТОГА_НЕТ = "E_RESULT_MISSING"
НЕТ_ПРАВ = "E_NO_WRITE_ACCESS"
НЕТ_МЕСТА = "E_NO_SPACE"

KNOWN_LIMITATIONS = (
    "Перенос на своё имя считается неделимым. На обычных файловых системах "
    "это верно; на сетевых дисках и в облачных папках — не всегда, и там "
    "обещание целой записи слабее.",
    "Осмотр не чинит. Он называет беду и оставляет решение человеку: чинить "
    "молча — значит решать за него, что было верным.",
    "Конец места на диске проверяется двумя способами: запасом перед записью и "
    "отказом операционной системы во время неё. Первый способ — оценка: между "
    "проверкой и записью место могут занять другие.",
    "Права на запись проверяются пробной записью, а не разбором прав доступа. "
    "Это вернее по существу — важно не то, что записано в правах, а то, "
    "получится ли записать, — но проба оставляет след и требует места.",
)


class ВосстановлениеНевозможно(OSError):
    """Состояние испорчено так, что продолжать нельзя. Сказано, чем именно."""


@dataclass(frozen=True, slots=True)
class Беда:
    """Одна найденная беда: код, место и слова для человека."""

    код: str
    где: str
    словами: str

    def as_json(self) -> dict:
        return {"версия": RECOVERY_VERSION, "код": self.код, "где": self.где,
                "словами": self.словами}


# ---------------------------------------------------- целая запись


def записать_целиком(путь, данные: bytes) -> Path:
    """Пишет файл так, что под своим именем он появляется только дописанным.

    Сперва сторонний файл, затем принудительный сброс на диск, затем перенос на
    своё имя одним движением. Убей станок в любой миг — под настоящим именем
    будет либо прежнее содержимое, либо новое целиком, но не половина.
    """
    место = Path(путь)
    место.parent.mkdir(parents=True, exist_ok=True)
    временный = место.with_name(место.name + ВРЕМЕННОЕ)
    try:
        with временный.open("wb") as файл:
            файл.write(данные)
            файл.flush()
            os.fsync(файл.fileno())
        временный.replace(место)
    except OSError as беда:
        # Временный остаток не убирается: по нему видно, что запись начиналась
        # и не кончилась. Прибрать его — дело осмотра, а не тихое действие в
        # обработчике ошибки.
        raise ВосстановлениеНевозможно(
            f"{_код_записи(беда)}: итог не записан целиком: {беда}") from беда
    return место


def _код_записи(беда: OSError) -> str:
    import errno

    if getattr(беда, "errno", None) == errno.ENOSPC:
        return НЕТ_МЕСТА
    if isinstance(беда, PermissionError):
        return НЕТ_ПРАВ
    return ИТОГ_НЕДОПИСАН


# ------------------------------------------------------ осмотр


def осмотреть_журнал(путь, схема=None) -> tuple[Беда, ...]:
    """Цела ли цепь журнала. Оборванный журнал называется, а не чинится."""
    место = Path(путь)
    if not место.exists():
        return ()
    try:
        journal.verify_journal(место, схема=схема or journal.нормализовать_событие)
    except journal.JournalError as беда:
        return (Беда(ЖУРНАЛ_ОБОРВАН, место.name,
                     f"журнал не проходит проверку цепи: {беда}. Записи после "
                     "разрыва свидетельством не являются"),)
    return ()


def осмотреть_части(путь, схема=None) -> tuple[Беда, ...]:
    """Целы ли части журнала и стыки между ними."""
    from .observability import проверить_части

    try:
        проверить_части(путь, схема=схема)
    except journal.JournalError as беда:
        код = СТЫК_РАЗОРВАН if "стык" in str(беда) else ЧАСТЬ_БИТА
        return (Беда(код, Path(путь).name,
                     f"нарезанный журнал не сходится: {беда}"),)
    return ()


def осмотреть_итог(путь) -> tuple[Беда, ...]:
    """Есть ли итог и не остался ли от него недописанный огрызок.

    Огрызок — не беда сама по себе, а **след прерванной записи**, и он обязан
    быть назван: молчание о нём означало бы, что запись прошла успешно.
    """
    место = Path(путь)
    временный = место.with_name(место.name + ВРЕМЕННОЕ)
    беды = []
    if временный.exists():
        беды.append(Беда(
            ИТОГ_НЕДОПИСАН, временный.name,
            "остался недописанный файл: запись прерывалась. Под настоящим "
            "именем итога нет либо лежит прежний — половина за целое не выдана"))
    if not место.exists():
        беды.append(Беда(ИТОГА_НЕТ, место.name,
                         "итога нет: работа не доведена до записи"))
    return tuple(беды)


def осмотреть_право_записи(каталог) -> tuple[Беда, ...]:
    """Можно ли вообще писать. Проверяется пробой, а не разбором прав."""
    место = Path(каталог)
    try:
        место.mkdir(parents=True, exist_ok=True)
        проба = место / f".проба-{os.getpid()}"
        проба.write_bytes(b"\x00")
        проба.unlink()
    except OSError as беда:
        return (Беда(НЕТ_ПРАВ, str(место),
                     f"писать в каталог нельзя: {беда}. Работа не начинается: "
                     "итог, который некуда положить, не итог"),)
    return ()


def осмотреть_место(каталог, нужно_байт: int) -> tuple[Беда, ...]:
    """Хватит ли места. Это оценка перед работой, а не обещание."""
    try:
        свободно = shutil.disk_usage(str(каталог)).free
    except OSError as беда:
        return (Беда(НЕТ_МЕСТА, str(каталог),
                     f"не удалось узнать свободное место: {беда}"),)
    if свободно < нужно_байт:
        return (Беда(НЕТ_МЕСТА, str(каталог),
                     f"свободно {свободно} байт, нужно не меньше {нужно_байт}: "
                     "работа не начинается, чтобы не оборваться на середине"),)
    return ()


def осмотреть(журнал_путь=None, итог_путь=None, каталог=None,
              нужно_байт: int = 0, схема=None) -> dict:
    """Полный осмотр состояния перед работой и после сбоя.

    Возвращает найденное, а не чинит. Пустой список бед — единственное, что
    считается «состояние цело»; всякая беда названа кодом и словами.
    """
    беды: list[Беда] = []
    if журнал_путь is not None:
        беды.extend(осмотреть_журнал(журнал_путь, схема))
        беды.extend(осмотреть_части(журнал_путь, схема))
    if итог_путь is not None:
        беды.extend(осмотреть_итог(итог_путь))
    if каталог is not None:
        беды.extend(осмотреть_право_записи(каталог))
        if нужно_байт:
            беды.extend(осмотреть_место(каталог, нужно_байт))
    return {
        "версия": RECOVERY_VERSION,
        "цело": not беды,
        "бед": len(беды),
        "коды": sorted({б.код for б in беды}),
        "беды": [б.as_json() for б in беды],
    }


def прибрать_недописанное(путь) -> tuple[str, ...]:
    """Убирает **свои же** временные остатки. Только по прямой просьбе.

    Возвращает имена убранного: молчаливая уборка не отличалась бы от
    сокрытия следов.
    """
    место = Path(путь)
    временный = место.with_name(место.name + ВРЕМЕННОЕ)
    убрано = []
    if временный.exists():
        временный.unlink()
        убрано.append(временный.name)
    return tuple(убрано)


def место_под_итог(данные_байт: int, запас: float = 2.0) -> int:
    """Сколько места просить: итог плюс запас на временный файл.

    Запас двойной не из осторожности, а по устройству целой записи: в миг
    переноса на диске лежат и старый итог, и новый.
    """
    return int(данные_байт * запас)


