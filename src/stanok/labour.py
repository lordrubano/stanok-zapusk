# -*- coding: utf-8 -*-
"""Измерение времени и причин ручного труда.

Шаг 61 плана, последний в Фазе 5. Нормативная основа — чертёж v3.0, раздел 12:
«измерение времени и причины ручного труда как отдельной метрики».

**Это единственное место, откуда возьмётся честная цифра об экономии.** Пока
здесь пусто, во всех отчётах стоит «не измерено», и это верно: экономия,
названная без замера, — обещание продавца, а не свойство станка.

Три правила, на которых стоит замер.

**Время меряется по родам сомнения раздельно.** Двоякая дата, неявные копейки,
непрочитанное поле — разный труд. Одна разрешается сверкой с платёжкой за
несколько секунд, другая требует поднять договор. Сложенные в одно среднее, они
дают число, по которому нельзя ни планировать, ни считать деньги: оно не
описывает ни одного настоящего случая.

**Время решения по связке принадлежит всей связке.** Оператор, разрешивший
двоякую дату для восьмисот восьмидесяти двух записей одним решением, потратил
время на **решение**, а не на каждую запись. Разделить это время на записи и
сказать «секунда на запись» значит выдумать работу, которой не было. Поэтому у
замера две величины, и они не смешиваются: время решения и число записей, к
которым решение отнесено.

**Время приходит снаружи.** Часы станка тут не судьи — по тем же доводам, что и
в шаге 57: время работы человека есть свидетельство, и брать его из машины,
которая сама себе ставит оценку, нельзя.

## Что можно измерить сегодня, а что нельзя

Операторов нет, и **ни одной секунды ручного труда не измерено**. Но замер
нужен не только для секунд: по построенному уже видно **сколько раз человеку
придётся принять решение** и по каким поводам. Это счёт, а не время, и он
считается без единого человека — :func:`нагрузка`.

Чего без живого человека не будет: секунд на решение каждого рода, доли времени
по родам, усталости к концу дня, роста ошибок на однообразных случаях — и,
значит, никакой доли экономии. :func:`экономия` это и говорит отказом, а не
нулём: нуль выглядел бы как измеренное.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime


LABOUR_VERSION = "manual-labour/1"

KNOWN_LIMITATIONS = (
    "Ни одной секунды ручного труда не измерено: операторов нет. Всё, что "
    "здесь есть, — способ мерить и счёт предстоящих решений.",
    "Время подаётся снаружи двумя мгновениями. Что человек в этот промежуток "
    "делал именно эту работу, станок не знает: отлучился он или думал, видно "
    "только ему самому.",
    "Причина ручного труда берётся из рода сомнения (шаг 55). Работа, начатая "
    "без сомнения — сверка наугад, проверка выборкой, — этим замером не "
    "описывается.",
    "Доли экономии нет и не может быть, пока не измерено время той же работы "
    "без станка. Сравнивать с догадкой хуже, чем не сравнивать.",
)


class ЗамерНегоден(ValueError):
    """Замер не может быть принят: сказано, чего не хватает."""


class НечегоСравнивать(ValueError):
    """Экономию не с чем сравнить: основание не измерено."""


def _мгновение(значение: str, чего: str) -> datetime:
    строка = str(значение or "").strip()
    if not строка:
        raise ЗамерНегоден(f"{чего} не названо: время приходит снаружи, и "
                           "часами станка оно не подменяется")
    try:
        return datetime.fromisoformat(строка.replace("Z", "+00:00"))
    except ValueError as беда:
        raise ЗамерНегоден(
            f"{чего} записано не по правилу: ожидается вид «2026-08-05T03:20:00Z»"
        ) from беда


@dataclass(frozen=True, slots=True)
class Замер:
    """Сколько времени заняло одно решение человека и по какому поводу.

    ``записей`` — к скольким записям решение отнесено. Для решения по связке это
    вся связка; время при этом остаётся временем **решения**, а не суммой
    времени по записям.
    """

    род: str
    действие: str
    оператор: str
    начато: str
    кончено: str
    записей: int = 1
    связка: str | None = None
    роль: str | None = None

    def __post_init__(self) -> None:
        if not str(self.род or "").strip():
            raise ЗамерНегоден(
                "род сомнения не назван: без причины замер даёт время без "
                "ответа на вопрос «на что оно ушло»")
        if not str(self.действие or "").strip():
            raise ЗамерНегоден("действие не названо")
        if not str(self.оператор or "").strip():
            raise ЗамерНегоден("оператор не назван")
        начало = _мгновение(self.начато, "начало работы")
        конец = _мгновение(self.кончено, "конец работы")
        if конец < начало:
            raise ЗамерНегоден(
                "работа кончилась раньше, чем началась: такой замер "
                "свидетельством не является")
        if isinstance(self.записей, bool) or not isinstance(self.записей, int) \
                or self.записей < 1:
            raise ЗамерНегоден("записей в замере должно быть не меньше одной")
        if self.связка and self.записей == 1:
            raise ЗамерНегоден(
                "решение по связке касается не одной записи: либо назовите "
                "число записей связки, либо не называйте связку")

    @property
    def секунд(self) -> float:
        """Сколько длилось решение. Не делится на записи и делиться не должно."""
        return (_мгновение(self.кончено, "конец работы")
                - _мгновение(self.начато, "начало работы")).total_seconds()

    @property
    def по_связке(self) -> bool:
        return bool(self.связка) or self.записей > 1

    def as_json(self) -> dict:
        return {
            "версия": LABOUR_VERSION,
            "род": self.род,
            "действие": self.действие,
            "оператор": self.оператор,
            "начато": self.начато,
            "кончено": self.кончено,
            "секунд": self.секунд,
            "записей": self.записей,
            "связка": self.связка,
            "роль": self.роль,
            "по_связке": self.по_связке,
        }


