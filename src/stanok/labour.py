def _среднее(числа) -> float | None:
    числа = list(числа)
    return sum(числа) / len(числа) if числа else None


def по_родам(замеры) -> dict:
    """Время и счёт по каждому роду сомнения. Родов не смешивает.

    Внутри рода **решения поодиночке и решения по связке считаются врозь**:
    у них разная природа, и общее среднее по ним снова слило бы разное в одно.
    """
    замеры = tuple(замеры)
    свод_родов: dict[str, dict] = {}
    for замер in замеры:
        свои = свод_родов.setdefault(замер.род, {
            "решений": 0, "записей": 0, "секунд": 0.0,
            "поодиночке": {"решений": 0, "секунд": 0.0, "записей": 0},
            "по_связке": {"решений": 0, "секунд": 0.0, "записей": 0},
        })
        свои["решений"] += 1
        свои["записей"] += замер.записей
        свои["секунд"] += замер.секунд
        куда = свои["по_связке"] if замер.по_связке else свои["поодиночке"]
        куда["решений"] += 1
        куда["секунд"] += замер.секунд
        куда["записей"] += замер.записей

    for свои in свод_родов.values():
        for где in ("поодиночке", "по_связке"):
            часть = свои[где]
            часть["секунд_на_решение"] = (
                часть["секунд"] / часть["решений"] if часть["решений"] else None)
        одиночные = свои["поодиночке"]
        # «Секунд на запись» имеет смысл только там, где решение и запись —
        # одно и то же. У связки это число выдумано: восемьсот записей не
        # смотрели по одной.
        свои["секунд_на_запись"] = (
            одиночные["секунд"] / одиночные["записей"]
            if одиночные["записей"] else None)
        свои["секунд_на_запись_считается_только_поодиночке"] = True
    return свод_родов


def свод(замеры) -> dict:
    """Общая картина ручного труда. Единого среднего на запись здесь нет.

    Его нет намеренно: роды сомнения — разная работа, и одно число по ним всем
    не описывало бы ни одного настоящего случая. Кому нужно одно число — тому
    нужно сперва выбрать род.
    """
    замеры = tuple(замеры)
    роды = по_родам(замеры)
    всего_секунд = sum(з.секунд for з in замеры)
    return {
        "версия": LABOUR_VERSION,
        "решений": len(замеры),
        "записей": sum(з.записей for з in замеры),
        "всего_секунд": всего_секунд,
        "родов": len(роды),
        "по_родам": роды,
        "операторов": sorted({з.оператор for з in замеры}),
        "единого_среднего_на_запись_нет": True,
        "почему_нет": ("роды сомнения — разная работа; одно среднее по ним не "
                       "описывает ни одного настоящего случая"),
    }


