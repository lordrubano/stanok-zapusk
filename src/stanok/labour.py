def нагрузка(связки, всего_записей: int = 0) -> dict:
    """Сколько решений предстоит человеку и по каким поводам. Счёт, не время.

    Считается по связкам сомнений (шаг 55) и **не требует ни одного оператора**:
    это единственное, что можно узнать о ручном труде до того, как он начался.

    Показывается двумя числами сразу: сколько решений выйдет, если разбирать
    записи поодиночке, и сколько — если разрешать связками. Разница между ними
    и есть то, что даёт консоль; во сколько секунд она обойдётся, покажет
    только живой человек.
    """
    связки = tuple(связки)
    по_родам_нагрузки = {}
    поодиночке = 0
    for связка in связки:
        поодиночке += связка.сколько
        # Связки копятся, а не затирают друг друга: один и тот же род приходит
        # из каждого документа своим, и «последняя победила» дала бы счёт
        # одного документа вместо всех.
        свои = по_родам_нагрузки.setdefault(связка.род, {
            "записей": 0, "решений_поодиночке": 0, "решений_связкой": 0,
            "поля": [],
        })
        свои["записей"] += связка.сколько
        свои["решений_поодиночке"] += связка.сколько
        свои["решений_связкой"] += 1
        for поле in связка.поля:
            if поле not in свои["поля"]:
                свои["поля"].append(поле)
    return {
        "версия": LABOUR_VERSION,
        "записей_всего": всего_записей,
        "записей_с_сомнением": поодиночке,
        "решений_поодиночке": поодиночке,
        "решений_связками": len(связки),
        "по_родам": по_родам_нагрузки,
        "времени_не_измерено": True,
    }


def экономия(замеры, без_станка_секунд: float | None = None) -> dict:
    """Доля сэкономленного времени. Без измеренного основания — отказ.

    Нуль здесь был бы хуже отказа: нуль выглядит как измеренное. Пока время той
    же работы без станка никто не мерил, сравнивать не с чем, и станок говорит
    это прямо.
    """
    if без_станка_секунд is None:
        raise НечегоСравнивать(
            "время той же работы без станка не измерено: доли экономии нет. "
            "Сперва меряется ручная обработка без станка, потом сравнивается")
    if без_станка_секунд <= 0:
        raise НечегоСравнивать(
            "основание сравнения должно быть больше нуля секунд")
    со_станком = sum(з.секунд for з in замеры)
    return {
        "версия": LABOUR_VERSION,
        "со_станком_секунд": со_станком,
        "без_станка_секунд": без_станка_секунд,
        "сэкономлено_секунд": без_станка_секунд - со_станком,
        "доля": (без_станка_секунд - со_станком) / без_станка_секунд,
    }


