@dataclass(frozen=True, slots=True)
class НастройкиСегментации:
    """Настройки разложения. Все числа здесь — предмет измерения, не веры.

    **Что измерено, а что осталось умозрительным.**

    ``доля_кегля_на_строку`` — единственное число здесь, подобранное по
    настоящему документу, и подобрано оно не на глаз. У выписки первого
    семейства разрывы между соседними уровнями текста распределены с чистой
    впадиной: разрывов в 1–4 пункта много (это дрожание базовой линии внутри
    одной строки), разрывов в 7–8 пунктов **нет ни одного**, а с 9 пунктов
    начинаются настоящие межстрочные шаги. Порог 0,5 кегля кладёт допуск ровно
    во впадину: 7 пунктов при кегле 14.

    Было 0,6 — число умозрительное. **Это подгонка под первое семейство, и она
    объявлена здесь именно поэтому.** Второе семейство может иметь другой шаг,
    другой кегль и другую впадину; тогда настройку придётся передавать
    оснасткой, а не держать общей. Пока семейство одно, и общее значение
    честнее вида, будто оно проверено на многих.

    Остальные числа — ``допуск_столбца``, минимумы таблицы — умозрительны
    по-прежнему: на настоящем документе они не мерились.
    """

    доля_кегля_на_строку: str = "0.5"
    допуск_столбца: str = "0.02"
    минимум_строк_таблицы: int = 2
    минимум_столбцов_таблицы: int = 2


@dataclass(frozen=True, slots=True)
class Ячейка:
    """Один объект источника внутри строки."""

    текст: str
    адрес: str
    столбец: str | None = None
    объект: SourceObject | None = None


@dataclass(frozen=True, slots=True)
class Строка:
    """Строка источника: набор ячеек с общим адресом."""

    адрес: str
    страница: int
    ячейки: tuple[Ячейка, ...]
    место: str | None = None

    @property
    def текст(self) -> str:
        return " ".join(ячейка.текст for ячейка in self.ячейки if ячейка.текст)


@dataclass(frozen=True, slots=True)
class Кандидат:
    """То, что **может** оказаться записью.

    Ничего не утверждает о своём содержимом. Признание — дело валидатора и
    движка политик, а не сегментатора.

    У кандидата два разных поля про место, и путать их нельзя.

    * ``адрес`` — местное имя вида «страница[1]/строка[7]». Годится, чтобы
      показать человеку и найти глазами. **Ссылаться на него нельзя**: номер
      строки поедет при первой же правке порогов склейки.
    * ``якорь`` — устойчивый адрес области источника (шаг 33). Только он
      годится для доказательной связи и для ссылок из записей.
    """

    адрес: str
    страница: int
    строка: Строка
    таблица: str | None = None
    якорь: object | None = None
    почему_без_якоря: str = ""

    @property
    def source_anchor_id(self) -> str | None:
        """Устойчивый адрес записи либо None, если его построить нельзя."""
        return self.якорь.идентификатор if self.якорь is not None else None

    def as_json(self) -> dict:
        return {
            "местное_имя": self.адрес,
            "source_anchor_id": self.source_anchor_id,
            "почему_без_якоря": self.почему_без_якоря,
            "страница": self.страница,
            "таблица": self.таблица,
            "ячейки": [
                {"текст": ячейка.текст, "адрес": ячейка.адрес,
                 "столбец": ячейка.столбец}
                for ячейка in self.строка.ячейки
            ],
        }


@dataclass(frozen=True, slots=True)
class Неразобранное:
    """Объект, который не удалось разложить, и прямо названная причина."""

    адрес: str
    причина: str
    объект: SourceObject | None = None


@dataclass(frozen=True, slots=True)
class Таблица:
    """Полоса соседних строк с общими столбцами.

    Наблюдение об устройстве, а не утверждение «это таблица выписки».
    """

    адрес: str
    страница: int
    строки: tuple[str, ...]
    столбцы: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class Сегментация:
    """Всё, что нашёл сегментатор, и всё, чего он не смог разложить."""

    schema_version: str = SEGMENTATION_VERSION
    страницы: tuple[dict, ...] = ()
    строки: tuple[Строка, ...] = ()
    таблицы: tuple[Таблица, ...] = ()
    кандидаты: tuple[Кандидат, ...] = ()
    неразобранное: tuple[Неразобранное, ...] = ()
    способ: str = ""
    учтено_объектов: int = 0
    подано_объектов: int = 0

    @property
    def учёт_сходится(self) -> bool:
        """Сошёлся ли учёт: ни один объект не пропал молча."""
        return self.подано_объектов == self.учтено_объектов

    def as_json(self) -> dict:
        return {
            "schema_version": self.schema_version,
            "способ": self.способ,
            "подано_объектов": self.подано_объектов,
            "учтено_объектов": self.учтено_объектов,
            "учёт_сходится": self.учёт_сходится,
            "страниц": len(self.страницы),
            "строк": len(self.строки),
            "таблиц": len(self.таблицы),
            "кандидатов": len(self.кандидаты),
            "неразобранного": len(self.неразобранное),
            "неразобранное": [
                {"адрес": н.адрес, "причина": н.причина}
                for н in self.неразобранное
            ],
        }


# ------------------------------------------------------- выбор способа

_РЕШЁТКА_СТРОКА = re.compile(r"строка\[(\d+)\]")
_РЕШЁТКА_ЛИСТ = re.compile(r"лист\[([^\]]*)\]/ячейка\[([A-Za-z]+)(\d+)\]")

# Виды объектов, которые сами по себе уже являются целой записью источника.
# Список содержательный, а не по именам движков: так его можно пополнять, не
# зная, кто именно объект произвёл.
_ЦЕЛЬНЫЕ_ВИДЫ = frozenset({"проводка", "остаток", "заголовок выписки"})

# Виды, описывающие устройство источника, а не его содержимое.
_УСТРОЙСТВО = frozenset({"страница"})


def выбрать_способ(объекты) -> str:
    """Как раскладывать: по координатам, по решётке или объекты уже цельные.

    Решается по тому, что несут сами объекты. Имена распознавателей здесь не
    участвуют и участвовать не должны.
    """
    цельных = решётчатых = координатных = 0
    for объект in объекты:
        вид = объект.свойство("вид")
        if вид in _УСТРОЙСТВО:
            continue
        if вид in _ЦЕЛЬНЫЕ_ВИДЫ or _поле_ли(объект):
            цельных += 1
        elif (объект.свойство("привязка_y") is not None
              or объект.свойство("привязка_x") is not None
              or объект.полигон):
            координатных += 1
        elif _адрес_решётки(объект) is not None:
            решётчатых += 1
    if цельных and цельных >= max(решётчатых, координатных):
        return "цельные записи"
    if координатных and координатных >= решётчатых:
        return "по координатам"
    if решётчатых:
        return "по решётке"
    return "нечего раскладывать"


def _адрес_решётки(объект: SourceObject):
    """Номер строки решётки: из свойств либо из структурного пути."""
    if объект.свойство("строка_файла") is not None:
        совпало = _РЕШЁТКА_СТРОКА.search(объект.структурный_путь)
        if совпало:
            return int(совпало.group(1))
    адрес = объект.свойство("адрес")
    if isinstance(адрес, str) and адрес:
        цифры = "".join(знак for знак in адрес if знак.isdigit())
        if цифры:
            return int(цифры)
    совпало = _РЕШЁТКА_СТРОКА.search(объект.структурный_путь)
    return int(совпало.group(1)) if совпало else None


# ---------------------------------------------------------- разложение


def разложить(объекты, настройки: НастройкиСегментации | None = None,
              срок=None) -> Сегментация:
    """Раскладывает объекты источника на строки, таблицы и кандидатов.

    Ничего не бросает: беда объекта — это запись в неразобранном, а не отказ
    всего разложения. Потерять объект молча нельзя ни при какой беде.

    Единственное, чем разложение прерывается, — истёкший срок сборки страниц.
    Все проходы здесь идут по конечному списку объектов и завершаются сами;
    срок стережёт не зацикливание, а медленность: на документе, где сборка
    растёт быстрее числа объектов, отказ приходит с названной причиной,
    а не после бесконечного ожидания.
    """
    срок = срок if срок is not None else срок_места("сборка страниц")
    срок.проверить()
    настройки = настройки or НастройкиСегментации()
    объекты = list(объекты)
    подано = len(объекты)

    устройство = [о for о in объекты if о.свойство("вид") in _УСТРОЙСТВО]
    содержимое = [о for о in объекты if о.свойство("вид") not in _УСТРОЙСТВО]
    страницы = tuple(
        {"страница": о.страница, "адрес": о.структурный_путь,
         **{ключ: значение for ключ, значение in о.свойства}}
        for о in устройство)

    способ = выбрать_способ(объекты)
    if способ == "цельные записи":
        строки, неразобранное, разложенные = _цельными(содержимое)
    elif способ == "по координатам":
        строки, неразобранное, разложенные = _по_координатам(содержимое, настройки)
    elif способ == "по решётке":
        строки, неразобранное, разложенные = _по_решётке(содержимое)
    else:
        строки, разложенные = (), []
        неразобранное = tuple(
            Неразобранное(о.структурный_путь,
                          "объект не несёт ни координат, ни адреса решётки, "
                          "ни признака цельной записи", о)
            for о in содержимое)

    срок.проверить()
    таблицы = _таблицы(строки, настройки)
    в_таблице = {адрес: таблица.адрес
                 for таблица in таблицы for адрес in таблица.строки}
    кандидаты = tuple(_кандидат(строка, в_таблице.get(строка.адрес))
                      for строка in строки)

    # Считаем **объекты**, а не ячейки: цельная запись даёт одну строку из
    # многих ячеек, и счёт по ячейкам показал бы учтённым больше, чем подано.
    # Ошибка в эту сторону опаснее недосчёта: сходящийся на вид учёт усыпляет.
    учтено = len(разложенные) + len(устройство) + len(неразобранное)
    if len({id(о) for о in разложенные}) != len(разложенные):
        # Один объект, разложенный дважды, тоже даёт ложное «сошлось».
        учтено = -1
    return Сегментация(
        SEGMENTATION_VERSION, страницы, строки, таблицы, кандидаты,
        неразобранное, способ, учтено, подано)


def _поле_ли(объект) -> bool:
    """Объект — именованное поле сообщения, а не целая запись.

    Так устроены телеграфные и меточные форматы: сообщение состоит из
    поименованных полей, и запись собирается из них по правилам семейства.
    Признак берётся по содержимому — наличию имени поля, — а не по движку.
    """
    return (объект.свойство("поле") is not None
            or объект.свойство("метка") is not None)


def _кандидат(строка: Строка, таблица: str | None) -> Кандидат:
    """Кандидат со своим устойчивым адресом.

    Невозможность построить якорь — состояние, а не падение: кандидат остаётся,
    но прямо объявляет, что ссылаться на него нельзя. Молча отдать кандидата без
    устойчивого адреса было бы хуже: ссылка на местное имя выглядит как ссылка и
    рвётся при первой правке порогов.
    """
    try:
        якорь = якорь_записи(строка.ячейки)
        почему = ""
    except ЯкорьНевозможен as беда:
        якорь, почему = None, str(беда)
    return Кандидат(строка.адрес, строка.страница, строка, таблица, якорь, почему)


def _цельными(объекты):
    """Цельные записи — сами по себе строки; поля сообщения — по сообщению.

    Разбить сообщение на записи по отдельным сделкам здесь нельзя: какое поле
    начинает запись, знает шаблон семейства (шаг 37). Собирать по догадке —
    ровно то, чего этот шаг обязан не делать. Поэтому поля одного сообщения
    складываются в одну строку целиком: ничего не потеряно и ничего не
    придумано.
    """
    строки, неразобранное, разложенные = [], [], []
    поля_сообщений: dict[int, list] = {}
    for объект in объекты:
        вид = объект.свойство("вид")
        if вид not in _ЦЕЛЬНЫЕ_ВИДЫ:
            if _поле_ли(объект):
                поля_сообщений.setdefault(объект.страница, []).append(объект)
                continue
            неразобранное.append(Неразобранное(
                объект.структурный_путь,
                f"вид {вид!r} не является цельной записью источника", объект))
            continue
        ячейки = tuple(
            Ячейка(str(значение), f"{объект.структурный_путь}/{ключ}", ключ, объект)
            for ключ, значение in объект.свойства if ключ != "вид")
        строки.append(Строка(
            объект.структурный_путь, объект.страница,
            ячейки or (Ячейка(объект.сырой_текст or "",
                              объект.структурный_путь, None, объект),),
            место=вид))
        разложенные.append(объект)

    for сообщение in sorted(поля_сообщений):
        свои = поля_сообщений[сообщение]
        ячейки = tuple(
            Ячейка(о.сырой_текст or "", о.структурный_путь,
                   str(о.свойство("поле") or о.свойство("метка")), о)
            for о in свои)
        строки.append(Строка(
            f"сообщение[{сообщение}]", сообщение, ячейки, место="поля сообщения"))
        разложенные.extend(свои)
    return tuple(строки), tuple(неразобранное), разложенные


def _по_решётке(объекты):
    """Строки берутся из адресов решётки: строка файла или номер строки листа."""
    по_строкам: dict[tuple, list] = {}
    неразобранное, разложенные = [], []
    for объект in объекты:
        номер = _адрес_решётки(объект)
        if номер is None:
            неразобранное.append(Неразобранное(
                объект.структурный_путь, "у объекта нет адреса строки", объект))
            continue
        лист = объект.свойство("лист") or ""
        ключ = (объект.страница, лист, номер)
        по_строкам.setdefault(ключ, []).append(объект)

    строки = []
    for (страница, лист, номер) in sorted(по_строкам):
        свои = по_строкам[(страница, лист, номер)]
        свои.sort(key=lambda о: _ключ_столбца(о))
        ячейки = tuple(
            Ячейка(о.сырой_текст or "", о.структурный_путь,
                   _имя_столбца(о), о)
            for о in свои)
        адрес = (f"лист[{лист}]/строка[{номер}]" if лист
                 else f"страница[{страница}]/строка[{номер}]")
        строки.append(Строка(адрес, страница, ячейки))
        разложенные.extend(свои)
    return tuple(строки), tuple(неразобранное), разложенные


def _имя_столбца(объект) -> str | None:
    заголовок = объект.свойство("заголовок")
    if заголовок:
        return str(заголовок)
    столбец = объект.свойство("столбец")
    return str(столбец) if столбец is not None else None


def _ключ_столбца(объект):
    столбец = объект.свойство("столбец")
    if isinstance(столбец, int):
        return (0, столбец, "")
    if isinstance(столбец, str) and столбец:
        # Буквенный столбец книги: сперва длина, затем буквы — так «AA» встаёт
        # после «Z», а не между «A» и «B».
        return (1, len(столбец), столбец)
    return (2, 0, объект.структурный_путь)


def _по_координатам(объекты, настройки: НастройкиСегментации):
    """Строки склеиваются по близости привязок вдоль страницы."""
    по_страницам: dict[int, list] = {}
    неразобранное, разложенные = [], []
    for объект in объекты:
        y = объект.свойство("привязка_y")
        if y is None and объект.полигон:
            y = объект.полигон[0][1]
        if y is None:
            неразобранное.append(Неразобранное(
                объект.структурный_путь,
                "у объекта нет привязки по высоте", объект))
            continue
        по_страницам.setdefault(объект.страница, []).append((Decimal(str(y)), объект))

    доля = Decimal(настройки.доля_кегля_на_строку)
    строки = []
    for страница in sorted(по_страницам):
        свои = sorted(по_страницам[страница], key=lambda пара: (-пара[0], _x(пара[1])))
        полосы: list[list] = []
        for y, объект in свои:
            допуск = _допуск_строки(объект, доля)
            if полосы and abs(полосы[-1][0][0] - y) <= допуск:
                полосы[-1].append((y, объект))
            else:
                полосы.append([(y, объект)])
        for номер, полоса in enumerate(полосы, start=1):
            полоса.sort(key=lambda пара: _x(пара[1]))
            ячейки = tuple(
                Ячейка(о.сырой_текст or "", о.структурный_путь,
                       str(о.свойство("привязка_x") or ""), о)
                for _, о in полоса)
            строки.append(Строка(
                f"страница[{страница}]/строка[{номер}]", страница, ячейки,
                место=str(полоса[0][0])))
            разложенные.extend(о for _, о in полоса)
    return tuple(строки), tuple(неразобранное), разложенные


def _допуск_строки(объект, доля: Decimal) -> Decimal:
    """Насколько близко по высоте должны стоять куски одной строки.

    Считается от кегля: у крупного заголовка разброс базовой линии больше, чем
    у мелкой строки таблицы, и общий допуск в долях страницы либо склеил бы
    таблицу, либо разорвал заголовок.

    Кегль берётся в долях листа у самого источника. Раньше он переводился из
    пунктов делением на 792 — высоту привычного листа. Настоящая выписка
    пришла на листе 1200×1700, и предположение оказалось неверным: у каждого
    семейства свой размер листа, и знать его — дело того, кто читал страницу.
    """
    в_долях = объект.свойство("кегль_долей")
    if в_долях is not None:
        try:
            высота = Decimal(str(в_долях))
        except (ValueError, ArithmeticError):
            высота = Decimal("0")
        return высота * доля if высота else _ДОПУСК_БЕЗ_КЕГЛЯ

    кегль = объект.свойство("кегль")
    try:
        высота = Decimal(str(кегль)) if кегль is not None else Decimal("0")
    except (ValueError, ArithmeticError):
        высота = Decimal("0")
    # Источник кегля в долях не дал. Переводим по привычной высоте листа и
    # честно считаем это предположением, а не измерением.
    return (высота / Decimal(792)) * доля if высота else _ДОПУСК_БЕЗ_КЕГЛЯ


def _x(объект) -> Decimal:
    значение = объект.свойство("привязка_x")
    if значение is None and объект.полигон:
        значение = объект.полигон[0][0]
    try:
        return Decimal(str(значение)) if значение is not None else Decimal(0)
    except (ValueError, ArithmeticError):
        return Decimal(0)


def _таблицы(строки, настройки: НастройкиСегментации):
    """Полосы соседних строк с общими столбцами.

    Это наблюдение об устройстве, а не утверждение, что перед нами таблица
    выписки: последнее решает шаблон семейства.
    """
    таблицы = []
    допуск = Decimal(настройки.допуск_столбца)
    текущие: list = []

    def закрыть():
        if len(текущие) >= настройки.минимум_строк_таблицы:
            общие = _общие_столбцы(текущие, допуск)
            if len(общие) >= настройки.минимум_столбцов_таблицы:
                таблицы.append(Таблица(
                    f"{текущие[0].адрес}~{текущие[-1].адрес}",
                    текущие[0].страница,
                    tuple(строка.адрес for строка in текущие),
                    tuple(str(столбец) for столбец in общие)))
        текущие.clear()

    def годится(набор) -> bool:
        return (len(_общие_столбцы(набор, допуск))
                >= настройки.минимум_столбцов_таблицы)

    for строка in строки:
        достаточно_ячеек = len(строка.ячейки) >= настройки.минимум_столбцов_таблицы
        та_же_страница = not текущие or строка.страница == текущие[-1].страница

        # Строка добавляется, только если общие столбцы остаются общими у всей
        # полосы. Жадное накопление с проверкой в конце губит таблицу целиком:
        # у настоящего счёта заголовок стоит чуть иначе, чем данные под ним, и
        # одна такая строка обнуляла общий набор для трёх последующих.
        if достаточно_ячеек and та_же_страница and годится([*текущие, строка]):
            текущие.append(строка)
            continue

        закрыть()
        # Строка, не ужившаяся с прежней полосой, сама может начать новую.
        if достаточно_ячеек:
            текущие.append(строка)
    закрыть()
    return tuple(таблицы)


def _общие_столбцы(строки, допуск: Decimal):
    """Столбцы, встречающиеся во всех переданных строках."""
    наборы = []
    for строка in строки:
        свои = []
        for ячейка in строка.ячейки:
            if ячейка.столбец in (None, ""):
                continue
            try:
                свои.append(Decimal(str(ячейка.столбец)))
            except (ValueError, ArithmeticError):
                свои.append(ячейка.столбец)
        наборы.append(свои)
    if not наборы or not наборы[0]:
        return []

    общие = []
    for столбец in наборы[0]:
        if all(_есть_рядом(столбец, набор, допуск) for набор in наборы[1:]):
            общие.append(столбец)
    return общие


def _есть_рядом(столбец, набор, допуск: Decimal) -> bool:
    for иной in набор:
        if isinstance(столбец, Decimal) and isinstance(иной, Decimal):
            if abs(столбец - иной) <= допуск:
                return True
        elif столбец == иной:
            return True
    return False


