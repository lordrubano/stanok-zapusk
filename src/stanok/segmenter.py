# -*- coding: utf-8 -*-
"""Сегментатор: страницы, области, таблицы, строки и записи-кандидаты.

Шаг 32 плана. Нормативная основа — чертёж v3.0, раздел 5.1 (компонент 4) и
раздел 8 (модель покрытия источника).

**Это узел наибольшего риска во всём станке.** Ошибка здесь невидима на всех
последующих уровнях: ненайденная строка не оставляет следа. Её не поймают ни
балансы, ни цепной хеш, ни подпись — они заверяют то, что найдено, и молчат о
том, чего не нашли.

Отсюда главное правило этого места: **учёт обязан сходиться**. Каждый объект
источника, поданный на вход, обязан оказаться ровно в одном из трёх мест:

* в строке — то есть учтён содержательно;
* в перечне устройства (страницы) — учтён как разметка, а не содержимое;
* в **неразобранном** — с прямо названной причиной, почему его не удалось
  разложить.

Молча потерять объект нельзя. Проверка на это — не одна из проверок, а
единственное, что отделяет сегментатор от красивой видимости работы.

**Кандидат — это то, что может оказаться записью, а не то, что ею признано.**
Здесь никто ничего не признаёт: признание — дело валидатора и движка политик.
Кандидат несёт своё содержимое, свой адрес и своё происхождение, и ничего
больше.

Карта покрытия здесь не строится — это шаг 34. Но всё, на чём она потом
строится, отдаётся отсюда: что найдено, где именно и что осталось неразобранным.

Способ разложения выбирается **по содержимому объектов**, а не по имени
распознавателя: у ядра нет и не должно быть списка известных движков — тот же
довод, что и в розетке шага 25.
"""

