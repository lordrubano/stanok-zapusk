# -*- coding: utf-8 -*-
"""Независимая перепроверка: изображение против текстового слоя.

Шаг 43 плана. Нормативная основа — чертёж v3.0, раздел 9 (уровень 8: другой
физический путь — изображение против текстового слоя или иной OCR) и раздел 11
(состояния записи и запуска).

**Это единственный уровень, идущий другим физическим путём.** Все прежние судят
прочитанное по внутренней согласованности: типы согласны со схемой, порядок с
объявленным, итоги с напечатанными, поля друг с другом. Ни один из них не может
заметить, что прочитано **не то, что напечатано**, — потому что все они читают
одно и то же прочтение. Здесь впервые сличается не разбор с документом, а разбор
**со вторым прочтением того же места**.

**Независимость — свойство пути, а не имени движка.** Два разных движка,
читающих один и тот же встроенный текстовый слой, независимыми не являются: при
битом слое они ошибутся **синхронно и одинаково**, и их согласие будет выглядеть
как подтверждение. Именно поэтому запрет здесь сделан устройством, а не
соглашением: :func:`сличить` **отказывается** сличать два прочтения встроенного
слоя — не понижает уверенность, не предупреждает, а прекращает работу.

Независимость даёт рендер страницы в изображение и распознавание **видимых
знаков**: этот путь не знает ни таблиц кодировки, ни ToUnicode, ни глифовых
подмен — он видит то же, что человек.

Различаются три степени, и они не равноценны:

* :data:`ПОЛНАЯ` — разные пути (изображение против текстового слоя). Битый слой
  ловится;
* :data:`ЧАСТИЧНАЯ` — один путь, разные движки (два распознавателя по одному
  рендеру). Раздел 9 такое допускает, но общая ошибка рендера, поворота и
  выбора области воспроизводится обоими, и это объявляется прямо;
* :data:`НЕТ` — один путь и один движок либо два чтения встроенного слоя.
  Перепроверки не существует, и объявить её состоявшейся нельзя.

**Второму пути не показывают ответ первого.** Распознаватель получает только
адреса областей — ни знака из первого прочтения. Иначе это не независимость, а
подтверждение: подсказанный ответ воспроизводится, а не проверяется. Розетка
устроена так, что показать ему первое прочтение нечем, и на это есть проверка.

**Здесь закрывается отложенное шагом 28.** Битый текстовый слой там
обнаруживался, но не лечился. Лечение — не починка текста (чинить нечего: знаки
подменены), а **замена пути**: страница с битым слоем требует второго прочтения,
и её значения берутся из него. Первое прочтение при этом **отбрасывается, а не
сливается** со вторым: слияние узаконило бы битое чтение, спрятав его внутрь
общего результата.

**Совпадение двух прочтений повышает уверенность, но доказательством не
является.** Общая систематическая ошибка воспроизводима обоими путями — перечень
в :data:`ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СОВПАДЕНИЕ`, и он уходит вместе с результатом.
"""

