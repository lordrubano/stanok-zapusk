class ПутиНеНезависимы(ValueError):
    """Попытка выдать за независимую перепроверку то, что ею не является.

    Отказ, а не понижение уверенности. Согласие двух прочтений одного и того же
    встроенного слоя выглядит как подтверждение и им не является: при битом
    слое оба движка ошибутся синхронно и одинаково. Такое «подтверждение»
    опаснее его отсутствия — оно закрывает вопрос, который никто не открывал.
    """

    код = "E_RECHECK_NOT_INDEPENDENT"


@dataclass(frozen=True, slots=True)
class Прочтение:
    """Одно прочтение одной области источника одним путём.

    ``адрес`` — якорь области (шаг 33). Сличать можно только прочтения **одного
    места**: сравнение разных мест не даёт ни согласия, ни расхождения, оно не
    значит ничего.
    """

    адрес: str
    путь: str
    движок: str
    версия: str
    текст: str | None = None

    def as_json(self) -> dict:
        return {"адрес": self.адрес, "путь": self.путь, "движок": self.движок,
                "версия": self.версия, "текст": self.текст}


def _результат(rule_id, статус, критичность, входы, вычисления, причина):
    return RuleResult(rule_id, RECHECK_VERSION, статус, критичность,
                      tuple(входы), вычисления, причина)


# --------------------------------------------------------- независимость


def оценить_независимость(первое: Прочтение, второе: Прочтение) -> tuple[str, str]:
    """Насколько два прочтения независимы друг от друга и почему.

    Судится путь и движок, а не имя и не репутация. Возвращает степень и
    причину человеческим языком.
    """
    чужие = [прочтение.путь for прочтение in (первое, второе)
             if прочтение.путь not in ПУТИ]
    if чужие:
        # Путь, которого уровень не знает, независимости не даёт. Считать его
        # независимым «раз он другой» значило бы выдавать независимость за
        # непохожесть названия.
        return НЕТ, ("путь " + ", ".join(repr(п) for п in чужие)
                     + " этому уровню неизвестен; независимость даёт "
                       "объявленный физический путь, а не незнакомое название")

    один_путь = первое.путь == второе.путь
    один_движок = (первое.движок, первое.версия) == (второе.движок, второе.версия)

    if один_путь and один_движок:
        return НЕТ, ("тот же движок тем же путём: это повторное чтение, а не "
                     "перепроверка")
    if один_путь and первое.путь == ПУТЬ_ТЕКСТОВЫЙ_СЛОЙ:
        return НЕТ, ("два движка по одному встроенному текстовому слою "
                     "независимыми не являются: при битом слое они ошибутся "
                     "синхронно и одинаково, и согласие будет выглядеть "
                     "подтверждением")
    if один_путь:
        return ЧАСТИЧНАЯ, ("разные движки одним путём: общая ошибка рендера, "
                           "поворота страницы и выбора области воспроизводится "
                           "обоими")
    return ПОЛНАЯ, ("разные физические пути: распознавание видимых знаков не "
                    "знает ни таблиц кодировки, ни ToUnicode, ни глифовых "
                    "подмен")


# ------------------------------------------------------------- сличение


def _для_сличения(текст: str) -> str:
    """Приводит текст к виду, в котором сличаются знаки, а не отображение.

    Свёртывается только то, что заведомо принадлежит отображению: пробельные
    цепочки и способ записи буквы (NFC). Дальше не идём: правило «О считать за
    ноль» скрыло бы ровно те ошибки, ради которых уровень существует.
    """
    свёрнутый = " ".join(str(текст).split())
    return unicodedata.normalize("NFC", свёрнутый)


def _первое_расхождение(левый: str, правый: str) -> str:
    for место, (л, п) in enumerate(zip(левый, правый), start=1):
        if л != п:
            return f"знак №{место}: {л!r} против {п!r}"
    короче = "первое" if len(левый) < len(правый) else "второе"
    общих = min(len(левый), len(правый))
    if общих == 0:
        return f"{короче} прочтение пусто, второе — нет"
    return f"совпадают до знака №{общих}, дальше {короче} прочтение кончилось"


def сличить(первое: Прочтение, второе: Прочтение) -> RuleResult:
    """Сличает два прочтения одной области. Мнимую независимость — отвергает.

    Отказ здесь намеренно жёсткий: молчаливое «перепроверка пройдена» на двух
    чтениях одного и того же слоя — это ложное свидетельство, попавшее в
    доказательную цепь.
    """
    if первое.адрес != второе.адрес:
        raise ПутиНеНезависимы(
            f"прочтения разных мест: {первое.адрес!r} и {второе.адрес!r}. "
            "Сравнение разных мест не значит ничего")

    степень, почему = оценить_независимость(первое, второе)
    if степень == НЕТ:
        raise ПутиНеНезависимы(почему)

    входы = (первое.адрес, первое.путь, второе.путь)
    if первое.текст is None or второе.текст is None:
        чьё = "первое" if первое.текст is None else "второе"
        return _результат(
            "перепроверка/сличение", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, входы,
            f"{чьё} прочтение области не дало текста",
            "сличать нечем: несличённое не считается совпавшим")

    левый = _для_сличения(первое.текст)
    правый = _для_сличения(второе.текст)
    if левый == правый:
        причина = ("два пути прочли одно и то же. Уверенность выше, "
                   "доказательством это не является: общая систематическая "
                   "ошибка воспроизводима обоими путями")
        if степень == ЧАСТИЧНАЯ:
            причина += ("; независимость частичная — путь один, разошлись "
                        "только движки")
        return _результат(
            "перепроверка/сличение", ПРОШЛО, КРИТИЧЕСКОЕ, входы,
            f"совпало ({степень} независимость): {левый!r}", причина)

    return _результат(
        "перепроверка/сличение", НАРУШЕНО, КРИТИЧЕСКОЕ, входы,
        f"{первое.движок}: {левый!r}; {второе.движок}: {правый!r}; "
        + _первое_расхождение(левый, правый),
        "пути разошлись: одно из двух прочтений неверно, и какое именно — "
        "отсюда не видно. Выбрать за них проверка не станет")


def сличить_области(первые, вторые) -> tuple[RuleResult, ...]:
    """Сличает наборы прочтений, сопоставляя их по адресу области.

    Область, второго прочтения не получившая, объявляется непроверенной. Это не
    придирка: перепроверка, засчитанная за области, которых никто не смотрел,
    и была бы тем самым ложным свидетельством.
    """
    первые = list(первые)
    вторые_по_адресу = {прочтение.адрес: прочтение for прочтение in вторые}
    итоги: list[RuleResult] = []
    непроверенные = []

    for прочтение in первые:
        пара = вторые_по_адресу.get(прочтение.адрес)
        if пара is None:
            непроверенные.append(прочтение.адрес)
            continue
        итоги.append(сличить(прочтение, пара))

    лишние = sorted(set(вторые_по_адресу) - {п.адрес for п in первые})
    if непроверенные:
        перечень = ", ".join(непроверенные[:10])
        хвост = "" if len(непроверенные) <= 10 else f" и ещё {len(непроверенные) - 10}"
        итоги.append(_результат(
            "перепроверка/охват", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ,
            (f"областей: {len(непроверенные)}",),
            f"без второго прочтения: {перечень}{хвост}",
            "область, второго прочтения не получившая, не перепроверена; её "
            "молчание не является согласием"))
    elif первые:
        итоги.append(_результат(
            "перепроверка/охват", ПРОШЛО, КРИТИЧЕСКОЕ,
            (f"областей: {len(первые)}",),
            "каждая поданная область прочитана дважды",
            "непроверенных областей среди поданных нет"))

    for адрес in лишние:
        итоги.append(_результат(
            "перепроверка/лишнее", НЕИЗВЕСТНО, ИСПРАВИМОЕ, (адрес,),
            "второй путь прочёл область, которой нет в первом прочтении",
            "сличать не с чем: либо первый путь эту область пропустил, либо "
            "второй прочёл лишнее. Оба случая — повод смотреть, а не молчать"))
    return tuple(итоги)


# ------------------------------------- битый слой: отложенное шага 28


def проверить_слой(слой: str, второй_путь_есть: bool) -> RuleResult:
    """Что делать со страницей, судя по её текстовому слою.

    Закрывает отложенное шагом 28. Лечение битого слоя — не починка текста
    (чинить нечего: знаки подменены), а **замена пути**.
    """
    if слой == "битый текстовый слой":
        if not второй_путь_есть:
            return _результат(
                "слой/битый", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (слой,),
                "битый слой без второго прочтения",
                "текст на вид есть, и доверять ему нельзя: знаки подменены. "
                "Пока страница не прочитана вторым путём, её значения не "
                "установлены — это неизвестность, а не текст")
        return _результат(
            "слой/битый", ПРОШЛО, КРИТИЧЕСКОЕ, (слой,),
            "битый слой прочитан вторым путём; первое прочтение отброшено",
            "первое прочтение не сливается со вторым, а отбрасывается: "
            "слияние узаконило бы битое чтение, спрятав его внутрь общего "
            "результата")

    if слой == "скан":
        return _результат(
            "слой/скан", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (слой,),
            "текстового слоя нет вовсе",
            "сличать не с чем: у скана единственный путь — изображение. "
            "Перепроверка возможна только другим движком по тому же пути, и "
            "независимость её будет частичной")

    if слой == "нечитаемая":
        return _результат(
            "слой/нечитаемая", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (слой,),
            "первого прочтения не было вовсе",
            "страница не прочитана ни разу: сличать нечего, и второй путь "
            "здесь не перепроверка, а единственное прочтение")

    if слой == "пустая":
        if not второй_путь_есть:
            return _результат(
                "слой/пустая", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (слой,),
                "пустота объявлена без второго прочтения",
                "страница объявлена пустой тем же путём, который на ней ничего "
                "не нашёл. Именно на пустой странице второй путь и нужен: "
                "не найденное одним путём не то же самое, что отсутствующее")
        return _результат(
            "слой/пустая", ПРОШЛО, КРИТИЧЕСКОЕ, (слой,),
            "пустота проверена вторым путём",
            "второй путь прошёл по странице; всё, что он на ней увидел, выйдет "
            "отдельным правилом о лишнем")

    if слой in ("текстовый слой", "смешанная"):
        if not второй_путь_есть:
            return _результат(
                "слой/перепроверен", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (слой,),
                "второго прочтения нет",
                "слой цел, но целость слоя доказывается им же самим: без "
                "второго пути подмена глифов остаётся необнаружимой")
        return _результат(
            "слой/перепроверен", ПРОШЛО, КРИТИЧЕСКОЕ, (слой,),
            "слой цел и прочитан вторым путём", "оба пути пройдены")

    return _результат(
        "слой/перепроверен", НЕИЗВЕСТНО, КРИТИЧЕСКОЕ, (str(слой),),
        f"состояние слоя {слой!r} этому уровню неизвестно",
        "неизвестное состояние не считается пригодным")


# ---------------------------------------------------------- розетка


@dataclass
class РозеткаПерепроверки:
    """Куда включается независимый путь. Пустая — честно бессильна.

    Розетка сделана отдельно от вилки по доводу шага 25: движок обязан
    заменяться без правки ядра. Здесь у неё есть вторая обязанность —
    **не пускать мнимую независимость**: распознаватель, объявивший себя
    читателем встроенного слоя, не подключается вовсе.
    """

    распознаватели: dict = field(default_factory=dict)

    def подключить(self, распознаватель) -> None:
        путь = getattr(распознаватель, "путь", None)
        имя = getattr(распознаватель, "имя", None)
        if путь != ПУТЬ_ИЗОБРАЖЕНИЕ:
            raise ПутиНеНезависимы(
                f"распознаватель {имя!r} объявил путь {путь!r}; независимый "
                f"путь здесь один: {ПУТЬ_ИЗОБРАЖЕНИЕ}. Чтение того же "
                "встроенного слоя другим движком перепроверкой не является")
        if not hasattr(распознаватель, "прочитать"):
            raise ПутиНеНезависимы(
                f"распознаватель {имя!r} не умеет читать области: нет "
                "«прочитать»")
        self.распознаватели[имя] = распознаватель

    def прочитать(self, конверт, данные: bytes, адреса,
                  движок: str | None = None, срок=None,
                  страниц: int | None = None) -> tuple[Прочтение, ...]:
        """Второе прочтение указанных областей.

        Распознавателю передаются **только адреса**. Первого прочтения он не
        видит и увидеть не может: показать ему ожидаемый ответ здесь нечем.
        Иначе это была бы не независимость, а подтверждение — подсказанный
        ответ воспроизводится, а не проверяется.

        **Срок здесь строже всего прочего.** Распознаватель — чужой код, и
        молчащий чужой код опаснее ошибающегося: ошибку видно, молчание — нет.
        Розетка стережёт срок между областями и после каждой прочитанной, но
        прервать чужой вызов, повисший внутри себя, изнутри одного процесса
        нельзя. Поэтому объявлено прямо: распознаватель, работающий не в
        клетке шага 24, стережётся только между областями. Жёсткое
        принуждение — отдельный процесс, убиваемый по времени.
        """
        from .deadline import (СРОК_СТРАНИЦЫ_РАСПОЗНАВАНИЯ, СРОКИ_МЕСТ,
                               место as срок_места)

        # Утверждено два числа, и меньшее из них главнее: на файл даётся 180 с,
        # но одна страница не получает больше тридцати. Названное число страниц
        # делает потолок теснее, неназванное оставляет только потолок файла —
        # выдумывать за вызывающего, сколько страниц он перепроверяет, нельзя.
        потолок = СРОКИ_МЕСТ["распознавание изображения"]
        if страниц is not None:
            потолок = min(потолок, СРОК_СТРАНИЦЫ_РАСПОЗНАВАНИЯ * max(1, страниц))
        свой = срок if срок is not None else срок_места(
            "распознавание изображения", предел=потолок)
        if not self.распознаватели:
            return ()
        if движок is None:
            if len(self.распознаватели) > 1:
                # Молчаливый выбор одного из нескольких — решение, спрятанное
                # в порядке словаря. Каким движком перепроверено, обязано быть
                # видно: от этого зависит вес свидетельства.
                raise ПутиНеНезависимы(
                    "подключено несколько распознавателей ("
                    + ", ".join(sorted(self.распознаватели))
                    + "); каким перепроверять — надо назвать: выбор наугад "
                      "скрыл бы, чьё это свидетельство")
            движок = next(iter(self.распознаватели))
        if движок not in self.распознаватели:
            raise ПутиНеНезависимы(f"распознаватель {движок!r} не подключён")
        имя = движок
        распознаватель = self.распознаватели[имя]
        собранные = []
        свой.проверить()
        for прочтение in распознаватель.прочитать(конверт, данные, tuple(адреса)):
            свой.проверить()
            # Происхождение ставит розетка, а не движок: иначе он мог бы
            # подписаться чужим путём и обойти запрет мнимой независимости.
            собранные.append(Прочтение(
                адрес=прочтение.адрес, путь=ПУТЬ_ИЗОБРАЖЕНИЕ,
                движок=имя, версия=str(getattr(распознаватель, "версия", "")),
                текст=прочтение.текст))
        return tuple(собранные)


# ---------------------------------------------------------------- свод


def перепроверка_пройдена(итоги) -> bool:
    """Условие ``independent_check_passed`` из формулы 10.1.

    Истинно только когда все правила прошли; одно ``неизвестно`` делает его
    ложным. «Не требуется версионированной политикой» — не здешнее решение:
    политику назначает шаг 45, объём перепроверки — шаг 44.
    """
    итоги = tuple(итоги)
    return bool(итоги) and all(итог.статус == ПРОШЛО for итог in итоги)


def свод(итоги) -> dict:
    итоги = tuple(итоги)
    return {
        "версия": RECHECK_VERSION,
        "правил": len(итоги),
        "прошло": sum(1 for и in итоги if и.статус == ПРОШЛО),
        "нарушено": sum(1 for и in итоги if и.статус == НАРУШЕНО),
        "неизвестно": sum(1 for и in итоги if и.статус == НЕИЗВЕСТНО),
        "перепроверка_пройдена": перепроверка_пройдена(итоги),
        "не_доказывает": list(ЧЕГО_НЕ_ДОКАЗЫВАЕТ_СОВПАДЕНИЕ),
        "результаты": [и.as_json() for и in итоги],
    }


