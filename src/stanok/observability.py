# -*- coding: utf-8 -*-
"""Наблюдаемость этапов: что видно снаружи о работе станка.

Шаг 63 плана. Нормативная основа — чертёж v3.0, раздел 19: «минимальный журнал
этапа: run_id, stage_id, попытка; время начала и окончания; версии кода,
модели, шаблона, справочника и политики; количество входных и выходных
объектов; потребление памяти и процессора; код результата и структурированная
причина; идентификатор безопасного повтора; ссылки на манифест без раскрытия
лишних данных».

**Зачем это.** Клиент говорит «у вас всё сломалось». Наблюдаемость — то, чем
можно ответить, где именно, не переспрашивая его и не прося прислать документ
ещё раз. Без неё разбор жалобы начинается с «пришлите файл», а это и долго, и
для клиента унизительно.

## Содержимого документов здесь нет и быть не может

Наблюдаемость **уходит наружу**: в отчёт клиенту, в переписку с поддержкой, в
чужие руки. Поэтому правило жёсткое и проверяемое устройством, а не обещанием:

* **можно** — счётчики, длительности, версии, коды результата, имена этапов;
* **нельзя** — суммы, контрагенты, назначения платежей, любые значения полей и
  любой кусок текста документа.

Принуждается это не запретом слов, а **разрешением видов**: значение
наблюдения обязано быть числом, признаком либо короткой строкой из
объявленного вида — код, версия, имя этапа, отпечаток. Всё прочее отвергается.
Запрещать перечислением было бы слабее: перечень запретов всегда неполон, а
перечень разрешённого закрыт.

## Границы роста журналов

Здесь же закрывается то, что шаг 58 назвал открытым. Журнал добавляемый и
растёт без предела; на потоке это станет бедой через месяц.

Решение: журнал **режется на части** по объявленному пределу. Цепь при этом не
рвётся — новая часть начинается записью-переносом, которая называет вершину
прежней части и её имя. Проверка идёт по частям и по стыкам между ними.

Чего решение **не** делает: ничего не удаляет. Удаление — не техническая
мелочь, а решение владельца о сроке хранения свидетельств, и станок его не
принимает за него.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import journal


OBSERVABILITY_VERSION = "stage-observability/1"

# Что вообще можно положить в наблюдение. Перечень закрыт.
ЧИСЛОВЫЕ = ("объектов_на_входе", "объектов_на_выходе", "записей", "решений",
            "длительность_мс", "память_байт", "процессор_мс", "страниц",
            "попытка", "отказов")
СТРОКОВЫЕ = ("этап", "код_результата", "причина_код", "маршрут", "движок",
             "версия_кода", "версия_оснастки", "версия_политики",
             "версия_справочника", "run_id", "ключ_повтора", "манифест",
             "начато", "кончено", "document_id")
ПРИЗНАКОВЫЕ = ("получилось",)

РАЗРЕШЕНО = frozenset((*ЧИСЛОВЫЕ, *СТРОКОВЫЕ, *ПРИЗНАКОВЫЕ))

# Короткая строка объявленного вида: код, версия, имя этапа, отпечаток, время.
# Ни сумма, ни имя контрагента, ни назначение платежа под это не подходят.
_ВИД_СТРОКИ = re.compile(r"^[A-Za-zА-Яа-яЁё0-9 _\-./:+@\[\]]{0,64}$")
_ЕСТЬ_БУКВА = re.compile(r"[A-Za-zА-Яа-яЁё]")
_ОТПЕЧАТОК = re.compile(r"^[0-9a-f]{0,64}$")
_ОТПЕЧАТКИ = ("document_id", "ключ_повтора", "run_id", "манифест")
_ПРЕДЕЛ_СТРОКИ = 64

KNOWN_LIMITATIONS = (
    "Наблюдение описывает работу станка, а не документ: по нему видно, где "
    "сломалось, но не что было в бумаге. Это не недостаток, а условие того, "
    "что наблюдаемость можно показать наружу.",
    "Длительности берутся часами машины — в отличие от времени ручного труда "
    "(шаг 61). Здесь это верно: станок мерит свою же работу, а не чужую.",
    "Резка журнала на части ничего не удаляет. Срок хранения свидетельств — "
    "решение владельца, и станок не принимает его за него.",
    "Имя этапа приходит из конвейера как есть. Появится этап, названный "
    "содержимым документа, — и запрет его пропустит: он смотрит на значения, "
    "а имена этапов объявляет разработчик, а не документ.",
)


class НаблюдениеНегодно(ValueError):
    """Наблюдение не может быть выпущено наружу: сказано, почему."""


def _проверить_значение(ключ: str, значение) -> None:
    if ключ not in РАЗРЕШЕНО:
        raise НаблюдениеНегодно(
            f"поля {ключ!r} нет в перечне наблюдаемого. Перечень закрыт "
            "нарочно: запреты всегда неполны, а разрешённое — счётно")
    if ключ in ЧИСЛОВЫЕ:
        if isinstance(значение, bool) or not isinstance(значение, int):
            raise НаблюдениеНегодно(
                f"{ключ}: ожидается целое число, а подано {type(значение).__name__}")
        if значение < 0:
            raise НаблюдениеНегодно(f"{ключ}: отрицательный счёт бессмыслен")
        return
    if ключ in ПРИЗНАКОВЫЕ:
        if not isinstance(значение, bool):
            raise НаблюдениеНегодно(f"{ключ}: ожидается признак «да» или «нет»")
        return
    if значение is None:
        return
    if not isinstance(значение, str):
        raise НаблюдениеНегодно(
            f"{ключ}: ожидается короткая строка объявленного вида")
    if len(значение) > _ПРЕДЕЛ_СТРОКИ or not _ВИД_СТРОКИ.match(значение):
        raise НаблюдениеНегодно(
            f"{ключ}: строка не похожа на код, версию или имя этапа. "
            "Содержимое документа наружу не выходит: ни сумм, ни контрагентов, "
            "ни назначений")
    if ключ in _ОТПЕЧАТКИ:
        # Отпечаток — шестнадцатеричное имя, а не содержимое: по нему документ
        # не восстановить. Проверяется он строже прочих именно поэтому.
        if not _ОТПЕЧАТОК.match(значение):
            raise НаблюдениеНегодно(
                f"{ключ}: ожидается шестнадцатеричный отпечаток")
        return
    if значение and not _ЕСТЬ_БУКВА.search(значение):
        # Строка без единой буквы — это число: сумма, счёт, ИНН, номер карты.
        # Кодов и версий без букв не бывает, а данные без букв бывают сплошь.
        raise НаблюдениеНегодно(
            f"{ключ}: строка из одних цифр и разделителей — это данные, а не "
            "код. Наружу выходят счётчики, а не номера и суммы")


@dataclass(frozen=True, slots=True)
class Наблюдение:
    """Что видно об одном этапе. Содержимого документа тут нет по устройству."""

    этап: str
    получилось: bool
    объектов_на_входе: int = 0
    объектов_на_выходе: int = 0
    длительность_мс: int = 0
    код_результата: str = "OK"
    причина_код: str | None = None
    маршрут: str | None = None
    версия_кода: str = ""
    версия_оснастки: str = ""
    версия_политики: str = ""
    run_id: str = ""
    ключ_повтора: str = ""
    document_id: str = ""
    попытка: int = 1

    def __post_init__(self) -> None:
        for ключ, значение in self.as_json().items():
            if ключ in ("версия", "schema_version"):
                continue
            _проверить_значение(ключ, значение)

    def as_json(self) -> dict:
        return {
            "этап": self.этап,
            "получилось": self.получилось,
            "объектов_на_входе": self.объектов_на_входе,
            "объектов_на_выходе": self.объектов_на_выходе,
            "длительность_мс": self.длительность_мс,
            "код_результата": self.код_результата,
            "причина_код": self.причина_код,
            "маршрут": self.маршрут,
            "версия_кода": self.версия_кода,
            "версия_оснастки": self.версия_оснастки,
            "версия_политики": self.версия_политики,
            "run_id": self.run_id,
            "ключ_повтора": self.ключ_повтора,
            "document_id": self.document_id,
            "попытка": self.попытка,
        }

    def для_журнала(self) -> dict:
        свой = {"schema_version": OBSERVABILITY_VERSION}
        свой.update(self.as_json())
        return свой


def проверить_чистоту(наблюдения) -> None:
    """Роняет отказом, если в наблюдения затесалось содержимое документа."""
    for наблюдение in наблюдения:
        свои = (наблюдение.as_json() if hasattr(наблюдение, "as_json")
                else dict(наблюдение))
        for ключ, значение in свои.items():
            if ключ in ("schema_version", "версия"):
                continue
            _проверить_значение(ключ, значение)


# ------------------------------------------------- из проводки


_КОДЫ_ЭТАПОВ = {True: "OK", False: "E_STAGE_FAILED"}


def из_проводки(проводка, *, версия_кода: str = "", версия_оснастки: str = "",
                версия_политики: str = "", run_id: str = "",
                ключ_повтора: str = "", длительности=None) -> tuple:
    """Наблюдения по всем этапам проводки. Берёт счёт, а не содержимое.

    Из журнала проводки сюда идут **имя этапа и удался ли он**; всё остальное —
    счётчики, взятые у самой проводки. Свободный текст этапа («сказано») не
    берётся вовсе: он писан для человека и однажды принесёт наружу то, чего там
    быть не должно.
    """
    длительности = длительности or {}
    паспорт = getattr(проводка, "паспорт", None)
    document_id = (getattr(паспорт, "document_id", "") or "")[:64]
    объектов = len(getattr(проводка, "объекты", ()))
    записей = len(getattr(проводка, "записи", ()))
    решений = len(getattr(проводка, "решения", ()))

    на_выходе = {
        "извлечение": объектов,
        "сегментация": объектов,
        "границы операций": записей,
        "типизация": записей,
        "решение": решений,
    }
    отказы = {о.code for о in getattr(паспорт, "refusals", ()) or ()}
    наблюдения = []
    for место, этап in enumerate(getattr(проводка, "журнал", ()), start=1):
        код = _КОДЫ_ЭТАПОВ[bool(этап.получилось)]
        причина = None
        if not этап.получилось and отказы:
            причина = sorted(отказы)[0]
        наблюдения.append(Наблюдение(
            этап=этап.имя[:_ПРЕДЕЛ_СТРОКИ],
            получилось=bool(этап.получилось),
            объектов_на_входе=объектов if место > 1 else 0,
            объектов_на_выходе=на_выходе.get(этап.имя, 0),
            длительность_мс=int(длительности.get(этап.имя, 0)),
            код_результата=код,
            причина_код=причина,
            версия_кода=версия_кода,
            версия_оснастки=версия_оснастки,
            версия_политики=версия_политики,
            run_id=run_id,
            ключ_повтора=ключ_повтора,
            document_id=document_id))
    return tuple(наблюдения)


def свод(наблюдения) -> dict:
    """Короткий ответ на вопрос «где сломалось»."""
    наблюдения = tuple(наблюдения)
    сорвалось = [н for н in наблюдения if not н.получилось]
    return {
        "версия": OBSERVABILITY_VERSION,
        "этапов": len(наблюдения),
        "сорвалось": len(сорвалось),
        "первый_сорвавшийся": сорвалось[0].этап if сорвалось else None,
        "код_первого": сорвалось[0].код_результата if сорвалось else None,
        "причина_первого": сорвалось[0].причина_код if сорвалось else None,
        "объектов": max((н.объектов_на_выходе for н in наблюдения), default=0),
        "длительность_мс": sum(н.длительность_мс for н in наблюдения),
    }


# ------------------------------------------- границы роста журнала


ПЕРЕНОС = "перенос части"
ПРЕДЕЛ_ЧАСТИ_БАЙТ = 32 * 1024 * 1024
"""Сколько весит часть журнала, прежде чем начнётся следующая.

Тридцать два мегабайта — это порядка сорока тысяч событий действий оператора:
месяц потока при тысяче документов в день. Число объявлено здесь, а не спрятано
в вызове: менять его — решение, а не настройка вызова.
"""


def части(путь) -> tuple[Path, ...]:
    """Все части журнала по порядку: сам файл и его нарезки."""
    место = Path(путь)
    свои = [место] if место.exists() else []
    свои.extend(sorted(место.parent.glob(f"{место.stem}.часть-*{место.suffix}")))
    return tuple(свои)


def нарезать(путь, предел_байт: int = ПРЕДЕЛ_ЧАСТИ_БАЙТ, схема=None) -> Path | None:
    """Отрезает выросшую часть журнала и начинает новую. Ничего не удаляет.

    Цепь не рвётся: новая часть начинается записью-переносом, которая называет
    вершину прежней части и её имя. По этой записи проверка проходит стык между
    частями так же, как проходит его внутри части.
    """
    место = Path(путь)
    if not место.exists() or место.stat().st_size < предел_байт:
        return None
    схема = схема or journal.нормализовать_событие
    вершина = journal.verify_journal(место, схема=схема)
    номер = 1 + len(list(место.parent.glob(f"{место.stem}.часть-*{место.suffix}")))
    отрезанная = место.with_name(f"{место.stem}.часть-{номер:03d}{место.suffix}")
    место.rename(отрезанная)
    journal.append_record(место, {
        "schema_version": OBSERVABILITY_VERSION,
        "род": ПЕРЕНОС,
        "прежняя_часть": отрезанная.name,
        "прежняя_вершина": вершина,
        "номер_части": номер,
    }, схема=схема)
    return отрезанная


def проверить_части(путь, схема=None) -> dict:
    """Проверяет каждую часть и стыки между ними.

    Стык — не формальность: без него нарезка стала бы тем самым способом
    незаметно оборвать цепь, от которого журнал и защищает.
    """
    схема = схема or journal.нормализовать_событие
    место = Path(путь)
    нарезки = sorted(место.parent.glob(f"{место.stem}.часть-*{место.suffix}"))
    порядок = [*нарезки, место] if место.exists() else list(нарезки)
    проверено, стыки = [], []
    прежняя_вершина = None
    for часть in порядок:
        вершина = journal.verify_journal(часть, схема=схема)
        первая = None
        for строка in часть.read_bytes().split(b"\n"):
            if строка.strip():
                первая = json.loads(строка.decode("utf-8"))
                break
        if прежняя_вершина is not None:
            если_перенос = (первая or {}).get("род") == ПЕРЕНОС
            сошлось = (первая or {}).get("прежняя_вершина") == прежняя_вершина
            стыки.append({"часть": часть.name, "перенос": если_перенос,
                          "сошлось": bool(если_перенос and сошлось)})
            if not (если_перенос and сошлось):
                raise journal.JournalError(
                    "E_PART_LINK_BROKEN",
                    f"стык частей не сошёлся: {часть.name} не продолжает "
                    "прежнюю вершину")
        проверено.append({"часть": часть.name, "вершина": вершина})
        прежняя_вершина = вершина
    return {"версия": OBSERVABILITY_VERSION, "частей": len(проверено),
            "части": проверено, "стыки": стыки}


