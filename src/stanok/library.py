class ВыпускНевозможен(RuntimeError):
    """Черновик не стал выпуском: названо, чего не хватает."""


class ШаблонНеНайден(LookupError):
    """В библиотеке нет подходящего шаблона: названо, чего искали."""


# --------------------------------------------------------------- запись


@dataclass
class Запись:
    """Один шаблон в библиотеке и его путь от черновика до выпуска."""

    семейство: str
    версия: str
    уровень: str
    состояние: str = ЗАВЕДЁН
    клиент: str = ""
    объявление: dict = field(default_factory=dict)
    проба: dict | None = None
    согласование: dict | None = None
    пакет: str = ""
    отпечаток: str = ""
    подпись: dict | None = None
    заведён: str = ""
    выпущен: str = ""
    в_архиве_с: str = ""

    @property
    def выдаётся_в_работу(self) -> bool:
        """Черновик и архив в работу не выдаются никогда."""
        return self.состояние == ВЫПУЩЕН and self.уровень in СТАРШИНСТВО

    def as_json(self) -> dict:
        return {"версия_записи": LIBRARY_VERSION, "семейство": self.семейство,
                "версия": self.версия, "уровень": self.уровень,
                "состояние": self.состояние, "клиент": self.клиент,
                "проба": self.проба, "согласование": self.согласование,
                "пакет": self.пакет, "отпечаток": self.отпечаток,
                "подпись": self.подпись, "заведён": self.заведён,
                "выпущен": self.выпущен, "в_архиве_с": self.в_архиве_с}


def _сейчас() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def завести_черновик(объявление: dict, *, уровень: str = ОБЩИЙ,
                     клиент: str = "", когда: str = "") -> Запись:
    """Заводит черновик. Ни в работу, ни в выпуск он пока не годится."""
    if уровень not in (ОБЩИЙ, КЛИЕНТСКИЙ):
        raise ВыпускНевозможен(
            f"черновик заводится общим или клиентским, а не {уровень!r}")
    if уровень == КЛИЕНТСКИЙ and not клиент.strip():
        raise ВыпускНевозможен(
            "клиентский шаблон без имени клиента невозможен: по нему его и "
            "находят")
    опознание = (объявление or {}).get("идентификация") or {}
    семейство = str(опознание.get("семейство") or "не названо")
    версия = f"{семейство}/{опознание.get('версия_формы') or '1'}"
    return Запись(семейство=семейство, версия=версия, уровень=уровень,
                  состояние=ЗАВЕДЁН, клиент=клиент.strip(),
                  объявление=dict(объявление or {}), заведён=когда or _сейчас())


def приложить_пробу(запись: Запись, проба) -> Запись:
    """Прикладывает пробу шага 84. Без неё утверждать нечего."""
    свой = проба.as_json() if hasattr(проба, "as_json") else dict(проба)
    if not свой.get("это_проба"):
        raise ВыпускНевозможен(
            "это не проба: пометка пробы обязательна, иначе утверждение об "
            "итогах будет прочитано как утверждение о документе")
    if not свой.get("строк"):
        raise ВыпускНевозможен(
            "проба пуста: на нуле операций утверждать нечего")
    запись.проба = свой
    запись.состояние = С_ПРОБОЙ
    return запись


def утвердить(запись: Запись, согласование) -> Запись:
    """Принимает согласование шага 84. Своей отметки «согласовано» здесь нет."""
    свой = (согласование.as_json() if hasattr(согласование, "as_json")
            else dict(согласование))
    if not свой.get("кем"):
        raise ВыпускНевозможен(
            "согласование без имени согласовавшего не принимается")
    если_версия = свой.get("версия_шаблона")
    if str(если_версия) not in (запись.версия, запись.версия.split("/")[-1]):
        raise ВыпускНевозможен(
            f"{СОГЛАСОВАНО_ДРУГОЕ}: согласована версия {если_версия!r}, а "
            f"выпускается {запись.версия!r}. Согласовали одно, выпускают "
            "другое — это не выпуск, а подмена")
    if запись.проба is None:
        запись.проба = свой.get("проба")
    запись.согласование = свой
    запись.состояние = УТВЕРЖДЁН
    return запись


def выпустить(запись: Запись, куда, *, тайный=None, открытый=None,
              кем: str = "", когда: str = "",
              наименьшее_ядро: str = "1") -> Запись:
    """Собирает и подписывает пакет. Без согласования не выпускает.

    Сборка — шага 70, подпись — шага 74. Здесь только порядок и запрет.
    """
    if запись.состояние != УТВЕРЖДЁН:
        raise ВыпускНевозможен(
            f"{ВЫПУСК_БЕЗ_СОГЛАСОВАНИЯ}: шаблон в состоянии "
            f"«{запись.состояние}». Черновик не может стать выпуском, минуя "
            "согласование: выпускать нечего, пока никто не согласовал")
    if запись.согласование is None:
        raise ВыпускНевозможен(
            f"{ВЫПУСК_БЕЗ_СОГЛАСОВАНИЯ}: события согласования нет")

    куда = Path(куда)
    куда.parent.mkdir(parents=True, exist_ok=True)
    путь = пакеты.собрать(запись.объявление, куда,
                          наименьшее_ядро=наименьшее_ядро)
    опись = пакеты.прочитать_опись(путь)
    запись.пакет = str(путь)
    запись.отпечаток = опись.отпечаток
    запись.состояние = ВЫПУЩЕН
    запись.выпущен = когда or _сейчас()

    if тайный is not None and открытый is not None:
        from . import delivery as поставка

        запись.подпись = поставка.подписать_изделие(
            путь, тайный, открытый, кем or "не назван", запись.выпущен)
    return запись


# --------------------------------------------------------------- библиотека


@dataclass
class Библиотека:
    """Четыре уровня шаблонов. Удаления здесь нет вовсе."""

    где: Path
    записи: list = field(default_factory=list)

    # ------------------------------------------------------- хранение

    @property
    def опись(self) -> Path:
        return Path(self.где) / "biblioteka.json"

    def положить(self, запись: Запись) -> Запись:
        if запись.состояние != ВЫПУЩЕН and запись.уровень in СТАРШИНСТВО:
            # Черновик кладётся черновиком, а не общим: иначе его однажды
            # выдадут в работу.
            запись.уровень = ЧЕРНОВИК
        self.записи.append(запись)
        return запись

    def записать(self) -> Path:
        Path(self.где).mkdir(parents=True, exist_ok=True)
        self.опись.write_text(json.dumps(
            {"версия": LIBRARY_VERSION,
             "записи": [з.as_json() for з in self.записи]},
            ensure_ascii=False, indent=1), encoding="utf-8")
        return self.опись

    # ------------------------------------------------------- поиск

    def найти(self, семейство: str, клиент: str = "") -> Запись:
        """Клиентский старше общего. Черновик и архив не выдаются."""
        свои = [з for з in self.записи
                if з.семейство == семейство and з.выдаётся_в_работу]
        for уровень in СТАРШИНСТВО:
            for запись in свои:
                if запись.уровень != уровень:
                    continue
                if уровень == КЛИЕНТСКИЙ and запись.клиент != клиент:
                    continue
                return запись
        raise ШаблонНеНайден(
            f"{ШАБЛОНА_НЕТ}: для семейства {семейство!r}"
            + (f" и клиента {клиент!r}" if клиент else "")
            + " выпущенного шаблона нет. Черновики и архив в работу не "
              "выдаются")

    def по_версии(self, версия: str) -> tuple[Запись, ...]:
        """Ищет по версии среди **всех** уровней, включая архив."""
        return tuple(з for з in self.записи if з.версия == версия)

    def в_архив(self, запись: Запись, когда: str = "") -> Запись:
        """Переводит выпуск в архив. Из библиотеки он при этом не исчезает."""
        запись.уровень = АРХИВНЫЙ
        запись.в_архиве_с = когда or _сейчас()
        return запись

    def свод(self) -> dict:
        по_уровням = {у: sum(1 for з in self.записи if з.уровень == у)
                      for у in УРОВНИ}
        return {"версия": LIBRARY_VERSION, "записей": len(self.записи),
                "по_уровням": по_уровням,
                "удаление_есть": False,
                "клиентский_старше_общего": True}

    # ------------------------------------------------------- выдача ядру

    def выдать_ядру(self, семейство: str, версия_ядра: str,
                    клиент: str = ""):
        """Отдаёт оснастку ядру через правило шага 38.

        Пакет, требующий ядра новее, даёт отказ с причиной. Библиотека этого
        правила не повторяет — она его зовёт, и потому смягчить его не может.
        """
        запись = self.найти(семейство, клиент)
        return пакеты.поставить(запись.пакет, версия_ядра=версия_ядра)


def прочитать(где) -> Библиотека:
    """Читает библиотеку с диска. Архивные записи читаются наравне с прочими."""
    своя = Библиотека(где=Path(где))
    if не_читается(своя.опись):
        return своя
    свой = json.loads(своя.опись.read_text(encoding="utf-8"))
    for запись in свой.get("записи", ()):
        своя.записи.append(Запись(
            семейство=запись.get("семейство", ""),
            версия=запись.get("версия", ""),
            уровень=запись.get("уровень", ЧЕРНОВИК),
            состояние=запись.get("состояние", ЗАВЕДЁН),
            клиент=запись.get("клиент", ""),
            проба=запись.get("проба"),
            согласование=запись.get("согласование"),
            пакет=запись.get("пакет", ""),
            отпечаток=запись.get("отпечаток", ""),
            подпись=запись.get("подпись"),
            заведён=запись.get("заведён", ""),
            выпущен=запись.get("выпущен", ""),
            в_архиве_с=запись.get("в_архиве_с", "")))
    return своя


def не_читается(путь: Path) -> bool:
    return not Path(путь).is_file()


def чем_разбирали(библиотека: Библиотека, семейство: str,
                  когда: str) -> tuple[Запись, ...]:
    """Чем разбирали в такой-то день. Архив для того и держится.

    Возвращает выпуски этого семейства, действовавшие на названный день:
    выпущенные не позже него и не ушедшие в архив раньше.
    """
    свои = []
    for запись in библиотека.записи:
        if запись.семейство != семейство or запись.состояние != ВЫПУЩЕН:
            continue
        if запись.выпущен and запись.выпущен[:10] > когда[:10]:
            continue
        if запись.в_архиве_с and запись.в_архиве_с[:10] < когда[:10]:
            continue
        свои.append(запись)
    return tuple(свои)


# --------------------------------------------------------------- показ


def _т(значение) -> str:
    return обезвредить(значение)


_ЦВЕТ = {КЛИЕНТСКИЙ: "t-zel", ОБЩИЙ: "t-zel", ЧЕРНОВИК: "t-zhel",
         АРХИВНЫЙ: "t-ser"}


def путь_html(запись: Запись) -> str:
    """Путь черновика до выпуска — четыре шага, и видно, где мы."""
    куски = ['<div class="lenta">']
    место = ПУТЬ_ВЫПУСКА.index(запись.состояние)
    for номер, шаг in enumerate(ПУТЬ_ВЫПУСКА):
        точка = ("t-zel" if номер < место else
                 "t-zhel" if номер == место else "t-ser")
        куски.append(f'<span class="shag"><span class="tochka {точка}"></span>'
                     f"{_т(шаг)}</span>")
    куски.append("</div>")
    return "".join(куски)


def библиотека_html(библиотека: Библиотека) -> str:
    """Библиотека уровней: что есть, чем выдаётся и что в архиве."""
    строки = ['<table class="dok"><tr><th>Семейство</th><th>Версия</th>'
              "<th>Уровень</th><th>Клиент</th><th>Состояние</th>"
              "<th>Выдаётся</th></tr>"]
    for з in библиотека.записи:
        точка = _ЦВЕТ.get(з.уровень, "t-ser")
        строки.append(
            f"<tr><td>{_т(з.семейство)}</td><td><code>{_т(з.версия)}</code>"
            f'</td><td><span class="tochka {точка}"></span>{_т(з.уровень)}</td>'
            f"<td>{_т(з.клиент) or '—'}</td><td>{_т(з.состояние)}</td>"
            f"<td>{'да' if з.выдаётся_в_работу else 'нет'}</td></tr>")
    строки.append("</table>")
    строки.append('<div class="tih">Клиентский вариант старше общего: у клиента '
                  "может быть свой вариант формы того же банка. Черновик и "
                  "архив в работу не выдаются никогда, но и не исчезают: по "
                  "архивному разбираются, когда спрашивают, чем разбирали "
                  "полгода назад.</div>")
    return "".join(строки)


def свод() -> dict:
    return {"версия": LIBRARY_VERSION,
            "уровни": list(УРОВНИ),
            "старшинство": list(СТАРШИНСТВО),
            "путь_выпуска": list(ПУТЬ_ВЫПУСКА),
            "удаление_есть": False,
            "выпуск_без_согласования": False,
            "отказ_от_чужой_версии": "правило шага 38, вызывается, а не "
                                     "повторяется"}


