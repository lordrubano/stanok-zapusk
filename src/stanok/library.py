    "правку описи руками станок не обнаружит. Доказательная сила у события "
    "согласования (шаг 58) и у подписи (шаг 74), а у описи — рабочая.",
    "Клиентский вариант старше общего по устройству. Случая, когда клиенту "
    "нужен именно общий вариант при наличии своего, библиотека не "
    "рассматривает: такой случай означал бы, что клиентский вариант заведён "
    "зря.",
    "Удаления в библиотеке нет вовсе. Место на диске она поэтому только "
