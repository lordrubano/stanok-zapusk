# -*- coding: utf-8 -*-
"""Разбор по кнопке: положенный файл становится разобранным документом.

Между приёмом и экранами разбора зияла дыра: файл принимался и оставался
лежать — «прогон не начат», — а запустить его было нечем. Показывать разбор
станок умел только для того документа, который назван ему в командной строке
при запуске. Здесь эта дыра закрыта.

## Чем оснастка выбирается

Не человеком и не порядком файлов в папке, а **опознанием формы**: у каждого
семейства объявлены признаки выбора, и документ спрашивается ими. Признали
своим двое — отказ с обоими именами: выбрать наугад значило бы молча решить,
чем разбирать. Не признал никто — тоже отказ, и сказано, чем именно каждая не
подошла.

## Чем платим

Текст для опознания извлекается **до** разбора, отдельным заходом, — а потом
конвейер извлекает его снова для себя. Это лишняя работа: на выписке в 51
страницу около трёх секунд. Названо прямо, а не спрятано: убрать её можно,
только научив конвейер брать оснастку по ходу, а это меняет его устройство.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

RAZBOR_VERSION = "razbor/1"


class РазборНеНачался(ValueError):
    """Разбор не начат: нечем, не на чем или не с чем."""

    код = "E_PARSE_NOT_STARTED"


@dataclass(frozen=True, slots=True)
class Итог:
    """Чем кончился разбор по кнопке."""

    проводка: object
    оснастка: object
    прогон: Path
    объяснения: tuple[str, ...] = ()

    @property
    def записей(self) -> int:
        return len(getattr(self.проводка, "записи", ()) or ())


def оснастки_из(папка) -> tuple[object, ...]:
    """Оснастки, лежащие в папке: собранные пакеты и объявления семейств.

    Негодная оснастка пропускается молча только в одном смысле — она не
    останавливает остальные; но и своим документ она не признает, и в
    объяснениях её не будет. Это осознанный выбор: одна испорченная оснастка в
    папке не должна лишать оператора работы с остальными.
    """
    from .package import ПакетНегоден, поставить
    from .tooling import ОснасткаНегодна, загрузить

    место = Path(папка)
    if not место.is_dir():
        return ()
    свои = []
    for путь in sorted(место.iterdir()):
        try:
            if путь.suffix.lower() == ".zip":
                свои.append(поставить(путь, "1"))
            elif путь.suffix.lower() == ".json":
                свои.append(загрузить(json.loads(
                    путь.read_text(encoding="utf-8"))))
        except (ПакетНегоден, ОснасткаНегодна, OSError, ValueError):
            continue
    return tuple(свои)


def _текст_документа(путь, розетка) -> str:
    """Текст для опознания. Отдельным заходом — см. «Чем платим» наверху."""
    from .intake import accept_file

    свой = Path(путь)
    паспорт = accept_file(свой)
    извлечение = розетка.извлечь(паспорт, свой.read_bytes())
    return " ".join(о.сырой_текст or "" for о in getattr(извлечение, "объекты", ()))


def разобрать(документ, *, оснастки=(), куда, политика=None, розетка=None,
              отметчик=None, имя_документа: str = "") -> Итог:
    """Разбирает документ и кладёт прогон рядом с партией.

    Оснастка выбирается опознанием; не выбралась — отказ, и разбор не идёт
    вовсе. Приложить чужие правила к документу хуже, чем не разобрать его:
    правдоподобный разбор чужого — худший из исходов, и это правило шага 29.
    """
    from . import progon as хранение
    from .adapter_pdf import РазборPDF
    from .adapters import Розетка
    from .pipeline import провести
    from .tooling import выбрать_по_форме

    свой = Path(документ)
    if not свой.is_file():
        raise РазборНеНачался(f"{РазборНеНачался.код}: файла нет: {свой}")
    if not оснастки:
        raise РазборНеНачался(
            f"{РазборНеНачался.код}: ни одной оснастки не найдено. Станок "
            "разбирает только те формы, для которых есть шаблон семейства")

    если_розетка = розетка
    if если_розетка is None:
        если_розетка = Розетка()
        если_розетка.подключить(РазборPDF())

    текст = _текст_документа(свой, если_розетка)
    выбрана, объяснения = выбрать_по_форме(оснастки, текст)
    if выбрана is None:
        raise РазборНеНачался(
            f"{РазборНеНачался.код}: форма документа не опознана. "
            + "; ".join(объяснения))

    проводка = провести(свой, оснастка=выбрана, политика=политика,
                        розетка=если_розетка, отметчик=отметчик)
    путь = хранение.сохранить(проводка, куда,
                              документ=имя_документа or свой.name,
                              оснастка=выбрана.версия)
    return Итог(проводка, выбрана, путь, tuple(объяснения))


def свод() -> dict:
    return {"версия": RAZBOR_VERSION,
            "оснастка_выбирается": "опознанием формы (признаки выбора)",
            "двое_подошли": "отказ: выбирать наугад нельзя",
            "никто_не_подошёл": "отказ с объяснением по каждой оснастке",
            "лишнее_извлечение": "да, один раз для опознания"}


