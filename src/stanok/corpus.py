# -*- coding: utf-8 -*-
"""Разделение корпуса на наборы: обучающий, калибровочный, закрытый.

Шаг 47 плана. Нормативная основа — чертёж v3.0, раздел 16.1 («документы и
производные одного исходника не пересекаются между наборами»; «исправление
шаблона не изменяет закрытый эталон задним числом») и раздел 16.2 («тысячи строк
одной выписки не считаются тысячами независимых испытаний»).

**Правило строится до появления корпуса намеренно.** Разложить документы «как
придётся» можно ровно один раз: после того как закрытый набор увидел станок,
закрытым он уже не станет, и никакая перекладка этого не вернёт.

## Что считать источником

Не файл и не период. **Источник — это счёт в банке.**

* **период** — то, чем документы одного счёта **различаются**, а не то, чем они
  тождественны. Разделить по периоду значило бы разложить по разным наборам две
  выписки одного счёта за соседние месяцы — с теми же контрагентами, теми же
  назначениями, той же вёрсткой. Закрытый набор перестал бы проверять, а
  измеренная доля ошибок оказалась бы завышенной: станок узнавал бы уже
  виденное;
* **файл** — слишком мелко ровно по той же причине;
* **банк** — слишком крупно: пока банк один, деления не выйдет вовсе, а
  раздельность банков и без того обеспечена, если счета в них разные;
* **счёт в банке** — то, что нужно. Две выписки одного счёта неразделимы; счета
  разных владельцев независимы настолько, насколько независимы их контрагенты.

## Родство сверх источника

Два счёта одного владельца — разные источники, но не независимые: у них общие
контрагенты, общие назначения платежей, общий бухгалтер, набирающий текст.
Поэтому счета одного владельца **связаны** и попадают в один набор целиком.
Семейство вправе объявить иначе, но только с основанием.

Связанные источники образуют **гроздь**, и в набор попадает гроздь целиком.
Делится не документ и не счёт, а гроздь.

## Закрытый набор

Он не показывается станку до последнего прогона, и запрет здесь сделан так,
чтобы **его нельзя было обойти по невнимательности**:

1. документы закрытого набора не лежат ни в одном поле, по которому можно
   пройти циклом: обращение к ним поднимает отказ;
2. перебор разделения выдаёт только открытые наборы — случайное «для набора в
   разделении» до закрытого не дойдёт;
3. в отчётном виде разделения нет ни путей, ни имён закрытого набора — только
   счётчики и отпечатки;
4. вскрытие требует имени, основания и времени, записывается навсегда, и всякий
   последующий отчёт говорит, что набор вскрыт;
5. у закрытого набора есть **печать** — отпечаток его состава. Изменился состав
   — печать не сходится, и это видно: раздел 16.1 запрещает менять закрытый
   эталон задним числом;
6. отдельная проверка чистоты сличает то, что станок видел, с закрытым набором и
   называет утечку поимённо.

Ни одно из шести не защищает от злого умысла — от него защищает не код. Все
шесть защищают от невнимательности, а она случается чаще.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation


CORPUS_VERSION = "corpus-split/1"

ОБУЧАЮЩАЯ = "обучающая"
КАЛИБРОВОЧНАЯ = "калибровочная"
ЗАКРЫТАЯ = "закрытая"
ЧАСТИ = (ОБУЧАЮЩАЯ, КАЛИБРОВОЧНАЯ, ЗАКРЫТАЯ)

# Доли по умолчанию. Числа умозрительные и объявлены таковыми: сколько именно
# нужно закрытому набору, покажет правило трёх на измеренной доле ошибок, а не
# соображения удобства.
ДОЛИ_ПО_УМОЛЧАНИЮ = {ОБУЧАЮЩАЯ: "0.50", КАЛИБРОВОЧНАЯ: "0.25", ЗАКРЫТАЯ: "0.25"}

KNOWN_LIMITATIONS = (
    "Источником назван счёт в банке. У семейства, где один счёт ведётся в "
    "нескольких валютах отдельными выписками, это придётся уточнить: такие "
    "выписки — один источник, а не разные.",
    "Родство определяется владельцем счёта. Родство по иным признакам — общий "
    "бухгалтерский подрядчик, одна и та же учётная программа — здесь не "
    "распознаётся и должно объявляться руками.",
    "Доли наборов умозрительны. Сколько нужно закрытому набору, показывает "
    "правило трёх (раздел 17.2) на измеренной доле ошибок, а не удобство.",
    "Печать закрытого набора — отпечаток состава, а не подпись ключом. Она "
    "ловит незаметную правку, а не подмену доверенным лицом.",
    "Ни один настоящий корпус через это правило не проходил: корпуса нет. "
    "Проверено оно на двух настоящих документах и на построенных образцах.",
)


class КорпусНеделим(ValueError):
    """Корпус нельзя разделить, не нарушив правила.

    Отказ, а не деление кое-как. Разделение, где закрытый набор пуст или где
    гроздь разорвана между наборами, хуже отсутствия разделения: оно выглядит
    как разделение и даёт метрику, которой нельзя верить.
    """

    код = "E_CORPUS_INDIVISIBLE"


class ЗакрытыйНаборЗапечатан(RuntimeError):
    """Попытка заглянуть в закрытый набор до последнего прогона."""

    код = "E_CORPUS_SEALED"


@dataclass(frozen=True, slots=True)
class Документ:
    """Документ корпуса и то, чем он опознаётся как источник."""

    имя: str
    отпечаток: str
    банк: str
    счёт: str
    владелец: str = ""
    период_от: str = ""
    период_до: str = ""

    @property
    def ключ_источника(self) -> str:
        """Счёт в банке. Ни файл, ни период источником не являются."""
        return f"{self.банк}|{self.счёт}"

    def as_json(self) -> dict:
        return {"имя": self.имя, "отпечаток": self.отпечаток,
                "источник": self.ключ_источника, "владелец": self.владелец,
                "период": f"{self.период_от}…{self.период_до}"}


@dataclass(frozen=True, slots=True)
class Гроздь:
    """Связанные источники, которые делить между наборами нельзя."""

    ключ: str
    источники: tuple
    документы: tuple

    @property
    def вес(self) -> int:
        return len(self.документы)

    def as_json(self) -> dict:
        return {"ключ": self.ключ, "источников": len(self.источники),
                "документов": len(self.документы)}


def _доля(значение):
    try:
        число = Decimal(str(значение))
    except (InvalidOperation, TypeError):
        return None
    return число if число.is_finite() and число >= 0 else None


def _отпечаток(куски) -> str:
    материал = "|".join(sorted(куски)).encode("utf-8")
    return hashlib.sha256(материал).hexdigest()[:32]


def грозди(документы, связывать_по_владельцу: bool = True) -> tuple:
    """Собирает документы в грозди связанных источников.

    Гроздь — наименьшее, что можно положить в набор целиком. Разорвать её
    между наборами значит положить в закрытый набор то, что станок уже видел в
    обучающем, и получить завышенную метрику.
    """
    документы = list(документы)
    по_источникам: dict[str, list] = {}
    for документ in документы:
        по_источникам.setdefault(документ.ключ_источника, []).append(документ)

    # Связи: источники одного владельца идут вместе.
    родитель: dict[str, str] = {ключ: ключ for ключ in по_источникам}

    def корень(ключ):
        while родитель[ключ] != ключ:
            родитель[ключ] = родитель[родитель[ключ]]
            ключ = родитель[ключ]
        return ключ

    def связать(а, б):
        ка, кб = корень(а), корень(б)
        if ка != кб:
            родитель[кб] = ка

    if связывать_по_владельцу:
        # Владельцы берутся у **всех** документов источника, а не у первого.
        # Иначе связь решалась бы порядком, в котором документы подали, — и
        # один и тот же корпус делился бы по-разному от перестановки строк.
        по_владельцам: dict[str, set] = {}
        for ключ, свои in по_источникам.items():
            for документ in свои:
                if документ.владелец:
                    по_владельцам.setdefault(документ.владелец, set()).add(ключ)
        for ключи in по_владельцам.values():
            упорядоченные = sorted(ключи)
            for другой in упорядоченные[1:]:
                связать(упорядоченные[0], другой)

    собранные: dict[str, list] = {}
    for ключ in по_источникам:
        собранные.setdefault(корень(ключ), []).append(ключ)

    итог = []
    for _, источники in sorted(собранные.items()):
        свои = [д for ключ in sorted(источники) for д in по_источникам[ключ]]
        итог.append(Гроздь(_отпечаток(источники), tuple(sorted(источники)),
                           tuple(свои)))
    return tuple(sorted(итог, key=lambda г: г.ключ))


@dataclass
class Разделение:
    """Разделённый корпус. К закрытому набору обращаться нельзя."""

    версия: str = CORPUS_VERSION
    зерно: str = ""
    доли: dict = field(default_factory=dict)
    обучающая: tuple = ()
    калибровочная: tuple = ()
    _закрытая: tuple = ()
    печать: str = ""
    вскрыт: bool = False
    вскрытия: tuple = ()

    @property
    def закрытая(self):
        """Закрытый набор. Обращение до вскрытия — отказ.

        Свойство существует именно затем, чтобы невнимательность натыкалась на
        отказ. Молча вернуть пустое было бы хуже: работа пошла бы дальше, и
        никто бы не заметил, что закрытый набор не смотрели вовсе.
        """
        raise ЗакрытыйНаборЗапечатан(
            "закрытый набор не показывается станку до последнего прогона. "
            "Если это и есть последний прогон, откройте его вызовом «вскрыть» "
            "с именем, основанием и временем — вскрытие записывается навсегда")

    def __iter__(self):
        """Перебор разделения выдаёт только открытые наборы.

        Случайное «для набора в разделении» до закрытого не дойдёт — а именно
        так его и задели бы по невнимательности.
        """
        yield ОБУЧАЮЩАЯ, self.обучающая
        yield КАЛИБРОВОЧНАЯ, self.калибровочная

    @property
    def отпечатки_закрытого(self) -> tuple:
        """Отпечатки закрытого набора: по ним ловится утечка, но не читается
        содержимое. Имён и путей здесь нет намеренно."""
        return tuple(sorted(д.отпечаток for д in self._закрытая))

    def вскрыть(self, кто: str, основание: str, когда: str) -> tuple:
        """Открывает закрытый набор. Записывается навсегда."""
        if not (кто and основание and когда):
            raise ЗакрытыйНаборЗапечатан(
                "вскрытие без имени, основания или времени свидетельством не "
                "является: закрытый набор открывают один раз, и известно "
                "должно быть кто и зачем")
        self.вскрыт = True
        self.вскрытия = self.вскрытия + (
            {"кто": кто, "основание": основание, "когда": когда},)
        return self._закрытая

    def как_запечатан(self) -> str:
        return _отпечаток(д.отпечаток for д in self._закрытая)

    @property
    def печать_цела(self) -> bool:
        """Не менялся ли состав закрытого набора после запечатывания.

        Раздел 16.1: исправление шаблона не изменяет закрытый эталон задним
        числом. Печать — способ это заметить.
        """
        return self.печать == self.как_запечатан()

    def as_json(self) -> dict:
        """Отчётный вид. Ни путей, ни имён закрытого набора здесь нет."""
        return {
            "версия": self.версия,
            "зерно": self.зерно,
            "доли": dict(self.доли),
            "обучающая": [д.имя for д in self.обучающая],
            "калибровочная": [д.имя for д in self.калибровочная],
            "закрытая": {"документов": len(self._закрытая),
                         "печать": self.печать,
                         "печать_цела": self.печать_цела},
            "вскрыт": self.вскрыт,
            "вскрытия": list(self.вскрытия),
        }


def разделить(документы, зерно: str, доли=None,
              связывать_по_владельцу: bool = True) -> Разделение:
    """Делит корпус по гроздьям. Не делится — отказывает.

    Деление детерминированное: те же документы с тем же зерном дают то же
    разделение. Иначе повторить испытание было бы нечем, а неповторимое
    испытание доказательством не является.
    """
    if not зерно:
        raise КорпусНеделим(
            "деление без зерна невоспроизводимо: повторить испытание будет нечем")

    свои_доли = {часть: _доля((доли or ДОЛИ_ПО_УМОЛЧАНИЮ).get(часть))
                 for часть in ЧАСТИ}
    if any(з is None for з in свои_доли.values()):
        raise КорпусНеделим("доли наборов объявлены негодно: нужны десятичные "
                            "строки от нуля")
    if свои_доли[ЗАКРЫТАЯ] <= 0:
        raise КорпусНеделим(
            "доля закрытого набора равна нулю: набор, которого нет, ничего не "
            "проверяет, а отчёт выглядел бы так, будто проверка была")

    свои_грозди = грозди(документы, связывать_по_владельцу)
    if len(свои_грозди) < len(ЧАСТИ):
        raise КорпусНеделим(
            f"гроздей связанных источников {len(свои_грозди)}, а наборов "
            f"{len(ЧАСТИ)}: разделить нечего. Две выписки одного счёта — один "
            "источник, и класть их в разные наборы нельзя: закрытый набор "
            "перестал бы проверять, а доля ошибок вышла бы завышенной")

    всего = sum(г.вес for г in свои_грозди)
    нужно = {часть: свои_доли[часть] * Decimal(всего) for часть in ЧАСТИ}
    набралось = {часть: Decimal(0) for часть in ЧАСТИ}
    наборы: dict[str, list] = {часть: [] for часть in ЧАСТИ}

    # Порядок обхода — по отпечатку грозди с зерном: случайный на вид,
    # воспроизводимый на деле.
    порядок = sorted(свои_грозди,
                     key=lambda г: _отпечаток([зерно, г.ключ]))
    for гроздь in порядок:
        # Гроздь идёт в тот набор, которому её недостаёт больше всех. При
        # равенстве — в объявленном порядке частей: без этого разделение
        # зависело бы от порядка словаря.
        часть = min(ЧАСТИ, key=lambda ч: (набралось[ч] - нужно[ч], ЧАСТИ.index(ч)))
        наборы[часть].extend(гроздь.документы)
        набралось[часть] += Decimal(гроздь.вес)

    if not наборы[ЗАКРЫТАЯ]:
        raise КорпусНеделим(
            "закрытый набор вышел пустым: гроздей слишком мало или доли "
            "объявлены так, что ему ничего не досталось")

    разделение = Разделение(
        CORPUS_VERSION, зерно,
        {часть: str(свои_доли[часть]) for часть in ЧАСТИ},
        tuple(наборы[ОБУЧАЮЩАЯ]), tuple(наборы[КАЛИБРОВОЧНАЯ]),
        tuple(наборы[ЗАКРЫТАЯ]))
    разделение.печать = разделение.как_запечатан()
    return разделение


def проверить_чистоту(увиденные_отпечатки, разделение: Разделение) -> tuple:
    """Не видел ли станок закрытого набора. Утечка называется поимённо.

    Проверка нужна затем, что первые пять запретов стоят на пути, а этот
    смотрит по следам: документ мог попасть станку в обход разделения — из
    другого каталога, из старого прогона, из чужой копии.
    """
    закрытые = set(разделение.отпечатки_закрытого)
    утекли = sorted(закрытые & {str(о) for о in увиденные_отпечатки})
    return tuple(утекли)


def свод(разделение: Разделение) -> dict:
    итог = разделение.as_json()
    итог["чистота"] = ("закрытый набор не вскрывался" if not разделение.вскрыт
                       else "ЗАКРЫТЫЙ НАБОР ВСКРЫТ: метрика на нём больше не "
                            "является допускающей")
    return итог


