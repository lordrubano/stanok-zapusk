# -*- coding: utf-8 -*-
"""Дочерняя половина изолированного запуска.

Здесь живёт всё, что делает обработчик внутри своего процесса. Вынесено в
отдельный файл не для красоты: командная строка Windows не переносит кириллицу
в кодировке системы, и вступление, передаваемое через ``-c``, обязано состоять
из одних латинских букв. Всё осмысленное — тут.

Порядок в ``выполнить`` не украшение, а суть: запреты ставятся раньше, чем
будет загружена хоть одна библиотека разбора. Запрет, поставленный после,
ничего не стоит — библиотека успеет открыть соединение при загрузке.

Обмен с родителем идёт через стандартный ввод и вывод, ключи в нём латинские
по той же причине, что и вступление.
"""

from __future__ import annotations

import json
import sys
import traceback


def выполнить(задача: dict) -> dict:
    """Ставит запреты, зовёт обработчик и описывает исход словами."""

    from stanok.sandbox_guard import запретить_запуск_процессов, запретить_сеть

    запретить_сеть()
    запретить_запуск_процессов()

    try:
        import importlib

        модуль = importlib.import_module(задача["module"])
        значение = getattr(модуль, задача["function"])(задача["argument"])
        return {"исход": "готово", "значение": значение}
    except BaseException as беда:  # noqa: BLE001 — обработчик чужой
        return {
            "исход": "ошибка",
            "порода": type(беда).__name__,
            "код": getattr(беда, "код", None),
            "объяснение": str(беда),
            "след": traceback.format_exc(limit=3),
        }


def main(задача: dict) -> None:
    ответ = выполнить(задача)
    # Пишем байтами в явной кодировке, а не строкой. Строка ушла бы в кодировке
    # системы — на Windows это cp1251, — и родитель, читающий UTF-8, получил бы
    # труху вместо ответа. Со стороны родителя это выглядело бы как поломка
    # обработчика, хотя обработчик отработал верно.
    sys.stdout.buffer.write(
        json.dumps(ответ, ensure_ascii=False, default=str).encode("utf-8"))
    sys.stdout.buffer.flush()


__all__ = ["main", "выполнить"]
