# -*- coding: utf-8 -*-
"""Учебный документ: показать экраны людям, не вынося наружу ни строчки чужой.

Работа вне нумерации, по решению владельца от 05.08.2026. Служит трём делам:
показу экранов сотрудникам до того, как переделка станет дорогой; обучению
операторов (шаг 68); образцом для проверок.

## Настоящее в нём — форма, вымышленное — содержимое

Наружу не уходит ничего, потому что снаружи ничего настоящего и нет: банк,
контрагенты, суммы и назначения выдуманы здесь и никогда не были ничьими.
Настоящими остаются **форма документа, роды сомнений и пропорции**.

Пропорции взяты с настоящих выписок и названы, а не подобраны:

| Настоящий документ | Записей | С сомнением | Доля |
|---|---|---|---|
| выписка за год | 827 | 182 | 22 % |
| выписка за четыре года | 3 318 | 882 | 27 % |

Учебный держит **27 %** — верхнюю из измеренных. Облегчать было бы вреднее
всего: сотрудники должны увидеть настоящую тяжесть работы, иначе критика придёт
на игрушку, а работать они сядут за станок.

## Он собран настоящими частями станка

Ни одной подделки: записи, свидетельства происхождения, строки источника и
предупреждения — те же классы, которыми пользуется конвейер. Подделка,
устроенная иначе настоящего, показала бы не станок, а своё изображение.

## Он помечен учебным везде

:data:`МЕТКА` стоит в имени банка, в назначении каждой операции и в заголовке
каждой страницы. Принять этот документ за настоящий нельзя даже мельком — а
это единственное, чем документ-образец опасен.
"""

from __future__ import annotations

import datetime as _дата
from decimal import Decimal

from .evidence import FieldEvidence
from .pipeline import Проводка
from .segmenter import Строка, Сегментация, Ячейка
from .value_warnings import (
    ИЗМЕНЕНО_НАПИСАНИЕ,
    РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ,
    Предупреждение,
)

TRAINING_VERSION = "training/1"

# Метка стоит всюду, где документ может попасться на глаза.
МЕТКА = "УЧЕБНЫЙ ОБРАЗЕЦ"

# Доля записей, уходящих человеку. Верхняя из измеренных на настоящих
# выписках — облегчать нельзя, иначе показана будет не работа, а её тень.
ДОЛЯ_НА_ПРОВЕРКУ = 0.27

# Из уходящих человеку — доля крупнейшей группы (двоякие даты). На настоящих
# документах род сомнения был один и брал всю долю; здесь оставлены и другие
# роды, чтобы оператор увидел, что группа не одна.
ДОЛЯ_КРУПНОЙ_ГРУППЫ = 0.94

ЗАПИСЕЙ = 840

# Вымышленные стороны. Имена нарочно не похожи на настоящие: ни одного
# реального банка, ни одного правдоподобного счёта.
КОНТРАГЕНТЫ = (
    'ООО "ОБРАЗЕЦ-ОДИН"', 'ООО "ОБРАЗЕЦ-ДВА"', 'ЗАО "ПРИМЕРНОЕ"',
    'ИП ОБРАЗЦОВ О. О.', 'ООО "УЧЕБНАЯ ПОСТАВКА"', 'ООО "ПРИМЕР-СЕРВИС"',
)
НАЗНАЧЕНИЯ = (
    "оплата по учебному счёту № {н}",
    "возврат по учебному договору № {н}",
    "услуги по учебному соглашению № {н}",
)
БАНК = f'АО "БАНК-{МЕТКА}"'
СЧЁТ = "40702810000000000000"

СТРОК_НА_СТРАНИЦЕ = 16

# Семейство учебного документа — своё, а не имя настоящего банка. Имя
# настоящего семейства в ядре не живёт и жить не может: оно приходит пакетом
# оснастки (шаг 70), и проверка на это стоит с тех пор. Учебный документ едва
# не пробил её, вписав имя прямо в код.
СЕМЕЙСТВО = "учебное-1/1"


def _двоякая(день: int, месяц: int) -> bool:
    """День и месяц оба не больше 12 — дату можно прочесть в два способа.

    День, равный месяцу, сюда не годится: 01.01 формально двояка, а объяснение
    выходит нелепым — «это и первое января, и первое января». В учебном
    документе такие даты только подорвали бы доверие к показу.
    """
    return день <= 12 and месяц <= 12 and день != месяц


def _даты(сколько: int, двояких: int) -> list:
    """Даты так, чтобы двояких было **ровно** столько, сколько заказано.

    Двоякие раскладываются вперемешку с однозначными, а не подряд: в настоящем
    документе они рассыпаны по всему периоду, и группа, собранная из подряд
    идущих записей, показала бы работу легче, чем она есть.
    """
    двоякие, однозначные = [], []
    день, месяц = 1, 1
    while len(двоякие) < двояких:
        if _двоякая(день, месяц):
            двоякие.append(_дата.date(2024, месяц, день))
        день += 1
        if день > 12:
            день, месяц = 1, (месяц % 12) + 1
    день, месяц = 13, 1
    while len(однозначные) < сколько - двояких:
        однозначные.append(_дата.date(2024, месяц, min(день, 28)))
        день += 1
        if день > 28:
            день, месяц = 13, (месяц % 12) + 1

    # Чередование по доле: на каждую двоякую приходится столько однозначных,
    # сколько велит пропорция. Раскладка детерминирована — учебный документ
    # обязан быть один и тот же при каждой сборке.
    вместе = []
    на_одну = max(1, len(однозначные) // max(1, len(двоякие)))
    while двоякие or однозначные:
        if двоякие:
            вместе.append(двоякие.pop(0))
        for _ in range(на_одну):
            if однозначные:
                вместе.append(однозначные.pop(0))
    return вместе[:сколько]


def собрать(записей: int = ЗАПИСЕЙ) -> Проводка:
    """Учебная проводка: настоящие части станка, вымышленное содержимое."""
    на_проверку = round(записей * ДОЛЯ_НА_ПРОВЕРКУ)
    двояких = round(на_проверку * ДОЛЯ_КРУПНОЙ_ГРУППЫ)
    даты = _даты(записей, двояких)

    строки: list[Строка] = []
    записи: list[dict] = []
    происхождение: dict[str, tuple] = {}
    предупреждения: dict[str, tuple] = {}

    for номер in range(записей):
        страница = 1 + номер // СТРОК_НА_СТРАНИЦЕ
        адрес = f"страница[{страница}]/строка[{номер % СТРОК_НА_СТРАНИЦЕ}]"
        record_id = f"учебная-{номер:04d}"
        дата = даты[номер]
        сумма = Decimal(f"{1000 + номер * 137}.{(номер * 7) % 100:02d}")
        контрагент = КОНТРАГЕНТЫ[номер % len(КОНТРАГЕНТЫ)]
        назначение = (НАЗНАЧЕНИЯ[номер % len(НАЗНАЧЕНИЯ)].format(н=номер + 1)
                      + f" ({МЕТКА})")
        сырьё_даты = дата.strftime("%d.%m.%Y")
        сырьё_суммы = f"{сумма:,.2f}".replace(",", " ").replace(".", ",")

        ячейки = tuple(
            Ячейка(текст, f"{адрес}/я{столбец}", столбец, None)
            for столбец, текст in enumerate(
                (сырьё_даты, str(номер + 1), сырьё_суммы, контрагент,
                 назначение)))
        строки.append(Строка(адрес, страница, ячейки, "учебная строка"))

        записи.append({
            "schema_version": "record/1",
            "record_id": record_id,
            "template_version": СЕМЕЙСТВО,
            "source_anchor_ids": [адрес],
            # Поле записи — не голое значение, а словарь с «value» и «raw»:
            # ровно так его строит настоящий разбор. Голое значение здесь уже
            # однажды сделало учебный документ непохожим на настоящий, и
            # критические поля на экране пропали.
            "fields": {
                "дата": {"value": дата, "raw": сырьё_даты},
                "номер_документа": {"value": str(номер + 1),
                                    "raw": str(номер + 1)},
                "сумма": {"value": сумма, "raw": сырьё_суммы,
                          "currency": "RUB"},
                "контрагент": {"value": контрагент, "raw": контрагент},
                "назначение": {"value": назначение, "raw": назначение},
                "бик_контрагента": {"value": "000000000",
                                    "raw": "000000000"},
                "вид_документа": {"value": "платёжное поручение",
                                  "raw": "платёжное поручение"},
                "признак": {"value": "дебет" if номер % 3 else "кредит",
                            "raw": "дебет" if номер % 3 else "кредит"},
            },
        })
        происхождение[record_id] = (
            FieldEvidence("дата", адрес, сырьё_даты, "учебный", "1",
                          "дата из первой колонки", str(дата), страница),
            FieldEvidence("сумма", адрес, сырьё_суммы, "учебный", "1",
                          "сумма с разделителем разрядов", str(сумма),
                          страница),
            FieldEvidence("контрагент", адрес, контрагент, "учебный", "1",
                          "имя стороны как есть", контрагент, страница),
        )

        # Двоякость — свойство самой даты, а не порядкового номера: судить
        # по номеру значило бы разойтись с тем, что увидит разбор.
        если_двоякая = _двоякая(дата.day, дата.month)
        если_прочее = (not если_двоякая
                       and len(предупреждения) < на_проверку
                       and номер % 23 == 0)
        свои = []
        # Роды сомнения — те же, что рождает настоящий разбор: они узнаются
        # по правилу, которым станок разрешил неоднозначность, а не по имени
        # поля. Выдумывать здесь свои значило бы показать несуществующее.
        if если_двоякая:
            свои.append(Предупреждение(
                "дата", РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ, сырьё_даты,
                "порядок частей даты: день впереди месяца",
                "обе части не больше двенадцати"))
        elif если_прочее:
            if номер % 2:
                свои.append(Предупреждение(
                    "сумма", РАЗРЕШЕНА_НЕОДНОЗНАЧНОСТЬ,
                    сырьё_суммы.split(",")[0],
                    "неявные копейки: дробной части нет",
                    "в источнике копейки не выписаны"))
            else:
                свои.append(Предупреждение(
                    "контрагент", ИЗМЕНЕНО_НАПИСАНИЕ, контрагент.lower(),
                    "нормализация написания",
                    "написание приведено к верхнему регистру"))
        if свои:
            предупреждения[record_id] = tuple(свои)

    сегментация = Сегментация(строки=tuple(строки),
                              способ="учебный документ",
                              учтено_объектов=len(строки),
                              подано_объектов=len(строки))
    return Проводка(
        записи=записи,
        сегментация=сегментация,
        происхождение=происхождение,
        предупреждения=предупреждения,
        решения=_решения(записи, предупреждения),
        состояние_запуска="partial",
        опознан=True,
    )


def _решения(записи, предупреждения) -> list:
    """Решения по записям **с сомнением** — настоящим движком политик (шаг 45).

    Без решений учебный документ не годится для работы оператора: подтверждают
    **решение**, а не запись, и без него кнопка ничего не делает.

    Решения заводятся только там, где есть сомнение. Первая редакция заводила
    их на все 840 записей, и проверки шага 79 поймали это сразу: каждая запись
    получала невыполненное слагаемое допуска, доля на проверку становилась
    стопроцентной, а крупнейшей группой вместо «двоякой даты» — служебная.
    Учебный документ перестал бы показывать измеренную тяжесть работы, ради
    которой он и сделан.

    Статус здесь не ставится руками: его рождает движок из наблюдений.
    """
    from . import decision as реш

    политика = реш.подписать(реш.Политика("допуск/учебное", "владелец",
                                          "2026-08-06", откат="нет"))
    наблюдения = tuple(
        реш.Наблюдение(ключ, реш.НЕ_ИЗВЕСТНО, "учебный документ", False,
                       "на учебном документе слагаемое не измеряется")
        for ключ in реш.КЛЮЧИ)
    свои = []
    for запись in записи:
        record_id = запись.get("record_id", "")
        if record_id not in предупреждения:
            continue
        свои.append(реш.решить(record_id, наблюдения, политика,
                               состояние_запуска=реш.PARTIAL))
    return свои


def свод(проводка=None) -> dict:
    """Числа учебного документа — чтобы их можно было назвать в записке."""
    from . import console

    проводка = собрать() if проводка is None else проводка
    экраны = console.собрать_экраны(проводка)
    с_сомнением = [э for э in экраны if э.сомнения]
    группы = console.связки(экраны)
    return {
        "версия": TRAINING_VERSION,
        "метка": МЕТКА,
        "записей": len(экраны),
        "с_сомнением": len(с_сомнением),
        "доля_на_проверку": (round(len(с_сомнением) / len(экраны) * 100)
                             if экраны else 0),
        "групп": len(группы),
        "крупнейшая_группа": (
            {"род": группы[0].род, "записей": группы[0].сколько}
            if группы else None),
        "настоящее_содержимое": False,
    }


