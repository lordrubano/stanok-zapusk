# -*- coding: utf-8 -*-
"""Ядро как изделие: проводит документ пакетом оснастки, который ему подали.

Шаг 70. Это точка входа собранного ядра — то, что запускается у клиента. Ни
одного имени семейства здесь нет и быть не может: пакет приходит доводом, а не
живёт внутри.

Вывод — числа и коды, без содержимого документа: тем же правилом, что и
наблюдаемость (шаг 63).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ВЕРСИЯ_ЯДРА = "1"

# Петлевой адрес по умолчанию — тот же, что у узла. Берётся строкой, а не
# ввозом модуля: разбор доводов не должен тянуть за собой узел.
АДРЕС_ПО_УМОЛЧАНИЮ = "127.0.0.1"


def main(доводы=None) -> int:
    разбор = argparse.ArgumentParser(
        prog="stanok", add_help=True,
        description="Разбор документа пакетом оснастки")
    разбор.add_argument("--документ", required=False)
    разбор.add_argument("--пакет", required=False)
    разбор.add_argument("--версия", action="store_true")
    разбор.add_argument("--описать-пакет", dest="описать", required=False)
    разбор.add_argument("--осмотреть-окружение", dest="осмотр", required=False,
                        metavar="КАТАЛОГ")
    разбор.add_argument("--установить", dest="установить", required=False,
                        metavar="КУДА")
    разбор.add_argument("--из", dest="дистрибутив", required=False)
    разбор.add_argument("--первый-запуск", dest="первый", required=False,
                        metavar="КАТАЛОГ")
    разбор.add_argument("--проверить-откат", dest="откат", required=False,
                        metavar="КАТАЛОГ_ДАННЫХ")
    разбор.add_argument("--состав", dest="состав", nargs="?", const="",
                        metavar="ИЗДЕЛИЕ")
    разбор.add_argument("--лицензии", dest="лицензии_", nargs="?", const="",
                        metavar="ИЗДЕЛИЕ")
    разбор.add_argument("--проверить-подпись", dest="подпись", required=False,
                        metavar="ИЗДЕЛИЕ")
    разбор.add_argument("--ключ-издателя", dest="ключ", default="",
                        metavar="ОТКРЫТЫЙ_КЛЮЧ")
    разбор.add_argument("--проверить-право", dest="право", required=False,
                        metavar="ФАЙЛ_ПРАВА")
    разбор.add_argument("--на-число", dest="число", default="",
                        metavar="ГГГГ-ММ-ДД")
    разбор.add_argument("--что-может-защита", dest="защита",
                        action="store_true")
    разбор.add_argument("--доказательный-пакет", dest="пакет_аудитору",
                        required=False, metavar="КУДА")
    разбор.add_argument("--в-excel", dest="в_excel", required=False,
                        metavar="КУДА",
                        help="собрать книги Excel: клиентскую и контрольную")
    разбор.add_argument("--оснастки", dest="оснастки", required=False,
                        metavar="ПАПКА",
                        help="папка с шаблонами семейств: с ней узел умеет "
                             "разбирать положенное через браузер")
    разбор.add_argument("--политика", dest="политика", required=False,
                        metavar="ФАЙЛ",
                        help="политика допуска, утверждённая владельцем: без "
                             "неё станок не выносит решений по записям")
    разбор.add_argument("--узел", dest="узел", action="store_true",
                        help="поднять местный узел интерфейса")
    разбор.add_argument("--порт", dest="порт", type=int, default=0,
                        metavar="ПОРТ")
    разбор.add_argument("--учебный", dest="учебный", action="store_true",
                        help="поднять узел на учебном документе: форма и роды "
                             "сомнений настоящие, содержимое вымышлено")
    разбор.add_argument("--рабочий-каталог", dest="каталог", required=False,
                        metavar="ПАПКА",
                        help="одна папка на прогон: партия, отметка хода, "
                             "реестр запусков и журнал решений. Без неё "
                             "действия оператора принимать некуда")
    разбор.add_argument("--оператор", dest="оператор", default="",
                        metavar="ИМЯ",
                        help="кто работает. Объявление, а не пароль: станок "
                             "записывает названное и человека не удостоверяет")
    разбор.add_argument("--наружу", dest="наружу", default="",
                        metavar="ИМЯ",
                        help="имя, под которым узел виден снаружи через трубу. "
                             "Гнездо остаётся петлевым; принимается ровно это "
                             "одно имя сверх петлевых")
    разбор.add_argument("--слушать", dest="слушать", default=АДРЕС_ПО_УМОЛЧАНИЮ,
                        metavar="АДРЕС",
                        help="на каком адресе висеть. По умолчанию петлевой. "
                             "0.0.0.0 нужен на чужой площадке, где обращения "
                             "приводит её привратник; узел скажет об этом "
                             "вслух в своём ответе")
    свои = разбор.parse_args(доводы)

    from stanok.package import ПакетНегоден, описать, поставить
    from stanok.tooling import ОснасткаНегодна

    if свои.версия:
        print(json.dumps({"ядро": ВЕРСИЯ_ЯДРА}, ensure_ascii=False))
        return 0

    if свои.осмотр:
        from stanok.install import осмотреть_окружение

        итог = осмотреть_окружение(свои.осмотр, свои.дистрибутив)
        print(json.dumps(итог, ensure_ascii=False))
        return 0 if итог["можно_ставить"] else 3

    if свои.установить:
        from stanok.install import установить

        итог = установить(свои.дистрибутив or ".", свои.установить)
        print(json.dumps(итог, ensure_ascii=False))
        return 0 if итог["поставлено"] else 3

    if свои.первый:
        from stanok.install import первый_запуск

        print(json.dumps(первый_запуск(свои.первый), ensure_ascii=False))
        return 0

    if свои.узел:
        from stanok.node import ПОРТ_ПО_УМОЛЧАНИЮ, Страница, Узел, свод
        from stanok.node import обезвредить, собрать_страницу

        def начало() -> str:
            свой = свод()
            строки = ["<h1>Станок</h1>",
                      "<p class=tih>Узел интерфейса на этой машине. "
                      "Наружу не ходит.</p>",
                      "<table><tr><th>Что</th><th>Значение</th></tr>"]
            for имя, значение in (("ядро", ВЕРСИЯ_ЯДРА),
                                  ("узел", свой["версия"]),
                                  ("адрес", свой["адрес"]),
                                  ("наружу не ходит", "да")):
                строки.append(f"<tr><td>{обезвредить(имя)}</td>"
                              f"<td><code>{обезвредить(значение)}</code></td>"
                              "</tr>")
            строки.append("</table>")
            строки.append(
                "<p class=tih>Экраны оператора открываются, когда узлу дан "
                "документ: <code>--узел --документ … --пакет …</code> для "
                "настоящего или <code>--узел --учебный</code> для учебного. "
                "Без документа показывать нечего, кроме себя самого.</p>")
            return "".join(строки)

        # Рабочий каталог: одна папка на прогон. Без неё экраны только
        # показывают — действия принимать некуда, и это сказано на самих
        # экранах, а не подразумевается.
        # Каталог заводится сам: оператор не должен думать о папках. Не назван
        # — берётся «работа-станка» рядом с изделием, и станок говорит, где он.
        from stanok.session import Оператор, завести_каталог

        каталог = завести_каталог(свои.каталог or "работа-станка")

        # Дальний склад. На чужой площадке рабочая папка не переживает
        # засыпания машины, и её надо принести оттуда, где она пережила.
        # Приносится ДО сборки страниц: экраны строятся по тому, что лежит в
        # папке, и принести после значило бы показать человеку пустое место с
        # уже прожитой работой.
        from stanok import sklad as склад_

        склад = склад_.из_окружения()
        принесено = []
        if склад is not None:
            try:
                # Склада ждут: площадка заводит базу и службы разом, и первая
                # служба может постучаться раньше, чем база ответила.
                принесено = склад_.дождаться(
                    склад, каталог.где,
                    сказать=lambda что: print(
                        json.dumps({"склад_ждём": что}, ensure_ascii=False)))
            except RuntimeError as беда:
                # Не поднимаемся молча без склада: работа тогда пропадёт при
                # первом же засыпании машины, и никто не узнает. Причина
                # называется словами, а не стеком.
                print(json.dumps({"отказ": str(беда),
                                  "склад": склад.описание()},
                                 ensure_ascii=False))
                return 4

        def закрепить() -> None:
            """Сложить папку в склад. Зовётся узлом после каждого действия."""
            склад_.сохранить(склад, каталог.где)
        # Имени нет — не подставляем заглушку: пустое имя спрашивает первый
        # экран браузера, там, куда человек и так смотрит. Заглушка молча
        # съедала бы этот вопрос, и в журнале стояло бы «оператор не назвался».
        оператор_прогона = (Оператор(имя=свои.оператор.strip())
                            if свои.оператор.strip() else None)

        # Политика допуска нужна и здесь: без неё движок не выносит решений,
        # и записи не появятся ни в очереди, ни в книге.
        политика_узла = None
        if свои.политика:
            from stanok.decision import ПолитикаНегодна, прочитать_политику

            try:
                политика_узла = прочитать_политику(свои.политика)
            except ПолитикаНегодна as беда:
                print(json.dumps({"отказ": "E_POLICY_INVALID",
                                  "почему": str(беда)}, ensure_ascii=False))
                return 2
        from stanok.pipeline import Проводка

        свои_страницы = [Страница("/о", "Станок", начало)]
        # Рабочий режим браузерного пути: станок поднимается пустым, документ
        # приходит через экран приёма, разбор запускается кнопкой. Проводка
        # живёт на диске рядом с партией — потому и переживает закрытие окна.
        держатель = {"проводка": None, "оснастка": None, "узел": None,
                     "оператор": None, "документ": ""}
        if свои.оснастки and not свои.учебный and not свои.документ:
            from stanok import progon as хранение
            from stanok import razbor as разбор_
            from stanok.workplace import страницы as страницы_места

            папка_оснасток = Path(свои.оснастки)
            байты_подачи = каталог.где / "podacha" if каталог else None

            def _собрать_страницы():
                проводка = держатель["проводка"]
                оснастка = держатель["оснастка"]
                return [*страницы_места(
                    проводка if проводка is not None else Проводка(),
                    оснастка.семейство if оснастка else "не назван",
                    оснастка.версия if оснастка else "не названа",
                    оснастка=оснастка,
                    отметка_путь=каталог.отметка if каталог else None,
                    реестр=каталог.реестр if каталог else None,
                    каталог=каталог,
                    оператор=держатель.get("оператор") or оператор_прогона,
                    куда_байты=байты_подачи, разобрать=_разобрать,
                    после_решения=_закрепить_прогон,
                    запомнить_оператора=_запомнить_оператора,
                    склад={"описание": склад.описание() if склад else "",
                           "принесено": принесено}),
                    Страница("/о", "Станок", начало)]

            def _запомнить_оператора(кто) -> None:
                """Имя названо один раз и живёт до конца работы."""
                держатель["оператор"] = кто

            def _закрепить_прогон(проводка) -> None:
                """Решение принято — прогон на диске должен об этом знать.

                Иначе закрытая человеком запись воскресала бы при следующем
                открытии станка: на экране «сделано», на диске «ждёт».

                Сохраняется **вместе со сведениями о том, чей это разбор**.
                Прежде здесь их не было, и первое же решение стирало имя
                оснастки: записи после перезапуска возвращались все до единой,
                а книга выходила без единой колонки — их берут из оснастки, а
                какая она была, станок уже не знал. Куплено проверкой комплекта
                на чистом месте.
                """
                if каталог is not None:
                    своя = держатель.get("оснастка")
                    хранение.сохранить(
                        проводка, каталог.где,
                        документ=держатель.get("документ", ""),
                        оснастка=своя.версия if своя else "")

            def _разобрать(путь, имя):
                """Кнопка «Разобрать» на экране приёма зовёт это."""
                отметчик = None
                if каталог is not None:
                    from stanok.progress import Отметчик

                    отметчик = Отметчик(каталог.отметка)
                итог = разбор_.разобрать(
                    путь, оснастки=разбор_.оснастки_из(папка_оснасток),
                    куда=каталог.где if каталог else Path("."),
                    политика=политика_узла, отметчик=отметчик,
                    имя_документа=имя)
                if отметчик is not None:
                    отметчик.кончено()
                держатель["проводка"] = итог.проводка
                держатель["оснастка"] = итог.оснастка
                держатель["документ"] = имя
                # Экраны строятся по проводке, а она только что появилась:
                # без подмены человек нажал бы «Разобрать» и увидел прежние
                # пустые экраны, решив, что разбор не сработал.
                if держатель["узел"] is not None:
                    держатель["узел"].заменить_страницы(_собрать_страницы())
                return итог

            # Прогон с прошлого раза: закрыл окно — вернулся и видишь то же.
            if каталог is not None:
                прежний = хранение.прочитать(каталог.где)
                if прежний is not None:
                    держатель["проводка"] = прежний
                    # Оснастка в прогоне не лежит — она приходит пакетом. Но
                    # без неё книга выходит без единой колонки: сборка берёт
                    # их из оснастки. Поэтому ищем ту самую, по версии.
                    свои_сведения = хранение.сведения(каталог.где)
                    держатель["документ"] = свои_сведения.get("документ", "")
                    чьё = свои_сведения.get("оснастка", "")
                    for своя in разбор_.оснастки_из(папка_оснасток):
                        if своя.версия == чьё:
                            держатель["оснастка"] = своя
                            break
            свои_страницы = _собрать_страницы()
        elif свои.учебный:
            # Учебный документ едет внутри изделия: оператору есть на чём
            # смотреть экраны, не принося настоящих выписок на свою машину.
            from stanok.training import собрать as собрать_учебное
            from stanok.workplace import страницы as страницы_места

            проводка = собрать_учебное()
            свои_страницы = [*страницы_места(
                проводка, "учебное-1", "учебное-1/1",
                отметка_путь=каталог.отметка if каталог else None,
                реестр=каталог.реестр if каталог else None,
                каталог=каталог, оператор=оператор_прогона),
                *свои_страницы]
        elif свои.документ and свои.пакет:
            # Рабочее место поднимается над настоящей проводкой: узел без
            # документа показывать оператору нечего, кроме себя самого.
            from stanok.adapter_pdf import РазборPDF
            from stanok.adapters import Розетка
            from stanok.pipeline import провести
            from stanok.workplace import страницы as страницы_места

            оснастка = поставить(свои.пакет, ВЕРСИЯ_ЯДРА)
            розетка = Розетка()
            розетка.подключить(РазборPDF())
            отметчик = None
            if каталог is not None:
                from stanok.progress import Отметчик

                отметчик = Отметчик(каталог.отметка)
            проводка = провести(свои.документ, оснастка=оснастка,
                                розетка=розетка, отметчик=отметчик)
            if отметчик is not None:
                отметчик.кончено()
            свои_страницы = [*страницы_места(
                проводка, оснастка.семейство, оснастка.версия,
                оснастка=оснастка,
                отметка_путь=каталог.отметка if каталог else None,
                реестр=каталог.реестр if каталог else None,
                каталог=каталог, оператор=оператор_прогона),
                *свои_страницы]

        узел = Узел(свои_страницы, порт=свои.порт or ПОРТ_ПО_УМОЛЧАНИЮ,
                    наружу=свои.наружу, слушать=свои.слушать,
                    после_приёма=закрепить if склад is not None else None)
        держатель["узел"] = узел
        try:
            порт = узел.поднять()
        except OSError as беда:
            print(json.dumps({"отказ": f"узел не поднялся: {беда}"},
                             ensure_ascii=False))
            return 3
        print(json.dumps({"узел": узел.адрес,
                          "слушает_только_свою_машину":
                              узел.слушает_только_свою_машину(),
                          "порт": порт,
                          "наружу": узел.наружу or None,
                          "склад": склад.описание() if склад else None,
                          "принесено_из_склада": принесено,
                          "остановить": "закройте это окно"},
                         ensure_ascii=False))
        try:
            узел._нить.join()
        except KeyboardInterrupt:
            pass
        finally:
            узел.остановить()
        return 0

    if свои.защита:
        from stanok.delivery import свод as свод_защиты

        print(json.dumps(свод_защиты(), ensure_ascii=False))
        return 0

    if свои.подпись:
        from stanok.delivery import проверить_изделие, прочитать_свидетельство

        итог = проверить_изделие(свои.подпись,
                                 прочитать_свидетельство(свои.подпись),
                                 свои.ключ)
        print(json.dumps(итог, ensure_ascii=False))
        return 0 if итог["наше"] else 3

    if свои.право:
        from stanok.delivery import проверить_право

        try:
            право = json.loads(Path(свои.право).read_text(encoding="utf-8"))
        except (OSError, ValueError) as беда:
            print(json.dumps({"отказ": f"право не читается: {беда}"},
                             ensure_ascii=False))
            return 2
        итог = проверить_право(право, свои.число or "", доверенный_ключ=свои.ключ)
        print(json.dumps(итог, ensure_ascii=False))
        return 0 if итог["действует"] else 3

    if свои.состав is not None or свои.лицензии_ is not None:
        from stanok.inventory import лицензии, перечень_как_json
        from stanok.inventory import прочитать_из_изделия, сверить

        изделие = свои.состав or свои.лицензии_ or sys.argv[0]
        try:
            перечень = прочитать_из_изделия(изделие)
        except ValueError as беда:
            print(json.dumps({"отказ": str(беда)}, ensure_ascii=False))
            return 2
        if свои.лицензии_ is not None:
            print(json.dumps(лицензии(перечень), ensure_ascii=False))
            return 0
        перечень["сверка"] = сверить(перечень, изделие)
        # Тексты лицензий никуда не деваются — они лежат внутри изделия, в
        # каталоге ЛИЦЕНЗИИ. В ответ их не печатаем: перечень читают глазами.
        краткий = dict(перечень, составные=[
            {к: з for к, з in ч.items() if к != "текст_лицензии"}
            for ч in перечень.get("составные", ())])
        print(перечень_как_json(краткий))
        return 0 if перечень["сверка"]["сошлось"] else 3

    if свои.откат:
        from stanok.upgrade import свод as свод_обновления

        итог = свод_обновления(свои.откат)
        print(json.dumps(итог, ensure_ascii=False))
        return 0 if итог["откат"]["можно_откатывать"] else 3

    if свои.описать:
        try:
            print(json.dumps(описать(свои.описать), ensure_ascii=False))
        except ПакетНегоден as беда:
            print(json.dumps({"отказ": str(беда)}, ensure_ascii=False))
            return 2
        return 0

    if not (свои.документ and свои.пакет):
        разбор.print_usage()
        return 1

    try:
        оснастка = поставить(свои.пакет, ВЕРСИЯ_ЯДРА)
    except (ПакетНегоден, ОснасткаНегодна) as беда:
        print(json.dumps({"отказ": type(беда).__name__, "почему": str(беда)},
                         ensure_ascii=False))
        return 2

    from stanok.adapter_pdf import РазборPDF
    from stanok.adapters import Розетка
    from stanok.pipeline import провести

    розетка = Розетка()
    розетка.подключить(РазборPDF())

    # Политика допуска — документ владельца. Без неё движок не выносит
    # решений вовсе, и книга выходит пустой не потому, что записей нет, а
    # потому, что решать нечем. Молчать об этом нельзя: пустая книга читается
    # как «ничего не нашли».
    политика = None
    if свои.политика:
        from stanok.decision import ПолитикаНегодна, прочитать_политику

        try:
            политика = прочитать_политику(свои.политика)
        except ПолитикаНегодна as беда:
            print(json.dumps({"отказ": "E_POLICY_INVALID", "почему": str(беда)},
                             ensure_ascii=False))
            return 2

    проводка = провести(свои.документ, оснастка=оснастка, розетка=розетка,
                        политика=политика)

    if свои.пакет_аудитору:
        from stanok import dossier
        from stanok.delivery import прочитать_свидетельство
        from stanok.inventory import прочитать_из_изделия

        своё = Path(sys.argv[0])
        try:
            состав = прочитать_из_изделия(своё)
        except ValueError:
            состав = None
        пакет = dossier.собрать(
            проводка, состав=состав,
            свидетельство=прочитать_свидетельство(своё),
            документ=Path(свои.документ).name,
            выпуск=f"ядро {ВЕРСИЯ_ЯДРА}")
        словами, числами = dossier.записать(пакет, свои.пакет_аудитору)
        print(json.dumps({"доказательный_пакет": [словами.name, числами.name],
                          "куда": str(Path(свои.пакет_аудитору))},
                         ensure_ascii=False))

    if свои.в_excel:
        # Книги собираются и при закрытых воротах: собрать книгу и **отдать**
        # её клиенту — разные действия, и запрет стоит на втором. Что с
        # воротами, сказано тут же, рядом, чтобы собранная книга не читалась
        # как разрешённая к выдаче.
        from stanok import release as выпуск

        собранные = выпуск.книги(проводка, свои.в_excel, оснастка=оснастка)
        свои_ворота = выпуск.ворота(проводка)

        # Два класса выдачи, и они ручаются за разное. Рабочая книга выходит по
        # закрытым человеком записям и сошедшемуся итогу; доказательный пакет —
        # только по полным воротам. Ни одно слагаемое при этом не смягчено:
        # рабочая книга просто не утверждает полноты и потому о ней не
        # спрашивает.
        рабочая_вышла, почему_нет = None, ""
        try:
            выдача = выпуск.выдать_рабочую(проводка, свои.в_excel,
                                           оснастка=оснастка)
            рабочая_вышла = str(выдача.части[0].путь)
        except выпуск.ВыпускЗакрыт as беда:
            почему_нет = str(беда)

        print(json.dumps({
            "рабочая_книга": рабочая_вышла or f"не вышла: {почему_нет}",
            "доказательный_пакет": (
                "вышел" if свои_ворота.можно else
                "не вышел: нужны полные ворота, все семь механизмов покрытия"),
            "книги": {"клиенту": str(собранные["клиентская"]),
                      "контрольная": str(собранные["контрольная"])},
            "строк_клиенту": собранные["строк_клиенту"],
            "по_листам": собранные["по_листам"],
            "колонки": собранные["колонки"],
            "ворота": "открыты" if свои_ворота.можно else "закрыты",
            "выдача": ("разрешена" if свои_ворота.можно else
                       "запрещена: " + свои_ворота.почему),
            **({} if политика is not None else {
                "почему_книги_пусты":
                    "политика допуска не приложена (--политика ФАЙЛ): без неё "
                    "станок не выносит решений, и раскладывать по листам "
                    "нечего. Записи разобраны: "
                    f"{len(проводка.записи)}"}),
        }, ensure_ascii=False))

    print(json.dumps({
        "ядро": ВЕРСИЯ_ЯДРА,
        "семейство": оснастка.семейство,
        "версия_оснастки": оснастка.версия,
        "состояние": проводка.состояние_запуска,
        "записей": len(проводка.записи),
        "объектов": len(проводка.объекты),
        "сорвалось": [э.имя for э in проводка.журнал if not э.получилось],
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
