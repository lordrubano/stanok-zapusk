# -*- coding: utf-8 -*-
"""Установка на чужой машине: проверка окружения до работы, а не во время.

Шаг 71 плана. Нормативная основа — чертёж v3.0, раздел 20.

**Первый запуск без участия разработчика.** Клиент получает дистрибутив, ставит
и работает. Всё, что требует нашего присутствия, — не продукт, а услуга, и
продаётся иначе.

Отсюда главное правило шага: **окружение проверяется при установке, а не на
первом документе клиента**. Не та версия языка, нет библиотеки, нет прав на
запись — отказ с внятной причиной сразу, пока клиент ещё смотрит на установку и
готов что-то поправить. Падение на первом документе выглядит как поломка
продукта, даже если виновата чужая машина.

## Что нужно, а что желательно

Требования делятся надвое, и смешивать их нельзя:

* **без чего работать нельзя** — версия языка, право писать в рабочий каталог,
  место на диске, само ядро;
* **без чего работает не всё** — библиотека подписей. Без неё разбор,
  проверки и книга Excel работают полностью; не работает подписание паспорта
  запуска. Это **урезание, а не поломка**, и оно называется вслух при установке,
  а не обнаруживается через месяц.

Библиотека книги Excel в изделие уложена: она написана на самом языке и потому
едет внутри ядра. Библиотека подписей двоичная — она собрана под свою
операционную систему и своё железо, и класть её внутрь означало бы либо возить
чужую сборку, либо обещать переносимость, которой нет.

## Установка без сети

Ставится **без сети целиком**: дистрибутив — папка с файлами, установка —
копирование и проверка. Ни одного обращения наружу.

Единственное, чего без сети не будет, — библиотеки подписей, если её нет на
машине клиента и она не положена в дистрибутив заранее. Это названо прямо: либо
она приезжает в дистрибутиве, собранная под ту же систему, либо клиент ставит её
сам, либо подписание паспорта не работает и это объявлено.
"""

from __future__ import annotations

import importlib.util
import json
import os
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path


INSTALL_VERSION = "install/1"

НАИМЕНЬШИЙ_ЯЗЫК = (3, 12)

# Коды. Каждый — про одну беду и выговаривается словами.
СТАРЫЙ_ЯЗЫК = "E_PYTHON_TOO_OLD"
НЕТ_БИБЛИОТЕКИ = "E_LIB_MISSING"
НЕТ_ПРАВ = "E_NO_WRITE_ACCESS"
НЕТ_МЕСТА = "E_NO_SPACE"
НЕТ_ЯДРА = "E_CORE_MISSING"
УРЕЗАНО = "W_REDUCED"

KNOWN_LIMITATIONS = (
    "Проверка окружения смотрит на то, что можно проверить до работы: версию "
    "языка, наличие библиотек, право писать, место. Скорость машины, объём "
    "памяти под большой документ и особенности файловой системы этим осмотром "
    "не покрываются.",
    "Библиотека подписей двоичная и в изделие не укладывается. Без неё "
    "подписание паспорта запуска недоступно; всё остальное работает.",
    "Установка не заводит службу и не прописывается в системе: это копирование "
    "и проверка. Запуск по расписанию, автозагрузка и обновление на месте — "
    "не здесь (шаг 72).",
)


@dataclass(frozen=True, slots=True)
class Замечание:
    """Одно замечание об окружении: код, слова и мешает ли оно работать."""

    код: str
    словами: str
    мешает: bool = True

    def as_json(self) -> dict:
        return {"код": self.код, "словами": self.словами, "мешает": self.мешает}


def _есть_библиотека(имя: str) -> bool:
    try:
        return importlib.util.find_spec(имя) is not None
    except (ImportError, ValueError):
        return False


def проверить_язык() -> tuple[Замечание, ...]:
    свой = sys.version_info[:2]
    if свой < НАИМЕНЬШИЙ_ЯЗЫК:
        нужно = ".".join(str(ч) for ч in НАИМЕНЬШИЙ_ЯЗЫК)
        есть = ".".join(str(ч) for ч in свой)
        return (Замечание(
            СТАРЫЙ_ЯЗЫК,
            f"нужен язык не ниже {нужно}, а на машине {есть}. Станок написан "
            "на нынешнем языке и старым не читается"),)
    return ()


def проверить_библиотеки() -> tuple[Замечание, ...]:
    """Что есть и чего нет. Разделяет «нельзя работать» и «работает не всё»."""
    свои = []
    if not _есть_библиотека("openpyxl"):
        свои.append(Замечание(
            НЕТ_БИБЛИОТЕКИ,
            "нет библиотеки книги Excel. Она едет внутри изделия, и её "
            "отсутствие означает, что изделие собрано неполно"))
    if not _есть_библиотека("cryptography"):
        свои.append(Замечание(
            УРЕЗАНО,
            "нет библиотеки подписей: разбор, проверки и выгрузка в Excel "
            "работают полностью, подписание паспорта запуска — нет. Она "
            "двоичная и собирается под свою систему, потому в изделие не "
            "уложена",
            мешает=False))
    return tuple(свои)


def проверить_каталог(куда, нужно_байт: int = 64 * 1024 * 1024
                      ) -> tuple[Замечание, ...]:
    from .recovery import осмотреть_место, осмотреть_право_записи

    # Осмотр — это осмотр: он не должен оставлять следов на чужой машине.
    # Проба записи заводит каталог, если его не было; если ставить потом
    # окажется нельзя, пустой каталог останется врать, что установка была.
    место = Path(куда)
    был_до_нас = место.exists()

    свои = []
    for беда in осмотреть_право_записи(место):
        свои.append(Замечание(НЕТ_ПРАВ, беда.словами))
    if not свои:
        for беда in осмотреть_место(место, нужно_байт):
            свои.append(Замечание(НЕТ_МЕСТА, беда.словами))

    if not был_до_нас and место.is_dir() and not any(место.iterdir()):
        try:
            место.rmdir()
        except OSError:  # pragma: no cover — чужая машина вправе не дать
            pass
    return tuple(свои)


def проверить_изделия(дистрибутив) -> tuple[Замечание, ...]:
    место = Path(дистрибутив)
    ядра = list(место.glob("ядро-*.pyz"))
    if not ядра:
        return (Замечание(
            НЕТ_ЯДРА,
            f"в дистрибутиве {место.name} нет ядра: ставить нечего"),)
    return ()


def осмотреть_окружение(куда, дистрибутив=None,
                        нужно_байт: int = 64 * 1024 * 1024) -> dict:
    """Полный осмотр до установки. Возвращает найденное, а не чинит.

    Замечания разделены надвое: мешающие работать и урезающие её. Первое —
    отказ, второе — предупреждение, которое обязано быть сказано вслух.
    """
    замечания: list[Замечание] = []
    замечания.extend(проверить_язык())
    замечания.extend(проверить_библиотеки())
    замечания.extend(проверить_каталог(куда, нужно_байт))
    if дистрибутив is not None:
        замечания.extend(проверить_изделия(дистрибутив))

    мешающие = [з for з in замечания if з.мешает]
    return {
        "версия": INSTALL_VERSION,
        "язык": ".".join(str(ч) for ч in sys.version_info[:3]),
        "можно_ставить": not мешающие,
        "замечаний": len(замечания),
        "мешающих": len(мешающие),
        "замечания": [з.as_json() for з in замечания],
        "урезано": [з.as_json() for з in замечания if not з.мешает],
    }


def установить(дистрибутив, куда, нужно_байт: int = 64 * 1024 * 1024) -> dict:
    """Ставит изделия в указанный каталог. Осматривает окружение **до** работы.

    Установка — копирование и проверка, без единого обращения наружу. Если
    окружение негодно, ничего не копируется вовсе: половина установки хуже её
    отсутствия, потому что выглядит как установка.
    """
    осмотр = осмотреть_окружение(куда, дистрибутив, нужно_байт)
    if not осмотр["можно_ставить"]:
        return {"версия": INSTALL_VERSION, "поставлено": False,
                "почему": [з for з in осмотр["замечания"] if з["мешает"]],
                "осмотр": осмотр}

    откуда, место = Path(дистрибутив), Path(куда)
    место.mkdir(parents=True, exist_ok=True)
    поставленное = []
    for образец in ("ядро-*.pyz", "оснастка-*.zip", "*.опись.json", "ЧИТАЙ*.md"):
        for файл in sorted(откуда.glob(образец)):
            цель = место / файл.name
            shutil.copy2(файл, цель)
            поставленное.append(файл.name)

    return {
        "версия": INSTALL_VERSION,
        "поставлено": True,
        "куда": str(место),
        "файлов": len(поставленное),
        "изделия": поставленное,
        "урезано": осмотр["урезано"],
        "сети_не_требовалось": True,
    }


def первый_запуск(куда) -> dict:
    """Что клиент может проверить сам, не зовя разработчика."""
    место = Path(куда)
    ядра = sorted(место.glob("ядро-*.pyz"))
    пакеты = sorted(место.glob("оснастка-*.zip"))
    return {
        "версия": INSTALL_VERSION,
        "ядро": ядра[0].name if ядра else None,
        "пакетов_оснастки": len(пакеты),
        "пакеты": [п.name for п in пакеты],
        "как_проверить": (
            f"python {ядра[0].name} --версия" if ядра else "ядра нет"),
        "как_разобрать": (
            f"python {ядра[0].name} --документ <файл.pdf> --пакет {пакеты[0].name}"
            if ядра and пакеты else "нужен и пакет оснастки"),
    }


