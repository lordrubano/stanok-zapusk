def _спросить_полноту(проводка) -> Слагаемое:
    """Спрашивает готовый статус полноты. Своего суждения не выносит."""
    полнота = getattr(проводка, "полнота", None)
    if полнота is None:
        return Слагаемое("полнота источника", НЕ_ИЗВЕСТНО,
                         "полнота не оценивалась: карты покрытия нет")
    статус = getattr(полнота, "статус", "") or ""
    # Право на автодопуск решает сам модуль полноты. Ворота его не пересчитывают.
    if getattr(полнота, "автодопуск_разрешён", False):
        return Слагаемое("полнота источника", ДА, f"статус «{статус}»")
    ответ = НЕ_ИЗВЕСТНО if статус in ("", "unknown") else НЕТ
    причины = "; ".join(getattr(полнота, "причины", ()) or ())
    return Слагаемое("полнота источника", ответ,
                     f"статус «{статус or 'не назван'}»"
                     + (f": {причины}" if причины else ""))


def _спросить_исключения(проводка, решения=None) -> Слагаемое:
    """Спрашивает движок политик: остались ли записи, ждущие человека."""
    свои = tuple(решения if решения is not None
                 else getattr(проводка, "решения", ()) or ())
    записей = len(getattr(проводка, "записи", ()) or ())
    if not свои:
        # Ни одного решения — сказать об исключениях нечего. Это неизвестность,
        # а не «исключений нет»: молчание не бывает согласием.
        return Слагаемое("исключения закрыты", НЕ_ИЗВЕСТНО,
                         f"решений нет, а записей {записей}"
                         if записей else "решений нет, и записей нет")
    ждут = [р for р in свои
            if not getattr(р, "статус_рождён", False)
            or getattr(р, "статус", None) == REVIEW]
    if ждут:
        return Слагаемое("исключения закрыты", НЕТ,
                         f"ждут человека {len(ждут)} записей из {len(свои)}")
    if записей and len(свои) != записей:
        return Слагаемое("исключения закрыты", НЕ_ИЗВЕСТНО,
                         f"решений {len(свои)}, а записей {записей}: "
                         "часть записей без решения")
    return Слагаемое("исключения закрыты", ДА,
                     f"решено {len(свои)} записей, ждущих нет")


def _этап(проводка, имя: str):
    for этап in getattr(проводка, "журнал", ()) or ():
        if getattr(этап, "имя", "") == имя:
            return этап
    return None


def _спросить_итог(проводка) -> Слагаемое:
    """Спрашивает журнал этапов: сошлись ли итоги. Сам ничего не считает."""
    найдены = [(имя, _этап(проводка, имя)) for имя in ЭТАПЫ_ИТОГА]
    если_есть = [(имя, э) for имя, э in найдены if э is not None]
    if not если_есть:
        return Слагаемое("итог сошёлся", НЕ_ИЗВЕСТНО,
                         "проверок итога не проводилось: этапов нет в журнале")
    сорвались = [(имя, э) for имя, э in если_есть
                 if not getattr(э, "получилось", False)]
    if сорвались:
        имя, этап = сорвались[0]
        сказано = getattr(этап, "сказано", "") or ""
        return Слагаемое("итог сошёлся", НЕТ,
                         f"этап «{имя}» не сошёлся"
                         + (f": {сказано}" if сказано else ""))
    if len(если_есть) < len(ЭТАПЫ_ИТОГА):
        нет = ", ".join(имя for имя, э in найдены if э is None)
        return Слагаемое("итог сошёлся", НЕ_ИЗВЕСТНО,
                         f"часть проверок не проводилась: {нет}")
    return Слагаемое("итог сошёлся", ДА,
                     "все проверки итога прошли: "
                     + ", ".join(имя for имя, _ in если_есть))


def _спросить_запуск(проводка) -> Слагаемое:
    """Спрашивает состояние запуска — то, что вывел движок политик."""
    from . import decision as движок

    состояние = getattr(проводка, "состояние_запуска", "") or ""
    сорвалось = list(getattr(проводка, "сорвалось", ()) or ())
    if состояние == движок.COMPLETED:
        return Слагаемое("запуск состоялся", ДА, "состояние «completed»")
    if состояние in (движок.FAILED, движок.BLOCKED):
        return Слагаемое("запуск состоялся", НЕТ,
                         f"состояние «{состояние}»"
                         + (f", не сошлись этапы: {', '.join(сорвалось)}"
                            if сорвалось else ""))
    if состояние == движок.PARTIAL:
        return Слагаемое("запуск состоялся", НЕТ,
                         "состояние «partial»: часть записей без конечного "
                         "решения")
    return Слагаемое("запуск состоялся", НЕ_ИЗВЕСТНО,
                     f"состояние «{состояние or 'не названо'}»")


def ворота(проводка=None, решения=None) -> Ворота:
    """Спрашивает готовые проверки и складывает ответ. Своих проверок нет."""
    if проводка is None:
        return Ворота(tuple(
            Слагаемое(ключ, НЕ_ИЗВЕСТНО, "запуска нет: спрашивать не о чем")
            for ключ in КЛЮЧИ))
    return Ворота((
        _спросить_полноту(проводка),
        _спросить_исключения(проводка, решения),
        _спросить_итог(проводка),
        _спросить_запуск(проводка),
    ))


