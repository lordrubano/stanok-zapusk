def _ячейка(поле):
    """Значение поля так, как его понимает сборщик книги.

    Тип берётся у самого значения, а не угадывается по имени поля: деньги
    приходят точным числом, дата — датой, и превращать их в строку значило бы
    отдать клиенту книгу, в которой ни сложить, ни отсортировать.
    """
    from datetime import date, datetime
    from decimal import Decimal

    from .excel import Cell

    значение = поле.get("value") if isinstance(поле, dict) else поле
    if значение is None:
        return None
    if isinstance(значение, Decimal):
        return Cell(значение, "money")
    if isinstance(значение, (date, datetime)):
        return Cell(значение, "date")
    if isinstance(значение, bool):
        return Cell(str(значение), "text")
    if isinstance(значение, int):
        return Cell(значение, "integer")
    return Cell(str(значение), "text")


def _поля(запись) -> dict:
    поля = запись.get("fields")
    return поля if isinstance(поля, dict) else запись


def _строка_клиента(запись, колонки) -> dict:
    """Одна строка клиентской книги по объявленным колонкам."""
    поля = _поля(запись)
    признак_записи = поля.get("признак")
    признак_записи = (признак_записи.get("value")
                      if isinstance(признак_записи, dict) else признак_записи)
    строка = {}
    for имя, поле, признак in колонки:
        значение = поля.get(поле)
        if not isinstance(значение, dict):
            строка[имя] = None
            continue
        if признак:
            нужное = признак.get("значение")
            чьё = поля.get(признак.get("поле", "признак"))
            чьё = чьё.get("value") if isinstance(чьё, dict) else чьё
            if str(чьё or признак_записи or "") != str(нужное):
                строка[имя] = None
                continue
        строка[имя] = _ячейка(значение)
    return строка


def _по_листам(проводка, решения) -> dict[str, list]:
    """Записи, разложенные по листам контрольной книги их же решениями.

    Лист назначает движок политик, а не эта сборка: своё правило раскладки было
    бы вторым мнением о статусе, а статус рождается в одном месте.
    """
    записи = {з.get("record_id"): з for з in getattr(проводка, "записи", ()) or ()}
    разложено: dict[str, list] = {"DATA": [], "REVIEW": [], "REJECTED": []}
    for решение in решения:
        лист = getattr(решение, "лист", None)
        if лист not in разложено:
            continue
        запись = записи.get(getattr(решение, "record_id", ""))
        if запись is None:
            continue
        разложено[лист].append((запись, решение))
    return разложено


def _строки_ошибок(проводка) -> list[dict]:
    """Лист ERRORS: чем именно кончилось несошедшееся, а не «были ошибки»."""
    from .excel import Cell

    строки = []
    for этап in getattr(проводка, "журнал", ()) or ():
        if getattr(этап, "получилось", True):
            continue
        строки.append({
            "что": Cell("этап не сошёлся", "text"),
            "где": Cell(str(getattr(этап, "имя", "")), "text"),
            "сказано": Cell(str(getattr(этап, "сказано", "")), "text"),
        })
    паспорт = getattr(проводка, "паспорт", None)
    for отказ in getattr(паспорт, "refusals", ()) or ():
        строки.append({
            "что": Cell("отказ приёма", "text"),
            "где": Cell(str(getattr(отказ, "code", "") or ""), "text"),
            "сказано": Cell(str(getattr(отказ, "reason", "") or отказ), "text"),
        })
    return строки


def ворота_рабочей(проводка=None, решения=None) -> Ворота:
    """Ворота рабочей книги: те же слагаемые, но спрошены не все.

    Это **не ослабление**: ни одно слагаемое здесь не смягчено, не пересчитано
    и не обойдено — ответы берутся у тех же ворот. Убрано другое: рабочая книга
    не утверждает полноту охвата источника, и потому не спрашивает о ней. То,
    чего документ не обещает, он не обязан и доказывать; а то, что обещает —
    закрытые человеком записи и сошедшийся итог, — обязано быть выполнено
    целиком, иначе книга не выходит.

    Полные ворота остаются полными и живут отдельно: ими выходит доказательный
    пакет.
    """
    все = ворота(проводка, решения)
    свои = tuple(с for с in все.слагаемые if с.ключ in СЛАГАЕМЫЕ_РАБОЧЕЙ)
    return Ворота(свои)


def _строки_оговорок() -> list[dict]:
    """Лист оговорок: по строке на утверждение, которого книга не делает."""
