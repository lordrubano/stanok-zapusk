# ------------------------------------------------------------ слагаемое


@dataclass(frozen=True, slots=True)
class Слагаемое:
    """Один ответ ворот: что спрошено, что отвечено и кто отвечал."""

    ключ: str
    ответ: str
    подробность: str = ""

    @property
    def вопрос(self) -> str:
        return _ВОПРОСЫ[self.ключ]

    @property
    def откуда(self) -> str:
        return _ОТКУДА[self.ключ]

    @property
    def выполнено(self) -> bool:
        """Неизвестность приравнена к невыполнению — как в движке политик."""
        return self.ответ == ДА

    def as_json(self) -> dict:
        return {"ключ": self.ключ, "вопрос": self.вопрос, "ответ": self.ответ,
                "выполнено": self.выполнено, "откуда": self.откуда,
                "подробность": self.подробность}


@dataclass(frozen=True, slots=True)
class Ворота:
    """Одно место, где проверки складываются в «можно / нельзя»."""

    слагаемые: tuple[Слагаемое, ...]
    версия: str = RELEASE_VERSION

    @property
    def можно(self) -> bool:
        return all(с.выполнено for с in self.слагаемые)

    @property
    def невыполненные(self) -> tuple[Слагаемое, ...]:
        return tuple(с for с in self.слагаемые if not с.выполнено)

    @property
    def почему(self) -> str:
        """Отказ называет слагаемые поимённо. Общего «нельзя» не бывает."""
        if self.можно:
            return ("все слагаемые выполнены: "
                    + "; ".join(f"{с.ключ} — {с.ответ}" for с in self.слагаемые))
        части = [f"{с.ключ} ({с.вопрос}) — {с.ответ}, отвечал {с.откуда}"
                 + (f": {с.подробность}" if с.подробность else "")
                 for с in self.невыполненные]
        return f"{ВЫПУСК_ЗАКРЫТ}: " + "; ".join(части)

    def as_json(self) -> dict:
        return {"версия": self.версия, "можно": self.можно,
                "почему": self.почему,
                "слагаемые": [с.as_json() for с in self.слагаемые]}


