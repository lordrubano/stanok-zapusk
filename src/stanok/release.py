_ТОЧКА = {ДА: "t-zel", НЕТ: "t-kras", НЕ_ИЗВЕСТНО: "t-zhel"}


def ворота_html(свои: Ворота) -> str:
    """Одно место «можно / нельзя» — и все слагаемые с ответами."""
    если_можно = свои.можно
    заголовок = ("● Выпуск разрешён: все слагаемые выполнены" if если_можно
                 else "⚠ Выпуск закрыт")
    куски = ['<div class="karta"><div class="mnk">Ворота выпуска</div>']
    if если_можно:
        куски.append('<div class="sopost"><div class="sost sost-zel">'
                     f"{_т(заголовок)}</div></div>")
    else:
        имена = ", ".join(с.ключ for с in свои.невыполненные)
        куски.append(f'<div class="vrezka"><b>{_т(заголовок)}</b><span>'
                     f"Не выполнено: {_т(имена)}. Общего «нельзя» не бывает — "
                     "ниже сказано, какое слагаемое каким ответом закрыло "
                     "ворота.</span></div>")
    куски.append('<table class="dok"><tr><th>Слагаемое</th><th>Вопрос</th>'
                 "<th>Ответ</th><th>Кто отвечал</th><th>Подробность</th></tr>")
    for с in свои.слагаемые:
        куски.append(
            f"<tr><td>{_т(с.ключ)}</td><td>{_т(с.вопрос)}</td>"
            f'<td><span class="tochka {_ТОЧКА.get(с.ответ, "t-ser")}"></span>'
            f"{_т(с.ответ)}</td><td>{_т(с.откуда)}</td>"
            f"<td>{_т(с.подробность) or '—'}</td></tr>")
    куски.append("</table>")
    куски.append('<div class="tih">Ворота не заводят своих проверок: они '
                 "спрашивают готовые и складывают ответ. Своя проверка здесь "
                 "была бы вторым мнением о том же. Неизвестность приравнена к "
                 "невыполнению — как в движке политик.</div></div>")
    return "".join(куски)


