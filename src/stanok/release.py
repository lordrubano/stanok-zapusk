"""Ворота выпуска: одно место, где проверки складываются в «можно / нельзя».

Шаг 87 плана. Нормативная основа — ТЗ на интерфейс 1.0, части VI и IV.

## Ворота не заводят своих проверок

Все проверки уже есть и работают: полнота (шаги 34–35), статусы записей
(шаг 45), итоги и балансы (шаг 41), учёт объектов (шаг 32). Ворота **спрашивают
готовые ответы и складывают их**, и больше не делают ничего.

Своя проверка здесь была бы **вторым мнением о том же**: разойдись она с
настоящей — верить нельзя ни одной, а сойдись — она ничего не добавила. То же
правило, по которому статус записи рождается в одном месте.

## Неизвестность приравнена к невыполнению

Ровно как в движке политик. Нет карты покрытия — не «ладно», а «неизвестно», и
неизвестное закрывает ворота. Иначе достаточно было бы не построить проверку,
чтобы она перестала мешать: самый лёгкий способ пройти ворота — не дать им
данных.

## Отказ называет слагаемое

Общего «нельзя» не бывает. Отказ говорит, какое именно слагаемое не выполнено,
каким ответом, и кто на этот вопрос отвечал. Оператору нужно знать, что чинить,
а не что запрещено.

## Два результата, а не один

Часть IV: клиентский результат и контрольный пакет — разные вещи, и едут они
порознь. Контрольная книга с пятью листами (DATA, REVIEW, REJECTED, ERRORS,
AUDIT) — доказательство производства; заставлять клиента работать с ней нельзя.

## Два класса выдачи, а не одна дверь с разной строгостью

**Рабочая книга** выходит, когда человек прошёл каждую запись и итоги документа
сошлись. Полноту охвата источника она **не утверждает** — и потому о ней не
спрашивает; первым её листом идёт прямой перечень того, чего книга не обещает,
человеческим языком.

**Доказательный пакет** выходит только при полных воротах: он ручается и за
полноту, а значит требует всей совокупности механизмов покрытия. Сегодня их не
хватает двух, и это нормальное состояние дел, а не поломка.

Разделение проходит **не по строгости, а по обещанию**. Ни одно слагаемое не
смягчено, не пересчитано и не обойдено: рабочая книга берёт ответы у тех же
ворот, просто задаёт два вопроса из четырёх, потому что за остальное не
ручается. Документ, который чего-то не обещает, не обязан это и доказывать — но
обещанное обязан выполнить целиком.

Обе книги собираются здесь и обе — настоящие книги Excel: клиентская с
колонками, объявленными оснасткой, и контрольная на пять листов. Собирает их
сборщик шага 31 со всеми его защитами, включая обратное чтение готового файла с
диска: «я записал» и «там лежит» — разные утверждения. Прежде сборщик в рабочем
пути не звался вовсе и жил только в проверках, а клиентский результат уходил
машинным файлом.

Что здесь **не** сделано и названо вслух: колонки взяты из оснастки, а не
согласованы с клиентом. Согласование — шаг 84, и выдавать одно за другое станок
не станет. Оснастка объявляет полосы разбора, а не вид выдачи: человеческих
заголовков в ней нет, порядка и ширины нет, а «сумма» объявлена дважды —
полосой дебета и полосой кредита, — и различает их только признак операции.
"""

