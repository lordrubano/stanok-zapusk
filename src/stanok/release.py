def _клиентские_колонки(оснастка) -> tuple[str, ...]:
    """Колонки клиентского результата — те, что объявила оснастка."""
    if оснастка is None:
        return ()
    from .columns import колонки

    имена = []
    for колонка in колонки(оснастка) or ():
        имя = (колонка.get("поле") if isinstance(колонка, dict)
               else getattr(колонка, "поле", None))
        if имя and имя not in имена:
            имена.append(str(имя))
    return tuple(имена)


def колонки_книги(оснастка) -> tuple[tuple[str, str, dict | None], ...]:
    """Колонки клиентской книги: имя в книге, поле записи и признак отбора.

    Оснастка объявляет **полосы разбора**, а не вид выдачи, и одно поле бывает
    объявлено дважды: «сумма» полосой дебета и полосой кредита. Свести их в
    одну колонку значило бы сложить списания с поступлениями; выкинуть одну —
    потерять половину сумм. Поэтому колонка книги называется полем и признаком,
    по которому полоса отобрана, а значение берётся только у тех записей, чей
    признак совпал.

    Человеческих заголовков оснастка не даёт вовсе — в книге стоят имена полей.
    """
    if оснастка is None:
        return ()
    from .columns import колонки

    собранные: list[tuple[str, str, dict | None]] = []
    for колонка in колонки(оснастка) or ():
        если_словарь = колонка if isinstance(колонка, dict) else None
        поле = (если_словарь.get("поле") if если_словарь
                else getattr(колонка, "поле", None))
        if not поле:
            continue
        признак = (если_словарь.get("признак") if если_словарь
                   else getattr(колонка, "признак", None))
        имя = str(поле)
        if признак:
            имя = f"{поле} ({признак.get('значение', 'признак')})"
        if any(имя == было for было, _, _ in собранные):
            continue
        собранные.append((имя, str(поле), признак))
    return tuple(собранные)


