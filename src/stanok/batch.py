# -*- coding: utf-8 -*-
"""Партия как объект учёта: набор документов, переживающий подачи.

Шаг 86 плана. Нормативная основа — ТЗ на интерфейс 1.0 (часть III) и пакет
интерфейса 1.2.

Партия держит остальные экраны: без неё приём показывает подачу, а не работу с
набором, а дашборд не знает, о чём он.

## Состояние партии рождается из состояний файлов

Ровно то же правило, что для записи: **статус в одном месте**. Оператор не
назначает партии состояние рукой — оно выводится :func:`состояние_партии` из
того, что стало с файлами. Кнопка «заблокировать» была бы здесь такой же
подменой, как кнопка, выдающая статус записи (шаг 45).

Отсюда следствие, которое важнее правила: **станок не показывает состояний,
которых не умеет вывести**. Из шести очередей ТЗ выводятся четыре — «новые»,
«обрабатываются», «проверить», «заблокировано». «Согласовать шаблон» появится с
шагом 84, «готово» — с воротами выпуска (шаг 87). До тех пор партия честно
говорит, что этих состояний не знает, а не притворяется, будто их не бывает.

## Партия не отменяет тождества документа

Один и тот же файл, поданный дважды, — **один документ**: тождество даётся
отпечатком байтов (шаг 62), и партия его не переопределяет. Повторная подача
добавляет не документ, а **подачу того же документа**: имя может отличаться,
время отличается, содержимое — нет.

Это не мелочь учёта. Партия, где один файл сосчитан дважды, врёт о своём
объёме, и врёт незаметно: числа сходятся между собой, а с действительностью
нет.

## Замена файла: механика здесь, лицо — нет

Действие «заменить файл» из ТЗ разделено надвое сознательно.

**Механика входит сюда**: без неё партия неполна как объект — отвергнутый файл
нечем исправить, и набор остаётся с дырой навсегда. Замена сделана **не
подменой, а добавлением**: прежний файл остаётся в партии со состоянием
:data:`ЗАМЕНЁН`, новый несёт ссылку на него. Это правило шага 59 в приложении к
партии: производное не переписывает первичное.

**Лица здесь нет**: кнопка живёт в режиме приёма, а он закрыт шагом 80 и
дополняется отдельно. Объект учёта умеет замену — экран для неё будет.
"""

