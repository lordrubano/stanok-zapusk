def шапка_html(партия: Партия) -> str:
    """Клиент, период, состояние набора — то, чего экрану не хватало.

    Состояние показано вместе с причиной: цвет без причины не в счёт.
    """
    свои = [("Клиент", партия.клиент or "не назван"),
            ("Период", партия.период or "не назван"),
            ("Партия", партия.идентификатор),
            ("Заведена", партия.заведена or "не записано"),
            ("Подач", str(len(партия.подачи)))]
    строки = ['<div class="karta"><div class="mnk">Партия</div>',
              '<table class="svoystva">']
    for имя, значение in свои:
        строки.append(f"<tr><th>{_т(имя)}</th><td>{_т(значение)}</td></tr>")
    строки.append("</table>")
    цвет = _ЦВЕТ_СОСТОЯНИЯ.get(партия.состояние, "sost-zhel")
    строки.append(f'<div class="sopost"><div class="sost {цвет}">● '
                  f"{_т(партия.состояние)} — {_т(почему_состояние(партия))}"
                  "</div></div></div>")
    return "".join(строки)


def плитки_html(партия: Партия) -> str:
    """Счёт по партии, а не по подаче. Тот же вид, что очереди на макете."""
    свои = [("документов", партия.документов, "pl-seraya"),
            ("принято", партия.сколько(ПРИНЯТ), "pl-zelenaya"),
            ("отвергнуто", партия.сколько(ОТВЕРГНУТ), "pl-krasnaya"),
            ("ждёт", партия.сколько(ЖДЁТ), "pl-seraya")]
    заменено = партия.сколько(ЗАМЕНЁН)
    if заменено:
        свои.append(("заменено", заменено, "pl-zheltaya"))
    куски = []
    for имя, сколько, цвет in свои:
        куски.append(f'<div class="plitka {цвет}"><div class="p">{_т(имя)}'
                     f'</div><div class="n">{сколько}</div></div>')
    return f'<div class="plitki">{"".join(куски)}</div>'


def сходимость_html(партия: Партия) -> str:
    """Сходимость **по партии**: за все подачи, а не за последнюю."""
    учтено = sum(ф.подач for ф in партия.файлы.values())
    повторов = учтено - len(партия.файлы)
    if партия.сошлось:
        хвост = f", из них повторных подач {повторов}" if повторов else ""
        return ('<div class="sopost"><div class="sost sost-zel">● Счёт по '
                f"партии сошёлся: подано {партия.положено} за "
                f"{len(партия.подачи)} подач = учтено {учтено}{_т(хвост)}"
                "</div></div>")
    свой = партия.свод().get("почему_не_сошлось", "")
    return ('<div class="vrezka"><b>⚠ Счёт по партии не сошёлся</b>'
            f"<span>{_т(свой)}</span></div>")


def подача_html(свод_подачи: dict | None) -> str:
    """Что дала последняя подача. Без неё не видно, куда делся поданный файл."""
    if not свод_подачи:
        return ""
    повторов = свод_подачи.get("повторов", 0)
    хвост = ""
    if повторов:
        хвост = (f", повторов {повторов} — тот же файл уже в партии, и вторым "
                 "документом он не станет")
    return ('<div class="sopost"><div class="sost">Последняя подача: положено '
            f"{свод_подачи.get('положено', 0)}, новых "
            f"{свод_подачи.get('новых', 0)}{_т(хвост)}</div></div>")


def файлы_html(партия: Партия) -> str:
    """Файлы партии: все, за все подачи. Прежние имена не теряются."""
    строки = ['<table class="dok"><tr><th>Файл</th><th>Состояние</th>'
              "<th>Причина</th><th>Размер</th><th>Подач</th></tr>"]
    for ф in партия.файлы.values():
        точка = ТОЧКА.get(ф.состояние, "t-ser")
        прежние = ""
        if len(ф.имена) > 1:
            свои = ", ".join(ф.имена[:-1])
            прежние = (f'<div class="tih">подавался также как '
                       f"<code>{_т(свои)}</code></div>")
        если_заменён = ""
        if ф.заменён_на:
            если_заменён = ('<div class="tih">заменён файлом '
                            f"<code>{_т(ф.заменён_на[:12])}</code></div>")
        elif ф.заменяет:
            если_заменён = ('<div class="tih">заменяет '
                            f"<code>{_т(ф.заменяет[:12])}</code></div>")
        размер = f"{ф.байт} б" if ф.байт is not None else "—"
        строки.append(
            f"<tr><td><code>{_т(ф.имя)}</code>{прежние}{если_заменён}</td>"
            f'<td><span class="tochka {точка}"></span>{_т(ф.состояние)}</td>'
            f"<td>{_т(ф.почему) or '—'}</td><td>{_т(размер)}</td>"
            f"<td>{ф.подач}</td></tr>")
    строки.append("</table>")
    return "".join(строки)


def невыводимое_html() -> str:
    """Названо прямо: каких состояний станок вывести не умеет и почему.

    Молчание тут читалось бы как «такого не бывает», а это неправда: бывает,
    просто механики за этим ещё нет.
    """
    свои = "; ".join(f"«{имя}» — {почему}"
                     for имя, почему in НЕВЫВОДИМЫЕ.items())
    return (f'<div class="snoska">Из шести очередей станок выводит четыре. '
            f"{_т(свои)}. Пока их нет, партия про них молчать не будет.</div>")


def оговорка_html() -> str:
    """Чего партии не хватает. На экране, а не в отчёте."""
    return ('<div class="tih">Замена файла есть как действие учёта, но кнопки '
            "для неё на этом экране нет: лицо замены — отдельная работа. "
            "Клиент и период станок хранит и показывает, но не проверяет: "
            "сверять их не с чем.</div>")


