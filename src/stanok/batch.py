# --------------------------------------------------------------- файл партии


@dataclass(frozen=True, slots=True)
class ФайлПартии:
    """Один документ в партии. Тождество — по отпечатку, не по имени."""

    отпечаток: str
    состояние: str
    имена: tuple[str, ...] = ()
    почему: str = ""
    байт: int | None = None
    подач: int = 1
    заменяет: str | None = None
    заменён_на: str | None = None

    @property
    def имя(self) -> str:
        """Как назван последний раз. Прежние имена не теряются."""
        return self.имена[-1] if self.имена else self.отпечаток[:12]

    def as_json(self) -> dict:
        return {"отпечаток": self.отпечаток, "состояние": self.состояние,
                "имена": list(self.имена), "почему": self.почему,
                "байт": self.байт, "подач": self.подач,
                "заменяет": self.заменяет, "заменён_на": self.заменён_на}


# --------------------------------------------------------------- партия


@dataclass
class Партия:
    """Набор документов одного дела. Переживает подачи."""

    идентификатор: str
    клиент: str = ""
    период: str = ""
    заведена: str = ""
    файлы: dict = field(default_factory=dict)
    подачи: list = field(default_factory=list)

    # ----------------------------------------------------------- состав

    @property
    def документов(self) -> int:
        """Документов в наборе. Заменённые не в счёт: их место занято новыми."""
        return sum(1 for ф in self.файлы.values() if ф.состояние != ЗАМЕНЁН)

    def сколько(self, состояние: str) -> int:
        return sum(1 for ф in self.файлы.values() if ф.состояние == состояние)

    @property
    def положено(self) -> int:
        """Сколько файлов подали за все подачи, включая повторные."""
        return sum(п["положено"] for п in self.подачи)

    @property
    def сошлось(self) -> bool:
        """Судьба известна у каждого поданного файла.

        Повторная подача того же документа не добавляет строки в набор, но и не
        теряется: она считается подачей. Сходимость проверяется по подачам, а
        не по числу документов — иначе повтор выглядел бы потерей.
        """
        учтено = sum(ф.подач for ф in self.файлы.values())
        return учтено == self.положено

    # ----------------------------------------------------------- подача

    def принять_подачу(self, приёмная, когда: str = "") -> dict:
        """Вносит поданное в партию. Один и тот же файл — один документ.

        Возвращает свод подачи: что ново, что повторено, что заменено.
        """
        когда = когда or _сейчас()
        новых, повторов = 0, 0
        for файл in приёмная.файлы:
            отпечаток = файл.отпечаток or _отпечаток_имени(файл)
            прежний = self.файлы.get(отпечаток)
            if прежний is None:
                self.файлы[отпечаток] = ФайлПартии(
                    отпечаток=отпечаток, состояние=файл.состояние,
                    имена=(файл.объявленное_имя,), почему=файл.почему,
                    байт=файл.байт)
                новых += 1
            else:
                # Тождество даётся отпечатком: это не новый документ, а новая
                # подача прежнего. Имя могло измениться — оно копится, а не
                # затирается: по прежнему имени клиент свой файл и помнит.
                имена = прежний.имена
                if файл.объявленное_имя not in имена:
                    имена = (*имена, файл.объявленное_имя)
                self.файлы[отпечаток] = ФайлПартии(
                    отпечаток=отпечаток, состояние=прежний.состояние,
                    имена=имена, почему=прежний.почему, байт=прежний.байт,
                    подач=прежний.подач + 1, заменяет=прежний.заменяет,
                    заменён_на=прежний.заменён_на)
                повторов += 1

        свод = {"когда": когда, "положено": приёмная.положено,
                "новых": новых, "повторов": повторов}
        self.подачи.append(свод)
        return свод

    # ----------------------------------------------------------- замена

    def заменить(self, отпечаток_прежнего: str, приёмка,
                 основание: str, когда: str = "") -> ФайлПартии:
        """Заменяет файл, не стирая прежнего.

        Прежний остаётся в партии со своим состоянием и причиной — иначе
        история набора теряется, а вместе с ней ответ на вопрос «почему здесь
        два файла с одним именем».
        """
        прежний = self.файлы.get(отпечаток_прежнего)
        if прежний is None:
            raise ValueError(
                f"заменять нечего: документа {отпечаток_прежнего[:12]} в "
                "партии нет")
        if not основание or len(основание.strip()) < 3:
            raise ValueError(
                "замена без основания не принимается: оно нужно тому, кто "
                "будет разбираться потом")

        новый_отпечаток = приёмка.отпечаток or _отпечаток_имени(приёмка)
        if новый_отпечаток == отпечаток_прежнего:
            raise ValueError(
                "заменяющий файл тот же самый: отпечаток совпал. Замена "
                "тем же ничего не меняет и только запутает набор")

        self.файлы[отпечаток_прежнего] = ФайлПартии(
            отпечаток=прежний.отпечаток, состояние=ЗАМЕНЁН,
            имена=прежний.имена,
            почему=f"{прежний.почему or 'заменён'} — {основание.strip()}",
            байт=прежний.байт, подач=прежний.подач,
            заменяет=прежний.заменяет, заменён_на=новый_отпечаток)
        новый = ФайлПартии(
            отпечаток=новый_отпечаток, состояние=приёмка.состояние,
            имена=(приёмка.объявленное_имя,), почему=приёмка.почему,
            байт=приёмка.байт, заменяет=отпечаток_прежнего)
        self.файлы[новый_отпечаток] = новый
        self.подачи.append({"когда": когда or _сейчас(), "положено": 1,
                            "новых": 1, "повторов": 0, "замена": True})
        return новый

    # ----------------------------------------------------------- состояние

    @property
    def состояние(self) -> str:
        return состояние_партии(self)

    def свод(self) -> dict:
        свой = {
            "версия": BATCH_VERSION,
            "идентификатор": self.идентификатор,
            "клиент": self.клиент or "не назван",
            "период": self.период or "не назван",
            "заведена": self.заведена,
            "состояние": self.состояние,
            "состояние_откуда": "выведено из состояний файлов",
            "документов": self.документов,
            "принято": self.сколько(ПРИНЯТ),
            "отвергнуто": self.сколько(ОТВЕРГНУТ),
            "ждёт": self.сколько(ЖДЁТ),
            "заменено": self.сколько(ЗАМЕНЁН),
            "подач": len(self.подачи),
            "положено_всего": self.положено,
            "сошлось": self.сошлось,
            "невыводимые_состояния": dict(НЕВЫВОДИМЫЕ),
            "файлы": [ф.as_json() for ф in self.файлы.values()],
        }
        if not self.сошлось:
            учтено = sum(ф.подач for ф in self.файлы.values())
            свой["почему_не_сошлось"] = (
                f"{ПАРТИЯ_НЕ_СОШЛАСЬ}: подано {self.положено} файлов за "
                f"{len(self.подачи)} подач, а учтено {учтено}. Потерянный файл "
                "опаснее отвергнутого: отвергнутый назван, потерянный молчит")
        return свой

    # ----------------------------------------------------------- хранение

    def записать(self, куда) -> Path:
        """Кладёт партию на диск. Она обязана пережить закрытие окна."""
        место = Path(куда)
        место.parent.mkdir(parents=True, exist_ok=True)
        место.write_text(json.dumps(self._как_запись(), ensure_ascii=False,
                                    indent=1), encoding="utf-8")
        return место

    def _как_запись(self) -> dict:
        return {"версия": BATCH_VERSION, "идентификатор": self.идентификатор,
                "клиент": self.клиент, "период": self.период,
                "заведена": self.заведена,
                "файлы": [ф.as_json() for ф in self.файлы.values()],
                "подачи": list(self.подачи)}


def прочитать(откуда) -> Партия:
    """Читает партию с диска. Состояние выводится заново, а не берётся из файла.

    Записанное состояние было бы вторым мнением о том же: разойдись оно с
    файлами — верить нельзя ни одному. Поэтому хранится только состав.
    """
    свой = json.loads(Path(откуда).read_text(encoding="utf-8"))
    партия = Партия(идентификатор=свой["идентификатор"],
                    клиент=свой.get("клиент", ""),
                    период=свой.get("период", ""),
                    заведена=свой.get("заведена", ""),
                    подачи=list(свой.get("подачи", ())))
    for ф in свой.get("файлы", ()):
        партия.файлы[ф["отпечаток"]] = ФайлПартии(
            отпечаток=ф["отпечаток"], состояние=ф["состояние"],
            имена=tuple(ф.get("имена", ())), почему=ф.get("почему", ""),
            байт=ф.get("байт"), подач=ф.get("подач", 1),
            заменяет=ф.get("заменяет"), заменён_на=ф.get("заменён_на"))
    return партия


# --------------------------------------------------------------- состояние


def состояние_партии(партия: Партия) -> str:
    """Единственное место, где рождается состояние партии.

    Выводится из состояний файлов и ниоткуда больше. Порядок правил не
    случаен: беда важнее хода, ход важнее покоя.
    """
    живые = [ф for ф in партия.файлы.values() if ф.состояние != ЗАМЕНЁН]
    if not живые:
        return ПУСТА
    if not партия.сошлось:
        return ЗАБЛОКИРОВАНА
    принятых = sum(1 for ф in живые if ф.состояние == ПРИНЯТ)
    if принятых == 0:
        # Все живые файлы отвергнуты: работать не с чем.
        return ЗАБЛОКИРОВАНА
    if any(ф.состояние == ЖДЁТ for ф in живые):
        return ОБРАБАТЫВАЮТСЯ
    return НОВЫЕ


def почему_состояние(партия: Партия) -> str:
    """Словами: отчего партия в этом состоянии. Цвет без причины не в счёт."""
    состояние = состояние_партии(партия)
    живые = [ф for ф in партия.файлы.values() if ф.состояние != ЗАМЕНЁН]
    if состояние == ПУСТА:
        return "в партии нет ни одного документа"
    if состояние == ЗАБЛОКИРОВАНА and not партия.сошлось:
        return партия.свод().get("почему_не_сошлось", "счёт не сошёлся")
    if состояние == ЗАБЛОКИРОВАНА:
        причины = {ф.почему for ф in живые if ф.почему}
        свои = "; ".join(sorted(причины)[:2]) or "все документы отвергнуты"
        return f"работать не с чем: {свои}"
    if состояние == ОБРАБАТЫВАЮТСЯ:
        сколько = sum(1 for ф in живые if ф.состояние == ЖДЁТ)
        return f"{_документов(сколько)} ещё не прошли приём"
    сколько = sum(1 for ф in живые if ф.состояние == ПРИНЯТ)
    один = сколько % 10 == 1 and сколько % 100 != 11
    сказуемое = "принят и ждёт" if один else "приняты и ждут"
    return f"{_документов(сколько)} {сказуемое} разбора"


def _документов(сколько: int) -> str:
    """Число со склонением: экран читает человек, а не машина."""
    сотня = сколько % 100
    if 11 <= сотня <= 14:
        return f"{сколько} документов"
    последняя = сколько % 10
    if последняя == 1:
        return f"{сколько} документ"
    if 2 <= последняя <= 4:
        return f"{сколько} документа"
    return f"{сколько} документов"


# --------------------------------------------------------------- заведение


def завести(клиент: str = "", период: str = "", когда: str = "") -> Партия:
    """Заводит партию. Идентификатор свой, а не имя клиента.

    Имя клиента недоверено так же, как имя файла, и в идентификатор не годится
    ни при каких условиях: по нему строятся пути и ссылки.
    """
    когда = когда or _сейчас()
    основа = f"{клиент}|{период}|{когда}".encode("utf-8")
    return Партия(идентификатор=hashlib.sha256(основа).hexdigest()[:16],
                  клиент=клиент.strip(), период=период.strip(), заведена=когда)


def _сейчас() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _отпечаток_имени(файл) -> str:
    """Запасной отпечаток, когда приём его не дал: отвергнутый файл.

    Отвергнутому документ-идентификатор не присваивается — приём до него не
    доходит. Но место в партии ему нужно, и различать такие файлы надо: два
    отвергнутых с разными именами — два разных файла.
    """
    основа = f"{файл.объявленное_имя}|{файл.байт}".encode("utf-8")
    return "нет-отпечатка-" + hashlib.sha256(основа).hexdigest()[:24]


