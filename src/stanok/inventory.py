# -*- coding: utf-8 -*-
"""Перечень состава выпуска: из чего собрано изделие.

Шаг 73 плана. Нормативная основа — чертёж v3.0, раздел 13.1.

Это не бюрократия. Мы продаём **доказуемость**, а происхождение кода станет
вопросом при первой же продаже аудитору: что внутри, чьё оно, под какой
лицензией и не числится ли за ним известной беды.

## Перечень собирается сборкой, а не пишется руками

Написанный руками перечень расходится с изделием на первом же обновлении — и
расходится молча, потому что сверять его не с чем. Здесь всё наоборот:

* состав снимается с **того самого дерева**, из которого собирается изделие;
* версия и лицензия каждой библиотеки читаются из **её собственной описи**, а
  не из нашей памяти;
* у каждого файла берётся отпечаток, и перечень **сверяется с изделием**
  (:func:`сверить`) — расхождение называется, а не предполагается.

Перечень едет внутри изделия. Лежащий рядом файл теряется при первой пересылке,
а внутренний уезжает к клиенту вместе с тем, что он описывает.

## Лицензия верхнего уровня не отменяет вложенных

Библиотека книги Excel уложена **внутрь** изделия (шаг 71) — значит её лицензия
едет вместе с ним, и текст лицензии тоже. :func:`лицензии` собирает все
обязательства разом: своё и всех вложенных. Отдельно проверяется, что у каждой
уложенной библиотеки есть и название лицензии, и её текст: название без текста
обязательства не исполняет.

## Известные уязвимости — и почему их нельзя знать самому

Уязвимости узнаются из ленты, лента приходит по сети, а станок в сеть не ходит
(шаг 65). Придумывать ленту он не станет. Поэтому здесь честное разделение:

* станок даёт **точный и датированный состав**: имя, версия, отпечаток. Этого
  довольно, чтобы кто угодно с лентой сверил его за минуту;
* сверка с лентой — :func:`сверить_с_лентой` — работает от поданной ленты. Нет
  ленты — так и сказано: ``проверено: false`` с причиной. Молчаливого «ничего не
  найдено» здесь нет: пустой ответ без ленты означал бы «мы посмотрели», а
  никто не смотрел.
"""

