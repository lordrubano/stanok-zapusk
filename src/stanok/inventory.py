# --------------------------------------------------------------- лицензии


@dataclass(frozen=True, slots=True)
class Составная:
    """Одна составная часть выпуска: своя или чужая."""

    имя: str
    версия: str
    лицензия: str
    происхождение: str
    отпечаток: str
    файлов: int
    текст_лицензии: str = ""
    в_тексте: tuple = ()

    def as_json(self) -> dict:
        return {"имя": self.имя, "версия": self.версия,
                "лицензия": self.лицензия,
                "происхождение": self.происхождение,
                "отпечаток": self.отпечаток, "файлов": self.файлов,
                "текст_лицензии": self.текст_лицензии,
                "лицензии_в_тексте": list(self.в_тексте)}


def _отпечаток_дерева(корень: Path) -> tuple[str, int]:
    """Отпечаток дерева файлов: путь и содержимое каждого, по порядку.

    Путь входит в отпечаток нарочно: перемещённый файл — другое дерево, даже
    если содержимое всех файлов прежнее.
    """
    сложение = hashlib.sha256()
    сколько = 0
    for путь in sorted(корень.rglob("*")):
        if not путь.is_file():
            continue
        сложение.update(путь.relative_to(корень).as_posix().encode("utf-8"))
        сложение.update(b"\x1f")
        сложение.update(hashlib.sha256(путь.read_bytes()).digest())
        сложение.update(b"\x1e")
        сколько += 1
    return сложение.hexdigest(), сколько


def _опись_библиотеки(имя: str, где: Path) -> tuple[str, str, str]:
    """Версия, лицензия и текст лицензии — из описи самой библиотеки.

    Читаем то, что положил её автор, а не то, что помним мы. Помним мы плохо, а
    обновляется библиотека без нашего участия.
    """
    доли = sorted(где.glob(f"{имя}-*.dist-info")) or sorted(
        где.glob(f"{имя.replace('_', '-')}-*.dist-info"))
    if not доли:
        return "не названа", "лицензия не названа", ""
    опись = доли[-1]
    версия = "не названа"
    лицензия = "лицензия не названа"
    сведения = опись / "METADATA"
    if сведения.is_file():
        текст = сведения.read_text(encoding="utf-8", errors="replace")
        for строка in текст.splitlines():
            if строка.startswith("Version:") and версия == "не названа":
                версия = строка.split(":", 1)[1].strip()
            elif строка.startswith("License:") and лицензия.startswith("лиценз"):
                значение = строка.split(":", 1)[1].strip()
                if значение:
                    лицензия = значение
            elif строка.startswith("Classifier: License ::") and \
                    лицензия.startswith("лиценз"):
                лицензия = строка.rsplit("::", 1)[-1].strip()

    текст_лицензии = ""
    for образец in ("LICENCE*", "LICENSE*", "COPYING*"):
        свои = sorted(опись.glob(образец))
        if свои:
            текст_лицензии = свои[0].read_text(encoding="utf-8",
                                               errors="replace")
            break
    return версия, лицензия, текст_лицензии


# Имена лицензий, которые ищутся в самом тексте. Перечень нужен потому, что
# объявленная лицензия и лицензии внутри текста — не одно и то же: библиотека
# может быть объявлена под MIT и нести внутри код под другой лицензией. Так и
# оказалось у одной из уложенных (шаг 73).
ИМЕНА_ЛИЦЕНЗИЙ = (
    ("MIT", "MIT Licence", "MIT License"),
    ("PSF", "PYTHON SOFTWARE FOUNDATION LICENSE", "Python Software Foundation"),
    ("BSD", "BSD LICENSE", "ZERO-CLAUSE BSD"),
    ("Apache", "Apache License"),
    ("GPL", "GNU General Public License"),
    ("LGPL", "GNU Lesser General Public"),
    ("MPL", "Mozilla Public License"),
)


def лицензии_в_тексте(текст: str) -> tuple[str, ...]:
    """Какие лицензии **упомянуты** в тексте — не какие на него наложены.

    Разница здесь не придирка, и куплена она ошибкой. Объявленная лицензия —
    то, что автор написал в поле описи; текст бывает богаче, и в нём случаются
    условия заимствованного кода. Но текст лицензии бывает и просто
    разговорчив: у одной из уложенных библиотек в тексте помянут GPL — не как
    условие, а как рассуждение о совместимости с ним.

    Поэтому здесь **упоминание, а не приговор**. Разбирает упоминания человек;
    станок лишь показывает, что поля описи для этой библиотеки мало.
    """
    если_нет = ()
    if not текст:
        return если_нет
    внизу = текст.lower()
    свои = []
    for имя, *приметы in ИМЕНА_ЛИЦЕНЗИЙ:
        if any(примета.lower() in внизу for примета in приметы):
            свои.append(имя)
    return tuple(свои)


def описать_уложенное(имя: str, куда_уложено: Path,
                      где_взято: Path) -> Составная:
    """Описывает одну уложенную внутрь изделия библиотеку."""
    версия, лицензия, текст = _опись_библиотеки(имя, где_взято)
    отпечаток, файлов = _отпечаток_дерева(куда_уложено)
    return Составная(имя, версия, лицензия, "уложена внутрь изделия",
                     отпечаток, файлов, текст,
                     лицензии_в_тексте(текст))


def лицензии(перечень: dict) -> dict:
    """Все обязательства выпуска разом: своё и всех вложенных.

    Лицензия верхнего уровня не отменяет вложенных: то, что уложено внутрь,
    едет со своей лицензией, и текст её обязан ехать тоже.
    """
    свои = []
    беды = []
    for часть in перечень.get("составные", ()):
        в_тексте = tuple(часть.get("лицензии_в_тексте") or ())
        свои.append({"имя": часть["имя"], "версия": часть["версия"],
                     "лицензия": часть["лицензия"],
                     "лицензии_в_тексте": list(в_тексте),
                     "текст_есть": bool(часть.get("текст_лицензии"))})
        объявленная = str(часть["лицензия"])
        сверх = [и for и in в_тексте if и.lower() not in объявленная.lower()]
        if сверх:
            беды.append({
                "код": ЛИЦЕНЗИЯ_ШИРЕ_ОБЪЯВЛЕННОЙ,
                "словами": (f"{часть['имя']} объявлена под {объявленная}, а в "
                            "тексте её лицензии помянуты и другие: "
                            + ", ".join(сверх)
                            + ". Это повод прочитать текст человеку, а не "
                            "готовый вывод: упоминание условием не является")})
        if часть["происхождение"] == "уложена внутрь изделия" and \
                not часть.get("текст_лицензии"):
            беды.append({
                "код": ЛИЦЕНЗИЯ_БЕЗ_ТЕКСТА,
                "словами": (f"{часть['имя']} уложена внутрь изделия, а текста "
                            "её лицензии рядом нет. Название лицензии "
                            "обязательства не исполняет")})
    # Обязательства — только объявленные лицензии. Упомянутое в тексте сюда не
    # подмешивается: смешать их значило бы выдать догадку за обязательство, а
    # аудитору мы продаём обратное.
    обязательства = sorted({ч["лицензия"]
                            for ч in перечень.get("составные", ())})
    упомянуто = sorted({и for ч in перечень.get("составные", ())
                        for и in (ч.get("лицензии_в_тексте") or ())})
    мешающие = [б for б in беды if б["код"] == ЛИЦЕНЗИЯ_БЕЗ_ТЕКСТА]
    return {"версия": SOSTAV_VERSION,
            "своя": перечень.get("лицензия", СВОЯ_ЛИЦЕНЗИЯ),
            "вложенные": свои,
            "объявленные_обязательства": обязательства,
            "упомянуто_в_текстах": упомянуто,
            "требует_прочтения": [б["словами"] for б in беды
                                  if б["код"] == ЛИЦЕНЗИЯ_ШИРЕ_ОБЪЯВЛЕННОЙ],
            "беды": беды, "всё_ли_есть": not мешающие}


# --------------------------------------------------------------- сверка


def сверить(перечень: dict, изделие) -> dict:
    """Сверяет перечень с собранным изделием. Расхождение называется.

    Проверяется то, ради чего перечень и существует: изделие собрано ровно из
    описанного. Считается по файлам внутри изделия, а не по нашей памяти о
    сборке.
    """
    место = Path(изделие)
    если_нет = {"версия": SOSTAV_VERSION, "сошлось": False,
                "почему": [{"код": СОСТАВ_РАЗОШЁЛСЯ,
                            "словами": f"изделия {место.name} нет на месте"}]}
    if not место.is_file():
        return если_нет

    расхождения = []
    отпечаток = hashlib.sha256(место.read_bytes()).hexdigest()
    если_обещан = перечень.get("отпечаток_изделия")
    if если_обещан and если_обещан != отпечаток:
        расхождения.append({
            "код": СОСТАВ_РАЗОШЁЛСЯ,
            "словами": ("отпечаток изделия не тот, что записан в перечне: "
                        "изделие пересобрано или подменено")})

    внутри = _файлы_изделия(место)
    названные = set()
    for часть in перечень.get("составные", ()):
        если_внутри = часть["происхождение"] == "уложена внутрь изделия"
        названные.add(часть["имя"])
        свои = [и for и in внутри if _путь_внутри(и, часть["имя"])]
        if не_нашлось := (если_внутри and not свои):
            расхождения.append({
                "код": СОСТАВ_РАЗОШЁЛСЯ,
                "словами": (f"{часть['имя']} записана в перечень, а внутри "
                            "изделия её нет")})
        if если_внутри and not не_нашлось:
            стало = _отпечаток_внутри(место, часть["имя"])
            if стало != часть["отпечаток"]:
                расхождения.append({
                    "код": СОСТАВ_РАЗОШЁЛСЯ,
                    "словами": (f"{часть['имя']} внутри изделия не та, что "
                                "записана в перечне: содержимое изменено "
                                "после сборки")})

    # Обратная сторона, и она для аудитора важнее прямой: код, приехавший в
    # изделии, но в перечень не попавший. Прямую беду видно и так, а эту —
    # только если искать нарочно.
    for имя in sorted(_верхние_имена(внутри) - названные - СЛУЖЕБНОЕ):
        расхождения.append({
            "код": СОСТАВ_РАЗОШЁЛСЯ,
            "словами": (f"внутри изделия лежит {имя}, которого в перечне нет: "
                        "состав описан неполно")})

    return {"версия": SOSTAV_VERSION, "сошлось": not расхождения,
            "файлов_в_изделии": len(внутри),
            "отпечаток_изделия": отпечаток,
            "почему": расхождения}


# Что лежит в изделии по праву сборки и составной частью не является.
СЛУЖЕБНОЕ = frozenset({"__main__.py", "СОСТАВ.json", "ЛИЦЕНЗИИ"})


def _верхние_имена(внутри) -> set:
    """Имена первого уровня внутри изделия: каталог или отдельный файл."""
    return {и.split("/", 1)[0] for и in внутри if и.strip("/")}


def _отпечаток_внутри(изделие: Path, имя: str) -> str:
    """Отпечаток уложенной библиотеки, снятый с самого изделия.

    Считается тем же способом, что и при сборке: путь, разделитель,
    содержимое. Два способа счёта дали бы два отпечатка и ни одного
    доказательства.
    """
    сложение = hashlib.sha256()
    with zipfile.ZipFile(изделие) as архив:
        свои = sorted(и for и in архив.namelist()
                      if _путь_внутри(и, имя) and not и.endswith("/"))
        for путь in свои:
            сложение.update(путь[len(имя) + 1:].encode("utf-8"))
            сложение.update(b"")
            сложение.update(hashlib.sha256(архив.read(путь)).digest())
            сложение.update(b"")
    return сложение.hexdigest()


def _путь_внутри(путь: str, имя: str) -> bool:
    """Файл принадлежит библиотеке, если лежит в её каталоге."""
    return путь == имя or путь.startswith(имя + "/")


def _файлы_изделия(изделие: Path) -> dict:
    with zipfile.ZipFile(изделие) as архив:
        return {и: архив.getinfo(и).file_size for и in архив.namelist()}


# --------------------------------------------------------------- уязвимости


def сверить_с_лентой(перечень: dict, лента=None) -> dict:
    """Сверяет состав с поданной лентой известных уязвимостей.

    Ленты нет — так и сказано. Пустой ответ без ленты означал бы «мы
    посмотрели», а никто не смотрел; это ровно тот довод, за который на шаге 64
    поплатилась вырезанная середина документа.

    Лента — перечень записей вида ``{"имя", "версии", "чем плохо", "код"}``.
    Откуда она взялась, станок не знает и знать не может: сети у него нет.
    """
    if лента is None:
        return {"версия": SOSTAV_VERSION, "проверено": False,
                "код": ЛЕНТЫ_НЕТ,
                "словами": ("ленты известных уязвимостей не подали. Станок в "
                            "сеть не ходит и ленту не выдумывает: он даёт "
                            "точный состав, сверить его с лентой может любой"),
                "совпадений": []}

    свои = {ч["имя"]: ч["версия"] for ч in перечень.get("составные", ())}
    совпадения = []
    for запись in лента:
        имя = запись.get("имя")
        if имя not in свои:
            continue
        версии = запись.get("версии") or ()
        if версии and свои[имя] not in версии:
            continue
        совпадения.append({"имя": имя, "версия": свои[имя],
                           "код": запись.get("код", "без кода"),
                           "чем_плохо": запись.get("чем_плохо", "не сказано")})
    return {"версия": SOSTAV_VERSION, "проверено": True,
            "составных_сверено": len(свои),
            "совпадений": совпадения,
            "чисто": not совпадения}


# --------------------------------------------------------------- перечень


def перечень_как_json(перечень: dict) -> str:
    return json.dumps(перечень, ensure_ascii=False, indent=1, sort_keys=True)


def прочитать_из_изделия(изделие) -> dict:
    """Читает перечень, уехавший внутри изделия.

    Лежащий рядом файл теряется при первой пересылке; внутренний уезжает к
    клиенту вместе с тем, что описывает.
    """
    место = Path(изделие)
    try:
        with zipfile.ZipFile(место) as архив:
            return json.loads(архив.read(ИМЯ_ВНУТРИ).decode("utf-8"))
    except (OSError, KeyError, zipfile.BadZipFile, ValueError) as беда:
        raise ValueError(
            f"перечня состава внутри {место.name} нет или он не читается: "
            f"{беда}") from беда


