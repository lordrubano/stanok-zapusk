# -*- coding: utf-8 -*-
"""Точки входа обработчиков для изолированного запуска.

Работа вне нумерации: клетка шага 24 стояла, но конвейер её не звал. Документ
шёл через розетку **в том же процессе**, и жёсткого принуждения по времени и
памяти на настоящем пути не было — только мягкий срок отметками, то есть
собственная вежливость разбора.

Здесь лежит то, чего не хватало для стыка: **обработчик, который можно назвать
именем**. Клетка запускает не предмет в памяти, а модуль и функцию: дочернему
процессу предмет не передать. Розетка выбирает вилку, а конвейер называет
клетке её движок — модулем и классом — и путь к файлу.

**Чего здесь нет и не будет.** Список штатных адаптеров: его тут быть не может
по тому же доводу, по которому его нет в розетке (шаг 25). Что запускать,
говорит вызывающий; обработчик только исполняет названное.

**Почему объекты уходят через JSON.** Дочерний процесс отдаёт ответ строкой, и
это не досадная мелочь, а суть изоляции: между разбором недоверенного входа и
ядром станка нет ничего, кроме простого текста. Никаких общих предметов,
никакой памяти на двоих. Цена этому — время на укладку и разбор, и она
измерена, а не забыта.
"""

from __future__ import annotations

import importlib

from .adapters import Розетка, SourceObject


HANDLERS_VERSION = "handlers/1"


def объект_в_json(объект: SourceObject) -> dict:
    """Объект источника в простой вид. Обратное — :func:`объект_из_json`."""
    return объект.as_json()


def объект_из_json(запись: dict) -> SourceObject:
    """Собирает объект источника обратно из простого вида.

    Собирается **ровно то, что уложено**: ни одно поле не достраивается по
    умолчанию. Потерянное при укладке обязано быть заметно здесь, а не всплыть
    через три уровня разбора.
    """
    полигон = запись.get("полигон")
    свойства = запись.get("свойства") or {}
    return SourceObject(
        document_id=запись["document_id"],
        страница=запись["страница"],
        система_координат=запись["система_координат"],
        структурный_путь=запись["структурный_путь"],
        сырой_текст=запись.get("сырой_текст"),
        полигон=tuple(tuple(точка) for точка in полигон) if полигон else None,
        свойства=tuple(свойства.items()),
        движок=запись.get("движок", ""),
        версия_движка=запись.get("версия_движка", ""),
    )


def извлечь(задача: dict) -> dict:
    """Извлекает объекты источника названным движком. Работает в клетке.

    Задача: ``путь`` — файл; ``движок`` — модуль и класс вилки; ``формат`` —
    чем выбирать вилку; ``document_id`` — постоянное имя документа.

    Файл читается **здесь**, а не передаётся байтами: гонять сто мегабайт через
    стандартный ввод незачем, а прав на чтение у обработчика ровно столько же,
    сколько у станка.
    """
    модуль = importlib.import_module(задача["движок"]["модуль"])
    вилка = getattr(модуль, задача["движок"]["класс"])()

    розетка = Розетка()
    розетка.подключить(вилка)

    with open(задача["путь"], "rb") as файл:
        данные = файл.read()

    конверт = _Конверт(задача.get("document_id", ""), задача.get("формат"))
    извлечение = розетка.извлечь(конверт, данные, формат=задача.get("формат"))
    return {
        "движок": извлечение.движок,
        "версия_движка": извлечение.версия_движка,
        "объекты": [объект_в_json(о) for о in извлечение.объекты],
        "refusals": [{"code": о.code, "message": о.message}
                     for о in извлечение.refusals],
    }


class _Конверт:
    """То немногое о документе, что нужно адаптеру: имя и формат."""

    __slots__ = ("document_id", "suffix")

    def __init__(self, document_id: str, формат: str | None) -> None:
        self.document_id = document_id
        self.suffix = f".{формат}" if формат else ""


def точка_входа(адаптер) -> dict | None:
    """Имя модуля и класса адаптера — то, чем его можно назвать клетке.

    Адаптер, собранный на месте (безымянный класс, замыкание, предмет из
    проверки), назвать нечем, и это не беда, а прямое следствие изоляции:
    дочернему процессу его не передать. Такой случай возвращает None, и
    вызывающий обязан решить, что делать, — молча выполнить его в своём
    процессе значило бы обойти клетку тайком.
    """
    порода = type(адаптер)
    модуль, имя = порода.__module__, порода.__qualname__
    if "." in имя or модуль in ("__main__", "builtins"):
        return None
    try:
        собранный = getattr(importlib.import_module(модуль), имя, None)
    except ImportError:
        return None
    if собранный is not порода:
        return None
    return {"модуль": модуль, "класс": имя}


