# -*- coding: utf-8 -*-
"""Запрет исправленного результата как нового источника.

Шаг 59 плана. Нормативная основа — чертёж v3.0, раздел 12: «запрет
использования исправленного результата как нового источника», «включение
исправления в корпус только после проверки разметки».

**Зачем запрет.** Оператор исправил значение — это его суждение, а не то, что
напечатано в бумаге. Подай исправленное на вход следующему разбору, и суждение
станет «прочитанным из документа»: у него появятся координаты, происхождение и
вид измеренного. Через два круга никто не отличит прочитанное от додуманного, а
доказательная связь, ради которой станок и существует, превратится в
самоподтверждение.

**Правило одно, и оно широкое: результат станка не бывает его входом.** Не
«исправленный результат», а любой — потому что различить их снаружи нельзя.
Выгрузка, поданная обратно, всегда означает одно: разбор второго круга по
разобранному, а не по документу.

Как это принуждается:

* **всё, что станок отдаёт наружу, помечено** словом-меткой. Метка не прячется:
  её видно и человеку, и машине;
* **приём отвергает файл с меткой** — до разбора, отказом с названной причиной;
* **разбор отвергает содержимое с меткой** — на случай, когда метка спрятана
  внутрь контейнера (книга Excel, архив) и в байтах файла её не видно;
* **производная запись не идёт эталоном**: сличать разбор с исправленным
  человеком значило бы мерить станок по его же ответу, поправленному вручную.

**Чего запрет не может.** Метку можно убрать: открыть выгрузку, стереть строку и
подать. Станок этого не заметит — и обещать обратное было бы враньём. Запрет
защищает от **невнимательности**, а не от умысла: от «взял вчерашнюю выгрузку,
она под рукой», а не от того, кто нарочно заметает следы. Защита от умысла —
права доступа и роли, и они лежат вне станка.
"""

from __future__ import annotations


DERIVED_VERSION = "derived-guard/1"

МЕТКА = "СТАНОК-РЕЗУЛЬТАТ-НЕ-ИСТОЧНИК"
"""Слово-метка на всём, что станок отдаёт наружу.

Латиницей и кириллицей одновременно её не пишут нарочно: метка обязана
находиться простым поиском по байтам, а не разбором формата.
"""

ПОЛЕ_МЕТКИ = "производное"
ПОЛЕ_ПЕРВИЧНОЙ = "первичная_запись"

КОД_ОТКАЗА = "E_DERIVED_INPUT"

ОБЪЯСНЕНИЕ = (
    "это результат станка, а не документ. Разбор разобранного превращает "
    "суждение оператора в «прочитанное из бумаги»: подайте исходный документ")

KNOWN_LIMITATIONS = (
    "Метку можно снять руками: открыть выгрузку, стереть строку и подать. "
    "Запрет защищает от невнимательности, а не от умысла; защита от умысла — "
    "права доступа, и они вне станка.",
    "В байтах файла метка ищется прямым поиском. У сжатых контейнеров (книга "
    "Excel, архив) её там не видно, и ловится она уже после извлечения — "
    "то есть позже, но до сборки записей.",
    "Производная запись узнаётся по своей пометке. Значение, переписанное в "
    "чужой программе без всякой пометки, для станка неотличимо от "
    "прочитанного — и это не дыра запрета, а граница знания.",
)


class ПроизводноеНеИсточник(ValueError):
    """Производное подано туда, где нужен первоисточник."""

    код = КОД_ОТКАЗА


# ---------------------------------------------------------------- метка


def пометить(что: dict, первичная: str = "") -> dict:
    """Ставит метку на то, что станок отдаёт наружу. Возвращает новый предмет."""
    свой = dict(что)
    свой[ПОЛЕ_МЕТКИ] = True
    свой["метка_станка"] = МЕТКА
    if первичная:
        свой[ПОЛЕ_ПЕРВИЧНОЙ] = первичная
    return свой


def производное_ли(что) -> bool:
    """Помечено ли это как результат станка."""
    if isinstance(что, dict):
        return bool(что.get(ПОЛЕ_МЕТКИ)) or что.get("метка_станка") == МЕТКА
    return False


def метка_в_байтах(данные: bytes, сколько: int = 1 << 20) -> bool:
    """Есть ли метка в файле. Смотрится начало и конец, а не всё целиком.

    Метка станка стоит в паспорте и в сводных строках — то есть в начале либо в
    конце. Читать сто мегабайт ради поиска слова незачем, а вот пропустить его
    из-за середины файла — можно, и об этом сказано в оговорках.
    """
    образец = МЕТКА.encode("utf-8")
    if len(данные) <= 2 * сколько:
        return образец in данные
    return образец in данные[:сколько] or образец in данные[-сколько:]


def метка_в_объектах(объекты, сколько: int = 500) -> bool:
    """Есть ли метка в извлечённом содержимом.

    Нужно для сжатых контейнеров: в байтах книги Excel метки не видно, а в её
    ячейках — видно. Смотрятся первые объекты: метка станка стоит в паспорте,
    а он идёт первым.
    """
    for место, объект in enumerate(объекты):
        if место >= сколько:
            return False
        текст = getattr(объект, "сырой_текст", None) or ""
        if МЕТКА in текст:
            return True
    return False


# --------------------------------------------------------------- запрет


def запретить_как_источник(что, где: str = "источник") -> None:
    """Роняет отказом, если подано производное. Молчит, если подан первоисточник."""
    if производное_ли(что):
        имя = что.get(ПОЛЕ_ПЕРВИЧНОЙ) or что.get("record_id") or "запись"
        raise ПроизводноеНеИсточник(
            f"{КОД_ОТКАЗА}: {где}: {имя} исправлена человеком и первоисточником "
            f"не является. {ОБЪЯСНЕНИЕ}")


def запретить_эталоном(записи) -> None:
    """Производное не идёт эталоном: мерить станок его же ответом нельзя."""
    for запись in (записи.values() if isinstance(записи, dict) else записи):
        запретить_как_источник(запись, где="эталон")


def отказ_приёма(откуда: str = "файл") -> tuple[str, str]:
    """Код и объяснение для паспорта входа."""
    return КОД_ОТКАЗА, f"{откуда}: {ОБЪЯСНЕНИЕ}"


