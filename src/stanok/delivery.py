# -*- coding: utf-8 -*-
"""Подпись поставки и право на работу: чьё изделие и кому оно продано.

Шаг 74 плана. Нормативная основа — чертёж v3.0, раздел 20.

Здесь закрывается названное на шагах 70 и 73: **подписи пакета нет** и
**доверие к сборочной машине не закрыто**.

## Отпечаток и подпись — разные вещи

Отпечаток (шаг 73) показывает **подмену**: изделие не то, что описано. Он
ничего не говорит об **авторстве**: собрать своё изделие, посчитать его
отпечаток и записать в свой перечень может кто угодно. Всё сойдётся, и всё
будет чужим.

Авторство даёт подпись: свидетельство подписывается тайным ключом, который
живёт на сборочной машине и никуда не уезжает; проверяется общедоступным, и
проверить может любой.

## Проверка не требует ни сети, ни двоичной библиотеки

Два требования, и оба непереговорные.

**Ни сети.** Проверка права на работу, требующая сети, отменяет товарное
свойство, за которое клиент платит: станок работает на машине без сети (шаг 65).
Здесь наружу не идёт ничего: подпись, ключ и право — файлы рядом с изделием.

**Ни двоичной библиотеки.** Проверка Ed25519 сделана счётом на самом языке
(:mod:`stanok.ed25519_pure`), потому что двоичная библиотека подписей у клиента
необязательна (шаг 71). Свойство, доступное не всякому покупателю, товарным не
является. Подписание — обратное дело: оно требует библиотеки и делается только
у нас, на сборочной машине.

## Право на работу проверяется вычитанием, а не разрешением

Право — подписанный нами файл: кому продано, до какого числа, на какие
семейства. Станок читает его, проверяет подпись и сверяет с сегодняшним днём.
Никто ничего не разрешает по сети: разрешение уже лежит на диске, и всё, что
делает станок, — читает и считает.

Просроченное или чужое право даёт **отказ с внятной причиной**, а не тихое
ухудшение работы. Тихое ухудшение — худший вид защиты: клиент решает, что
сломался товар.

## Где кончается техническая защита

Прямо и без прикрас, потому что изображать защиту от того, от чего защищает
только право, — обман покупателя.

**Техническая защита может:**

* доказать, что изделие и пакет пришли от нас, — тому, кто **хочет** это
  проверить: клиенту, аудитору, суду;
* отличить наш пакет от собранного кем угодно;
* показать подмену изделия после сборки;
* дать однозначный ответ, действует ли право на работу на названное число.

**Техническая защита не может:**

* помешать тому, у кого изделие уже есть, вырезать проверку. Код исполняется на
  чужой машине, и её хозяин сильнее любой проверки внутри. Это не наша слабость
  — это устройство мира;
* помешать перевести часы назад и продлить себе срок;
* помешать поставить изделие на большее число машин, чем куплено;
* доказать, что подписал именно владелец, а не тот, кто добрался до тайного
  ключа. Ключ — предмет охраны, а не следствие подписи.

**Начинается договор.** Всё перечисленное во втором списке закрывается не кодом,
а обязательством: право пользования, число машин, запрет передачи третьим лицам,
ответственность за обход. Техническая защита делает нарушение **видимым и
доказуемым**, а не невозможным. Продавать её как невозможность — врать.

Отсюда же граница проверки самого ядра. Ядро, проверяющее свою подпись само,
доказывает ровно ничего: подменивший ядро подменит и ключ в нём, и проверку.
Ядро проверяется **снаружи** — открытым ключом издателя, полученным другим
путём (из договора, с нашей страницы). Пакеты оснастки — другое дело: их
проверяет ядро, которому клиент уже доверяет, и вот это осмысленно.
"""

