# --------------------------------------------------------------- подписание


def _требуется_библиотека():
    try:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric.ed25519 import (
            Ed25519PrivateKey,
        )
    except ImportError as беда:  # pragma: no cover — проверяется установкой
        raise RuntimeError(
            "E_LIB_MISSING: подписание требует двоичной библиотеки подписей. "
            "Оно делается на сборочной машине, а не у клиента: проверка "
            "подписи работает и без неё") from беда
    return serialization, Ed25519PrivateKey


def завести_ключ() -> tuple[bytes, bytes]:
    """Заводит ключевую пару. Делается один раз и у владельца.

    Возвращает (тайный, открытый) в сырых байтах. Тайный ключ на клиентскую
    машину не попадает никогда — иначе подписать сможет и клиент.
    """
    serialization, Ed25519PrivateKey = _требуется_библиотека()
    ключ = Ed25519PrivateKey.generate()
    тайный = ключ.private_bytes(
        serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
        serialization.NoEncryption())
    открытый = ключ.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return тайный, открытый


def _подписать_байты(что: bytes, тайный: bytes) -> bytes:
    serialization, Ed25519PrivateKey = _требуется_библиотека()
    return Ed25519PrivateKey.from_private_bytes(тайный).sign(что)


def _в_строку(байты: bytes) -> str:
    return base64.b64encode(байты).decode("ascii")


def _из_строки(строка) -> bytes:
    if not isinstance(строка, str):
        return b""
    try:
        return base64.b64decode(строка.encode("ascii"), validate=True)
    except Exception:
        return b""


def _подписываемое(свидетельство: dict) -> bytes:
    """Байты, которые подписываются. Порядок ключей закреплён сортировкой.

    Подпись в подписываемое не входит: иначе подписать было бы нечего.
    """
    без_подписи = {к: з for к, з in свидетельство.items() if к != "подпись"}
    return json.dumps(без_подписи, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def подписать_изделие(путь, тайный: bytes, открытый: bytes, кем: str,
                      когда: str, что: str = "ядро") -> dict:
    """Свидетельство авторства для собранного изделия.

    Подписывается **отпечаток изделия**, а не само изделие: подпись должна
    остаться проверяемой, не читая мегабайты, и лечь рядом файлом.
    """
    место = Path(путь)
    свидетельство = {
        "версия": POSTAVKA_VERSION,
        "что": что,
        "файл": место.name,
        "отпечаток": hashlib.sha256(место.read_bytes()).hexdigest(),
        "алгоритм": АЛГОРИТМ,
        "издатель": кем,
        "открытый_ключ": _в_строку(открытый),
        "подписано": когда,
    }
    свидетельство["подпись"] = _в_строку(
        _подписать_байты(_подписываемое(свидетельство), тайный))
    return свидетельство


# --------------------------------------------------------------- проверка


@dataclass(frozen=True, slots=True)
class Отказ:
    код: str
    словами: str

    def as_json(self) -> dict:
        return {"код": self.код, "словами": self.словами}


def проверить_изделие(путь, свидетельство, доверенный_ключ: str = "") -> dict:
    """Проверяет, что изделие пришло от названного издателя.

    Три вопроса и все три обязательны: то ли это изделие, сошлась ли подпись и
    **тот ли это издатель**. Без третьего проверка бесполезна: подпись всегда
    сходится с тем ключом, который к ней приложен.
    """
    место = Path(путь)
    беды: list[Отказ] = []

    if not свидетельство:
        return _ответ([Отказ(НЕТ_ПОДПИСИ,
                             f"у {место.name} нет свидетельства авторства: "
                             "чьё это изделие, сказать нечем")])

    if not место.is_file():
        return _ответ([Отказ(НЕТ_ПОДПИСИ, f"изделия {место.name} нет на месте")])

    отпечаток = hashlib.sha256(место.read_bytes()).hexdigest()
    if отпечаток != свидетельство.get("отпечаток"):
        беды.append(Отказ(
            ПОДПИСЬ_НЕ_СОШЛАСЬ,
            "свидетельство подписано для другого изделия: отпечаток не тот. "
            "Изделие подменено или свидетельство чужое"))

    ключ = _из_строки(свидетельство.get("открытый_ключ"))
    подпись = _из_строки(свидетельство.get("подпись"))
    if свидетельство.get("алгоритм") != АЛГОРИТМ:
        беды.append(Отказ(
            ПОДПИСЬ_НЕ_СОШЛАСЬ,
            f"подпись сделана неизвестным способом "
            f"{свидетельство.get('алгоритм')!r}: проверить её нечем"))
    elif not _проверить_подпись(_подписываемое(свидетельство), подпись, ключ):
        беды.append(Отказ(
            ПОДПИСЬ_НЕ_СОШЛАСЬ,
            "подпись не сошлась: свидетельство изменено после подписания"))

    доверенный = доверенный_ключ or ОТКРЫТЫЙ_КЛЮЧ_ИЗДАТЕЛЯ
    if not доверенный:
        беды.append(Отказ(
            ИЗДАТЕЛЬ_НЕ_ОБЪЯВЛЕН,
            "открытый ключ издателя не объявлен: подпись проверена сама с "
            "собой, а это не доказывает ничего. Ключ берётся из договора или "
            "с нашей страницы, а не из подписанного файла"))
    elif доверенный != свидетельство.get("открытый_ключ"):
        беды.append(Отказ(
            ЧУЖОЙ_ИЗДАТЕЛЬ,
            "изделие подписано не тем ключом, которому вы доверяете: подпись "
            "своя, но издатель чужой"))

    return _ответ(беды)


def _ответ(беды) -> dict:
    # «Подпись сошлась» — про саму подпись и только про неё. Чужой издатель и
    # необъявленный ключ — беды не подписи, а доверия, и смешивать их значило
    # бы отвечать не на заданный вопрос.
    решающие = [б for б in беды
                if б.код in (НЕТ_ПОДПИСИ, ПОДПИСЬ_НЕ_СОШЛАСЬ)]
    return {"версия": POSTAVKA_VERSION,
            "наше": not беды,
            "подпись_сошлась": not решающие,
            "почему": [б.as_json() for б in беды]}


# --------------------------------------------------------------- право


def выдать_право(кому: str, до: str, семейства, выпуск: str, тайный: bytes,
                 открытый: bytes, кем: str) -> dict:
    """Право на работу: кому продано, до какого числа, на что.

    Выдаётся у нас и подписывается тем же ключом, что изделия.
    """
    право = {
        "версия": POSTAVKA_VERSION,
        "что": "право на работу",
        "кому": кому,
        "до": до,
        "семейства": sorted(семейства),
        "выпуск": выпуск,
        "алгоритм": АЛГОРИТМ,
        "издатель": кем,
        "открытый_ключ": _в_строку(открытый),
    }
    право["подпись"] = _в_строку(
        _подписать_байты(_подписываемое(право), тайный))
    return право


def проверить_право(право, сегодня: str, кому: str = "", семейство: str = "",
                    доверенный_ключ: str = "") -> dict:
    """Действует ли право. Считается на месте, без единого обращения наружу.

    Сегодняшний день подаётся снаружи нарочно: часы — дело окружения, а не
    станка, и подмешивать их сюда значило бы делать проверку непроверяемой.
    """
    беды: list[Отказ] = []
    if not право:
        return {"версия": POSTAVKA_VERSION, "действует": False,
                "почему": [Отказ(НЕТ_ПОДПИСИ,
                                 "права на работу нет вовсе").as_json()],
                "сети_не_требовалось": True}

    ключ = _из_строки(право.get("открытый_ключ"))
    подпись = _из_строки(право.get("подпись"))
    if not _проверить_подпись(_подписываемое(право), подпись, ключ):
        беды.append(Отказ(ПОДПИСЬ_НЕ_СОШЛАСЬ,
                          "подпись права не сошлась: право изменено после "
                          "выдачи"))

    доверенный = доверенный_ключ or ОТКРЫТЫЙ_КЛЮЧ_ИЗДАТЕЛЯ
    if доверенный and доверенный != право.get("открытый_ключ"):
        беды.append(Отказ(ЧУЖОЙ_ИЗДАТЕЛЬ,
                          "право подписано не тем ключом, которому вы "
                          "доверяете"))

    if str(сегодня) > str(право.get("до", "")):
        беды.append(Отказ(
            ПРАВО_ПРОСРОЧЕНО,
            f"право действовало до {право.get('до')}, а сегодня {сегодня}. "
            "Работа не начинается: это отказ с причиной, а не поломка"))

    if кому and кому != право.get("кому"):
        беды.append(Отказ(
            ПРАВО_ЧУЖОЕ,
            f"право выдано на {право.get('кому')!r}, а машина объявлена "
            f"{кому!r}"))

    if семейство and семейство not in (право.get("семейства") or ()):
        беды.append(Отказ(
            ПРАВО_НЕ_ПОКРЫВАЕТ,
            f"право не покрывает семейство {семейство!r}: куплены "
            + ", ".join(право.get("семейства") or ["ничего"])))

    return {"версия": POSTAVKA_VERSION, "действует": not беды,
            "кому": право.get("кому"), "до": право.get("до"),
            "почему": [б.as_json() for б in беды],
            "сети_не_требовалось": True}


