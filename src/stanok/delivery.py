ИМЯ_ПОДПИСИ = ".podpis.json"
ИМЯ_ПРАВА = "pravo.json"


def записать_свидетельство(изделие, свидетельство) -> Path:
    место = Path(изделие)
    рядом = место.with_suffix(место.suffix + ИМЯ_ПОДПИСИ)
    рядом.write_text(json.dumps(свидетельство, ensure_ascii=False, indent=1),
                     encoding="utf-8")
    return рядом


def прочитать_свидетельство(изделие) -> dict | None:
    место = Path(изделие)
    рядом = место.with_suffix(место.suffix + ИМЯ_ПОДПИСИ)
    if not рядом.is_file():
        return None
    try:
        return json.loads(рядом.read_text(encoding="utf-8"))
    except ValueError:
        return None


