"""Адаптеры нативных маршрутов: XLSX и DOCX.

Шаг 26 плана. Нормативная основа — чертёж v3.0, раздел 5.1 (компонент 3
«Адаптеры извлечения», выход ``SourceObject[]``), раздел 5.3 (нативный маршрут
для XLSX и DOCX с сохранением типов, формул, объединений, скрытых листов и
точности) и раздел 14.1 (запрет XXE и внешних сущностей).

**Почему нативно.** Офисный файл легко превратить в текст или разметку и
разбирать уже её. Так делать нельзя: при таком превращении теряется ровно то,
ради чего продукт существует — тип ячейки, формула за числом, объединение
ячеек, точный адрес, скрытые строки и листы, а главное — числовая точность.
Пересказ выглядит убедительно и молча врёт.

Поэтому пакет разбирается по частям, как он есть: читается разметка листа, и из
неё берутся **сырые** значения ровно в том виде, в каком они записаны. Число не
превращается в число языка: `0.1 + 0.2` в двоичной дроби даёт `0.30000000000000004`,
и деньги от такого превращения перестают сходиться. Сырая строка `1234.5000000001`
сохраняется строкой, а истолкование — дело типизатора (шаг 29).

**Внешние сущности.** Каждая часть пакета проверяется до разбора: объявление
типа документа и объявление сущности отвергают весь документ. Подробности —
``stanok.xmlsafe``.

Что не делается здесь: ни один разобранный признак не истолковывается. Формула
не вычисляется, дата не разбирается, число не округляется. Адаптер отдаёт
источник как он есть — истолкование начинается позже и отдельно.
"""

