class ДокументDOCX:
    """Нативный разбор документа: абзацы и таблицы со структурными адресами."""

    имя = "нативный-docx"
    версия = "1"
    форматы = frozenset({"docx", "docm"})

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        document_id = getattr(конверт, "document_id", "") or ""
        пакет = _части(данные)
        with пакет:
            корень = _разобрать_часть(пакет, "word/document.xml")
            if корень is None:
                raise ValueError("в пакете нет части документа word/document.xml")
            тело = корень.find(f"{_ДОК}body")
            if тело is None:
                return
            yield from self._тело(document_id, тело, "тело")

    def _тело(self, document_id, узел, путь) -> Iterator[SourceObject]:
        абзац_номер = 0
        таблица_номер = 0
        for ребёнок in узел:
            if ребёнок.tag == f"{_ДОК}p":
                абзац_номер += 1
                yield self._абзац(document_id, ребёнок,
                                  f"{путь}/абзац[{абзац_номер}]")
            elif ребёнок.tag == f"{_ДОК}tbl":
                таблица_номер += 1
                yield from self._таблица(
                    document_id, ребёнок, f"{путь}/таблица[{таблица_номер}]")

    def _абзац(self, document_id, абзац, путь) -> SourceObject:
        стиль_узел = абзац.find(f"{_ДОК}pPr/{_ДОК}pStyle")
        свойства = [("вид", "абзац")]
        if стиль_узел is not None:
            свойства.append(("стиль", стиль_узел.get(f"{_ДОК}val", "")))
        # Число кусков сохраняем: разбиение на куски несёт разметку, и
        # склеенный текст этого уже не покажет.
        свойства.append(("кусков", len(абзац.findall(f".//{_ДОК}t"))))
        return SourceObject(
            document_id=document_id,
            страница=1,
            система_координат="структура документа",
            структурный_путь=путь,
            сырой_текст=_текст(абзац, f"{_ДОК}t"),
            полигон=None,
            свойства=tuple(свойства),
        )

    def _таблица(self, document_id, таблица, путь) -> Iterator[SourceObject]:
        for номер_строки, строка in enumerate(
                таблица.findall(f"{_ДОК}tr"), start=1):
            for номер_ячейки, ячейка in enumerate(
                    строка.findall(f"{_ДОК}tc"), start=1):
                охват = ячейка.find(f"{_ДОК}tcPr/{_ДОК}gridSpan")
                слияние = ячейка.find(f"{_ДОК}tcPr/{_ДОК}vMerge")
                адрес = f"{путь}/строка[{номер_строки}]/ячейка[{номер_ячейки}]"
                свойства = [("вид", "ячейка таблицы")]
                if охват is not None:
                    свойства.append(("объединение_столбцов",
                                     охват.get(f"{_ДОК}val", "")))
                if слияние is not None:
                    свойства.append(("объединение_строк",
                                     слияние.get(f"{_ДОК}val", "продолжение")))
                yield SourceObject(
                    document_id=document_id,
                    страница=1,
                    система_координат="структура документа",
                    структурный_путь=адрес,
                    сырой_текст=_текст(ячейка, f"{_ДОК}t"),
                    полигон=None,
                    свойства=tuple(свойства),
                )


