_ОСН = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
_ДОК = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
_СВЯЗИ = "{http://schemas.openxmlformats.org/package/2006/relationships}"
_ОТН = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"


def _части(данные: bytes) -> zipfile.ZipFile:
    try:
        return zipfile.ZipFile(io.BytesIO(данные))
    except (zipfile.BadZipFile, OSError, ValueError) as беда:
        raise ValueError(f"пакет не читается: {беда}") from беда


def _прочитать(пакет: zipfile.ZipFile, имя: str) -> bytes | None:
    try:
        return пакет.read(имя)
    except KeyError:
        return None


def _разобрать_часть(пакет: zipfile.ZipFile, имя: str):
    данные = _прочитать(пакет, имя)
    if данные is None:
        return None
    return разобрать(данные, имя)


def _текст(узел, метка: str) -> str:
    """Собирает текст всех кусков подряд, сохраняя порядок и пробелы."""
    return "".join(кусок.text or "" for кусок in узел.iter(метка))


# ------------------------------------------------------------------- книга


def _общие_строки(пакет: zipfile.ZipFile) -> list[str]:
    корень = _разобрать_часть(пакет, "xl/sharedStrings.xml")
    if корень is None:
        return []
    return [_текст(запись, f"{_ОСН}t") for запись in корень.findall(f"{_ОСН}si")]


def _листы(пакет: zipfile.ZipFile) -> list[tuple[str, str, str]]:
    """Листы книги: имя, состояние и путь к части листа."""
    книга = _разобрать_часть(пакет, "xl/workbook.xml")
    связи = _разобрать_часть(пакет, "xl/_rels/workbook.xml.rels")
    if книга is None:
        raise ValueError("в пакете нет части книги xl/workbook.xml")

    куда = {}
    if связи is not None:
        for связь in связи.findall(f"{_СВЯЗИ}Relationship"):
            куда[связь.get("Id")] = связь.get("Target", "")

    итог = []
    for лист in книга.iter(f"{_ОСН}sheet"):
        имя = лист.get("name", "")
        состояние = лист.get("state", "visible")
        цель = куда.get(лист.get(f"{_ОТН}id"), "")
        итог.append((имя, состояние, _путь_части(цель)))
    return итог


def _путь_части(цель: str) -> str:
    """Путь к части пакета по ссылке из описи связей.

    Ссылка бывает трёх видов, и все три встречаются в настоящих файлах:
    абсолютная от корня пакета («/xl/worksheets/sheet1.xml»), уже полная
    («xl/worksheets/sheet1.xml») и относительная от книги
    («worksheets/sheet1.xml»). Разбирать только последний вид — значит молча
    не найти лист в файле, записанном обычной библиотекой.
    """
    цель = (цель or "").replace("\\", "/")
    if цель.startswith("/"):
        return цель.lstrip("/")
    if цель.startswith("xl/"):
        return цель
    return f"xl/{цель}"


def _объединения(лист) -> dict[str, str]:
    """Адрес ячейки -> область объединения, в которую она входит."""
    итог = {}
    for область in лист.iter(f"{_ОСН}mergeCell"):
        диапазон = область.get("ref", "")
        если_есть = диапазон.split(":")[0] if диапазон else ""
        if если_есть:
            итог[если_есть] = диапазон
    return итог


class КнигаXLSX:
    """Нативный разбор книги: ячейка за ячейкой, как записано."""

    имя = "нативный-xlsx"
    версия = "1"
    форматы = frozenset({"xlsx", "xlsm"})

    def извлечь(self, конверт, данные: bytes, срок=None) -> Iterator[SourceObject]:
        if срок is not None:
            # Работа здесь конечна по устройству — она идёт по строкам, листам
            # или сообщениям, и зациклиться ей не на чем. Но уже израсходованный
            # запас файла обязан остановить и её: тратить остаток на разбор,
            # итог которого всё равно будет отброшен, незачем.
            срок.проверить()
        document_id = getattr(конверт, "document_id", "") or ""
        пакет = _части(данные)
        with пакет:
            строки = _общие_строки(пакет)
            for номер_листа, (имя_листа, состояние, путь) in enumerate(
                    _листы(пакет), start=1):
                корень = _разобрать_часть(пакет, путь)
                if корень is None:
                    # Молча пропустить лист нельзя. Пропущенный лист выглядит
                    # как пустой, и выписка теряет строки без единого следа —
                    # ровно то, чего продукт обещает не допускать.
                    raise ValueError(
                        f"лист «{имя_листа}» объявлен, но части {путь} в пакете "
                        "нет: разбор неполон и потому отвергнут")
                объединения = _объединения(корень)
                скрытые_столбцы = {
                    столбец.get("min"): столбец.get("max")
                    for столбец in корень.iter(f"{_ОСН}col")
                    if столбец.get("hidden") == "1"
                }
                for строка in корень.iter(f"{_ОСН}row"):
                    строка_скрыта = строка.get("hidden") == "1"
                    for ячейка in строка.findall(f"{_ОСН}c"):
                        yield self._ячейка(
                            document_id, номер_листа, имя_листа, состояние,
                            строка, строка_скрыта, ячейка, строки, объединения,
                            скрытые_столбцы)

    def _ячейка(self, document_id, номер_листа, имя_листа, состояние, строка,
                строка_скрыта, ячейка, общие, объединения, скрытые_столбцы):
        адрес = ячейка.get("r", "")
        тип = ячейка.get("t", "n")
        формула_узел = ячейка.find(f"{_ОСН}f")
        значение_узел = ячейка.find(f"{_ОСН}v")

        # Сырое значение берём строкой ровно как записано. Превращать его в
        # число языка нельзя: двоичная дробь меняет запись, и деньги перестают
        # сходиться. Истолкование — дело типизатора.
        сырое = значение_узел.text if значение_узел is not None else None
        if тип == "s" and сырое is not None:
            try:
                сырое = общие[int(сырое)]
            except (ValueError, IndexError):
                сырое = None
        elif тип == "inlineStr":
            встроенная = ячейка.find(f"{_ОСН}is")
            сырое = _текст(встроенная, f"{_ОСН}t") if встроенная is not None else None

        столбец = "".join(знак for знак in адрес if знак.isalpha())
        свойства = [
            ("лист", имя_листа),
            ("лист_скрыт", состояние != "visible"),
            ("адрес", адрес),
            ("тип_ячейки", тип),
            ("строка_скрыта", строка_скрыта),
            ("столбец", столбец),
        ]
        if формула_узел is not None:
            свойства.append(("формула", формула_узел.text or ""))
        if адрес in объединения:
            свойства.append(("объединение", объединения[адрес]))
        if ячейка.get("s") is not None:
            свойства.append(("стиль", ячейка.get("s")))
        if скрытые_столбцы:
            свойства.append(("есть_скрытые_столбцы", True))

        return SourceObject(
            document_id=document_id,
            страница=номер_листа,
            система_координат="лист-ячейка",
            структурный_путь=f"лист[{имя_листа}]/ячейка[{адрес}]",
            сырой_текст=сырое,
            полигон=None,
            свойства=tuple(свойства),
        )


