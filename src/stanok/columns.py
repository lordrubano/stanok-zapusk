# -*- coding: utf-8 -*-
"""Сопоставление колонок с полями и чтение реквизитов документа.

Работа вне нумерации, Фаза 4. Нормативная основа — чертёж v3.0, раздел 7
(группа «Адресация»: колонки) и раздел 6.1.

Конвейер до сих пор раскладывал ячейки по полям **по порядку** — первую ячейку
в первое объявленное поле, вторую во второе. Это было названо заведомо неверным
ещё до встречи с настоящим документом, и настоящий документ это подтвердил: у
него колонок восемь, заполненных ячеек семь, одна колонка пуста, а две колонки
делят одно поле.

Здесь ячейка попадает в поле **по своему месту на листе**, а места объявляет
оснастка долями листа. Ядро не знает ни одного числа семейства.

**Две колонки под одно поле — обычное дело, а не исключение.** У выписки сумма
стоит либо в колонке дебета, либо в колонке кредита, и колонка, в которой она
оказалась, **и есть знак операции**. Поэтому колонка вправе объявить, какое
значение положить в поле признака: знак берётся из вёрстки документа, а не
угадывается по самой сумме.

**Реквизиты документа** — счёт, период, валюта, входящий и исходящий остатки,
обороты — лежат на первой странице парами «метка — значение». Метку объявляет
оснастка, значение берётся из соседней ячейки справа. Ядро не ищет реквизиты по
догадке и не выдумывает их: не объявлено — не прочитано.

**Реквизит записан для человека, а не для станка.** Валюта счёта стоит словами
(«Российский рубль»), а сумма остатка — с приписанным обозначением валюты в
конце. Ни то, ни другое ядро не разбирает само: догадка о том, что последние
четыре знака суть валюта, ошибётся на первом же семействе, где так не пишут.
Поэтому семейство вправе объявить у реквизита **хвост, который отбрасывается**,
и **словарь, по которому значение переводится**. Оба объявления — данные, и оба
требуют основания.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, InvalidOperation


COLUMNS_VERSION = "columns/1"

KNOWN_LIMITATIONS = (
    "Колонка задаётся полосой долей листа. Семейству с плавающей вёрсткой "
    "этого мало, и понадобится иной способ адресации колонки.",
    "Значение реквизита берётся из ближайшей ячейки справа от метки. "
    "Реквизит, у которого значение стоит снизу или через ячейку, потребует "
    "своего объявления.",
    "Ячейка, не попавшая ни в одну объявленную колонку, объявляется лишней и "
    "в поля не идёт. Молча приписать её соседнему полю нельзя: поле, собранное "
    "из чужой колонки, выглядит как прочитанное.",
)


@dataclass(frozen=True, slots=True)
class _Выведенное:
    """Поле без своей ячейки: значение выведено правилом колонки.

    Адрес берётся у колонки, из которой выведено, и вместе с ним — пояснение
    «откуда». Выдать такое поле за прочитанное из своей ячейки нельзя: оно
    прочитано не было.
    """

    текст: str
    ячейка: object
    откуда: str


def _полоса(объявление):
    try:
        от = Decimal(str(объявление.get("от")))
        до = Decimal(str(объявление.get("до")))
    except (InvalidOperation, TypeError):
        return None
    return (от, до) if от <= до else None


def _x(ячейка):
    try:
        return Decimal(str(ячейка.столбец))
    except (InvalidOperation, TypeError):
        return None


def колонки(оснастка) -> tuple:
    if оснастка is None:
        return ()
    адресация = оснастка.содержимое.get("адресация") or {}
    объявленные = адресация.get("колонки")
    return tuple(объявленные) if isinstance(объявленные, list) else ()


def разложить_по_колонкам(строка, оснастка) -> tuple[dict, tuple, tuple]:
    """Раскладывает ячейки строки по объявленным колонкам.

    Возвращает поля, лишние ячейки и **повторы** — колонки, в которые попало
    больше одной ячейки.

    В поле кладётся **сама ячейка**, а не только её текст: без ячейки не
    построить адрес области, а без адреса поле непрослеживаемо.

    **Две ячейки в одной колонке — не значение, а неопределённость.** Раньше
    бралась первая, а вторая молча поглощалась; корпус дефектов шага 50 показал
    это буквально: повторённая ячейка исчезала бесследно, и станок не замечал
    дубля вовсе. Выбрать одну из двух здесь нельзя — какая из них настоящая,
    знает документ, а не станок, — поэтому поле остаётся незаполненным, а
    повтор называется вслух. Незаполненное поле поймает проверка
    обязательности; поглощённое не ловил никто.
    """
    свои = колонки(оснастка)
    if not свои:
        return {}, tuple(я.адрес for я in строка.ячейки), ()

    попавшие: dict = {}
    признаки: dict = {}
    занятые = set()
    for объявление in свои:
        полоса = _полоса(объявление)
        имя = объявление.get("поле")
        if полоса is None or not имя:
            continue
        от, до = полоса
        for ячейка in строка.ячейки:
            x = _x(ячейка)
            if x is None or not (от <= x <= до):
                continue
            занятые.add(ячейка.адрес)
            попавшие.setdefault(имя, []).append(ячейка)
            # Колонка вправе объявить, что её заполненность и есть признак:
            # у выписки это дебет против кредита, то есть знак операции.
            # Своей ячейки у такого поля нет, и адрес оно получает от той
            # колонки, из которой выведено, — вместе с пояснением, откуда.
            признак = объявление.get("признак")
            if признак:
                признаки.setdefault(признак["поле"], _Выведенное(
                    признак["значение"], ячейка,
                    f"по колонке {имя!r}: сумма стоит в ней"))

    поля: dict = {}
    повторы = []
    for имя, ячейки in попавшие.items():
        if len(ячейки) == 1:
            поля[имя] = ячейки[0]
            continue
        повторы.append({
            "поле": имя,
            "ячеек": len(ячейки),
            "адреса": tuple(я.адрес for я in ячейки),
            "почему": "в объявленную колонку попало больше одной ячейки: какая "
                      "из них значение поля, знает документ, а не станок",
        })
    for имя, выведенное in признаки.items():
        поля.setdefault(имя, выведенное)

    лишние = tuple(я.адрес for я in строка.ячейки if я.адрес not in занятые)
    return поля, лишние, tuple(повторы)


# ------------------------------------------------------- реквизиты


def реквизиты_объявлены(оснастка) -> tuple:
    if оснастка is None:
        return ()
    адресация = оснастка.содержимое.get("адресация") or {}
    объявленные = адресация.get("реквизиты")
    return tuple(объявленные) if isinstance(объявленные, list) else ()


def _очистить(значение: str, объявление, словари) -> str:
    """Убирает объявленный хвост и переводит по объявленному словарю.

    Ни то, ни другое не делается по догадке: и хвост, и словарь называет
    семейство. Значение, которого нет в объявленном словаре, остаётся как есть
    — подставить вместо него что-нибудь похожее значило бы прочитать не то,
    что написано.
    """
    хвост = объявление.get("отбросить_хвост")
    if хвост and значение.endswith(хвост):
        значение = значение[: -len(хвост)].strip()
    имя_словаря = объявление.get("словарь")
    словарь = словари.get(имя_словаря) if имя_словаря else None
    if словарь and значение in словарь:
        return словарь[значение]
    return значение


def прочитать_реквизиты(строки, оснастка) -> tuple[dict, tuple[str, ...]]:
    """Читает реквизиты документа по объявленным меткам.

    Возвращает найденное и перечень объявленных, но не найденных. Не найденный
    реквизит — это «нет», а не «ноль»: подставить ноль значило бы сообщить
    проверкам величину, которой в документе никто не видел.
    """
    объявленные = реквизиты_объявлены(оснастка)
    if not объявленные:
        return {}, ()

    словари = ((оснастка.содержимое.get("нормализация") or {}).get("словари")
               or {})
    найдено: dict = {}
    for объявление in объявленные:
        имя, метка = объявление.get("имя"), объявление.get("метка")
        if not имя or not метка:
            continue
        for строка in строки:
            ячейки = list(строка.ячейки)
            for место, ячейка in enumerate(ячейки):
                if (ячейка.текст or "").strip() != метка:
                    continue
                if место + 1 < len(ячейки):
                    найдено[имя] = _очистить(
                        ячейки[место + 1].текст.strip(), объявление, словари)
                break
            if имя in найдено:
                break
    не_найдены = tuple(о["имя"] for о in объявленные
                       if о.get("имя") and о["имя"] not in найдено)
    return найдено, не_найдены


