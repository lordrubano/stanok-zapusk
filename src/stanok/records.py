# -*- coding: utf-8 -*-
"""Границы записи: где кончается одна операция и начинается следующая.

Работа вне нумерации, Фаза 4. Нормативная основа — чертёж v3.0, раздел 7
(группа «Адресация»: ожидаемые продолжения) и раздел 8.2.

Сегментатор (шаг 32) собирает **текстовые строки**. Одна операция выписки
занимает несколько строк: назначение платежа и наименование контрагента
переносятся. Склеить их по счёту — «каждые три строки суть одна операция» —
нельзя: на первом же настоящем документе длина операции оказалась от трёх строк
до одиннадцати. Склеивать надо по правилу, и правило это — свойство семейства,
а не догадка ядра.

**Что отличает первую строку операции от её продолжения.** Ядро исполняет один
закрытый вид правила: **первая строка начинается в объявленной полосе слева, а
продолжения в неё не заходят**. Полосу объявляет оснастка долями листа, и ядро
не знает ни одного числа наперёд.

Вид выбран не из удобства, а по измерению на первом настоящем документе: у него
строки-операции начинаются в самой левой полосе все до одной, а продолжения
смещены вправо — в колонки контрагента и назначения — и **ни одно не заходит в
левую полосу ни разу**. Такое разделение и делает правило исполнимым.

**Учёт обязан сходиться, как и в сегментаторе.** Каждая поданная строка обязана
оказаться либо внутри записи, либо в перечне «вне записей» с названной причиной:
шапка, реквизиты страницы, строка до первой операции. Молча потерять строку
нельзя — потерянная строка означает потерянные деньги, и ни один последующий
уровень её не хватится.

**Продолжение не переносится через страницу.** Операция, начатая на одной
странице, здесь на другую не продолжается: перенос между страницами — дело
сшивки продолжений (шаг 36), у которой свои доказательства. Считать соседство
по странице переносом значило бы склеить две разные операции, если последняя
строка страницы окажется началом новой.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation


RECORDS_VERSION = "records/1"

# Виды правила границы, которые ядро умеет исполнять. Набор закрыт по тому же
# доводу, что и виды межполевых правил шага 42: пакет остаётся данными.
ВИДЫ_ГРАНИЦЫ = ("ячейка_в_полосе",)

KNOWN_LIMITATIONS = (
    "Вид правила один: первая строка узнаётся по ячейке в объявленной полосе "
    "слева. Семейству, где операции различаются иначе — отступом, линейкой, "
    "цветом, — понадобится новый вид в языке и новый выпуск ядра.",
    "Полоса объявляется долями листа. У семейства с другой вёрсткой доли "
    "другие, и переносить их с одного семейства на другое нельзя.",
    "Продолжение через границу страницы здесь не собирается: это сшивка "
    "продолжений, шаг 36.",
    "Строки до первой операции на странице объявляются «вне записей» с "
    "причиной, но что именно они означают — шапку, реквизиты или мусор — "
    "решает не этот уровень.",
)


@dataclass(frozen=True, slots=True)
class Запись:
    """Одна операция: первая строка и её продолжения."""

    адрес: str
    страница: int
    первая: object
    продолжения: tuple = ()

    @property
    def строк(self) -> int:
        return 1 + len(self.продолжения)

    @property
    def все_строки(self) -> tuple:
        return (self.первая,) + tuple(self.продолжения)

    def as_json(self) -> dict:
        return {"адрес": self.адрес, "страница": self.страница,
                "строк": self.строк,
                "ячеек_в_первой": len(self.первая.ячейки)}


@dataclass(frozen=True, slots=True)
class ВнеЗаписей:
    """Строка, не вошедшая ни в одну запись, и почему."""

    адрес: str
    страница: int
    причина: str

    def as_json(self) -> dict:
        return {"адрес": self.адрес, "страница": self.страница,
                "причина": self.причина}


@dataclass(frozen=True, slots=True)
class Сборка:
    """Итог сборки записей. Учёт обязан сходиться."""

    версия: str = RECORDS_VERSION
    записи: tuple = ()
    вне_записей: tuple = ()
    подано_строк: int = 0
    беды: tuple = ()

    @property
    def учтено_строк(self) -> int:
        return sum(з.строк for з in self.записи) + len(self.вне_записей)

    @property
    def учёт_сходится(self) -> bool:
        return self.учтено_строк == self.подано_строк

    def as_json(self) -> dict:
        return {
            "версия": self.версия,
            "записей": len(self.записи),
            "вне_записей": len(self.вне_записей),
            "подано_строк": self.подано_строк,
            "учтено_строк": self.учтено_строк,
            "учёт_сходится": self.учёт_сходится,
            "беды": list(self.беды),
        }


def _полоса(правило) -> tuple[Decimal, Decimal] | None:
    полоса = (правило or {}).get("полоса")
    if not isinstance(полоса, dict):
        return None
    try:
        от = Decimal(str(полоса.get("от")))
        до = Decimal(str(полоса.get("до")))
    except (InvalidOperation, TypeError):
        return None
    return (от, до) if от <= до else None


def _правило(оснастка):
    if оснастка is None:
        return None
    адресация = оснастка.содержимое.get("адресация") or {}
    правило = адресация.get("граница_записи")
    return правило if isinstance(правило, dict) else None


def _в_полосе(ячейка, от: Decimal, до: Decimal) -> bool:
    try:
        x = Decimal(str(ячейка.столбец))
    except (InvalidOperation, TypeError):
        return False
    return от <= x <= до


def _подходит_тип(ячейка, тип) -> bool:
    """Проверяет вид содержимого ячейки, если оснастка его объявила.

    Проверка нарочно грубая: здесь решается не «что это за значение», а «эта ли
    строка начинает операцию». Истолкование — дело типизатора, и подменять его
    тут значило бы делать одну работу дважды и по-разному.
    """
    if not тип:
        return True
    текст = (ячейка.текст or "").strip()
    if тип == "дата":
        части = текст.replace("/", ".").replace("-", ".").split(".")
        return (len(части) == 3 and all(ч.isdigit() for ч in части)
                and len(части[-1]) in (2, 4))
    if тип == "число":
        return any(з.isdigit() for з in текст)
    if тип == "непусто":
        return bool(текст)
    return False


def начинает_запись(строка, правило) -> bool:
    """Начинает ли строка новую операцию по объявленному правилу."""
    полоса = _полоса(правило)
    if полоса is None:
        return False
    от, до = полоса
    тип = (правило or {}).get("тип")
    return any(_в_полосе(я, от, до) and _подходит_тип(я, тип)
               for я in строка.ячейки)


def собрать(строки, оснастка=None, срок=None) -> Сборка:
    """Собирает строки в записи по объявленному оснасткой правилу границы.

    Правила нет — записей нет: ядро не выдумывает границу операции. Это не
    молчаливый отказ, а объявленная беда, и все строки уходят «вне записей».
    """
    from .deadline import место as срок_места

    (срок if срок is not None else срок_места("сборка страниц")).проверить()
    строки = list(строки)
    правило = _правило(оснастка)

    if правило is None:
        return Сборка(
            RECORDS_VERSION, (), tuple(
                ВнеЗаписей(с.адрес, с.страница,
                           "правило границы записи оснасткой не объявлено")
                for с in строки), len(строки),
            ("правило границы записи оснасткой не объявлено: где кончается "
             "одна операция и начинается следующая, знает семейство, а не ядро",))

    вид = правило.get("вид")
    if вид not in ВИДЫ_ГРАНИЦЫ:
        return Сборка(
            RECORDS_VERSION, (), tuple(
                ВнеЗаписей(с.адрес, с.страница,
                           f"вид правила границы {вид!r} ядру неизвестен")
                for с in строки), len(строки),
            (f"вид правила границы {вид!r} ядру неизвестен; ядро умеет: "
             + ", ".join(ВИДЫ_ГРАНИЦЫ),))

    if _полоса(правило) is None:
        return Сборка(
            RECORDS_VERSION, (), tuple(
                ВнеЗаписей(с.адрес, с.страница, "полоса объявлена негодно")
                for с in строки), len(строки),
            ("полоса границы объявлена негодно: нужны «от» и «до» десятичными "
             "строками, и «от» не больше «до»",))

    записи: list[Запись] = []
    вне: list[ВнеЗаписей] = []
    текущая: list = []
    первая = None
    страница_текущей = None

    def закрыть():
        nonlocal первая, текущая, страница_текущей
        if первая is not None:
            записи.append(Запись(f"{первая.адрес}/запись", первая.страница,
                                 первая, tuple(текущая)))
        первая, текущая, страница_текущей = None, [], None

    for строка in строки:
        # Страница сменилась — открытая запись закрывается. Перенос операции
        # между страницами доказывает сшивка продолжений, а не соседство.
        if страница_текущей is not None and строка.страница != страница_текущей:
            закрыть()

        if начинает_запись(строка, правило):
            закрыть()
            первая, текущая, страница_текущей = строка, [], строка.страница
        elif первая is not None:
            текущая.append(строка)
        else:
            вне.append(ВнеЗаписей(
                строка.адрес, строка.страница,
                "строка до первой операции страницы: шапка, реквизиты или "
                "заголовок"))
    закрыть()

    return Сборка(RECORDS_VERSION, tuple(записи), tuple(вне), len(строки))


def свод(сборка: Сборка) -> dict:
    """Счётчики сборки. Длина записи — наблюдение, а не норма."""
    длины: dict[int, int] = {}
    for запись in сборка.записи:
        длины[запись.строк] = длины.get(запись.строк, 0) + 1
    ячейки: dict[int, int] = {}
    for запись in сборка.записи:
        сколько = len(запись.первая.ячейки)
        ячейки[сколько] = ячейки.get(сколько, 0) + 1
    return {
        **сборка.as_json(),
        "длина_записи": dict(sorted(длины.items())),
        "ячеек_в_первой_строке": dict(sorted(ячейки.items())),
    }


__all__ = ["KNOWN_LIMITATIONS", "RECORDS_VERSION", "ВИДЫ_ГРАНИЦЫ", "ВнеЗаписей",
           "Запись", "Сборка", "начинает_запись", "свод", "собрать"]
