# ------------------------------------------------------- сам узел


@dataclass(frozen=True, slots=True)
class Страница:
    """Готовая страница: путь, заголовок и как её построить."""

    путь: str
    заголовок: str
    построить: object
    принять: object = None
    # Отдать файл вместо страницы. Зовётся вместо ``построить`` и возвращает
    # (имя, тип содержимого, байты). Заведено для книги Excel: узел умел
    # отвечать только разметкой, и скачать собранное было нечем — человеку
    # предлагалось искать файл на диске самому.
    отдать_файл: object = None


def _путь_из_запроса(строка: str) -> str:
    """Разбирает путь запроса и не даёт выйти за пределы своего.

    Двойник защиты от обхода каталогов в архивах (шаг 22): «..» и хитрая
    запись знаков не должны выводить за границы. Здесь путей на диске нет
    вовсе, но правило то же — сначала привести к простому виду, потом судить.
    """
    сырой = unquote(urlparse(строка).path or "/")
    свой = PurePosixPath(сырой)
    if any(часть == ".." for часть in свой.parts):
        raise ValueError(f"{ВЫХОД_ИЗ_КАТАЛОГА}: в пути запроса есть «..»")
    приведённый = str(PurePosixPath("/", *[ч for ч in свой.parts if ч != "/"]))
    return приведённый or "/"


def _имя_хозяина(заголовок: str | None) -> str:
    """Имя из заголовка ``Host`` без порта и скобок, в нижнем регистре."""
    if not заголовок:
        return ""
    return заголовок.rsplit(":", 1)[0].strip("[]").lower()


def _свой_ли_хозяин(заголовок: str | None, порт: int,
                    наружу: str = "") -> bool:
    """Обращаются ли к нам по нашему же адресу.

    Без этой проверки чужая страница в браузере может увести браузер на наш
    узел по подставленному имени и прочитать ответ. Имя должно быть петлевым.

    ``наружу`` — **одно** имя сверх петлевых, названное при подъёме узла. Оно
    нужно веб-контуру: труба приводит обращение снаружи с тем именем, под
    которым станок виден в сети, и петлевого имени в заголовке уже не будет.
    Ослабление сделано узко и осознанно: не «любое имя», а ровно то, которое
    названо доводом. Не названо — прежний запрет в силе целиком, и всякое
    чужое имя получает отказ.
    """
    имя = _имя_хозяина(заголовок)
    if not имя:
        return False
    if имя in ("127.0.0.1", "localhost", "::1"):
        return True
    свой = _имя_хозяина(наружу) if наружу else ""
    return bool(свой) and имя == свой


class _Обработчик(BaseHTTPRequestHandler):
    страницы: dict = {}
    порт: int = ПОРТ_ПО_УМОЛЧАНИЮ
    наружу: str = ""
    после_приёма: object = None
    server_version = "stanok"
    sys_version = ""

    def log_message(self, формат, *доводы):  # noqa: N802 — имя чужое
        """Молчим: путь запроса может нести содержимое документа."""

    def do_GET(self):  # noqa: N802 — имя чужое
        if not _свой_ли_хозяин(self.headers.get("Host"), self.порт,
                               self.наружу):
            self._отдать(421, "<h1>Не тот адрес</h1><p class=tih>"
                              f"{ЧУЖОЙ_АДРЕС}: узел отвечает только на "
                              "обращения к этой машине.</p>")
            return
        try:
            путь = _путь_из_запроса(self.path)
        except ValueError:
            self._отдать(400, "<h1>Негодный путь</h1>")
            return

        страница = self.страницы.get(путь)
        if страница is None:
            self._отдать(404, "<h1>Такой страницы нет</h1>"
                              f"<p class=tih>Известные: "
                              f"{обезвредить(', '.join(sorted(self.страницы)))}"
                              "</p>")
            return
        if getattr(страница, "отдать_файл", None) is not None:
            try:
                готовое = страница.отдать_файл()
            except Exception as беда:  # noqa: BLE001 — беда не валит узел
                self._отдать(500, "<h1>Файл не отдан</h1>"
                                  f"<p class=tih>{обезвредить(type(беда).__name__)}"
                                  "</p>")
                return
            # Файла нет — не беда узла, а ответ по существу: страница скажет
            # почему. Отдавать здесь пятисотую значило бы называть поломкой
            # закрытые ворота, а они работают именно так, как должны.
            if готовое is not None:
                имя, тип, байты = готовое
                self._отдать_байты(имя, тип, байты)
                return
        try:
            тело = страница.построить()
        except Exception as беда:  # noqa: BLE001 — беда страницы не валит узел
            # Текст чужой беды в страницу не пойдёт: в нём может оказаться
            # кусок документа. Наружу — только род беды.
            self._отдать(500, "<h1>Страница не собралась</h1>"
                              f"<p class=tih>{обезвредить(type(беда).__name__)}"
                              "</p>")
            return
        self._отдать(200, тело, страница.заголовок)

    def do_POST(self):  # noqa: N802 — имя чужое
        """Принимает только там, где приём объявлен. Прочее — отказ.

        Узел до шага 80 не принимал ничего вовсе. Приём документов это
        изменил, и изменение сделано узко: принимает **одна** объявленная
        страница, всё остальное отвечает отказом, как и прежде.
        """
        if not _свой_ли_хозяин(self.headers.get("Host"), self.порт,
                               self.наружу):
            self._отдать(421, "<h1>Не тот адрес</h1>")
            return
        try:
            путь = _путь_из_запроса(self.path)
        except ValueError:
            self._отдать(400, "<h1>Негодный путь</h1>")
            return

        страница = self.страницы.get(путь)
        приём = getattr(страница, "принять", None) if страница else None
        if приём is None:
            self._отдать(405, "<h1>Эта страница ничего не принимает</h1>")
            return

        сколько = int(self.headers.get("Content-Length") or 0)
        if сколько > ПРЕДЕЛ_ПРИЁМА:
            self._отдать(413, "<h1>Слишком много за раз</h1>"
                              f'<p class=tih>Предел приёма — {ПРЕДЕЛ_ПРИЁМА} '
                              "байт за один раз.</p>")
            return
        тело_запроса = self.rfile.read(сколько) if сколько else b""
        try:
            тело = приём(тело_запроса, self.headers.get("Content-Type", ""))
        except Exception as беда:  # noqa: BLE001 — беда приёма не валит узел
            self._отдать(500, "<h1>Приём не состоялся</h1>"
                              f"<p class=tih>{обезвредить(type(беда).__name__)}"
                              "</p>")
            return

        # Принятое действие закрепляется до ответа человеку, а не после.
        # Иначе экран сказал бы «сделано» о том, что живёт только в памяти
        # машины: на площадке, где машина засыпает с чистым диском, это и есть
        # потеря работы. Не закрепилось — человеку говорится прямо, а не
        # показывается зелёный экран.
        if self.после_приёма is not None:
            try:
                self.после_приёма()
            except Exception as беда:  # noqa: BLE001 — сказать, а не молчать
                self._отдать(500,
                             "<h1>Сделано, но не сохранено</h1>"
                             "<p>Действие принято этой машиной, но в дальнее "
                             "хранилище не легло. При засыпании машины оно "
                             "пропадёт.</p>"
                             f"<p class=tih>{НЕ_ЗАКРЕПЛЕНО}: "
                             f"{обезвредить(type(беда).__name__)}</p>"
                             "<p class=tih>Повторите действие: если хранилище "
                             "отозвалось, оно ляжет вместе с прежними.</p>")
                return
        self._отдать(200, тело, страница.заголовок)

    def _отдать_байты(self, имя: str, тип: str, байты: bytes):
        """Отдаёт файл. Тем же узлом, но без единой поблажки странице.

        Заголовки те же строгие: браузеру запрещено угадывать тип, содержимое
        объявлено вложением — то есть показывать его страницей он не станет, и
        книга не превратится в исполняемый на просмотре предмет. Имя чистится
        тем же обезвреживанием, что и всё чужое.
        """
        from .intake import safe_name

        чистое = safe_name(имя)
        self.send_response(200)
        self.send_header("Content-Type", тип or "application/octet-stream")
        self.send_header("Content-Length", str(len(байты)))
        # Имя в кавычках и отдельно в кодированном виде: кириллица в
        # заголовке иначе доедет искажённой, и книга сохранится с именем-
        # крякозяброй.
        from urllib.parse import quote

        self.send_header(
            "Content-Disposition",
            "attachment; filename=\"kniga.xlsx\"; "
            f"filename*=UTF-8''{quote(чистое)}")
        self.send_header("Content-Security-Policy", ПОЛИТИКА_СОДЕРЖИМОГО)
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(байты)

    def _отдать(self, код: int, тело: str, заголовок: str = "Станок"):
        try:
            страница = собрать_страницу(заголовок, тело)
        except ValueError:
            код, страница = 500, _КАРКАС.format(
                заголовок="Станок", стиль=_СТИЛЬ,
                тело="<h1>Страница не отдана</h1>")
        байты = страница.encode("utf-8")
        self.send_response(код)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(байты)))
        self.send_header("Content-Security-Policy", ПОЛИТИКА_СОДЕРЖИМОГО)
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(байты)


class _Сервер(ThreadingHTTPServer):
    """Сервер, который не садится на чужое место.

    На Windows повторное использование адреса означает не «занять после
    себя», а «занять поверх другого»: два узла живут на одном порте, и какому
    из них достанется запрос — как повезёт. Здесь это выключено.
    """

    allow_reuse_address = os.name != "nt"


def _порт_занят(порт: int, адрес: str = АДРЕС) -> bool:
    """Отвечает ли уже кто-нибудь на этом порте.

    Проверка делом: попытка соединиться. Она не полагается на то, как
    операционная система толкует повторное занятие адреса. Ноль-адрес значит
    «все адреса», соединяться с ним нельзя — спрашиваем петлевой.
    """
    куда = АДРЕС if адрес in ("0.0.0.0", "::", "") else адрес
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as гнездо:
        гнездо.settimeout(0.4)
        return гнездо.connect_ex((куда, порт)) == 0


class Узел:
    """Узел интерфейса. Поднимается на петлевом адресе и там же умирает."""

    def __init__(self, страницы=(), порт: int = ПОРТ_ПО_УМОЛЧАНИЮ,
                 наружу: str = "", слушать: str = АДРЕС,
                 после_приёма=None) -> None:
        self.порт = порт
        # На чужой площадке гнездо петлевым быть не может: обращения приводит
        # её собственный привратник, и он стучится с другого адреса. Здесь это
        # названо доводом, а не подразумевается: узел, слушающий не свою
        # машину, обязан говорить об этом вслух (см. `слушает_только_свою_
        # машину`), иначе тихое открытие наружу однажды случится незаметно.
        self.слушать = слушать or АДРЕС
        self.после_приёма = после_приёма
        # Имя, под которым узел виден снаружи через трубу. Пусто — узел живёт
        # так же, как жил: только своя машина. Гнездо от этого имени не
        # меняется никогда: наружу узел не слушает и с ним.
        self.наружу = _имя_хозяина(наружу) if наружу else ""
        self.страницы = {с.путь: с for с in страницы}
        self._сервер: ThreadingHTTPServer | None = None
        self._нить: threading.Thread | None = None

    def заменить_страницы(self, страницы) -> None:
        """Ставит новый набор экранов на живом узле.

        Нужно затем, что экраны разбора строятся по проводке, а проводка
        появляется в середине работы — когда человек нажал «Разобрать».
        Правится **тот же** словарь, а не заводится новый: обработчик держит
        ссылку на него, и подмена ссылки до него бы не дошла — запросы шли бы
        к прежним экранам, а человек считал бы, что видит новые.
        """
        self.страницы.clear()
        self.страницы.update({с.путь: с for с in страницы})

    def поднять(self) -> int:
        """Поднимает узел. Возвращает порт, на котором он слушает.

        Если порт занят — отказ с названной причиной, а не тихая жизнь без
        порта. Найдено пробой: на Windows ``SO_REUSEADDR`` разрешает сесть на
        уже занятый порт, второй узел «поднимался», а запросы браузера шли
        первому. Человек при этом видел старый станок и считал его новым.
        """
        if self.порт and _порт_занят(self.порт, self.слушать):
            raise OSError(f"порт {self.порт} занят: там уже кто-то отвечает")
        обработчик = type("_Свой", (_Обработчик,),
                          {"страницы": self.страницы, "порт": self.порт,
                           "наружу": self.наружу,
                           "после_приёма": staticmethod(self.после_приёма)
                           if self.после_приёма else None})
        self._сервер = _Сервер((self.слушать, self.порт), обработчик)
        self.порт = self._сервер.server_address[1]
        self._сервер.RequestHandlerClass.порт = self.порт
        self._нить = threading.Thread(target=self._сервер.serve_forever,
                                      daemon=True)
        self._нить.start()
        return self.порт

    def остановить(self) -> None:
        if self._сервер is not None:
            self._сервер.shutdown()
            self._сервер.server_close()
            self._сервер = None

    def __enter__(self):
        self.поднять()
        return self

    def __exit__(self, *беды):
        self.остановить()
        return False

    @property
    def адрес(self) -> str:
        return f"http://{АДРЕС}:{self.порт}/"

    def слушает_только_свою_машину(self) -> bool:
        """Проверка делом, а не обещанием: на каком адресе висит сокет."""
        if self._сервер is None:
            return False
        свой = self._сервер.socket.getsockname()[0]
        return свой == АДРЕС and свой not in ("0.0.0.0", "::")


