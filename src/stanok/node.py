# ------------------------------------------------------- обезвреживание


# Знаки, которыми данные превращаются в разметку. Список закрыт: закрытый
# перечень опасного надёжнее открытого перечня безопасного (шаг 63).
ОПАСНЫЕ_ЗНАКИ = ("&", "<", ">", '"', "'")

# То же в готовом виде — чем ищем следы разметки при обратном чтении.
_СЛЕД_РАЗМЕТКИ = re.compile(r"[<>]")


def обезвредить(значение) -> str:
    """Данные, годные для вставки в страницу. Ни одного исполняемого знака.

    Двойник обезвреживания формул в книге (шаг 44). Значение не толкуется и не
    подрезается: ведущие нули, пробелы и знаки остаются как есть — меняется
    только запись опасных знаков, а не смысл.
    """
    if значение is None:
        return ""
    return html.escape(str(значение), quote=True)


def сверить_обратным_чтением(страница: str, данные) -> None:
    """Перечитывает готовую страницу и ищет разметку, пришедшую из данных.

    Двойник ``guard_readback``: не «я экранировал», а «в готовом тексте этого
    нет». Ошибка в экранировании ловится здесь, а не у клиента.
    """
    for значение in данные:
        сырое = "" if значение is None else str(значение)
        if not _СЛЕД_РАЗМЕТКИ.search(сырое):
            continue
        # Кусок данных со знаком разметки не должен встречаться в странице
        # дословно: если встречается — экранирование где-то обошли.
        if сырое in страница:
            raise ValueError(
                f"{РАЗМЕТКА_ИЗ_ДАННЫХ}: в готовую страницу попал кусок данных "
                "со знаками разметки в исходном виде. Значение из документа "
                "стало разметкой — это то же, что формула из документа в книге"
            )


def проверить_размер(страница: str) -> None:
    сколько = len(страница.encode("utf-8"))
    if сколько > ПРЕДЕЛ_СТРАНИЦЫ:
        raise ValueError(
            f"{СТРАНИЦА_ВЕЛИКА}: страница {сколько} байт при пределе "
            f"{ПРЕДЕЛ_СТРАНИЦЫ}. Урезание должно быть видимым, а не тихим: "
            "показывайте часть и говорите, что это часть")


def собрать_страницу(заголовок: str, тело: str, данные=()) -> str:
    """Складывает страницу и проверяет её обоими двойниками разом.

    ``данные`` — сырые значения из документа, попавшие в тело. Они нужны для
    обратного чтения: без них проверка была бы верой в аккуратность.
    """
    страница = _КАРКАС.format(заголовок=обезвредить(заголовок),
                              стиль=_СТИЛЬ, тело=тело)
    сверить_обратным_чтением(страница, данные)
    проверить_размер(страница)
    return страница


