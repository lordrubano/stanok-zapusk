def построить_набор(данные: bytes, основа: str = "документ") -> dict:
    """Строит по одному порченому документу на каждый класс дефекта.

    Класс, который построить не удалось, объявляется вслух: молча пропущенный
    дефект превратил бы корпус в набор того, что легко строится.
    """
    собранные, беды = {}, {}
    for имя, порча in ПОРЧИ.items():
        try:
            своя = порча(данные)
        except Exception as беда:
            беды[имя] = f"{type(беда).__name__}: {беда}"
            continue
        собранные[имя] = Порча(DEFECTS_VERSION, своя.данные, своя.ожидания,
                               основа)
    return {"построено": собранные, "не_построено": беды}


def свод(набор: dict) -> dict:
    return {
        "версия": DEFECTS_VERSION,
        "классов_объявлено": len(КЛАССЫ),
        "построено": sorted(набор["построено"]),
        "не_построено": набор["не_построено"],
        "ожидания": {имя: [о.as_json() for о in порча.ожидания]
                     for имя, порча in sorted(набор["построено"].items())},
    }


