# -*- coding: utf-8 -*-
"""Порча документа известным способом: корпус обязательных дефектов.

Шаг 50 плана. Нормативная основа — чертёж v3.0, раздел 16.2 (обязательные
дефекты испытательного корпуса).

**Корпус из одних хороших документов измеряет не надёжность, а везение.** Он
показывает, что станок справляется с тем, что ему уже давали, и молчит о том,
что случится на первом же документе с изъяном. А изъяны в выписках обычны:
перенос таблицы, скобки вместо минуса, повёрнутая страница, повреждённая
кодировка.

**Дефектных документов у нас нет, и потому они строятся.** Берётся настоящий
документ и портится **известным способом**. От этого правильный ответ известен
точно: не «мы полагаем, что здесь пропала строка», а «здесь удалена ровно эта
строка, и вот её содержимое до удаления».

Это сильнее настоящего дефектного документа в одном и слабее в другом:

* **сильнее** — эталон точен. У настоящего документа с изъяном эталон пришлось
  бы размечать руками, то есть с той же неуверенностью, что и всё остальное;
* **слабее** — испорчено ровно так, как я умею портить. Настоящий изъян
  случается иначе, и чего я не придумал, того в корпусе не будет. Это названо
  в оговорках и в отчёте по шагу.

**Здесь ничего не публикуется.** Порченые копии строятся из настоящего
документа, несут его содержимое и потому остаются на машине владельца ровно так
же, как исходник. Наружу уходит этот код и описание дефектов, но не файлы.

## Как устроена порча

Файл разбирается на объекты, нужные правятся, файл собирается заново с новой
таблицей ссылок. Это честнее правки байтов на месте: правка на месте требует
сохранять длину, а сохранение длины ограничивает порчу тем, что случайно
подошло по размеру.
"""

