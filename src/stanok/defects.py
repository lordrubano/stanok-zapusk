@dataclass(frozen=True, slots=True)
class Ожидание:
    """Что именно испорчено и чего ждать от станка.

    Правильный ответ хранится рядом с документом: без него порченый документ —
    просто мусор, а не испытание.
    """

    класс: str
    что_сделано: str
    где: str
    чего_ждать: str
    было: str = ""
    стало: str = ""

    def as_json(self) -> dict:
        return {"класс": self.класс, "что_сделано": self.что_сделано,
                "где": self.где, "чего_ждать": self.чего_ждать,
                "было": self.было, "стало": self.стало}


@dataclass
class Порча:
    """Порченый документ и правильный ответ к нему."""

    версия: str = DEFECTS_VERSION
    данные: bytes = b""
    ожидания: tuple = ()
    основа: str = ""

    def as_json(self) -> dict:
        return {"версия": self.версия, "основа": self.основа,
                "байт": len(self.данные),
                "ожидания": [о.as_json() for о in self.ожидания]}


# ------------------------------------------------- разбор и сборка


_ОБЪЕКТ = re.compile(rb"(?<![0-9])(\d{1,10})\s+(\d{1,5})\s+obj\b")


@dataclass
class _Объект:
    номер: int
    поколение: int
    тело: bytes


def _разобрать(данные: bytes) -> tuple:
    """Собирает объекты файла в порядке появления."""
    объекты = []
    места = list(_ОБЪЕКТ.finditer(данные))
    for место, совпало in enumerate(места):
        начало = совпало.end()
        конец = данные.find(b"endobj", начало)
        if конец < 0:
            конец = (места[место + 1].start() if место + 1 < len(места)
                     else len(данные))
        объекты.append(_Объект(int(совпало.group(1)), int(совпало.group(2)),
                               данные[начало:конец]))
    return tuple(объекты)


def _корень_и_прочее(данные: bytes) -> bytes:
    """Хвост трейлера: /Root, /Info, /ID — то, без чего файл не откроется."""
    место = данные.rfind(b"trailer")
    if место < 0:
        return b"<</Root 1 0 R>>"
    конец = данные.find(b">>", место)
    return данные[данные.find(b"<<", место):конец + 2]


def _собрать(объекты, трейлер: bytes) -> bytes:
    """Собирает файл заново с новой таблицей ссылок.

    Таблица считается заново намеренно: порча меняет длины, и старая таблица
    указывала бы мимо. Файл с таблицей, указывающей мимо, — это уже другой
    дефект, и смешивать его с задуманным нельзя.
    """
    куски = [b"%PDF-1.5\n%\xe2\xe3\xcf\xd3\n"]
    смещения = {}
    место = len(куски[0])
    for объект in sorted(объекты, key=lambda о: о.номер):
        смещения[объект.номер] = место
        кусок = (b"%d %d obj" % (объект.номер, объект.поколение)
                 + объект.тело + b"endobj\n")
        куски.append(кусок)
        место += len(кусок)

    наибольший = max(смещения) if смещения else 0
    строки = [b"xref\n", b"0 %d\n" % (наибольший + 1),
              b"0000000000 65535 f \n"]
    for номер in range(1, наибольший + 1):
        if номер in смещения:
            строки.append(b"%010d 00000 n \n" % смещения[номер])
        else:
            строки.append(b"0000000000 65535 f \n")
    таблица = b"".join(строки)
    свой_трейлер = трейлер.replace(b"/Size", b"/XSize")  # старый размер не годен
    хвост = (b"trailer\n" + свой_трейлер[:-2]
             + b"/Size %d>>\n" % (наибольший + 1)
             + b"startxref\n%d\n%%%%EOF\n" % место)
    return b"".join(куски) + таблица + хвост


def _поток(тело: bytes):
    """Разжатое содержимое потока объекта либо None."""
    начало = тело.find(b"stream")
    if начало < 0:
        return None, None, None
    сырое_начало = начало + len(b"stream")
    if тело[сырое_начало:сырое_начало + 2] == b"\r\n":
        сырое_начало += 2
    elif тело[сырое_начало:сырое_начало + 1] in (b"\n", b"\r"):
        сырое_начало += 1
    конец = тело.find(b"endstream", сырое_начало)
    if конец < 0:
        return None, None, None
    сырое = тело[сырое_начало:конец]
    словарь = тело[:начало]
    if b"/FlateDecode" not in словарь:
        return словарь, сырое, конец
    try:
        return словарь, zlib.decompress(сырое), конец
    except zlib.error:
        return None, None, None


def _заменить_поток(объект: _Объект, содержимое: bytes) -> None:
    """Кладёт в объект новое содержимое потока, поправив длину."""
    словарь, _, конец = _поток(объект.тело)
    if словарь is None:
        return
    сжатое = zlib.compress(содержимое)
    свой = re.sub(rb"/Length\s+\d+", b"/Length %d" % len(сжатое), словарь)
    if b"/Length" not in свой:
        свой = свой.replace(b"<<", b"<</Length %d" % len(сжатое), 1)
    объект.тело = свой + b"stream\n" + сжатое + b"\n" + объект.тело[конец:]


def _страницы(объекты) -> tuple:
    return tuple(о for о in объекты if re.search(rb"/Type\s*/Page\b", о.тело))


def _содержимое_страницы(объекты, страница: _Объект):
    """Объект потока содержимого страницы и его разжатый текст."""
    совпало = re.search(rb"/Contents\s+(\d+)\s+\d+\s+R", страница.тело)
    if not совпало:
        return None, None
    номер = int(совпало.group(1))
    for объект in объекты:
        if объект.номер == номер:
            _, содержимое, _ = _поток(объект.тело)
            return объект, содержимое
    return None, None


# Показ текста в настоящем документе выглядит как «(коды)Tj» — без пробела
# перед оператором, а между матрицей и строкой стоят выбор шрифта и цвет.
# Первая мерка искала их вплотную и не нашла ни одного: показ ищется сам по
# себе, а место берётся у ближайшей матрицы слева.
_ПОКАЗ = re.compile(rb"\((?:[^()\\]|\\.)*\)\s*Tj")
_МАТРИЦА = re.compile(rb"1 0 0 1 ([-\d.]+) ([-\d.]+) Tm")


def _обратная_таблица(данные: bytes):
    """Таблица «знак → код шрифта» и признак двухбайтовости.

    Текст в потоке записан кодами шрифта, а не знаками: «(1 234,56)» в потоке
    даст не «1 234,56», а то, во что эти байты истолкует таблица шрифта.
    Поэтому написать в документ **задуманный** текст можно только через
    обратную таблицу. Без неё порча была бы наугад, а правильный ответ —
    предположением.
    """
    from .adapter_pdf import _разобрать_cmap

    for объект in _разобрать(данные):
        совпало = re.search(rb"/ToUnicode\s+(\d+)\s+\d+\s+R", объект.тело)
        if not совпало:
            continue
        for свой in _разобрать(данные):
            if свой.номер != int(совпало.group(1)):
                continue
            _, поток, _ = _поток(свой.тело)
            if поток is None:
                continue
            прямая = _разобрать_cmap(поток)
            обратная = {}
            for код, знак in прямая.items():
                обратная.setdefault(знак, код)
            # Двухбайтовость берётся у самого шрифта, а не у величины кодов:
            # у составного шрифта коды бывают и мелкими, и записывать их одним
            # байтом значило бы написать в документ не то. Проверка на
            # собранном образце это и поймала.
            двухбайтовый = b"/Type0" in объект.тело
            return обратная, двухбайтовый
    return {}, False


def _закодировать(текст: str, обратная, двухбайтовый) -> bytes:
    """Переводит задуманный текст в коды шрифта документа."""
    свои = bytearray()
    for знак in текст:
        код = обратная.get(знак)
        if код is None:
            raise ValueError(
                f"знака {знак!r} нет в таблице толкования шрифта: написать его "
                "в документ нечем. Порча, написанная наугад, дала бы неверный "
                "правильный ответ")
        if двухбайтовый:
            свои += bytes([(код >> 8) & 0xFF, код & 0xFF])
        else:
            свои.append(код & 0xFF)
    вышло = bytearray()
    for байт in свои:
        if байт in (0x28, 0x29, 0x5C):
            вышло.append(0x5C)
        вышло.append(байт)
    return bytes(вышло)


