def повредить_кодировку(данные: bytes, номер_страницы: int = 2) -> Порча:
    """Заменяет коды знаков ячейки на такие, которых нет в таблице толкования.

    Так и выглядит повреждённая кодировка: коды в потоке есть, истолковать их
    нечем. Написать вместо текста «другие буквы» было бы не тем дефектом:
    шрифт документа их не содержит.
    """
    прямая, двухбайтовый = _обратная_таблица(данные)
    известные = set(прямая.values())
    свободные = [код for код in range(0x20, 0xFFFF) if код not in известные]
    от, до = ПОЛОСЫ["сумма"]

    def править(содержимое):
        показ, _ = _показ_колонки(содержимое, от, до, ПЕРВАЯ_ОПЕРАЦИЯ)
        было = показ.group(0)
        мусор = bytearray()
        for код in свободные[:6]:
            if двухбайтовый:
                мусор += bytes([(код >> 8) & 0xFF, код & 0xFF])
            else:
                мусор.append(код & 0xFF)
        экранированный = bytearray()
        for байт in мусор:
            if байт in (0x28, 0x29, 0x5C):
                экранированный.append(0x5C)
            экранированный.append(байт)
        замена = b"(" + bytes(экранированный) + b")Tj"
        свежее = содержимое[:показ.start()] + замена + содержимое[показ.end():]
        return свежее, (Ожидание(
            "повреждённая кодировка",
            "коды знаков ячейки суммы заменены на не имеющие толкования",
            f"страница {номер_страницы}, первая ячейка колонки суммы",
            "в тексте появятся знаки замены, истолкование суммы не состоится, "
            "и поле не должно быть принято за прочитанное",
            было.decode("latin-1")[:30], "коды без толкования"),)

    новые, ожидания = _правка_страницы(данные, номер_страницы, править)
    return Порча(DEFECTS_VERSION, новые, ожидания)


def сменить_версию_формы(данные: bytes, номер_страницы: int = 2,
                         сдвиг: float = 60.0) -> Порча:
    """Сдвигает колонку суммы по листу: банк переверстал форму.

    Переписать заголовок другими словами нельзя — шрифт документа не содержит
    чужих букв. Сдвиг колонки честнее и ближе к жизни: у новой версии формы
    столбцы стоят на других местах, и объявленные полосы перестают совпадать.
    """
    от, до = ПОЛОСЫ["сумма"]

    def править(содержимое):
        свои = показы_колонки(содержимое, от, до)
        if not свои:
            raise ValueError("колонка не найдена: сдвигать нечего")
        свежее = содержимое
        # Идём с конца, чтобы правки не сбивали места остальных.
        for показ, матрица in reversed(свои):
            замена = b"1 0 0 1 %s %.2f Tm" % (матрица.group(1),
                                              float(матрица.group(2)) + сдвиг)
            свежее = свежее[:матрица.start()] + замена + свежее[матрица.end():]
        return свежее, (Ожидание(
            "изменившаяся версия формы",
            f"колонка суммы сдвинута по листу на {сдвиг:.0f} пунктов "
            f"({len(свои)} ячеек)",
            f"страница {номер_страницы}",
            "объявленная оснасткой полоса колонки перестанет совпадать: ячейки "
            "уйдут из своей колонки и будут объявлены лишними, а поле суммы "
            "останется незаполненным",
            "колонка на объявленном месте", "колонка сдвинута"),)

    новые, ожидания = _правка_страницы(данные, номер_страницы, править)
    return Порча(DEFECTS_VERSION, новые, ожидания)


def перенести_на_разрыв(данные: bytes, номер_страницы: int = 2) -> Порча:
    """Переносит последние показы страницы на следующую.

    Ждём: операция окажется разорванной границей страницы — её первая строка на
    одной, продолжение на другой. Сборка записей продолжение через границу не
    переносит, и хвост уйдёт «вне записей».
    """
    объекты = list(_разобрать(данные))
    страницы = _страницы(объекты)
    if номер_страницы >= len(страницы):
        raise ValueError("нужна страница, за которой есть следующая")
    объект_1, содержимое_1 = _содержимое_страницы(объекты,
                                                  страницы[номер_страницы - 1])
    объект_2, содержимое_2 = _содержимое_страницы(объекты,
                                                  страницы[номер_страницы])
    if содержимое_1 is None or содержимое_2 is None:
        raise ValueError("содержимое страниц не читается")

    показы = list(_ПОКАЗ.finditer(содержимое_1))
    if len(показы) < 4:
        raise ValueError("на странице слишком мало показов")
    хвост_с = показы[-3].start()
    хвост = содержимое_1[хвост_с:]
    без_хвоста = содержимое_1[:хвост_с] + b"\nET\n"
    _заменить_поток(объект_1, без_хвоста)
    _заменить_поток(объект_2, b"BT /F1 14 Tf\n" + хвост + b"\n" + содержимое_2)

    ожидание = Ожидание(
        "продолжение таблицы через разрыв страницы",
        "последние показы страницы перенесены в начало следующей",
        f"страницы {номер_страницы} и {номер_страницы + 1}",
        "операция окажется разорванной границей страницы: сборка записей "
        "продолжение через границу не переносит, и хвост уйдёт «вне записей». "
        "Это и есть тот случай, ради которого нужна сшивка продолжений",
        "операция целиком на одной странице", "разорвана между двумя")
    return Порча(DEFECTS_VERSION, _собрать(объекты, _корень_и_прочее(данные)),
                 (ожидание,))


