# Полосы колонок первого семейства в долях листа. Числа те же, что объявлены в
# пакете оснастки, и повторены здесь намеренно: порча обязана бить в то самое
# поле, которое потом будет проверяться. Другому семейству — свои числа.
ПОЛОСЫ = {
    "дата": (0.000, 0.030),
    "номер": (0.060, 0.090),
    "сумма": (0.140, 0.200),
    "сумма_кредит": (0.240, 0.300),
    "контрагент": (0.300, 0.320),
    "назначение": (0.660, 0.690),
}


def показы_колонки(содержимое: bytes, от_доли: float, до_доли: float,
                   высота_рамки: float = 1700.0) -> list:
    """Показы, попавшие в объявленную колонку повёрнутой страницы.

    Первая мерка била в показ по порядку — то есть куда придётся. Из девяти
    построенных дефектов семь оказались незаметны станку не потому, что он их
    проглядел, а потому, что порча задевала не значащую ячейку, а что попало.
    Дефект, не попавший в поле, ничего не испытывает.

    У страницы этого семейства своя матрица поворота в начале потока, и она
    уже переводит запись в вид листа. Колонка ищется по «x» матрицы, делённому
    на длинную сторону листа: заголовок «Дата» стоит на 52,62, что и даёт
    объявленные 0,031. Первая мерка делила «y» и выбирала не те ячейки — от
    этого семь построенных дефектов оказались незаметны станком не потому, что
    он их проглядел, а потому, что порча била мимо поля.
    """
    свои = []
    for показ in _ПОКАЗ.finditer(содержимое):
        if len(показ.group(0)) <= 4:
            continue
        начало = содержимое.rfind(b"Tm", 0, показ.start())
        if начало < 0:
            continue
        строка_н = содержимое.rfind(b"\n", 0, начало) + 1
        матрица = _МАТРИЦА.search(содержимое, строка_н, показ.start())
        if not матрица:
            continue
        доля = float(матрица.group(1)) / высота_рамки
        if от_доли <= доля <= до_доли:
            свои.append((показ, матрица))
    return свои


# Первая ячейка колонки — её заголовок, а не значение операции. Порча по
# умолчанию бьёт мимо него: испорченный заголовок испытывает не разбор поля, а
# опознание шапки, и это другой дефект.
ПЕРВАЯ_ОПЕРАЦИЯ = 2


def _показ_колонки(содержимое: bytes, от_доли: float, до_доли: float,
                   какой: int = ПЕРВАЯ_ОПЕРАЦИЯ):
    свои = показы_колонки(содержимое, от_доли, до_доли)
    if len(свои) <= какой:
        raise ValueError(
            f"в полосе {от_доли}…{до_доли} показов {len(свои)}, "
            f"а порча просит номер {какой + 1}")
    return свои[какой]


def _правка_страницы(данные: bytes, номер_страницы: int, править) -> tuple:
    """Общий ход: разобрать, поправить содержимое страницы, собрать."""
    объекты = list(_разобрать(данные))
    страницы = _страницы(объекты)
    if номер_страницы > len(страницы):
        raise ValueError(f"в документе {len(страницы)} страниц, "
                         f"а порча просит {номер_страницы}")
    страница = страницы[номер_страницы - 1]
    объект, содержимое = _содержимое_страницы(объекты, страница)
    if объект is None or содержимое is None:
        raise ValueError("содержимое страницы не читается: портить нечего")
    новое, ожидания = править(содержимое)
    _заменить_поток(объект, новое)
    return _собрать(объекты, _корень_и_прочее(данные)), ожидания


def повернуть_страницу(данные: bytes, номер_страницы: int = 1,
                       угол: int = 0) -> Порча:
    """Меняет объявленный поворот страницы.

    Ждём: строки этой страницы соберутся поперёк, и это будет видно по счёту —
    дат в строке станет много, а строк на странице мало.
    """
    объекты = list(_разобрать(данные))
    страницы = _страницы(объекты)
    страница = страницы[номер_страницы - 1]
    было = re.search(rb"/Rotate\s+(-?\d+)", страница.тело)
    прежний = было.group(1).decode() if было else "нет"
    if было:
        страница.тело = re.sub(rb"/Rotate\s+-?\d+", b"/Rotate %d" % угол,
                               страница.тело)
    else:
        страница.тело = страница.тело.replace(b"<<", b"<</Rotate %d" % угол, 1)
    ожидание = Ожидание(
        "повёрнутая страница",
        f"объявленный поворот страницы {номер_страницы} изменён",
        f"страница {номер_страницы}", "строки этой страницы соберутся поперёк: "
        "дат в одной строке станет много, а строк на странице мало",
        прежний, str(угол))
    return Порча(DEFECTS_VERSION, _собрать(объекты, _корень_и_прочее(данные)),
                 (ожидание,))


def сломать_толкование(данные: bytes) -> Порча:
    """Убирает таблицу толкования знаков у шрифта.

    Ждём: страницы получат отметку битого текстового слоя, а истолковать текст
    станет нечем.
    """
    объекты = list(_разобрать(данные))
    тронуто = 0
    for объект in объекты:
        if b"/ToUnicode" in объект.тело:
            объект.тело = re.sub(rb"/ToUnicode\s+\d+\s+\d+\s+R", b"", объект.тело)
            тронуто += 1
    if not тронуто:
        raise ValueError("в документе нет таблицы толкования: ломать нечего")
    ожидание = Ожидание(
        "битый текстовый слой",
        "у шрифта убрана таблица толкования знаков",
        f"шрифтов затронуто: {тронуто}",
        "доля толкуемых знаков упадёт, страницы получат отметку битого слоя, "
        "и по шагу 43 такой документ потребует второго прочтения",
        "таблица толкования есть", "таблицы толкования нет")
    return Порча(DEFECTS_VERSION, _собрать(объекты, _корень_и_прочее(данные)),
                 (ожидание,))


def _первый_показ(содержимое: bytes, пропустить: int = 0):
    """Находит показ текста по порядку на странице."""
    показы = [м for м in _ПОКАЗ.finditer(содержимое)
              if len(м.group(0)) > 4]      # пустые «()Tj» пропускаем
    if len(показы) <= пропустить:
        raise ValueError(f"на странице показов текста {len(показы)}, "
                         f"а порча просит номер {пропустить + 1}")
    return показы[пропустить]


def убрать_строку(данные: bytes, номер_страницы: int = 2,
                  колонка: str = "сумма", какая: int = ПЕРВАЯ_ОПЕРАЦИЯ) -> Порча:
    """Удаляет ячейку объявленной колонки: сумма операции исчезает.

    Ждём: у операции не станет суммы, разобранное не сойдётся с напечатанными
    итогами, и проверка итогов объявит расхождение.
    """
    от, до = ПОЛОСЫ[колонка]

    def править(содержимое):
        показ, _ = _показ_колонки(содержимое, от, до, какая)
        было = показ.group(0)
        свежее = содержимое[:показ.start()] + содержимое[показ.end():]
        return свежее, (Ожидание(
            "пропущенная строка",
            "удалена ячейка колонки «" + колонка + "»",
            f"страница {номер_страницы}, ячейка №{какая + 1} этой колонки",
            "у операции не станет значения в этой колонке: разобранное не "
            "сойдётся с напечатанными итогами, и проверка итогов объявит "
            "расхождение",
            было.decode("latin-1")[:30], "удалено"),)

    новые, ожидания = _правка_страницы(данные, номер_страницы, править)
    return Порча(DEFECTS_VERSION, новые, ожидания)


def задвоить_строку(данные: bytes, номер_страницы: int = 2,
                    колонка: str = "сумма", какая: int = ПЕРВАЯ_ОПЕРАЦИЯ) -> Порча:
    """Повторяет ячейку колонки: в строке окажется две суммы.

    Ждём: разобранное станет больше напечатанного в итогах.
    """
    от, до = ПОЛОСЫ[колонка]

    def править(содержимое):
        показ, матрица = _показ_колонки(содержимое, от, до, какая)
        # Повтор ставится чуть ниже: лёгший ровно поверх был бы неотличим от
        # одной ячейки, и дефекта не вышло бы.
        сдвиг = b"1 0 0 1 %s %.2f Tm" % (матрица.group(1),
                                         float(матрица.group(2)) + 6.0)
        кусок = сдвиг + b"\n" + показ.group(0)
        свежее = (содержимое[:показ.end()] + b"\n" + кусок
                  + содержимое[показ.end():])
        return свежее, (Ожидание(
            "дубль строки",
            "ячейка колонки «" + колонка + "» повторена дважды",
            f"страница {номер_страницы}, ячейка №{какая + 1} этой колонки",
            "разобранного станет больше напечатанного в итогах; при разных "
            "адресах областей это увидит и проверка повторов",
            показ.group(0).decode("latin-1")[:30], "повторено"),)

    новые, ожидания = _правка_страницы(данные, номер_страницы, править)
    return Порча(DEFECTS_VERSION, новые, ожидания)


def переписать_показ(данные: bytes, номер_страницы: int, колонка: str,
                     какая: int, новый_текст: str, класс: str,
                     чего_ждать: str) -> Порча:
    """Заменяет текст ячейки объявленной колонки."""
    обратная, двухбайтовый = _обратная_таблица(данные)
    от, до = ПОЛОСЫ[колонка]

    def править(содержимое):
        показ, _ = _показ_колонки(содержимое, от, до, какая)
        было = показ.group(0)
        замена = b"(" + _закодировать(новый_текст, обратная, двухбайтовый) + b")Tj"
        свежее = содержимое[:показ.start()] + замена + содержимое[показ.end():]
        return свежее, (Ожидание(
            класс, "ячейка колонки «" + колонка + "» переписана на "
            + repr(новый_текст),
            f"страница {номер_страницы}, ячейка №{какая + 1} этой колонки",
            чего_ждать, было.decode("latin-1")[:30], новый_текст),)

    новые, ожидания = _правка_страницы(данные, номер_страницы, править)
    return Порча(DEFECTS_VERSION, новые, ожидания)


