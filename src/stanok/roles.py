class ПравоНеДано(PermissionError):
    """Роли этого не позволено. Сказано, кому, чего и почему."""

    код = "E_ROLE_FORBIDDEN"


def роль_годна(роль: str) -> bool:
    return роль in ПОЗВОЛЕНО


def позволено(роль: str, работа: str) -> bool:
    """Позволена ли роли эта работа. Незнакомое запрещено, а не разрешено."""
    return работа in ПОЗВОЛЕНО.get(роль, frozenset())


def проверить_право(роль: str, работа: str) -> None:
    """Роняет отказом, если роли работа не позволена.

    Отказ объясняется словами: человеку, которому не дали сделать, важнее
    понять причину, чем получить код.
    """
    if not роль_годна(роль):
        raise ПравоНеДано(
            f"{ПравоНеДано.код}: роли {роль!r} не существует; их три: "
            + ", ".join(РОЛИ))
    if работа not in РАБОТЫ:
        raise ПравоНеДано(
            f"{ПравоНеДано.код}: работы {работа!r} нет в перечне; позволенное "
            "объявляется, а не подразумевается")
    if not позволено(роль, работа):
        почему = ПОЧЕМУ.get((роль, работа), "роли это не позволено")
        raise ПравоНеДано(
            f"{ПравоНеДано.код}: {роль} не делает «{работа}»: {почему}")


def кто_может(работа: str) -> tuple[str, ...]:
    """Какие роли вправе делать эту работу."""
    return tuple(роль for роль in РОЛИ if позволено(роль, работа))


def свод() -> dict:
    """Права ролей одним предметом — для показа и для журнала."""
    return {
        "версия": ROLES_VERSION,
        "роли": list(РОЛИ),
        "работы": list(РАБОТЫ),
        "позволено": {роль: sorted(ПОЗВОЛЕНО[роль]) for роль in РОЛИ},
        "личность_не_проверяется": True,
    }


