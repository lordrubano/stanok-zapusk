# -*- coding: utf-8 -*-
"""Разграничение ролей: разметчик, проверяющий, администратор.

Шаг 60 плана. Нормативная основа — чертёж v3.0, раздел 12: «разграничение ролей
разметчика, проверяющего и администратора».

**Роль ограничивает действия, а не только называет.** Имя в событии говорит,
кто решил; роль говорит, что этому кому-то вообще позволено. Без второго первое
— украшение: сегодня все могут всё, и запись о том, кто это сделал, лишь
называет виновника задним числом.

Три роли и три границы, каждая со своим доводом:

* **разметчик** размечает эталон и **не решает судьбу записей**. Он видит
  документ раньше и подробнее всех, и потому его суждение попадает в эталон, по
  которому меряют станок. Позволь ему допускать записи — и он будет мерить
  станок по своей же разметке, а расхождение с ней объявлять допущенным;
* **проверяющий** решает судьбу записей и **не правит оснастку**. Он вправе
  сказать «виновата настройка» — это возврат оснастки, сигнал, — но не менять
  её сам: правка формы разбора меняет тысячи записей разом, включая уже
  решённые им, и это работа не одного человека с одним экраном;
* **администратор** ведёт роли и настройку и **не подменяет решения по
  записям**. Иначе разграничение ролей теряет смысл: тот, кто раздаёт права,
  раздаст их себе.

## Где кончается то, что может станок

Станок принуждает **право**, а не **личность**. Он знает: эта роль такого не
делает; событие без роли не рождается; роль записана в неизменяемую историю
вместе с именем и основанием.

Станок **не знает**, что за именем «проверяющий Петрова» стоит та самая
Петрова. Ни имени, ни пароля, ни второго признака он не проверяет и проверять
не может: удостоверение личности даёт окружение — учётная запись машины,
служба входа предприятия, — а не программа разбора документов. Всё, что станок
получает, — это утверждение вызывающего о том, кто он.

Отсюда прямое следствие, и его не надо смягчать: **разграничение ролей здесь
защищает от ошибки, а не от обмана**. Оно не даёт проверяющему случайно
править оснастку и разметчику — случайно допускать записи. От того, кто
нарочно назовётся чужой ролью, защищает только окружение.
"""

