def крупные_html(свои) -> str:
    """Шесть крупных этапов плитками. Полные — в подробном журнале."""
    куски = []
    for э in свои:
        цвет = _ЦВЕТ_ХОДА[э.состояние]
        # Числом стоит пройденное, а не доля: доля врала бы, потому что часть
        # подробных этапов срабатывает только на своих ветках.
        хвост = (f"; сорвалось: {_т(', '.join(э.сорвалось))}" if э.сорвалось
                 else "")
        куски.append(f'<div class="plitka {цвет}"><div class="p">'
                     f'{_т(э.заголовок)}</div><div class="n">{э.прошло}</div>'
                     f'<div class="p" style="margin:6px 0 0;'
                     f'text-transform:none;letter-spacing:0">'
                     f"{_т(э.состояние)}, из {э.возможных} возможных"
                     f"{хвост}</div></div>")
    return f'<div class="plitki">{"".join(куски)}</div>'


def лента_html(свои) -> str:
    """Укрупнённое движение по ходу работы: шесть шагов лентой, без чисел.

    Чисел здесь нет намеренно: по отметке они неизвестны, а нарисованные
    выглядели бы измеренными.
    """
    куски = ['<div class="lenta">']
    for э in свои:
        точка = _ТОЧКА_ХОДА[э.состояние]
        куски.append(f'<span class="shag"><span class="tochka {точка}"></span>'
                     f"{_т(э.заголовок)} — {_т(э.состояние)}</span>")
    куски.append("</div>")
    return "".join(куски)


