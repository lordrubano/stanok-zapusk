class Наблюдатель:
    """Независимый наблюдатель: смотрит, **меняется ли** отметка.

    Своя память нужна затем, что вопрос части VII — не «давно ли положена
    отметка», а «меняется ли она». Наблюдатель помнит, какую отметку видел и с
    какого времени она такая; работа на эту память не влияет никак.

    Живёт в другом процессе, чем работа. Это и есть независимость: в том же
    процессе он молчал бы вместе с ним.
    """

    def __init__(self, отметка_путь, память_путь=None, *,
                 предел: float = ПРЕДЕЛ_МОЛЧАНИЯ) -> None:
        self.отметка_путь = Path(отметка_путь)
        self.память_путь = (Path(память_путь) if память_путь is not None
                            else self.отметка_путь.with_suffix(".наблюдение"))
        self.предел = предел

    # -------------------------------------------------------- память

    def _вспомнить(self) -> dict:
        if not self.память_путь.is_file():
            return {}
        try:
            свой = json.loads(self.память_путь.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError, OSError):
            return {}
        return свой if isinstance(свой, dict) else {}

    def _запомнить(self, отпечаток: str, с_каких_пор: float) -> None:
        записать_целиком(self.память_путь, json.dumps(
            {"версия": PROGRESS_VERSION, "отпечаток": отпечаток,
             "с_каких_пор": с_каких_пор}, ensure_ascii=False).encode("utf-8"))

    # -------------------------------------------------------- приговор

    def посмотреть(self, сейчас: float | None = None) -> Вердикт:
        сейчас = float(time.time() if сейчас is None else сейчас)
        отметка = прочитать_отметку(self.отметка_путь)
        if отметка is None:
            return Вердикт(НЕ_НАЧИНАЛОСЬ,
                           "отметки хода нет: работа не начиналась или "
                           "отметку убрали")
        if отметка.кончено:
            return Вердикт(КОНЧЕНО, "работа кончилась",
                           отметка.последнее_действие(),
                           процесс=процесс_жив(отметка.процесс))

        прежнее = self._вспомнить()
        отпечаток = отметка.отпечаток
        своя_давность = max(0.0, сейчас - отметка.секунды)
        if прежнее.get("отпечаток") != отпечаток:
            # Отметка изменилась. Но «изменилась с прошлого взгляда» ещё не
            # значит «меняется»: наблюдатель мог впервые посмотреть уже после
            # остановки, и тогда всякая отметка для него нова. Возраст самой
            # отметки судит наравне с её сменой — найдено проверкой, где
            # наблюдатель приходил к давно умершей работе и объявлял её живой.
            self._запомнить(отпечаток, сейчас - своя_давность)
            if своя_давность < self.предел:
                return Вердикт(ИДЁТ, "отметка изменилась с прошлого взгляда",
                               отметка.последнее_действие(), 0.0,
                               процесс_жив(отметка.процесс))

        с_каких_пор = float(прежнее.get("с_каких_пор", сейчас))
        молчит = max(0.0, сейчас - с_каких_пор)
        # Второй ключ к тому же замку: сама отметка могла залежаться ещё до
        # того, как наблюдатель посмотрел впервые.
        молчит = max(молчит, своя_давность)
        жив = процесс_жив(отметка.процесс)
        if молчит < self.предел:
            return Вердикт(ИДЁТ,
                           f"отметка та же {молчит:.0f} с при пределе "
                           f"{self.предел:.0f} с",
                           отметка.последнее_действие(), молчит, жив)

        почему = (f"отметка не менялась {молчит:.0f} с при пределе "
                  f"{self.предел:.0f} с")
        if жив == МЁРТВ:
            почему += "; рабочего процесса больше нет"
        elif жив == ЖИВ:
            почему += "; процесс жив, но не движется"
        return Вердикт(НЕ_ДВИЖЕТСЯ, почему, отметка.последнее_действие(),
                       молчит, жив, ДВИЖЕНИЯ_НЕТ)


def словами(вердикт: Вердикт) -> str:
    """Строка для оператора. Дословно по части VII, без своих украшений."""
    if вердикт.исход == НЕ_ДВИЖЕТСЯ:
        хвост = вердикт.последнее_действие or "нет отметки"
        return f"Обработка не движется. Последнее завершённое действие: {хвост}."
    if вердикт.исход == ИДЁТ:
        return f"Обработка идёт. Последнее завершённое действие: " \
               f"{вердикт.последнее_действие or 'нет отметки'}."
    if вердикт.исход == КОНЧЕНО:
        return "Обработка кончилась."
    return "Обработка не начиналась."


