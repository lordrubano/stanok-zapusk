@dataclass(frozen=True, slots=True)
class Отметка:
    """Отметка хода: этап, документ, страница, время. И ничего сверх."""

    когда: str
    секунды: float
    этап: str
    документ: str = ""
    страница: int | None = None
    страниц: int | None = None
    run_id: str = ""
    процесс: int = 0
    кончено: bool = False

    @property
    def крупный(self) -> str:
        return _ПО_ЭТАПАМ.get(self.этап, "")

    @property
    def отпечаток(self) -> str:
        """Чем одна отметка отличается от другой. Время сюда не входит.

        Иначе всякая новая отметка выглядела бы движением — в том числе
        положенная зацикленной работой, которая только и умеет, что писать
        время.
        """
        return f"{self.этап}|{self.документ}|{self.страница}|{self.кончено}"

    def as_json(self) -> dict:
        return {"версия": PROGRESS_VERSION, "когда": self.когда,
                "секунды": self.секунды, "этап": self.этап,
                "документ": self.документ, "страница": self.страница,
                "страниц": self.страниц, "run_id": self.run_id,
                "процесс": self.процесс, "кончено": self.кончено}

    def последнее_действие(self) -> str:
        """Словами: что сделано последним. Ровно как в части VII ТЗ."""
        if self.страница and self.страниц:
            return f"страница {self.страница} из {self.страниц}"
        if self.страница:
            return f"страница {self.страница}"
        return f"этап «{self.этап}»" if self.этап else "ничего"


# Сколько раз повторить попытку положить отметку. Windows не даёт переименовать
# файл поверх того, который в этот самый миг кто-то читает, — а читает его
# ровно тот, для кого отметка и пишется. Найдено живым испытанием: рабочий
# процесс падал на замене отметки, и падал именно оттого, что наблюдатель
# работал исправно.
ПОПЫТОК_ЗАПИСИ = 5
ПЕРЕДЫШКА_С = 0.02


def _положить_на_диск(куда: Path, отметка: "Отметка") -> bool:
    """Кладёт отметку целиком. Не вышло — молча уходит, а не валит работу.

    Отметка — сведение о работе, а не сама работа. Уронить разбор документа
    из-за того, что не записалась строчка о его ходе, значило бы сделать
    наблюдателя причиной той самой остановки, которую он стережёт.
    """
    байты = json.dumps(отметка.as_json(), ensure_ascii=False).encode("utf-8")
    for попытка in range(ПОПЫТОК_ЗАПИСИ):
        try:
            записать_целиком(куда, байты)
            return True
        except PermissionError:
            # Читающий держит файл долю мгновения: подождать дешевле, чем
            # потерять отметку.
            time.sleep(ПЕРЕДЫШКА_С * (попытка + 1))
        except OSError:
            return False
    return False


def _сейчас_строкой() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class Отметчик:
    """Кладёт отметку хода. Живёт в рабочем процессе и больше ничего не умеет.

    Пишется отметка целиком и одним движением (шаг 64): под своим именем файл
    никогда не бывает половиной. Наблюдатель читает его в любой миг и застаёт
    либо прежнюю отметку, либо новую, но не обрывок.
    """

    def __init__(self, куда, *, run_id: str = "", документ: str = "",
                 часы=time.time, шаг: float = ШАГ_ОТМЕТКИ_С) -> None:
        self.куда = Path(куда)
        self.run_id = run_id
        self.документ = документ
        self.часы = часы
        self.шаг = шаг
        self.страниц: int | None = None
        self._этап = ""
        self._страница: int | None = None
        self._положено = 0.0

    # -------------------------------------------------------- запись

    def этап(self, имя: str) -> Отметка:
        """Этап сменился — отметка кладётся всегда, без всякой скупости.

        Страница при этом забывается: последним завершённым действием стал
        сам этап, и держать в отметке страницу, пройденную до него, значило бы
        показывать оператору вчерашнее.
        """
        self._этап = имя
        self._страница = None
        return self._положить(обязательно=True)

    def страница(self, номер: int, всего: int | None = None) -> Отметка | None:
        """Страница пройдена. Кладётся не чаще шага: диск не бездонный.

        Первая страница после смены этапа кладётся всегда: это не та же
        отметка, что этап, а другая по роду, и скупость тут сделала бы вид,
        будто работа стоит на этапе.
        """
        первая = self._страница is None
        self._страница = номер
        if всего is not None:
            self.страниц = всего
        return self._положить(обязательно=первая)

    def кончено(self) -> Отметка:
        """Работа кончилась. Отметка говорит это прямо, а не молчанием."""
        return self._положить(обязательно=True, кончено=True)

    def _положить(self, *, обязательно: bool,
                  кончено: bool = False) -> Отметка | None:
        сейчас = float(self.часы())
        if not обязательно and сейчас - self._положено < self.шаг:
            return None
        отметка = Отметка(
            когда=_сейчас_строкой(), секунды=сейчас, этап=self._этап,
            документ=self.документ, страница=self._страница,
            страниц=self.страниц, run_id=self.run_id, процесс=os.getpid(),
            кончено=кончено)
        if not _положить_на_диск(self.куда, отметка):
            return None
        self._положено = сейчас
        return отметка

    # ------------------------------------------------- как крючок конвейера

    def __call__(self, имя: str) -> None:
        """Конвейер зовёт отметчика как простую подпись: имя этапа."""
        self.этап(имя)


def прочитать_отметку(откуда) -> Отметка | None:
    """Читает отметку. Нет её или испорчена — так и говорит, а не гадает."""
    путь = Path(откуда)
    if not путь.is_file():
        return None
    try:
        свой = json.loads(путь.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError, OSError):
        return None
    if not isinstance(свой, dict) or "секунды" not in свой:
        return None
    return Отметка(
        когда=str(свой.get("когда", "")), секунды=float(свой["секунды"]),
        этап=str(свой.get("этап", "")), документ=str(свой.get("документ", "")),
        страница=свой.get("страница"), страниц=свой.get("страниц"),
        run_id=str(свой.get("run_id", "")), процесс=int(свой.get("процесс", 0)),
        кончено=bool(свой.get("кончено", False)))


