ПОВТОР_НЕЛЬЗЯ = "E_REPEAT_NOT_SAFE"


def можно_повторить(события, ключ_запуска: str, беды=()) -> tuple[bool, str]:
    """Появляться ли кнопке «повторить». Часть VII: только после фиксации.

    Три условия, и каждое — отказ со своей причиной:

    1. запуск должен быть в реестре: повторять неизвестное нечего;
    2. запуск должен быть незавершённым: законченный повторяют не кнопкой
       беды, а обычным запуском;
    3. осмотр после сбоя (шаг 64) не должен находить недописанного. Пока
       половина итога лежит под настоящим именем, повтор поверх неё сделает
       вторую половину — и обе будут выглядеть целыми.
    """
    from . import run as реестр

    свои = tuple(события)
    ключи = {с.get("ключ") for с in свои}
    if ключ_запуска not in ключи:
        return False, (f"{ПОВТОР_НЕЛЬЗЯ}: такого запуска в реестре нет — "
                       "повторять нечего")
    if реестр.завершённый(свои, ключ_запуска) is not None:
        return False, (f"{ПОВТОР_НЕЛЬЗЯ}: запуск завершён; повтор законченного "
                       "идёт обычным порядком, а не кнопкой беды")
    беды = tuple(беды)
    if беды:
        первая = getattr(беды[0], "словами", None) or str(беды[0])
        return False, (f"{ПОВТОР_НЕЛЬЗЯ}: состояние не зафиксировано — "
                       f"{первая}. Сначала прибрать, потом повторять")
    return True, "состояние зафиксировано: повтор безопасен"


