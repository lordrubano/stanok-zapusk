def крупный(этап: str) -> str:
    """Какому крупному этапу принадлежит подробный. Прерывание — не этап."""
    return _ПО_ЭТАПАМ.get(этап, "")


@dataclass(frozen=True, slots=True)
class КрупныйХод:
    """Один из шести: сколько подробных прошло и чем кончилось."""

    ключ: str
    заголовок: str
    возможных: int
    прошло: int
    состояние: str
    сорвалось: tuple[str, ...] = ()

    def as_json(self) -> dict:
        return {"ключ": self.ключ, "заголовок": self.заголовок,
                "возможных": self.возможных, "прошло": self.прошло,
                "состояние": self.состояние,
                "сорвалось": list(self.сорвалось)}


def ход(журнал, кончено: bool = True) -> tuple[КрупныйХод, ...]:
    """Шесть крупных этапов по подробному журналу проводки.

    Состояние крупного этапа **не считается долей пройденных подробных**. Часть
    подробных этапов срабатывает только на своих ветках: «производное» — лишь
    когда на вход подали наш же результат, «клетка» — лишь когда изоляцию
    выключили. Доля пройденных у них не доходит до полной никогда, и плитка
    навсегда осталась бы «идёт» на законченной работе.

    Судим по движению вперёд: работа ушла к следующему крупному этапу — этот
    пройден. Ушла и не вернулась — значит, кончен. Это то же правило, что у
    самой отметки хода: движение видно по тому, что оно **сменилось**.
    """
    журнал = tuple(журнал)
    пройдено, сорвалось = {}, {}
    последний = -1
    порядок = {ключ: место for место, (ключ, _, _) in enumerate(КРУПНЫЕ)}
    for этап in журнал:
        имя = getattr(этап, "имя", None) or этап.get("этап", "")
        удался = (getattr(этап, "получилось", None)
                  if hasattr(этап, "получилось") else этап.get("получилось"))
        ключ = _ПО_ЭТАПАМ.get(имя)
        if ключ is None:
            continue
        пройдено.setdefault(ключ, set()).add(имя)
        последний = max(последний, порядок[ключ])
        if not удался:
            сорвалось.setdefault(ключ, []).append(имя)

    свои = []
    for место, (ключ, заголовок, подробные) in enumerate(КРУПНЫЕ):
        свои_сорвались = tuple(сорвалось.get(ключ, ()))
        прошло = len(пройдено.get(ключ, ()))
        if свои_сорвались:
            состояние = СОРВАЛСЯ
        elif прошло == 0:
            состояние = ЖДЁТ
        elif место < последний or кончено:
            состояние = ГОТОВ
        else:
            состояние = ИДЁТ
        свои.append(КрупныйХод(
            ключ=ключ, заголовок=заголовок, возможных=len(подробные),
            прошло=прошло, состояние=состояние, сорвалось=свои_сорвались))
    return tuple(свои)


ПРОЙДЕН = "пройден"


def ход_по_отметке(отметка, кончено: bool = False) -> tuple[КрупныйХод, ...]:
    """Крупные этапы по одной отметке — то, что видно **по ходу работы**.

    Здесь нет и не может быть чисел пройденного и слова «сорвался»: отметка
    говорит, где работа сейчас, и не говорит, чем кончился каждый подробный
    этап. Это узнаётся из журнала проводки, когда работа кончится, — и там
    показывается отдельно.

    Молчать об этом различии нельзя: строка «Разбор — пройден» по ходу работы
    значит «работа ушла дальше», а не «разбор удался».
    """
    сейчас = _ПО_ЭТАПАМ.get(getattr(отметка, "этап", "") or "", "")
    порядок = {ключ: место for место, (ключ, _, _) in enumerate(КРУПНЫЕ)}
    место_сейчас = порядок.get(сейчас, -1)
    свои = []
    for место, (ключ, заголовок, подробные) in enumerate(КРУПНЫЕ):
        if кончено:
            состояние = ПРОЙДЕН
        elif место_сейчас < 0:
            состояние = ЖДЁТ
        elif место < место_сейчас:
            состояние = ПРОЙДЕН
        elif место == место_сейчас:
            состояние = ИДЁТ
        else:
            состояние = ЖДЁТ
        свои.append(КрупныйХод(ключ=ключ, заголовок=заголовок,
                               возможных=len(подробные), прошло=0,
                               состояние=состояние))
    return tuple(свои)


def прерывания(журнал) -> tuple[tuple[str, str], ...]:
    """Чем работа оборвана, если оборвана. Пусто — значит не оборвана."""
    свои = []
    for этап in журнал:
        имя = getattr(этап, "имя", None) or этап.get("этап", "")
        if имя in ПРЕРЫВАНИЯ:
            свои.append((имя, ПРЕРЫВАНИЯ[имя]))
    return tuple(свои)


