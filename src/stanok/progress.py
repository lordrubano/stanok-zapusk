НЕ_ЗНАЮ = "не знаю"


def процесс_жив(pid: int) -> str:
    """Есть ли ещё такой процесс. Третий ответ — «не знаю», и он честный.

    Сведение вспомогательное: приговор наблюдателя от него не зависит. Оно
    только отличает «стоит» от «его больше нет», а это разные беды и разные
    первые ходы оператора.
    """
    if not pid or pid < 0:
        return НЕ_ЗНАЮ
    if os.name == "nt":
        try:
            import ctypes

            SYNCHRONIZE = 0x00100000
            ядро = ctypes.windll.kernel32
            ручка = ядро.OpenProcess(SYNCHRONIZE, False, int(pid))
            if not ручка:
                return МЁРТВ
            try:
                # 0 — не ждать вовсе, только спросить.
                return МЁРТВ if ядро.WaitForSingleObject(ручка, 0) == 0 else ЖИВ
            finally:
                ядро.CloseHandle(ручка)
        except Exception:  # noqa: BLE001 — не знаю лучше, чем выдуманное «жив»
            return НЕ_ЗНАЮ
    try:
        os.kill(int(pid), 0)
    except ProcessLookupError:
        return МЁРТВ
    except PermissionError:
        return ЖИВ
    except OSError:
        return НЕ_ЗНАЮ
    return ЖИВ


