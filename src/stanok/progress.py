@dataclass(frozen=True, slots=True)
class СтрокаКартины:
    """Один документ партии вместе с тем, что о нём знает реестр запусков."""

    отпечаток: str
    имя: str
    состояние_файла: str
    прогон: str
    записей: int | None = None
    почему: str = ""
    идёт_сейчас: bool = False

    def as_json(self) -> dict:
        return {"отпечаток": self.отпечаток, "имя": self.имя,
                "состояние_файла": self.состояние_файла, "прогон": self.прогон,
                "записей": self.записей, "почему": self.почему,
                "идёт_сейчас": self.идёт_сейчас}


ПРОГОН_НЕ_НАЧАТ = "не начат"
ПРОГОН_ИДЁТ = "идёт"
ПРОГОН_КОНЧЕН = "кончен"
ПРОГОН_СОРВАН = "сорван"


def картина(партия, события=(), отметка: Отметка | None = None
            ) -> tuple[СтрокаКартины, ...]:
    """Сводит два учёта в один: партия знает файлы, реестр знает прогоны.

    Ключ склейки — **отпечаток документа**, а не имя файла: имя недоверено и в
    партии, и в реестре, а отпечаток одинаков в обоих (шаг 62).
    """
    from . import batch as учёт

    # Отпечаток документа стоит только в отметке «начат»: дальше запуск ведётся
    # по своему ключу. Поэтому сначала выясняется, какой ключ какому документу
    # принадлежит, и лишь потом к документу собираются все его отметки.
    события = tuple(события)
    ключ_документа = {с.get("ключ"): с.get("document_id")
                      for с in события if с.get("document_id")}
    по_документам: dict = {}
    for событие in события:
        документ = (событие.get("document_id")
                    or ключ_документа.get(событие.get("ключ")) or "")
        if документ:
            по_документам.setdefault(документ, []).append(событие)

    строки = []
    for файл in партия.файлы.values():
        свои = по_документам.get(файл.отпечаток, ())
        прогон, записей, почему = _судьба_прогона(свои)
        идёт = bool(отметка and not отметка.кончено
                    and отметка.документ == файл.отпечаток)
        if идёт and прогон == ПРОГОН_НЕ_НАЧАТ:
            прогон = ПРОГОН_ИДЁТ
        строки.append(СтрокаКартины(
            отпечаток=файл.отпечаток, имя=файл.имя,
            состояние_файла=файл.состояние, прогон=прогон, записей=записей,
            почему=почему or (файл.почему if файл.состояние == учёт.ОТВЕРГНУТ
                              else ""),
            идёт_сейчас=идёт))
    return tuple(строки)


def _судьба_прогона(события) -> tuple[str, int | None, str]:
    from . import run as реестр

    if not события:
        return ПРОГОН_НЕ_НАЧАТ, None, ""
    концы = [с for с in события if с.get("состояние") == реестр.КОНЧЕН]
    if концы:
        последний = концы[-1]
        return ПРОГОН_КОНЧЕН, последний.get("записей"), ""
    начала = [с for с in события if с.get("состояние") == реестр.НАЧАТ]
    if начала:
        return (ПРОГОН_СОРВАН, None,
                "начат и не кончен: работа оборвалась или ещё идёт")
    return ПРОГОН_НЕ_НАЧАТ, None, ""


