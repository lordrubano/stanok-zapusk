# -*- coding: utf-8 -*-
"""Безопасный разбор XML: запрет внешних сущностей и объявлений типа.

Часть шага 26. Нормативная основа — чертёж v3.0, раздел 14.1: «блокировка XXE,
внешних сущностей, обхода каталогов и zip-бомб». Обход каталогов и бомбы закрыты
шагом 22; сущности откладывались до разбора XML, а разбор XML начинается здесь.

Чем опасна внешняя сущность. Документ объявляет своё имя для куска содержимого
и указывает, откуда его взять: из файла на диске или по сети. Разборщик, честно
исполняя правила XML, подставляет содержимое чужого файла в документ — и оно
уходит дальше как часть разобранного. Так из машины утекают ключи, пароли и
что угодно ещё, а сам документ выглядит безобидно.

Правило здесь простое и строгое: **объявление типа документа отвергается
целиком**. Не «внешние сущности отвергаются, а внутренние разрешены» — целиком.
Основания:

* в офисных форматах объявления типа не бывает вовсе. Оно там не нужно ни для
  чего, и его появление означает либо порчу, либо умысел;
* разделять внутренние и внешние сущности значит перебирать случаи и полагаться
  на то, что перебор полон. Внутренние сущности вдобавок дают лавину: несколько
  строк раскрываются в гигабайты;
* отвергнуть целое проще проверить, чем частичный разбор, а простую защиту
  труднее сломать.

Проверка идёт **до** разбора, по байтам. Отдавать документ разборщику, а потом
спрашивать, что он там подставил, поздно: к этому времени чужой файл уже прочтён.
"""

from __future__ import annotations

import re
from xml.etree import ElementTree


XML_SAFETY_VERSION = "xml-safety/1"

KNOWN_LIMITATIONS = (
    "Проверяется только то, что объявления типа и сущностей в части нет. "
    "Разбор ведёт разборщик стандартной библиотеки, внешних источников он не "
    "открывает; но если однажды разбор станет вести иная библиотека, запрет "
    "придётся проверять заново — здесь он держится и на запрете объявления, и "
    "на поведении разборщика.",
    "XInclude не проверяется: разборщик стандартной библиотеки его не "
    "исполняет. При смене разборщика это надо проверить отдельно.",
)


class XMLОпасен(ValueError):
    """Часть документа содержит то, что разбирать нельзя."""

    def __init__(self, код: str, объяснение: str) -> None:
        self.код = код
        super().__init__(объяснение)


# Объявление типа документа и объявление сущности. Ищем по байтам до разбора:
# у разборщика спрашивать поздно, он к тому времени уже всё подставит.
_ОБЪЯВЛЕНИЕ_ТИПА = re.compile(rb"<!\s*DOCTYPE", re.IGNORECASE)
_ОБЪЯВЛЕНИЕ_СУЩНОСТИ = re.compile(rb"<!\s*ENTITY", re.IGNORECASE)


def проверить(данные: bytes, где: str = "часть") -> None:
    """Отвергает часть с объявлением типа или сущности. Иначе молчит."""

    if _ОБЪЯВЛЕНИЕ_СУЩНОСТИ.search(данные):
        raise XMLОпасен(
            "E_XML_ENTITY",
            f"{где}: объявление сущности запрещено — так подставляют чужие "
            "файлы и раскрывают лавину")
    if _ОБЪЯВЛЕНИЕ_ТИПА.search(данные):
        raise XMLОпасен(
            "E_XML_DOCTYPE",
            f"{где}: объявление типа документа запрещено — в офисных форматах "
            "его не бывает, и появление означает порчу или умысел")


def разобрать(данные: bytes, где: str = "часть"):
    """Проверяет часть и разбирает её. Возвращает корень дерева.

    Разборщик берётся заново на каждую часть: общий разборщик хранит состояние
    между разборами, и подсунутое в одной части могло бы отозваться в другой.
    """

    проверить(данные, где)
    try:
        return ElementTree.fromstring(данные)
    except ElementTree.ParseError as беда:
        raise XMLОпасен("E_XML_BROKEN", f"{где}: разметка испорчена ({беда})") from беда


__all__ = [
    "KNOWN_LIMITATIONS",
    "XMLОпасен",
    "XML_SAFETY_VERSION",
    "проверить",
    "разобрать",
]
