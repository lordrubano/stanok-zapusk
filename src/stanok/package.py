# -*- coding: utf-8 -*-
"""Пакет оснастки как изделие: ставится как данные, а не как код.

Шаг 70 плана. Нормативная основа — чертёж v3.0 и решение владельца о **двух
изделиях**: ядро и пакеты оснастки версионируются и поставляются раздельно.

**На этом стоит модель продажи.** Продукт — ядро; подписка — пакеты оснастки.
Если ради нового банка приходится пересобирать ядро, то продаётся не продукт с
подпиской, а разработка на заказ, и цена у неё другая.

Отсюда требования к пакету, и все они проверяемы:

* **пакет — данные.** Внутри объявление формы и опись; ни строчки кода. Ядро
  его читает, а не исполняет;
* **пакет знает, какому ядру он годится.** В описи стоит версия языка оснастки
  и наименьшая версия ядра, которая его понимает. Ядро, которое старше, —
  отказывается (шаг 38), а не разбирает как умеет;
* **пакет проверяем.** Опись несёт отпечаток содержимого: подменённый пакет
  виден до того, как по нему разберут документ;
* **ядро не знает пакетов.** В ядре нет ни одного имени семейства — оно
  появляется вместе с пакетом и уходит вместе с ним.

Установка пакета — **копирование файла**. Ни пересборки, ни перезапуска
разработчика: положил рядом, ядро нашло.
"""

from __future__ import annotations

import hashlib
import json
import zipfile
from dataclasses import dataclass
from pathlib import Path

from .tooling import ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ, ВерсияНеПоддержана, загрузить


PACKAGE_VERSION = "tooling-package/1"

ОПИСЬ = "опись.json"
ОБЪЯВЛЕНИЕ = "оснастка.json"

# Какие версии языка оснастки понимает какое ядро. Перечень **поимённый** —
# правило шага 38: ядро не «поддерживает всё до такой-то версии», а знает
# названные. Второе ядро читает обе версии, первое — только первую, и это
# позволяет откатить ядро назад, не потеряв прежних пакетов.
ЯЗЫКИ_ЯДРА = {
    "1": frozenset({"tooling/1"}),
    "2": frozenset({"tooling/1", "tooling/2"}),
}

KNOWN_LIMITATIONS = (
    "Опись несёт отпечаток, а не подпись ключом: подмену видно, авторство — "
    "нет. Подписание пакетов относится к поставке и лицензированию (шаг 74).",
    "Наименьшая версия ядра объявляется в пакете, а не выводится: тот, кто "
    "собирает пакет, отвечает за это число. Ядро может лишь отказаться, если "
    "оно старше.",
    "Пакет содержит одно семейство. Сборка нескольких семейств в один пакет "
    "потребует своей описи и здесь не делается.",
)


class ПакетНегоден(ValueError):
    """Пакет не может быть прочитан: сказано, чем именно."""


@dataclass(frozen=True, slots=True)
class Опись:
    """Что за пакет, кому годится и чем проверяется."""

    версия_описи: str
    семейство: str
    версия_оснастки: str
    язык: str
    наименьшее_ядро: str
    отпечаток: str

    def as_json(self) -> dict:
        return {
            "версия_описи": self.версия_описи,
            "семейство": self.семейство,
            "версия_оснастки": self.версия_оснастки,
            "язык": self.язык,
            "наименьшее_ядро": self.наименьшее_ядро,
            "отпечаток": self.отпечаток,
        }


def _отпечаток(байты: bytes) -> str:
    return hashlib.sha256(байты).hexdigest()


def собрать(объявление: dict | str | bytes, куда, наименьшее_ядро: str = "1") -> Path:
    """Собирает пакет оснастки из объявления семейства.

    Объявление проверяется **до** упаковки: негодный пакет не должен доехать до
    клиента, чтобы сломаться у него. Это тот же разбор, которым ядро читает
    оснастку, и другого здесь нет нарочно — иначе сборка и чтение однажды
    разошлись бы в понимании того, что такое годный пакет.
    """
    если_байты = объявление
    if isinstance(объявление, (str, bytes)):
        содержимое = json.loads(объявление)
    else:
        содержимое = объявление
    оснастка = загрузить(содержимое)      # роняет негодное здесь, а не у клиента

    байты = json.dumps(содержимое, ensure_ascii=False, sort_keys=True,
                       separators=(",", ":")).encode("utf-8")
    опись = Опись(
        версия_описи=PACKAGE_VERSION,
        семейство=оснастка.семейство,
        версия_оснастки=оснастка.версия,
        язык=содержимое.get("язык", ""),
        наименьшее_ядро=str(наименьшее_ядро),
        отпечаток=_отпечаток(байты))

    место = Path(куда)
    место.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(место, "w", zipfile.ZIP_DEFLATED) as пакет:
        пакет.writestr(ОБЪЯВЛЕНИЕ, байты)
        пакет.writestr(ОПИСЬ, json.dumps(опись.as_json(), ensure_ascii=False,
                                         sort_keys=True, indent=1))
    return место


def прочитать_опись(путь) -> Опись:
    """Опись пакета, без чтения самого объявления."""
    try:
        with zipfile.ZipFile(Path(путь)) as пакет:
            свод = json.loads(пакет.read(ОПИСЬ).decode("utf-8"))
    except (OSError, KeyError, zipfile.BadZipFile, ValueError) as беда:
        raise ПакетНегоден(f"опись пакета не читается: {беда}") from беда
    try:
        return Опись(**свод)
    except TypeError as беда:
        raise ПакетНегоден(f"опись пакета неполна: {беда}") from беда


def поставить(путь, версия_ядра: str = "1"):
    """Читает пакет и отдаёт оснастку. Проверяет всё до разбора документа.

    Порядок проверок не случаен: сперва целость, потом годность ядру, потом
    разбор объявления. Разбирать объявление подменённого пакета незачем, а
    читать пакет, которого это ядро не понимает, — тем более.
    """
    место = Path(путь)
    опись = прочитать_опись(место)
    try:
        with zipfile.ZipFile(место) as пакет:
            байты = пакет.read(ОБЪЯВЛЕНИЕ)
    except (OSError, KeyError, zipfile.BadZipFile) as беда:
        raise ПакетНегоден(f"объявление пакета не читается: {беда}") from беда

    if _отпечаток(байты) != опись.отпечаток:
        raise ПакетНегоден(
            "отпечаток не сходится: пакет подменён или испорчен. Разбирать "
            "документ таким пакетом нельзя")

    знает = ЯЗЫКИ_ЯДРА.get(str(версия_ядра), ПОДДЕРЖИВАЕМЫЕ_ВЕРСИИ)
    if опись.язык not in знает:
        raise ВерсияНеПоддержана([
            f"пакет написан на языке оснастки {опись.язык!r}, а ядро "
            f"{версия_ядра} знает " + ", ".join(sorted(знает))
            + ". Читать его нечем: нужно ядро новее или пакет на прежнем "
              "языке. Молчаливой попытки разобрать не будет"])

    if _старше(версия_ядра, опись.наименьшее_ядро):
        raise ВерсияНеПоддержана([
            f"пакет требует ядра не ниже {опись.наименьшее_ядро}, а это ядро "
            f"{версия_ядра}. Обновите ядро либо возьмите пакет для него"])

    return загрузить(json.loads(байты.decode("utf-8")))


def _старше(версия_ядра: str, нужно: str) -> bool:
    """Ядро старше требуемого? Сравнение по числам, а не по строкам."""
    def числа(строка: str):
        return tuple(int(ч) for ч in str(строка).split(".") if ч.isdigit())

    свои, нужные = числа(версия_ядра), числа(нужно)
    return свои < нужные if свои and нужные else False


def описать(путь) -> dict:
    """Что за пакет — для показа человеку и для журнала."""
    опись = прочитать_опись(путь)
    свой = опись.as_json()
    свой["файл"] = Path(путь).name
    свой["байт"] = Path(путь).stat().st_size
    return свой


