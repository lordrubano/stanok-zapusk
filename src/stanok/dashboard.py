"""Дашборд клиента и состояние системы — врозь, и врозь по устройству.

Шаг 83 плана. Нормативная основа — ТЗ на интерфейс 1.0, часть III (режим 4,
«Отдельно: состояние системы») и часть IX.

## Состояние системы не смешивается с состоянием партии

Версия ядра, подпись поставки, право на работу и дата резервной копии — это
**состояние машины**, а не состояние работы. В рабочем потоке им места нет:
оператор, разбирающий исключения, ничего не может сделать с истёкшим правом, а
мельтешение исправных показателей приучает не смотреть на них вовсе.

Поэтому: **пока всё в порядке — скрыто**. Истекает право, не сошлась подпись,
нет свежей копии — отдельное предупреждение, и оно единственное, что видно.

## Наружу уходят счётчики, а не содержимое

Часть XI: пока дашборд на машине оператора — суммы видны, это данные клиента и
показывать их ему можно. Вынесенный наружу дашборд показывает **только
счётчики, доли и коды**.

Разведено это **в устройстве, а не на словах**. Наружный вид собирается не
урезанием местного, а отдельной сборкой по **закрытому перечню** имён, и каждое
значение проходит те же правила, что наблюдения шага 63: числа обязаны быть
числами, строки — только вида кода или версии, строка из одних цифр и
разделителей отвергается как данные. Правила не переписаны — вызываются те же.

Отсюда следствие: сумма, номер счёта или имя контрагента **не могут** попасть
наружу по недосмотру. Не «мы их не кладём», а «положить не выйдет»: сборка
упадёт отказом.

## Доли уходят целыми процентами

Доля вида «0.8312» — строка из цифр и разделителей, то есть по правилам шага 63
неотличимая от данных. Наружу доли идут целыми процентами: и правилу не
противоречит, и смысл сохраняют.
"""

