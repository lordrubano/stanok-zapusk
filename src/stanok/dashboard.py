@dataclass(frozen=True, slots=True)
class Показатель:
    """Один показатель состояния системы: что, как и чем подтверждено."""

    имя: str
    значение: str
    состояние: str
    почему: str = ""
    откуда: str = ""

    @property
    def тревожит(self) -> bool:
        """Неизвестное тревожит наравне с плохим — как в движке политик."""
        return self.состояние != В_ПОРЯДКЕ

    def as_json(self) -> dict:
        return {"имя": self.имя, "значение": self.значение,
                "состояние": self.состояние, "почему": self.почему,
                "откуда": self.откуда}


def _показатель_ядра(состав) -> Показатель:
    if not состав:
        return Показатель("Версия ядра", "неизвестна", НЕИЗВЕСТНО,
                          "перечня состава рядом нет: изделие собрано не нами "
                          "или перечень не приложен",
                          "перечень состава выпуска (шаг 73)")
    версия = str(состав.get("версия") or "не названа")
    отпечаток = str(состав.get("отпечаток_изделия") or "")[:12]
    собрано = str(состав.get("собрано") or "")
    return Показатель("Версия ядра", версия, В_ПОРЯДКЕ,
                      f"отпечаток {отпечаток}"
                      + (f", собрано {собрано}" if собрано else ""),
                      "перечень состава выпуска (шаг 73)")


def _показатель_подписи(подпись) -> Показатель:
    откуда = "подпись поставки (шаг 74)"
    if not подпись:
        return Показатель("Подпись поставки", "не проверялась", НЕИЗВЕСТНО,
                          "свидетельства подписи рядом нет", откуда)
    почему = "; ".join(б.get("словами", "") for б in подпись.get("почему", ()))
    if not подпись.get("подпись_сошлась"):
        return Показатель("Подпись поставки", "не сошлась", ПРЕДУПРЕЖДЕНИЕ,
                          почему or "подпись не сошлась с изделием", откуда)
    if not подпись.get("наше"):
        # Подпись сошлась сама с собой — это не доказывает ничего, и молчать
        # об этом нельзя: зелёная строка тут была бы прямым обманом.
        return Показатель("Подпись поставки", "сошлась, но издатель не назван",
                          НЕИЗВЕСТНО, почему or
                          "открытый ключ издателя не объявлен: подпись "
                          "проверена сама с собой", откуда)
    return Показатель("Подпись поставки", "сошлась", В_ПОРЯДКЕ,
                      "изделие подписано известным издателем", откуда)


def _показатель_права(право) -> Показатель:
    откуда = "право на работу (шаг 74)"
    if not право:
        return Показатель("Право на работу", "не проверялось", НЕИЗВЕСТНО,
                          "файла права рядом нет", откуда)
    до = str(право.get("до") or "не названо")
    if not право.get("действует"):
        почему = "; ".join(б.get("словами", "")
                           for б in право.get("почему", ()))
        return Показатель("Право на работу", f"не действует (до {до})",
                          ПРЕДУПРЕЖДЕНИЕ, почему or "право не действует",
                          откуда)
    return Показатель("Право на работу", f"действует до {до}", В_ПОРЯДКЕ,
                      f"выдано {право.get('кому') or 'не названо'}", откуда)


def _показатель_копии(копия, сегодня: str) -> Показатель:
    откуда = "еженедельная копия (воскресенье, 21:00)"
    if not копия or not копия.get("когда"):
        return Показатель("Резервная копия", "неизвестна", НЕИЗВЕСТНО,
                          "о копии станку не сказано ничего", откуда)
    когда = str(копия.get("когда"))[:10]
    дней = _сколько_дней(когда, сегодня)
    if дней is None:
        return Показатель("Резервная копия", когда, НЕИЗВЕСТНО,
                          "дату копии не прочитать", откуда)
    if дней > СВЕЖЕСТЬ_КОПИИ_ДНЕЙ:
        return Показатель("Резервная копия", f"от {когда}", ПРЕДУПРЕЖДЕНИЕ,
                          f"копии {дней} дней при сроке "
                          f"{СВЕЖЕСТЬ_КОПИИ_ДНЕЙ}: задание не отработало или "
                          "копия не доехала", откуда)
    return Показатель("Резервная копия", f"от {когда}", В_ПОРЯДКЕ,
                      f"копии {дней} дней", откуда)


def _сколько_дней(когда: str, сегодня: str) -> int | None:
    try:
        было = date.fromisoformat(str(когда)[:10])
        нынче = date.fromisoformat(str(сегодня)[:10])
    except (ValueError, TypeError):
        return None
    return (нынче - было).days


def _показатель_склада(склад) -> Показатель:
    """Есть ли дальний склад и что он принёс при пробуждении.

    На арендованной площадке диск не переживает засыпания, и работа держится
    **только** складом. Пока его состояние было видно лишь в первой строке
    журнала площадки, снаружи нельзя было отличить работающий станок от
    станка, который всё потеряет при первом же засыпании: экран одинаков.
    Проверено живьём — решение, принятое на площадке, сна не пережило, и
    узнать об этом было неоткуда.
    """
    откуда = "дальний склад (src/stanok/sklad.py)"
    if not склад or not склад.get("описание"):
        return Показатель(
            "Дальний склад", "не настроен", ПРЕДУПРЕЖДЕНИЕ,
            "работа живёт только на диске этой машины: на площадке, которая "
            "засыпает с чистым диском, она пропадёт", откуда)
    принесено = склад.get("принесено")
    сколько = len(принесено) if принесено is not None else None
    подпись = str(склад.get("описание"))
    if сколько is None:
        return Показатель("Дальний склад", подпись, НЕИЗВЕСТНО,
                          "склад назван, но приносил ли он что-нибудь при "
                          "подъёме — не сказано", откуда)
    return Показатель(
        "Дальний склад", подпись, В_ПОРЯДКЕ,
        (f"при подъёме принесено файлов: {сколько}" if сколько
         else "при подъёме склад был пуст — это первый запуск или работа "
              "ещё не начиналась"), откуда)


def состояние_системы(*, состав=None, подпись=None, право=None, копия=None,
                      сегодня: str = "", склад=None) -> tuple[Показатель, ...]:
    """Пять показателей машины. Станок их не проверяет — он их спрашивает."""
    return (_показатель_ядра(состав), _показатель_подписи(подпись),
            _показатель_права(право), _показатель_копии(копия, сегодня),
            _показатель_склада(склад))


def тревожат(показатели) -> tuple[Показатель, ...]:
    return tuple(п for п in показатели if п.тревожит)


