def _т(значение) -> str:
    return обезвредить(значение)


_ТОЧКА = {В_ПОРЯДКЕ: "t-zel", ПРЕДУПРЕЖДЕНИЕ: "t-kras", НЕИЗВЕСТНО: "t-zhel"}


def система_html(показатели) -> str:
    """Состояние системы. Пока всё в порядке — свёрнуто, а не выложено.

    Свёрнутое не значит спрятанное: строка о том, что показатели есть и они в
    порядке, остаётся видимой. Спрятать вовсе значило бы отучить смотреть.
    """
    беспокоящие = тревожат(показатели)
    куски = []
    if беспокоящие:
        имена = ", ".join(п.имя.lower() for п in беспокоящие)
        подробно = " ".join(f"{п.имя}: {п.почему}." for п in беспокоящие)
        куски.append(f'<div class="vrezka"><b>⚠ Состояние системы требует '
                     f"внимания: {_т(имена)}</b><span>{_т(подробно)}</span>"
                     "</div>")
    строки = []
    for п in показатели:
        строки.append(
            f'<div class="ind"><div class="im">'
            f'<span class="tochka {_ТОЧКА[п.состояние]}"></span>{_т(п.имя)}'
            f'</div><div class="zn">{_т(п.значение)}'
            + (f" — {_т(п.почему)}" if п.почему else "")
            + f'<div class="tih">откуда: {_т(п.откуда)}</div></div></div>')
    открыто = " open" if беспокоящие else ""
    заголовок = ("Состояние системы — есть чем заняться"
                 if беспокоящие else
                 "Состояние системы: всё в порядке, подробности по нажатию")
    куски.append(f'<details class="sistema"{открыто}>'
                 f"<summary>{_т(заголовок)}</summary>"
                 f'<div class="karta">{"".join(строки)}</div></details>')
    return "".join(куски)


def партия_html(свод: dict) -> str:
    """Показатели партии — рабочий поток. Системных показателей здесь нет."""
    свои = [("документов", свод.get("документов", 0), "pl-seraya"),
            ("записей", свод.get("записей", 0), "pl-seraya"),
            ("ушло человеку", свод.get("ушло_человеку", 0), "pl-zheltaya"),
            ("допущено автоматически",
             свод.get("допущено_автоматически", 0), "pl-zelenaya")]
    куски = []
    for имя, число, цвет in свои:
        куски.append(f'<div class="plitka {цвет}"><div class="p">{_т(имя)}'
                     f'</div><div class="n">{число}</div></div>')
    return f'<div class="plitki">{"".join(куски)}</div>'


def значения_html(записи, сколько: int = 10) -> str:
    """Значения операций — данные клиента. Наружу этот вид не уходит никогда.

    Поля записи показываются **все**. Первая редакция брала первые пять — и на
    настоящем документе, где поля идут по алфавиту, сумма в эту пятёрку не
    попала: раздел, заведённый ради того, чтобы суммы были видны, суммы и не
    показывал. Урезание, о котором не сказано, тем и опасно, что выглядит как
    полный список.
    """
    записи = list(записи)
    строки = ['<table class="dok"><tr><th>Запись</th><th>Поля</th></tr>']
    показано = 0
    for запись in записи:
        поля = запись.get("fields")
        поля = поля if isinstance(поля, dict) else {}
        if not поля:
            continue
        пары = "; ".join(
            f"{имя}: {значение.get('value')}"
            for имя, значение in поля.items() if isinstance(значение, dict))
        строки.append(f"<tr><td><code>{_т(запись.get('record_id', ''))}</code>"
                      f"</td><td>{_т(пары)}</td></tr>")
        показано += 1
        if показано >= сколько:
            break
    строки.append("</table>")
    хвост = ""
    if len(записи) > показано:
        хвост = (f'<div class="snoska">Показано {показано} записей из '
                 f"{len(записи)}: страница не безразмерна. Поля показаны все, "
                 "без отбора.</div>")
    return "".join(строки) + хвост


