def _проверить_наружное(ключ: str, значение) -> None:
    """Проверяет значение теми же правилами, что наблюдения шага 63.

    Правила не переписаны: вызывается тот самый код. Два набора правил об одном
    рано или поздно разошлись бы, и щель между ними стала бы дырой — ровно то,
    чего боится сам шаг 63.
    """
    if ключ not in НАРУЖУ:
        raise наблюдаемость.НаблюдениеНегодно(
            f"{СОДЕРЖИМОЕ_НАРУЖУ}: поля {ключ!r} нет в перечне выносимого "
            "наружу. Перечень закрыт нарочно: запреты всегда отстают от "
            "выдумки, а разрешения — нет")
    образец = "записей" if ключ in НАРУЖУ_ЧИСЛОВЫЕ else "код_результата"
    наблюдаемость._проверить_значение(образец, значение)


def наружу(свод: dict) -> dict:
    """Собирает наружный вид. Содержимое сюда не попадает по устройству.

    Не урезание местного вида, а отдельная сборка по закрытому перечню: любое
    поле сверх перечня и любое значение, похожее на данные, роняют сборку
    отказом.
    """
    свой = {"версия": DASHBOARD_VERSION}
    for ключ, значение in свод.items():
        _проверить_наружное(ключ, значение)
        свой[ключ] = значение
    return свой


def процентами(часть: int, целое: int) -> int:
    """Доля целыми процентами: строка «0.8312» наружу не проходит по правилам."""
    if not целое:
        return 0
    return int(Decimal(часть) * 100 / Decimal(целое))


def свод_наружу(партия=None, проводка=None, ворота=None) -> dict:
    """Готовый наружный свод из того, что уже посчитано другими."""
    свой: dict = {}
    if партия is not None:
        свой["документов"] = партия.документов
        свой["состояние_партии"] = партия.состояние
        свой["подач"] = len(партия.подачи)
    if проводка is not None:
        # Имена статусов берутся у движка политик, а не пишутся здесь строкой:
        # статус рождается в одном месте, и называется он оттуда же.
        from .decision import ACCEPTED_AUTO, REVIEW

        записи = list(getattr(проводка, "записи", ()) or ())
        решения = list(getattr(проводка, "решения", ()) or ())
        ушло = sum(1 for р in решения if getattr(р, "статус", "") == REVIEW)
        авто = sum(1 for р in решения
                   if getattr(р, "статус", "") == ACCEPTED_AUTO)
        свой["записей"] = len(записи)
        свой["ушло_человеку"] = ушло
        свой["допущено_автоматически"] = авто
        свой["доля_автоматизации_процентов"] = процентами(авто, len(решения))
        свой["доля_ушедшего_человеку_процентов"] = процентами(ушло,
                                                              len(решения))
        свой["состояние_запуска"] = getattr(проводка, "состояние_запуска", "")
    if ворота is not None:
        свой["код_ворот"] = "открыты" if ворота.можно else "закрыты"
    return наружу(свой)


