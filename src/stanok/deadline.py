# -*- coding: utf-8 -*-
"""Предельное время обработки: молчание перестаёт быть возможным исходом.

Работа вне нумерации. Найдено поркой проверок: одна правка нижнего слоя чтения
PDF загоняла разбор в бесконечный цикл, и станок в таком случае **не отказывал
и не врал — он никогда не отвечал**. Ни отказа, ни ответа: тот единственный
исход, которого предъявить нельзя.

Пределы размера и числа страниц объявлены шагом 21 и стерегутся. Срока чтения
не было объявлено нигде — ни в чертеже, ни в коде. Здесь он объявлен.

**Три правила.**

* **Срок на файл общий.** Пять минут, утверждённые шагом 21, не удваиваются и
  не складываются: места делят один запас, а не получают каждое свой поверх
  него. Иначе предел на файл перестал бы быть пределом.
* **У каждого долгого места свой потолок.** Он не добавляет времени, а отнимает
  право молчать: место, съевшее свой потолок, отказывает сразу, не дожидаясь
  общих пяти минут, и называет себя поимённо.
* **Превышение — отказ, а не догадка.** Код отказа тот же, что у превышения
  размера и числа страниц: ``E_LIMIT_DURATION``. Частичного результата
  повисшая обработка не даёт: недоделанное не выдаётся за сделанное.

**Чего срок не может.** Соблюдение проверяется в отметках внутри циклов, а не
принуждением извне: своё же обращение к чужому коду прервать посреди вызова
Питон не даёт. Значит, срок ловит **зациклившееся** место и **медленное**
место, но не одиночный вызов чужой библиотеки, повисший внутри себя. Жёсткое
принуждение — только клетка шага 24: отдельный процесс, убиваемый по времени.
Это названо здесь, а не спрятано: срок в собственном коде и клетка вокруг
чужого — разные средства, и второе первым не заменяется.
"""

from __future__ import annotations

import time
from dataclasses import dataclass

from .intake import APPROVED_LIMITS


DEADLINE_VERSION = "deadline/1"

# Утверждено владельцем 04.08.2026 по замеру на настоящих документах.
# Замер: выписка 218 страниц — чтение устройства 0,07 с, извлечение текста
# 5,6 с (25,8 мс на страницу), сборка страниц 0,80 с. На предельной тысяче
# страниц извлечение по худшей измеренной скорости даёт около 26 с; потолок
# взят с запасом на медленную машину, а не подогнан под замер.
СРОКИ_МЕСТ = {
    "чтение устройства PDF": 60,
    "извлечение текста": 120,
    "разбор архива": 120,
    "сборка страниц": 60,
    "распознавание изображения": 180,
}
"""Потолок каждого долгого места, в секундах. Общий запас файла — свой."""

СРОК_СТРАНИЦЫ_РАСПОЗНАВАНИЯ = 30
"""Сколько даётся стороннему распознавателю на одну страницу, в секундах."""

ШАГ_ОПРОСА = 4096
"""Через сколько отметок часы спрашиваются по-настоящему.

Спрашивать время каждый оборот цикла дорого: у чтения PDF обороты считаются
миллионами. Отметка сама по себе — сложение и сравнение; часы спрашиваются
раз в несколько тысяч отметок, отчего опоздание отказа не превышает доли
секунды и на пятиминутном сроке незаметно.
"""


class СрокИстёк(Exception):
    """Предельное время вышло. Отказ, а не поломка."""

    код = "E_LIMIT_DURATION"

    def __init__(self, место: str, прошло: float, предел: int) -> None:
        self.место = место
        self.прошло = прошло
        self.предел = предел
        super().__init__(
            f"{self.код}: место «{место}» не уложилось в срок: "
            f"прошло {прошло:.1f} с, предел {предел} с")

    @property
    def отказ(self):
        """Причина отказа в том же виде, в каком её выдаёт приём."""
        from .intake import Refusal

        return Refusal(self.код, str(self).split(": ", 1)[1])


@dataclass
class Срок:
    """Запас времени у места работы. Знает своего родителя и не врёт ему.

    Место не может получить больше, чем осталось у файла: вложенный срок берёт
    меньшее из своего потолка и родительского остатка. Поэтому сумма потолков
    мест не растягивает предел на файл ни на секунду.
    """

    предел: int
    имя: str = "файл"
    родитель: "Срок | None" = None
    часы: object = time.monotonic

    def __post_init__(self) -> None:
        if isinstance(self.предел, bool) or not isinstance(self.предел, int) \
                or self.предел <= 0:
            raise ValueError(
                f"срок места «{self.имя}» должен быть целым числом секунд "
                "больше нуля")
        self.начат = self.часы()
        self._отметок = 0

    # ------------------------------------------------------------ запас

    def прошло(self) -> float:
        return self.часы() - self.начат

    def остаток(self) -> float:
        свой = self.предел - self.прошло()
        if self.родитель is None:
            return свой
        return min(свой, self.родитель.остаток())

    # ------------------------------------------------------------ места

    def место(self, имя: str, предел: int | None = None) -> "Срок":
        """Вложенный срок долгого места.

        Потолок берётся из утверждённого набора. Незнакомому месту потолок не
        выдумывается: назвать его обязан тот, кто заводит место, — молчаливое
        умолчание вернуло бы ровно ту беду, ради которой заведён этот модуль.
        """
        if предел is None:
            предел = СРОКИ_МЕСТ.get(имя)
        if предел is None:
            raise ValueError(
                f"срок места «{имя}» не объявлен: утверждены "
                + ", ".join(f"«{м}»" for м in sorted(СРОКИ_МЕСТ)))
        return Срок(предел, имя, родитель=self, часы=self.часы)

    # --------------------------------------------------------- проверка

    def проверить(self) -> None:
        """Роняет отказом, если вышел срок места или срок файла."""
        if self.прошло() > self.предел:
            raise СрокИстёк(self.имя, self.прошло(), self.предел)
        if self.родитель is not None:
            self.родитель.проверить()

    def тик(self, шаг: int = 1) -> None:
        """Отметка внутри цикла. Часы спрашиваются раз в ``ШАГ_ОПРОСА``."""
        self._отметок += шаг
        if self._отметок >= ШАГ_ОПРОСА:
            self._отметок = 0
            self.проверить()


def на_файл(пределы=APPROVED_LIMITS, часы=time.monotonic) -> Срок:
    """Срок на весь файл — тот самый, что утверждён шагом 21."""
    return Срок(пределы.max_duration_seconds, "файл", часы=часы)


def место(имя: str, срок: Срок | None = None, предел: int | None = None) -> Срок:
    """Срок долгого места. Без родителя заводится свой, а не бессрочный.

    Здесь и держится обещание «молчание невозможно»: место, которому срока не
    передали, не остаётся без срока — оно получает свой потолок и предел файла
    сверх него. Забыть передать срок можно; остаться без срока — нельзя.
    """
    if срок is None:
        срок = на_файл()
    return срок.место(имя, предел)


