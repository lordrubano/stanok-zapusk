# -*- coding: utf-8 -*-
"""Устойчивые адреса источника: якоря областей.

Шаг 33 плана. Нормативная основа — чертёж v3.0, раздел 6.2.

**Зачем.** Доказательная связь держится на адресе: поле ссылается на область
источника, проверка ссылается на поле, исправление оператора ссылается на
запись. Если адрес меняется от правки порогов сегментации, вся эта связь рвётся
**задним числом**: вчерашние ссылки указывают в никуда, и доказать уже ничего
нельзя — причём молча, потому что ссылка выглядит как ссылка.

**Чего в адресе быть не должно.**

* **Номера локальной строки.** Он поедет при первой же правке порогов склейки:
  сегодня строк двадцать четыре, завтра двадцать три, и «строка[7]» указывает на
  другое место. Адрес, зависящий от того, как хорошо мы сегодня разложили
  источник, адресом не является.
* **Версии распознавателя, шаблона и нормализации.** Раздел 6.2 прямо: они
  хранятся отдельными признаками. Смена движка не должна переименовывать области
  источника — источник-то не изменился.
* **Порядка вывода.** У страничных источников порядковый номер куска зависит от
  того, как движок обошёл содержимое, и меняется вместе с ним.

**На чём адрес держится.** На том, что принадлежит самому источнику: отпечаток
исходных байтов, номер страницы, место области на странице и роль области.
Место берётся долями страницы и **округляется до объявленной сетки** — иначе
разница в шестом знаке между двумя выпусками распознавателя дала бы другой
адрес при том же самом месте.

Округление — часть **координатной системы**, и у неё есть версия. Меняется
сетка — меняется версия, и тогда, по разделу 6.2, нужна таблица соответствия
старых и новых якорей. Вечная устойчивость адреса не обещается: обещается, что
её потеря будет объявленной, а не тихой.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from decimal import Decimal


# Версия координатной системы. Меняется вместе с сеткой округления или
# правилами построения адреса — и тогда нужна таблица соответствия.
# Версия 2: учтён поворот страницы. До неё координаты считались по рамке «как
# записано в файле», и у страницы с /Rotate 90 низ листа в файле оказывался его
# боком на бумаге. Ориентация, зафиксированная как «как записано», требованию
# раздела 6.2 не отвечает — оно требует ориентации, в какой лист читают.
#
# Смена версии обязательна и объявлена: у одной и той же области источника
# адрес во второй версии другой. Таблицу соответствия строит `соответствие`;
# наружу адреса первой версии не выдавались ни разу, и переносить нечего.
СИСТЕМА_КООРДИНАТ = "доли-страницы/2"

# Сетка округления координат. Тысячная доля страницы — это около 0,2 мм на
# листе А4: меньше толщины буквы, но крупнее любой разницы между выпусками
# распознавателя.
СЕТКА = Decimal("0.001")

ANCHOR_VERSION = "source-anchor/1"

KNOWN_LIMITATIONS = (
    "Таблица соответствия строится только по совпадению якорей. Геометрическое "
    "сличение разъехавшихся областей — отдельная работа, и без корпуса "
    "настоящих документов её не на чем настраивать.",
    "У источников без координат адрес держится на структурном пути, и его "
    "устойчивость — обязанность адаптера. Путь с порядковым номером вывода "
    "адресом быть не может, и такой источник якорь отвергает.",
    "Столкновение адресов возможно: две области, округлившиеся в одну клетку "
    "сетки, дадут один адрес. Это обнаруживается и объявляется, а не "
    "разрешается молча.",
)


class ЯкорьНевозможен(ValueError):
    """Из объекта нельзя построить устойчивый адрес."""

    код = "E_ANCHOR_UNSTABLE"


# Части структурного пути, зависящие от того, как движок обошёл содержимое.
# Путь с таким числом устойчивым адресом быть не может.
_ПОРЯДКОВЫЕ = ("текст[", "проводка[", "остаток[", "поле[", "слово[", "строка[")


@dataclass(frozen=True, slots=True)
class Якорь:
    """Адрес области источника. Состав — раздел 6.2."""

    document_id: str
    страница: int
    роль: str
    система: str = СИСТЕМА_КООРДИНАТ
    полигон: tuple[tuple[str, str], ...] | None = None
    структурный_путь: str | None = None

    def опознавательная_часть(self) -> dict:
        """Только то, что принадлежит источнику и не зависит от разложения."""
        часть = {
            "версия": ANCHOR_VERSION,
            "document_id": self.document_id,
            "страница": self.страница,
            "роль": self.роль,
            "система": self.система,
        }
        if self.полигон is not None:
            часть["полигон"] = [list(точка) for точка in self.полигон]
        else:
            часть["структурный_путь"] = self.структурный_путь
        return часть

    @property
    def идентификатор(self) -> str:
        """Отпечаток опознавательной части.

        Считается от канонического UTF-8 JSON с явным порядком ключей: так один
        и тот же источник даёт один и тот же адрес на любой машине, в любой
        локали и при любом порядке словарей в памяти.
        """
        материал = json.dumps(
            self.опознавательная_часть(), ensure_ascii=False, allow_nan=False,
            sort_keys=True, separators=(",", ":")).encode("utf-8")
        return hashlib.sha256(материал).hexdigest()[:32]

    def as_json(self) -> dict:
        представление = dict(self.опознавательная_часть())
        представление["идентификатор"] = self.идентификатор
        if self.полигон is not None and self.структурный_путь:
            # Путь остаётся при якоре как пояснение для человека, но в
            # опознавательную часть не входит: он зависит от порядка вывода.
            представление["путь_для_чтения"] = self.структурный_путь
        return представление


def на_сетку(значение) -> str:
    """Округляет долю страницы до объявленной сетки.

    Округление — не косметика. Без него разница в шестом знаке между двумя
    выпусками распознавателя давала бы разный адрес при том же самом месте на
    странице.
    """
    try:
        доля = Decimal(str(значение))
    except (ValueError, ArithmeticError) as беда:
        raise ЯкорьНевозможен(f"координата не читается: {значение!r}") from беда
    if доля < 0:
        доля = Decimal(0)
    if доля > 1:
        доля = Decimal(1)
    return f"{доля.quantize(СЕТКА):f}"


def _порядковый_путь(путь: str) -> bool:
    return any(кусок in путь for кусок in _ПОРЯДКОВЫЕ)


def якорь_объекта(объект, роль: str = "область") -> Якорь:
    """Строит адрес области по объекту источника.

    Если у объекта есть место на странице — адрес держится на месте. Если места
    нет, держится на структурном пути, и тогда путь обязан быть адресом, а не
    порядковым номером: иначе устойчивости нет и якорь отвергается.
    """
    document_id = getattr(объект, "document_id", "") or ""
    if not document_id:
        raise ЯкорьНевозможен(
            "у объекта нет отпечатка исходных байтов: адрес не к чему привязать")

    полигон = _полигон(объект)
    if полигон is not None:
        return Якорь(document_id, объект.страница, роль,
                     СИСТЕМА_КООРДИНАТ, полигон, объект.структурный_путь)

    путь = объект.структурный_путь or ""
    if not путь or _порядковый_путь(путь):
        raise ЯкорьНевозможен(
            f"структурный путь {путь!r} содержит порядковый номер вывода и "
            "устойчивым адресом быть не может")
    return Якорь(document_id, объект.страница, роль, СИСТЕМА_КООРДИНАТ,
                 None, путь)


def _полигон(объект):
    """Место объекта на странице, округлённое до сетки."""
    if объект.полигон:
        return tuple((на_сетку(x), на_сетку(y)) for x, y in объект.полигон)
    x = объект.свойство("привязка_x")
    y = объект.свойство("привязка_y")
    if x is None or y is None:
        return None
    # Точка привязки без ширины: область вырождается в точку. Выдумывать ей
    # ширину нельзя — это был бы ложный адрес, как и в шаге 28.
    точка = (на_сетку(x), на_сетку(y))
    return (точка,)


def якорь_записи(ячейки, роль: str = "запись") -> Якорь:
    """Адрес записи-кандидата: место её опорной ячейки.

    Опорной берётся ячейка, стоящая выше и левее прочих. Именно так адрес
    переживает правку порогов склейки: пока опорная ячейка та же, адрес тот же,
    сколько бы соседей ни присоединилось к строке или ни отпало от неё.

    Номера строки в адресе нет **намеренно**: он поедет при первой же правке
    порогов, и вчерашние ссылки укажут в другое место.
    """
    якоря = []
    for ячейка in ячейки:
        объект = getattr(ячейка, "объект", None) or ячейка
        якоря.append(якорь_объекта(объект, роль))
    if not якоря:
        raise ЯкорьНевозможен("запись без ячеек адреса не имеет")
    return sorted(якоря, key=_порядок_опоры)[0]


def _порядок_опоры(якорь: Якорь):
    """Выше и левее — раньше. Ось Y растёт снизу вверх, как в самом источнике."""
    if якорь.полигон:
        x, y = якорь.полигон[0]
        return (якорь.страница, -Decimal(y), Decimal(x), якорь.идентификатор)
    return (якорь.страница, Decimal(0), Decimal(0),
            якорь.структурный_путь or "", якорь.идентификатор)


# ------------------------------------------------- столкновения и переезды


def столкновения(якоря) -> dict:
    """Адреса, доставшиеся более чем одной области.

    Две области, округлившиеся в одну клетку сетки, дадут один адрес. Молча
    склеить их нельзя: это разные места источника.
    """
    по_адресам: dict[str, list] = {}
    for якорь in якоря:
        по_адресам.setdefault(якорь.идентификатор, []).append(якорь)
    return {адрес: свои for адрес, свои in по_адресам.items() if len(свои) > 1}


def соответствие(старые, новые) -> dict:
    """Что уцелело, что исчезло и что появилось при смене разложения.

    Раздел 6.2 требует таблицу соответствия при изменении сегментации. Здесь
    она строится по совпадению адресов — то есть честно показывает, какие
    ссылки пережили правку, а какие нет. Догадываться, во что «превратился»
    исчезнувший якорь, этот код не станет: такая догадка и была бы тихой
    потерей доказательности.
    """
    было = {якорь.идентификатор: якорь for якорь in старые}
    стало = {якорь.идентификатор: якорь for якорь in новые}
    уцелели = sorted(set(было) & set(стало))
    return {
        "уцелело": уцелели,
        "исчезло": sorted(set(было) - set(стало)),
        "появилось": sorted(set(стало) - set(было)),
        "всего_было": len(было),
        "всего_стало": len(стало),
    }


def anchor_probe() -> str:
    """Адрес образцовой области. Имя латинское намеренно.

    Служит для проверки на чужом запуске истолкователя: адрес обязан совпадать
    при другом зерне перемешивания словарей, в другой локали и на другой
    машине. Вызывается из проверки строкой команды, а кириллица в командной
    строке Windows не переживает кодировку — тот же урок, что и в шаге 24.
    """
    from .adapters import SourceObject

    образец = SourceObject(
        document_id="аб" * 32, страница=3,
        система_координат="доли страницы 0..1, начало снизу слева",
        структурный_путь="страница[3]/текст[7]", сырой_текст="1 234,56",
        полигон=None,
        свойства=(("вид", "текст"), ("привязка_x", "0.123456"),
                  ("привязка_y", "0.654321"), ("кегль", "9.96")))
    return якорь_объекта(образец, "запись").идентификатор


